% Default exclude patterns always applied when packaging a module (.nmz).
% Patterns use the .nmignore glob syntax (see nmm_pack_select).
% A builtin module gateway library lives at the module root or in 'builtin/',
% never in 'bin/', so excluding build output directories is safe.
%=============================================================================
function patterns = nmm_pack_default_excludes()
  patterns = {...
    '.git/', ...
    '.svn/', ...
    '.hg/', ...
    '.gitignore', ...
    '.gitattributes', ...
    '.gitmodules', ...
    'builder.m', ...
    'bin/', ...
    'build/', ...
    'builds/', ...
    'x64/', ...
    'Win32/', ...
    'ARM64/', ...
    'CMakeFiles/', ...
    'CMakeCache.txt', ...
    'cmake_install.cmake', ...
    '.vs/', ...
    '.vscode/', ...
    '.nmm-tmp/', ...
    '*.obj', ...
    '*.o', ...
    '*.tlog', ...
    '*.pdb', ...
    '*.exp', ...
    '*.ilk', ...
    '*.idb', ...
    '*.lib', ...
    '*.user', ...
    '*.suo', ...
    '*.nmz', ...
    '.DS_Store', ...
    'Thumbs.db', ...
    '.nmignore'};
end
