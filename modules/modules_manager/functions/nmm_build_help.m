function nmm_build_help(_MODULE_NAME, _MODULE_PATH)
  target = getenv('NELSON_DL_TARGET');
  if ~isempty(target) && ~strcmp(target, computer('arch'))
    % cross build (nmm('pack', ..., '-target')): the gateway cannot be loaded
    % on this host; the help sources are packaged and the engine generates the
    % help when the module is installed.
    fprintf(_('[%s] %s target: help is generated by the installing engine.\n'), _MODULE_NAME, target);
    return
  end
  if ~ismodule(_MODULE_NAME)
    try
      run([_MODULE_PATH '/loader.m']);
      loaded = true;
    catch e
      % a gateway built for another architecture (nmm('pack', ..., '-target'))
      % cannot be loaded here; the help sources are packaged and the engine
      % generates the help when the module is installed.
      loaded = false;
      fprintf(_('[%s] module not loaded on this host, help not generated: %s\n'), _MODULE_NAME, e.message);
      if ismodule(_MODULE_NAME)
        % addmodule registers the module before running its startup script
        try
          removemodule(_MODULE_NAME);
        catch
        end
      end
    end
  else
    loaded = true;
  end
  if loaded
    buildhelp(_MODULE_NAME);
    removemodule(_MODULE_NAME);
  end
end
