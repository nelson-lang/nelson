function [c, ceq, gc, gceq] = optimTestFminconCircleGrad(x)
  c = (x(1) - 1 / 3) ^ 2 + (x(2) - 1 / 3) ^ 2 - (1 / 3) ^ 2;
  ceq = [];
  gc = [2 * (x(1) - 1 / 3); 2 * (x(2) - 1 / 3)];
  gceq = zeros(2, 0);
end
