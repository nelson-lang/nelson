p = [0 0; 1 0; 1 1; 0 1];
vq = griddata(p(:, 1), p(:, 2), p(:, 1) + p(:, 2), 0.25, 0.25);
asserts.isapprox(vq, 0.5, 1e-12);
[xq, yq, vq] = griddata(p(:, 1), p(:, 2), p(:, 1) + p(:, 2), 0.25, 0.25);
asserts.isapprox([xq, yq, vq], [0.25, 0.25, 0.5], 1e-12);
