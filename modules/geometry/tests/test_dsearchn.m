p = [0 0; 1 0; 1 1; 0 1];
q = [0.25 0.25; 2 2];
[nearest, dist] = dsearchn(p, q);
asserts.isequal(nearest(1), 1);
asserts.isapprox(dist(1), sqrt(0.125), 1e-12);
