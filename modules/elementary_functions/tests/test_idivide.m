assert_isequal(idivide(int32(7), int32(2)), int32(3));
%=============================================================================
assert_isequal(idivide(int32(-7), int32(2)), int32(-3));
%=============================================================================
assert_isequal(idivide(int32(7), int32(2), 'ceil'), int32(4));
%=============================================================================
assert_isequal(idivide(int32(7), int32(2), 'round'), int32(4));
%=============================================================================
assert_isequal(idivide(int32(-7), int32(2), 'floor'), int32(-4));
%=============================================================================
assert_isequal(class(idivide(int16(9), int16(2))), 'int16');
%=============================================================================
assert_isequal(idivide(int32([7 8 9]), int32(2)), int32([3 4 4]));
%=============================================================================
assert_isequal(idivide(int32(5), int32(0)), intmax('int32'));
assert_isequal(idivide(int32(-5), int32(0)), intmin('int32'));
assert_isequal(idivide(int32(0), int32(0)), int32(0));
