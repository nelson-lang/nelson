% <--WEIGHT 4-->
% numeric form [N, D] = rat(X, tol)
[n, d] = rat(0.75);
asserts.isequal([n, d], [3, 4]);
%=============================================================================
[n, d] = rat(pi);
asserts.isequal([n, d], [355, 113]);
%=============================================================================
[n, d] = rat(pi, 0.01);
asserts.isequal([n, d], [22, 7]);
%=============================================================================
[n, d] = rat(-0.5);
asserts.isequal([n, d], [-1, 2]);
%=============================================================================
[n, d] = rat(5);
asserts.isequal([n, d], [5, 1]);
%=============================================================================
[n, d] = rat(0);
asserts.isequal([n, d], [0, 1]);
%=============================================================================
[n, d] = rat(exp(1), 1e-6);
asserts.isequal([n, d], [2721, 1001]);
%=============================================================================
[n, d] = rat(1 / 3);
asserts.isequal([n, d], [1, 3]);
%=============================================================================
[n, d] = rat(-0.25);
asserts.isequal([n, d], [-1, 4]);
%=============================================================================
% elementwise, same shape as x
[n, d] = rat([0.5 0.25 0.75]);
asserts.isequal(n, [1 1 3]);
asserts.isequal(d, [2 4 4]);
%=============================================================================
[n, d] = rat([0.5; 0.25; 0.75]);
asserts.isequal(n, [1; 1; 3]);
asserts.isequal(d, [2; 4; 4]);
%=============================================================================
% single precision keeps class
[n, d] = rat(single(0.75));
asserts.isequal(class(n), 'single');
asserts.isequal(class(d), 'single');
asserts.isequal([n, d], single([3, 4]));
%=============================================================================
% non finite values
[n, d] = rat([Inf -Inf NaN]);
asserts.isequal(n, [1 -1 0]);
asserts.isequal(d, [0 0 0]);
%=============================================================================
% empty
[n, d] = rat([]);
asserts.isequal(size(n), [0 0]);
asserts.isequal(size(d), [0 0]);
%=============================================================================
% string form s = rat(x) (one output -> character continued fraction)
s = rat(0.75);
asserts.isequal(s, '1 + 1/(-4)');
%=============================================================================
s = rat(pi);
asserts.isequal(s, '3 + 1/(7 + 1/(16))');
%=============================================================================
s = rat(-0.25);
asserts.isequal(s, '-0 + 1/(-4)');
%=============================================================================
s = rat(5);
asserts.isequal(s, '5');
%=============================================================================
s = rat(0);
asserts.isequal(s, '0');
%=============================================================================
s = rat(1 / 3);
asserts.isequal(s, '0 + 1/(3)');
%=============================================================================
% string form for an array returns a right padded char matrix
s = rat([0.5 0.25 0.75]);
asserts.istrue(ischar(s));
asserts.isequal(size(s), [3 10]);
asserts.isequal(s(1, :), '1 + 1/(-2)');
asserts.isequal(s(2, :), '0 + 1/(4) ');
asserts.isequal(s(3, :), '1 + 1/(-4)');
%=============================================================================
% complex numeric form
[n, d] = rat(0.5 + 0.25i);
asserts.isequal(n, 2 + 1i);
asserts.isequal(d, 4);
%=============================================================================
% complex string form
s = rat(0.5 + 0.25i);
asserts.isequal(size(s), [3 10]);
asserts.isequal(s(1, :), '1 + 1/(-2)');
asserts.isequal(s(2, :), ' +i* ...  ');
asserts.isequal(s(3, :), '0 + 1/(4) ');
%=============================================================================
% errors
asserts.checkerror('rat(int8(3))', _('Value must be a float.'));
