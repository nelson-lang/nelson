asserts.isequal(nargin('log1p'), 1);
asserts.isequal(nargout('log1p'), 1);
%=============================================================================
R = log1p(NaN);
REF = NaN;
asserts.isequal(R, REF);
%=============================================================================
R = log1p(0);
REF = 0;
asserts.isequal(R, REF);
%=============================================================================
R = log1p(1);
REF = 0.6931;
asserts.isapprox(R, REF, 1e-4);
%=============================================================================
R = log1p(10);
REF = 2.3979;
asserts.isapprox(R, REF, 1e-4);
%=============================================================================
R = log1p(100);
REF = 4.6151;
asserts.isapprox(R, REF, 1e-4);
%=============================================================================
R = log1p(3i);
REF = 1.1513 + 1.2490i;
asserts.isapprox(R, REF, 1e-4);
%=============================================================================
msg = sprintf(_('Check for incorrect argument data type or missing argument in call to function ''%s''.'), 'log1p');
asserts.checkerror('R = log1p(true);', msg);
%=============================================================================
R = log1p(-3);
REF = log1p(complex(-3, 0));
asserts.isequal(R, REF);
%=============================================================================
asserts.isequal(log1p(0), 0);
