asserts.isequal(nargin('conj'), 1)
asserts.isequal(nargout('conj'), 1)
%=============================================================================
asserts.isequal(conj(NaN), NaN);
%=============================================================================
asserts.isequal(conj([]), []);
%=============================================================================
x = [1 + i, -i; i, 2i];
r = conj(x);
ref = [1 - i, i; -i, -2i];
asserts.isequal(r, ref);
%=============================================================================
x = single([1 + i, -i; i, 2i]);
r = conj(x);
ref = single([1 - i, i; -i, -2i]);
asserts.isequal(r, ref);
%=============================================================================
Z = complex([1 2], [3 4]);
asserts.isequal(conj(Z), [1 - 3i 2 - 4i]);
