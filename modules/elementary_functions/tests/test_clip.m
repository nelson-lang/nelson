asserts.isequal(nargin('clip'), 3)
asserts.isequal(nargout('clip'), 1)
%=============================================================================
R = clip([-2 0 5 10], 0, 8);
REF = [0 0 5 8];
asserts.isequal(R, REF);
%=============================================================================
R = clip([-2 0 5 10; 1 2 3 4], 1, 3);
REF = [1 1 3 3; 1 2 3 3];
asserts.isequal(R, REF);
%=============================================================================
R = clip([NaN -1 2], 0, 1);
asserts.istrue(isnan(R(1)));
asserts.isequal(R(2:3), [0 1]);
%=============================================================================
R = clip(single([-2 5]), single(0), single(3));
asserts.isequal(class(R), 'single');
asserts.isequal(R, single([0 3]));
%=============================================================================
R = clip(5, 5, 5);
asserts.isequal(R, 5);
%=============================================================================
R = clip([], 0, 1);
asserts.istrue(isempty(R));
%=============================================================================
asserts.checkerror('clip(1, 2)', _('Not enough input arguments.'));
asserts.checkerror('clip(1, 3, 2)', _('Lower bound must be less than or equal to the upper bound.'));
