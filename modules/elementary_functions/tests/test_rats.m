% <--WEIGHT 2-->
asserts.isequal(rats(0.5), '      1/2     ');
%=============================================================================
asserts.isequal(rats([0.5 0.25]), '      1/2           1/4     ');
%=============================================================================
asserts.isequal(rats(pi), '    355/113   ');
%=============================================================================
asserts.isequal(rats(5), '       5      ');
%=============================================================================
asserts.isequal(rats(-0.5), '     -1/2     ');
%=============================================================================
asserts.isequal(rats(1 / 3), '      1/3     ');
%=============================================================================
asserts.isequal(rats([1 2 3]), '       1             2             3      ');
%=============================================================================
asserts.isequal(rats([]), '');
%=============================================================================
% fixed field width per element (default LEN = 13, +1 leading space)
r = rats(0.5);
asserts.isequal(size(r), [1 14]);
%=============================================================================
% complex output
asserts.isequal(rats(0.5 + 0.25i), '      1/2     +     1/4i     ');
%=============================================================================
% errors
asserts.checkerror('rats(int8(3))', _('Value must be a float.'));
