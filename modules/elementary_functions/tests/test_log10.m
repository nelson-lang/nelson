% <--WEIGHT 2-->
asserts.isequal(nargin('log10'), 1);
asserts.isequal(nargout('log10'), 1);
%=============================================================================
R = log10(NaN);
REF = NaN;
asserts.isequal(R, REF);
%=============================================================================
R = log10(0);
REF = -Inf;
asserts.isequal(R, REF);
%=============================================================================
R = log10(1);
REF = 0;
asserts.isequal(R, REF);
%=============================================================================
R = log10(10);
REF = 1;
asserts.isequal(R, REF);
%=============================================================================
R = log10(100);
REF = 2;
asserts.isequal(R, REF);
%=============================================================================
R = log10(3i);
REF = 0.4771 + 0.6822i;
asserts.isapprox(R, REF, 1e-4);
%=============================================================================
R = log10([1 10 100]);
REF = [0 1 2];
asserts.isequal(R, REF);
%=============================================================================
R = log10([1 10; 100 1000]);
REF = [0 1; 2 3];
asserts.isequal(R, REF);
%=============================================================================
R = log10(single(10));
REF = single(1);
asserts.isequal(R, REF);
%=============================================================================
msg = sprintf(_('Check for incorrect argument data type or missing argument in call to function ''%s''.'), 'log10');
asserts.checkerror('R = log10(true);', msg);
%=============================================================================
R = log10(-3);
REF = log10(complex(-3, 0));
asserts.isequal(R, REF);
%=============================================================================
R = log10([0i NaN]);
REF = [-Inf NaN];
asserts.isequal(R, REF);
%=============================================================================
R = log10([0i complex(NaN, NaN)]);
REF = [-Inf complex(NaN, NaN)];
asserts.isequal(R, REF);
%=============================================================================
asserts.isequal(log10(100), 2);
%=============================================================================
