asserts.isequal(nargin('complex'), 2);
asserts.isequal(nargout('complex'), 1);
%=============================================================================
asserts.isequal(complex([1 2], [3 4]), [1 + 3i 2 + 4i]);
asserts.isequal(real(complex(5, -2)), 5);
asserts.isequal(imag(complex(5, -2)), -2);
%=============================================================================
Z = complex([1 2], [3 4]);
asserts.isequal(Z, [1 + 3i 2 + 4i]);
