[n, b] = histc([0 1 1.5 2 3 NaN], [0 1 2]);
asserts.isequal(n, [1 2 1]);
asserts.isequal(b, [1 2 2 3 0 0]);
[n, b] = histc([0 1; 2 3], [0 1 2]);
asserts.isequal(n, [1 0; 0 1; 1 0]);
asserts.isequal(b, [1 2; 3 0]);
n = histc([0 1; 2 3], [0 1 2], 2);
asserts.isequal(n, [1 1 0; 0 0 1]);
