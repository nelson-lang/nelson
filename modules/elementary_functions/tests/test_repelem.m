assert_isequal(repelem([1 2 3], 2), [1 1 2 2 3 3]);
%=============================================================================
assert_isequal(repelem([1 2 3], [1 2 3]), [1 2 2 3 3 3]);
%=============================================================================
assert_isequal(repelem([1 2; 3 4], 2, 3), [1 1 1 2 2 2; 1 1 1 2 2 2; 3 3 3 4 4 4; 3 3 3 4 4 4]);
%=============================================================================
assert_isequal(repelem(5, 3), [5 5 5]);
%=============================================================================
assert_isequal(repelem([1 2 3]', 2), [1; 1; 2; 2; 3; 3]);
%=============================================================================
assert_isequal(repelem([1 2 3], 0), zeros(1, 0));
%=============================================================================
assert_isequal(repelem([1 2 3], [0 2 0]), [2 2]);
