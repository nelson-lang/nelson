% <--WEIGHT 2-->
asserts.isequal(nargin('power'), 2)
asserts.isequal(nargout('power'), 1)
%=============================================================================
R = [1:5] .^ 2;
REF = [1 4 9 16 25];
asserts.isequal(R, REF);
%=============================================================================
R = power([1:5], 2);
REF = [1 4 9 16 25];
asserts.isequal(R, REF);
%=============================================================================
R = [-Inf] .^ 2;
REF = Inf;
asserts.isequal(R, REF);
%=============================================================================
R = complex(-Inf, 0) .^ complex(2, 0);
REF = Inf;
asserts.isequal(R, REF);
%=============================================================================
R = complex(0, Inf) .^ complex(2, 0);
REF = -Inf;
%=============================================================================
R = [Inf] .^ 2;
REF = Inf;
asserts.isequal(R, REF);
%=============================================================================
R = [NaN] .^ 2;
REF = NaN;
asserts.isequal(R, REF);
%=============================================================================
R = [1 2 3; 4 5 6; 7 8 9] .^ -1;
REF = [1.0000 0.5000 0.3333;
  0.2500 0.2000 0.1667;
  0.1429 0.1250 0.1111];
asserts.isapprox(R, REF, 1e-4);
%=============================================================================
R = (-1) .^ (inv(3));
REF = 0.5000 + 0.8660i;
asserts.isapprox(R, REF, 1e-4);
%=============================================================================
R = [1 NaN 2] .^ 2;
REF = [1 NaN 4];
asserts.isequal(R, REF);
%=============================================================================
R = [1 Inf 2] .^ 2;
REF = [1 Inf 4];
asserts.isequal(R, REF);
%=============================================================================
R = [1 -Inf 2] .^ 2;
REF = [1 Inf 4];
asserts.isequal(R, REF);
%=============================================================================
R = [Inf:5] .^ 2;
REF = zeros(1, 0);
asserts.isequal(R, REF);
%=============================================================================
R = [1 2; 3 4] .^ 2.5;
REF = [1.0000 5.6569; 15.5885 32.0000];
asserts.isapprox(R, REF, 1e-4);
%=============================================================================
R = [1 2; 3 4] .^ i;
REF = [1.0000 + 0.0000i 0.7692 + 0.6390i;
  0.4548 + 0.8906i 0.1835 + 0.9830i];
asserts.isapprox(R, REF, 1e-4);
%=============================================================================
asserts.isequal(power([1 2 3], 2), [1 4 9]);
asserts.isapprox(([1 2; 3 4] .^ 2.5), [1 5.656854249492381; 15.588457268119896 32], 1e-12);
