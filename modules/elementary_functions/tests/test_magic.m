asserts.isequal(nargin('magic'), 1);
asserts.isequal(nargout('magic'), 1);
%=============================================================================
R = magic(0);
asserts.isequal(R, []);
%=============================================================================
R = magic(-5);
asserts.isequal(R, []);
%=============================================================================
R = magic(1);
asserts.isequal(R, 1);
%=============================================================================
R = magic(1.2);
asserts.isequal(R, 1);
%=============================================================================
R = magic(2);
REF = [1 3; 4 2];
asserts.isequal(R, REF);
%=============================================================================
asserts.checkerror('magic([2, 4])', _('Input must be a finite real scalar.'));
%=============================================================================
R = magic(5);
REF = [17 24 1 8 15;
  23 5 7 14 16;
  4 6 13 20 22;
  10 12 19 21 3;
  11 18 25 2 9];
asserts.isequal(R, REF);
%=============================================================================
R = magic(5);
REF = [17 24 1 8 15;
  23 5 7 14 16;
  4 6 13 20 22;
  10 12 19 21 3;
  11 18 25 2 9];
asserts.isequal(R, REF);
%=============================================================================
R = magic(single(2));
REF = double([1 3; 4 2]);
asserts.isequal(R, REF);
%=============================================================================
R = magic(int32(2));
REF = double([1 3; 4 2]);
asserts.isequal(R, REF);
%=============================================================================
R = magic(4);
REF = [16 2 3 13;
  5 11 10 8;
  9 7 6 12;
  4 14 15 1];
asserts.isequal(R, REF);
%=============================================================================
