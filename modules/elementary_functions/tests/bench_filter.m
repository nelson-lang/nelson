x = rand(20000, 8);
b = ones(1, 16) / 16;
tic();
for k = 1:5
  y = filter(b, 1, x);
end
toc();
asserts.isequal(size(y), size(x));
%=============================================================================
x3 = rand(256, 32, 8);
tic();
for k = 1:5
  y3 = filter([1 2 3], [1 -0.25 0.1], x3, [], 3);
end
toc();
asserts.isequal(size(y3), size(x3));
