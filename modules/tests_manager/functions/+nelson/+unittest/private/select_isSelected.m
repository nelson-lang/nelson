function tf = select_isSelected(testCase, options)
  tf = select_matchesText(testCase.name, options.Name) ...
    && select_matchesText(testCase.module, options.Module) ...
    && select_matchesText(testCase.file, options.File) ...
    && select_matchesKind(testCase.kind, options.Kind) ...
    && select_matchesIncludePattern(testCase.name, options.Match) ...
    && ~select_matchesExcludePattern(testCase.name, options.Exclude) ...
    && select_matchesRequiredTags(testCase.tags, options.Tags) ...
    && ~select_hasTags(testCase.tags, options.ExcludeTags);
end
