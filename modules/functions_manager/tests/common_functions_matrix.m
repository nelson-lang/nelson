%=============================================================================
function rows = makeRows(names, area)
  count = length(names);
  cells = [names(:), repmat({area}, count, 1), repmat({'supported'}, count, 1), ...
    repmat({'common'}, count, 1)];
  rows = cell2struct(cells, {'name', 'area', 'status', 'tier'}, 2);
end
