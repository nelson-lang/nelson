% Verner's "most efficient" explicit Runge-Kutta 8(7) pair (13 stages).
% The solution is advanced with the eighth-order weights b; the embedded
% seventh-order weights bhat provide the error estimate. Coefficients from
% J. H. Verner's published tables (RKV87.IIa, 2024 revision).
function [yhigh, ylow, evals] = odeVerner89Step(problem, t, y, h)
  [A, b, bhat, c] = odeVerner89Tableau();
  stages = 13;
  n = length(y);
  k = zeros(n, stages);
  k(:, 1) = odeRhs(problem, t, y);
  for stage = 2:stages
    yStage = y + h * (k(:, 1:(stage - 1)) * A(stage, 1:(stage - 1)).');
    k(:, stage) = odeRhs(problem, t + c(stage) * h, yStage);
  end
  yhigh = y + h * (k * b.');
  ylow = y + h * (k * bhat.');
  evals = stages;
end
