function [y5, y4, evals] = odeDormandPrinceStep(problem, t, y, h)
  k1 = odeRhs(problem, t, y);
  k2 = odeRhs(problem, t + h / 5, y + h * (k1 / 5));
  k3 = odeRhs(problem, t + 3 * h / 10, y + h * (3 * k1 / 40 + 9 * k2 / 40));
  k4 = odeRhs(problem, t + 4 * h / 5, y + h * (44 * k1 / 45 - 56 * k2 / 15 + 32 * k3 / 9));
  k5 = odeRhs(problem, t + 8 * h / 9, y + h * (19372 * k1 / 6561 - 25360 * k2 / 2187 + 64448 * k3 / 6561 - 212 * k4 / 729));
  k6 = odeRhs(problem, t + h, y + h * (9017 * k1 / 3168 - 355 * k2 / 33 + 46732 * k3 / 5247 + 49 * k4 / 176 - 5103 * k5 / 18656));
  k7 = odeRhs(problem, t + h, y + h * (35 * k1 / 384 + 500 * k3 / 1113 + 125 * k4 / 192 - 2187 * k5 / 6784 + 11 * k6 / 84));
  y5 = y + h * (35 * k1 / 384 + 500 * k3 / 1113 + 125 * k4 / 192 - 2187 * k5 / 6784 + 11 * k6 / 84);
  y4 = y + h * (5179 * k1 / 57600 + 7571 * k3 / 16695 + 393 * k4 / 640 - 92097 * k5 / 339200 + 187 * k6 / 2100 + k7 / 40);
  evals = 7;
end
