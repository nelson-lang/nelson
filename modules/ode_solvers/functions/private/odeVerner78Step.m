% Verner's "most efficient" explicit Runge-Kutta 7(6) pair (10 stages).
% The solution is advanced with the seventh-order weights b; the embedded
% sixth-order weights bhat provide the error estimate. Coefficients from
% J. H. Verner's published tables (RKV76.IIa, 2024 revision).
function [yhigh, ylow, evals] = odeVerner78Step(problem, t, y, h)
  [A, b, bhat, c] = odeVerner78Tableau();
  stages = 10;
  n = length(y);
  k = zeros(n, stages);
  k(:, 1) = odeRhs(problem, t, y);
  for stage = 2:stages
    yStage = y + h * (k(:, 1:(stage - 1)) * A(stage, 1:(stage - 1)).');
    k(:, stage) = odeRhs(problem, t + c(stage) * h, yStage);
  end
  yhigh = y + h * (k * b.');
  ylow = y + h * (k * bhat.');
  evals = stages;
end
