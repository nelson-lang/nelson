function s = odeSolverOptionsToStruct(obj)
  s = struct(...
    'AbsTol', [], ...
    'BDF', [], ...
    'Events', [], ...
    'InitialStep', [], ...
    'Jacobian', [], ...
    'JConstant', [], ...
    'JPattern', [], ...
    'LinearSolver', [], ...
    'Mass', [], ...
    'MassSingular', [], ...
    'MaxOrder', [], ...
    'MaxStep', [], ...
    'MinStep', [], ...
    'NonNegative', [], ...
    'NormControl', [], ...
    'OutputFcn', [], ...
    'OutputSel', [], ...
    'Refine', [], ...
    'RelTol', [], ...
    'Stats', [], ...
    'Preconditioner', [], ...
    'Vectorized', [], ...
    'MStateDependence', [], ...
    'MvPattern', [], ...
    'InitialSlope', []);
  names = properties(obj);
  for k = 1:length(names)
    name = names{k};
    switch name
      case 'OutputSelection'
        s.OutputSel = obj.(name);
      case 'Vectorization'
        s.Vectorized = odeStructVectorizedValue(obj.(name));
      otherwise
        if isfield(s, name)
          s.(name) = obj.(name);
        end
    end
  end
  if isprop(obj, 'Refine') && ~isempty(obj.Refine)
    s.Refine = obj.Refine;
  elseif isprop(obj, 'DefaultRefine')
    s.Refine = obj.DefaultRefine;
  end
  s.ID = obj.ID;
end
%=============================================================================
function value = odeStructVectorizedValue(value)
  if ~iscell(value)
    return
  end
  if numel(value) == 2 && strcmpi(value{1}, value{2})
    value = value{1};
    return
  end
end
