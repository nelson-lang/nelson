stateDelayProblem = ode('DelayDefinition', odeDelay('History', 1, ...
    'ValueDelay', @(t, y) max(0.02, 0.1 - 0.2 * t)), ...
  'ODEFcn', @(t, y, z) z, ...
  'InitialValue', 1, ...
  'SolverOptions', nelson.ode.options.ODE45(odeset('MaxStep', 0.01)));
stateDelayResult = solve(stateDelayProblem, 0, 0.2);
asserts.istrue(stateDelayResult.Solution(length(stateDelayResult.Time)) > 1.15);
implicitDelayProblem = ode('DelayDefinition', odeDelay('History', 1, 'ValueDelay', 0.1), ...
  'EquationType', 'fullyimplicit', ...
  'ODEFcn', @(t, y, yp, z) yp - z, ...
  'InitialValue', 1, ...
  'InitialSlope', 1, ...
  'SolverOptions', nelson.ode.options.ODE15i(odeset('MaxStep', 0.01)));
implicitDelayResult = solve(implicitDelayProblem, 0, 0.2);
asserts.istrue(abs(implicitDelayResult.Solution(length(implicitDelayResult.Time)) - 1.205) < 2e-3);
if odeClassdefSundialsRuntimeAvailable()
  idasDelayProblem = ode('DelayDefinition', odeDelay('History', 1, 'ValueDelay', 0.1), ...
    'EquationType', 'fullyimplicit', ...
    'ODEFcn', @(t, y, yp, z) yp - z, ...
    'InitialValue', 1, ...
    'InitialSlope', 1, ...
    'SolverOptions', nelson.ode.options.IDAS('MaxStep', 0.01));
  idasDelayResult = solve(idasDelayProblem, 0, 0.2);
  asserts.istrue(abs(idasDelayResult.Solution(length(idasDelayResult.Time)) - 1.205) < 2e-3);
end
%=============================================================================
function tf = odeClassdefSundialsRuntimeAvailable()
  tf = odeRequireSundialsForTest();
  if ~tf
    return
  end
  mode = upper(getenv('NELSON_SUNDIALS_RUNTIME'));
  tf = ~(strcmp(mode, 'OFF') || strcmp(mode, '0') || strcmp(mode, 'FALSE'));
end
