% <--WEIGHT 8-->
sensProblem = ode('ODEFcn', @(t, y, p) p(1) * y, ...
  'InitialValue', 1, ...
  'Parameters', 2, ...
  'Sensitivity', odeSensitivity('ParameterIndices', 1));
sensResult = solve(sensProblem, 0, 0.2);
asserts.isequal(size(sensResult.Sensitivity, 1), 1);
asserts.isequal(size(sensResult.Sensitivity, 2), 1);
asserts.isequal(size(sensResult.Sensitivity, 3), length(sensResult.Time));
sensFinal = sensResult.Sensitivity(1, 1, length(sensResult.Time));
asserts.istrue(abs(sensFinal - 0.2 * exp(0.4)) < 2e-3);
sensMassProblem = ode('ODEFcn', @(t, y, p) p(1) * y, ...
  'InitialValue', 1, ...
  'Parameters', 2, ...
  'MassMatrix', odeMassMatrix(2), ...
  'Sensitivity', odeSensitivity('ParameterIndices', 1), ...
  'SolverOptions', nelson.ode.options.ODE45(odeset('MaxStep', 0.02)));
sensMassResult = solve(sensMassProblem, 0, 0.2);
sensMassFinal = sensMassResult.Sensitivity(1, 1, length(sensMassResult.Time));
asserts.istrue(abs(sensMassFinal - 0.1 * exp(0.2)) < 2e-3);
sensMassFunctionProblem = ode('ODEFcn', @(t, y, p) p(1) * y, ...
  'InitialValue', 1, ...
  'Parameters', [2; 2], ...
  'MassMatrix', odeMassMatrix(@(t, y, p) p(2)), ...
  'Sensitivity', odeSensitivity('ParameterIndices', 1), ...
  'SolverOptions', nelson.ode.options.ODE45(odeset('MaxStep', 0.02)));
sensMassFunctionResult = solve(sensMassFunctionProblem, 0, 0.2);
sensMassFunctionFinal = sensMassFunctionResult.Sensitivity(1, 1, length(sensMassFunctionResult.Time));
asserts.istrue(abs(sensMassFunctionFinal - 0.1 * exp(0.2)) < 2e-3);
sensNonNegativeProblem = ode('ODEFcn', @(t, y, p) - p(1), ...
  'InitialValue', 0.1, ...
  'Parameters', 1, ...
  'NonNegativeVariables', 1, ...
  'Sensitivity', odeSensitivity(), ...
  'SolverOptions', nelson.ode.options.ODE45(odeset('MaxStep', 0.05)));
sensNonNegativeResult = solve(sensNonNegativeProblem, 0, 0.3);
asserts.istrue(all(sensNonNegativeResult.Solution(:) >= 0));
asserts.isequal(size(sensNonNegativeResult.Sensitivity, 1), 1);
sensEventProblem = ode('ODEFcn', @(t, y, p) p(1), ...
  'InitialValue', 0, ...
  'Parameters', 2, ...
  'Sensitivity', odeSensitivity(), ...
  'EventDefinition', odeEvent('EventFcn', @(t, y) y - 0.5, 'Response', 'stop'));
sensEventResult = solve(sensEventProblem, 0, 1);
asserts.istrue(abs(sensEventResult.EventTime(1) - 0.25) < 1e-8);
asserts.istrue(abs(sensEventResult.Sensitivity(1, 1, length(sensEventResult.Time)) - 0.25) < 1e-8);
asserts.istrue(abs(sensEventResult.EventSensitivity(1, 1, 1) - 0.25) < 1e-8);
clear global ODE_OUTPUT_RECORDER_LOG;
global ODE_OUTPUT_RECORDER_LOG;
ODE_OUTPUT_RECORDER_LOG = {};
sensOutputOptions = nelson.ode.options.ODE45(odeset(...
  'OutputFcn', @(t, y, flag, p) odeOutputRecorder(t, y, flag), ...
  'OutputSel', 1, ...
  'Refine', 1));
sensOutputProblem = ode('ODEFcn', @(t, y, p)[p(1); -p(1)], ...
  'InitialValue', [0; 1], ...
  'Parameters', 2, ...
  'Sensitivity', odeSensitivity('ParameterIndices', 1), ...
  'SolverOptions', sensOutputOptions);
sensOutputResult = solve(sensOutputProblem, 0, 0.1);
asserts.isequal(size(ODE_OUTPUT_RECORDER_LOG{2}.y, 1), 1);
asserts.isequal(size(sensOutputResult.Sensitivity, 1), 2);
clear global ODE_OUTPUT_STOP_LOG;
global ODE_OUTPUT_STOP_LOG;
ODE_OUTPUT_STOP_LOG = {};
sensStopOptions = nelson.ode.options.ODE45(odeset(...
  'OutputFcn', @(t, y, flag, p) odeOutputStopAtThree(t, y, flag), ...
  'MaxStep', 0.1));
sensStopProblem = ode('ODEFcn', @(t, y, p) p(1), ...
  'InitialValue', 0, ...
  'Parameters', 1, ...
  'Sensitivity', odeSensitivity(), ...
  'SolverOptions', sensStopOptions);
sensStopResult = solve(sensStopProblem, 0, 1);
asserts.istrue(sensStopResult.Time(length(sensStopResult.Time)) <= 0.4);
asserts.checkerror('ode(''ODEFcn'', @(t,y,p) p(1), ''InitialValue'', 0, ''Parameters'', 2, ''Sensitivity'', odeSensitivity(), ''EventDefinition'', odeEvent(''EventFcn'', @(t,y) y - 0.5, ''Response'', ''callback'', ''CallbackFcn'', @(t,y,i) false)).solve(0, 1);', ...
  _('Sensitivity equations with event callbacks are not supported yet.'));
asserts.checkerror('ode(''ODEFcn'', @(t,y,p) p(1)*y, ''InitialValue'', 1, ''Parameters'', 2, ''Sensitivity'', odeSensitivity(''Method'', ''adjoint''), ''Solver'', ''ode45'').solve(0, 0.2);', ...
  _('Adjoint sensitivities require a SUNDIALS solver.'));
asserts.checkerror('ode(''ODEFcn'', @(t,y,p) p(1)*y, ''InitialValue'', 1, ''Parameters'', {2}, ''Sensitivity'', odeSensitivity()).solve(0, 0.2);', ...
  _('Parameters must be a numeric vector to perform a sensitivity analysis.'));
