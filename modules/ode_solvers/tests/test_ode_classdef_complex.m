asserts.checkerror('ode(''SeparateComplexParts'', ''maybe'')', sprintf(_('%s must be ''on'' or ''off''.'), 'SeparateComplexParts'));
complexProblem = ode('ODEFcn', @(t, y) y .* t + 2 * 1i, ...
  'InitialValue', 1 + 1i, ...
  'SeparateComplexParts', 'on');
complexResult = solve(complexProblem, 0, 2);
complexExpected = exp(2) * (1 + 1i + 2i * sqrt(pi / 2) * erf(sqrt(2)));
asserts.isequal(size(complexResult.Solution, 1), 1);
asserts.istrue(abs(complexResult.Solution(1) - (1 + 1i)) < 1e-12);
asserts.istrue(abs(complexResult.Solution(length(complexResult.Time)) - complexExpected) < 2e-2);
[complexFcn, complexData] = solutionFcn(complexProblem, 0, 2);
complexMid = exp(0.5) * (1 + 1i + 2i * sqrt(pi / 2) * erf(1 / sqrt(2)));
asserts.istrue(abs(deval(complexData, 1) - complexMid) < 2e-2);
asserts.istrue(abs(complexFcn(1) - complexMid) < 2e-2);

complexEvent = odeEvent('EventFcn', @(t, y) imag(y) - 4, 'Response', 'stop');
complexEventProblem = ode('ODEFcn', @(t, y) y .* t + 2 * 1i, ...
  'InitialValue', 1 + 1i, ...
  'SeparateComplexParts', 'on', ...
  'EventDefinition', complexEvent);
complexEventResult = solve(complexEventProblem, 0, 2);
asserts.isequal(complexEventResult.EventIndex(1), 1);
asserts.isfalse(isreal(complexEventResult.EventSolution));
asserts.istrue(abs(imag(complexEventResult.EventSolution(1)) - 4) < 1e-3);

complexOutputOptions = nelson.ode.options.ODE45(odeset(...
  'OutputFcn', @odeComplexOutputCheck, ...
  'OutputSel', 2, ...
  'Refine', 2));
complexOutputProblem = ode('ODEFcn', @(t, y)[1i * y(1); -y(2)], ...
  'InitialValue', [1 + 1i; 2 - 1i], ...
  'SeparateComplexParts', 'on', ...
  'SolverOptions', complexOutputOptions);
complexOutputResult = solve(complexOutputProblem, 0, 0.2);
asserts.isequal(size(complexOutputResult.Solution, 1), 2);
asserts.isfalse(isreal(complexOutputResult.Solution));

complexMassProblem = ode('ODEFcn', @(t, y)(1 + 1i) * [1; -1i], ...
  'InitialValue', [0; 1 + 1i], ...
  'SeparateComplexParts', 'on', ...
  'MassMatrix', odeMassMatrix(1 + 1i), ...
  'SolverOptions', nelson.ode.options.ODE45(odeset('MaxStep', 0.02)));
complexMassResult = solve(complexMassProblem, 0, 0.2);
complexMassFinal = complexMassResult.Solution(:, length(complexMassResult.Time));
asserts.istrue(norm(complexMassFinal - [0.2; 1 + 0.8i], inf) < 2e-3);

complexJacobianProblem = ode('ODEFcn', @(t, y) 1i * y, ...
  'InitialValue', 1, ...
  'SeparateComplexParts', 'on', ...
  'Jacobian', odeJacobian(1i), ...
  'SolverOptions', nelson.ode.options.ODE23s(odeset('MaxStep', 0.02)));
complexJacobianResult = solve(complexJacobianProblem, 0, 0.2);
complexJacobianFinal = complexJacobianResult.Solution(length(complexJacobianResult.Time));
asserts.istrue(abs(complexJacobianFinal - exp(0.2i)) < 2e-3);

complexImplicitProblem = ode('EquationType', 'fullyimplicit', ...
  'ODEFcn', @(t, y, yp) yp + y, ...
  'InitialValue', 1 + 1i, ...
  'InitialSlope', -1 - 1i, ...
  'SeparateComplexParts', 'on', ...
  'EventDefinition', odeEvent('EventFcn', @odeComplexImplicitEvent, 'Response', 'stop'));
complexImplicitResult = solve(complexImplicitProblem, 0, 0.6);
asserts.istrue(abs(complexImplicitResult.EventTime(1) - 0.25) < 2e-3);
asserts.isfalse(isreal(complexImplicitResult.EventSolution));

complexCallbackEvent = odeEvent('EventFcn', @(t, y) real(y) - 0.5, ...
  'Response', 'callback', ...
  'CallbackFcn', @odeComplexCallbackState);
complexCallbackProblem = ode('ODEFcn', @(t, y) 1 + 1i, ...
  'InitialValue', 0, ...
  'SeparateComplexParts', 'on', ...
  'EventDefinition', complexCallbackEvent);
complexCallbackResult = solve(complexCallbackProblem, 0, 1);
asserts.istrue(abs(complexCallbackResult.EventTime(1) - 0.5) < 1e-8);
asserts.istrue(abs(complexCallbackResult.EventSolution(1) - (0.6 + 0.75i)) < 1e-8);
