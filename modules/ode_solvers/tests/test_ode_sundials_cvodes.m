autoSwitchNonstiffProblem = ode('ODEFcn', @(t, y) - y, ...
  'InitialValue', 1, ...
  'RelativeTolerance', 1e-8, ...
  'AbsoluteTolerance', 1e-10, ...
  'Solver', 'autoswitch');
asserts.isequal(autoSwitchNonstiffProblem.SelectedSolver, 'autoswitch');
autoSwitchNonstiffResult = solve(autoSwitchNonstiffProblem, 0, 1);
asserts.isequal(autoSwitchNonstiffResult.RawSolution.stats.autoSwitchSwitched, false);
asserts.isequal(autoSwitchNonstiffResult.RawSolution.stats.autoSwitchReason, 'nonstiffAccepted');
asserts.isequal(autoSwitchNonstiffResult.RawSolution.stats.autoSwitchLastReason, ...
  'nonstiffAccepted');
asserts.isequal(autoSwitchNonstiffResult.RawSolution.stats.autoSwitchMode, 'step');
asserts.isequal(autoSwitchNonstiffResult.RawSolution.stats.autoSwitchSwitchCount, 0);
asserts.isequal(autoSwitchNonstiffResult.RawSolution.stats.autoSwitchStiffnessCriterion, ...
  'errorPressure');
asserts.istrue(autoSwitchNonstiffResult.RawSolution.stats.autoSwitchStiffnessIndicator >= 0);
asserts.istrue(abs(autoSwitchNonstiffResult.SolutionValues(length(autoSwitchNonstiffResult.Time)) ...
  - exp(-1)) < 1e-5);
