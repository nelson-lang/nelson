autoSwitchStiffProblem = ode('ODEFcn', @(t, y) - 1000 * y, ...
  'InitialValue', 1, ...
  'RelativeTolerance', 1e-6, ...
  'AbsoluteTolerance', 1e-8, ...
  'Solver', 'autoswitch');
autoSwitchStiffResult = solve(autoSwitchStiffProblem, 0, 0.1);
asserts.isequal(autoSwitchStiffResult.RawSolution.stats.autoSwitchSwitched, true);
asserts.istrue(strcmp(autoSwitchStiffResult.RawSolution.stats.autoSwitchReason, ...
  'nonstiffFailure') || strcmp(autoSwitchStiffResult.RawSolution.stats.autoSwitchReason, ...
  'stiffnessHeuristic'));
asserts.istrue(strcmp(autoSwitchStiffResult.RawSolution.stats.autoSwitchLastReason, ...
  'nonstiffFailure') || strcmp(autoSwitchStiffResult.RawSolution.stats.autoSwitchLastReason, ...
  'stiffnessReleased'));
asserts.isequal(autoSwitchStiffResult.RawSolution.stats.autoSwitchMode, 'step');
asserts.istrue(autoSwitchStiffResult.RawSolution.stats.autoSwitchSwitchCount >= 1);
asserts.istrue(autoSwitchStiffResult.RawSolution.stats.autoSwitchSwitchTime > 0);
asserts.isequal(autoSwitchStiffResult.RawSolution.stats.autoSwitchStiffnessCriterion, ...
  'errorPressure');
asserts.istrue(autoSwitchStiffResult.RawSolution.stats.autoSwitchStiffnessIndicator >= 0);
asserts.istrue(abs(autoSwitchStiffResult.SolutionValues(length(autoSwitchStiffResult.Time)) ...
  - exp(-100)) < 1e-5);
