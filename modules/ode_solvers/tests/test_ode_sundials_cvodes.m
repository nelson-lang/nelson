stiffProblem = ode('ODEFcn', @(t, y) - 1000 * (y - exp(-t)) - exp(-t), ...
  'InitialValue', 1, ...
  'RelativeTolerance', 1e-8, ...
  'AbsoluteTolerance', 1e-10, ...
  'Solver', 'cvodesstiff');
stiffResult = solve(stiffProblem, 0, 1);
asserts.isequal(stiffResult.RawSolution.solver, 'cvodesstiff');
asserts.istrue(abs(stiffResult.SolutionValues(length(stiffResult.Time)) - exp(-1)) < 1e-4);
asserts.isequal(stiffResult.RawSolution.stats.linearSolver, 'dense');
asserts.isequal(stiffResult.RawSolution.stats.preconditioner, 'none');
