delaySensitivityProblem = ode('DelayDefinition', odeDelay('History', 1, 'ValueDelay', 0.1), ...
  'ODEFcn', @(t, y, z, p) p(1) * z, ...
  'InitialValue', 1, ...
  'Parameters', 2, ...
  'Sensitivity', odeSensitivity(), ...
  'SolverOptions', nelson.ode.options.ODE45(odeset('MaxStep', 0.01)));
delaySensitivityResult = solve(delaySensitivityProblem, 0, 0.2);
delaySensitivityFinal = delaySensitivityResult.Sensitivity(1, 1, length(delaySensitivityResult.Time));
asserts.istrue(abs(delaySensitivityFinal - 0.22) < 5e-3);
delayAdjointProblem = ode('DelayDefinition', odeDelay('History', 1, 'ValueDelay', 0.1), ...
  'ODEFcn', @(t, y, z, p) p(1) * z, ...
  'InitialValue', 1, ...
  'Parameters', 2, ...
  'Sensitivity', odeSensitivity('Method', 'adjoint', ...
    'ObjectiveFcn', @(t, y, p) y(1), 'ParameterIndices', 1), ...
  'SolverOptions', nelson.ode.options.ODE45(odeset('MaxStep', 0.01)));
delayAdjointResult = solve(delayAdjointProblem, 0, 0.2);
asserts.istrue(abs(delayAdjointResult.AdjointGradient(1) - 0.22) < 5e-3);
asserts.istrue(isempty(delayAdjointResult.Sensitivity));
