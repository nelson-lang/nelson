previousRuntime = getenv('NELSON_SUNDIALS_RUNTIME');
runtimeCleanup = onCleanup(@() setenv('NELSON_SUNDIALS_RUNTIME', previousRuntime)); %#ok<NLS0004>
buildAvailable = odeRequireSundialsForTest();
if ~buildAvailable
  return
end
setenv('NELSON_SUNDIALS_RUNTIME', 'ON');
%=============================================================================
massProblem = ode('ODEFcn', @(t, y) y, ...
  'InitialValue', 1, ...
  'RelativeTolerance', 1e-8, ...
  'AbsoluteTolerance', 1e-10, ...
  'MassMatrix', odeMassMatrix(2), ...
  'Solver', 'cvodesstiff');
massResult = solve(massProblem, 0, 1);
asserts.istrue(abs(massResult.SolutionValues(length(massResult.Time)) - exp(0.5)) < 1e-4);
%=============================================================================
eventProblem = ode('ODEFcn', @(t, y) 1, ...
  'InitialValue', 0, ...
  'EventDefinition', odeEvent('EventFcn', @odeSundialsEventHalf, 'Response', 'stop'), ...
  'Solver', 'cvodesnonstiff');
eventResult = solve(eventProblem, 0, 1);
asserts.isequal(eventResult.EventIndex(1), 1);
asserts.istrue(abs(eventResult.EventTime(1) - 0.5) < 1e-7);
asserts.istrue(abs(eventResult.EventSolution(1) - 0.5) < 1e-7);
%=============================================================================
idasOptions = nelson.ode.options.IDAS('ComputeConsistentInitialConditions', false);
idasProblem = ode('EquationType', 'fullyimplicit', ...
  'ODEFcn', @(t, y, yp) yp + y, ...
  'InitialValue', 1, ...
  'InitialSlope', -1, ...
  'RelativeTolerance', 1e-8, ...
  'AbsoluteTolerance', 1e-10, ...
  'SolverOptions', idasOptions);
idasResult = solve(idasProblem, 0, 1);
asserts.isequal(idasResult.RawSolution.solver, 'idas');
asserts.istrue(abs(idasResult.SolutionValues(length(idasResult.Time)) - exp(-1)) < 1e-5);
%=============================================================================
idasNonNegativeProblem = ode('EquationType', 'fullyimplicit', ...
  'ODEFcn', @(t, y, yp) yp + y, ...
  'InitialValue', 1, ...
  'InitialSlope', -1, ...
  'NonNegativeVariables', 1, ...
  'RelativeTolerance', 1e-8, ...
  'AbsoluteTolerance', 1e-10, ...
  'SolverOptions', idasOptions);
idasNonNegativeResult = solve(idasNonNegativeProblem, 0, 1);
asserts.istrue(all(idasNonNegativeResult.Solution(:) >= 0));
asserts.isequal(idasNonNegativeResult.RawSolution.idata.idxNonNegative, 1);
%=============================================================================
idasConsistentOptions = nelson.ode.options.IDAS('ComputeConsistentInitialConditions', true);
idasConsistentProblem = ode('EquationType', 'fullyimplicit', ...
  'ODEFcn', @(t, y, yp) yp + y, ...
  'InitialValue', 1, ...
  'InitialSlope', 0, ...
  'RelativeTolerance', 1e-8, ...
  'AbsoluteTolerance', 1e-10, ...
  'SolverOptions', idasConsistentOptions);
idasConsistentResult = solve(idasConsistentProblem, 0, 0.2);
asserts.isequal(idasConsistentResult.RawSolution.solver, 'idas');
asserts.istrue(abs(idasConsistentResult.RawSolution.extdata.yp0 + 1) < 1e-8);
asserts.istrue(abs(idasConsistentResult.RawSolution.extdata.options.InitialSlope + 1) < 1e-8);
asserts.istrue(abs(idasConsistentResult.SolutionValues(length(idasConsistentResult.Time)) ...
  - exp(-0.2)) < 1e-5);
%=============================================================================
idasSparseOptions = nelson.ode.options.IDAS('ComputeConsistentInitialConditions', false);
idasSparseProblem = ode('EquationType', 'fullyimplicit', ...
  'ODEFcn', @(t, y, yp) yp + [20 * y(1); 30 * y(2)], ...
  'InitialValue', [1; 2], ...
  'InitialSlope', [-20; -60], ...
  'RelativeTolerance', 1e-8, ...
  'AbsoluteTolerance', 1e-10, ...
  'Jacobian', odeJacobian([], 'Pattern', sparse(logical(eye(2)))), ...
  'SolverOptions', idasSparseOptions);
idasSparseResult = solve(idasSparseProblem, 0, 0.2);
asserts.isequal(idasSparseResult.RawSolution.stats.linearSolver, 'spgmr');
asserts.isequal(idasSparseResult.RawSolution.stats.preconditioner, 'jacobi');
asserts.istrue(max(abs(idasSparseResult.Solution(:, length(idasSparseResult.Time)) ...
  - [exp(-4); 2 * exp(-6)])) < 1e-4);
%=============================================================================
idasBandedOptions = nelson.ode.options.IDAS('ComputeConsistentInitialConditions', false, ...
  'LinearSolver', 'spgmr', ...
  'Preconditioner', 'banded');
idasBandedProblem = ode('EquationType', 'fullyimplicit', ...
  'ODEFcn', @(t, y, yp) yp + [20 * y(1) - y(2); 30 * y(2)], ...
  'InitialValue', [1; 2], ...
  'InitialSlope', [-18; -60], ...
  'RelativeTolerance', 1e-8, ...
  'AbsoluteTolerance', 1e-10, ...
  'Jacobian', odeJacobian([], 'Pattern', sparse(logical([1 1; 0 1]))), ...
  'SolverOptions', idasBandedOptions);
idasBandedResult = solve(idasBandedProblem, 0, 0.2);
asserts.isequal(idasBandedResult.RawSolution.stats.linearSolver, 'spgmr');
asserts.isequal(idasBandedResult.RawSolution.stats.preconditioner, 'banded');
idasBandedExpected = [1.2 * exp(-4) - 0.2 * exp(-6); 2 * exp(-6)];
asserts.istrue(max(abs(idasBandedResult.Solution(:, length(idasBandedResult.Time)) ...
  - idasBandedExpected)) < 1e-4);
%=============================================================================
idasIlu0Options = nelson.ode.options.IDAS('ComputeConsistentInitialConditions', false, ...
  'LinearSolver', 'spgmr', ...
  'Preconditioner', 'ilu0');
