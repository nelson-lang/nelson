  'ODEFcn', @(t, y, yp) yp + [20 * y(1) - y(2); 30 * y(2)], ...
  'InitialValue', [1; 2], ...
  'InitialSlope', [-18; -60], ...
  'RelativeTolerance', 1e-8, ...
  'AbsoluteTolerance', 1e-10, ...
  'Jacobian', odeJacobian([], 'Pattern', sparse(logical([1 1; 0 1]))), ...
  'SolverOptions', idasIlu0Options);
