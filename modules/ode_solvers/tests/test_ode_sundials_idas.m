idasSensitivityOptions = nelson.ode.options.IDAS('ComputeConsistentInitialConditions', false);
idasSensitivityProblem = ode('EquationType', 'fullyimplicit', ...
  'ODEFcn', @(t, y, yp, p) yp + p(1) * y, ...
  'InitialValue', 1, ...
  'InitialSlope', -2, ...
  'Parameters', 2, ...
  'Sensitivity', odeSensitivity(), ...
  'RelativeTolerance', 1e-8, ...
  'AbsoluteTolerance', 1e-10, ...
  'SolverOptions', idasSensitivityOptions);
idasSensitivityResult = solve(idasSensitivityProblem, 0, 0.2);
idasSensitivityFinal = idasSensitivityResult.Sensitivity(1, 1, length(idasSensitivityResult.Time));
asserts.isequal(idasSensitivityResult.RawSolution.solver, 'idas');
asserts.isequal(idasSensitivityResult.RawSolution.stats.sensitivityMethod, 'native');
asserts.istrue(abs(idasSensitivityFinal + 0.2 * exp(-0.4)) < 1e-4);
