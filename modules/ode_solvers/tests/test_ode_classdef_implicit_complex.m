previousSundialsRuntime = getenv('NELSON_SUNDIALS_RUNTIME');
runtimeCleanup = onCleanup(@() setenv('NELSON_SUNDIALS_RUNTIME', previousSundialsRuntime));
setenv('NELSON_SUNDIALS_RUNTIME', 'OFF');
implicit = ode('EquationType', 'fullyimplicit', ...
  'ODEFcn', @(t, y, yp) yp + y, ...
  'InitialValue', 1, ...
  'InitialSlope', -1);
asserts.isequal(implicit.SelectedSolver, 'ode15i');
implicitResult = solve(implicit, 0.5);
asserts.istrue(abs(implicitResult.SolutionValues(length(implicitResult.Time)) - exp(-0.5)) < 5e-4);
implicitSensitivity = ode('EquationType', 'fullyimplicit', ...
  'ODEFcn', @(t, y, yp, p) yp + p(1) * y, ...
  'InitialValue', 1, ...
  'InitialSlope', -2, ...
  'Parameters', 2, ...
  'Sensitivity', odeSensitivity());
implicitSensitivityResult = solve(implicitSensitivity, 0, 0.2);
implicitSensitivityFinal = implicitSensitivityResult.Sensitivity(1, 1, length(implicitSensitivityResult.Time));
asserts.isequal(implicitSensitivityResult.RawSolution.solver, 'ode15i');
asserts.istrue(abs(implicitSensitivityFinal + 0.2 * exp(-0.4)) < 2e-3);
setenv('NELSON_SUNDIALS_RUNTIME', previousSundialsRuntime);
consistentImplicit = ode('EquationType', 'fullyimplicit', ...
  'ODEFcn', @(t, y, yp) yp + y, ...
  'InitialValue', 1, ...
  'InitialSlope', 0, ...
  'SolverOptions', nelson.ode.options.ODE15i('ComputeConsistentInitialConditions', true));
consistentImplicitResult = solve(consistentImplicit, 0.1);
asserts.istrue(abs(consistentImplicitResult.RawSolution.extdata.options.InitialSlope + 1) < 1e-8);
inconsistentImplicit = ode('EquationType', 'fullyimplicit', ...
  'ODEFcn', @(t, y, yp) yp + y, ...
  'InitialValue', 1, ...
  'InitialSlope', 0, ...
  'SolverOptions', nelson.ode.options.ODE15i('ComputeConsistentInitialConditions', false));
inconsistentImplicitResult = solve(inconsistentImplicit, 0.1);
asserts.isequal(inconsistentImplicitResult.RawSolution.extdata.options.InitialSlope, 0);

asserts.checkerror('ode(''EquationType'', ''bad'')', sprintf(_('%s has an invalid value.'), 'EquationType'));
