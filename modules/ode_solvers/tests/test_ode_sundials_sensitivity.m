idasAdjointProblem = ode('EquationType', 'fullyimplicit', ...
  'ODEFcn', @(t, y, yp, p) yp + p(1) * y, ...
  'InitialValue', 1, ...
  'InitialSlope', -2, ...
  'Parameters', 2, ...
  'Sensitivity', odeSensitivity('Method', 'adjoint', ...
  'ObjectiveFcn', @(t, y, p) y(1)), ...
  'RelativeTolerance', 1e-8, ...
  'AbsoluteTolerance', 1e-10, ...
  'Solver', 'idas');
idasAdjointResult = solve(idasAdjointProblem, 0, 0.2);
asserts.isequal(idasAdjointResult.RawSolution.solver, 'idas');
asserts.isequal(idasAdjointResult.RawSolution.stats.sensitivityMethod, 'adjoint');
asserts.isequal(idasAdjointResult.RawSolution.stats.sensitivityBackend, 'idasAdjoint');
asserts.istrue(isempty(idasAdjointResult.Sensitivity));
asserts.istrue(abs(idasAdjointResult.AdjointGradient(1) + 0.2 * exp(-0.4)) < 1e-4);
