sensitivityProblem = ode('ODEFcn', @(t, y, p) p(1) * y, ...
  'InitialValue', 1, ...
  'Parameters', 2, ...
  'Sensitivity', odeSensitivity('ParameterIndices', 1), ...
  'RelativeTolerance', 1e-8, ...
  'AbsoluteTolerance', 1e-10, ...
  'Solver', 'cvodesnonstiff');
