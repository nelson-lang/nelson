idasAdjointQuadratureProblem = ode('EquationType', 'fullyimplicit', ...
  'ODEFcn', @(t, y, yp, p) yp + p(1) * y, ...
  'InitialValue', 1, ...
  'InitialSlope', -2, ...
  'Parameters', 2, ...
  'Sensitivity', odeSensitivity('Method', 'adjoint', ...
  'QuadratureFcn', @(t, y, p) y(1)), ...
  'RelativeTolerance', 1e-8, ...
  'AbsoluteTolerance', 1e-10, ...
  'Solver', 'idas');
idasAdjointQuadratureResult = solve(idasAdjointQuadratureProblem, 0, 0.2);
idasAdjointQuadratureExpected = (0.4 * exp(-0.4) + exp(-0.4) - 1) / 4;
