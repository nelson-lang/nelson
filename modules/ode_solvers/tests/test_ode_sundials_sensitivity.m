previousRuntime = getenv('NELSON_SUNDIALS_RUNTIME');
runtimeCleanup = onCleanup(@() setenv('NELSON_SUNDIALS_RUNTIME', previousRuntime)); %#ok<NLS0004>
buildAvailable = odeRequireSundialsForTest();
if ~buildAvailable
  return
end
setenv('NELSON_SUNDIALS_RUNTIME', 'ON');
%=============================================================================
autoProblem = ode('ODEFcn', @(t, y) - y, 'InitialValue', 1);
asserts.isequal(autoProblem.SelectedSolver, 'cvodesnonstiff');
stiffAuto = ode('Solver', 'stiff');
asserts.isequal(stiffAuto.SelectedSolver, 'cvodesstiff');
implicitAuto = ode('EquationType', 'fullyimplicit', ...
  'ODEFcn', @(t, y, yp) yp + y, ...
  'InitialValue', 1, ...
  'InitialSlope', -1);
asserts.isequal(implicitAuto.SelectedSolver, 'idas');
complexInitial = 1 + 0.1i;
complexAuto = ode('ODEFcn', @(t, y) 1i * y, 'InitialValue', complexInitial);
asserts.isequal(complexAuto.SelectedSolver, 'cvodesnonstiff');
%=============================================================================
nonstiffProblem = ode('ODEFcn', @(t, y) - y, ...
  'InitialValue', 1, ...
  'RelativeTolerance', 1e-8, ...
  'AbsoluteTolerance', 1e-10, ...
  'Solver', 'cvodesnonstiff');
nonstiffResult = solve(nonstiffProblem, 0, 1);
asserts.isequal(nonstiffResult.RawSolution.solver, 'cvodesnonstiff');
asserts.istrue(abs(nonstiffResult.SolutionValues(length(nonstiffResult.Time)) - exp(-1)) < 1e-5);
asserts.istrue(abs(deval(nonstiffResult, 0.5) - exp(-0.5)) < 1e-4);
asserts.istrue(nonstiffResult.RawSolution.stats.nsteps > 0);
