emptyDelayProblem = ode('DelayDefinition', odeDelay(), ...
  'ODEFcn', @(t, y) - y, ...
  'InitialValue', 1);
emptyDelayResult = solve(emptyDelayProblem, 0, 0.1);
asserts.istrue(abs(emptyDelayResult.Solution(length(emptyDelayResult.Time)) - exp(-0.1)) < 1e-3);
asserts.checkerror('ode(''DelayDefinition'', 1, ''ODEFcn'', @(t,y) -y)', sprintf(_('%s definition object expected.'), 'Delay'));
ddeProblem = ode('DelayDefinition', odeDelay('History', 1, 'ValueDelay', 0.1), ...
  'ODEFcn', @(t, y, z) z, ...
  'InitialValue', 1, ...
  'SolverOptions', nelson.ode.options.ODE45(odeset('MaxStep', 0.01)));
ddeResult = solve(ddeProblem, 0, 0.2);
ddeFinal = ddeResult.Solution(length(ddeResult.Time));
asserts.istrue(abs(ddeFinal - 1.205) < 2e-3);
ddeMid = deval(ddeResult, 0.1);
asserts.istrue(abs(ddeMid - 1.1) < 2e-3);
slopeDelayProblem = ode('DelayDefinition', odeDelay('History', @(t) 1 + t, 'SlopeDelay', 0.1), ...
  'ODEFcn', @(t, y, z, zp) zp, ...
  'InitialValue', 1, ...
  'SolverOptions', nelson.ode.options.ODE45(odeset('MaxStep', 0.01)));
slopeDelayResult = solve(slopeDelayProblem, 0, 0.2);
asserts.istrue(abs(slopeDelayResult.Solution(length(slopeDelayResult.Time)) - 1.2) < 2e-3);
functionDelayProblem = ode('DelayDefinition', odeDelay('History', 1, 'ValueDelay', @(t, y) 0.1), ...
  'ODEFcn', @(t, y, z) z, ...
  'InitialValue', 1, ...
  'SolverOptions', nelson.ode.options.ODE45(odeset('MaxStep', 0.01)));
functionDelayResult = solve(functionDelayProblem, 0, 0.2);
asserts.istrue(abs(functionDelayResult.Solution(length(functionDelayResult.Time)) - 1.205) < 2e-3);
delayEventProblem = ode('DelayDefinition', odeDelay('History', 1, 'ValueDelay', 0.1), ...
  'ODEFcn', @(t, y, z) z, ...
  'InitialValue', 1, ...
  'EventDefinition', odeEvent('EventFcn', @(t, y) y - 1.1, 'Response', 'stop'), ...
  'SolverOptions', nelson.ode.options.ODE45(odeset('MaxStep', 0.01)));
delayEventResult = solve(delayEventProblem, 0, 0.3);
asserts.istrue(abs(delayEventResult.EventTime(1) - 0.1) < 2e-3);
asserts.istrue(abs(delayEventResult.Solution(length(delayEventResult.Time)) - 1.1) < 2e-3);
delayMassProblem = ode('DelayDefinition', odeDelay('History', 1, 'ValueDelay', 0.1), ...
  'ODEFcn', @(t, y, z) z, ...
  'InitialValue', 1, ...
  'MassMatrix', odeMassMatrix(2), ...
  'SolverOptions', nelson.ode.options.ODE45(odeset('MaxStep', 0.01)));
delayMassResult = solve(delayMassProblem, 0, 0.2);
asserts.istrue(abs(delayMassResult.Solution(length(delayMassResult.Time)) - 1.10125) < 2e-3);
