% Output is size(A,1) x ceil(size(A,2) / number of conversions)
R = compose('%d', 1:3);
asserts.isequal(R, ["1" "2" "3"]);
%=============================================================================
R = compose('%d', [1; 2; 3]);
asserts.isequal(R, ["1"; "2"; "3"]);
%=============================================================================
R = compose('%d:%d', [1 2 3 4]);
asserts.isequal(R, ["1:2" "3:4"]);
%=============================================================================
R = compose('%d:%d', [1 2 3]);
asserts.isequal(R, ["1:2" "3:%d"]);
%=============================================================================
R = compose('%d:%d', [1; 2]);
asserts.isequal(R, ["1:%d"; "2:%d"]);
%=============================================================================
R = compose('%d', [1 2; 3 4]);
asserts.isequal(R, ["1" "2"; "3" "4"]);
%=============================================================================
R = compose('%d', 7);
asserts.isequal(R, "7");
%=============================================================================
% Several arguments: output has the shape of the non-scalar arguments
R = compose('%s=%d', ["a" "b"], [1 2]);
asserts.isequal(R, ["a=1" "b=2"]);
%=============================================================================
R = compose('%s=%d', ["a"; "b"], [1; 2]);
asserts.isequal(R, ["a=1"; "b=2"]);
%=============================================================================
R = compose('%s=%d', "x", [1 2]);
asserts.isequal(R, ["x=1" "x=2"]);
%=============================================================================
% A character vector is one value, not one per character
R = compose('%s', 'abc');
asserts.isequal(R, "abc");
%=============================================================================
R = compose('%s=%d', 'x', [1 2]);
asserts.isequal(R, ["x=1" "x=2"]);
%=============================================================================
% A string array formatSpec keeps its shape
R = compose(["%d a"; "%d b"], 5);
asserts.isequal(R, ["5 a"; "5 b"]);
%=============================================================================
R = compose(["a" "b"]);
asserts.isequal(R, ["a" "b"]);
