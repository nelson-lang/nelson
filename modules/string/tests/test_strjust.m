R = strjust('      s', 'center');
REF = '   s   ';
asserts.isequal(R, REF);
%=============================================================================
R = strjust([]);
REF = [];
asserts.isequal(R, REF);
%=============================================================================
str = ["Nelson"; "Mir   "; "ISS   "];
R = strjust(str, 'right');
REF = ["Nelson"; "   Mir"; "   ISS"];
asserts.isequal(R, REF);
%=============================================================================
str = {'Nelson'; 'Mir   '; 'ISS   '};
R = strjust(str, 'right');
REF = {'Nelson'; '   Mir'; '   ISS'};
asserts.isequal(R, REF);
%=============================================================================
R = strjust([69, 77]);
REF = 'EM';
asserts.isequal(R, REF);
