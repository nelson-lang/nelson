%=============================================================================
% C escape sequences \" ' \? produce the literal quote/question mark
asserts.isequal(double(sprintf('\"')), 34);
asserts.isequal(double(sprintf('\''')), 39);
asserts.isequal(double(sprintf('\?')), 63);
asserts.isequal(sprintf('say \"hi\"'), 'say "hi"');
