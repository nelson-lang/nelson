asserts.isequal(nargin('sprintf'), -1);
asserts.isequal(nargout('sprintf'), 2);
%=============================================================================
R = sprintf('%s', 'hello');
REF = 'hello';
asserts.isequal(R, REF);
%=============================================================================
R = sprintf('%s %s', 'hello', 'Nelson');
REF = 'hello Nelson';
asserts.isequal(R, REF);
%=============================================================================
R = sprintf(' %d %', 10);
