asserts.isequal(nargin('isStringScalar'), 1);
asserts.isequal(nargout('isStringScalar'), 1);
%=============================================================================
R = isStringScalar('hello');
asserts.isfalse(R);
%=============================================================================
R = isStringScalar("hello");
asserts.istrue(R);
%=============================================================================
R = isStringScalar(string(NaN));
asserts.istrue(R);
%=============================================================================
R = isStringScalar(string([]));
asserts.isfalse(R);
%=============================================================================
R = isStringScalar(["hello", "world"]);
asserts.isfalse(R);
