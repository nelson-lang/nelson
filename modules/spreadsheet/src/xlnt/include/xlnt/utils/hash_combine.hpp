#pragma once

#include <cstddef>
#include <functional>

namespace xlnt {
namespace detail {

    /// <summary>
    /// A standard, robust way to combine hash values.
    /// Often credited to Boost's hash_combine.
    /// </summary>
    template <class T>
    inline void
    hash_combine(std::size_t& seed, const T& v)
    {
        std::hash<T> hasher;
        seed ^= hasher(v) + 0x9e3779b9 + (seed << 6) + (seed >> 2);
    }

} // namespace detail
} // namespace xlnt
