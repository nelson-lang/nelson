function y = years(x)
  narginchk(1, 1);
  if isa(x, 'duration')
    y = double(x) ./ (86400 * 365.2425);
  else
    y = duration(0, 0, double(x) .* 86400 .* 365.2425);
    y.Format = 'y';
  end
end
