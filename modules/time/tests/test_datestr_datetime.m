R = datestr(datetime(2024, 12, 25), 'yyyy-mm-dd');
REF = '2024-12-25';
asserts.isequal(R, REF);
%=============================================================================
R = datestr(datetime(2024, 12, 25));
REF = '25-Dec-2024';
asserts.isequal(R, REF);
%=============================================================================
R = datestr(datetime(2024, 1, 1) + calmonths(0:2));
REF = ['01-Jan-2024'; '01-Feb-2024'; '01-Mar-2024'];
asserts.isequal(R, REF);
%=============================================================================
R = datestr(datetime(2024, 3, 15, 13, 45, 0), 'HH:MM');
REF = '13:45';
asserts.isequal(R, REF);
