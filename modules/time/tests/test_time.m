asserts.isequal(nargin('time'), 0);
asserts.isequal(nargout('time'), 1);
%=============================================================================
t = time();
t2 = time();
asserts.istrue(t2 >= t);
%=============================================================================
t = time('s');
asserts.isequal(class(t), 'double');
sleep(0.2);
t2 = time('s');
asserts.istrue(t2 - t >= 0.05);
asserts.istrue(t2 - t < 2);
%=============================================================================
t = time('ns');
asserts.isequal(class(t), 'uint64');
