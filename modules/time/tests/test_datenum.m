asserts.isequal(nargin('datenum'), 6);
asserts.isequal(nargout('datenum'), 1);
%=============================================================================
d = datenum([1973, 8, 4, 12, 1, 18]);
REF = 720840.500902777770534;
asserts.isequal(d, REF);
%=============================================================================
R = datevec(d);
REF = [1973, 8, 4, 12, 1, 18];
asserts.isequal(R, REF);
%=============================================================================
asserts.isequal(datenum(1973, 8, 4), 720840);
asserts.isequal(datenum(1970, 1, 1), 719529);
%=============================================================================
R = datenum([10000, 200000]);
REF = [10000, 200000];
asserts.isequal(R, REF);
%=============================================================================
Y = [1973; 1974];
M = [8; 7];
D = [15; 4];
R = datenum(Y, M, D);
REF = [720851; 721174];
asserts.isequal(R, REF);
%=============================================================================
Y = [1973; 1974];
M = [8; 7];
D = [15; 4];
H = [1; 12];
MIN = 30;
S = [0; 1];
R = datenum(Y, M, D, H, MIN, S);
REF = 1.0e+05 * [7.208510625000000; 7.211745208449074];
asserts.isequal(R, REF);
%=============================================================================
Y = [1973; 1974];
M = [8; 7];
D = [15; 4];
R = datenum(Y, M, D);
REF = [720851; 721174];
asserts.isequal(R, REF);
%=============================================================================
V = [1973 8 15; 1974 7 4; 2024 2 29];
R = datenum(V);
REF = [720851; 721174; 739311];
asserts.isequal(R, REF);
%=============================================================================
V = [1973 8 15 1 30 0; 1974 7 4 12 30 1; 2024 2 29 23 59 59];
R = datenum(V);
REF = [720851.0625; 721174.520844907383434; 739311.999988425988704];
asserts.isapprox(R, REF, 10 * eps);
%=============================================================================
V = [2020 * ones(1000, 1), ones(1000, 1), ones(1000, 1), zeros(1000, 3)];
R = datenum(V);
asserts.isequal(size(R), [1000 1]);
asserts.isequal(R(1), datenum(2020, 1, 1, 0, 0, 0));
asserts.isequal(R(end), datenum(2020, 1, 1, 0, 0, 0));
