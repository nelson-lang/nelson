[y, m, d] = ymd(datetime(2024, 5, 17));
asserts.isequal([y m d], [2024 5 17]);
[y, m, d] = ymd([datetime(2024, 1, 1), datetime(2025, 2, 3)]);
asserts.isequal(y, [2024 2025]);
asserts.isequal(m, [1 2]);
asserts.isequal(d, [1 3]);
