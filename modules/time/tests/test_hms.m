[h, m, s] = hms(datetime(2024, 5, 17, 13, 14, 15));
asserts.isequal([h m s], [13 14 15]);
[h, m, s] = hms(duration(27, 5, 6));
asserts.isequal([h m s], [27 5 6]);
[h, m, s] = hms(seconds(-3661));
asserts.isequal([h m s], [-1 1 1]);
