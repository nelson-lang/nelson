asserts.isequal(nargin('cputime'), 0);
asserts.isequal(nargout('cputime'), 1);
%=============================================================================
t1 = cputime;
A = rand(100, 100);
value = sum(A(:));
t2 = cputime;
asserts.istrue(value >= 0);
asserts.istrue(t2 >= t1);
