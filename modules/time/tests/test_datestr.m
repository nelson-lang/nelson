%=============================================================================
% A day-of-month 'dd' token must still be rendered when a day-name 'dddd'
% token appears earlier in the format.
R = datestr([2020, 7, 28, 0, 0, 0], 'dddd, mmmm dd, yyyy');
REF = 'Tuesday, July 28, 2020';
asserts.isequal(R, REF);
%=============================================================================
R = datestr([2020, 7, 28, 0, 0, 0], 'ddd dd mmm yyyy');
REF = 'Tue 28 Jul 2020';
asserts.isequal(R, REF);
%=============================================================================
% 'HH' with an AM/PM token uses a 12-hour clock (midnight is 12 AM).
R = datestr([2020, 7, 28, 0, 0, 0], 'HH:MM PM');
REF = '12:00 AM';
asserts.isequal(R, REF);
%=============================================================================
R = datestr([2020, 7, 28, 0, 0, 0], 'HH:MM AM');
REF = '12:00 AM';
asserts.isequal(R, REF);
%=============================================================================
% Noon is 12 PM.
R = datestr([2020, 7, 28, 12, 0, 0], 'HH:MM PM');
REF = '12:00 PM';
asserts.isequal(R, REF);
%=============================================================================
% Afternoon hours are converted to the 12-hour clock and space-padded.
R = datestr([2020, 7, 28, 13, 5, 9], 'HH:MM:SS PM');
REF = ' 1:05:09 PM';
asserts.isequal(R, REF);
%=============================================================================
% A day-name token together with a 12-hour clock.
R = datestr([2020, 7, 28, 13, 5, 9], 'dddd HH:MM PM');
REF = 'Tuesday  1:05 PM';
asserts.isequal(R, REF);
