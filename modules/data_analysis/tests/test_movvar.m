asserts.isequal(nargin('movvar'), -3);
asserts.isequal(nargout('movvar'), 2);
%=============================================================================
A = [1 2 8 4 5];
REF = [1 / 2 43 / 3 28 / 3 13 / 3 1 / 2];
asserts.isapprox(movvar(A, 3), REF, 1e-12);
%=============================================================================
B = [1 3; 2 4; 8 5];
REF = [1 / 2 1 / 2; 43 / 3 1; 18 1 / 2];
asserts.isapprox(movvar(B, 3, 1), REF, 1e-12);
%=============================================================================
W = [1 2 8 4 5];
asserts.isapprox(movvar(W, 3), [1 / 2 43 / 3 28 / 3 13 / 3 1 / 2], 1e-12);
%=============================================================================
% [S, M] with M the moving mean over the same windows
A = [4 8 6 -1 -2 -3 -1 3 4 5];
MU = [6 6 13 / 3 1 -2 -2 -1 / 3 2 4 4.5];
[S, M] = movvar(A, 3);
asserts.isapprox(S, [8 4 67 / 3 19 1 1 28 / 3 7 1 0.5], 1e-12);
asserts.isapprox(M, MU, 1e-12);
asserts.isequal(size(M), size(A));
%=============================================================================
[S, M] = movvar(A, 3, 'Endpoints', 'discard');
asserts.isapprox(M, MU(2:end - 1), 1e-12);
asserts.isequal(size(S), size(M));
%=============================================================================
B = [1 NaN 3 4];
[S, M] = movvar(B, 3, 'omitnan');
asserts.isapprox(M, [1 2 3.5 3.5], 1e-12);
[S, M] = movvar(B, 3);
asserts.isequal(isnan(M), [true true true false]);
%=============================================================================
C = [1 3; 2 4; 8 5];
[S, M] = movvar(C, 3, 2);
asserts.isapprox(M, [2 2; 3 3; 6.5 6.5], 1e-12);
