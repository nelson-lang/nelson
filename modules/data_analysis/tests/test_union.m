asserts.isequal(union([5 7 1], [3 1 1]), [1 3 5 7]);
%=============================================================================
clear ans;
txt = evalc('union([5 7 1], [3 1 1])');
asserts.istrue(contains(txt, 'ans ='));
asserts.istrue(contains(txt, '1     3     5     7'));
%=============================================================================
% 'rows' option
[C, ia, ib] = union([1 2; 3 4], [3 4; 5 6], 'rows');
asserts.isequal(C, [1 2; 3 4; 5 6]);
asserts.isequal(ia, [1; 2]);
asserts.isequal(ib, 2);
%=============================================================================
C = union([5 6; 1 2; 3 4], [3 4; 9 9], 'rows', 'stable');
asserts.isequal(C, [5 6; 1 2; 3 4; 9 9]);
