asserts.isequal(nargin('movmedian'), -3);
asserts.isequal(nargout('movmedian'), 1);
%=============================================================================
A = [1 2 8 4 5];
asserts.isequal(movmedian(A, 3), [1.5 2 4 5 4.5]);
%=============================================================================
B = [1 3; 2 4; 8 5];
asserts.isequal(movmedian(B, 3, 1), [1.5 3.5; 2 4; 5 4.5]);
%=============================================================================
W = [1 2 8 4 5];
asserts.isequal(movmedian(W, 3), [1.5 2 4 5 4.5]);
