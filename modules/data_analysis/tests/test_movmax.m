asserts.isequal(nargin('movmax'), -3);
asserts.isequal(nargout('movmax'), 1);
%=============================================================================
A = [1 2 8 4 5];
asserts.isequal(movmax(A, 3), [2 8 8 8 5]);
%=============================================================================
B = [1 3; 2 4; 8 5];
asserts.isequal(movmax(B, 3, 1), [2 4; 8 5; 8 5]);
%=============================================================================
W = [1 2 8 4 5];
asserts.isequal(movmax(W, 3), [2 8 8 8 5]);
