asserts.isequal(nargin('movprod'), -3);
asserts.isequal(nargout('movprod'), 1);
%=============================================================================
A = [1 2 8 4 5];
asserts.isequal(movprod(A, 3), [2 16 64 160 20]);
%=============================================================================
B = [1 3; 2 4; 8 5];
asserts.isequal(movprod(B, 3, 1), [2 12; 16 60; 16 20]);
%=============================================================================
W = [1 2 8 4 5];
asserts.isequal(movprod(W, 3), [2 16 64 160 20]);
