asserts.isequal(nargin('movmad'), -3);
asserts.isequal(nargout('movmad'), 1);
%=============================================================================
A = [1 2 8 4 5];
asserts.isequal(movmad(A, 3), [0.5 1 2 1 0.5]);
%=============================================================================
B = [1 3; 2 4; 8 5];
asserts.isequal(movmad(B, 3, 1), [0.5 0.5; 1 1; 3 0.5]);
%=============================================================================
W = [1 2 8 4 5];
asserts.isequal(movmad(W, 3), [0.5 1 2 1 0.5]);
