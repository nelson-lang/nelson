[G, gid] = findgroups([1; 2; 1; 3; 2]);
assert_isequal(G, [1; 2; 1; 3; 2]);
assert_isequal(gid, [1; 2; 3]);
%=============================================================================
assert_isequal(findgroups([10 30 10 20]), [1 3 1 2]);
%=============================================================================
assert_isequal(findgroups([1; NaN; 1; 2]), [1; NaN; 1; 2]);
%=============================================================================
[G, g1, g2] = findgroups([1; 1; 2; 2], [10; 20; 10; 20]);
assert_isequal(G, [1; 2; 3; 4]);
assert_isequal(g1, [1; 1; 2; 2]);
assert_isequal(g2, [10; 20; 10; 20]);
%=============================================================================
assert_isequal(findgroups(categorical({'a', 'b', 'a'})), [1 2 1]);
%=============================================================================
r = splitapply(@sum, [10; 20; 30; 40; 50], findgroups([1; 2; 1; 2; 1]));
assert_isequal(r, [90; 60]);
%=============================================================================
r = splitapply(@(x) max(x) - min(x), [5; 1; 8; 3], findgroups([1; 1; 2; 2]));
assert_isequal(r, [4; 5]);
