asserts.isequal(nargin('movmean'), -3);
asserts.isequal(nargout('movmean'), 1);
%=============================================================================
A = [1 2 8 4 5];
asserts.isapprox(movmean(A, 3), [1.5 11 / 3 14 / 3 17 / 3 4.5], 1e-12);
%=============================================================================
B = [1 3; 2 4; 8 5];
asserts.isapprox(movmean(B, 3, 1), [1.5 3.5; 11 / 3 4; 5 4.5], 1e-12);
%=============================================================================
W = [1 2 8 4 5];
asserts.isapprox(movmean(W, 3), [1.5 11 / 3 14 / 3 17 / 3 4.5], 1e-12);
%=============================================================================
% Numeric 'Endpoints' fill value pads incomplete windows with that value.
asserts.isapprox(movmean([1 2 3 4], 2, 'Endpoints', 0), [0.5 1.5 2.5 3.5], 1e-12);
asserts.isapprox(movmean([1 2 3 4 5], 3, 'Endpoints', 0), [1 2 3 4 3], 1e-12);
asserts.isapprox(movmean([10 20 30], 3, 'Endpoints', 5), [35 / 3 20 55 / 3], 1e-10);
