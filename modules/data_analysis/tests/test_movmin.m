asserts.isequal(nargin('movmin'), -3);
asserts.isequal(nargout('movmin'), 1);
%=============================================================================
A = [1 2 8 4 5];
asserts.isequal(movmin(A, 3), [1 1 2 4 4]);
%=============================================================================
B = [1 3; 2 4; 8 5];
asserts.isequal(movmin(B, 3, 1), [1 3; 1 3; 2 4]);
%=============================================================================
W = [1 2 8 4 5];
asserts.isequal(movmin(W, 3), [1 1 2 4 4]);
