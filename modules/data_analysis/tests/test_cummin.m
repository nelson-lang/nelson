asserts.isequal(nargin('cummin'), -2);
asserts.isequal(nargout('cummin'), 1);
%=============================================================================
A = [3 1; 2 4; 5 0];
asserts.isequal(cummin(A), [3 1; 2 1; 2 0]);
asserts.isequal(cummin(A, 2), [3 1; 2 2; 5 0]);
%=============================================================================
B = [3 1; 2 4; 5 0];
asserts.isequal(cummin(B), [3 1; 2 1; 2 0]);
