asserts.isequal(setdiff([5 7 1], [3 1 1]), [5 7]);
%=============================================================================
[C, ia] = setdiff([3 1 2 3 4], [2], 'stable');
asserts.isequal(C, [3 1 4]);
asserts.isequal(ia, [1; 2; 5]);
%=============================================================================
[C, ia] = setdiff({'red', 'blue', 'red', 'green'}, {'blue'}, 'stable');
asserts.isequal(C, {'red', 'green'});
asserts.isequal(ia, [1; 4]);
%=============================================================================
% 'rows' option
[C, ia] = setdiff([1 2; 3 4; 5 6], [3 4], 'rows');
asserts.isequal(C, [1 2; 5 6]);
asserts.isequal(ia, [1; 3]);
