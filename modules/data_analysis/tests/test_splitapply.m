G = findgroups([1; 2; 1; 2; 1]);
assert_isequal(splitapply(@sum, [10; 20; 30; 40; 50], G), [90; 60]);
%=============================================================================
assert_isequal(splitapply(@max, [3; 9; 1; 7], findgroups([1; 1; 2; 2])), [9; 7]);
%=============================================================================
assert_isequal(splitapply(@(x) sum(x), [1; 2; 3], findgroups([1; 1; 2])), [3; 3]);
%=============================================================================
assert_isequal(class(splitapply(@sum, [1; 2], findgroups([1; 2]))), 'double');
%=============================================================================
assert_checkerror('splitapply(1, [1; 2], [1; 2])', _('First input must be a function handle.'));
