%=============================================================================
asserts.isequal(nargin('min'), 4)
asserts.isequal(nargout('min'), 2)
%=============================================================================
R = min([]);
asserts.isequal(R, []);
%=============================================================================
[R, I] = min([]);
asserts.isequal(R, []);
asserts.isequal(I, []);
%=============================================================================
[R, I] = min(5);
asserts.isequal(R, 5);
asserts.isequal(I, 1);
%=============================================================================
[R, I] = min([1 NaN 3 Inf -Inf 4]);
asserts.isequal(R, -Inf);
asserts.isequal(I, 5);
%=============================================================================
A = [23 42 37 18 52];
R = min(A);
asserts.isequal(R, 18);
%=============================================================================
A = [23 42 37 18 52];
[R, I] = min(A);
asserts.isequal(R, 18);
asserts.isequal(I, 4);
%=============================================================================
A = [-2 + 2i, 4 + i, -1 - 3i];
[R, I] = min(A);
asserts.isequal(R, -2 + 2i);
asserts.isequal(I, 1);
%=============================================================================
A = [-2 + 2i, 4 + i, -1 - 5i];
[R, I] = min(A);
asserts.isequal(R, -2 + 2i);
asserts.isequal(I, 1);
%=============================================================================
A = [2 8 4; 7 3 9];
R = min(A);
asserts.isequal(R, [2 3 4]);
%=============================================================================
A = [1.7 1.2 1.5; 1.3 1.6 1.99];
R = min(A, [], 2);
asserts.isequal(R, [1.2; 1.3]);
%=============================================================================
A = [1 9 -2; 8 4 -5];
[R, I] = min(A);
asserts.isequal(R, [1 4 -5]);
asserts.isequal(I, [1 2 2]);
%=============================================================================
A = [1 7 3; 6 2 9];
B = 5;
R = min(A, B);
REF = [1 5 3; 5 2 5];
asserts.isequal(R, REF);
%=============================================================================
A = [8 2 4; 7 3 9];
[R, I] = min(A(:));
asserts.isequal(R, 2);
asserts.isequal(I, 3);
%=============================================================================
A = 'Nelson';
[R, I] = min(A);
asserts.isequal(R, 78);
asserts.isequal(I, 1);
%=============================================================================
A = [1 7 3; 6 2 9];
B = 5i;
R = min(A, B);
REF = [1.0000 + 0.0000i 0.0000 + 5.0000i 3.0000 + 0.0000i;
  0.0000 + 5.0000i 2.0000 + 0.0000i 0.0000 + 5.0000i];
asserts.isequal(R, REF);
%=============================================================================
A = [1 complex(7, NaN) 3; 6 2 complex(NaN, 9)];
B = 5;
R = min(A, B);
REF = [1 5 3; 5 2 5];
asserts.isequal(R, REF);
%=============================================================================
A = [1 complex(7, NaN) 3; 6 2 complex(NaN, 9)];
[R, I] = min(A, [], 1, 'omitnan');
asserts.isequal(R, [1 2 3]);
asserts.isequal(I, [1 2 1]);
%=============================================================================
A = [1 complex(7, NaN) 3; 6 2 complex(NaN, 9)];
[R, I] = min(A, [], 1);
asserts.isequal(R, [1 2 3]);
asserts.isequal(I, [1 2 1]);
%=============================================================================
A = [1 complex(7, NaN) 3; 6 2 complex(NaN, 9)];
[R, I] = min(A, [], 1, 'includenan');
asserts.isequal(R, [1, complex(7, NaN), complex(NaN, 9)]);
asserts.isequal(I, [1 1 2]);
%=============================================================================
A = [1 NaN 3; 6 2 NaN];
[R, I] = min(A, [], 1, 'omitnan');
asserts.isequal(R, [1 2 3]);
asserts.isequal(I, [1 2 1]);
%=============================================================================
A = [1 NaN 3; 6 2 NaN];
[R, I] = min(A, [], 1);
asserts.isequal(R, [1 2 3]);
asserts.isequal(I, [1 2 1]);
%=============================================================================
A = [1 NaN 3; 6 2 NaN];
[R, I] = min(A, [], 1, 'includenan');
asserts.isequal(R, [1 NaN NaN]);
asserts.isequal(I, [1 1 2]);
%=============================================================================
A = [1.77 -0.005 3.98 -2.95 NaN 0.34 NaN 0.19];
R = min(A, [], 'omitnan');
REF = -2.95;
asserts.isequal(R, REF);
%=============================================================================
R = min(A, [], 'includenan');
REF = NaN;
asserts.isequal(R, REF);
%=============================================================================
A = [1 NaN 3; 6 2 9];
B = [1 NaN 3; 6 2 NaN];
R = min(A, B);
asserts.isequal(R, [1 NaN 3; 6 2 9]);
R = min(A, B, 'omitnan');
asserts.isequal(R, [1 NaN 3; 6 2 9]);
R = min(A, B, 'includenan');
asserts.isequal(R, [1 NaN 3; 6 2 NaN]);
%=============================================================================
A = [1 NaN 3; 6 2 9] + i;
B = [1 NaN 3; 6 2 NaN];
R = min(A, B);
REF = [1.0000 + 0.0000i NaN + 1.0000i 3.0000 + 0.0000i;
  6.0000 + 0.0000i 2.0000 + 0.0000i 9.0000 + 1.0000i];
asserts.isequal(R, REF);
%=============================================================================
R = min(A, B, 'omitnan');
REF = [1.0000 + 0.0000i NaN + 1.0000i 3.0000 + 0.0000i;
  6.0000 + 0.0000i 2.0000 + 0.0000i 9.0000 + 1.0000i];
asserts.isequal(R, REF);
%=============================================================================
R = min(A, B, 'includenan');
REF = [1.0000 + 0.0000i NaN + 1.0000i 3.0000 + 0.0000i;
  6.0000 + 0.0000i 2.0000 + 0.0000i NaN + 0.0000i];
asserts.isequal(R, REF);
%=============================================================================
M = [10 20 30; 33 34 36; 39 3 44];
R = min(M, [], 'all');
asserts.isequal(R, 3);
%=============================================================================
[M, I] = min([1 2 3], [], 3);
REF_M = [1 2 3];
REF_I = [1 1 1];
asserts.isequal(M, REF_M);
asserts.isequal(I, REF_I);
%=============================================================================
B = [3 1; 2 4; 5 0];
[columnMin, columnMinIndices] = min(B);
asserts.isequal(columnMin, [2 0]);
asserts.isequal(columnMinIndices, [2 3]);
%=============================================================================
% 'all' with index output
[m, i] = min([1 2 3; 4 5 6], [], 'all');
assert_isequal(m, 1);
assert_isequal(i, 1);
%=============================================================================
% vector of dimensions (vecdim)
A = reshape(1:24, 2, 3, 4);
assert_isequal(min(A, [], [2 3]), [1; 2]);
