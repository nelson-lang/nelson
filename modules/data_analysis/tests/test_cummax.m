asserts.isequal(nargin('cummax'), -2);
asserts.isequal(nargout('cummax'), 1);
%=============================================================================
A = [3 1; 2 4; 5 0];
asserts.isequal(cummax(A), [3 1; 3 4; 5 4]);
asserts.isequal(cummax(A, 2), [3 3; 2 4; 5 5]);
%=============================================================================
B = [3 1; 2 4; 5 0];
asserts.isequal(cummax(B), [3 1; 3 4; 5 4]);
