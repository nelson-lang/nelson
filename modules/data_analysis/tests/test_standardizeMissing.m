A = [1; -99; 3];
R = standardizeMissing(A, -99);
asserts.istrue(isnan(R(2)));
%=============================================================================
C = {'a'; 'missing'; 'b'};
R = standardizeMissing(C, 'missing');
asserts.isequal(R{2}, []);
%=============================================================================
E = standardizeMissing([1; -99; 3], -99);
asserts.isequal(E, [1; NaN; 3]);
