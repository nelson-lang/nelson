asserts.isequal(nargin('movsum'), -3);
asserts.isequal(nargout('movsum'), 1);
%=============================================================================
A = [1 2 8 4 5];
asserts.isequal(movsum(A, 3), [3 11 14 17 9]);
%=============================================================================
B = [1 3; 2 4; 8 5];
asserts.isequal(movsum(B, 3, 1), [3 7; 11 12; 10 9]);
%=============================================================================
W = [1 2 8 4 5];
asserts.isequal(movsum(W, 3), [3 11 14 17 9]);
