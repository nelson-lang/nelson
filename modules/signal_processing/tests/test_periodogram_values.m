[pxx, f] = periodogram(ones(16, 1), [], 16, 8);
asserts.isequal(length(pxx), 9);
asserts.isequal(f(1), 0);
%=============================================================================
[pxx, f] = periodogram(sin((0:127)' * 0.1), [], 128, 10);
asserts.isapprox(pxx(1:6).', [1.89377417610814e-05 0.00359829484372897 6.25498647388943 0.0134621945878161 0.00401094686629151 0.00202718055430609], 1e-12);
asserts.isapprox(f(1:6).', [0 0.078125 0.15625 0.234375 0.3125 0.390625], 1e-12);
%=============================================================================
x = sin((0:7)' * 0.2);
[pxx, f] = periodogram(x, [], 8, 4, 'twosided');
asserts.isapprox(pxx.', [0.669627100731936 0.0762723691283261 0.0195309173022136 ...
  0.0111844900093334 0.00950196604226946 0.0111844900093334 ...
  0.0195309173022136 0.0762723691283261], 1e-12);
asserts.isapprox(f.', [0 0.5 1 1.5 2 2.5 3 3.5], 1e-12);
%=============================================================================
[pxx, f] = periodogram(x, [], 8, 4, 'centered');
asserts.isapprox(pxx.', [0.0111844900093334 0.0195309173022136 0.0762723691283261 ...
  0.669627100731936 0.0762723691283261 0.0195309173022136 ...
  0.0111844900093334 0.00950196604226946], 1e-12);
asserts.isapprox(f.', [-1.5 -1 -0.5 0 0.5 1 1.5 2], 1e-12);
%=============================================================================
[pxx, f] = periodogram(x, [], 8, 4, 'power');
asserts.isapprox(pxx.', [0.334813550365968 0.0762723691283261 0.0195309173022136 ...
  0.0111844900093334 0.00475098302113473], 1e-12);
asserts.isapprox(f.', [0 0.5 1 1.5 2], 1e-12);
%=============================================================================
[pxx, f] = periodogram(x, [], 8, 4, 'power', 'twosided');
asserts.isapprox(pxx.', [0.334813550365968 0.038136184564163 0.00976545865110678 ...
  0.0055922450046667 0.00475098302113473 0.0055922450046667 ...
  0.00976545865110678 0.038136184564163], 1e-12);
asserts.isapprox(f.', [0 0.5 1 1.5 2 2.5 3 3.5], 1e-12);
