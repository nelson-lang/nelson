b = fir2(4, [0 1], [1 0]);
asserts.isequal(length(b), 5);
asserts.isapprox(b, [0 0.109427221657125 0.5 0.109427221657125 0], 1e-12);
%=============================================================================
b = fir2(5, [0 1], [1 0]);
asserts.isapprox(b, [0.00129693658223624 0.017916061609652 0.369679876032147 0.369679876032147 0.017916061609652 0.00129693658223624], 1e-12);
%=============================================================================
b = fir2(4, [0 1], [1 0], ones(5, 1));
asserts.isapprox(b, [0 0.20264300306875 0.5 0.20264300306875 0], 1e-12);
%=============================================================================
asserts.checkerror('fir2(4, [0 1], [1])', _('Frequency and magnitude vectors must have the same length.'));
