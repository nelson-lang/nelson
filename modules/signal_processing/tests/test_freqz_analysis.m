[h, w] = freqz([1 1], 1, 4);
REF = [2; 1.7071 - 0.7071i; 1 - 1i; 0.2929 - 0.7071i];
asserts.isapprox(h, REF, 1e-4);
asserts.isapprox(w, [0; pi / 4; pi / 2; 3 * pi / 4], 1e-12);
%=============================================================================
[h, w] = freqz([1 1], 1, 4, 'whole');
REF = [2; 1 - 1i; 0; 1 + 1i];
asserts.isapprox(h, REF, 1e-12);
asserts.isapprox(w, [0; pi / 2; pi; 3 * pi / 2], 1e-12);
%=============================================================================
[h, f] = freqz([1 1], 1, 4, 10);
REF = [2; 1.7071 - 0.7071i; 1 - 1i; 0.2929 - 0.7071i];
asserts.isapprox(h, REF, 1e-4);
asserts.isapprox(f, [0; 1.25; 2.5; 3.75], 1e-12);
%=============================================================================
[h, w] = freqz([1 0.5], [1 -0.25], [0 pi / 2 pi]);
REF = [2; 0.823529411764706 - 0.705882352941177i; 0.4 - 5.87830463590729e-17i];
asserts.isapprox(h, REF, 1e-12);
asserts.isapprox(w, [0; pi / 2; pi], 1e-12);
%=============================================================================
[h, f] = freqz([1 0.5], [1 -0.25], [0 2 4], 10);
REF = [2; 1.04874797357035 - 0.785571654593599i; 0.458583404728767 - 0.300501967142334i];
asserts.isapprox(h, REF, 1e-12);
asserts.isapprox(f, [0; 2; 4], 1e-12);
%=============================================================================
sos = [1 0.5 0.25 1 -0.25 0; 1 0.75 0.5 1 0.5 0.25];
[h, w] = freqz(sos, 4);
REF = [3; 1.5200933732468 - 1.57800096466279i; ...
  0.294117647058824 - 0.823529411764706i; 0.386521412745413 - 0.0838375405382777i];
asserts.isapprox(h, REF, 1e-12);
asserts.isapprox(w, [0; pi / 4; pi / 2; 3 * pi / 4], 1e-12);
%=============================================================================
asserts.checkerror('freqz([], 1)', _('Filter coefficients must be vectors.'));
asserts.checkerror('freqz([1], [])', _('Filter coefficients must be vectors.'));
asserts.checkerror('freqz([1], 0)', _('First denominator filter coefficient must be nonzero.'));
