t = [0 pi / 2 pi 3 * pi / 2 2 * pi];
asserts.isapprox(sawtooth(t), [-1 -0.5 0 0.5 -1], 1e-12);
asserts.isapprox(sawtooth(t, 0.5), [-1 0 1 0 -1], 1e-12);
asserts.isapprox(sawtooth([0 NaN pi]), [-1 NaN 0], 1e-12);
