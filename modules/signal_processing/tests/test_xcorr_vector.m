[c, lags] = xcorr([1 2 3]);
asserts.isequal(c(:).', [3 8 14 8 3]);
asserts.isequal(lags(:).', [-2 -1 0 1 2]);
%=============================================================================
[c, lags] = xcorr([1 2 3], 1);
asserts.isequal(c(:).', [8 14 8]);
asserts.isequal(lags(:).', [-1 0 1]);
%=============================================================================
[c, lags] = xcorr([1 2 3], -1);
asserts.isequal(c(:).', [8 14 8]);
asserts.isequal(lags(:).', [-1 0 1]);
asserts.checkerror('xcorr([1 2 3], 1.5)', _('Value must be an integer.'));
%=============================================================================
[c, lags] = xcorr([1 2 3], [4 5]);
asserts.isapprox(c, [0 5 14 23 12], 1e-12);
asserts.isequal(lags, [-2 -1 0 1 2]);
%=============================================================================
[c, lags] = xcorr([1 + i 2], [3 4 * i]);
asserts.isapprox(c, [4 - 4 * i 3 - 5 * i 6], 1e-12);
asserts.isequal(lags, [-1 0 1]);
%=============================================================================
asserts.isapprox(xcorr([1 2 3], 'biased'), [1 2.6666667 4.6666667 2.6666667 1], 1e-6);
asserts.isapprox(xcorr([1 2 3], 'unbiased'), [3 4 4.6666667 4 3], 1e-6);
asserts.isapprox(xcorr([1 2 3], 'coeff'), [0.21428571 0.57142857 1 0.57142857 0.21428571], 1e-6);
