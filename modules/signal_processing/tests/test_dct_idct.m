x = [1; 2; 3; 4];
y = dct(x);
ref = [5; -2.230442497387663; 0; -0.158512667781108];
asserts.isapprox(y, ref, 1e-12);
asserts.isapprox(idct(y), x, 1e-12);
A = eye(4);
C = dct(A);
asserts.isapprox(C.' * C, eye(4), 1e-12);
asserts.isapprox(idct(C), A, 1e-12);
