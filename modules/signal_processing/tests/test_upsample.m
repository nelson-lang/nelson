y = upsample([1 2 3], 2);
REF = [1 0 2 0 3 0];
asserts.isequal(y, REF);
%=============================================================================
y = upsample([1 2 3], 2, 1);
REF = [0 1 0 2 0 3];
asserts.isequal(y, REF);
%=============================================================================
x = [1 2; 3 4];
y = upsample(x, 2, 0, 2);
REF = [1 0 2 0; 3 0 4 0];
asserts.isequal(y, REF);
