x(100:250:1900) = 5;
tic();
for k = 1:3
  y1 = medfilt1(x, 11);
  y2 = sgolayfilt(x, 3, 11);
end
toc();
asserts.isequal(size(y1), size(x));
asserts.isequal(size(y2), size(x));
