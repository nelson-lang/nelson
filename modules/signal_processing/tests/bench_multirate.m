x = sin((0:9999)' * 0.01);
h = hamming(33);
tic();
for k = 1:20
  y1 = upfirdn(x, h, 3, 2);
  y2 = resample(x, 3, 2);
end
toc();
asserts.istrue(iscolumn(y1));
asserts.istrue(iscolumn(y2));
%=============================================================================
xm = [x, cos((0:9999)' * 0.01)];
tic();
for k = 1:20
  ym = upfirdn(xm, h, 3, 2, 1);
end
toc();
asserts.isequal(size(ym, 2), 2);
