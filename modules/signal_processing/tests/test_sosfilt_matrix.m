sos = [1 0.5 0.25 1 -0.3 0.1; 1 0 0 1 -0.2 0];
y = sosfilt(sos, [1 0 0 0]);
asserts.isequal(length(y), 4);
%=============================================================================
y = sosfilt(sos, [1 2; 3 4; 5 6]);
asserts.isapprox(y, [1 2; 4 6; 8.59 11.18], 1e-12);
%=============================================================================
y = sosfilt(sos, [1 2; 3 4; 5 6], 2);
asserts.isapprox(y, [1 3; 3 7; 5 11], 1e-12);
%=============================================================================
x = reshape(1:12, [2, 3, 2]);
y = sosfilt(sos, x, 3);
REF = zeros(2, 3, 2);
REF(:, :, 1) = [1 3 5; 2 4 6];
REF(:, :, 2) = [8 12 16; 10 14 18];
asserts.isapprox(y, REF, 1e-12);
