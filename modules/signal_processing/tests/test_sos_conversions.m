[b, a] = butter(2, 0.4);
sos = tf2sos(b, a);
[bt, at] = sos2tf(sos);
asserts.isapprox(bt ./ bt(1), b ./ b(1), 1e-8);
asserts.isapprox(at ./ at(1), a ./ a(1), 1e-8);
%=============================================================================
sos = [1 0.5 0.25 1 -0.3 0.1; 1 0 0 1 -0.2 0];
[z, p, k] = sos2zp(sos);
asserts.isapprox(z, [-0.25 + 0.433012701892219 * i; -0.25 - 0.433012701892219 * i; 0], 1e-12);
asserts.isapprox(p, [0.15 + 0.278388218141501 * i; 0.15 - 0.278388218141501 * i; 0.2], 1e-12);
asserts.isequal(k, 1);
%=============================================================================
[z, p, k] = tf2zp(b, a);
sos2 = zp2sos(z, p, k);
asserts.isequal(size(sos2, 2), 6);
%=============================================================================
[bt, at] = sos2tf([]);
asserts.isequal(bt, 1);
asserts.isequal(at, 1);
%=============================================================================
[z, p, k] = sos2zp([]);
asserts.isequal(z, []);
asserts.isequal(p, []);
asserts.isequal(k, 1);
%=============================================================================
sos = zp2sos([], [], 2);
asserts.isequal(sos, [0 0 2 0 0 1]);
%=============================================================================
asserts.checkerror('sos2tf(ones(2, 5))', _('SOS matrix must have six columns.'));
asserts.checkerror('sos2zp(ones(2, 5))', _('SOS matrix must have six columns.'));
