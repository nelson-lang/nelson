y = fftfilt([1 1], [1 2 3 4]);
asserts.isequal(y, [1 3 5 7]);
%=============================================================================
y = fftfilt([1 1], [1; 2; 3; 4]);
asserts.isequal(y, [1; 3; 5; 7]);
%=============================================================================
y = fftfilt([1 1], [1 2; 3 4; 5 6]);
asserts.isequal(y, [1 2; 4 6; 8 10]);
%=============================================================================
y = fftfilt([1 + i 1], [1 2 3]);
asserts.isapprox(y, [1 + i 3 + 2 * i 5 + 3 * i], 1e-12);
%=============================================================================
asserts.isequal(fftfilt([1 1], []), []);
