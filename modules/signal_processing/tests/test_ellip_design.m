[b, a] = ellip(3, 1, 40, 0.35);
asserts.isapprox(b, [0.0747730458009297 0.146777158945922 0.146777158945922 0.0747730458009297], 1e-10);
asserts.isapprox(a, [1 -1.26582639733789 1.05008033898135 -0.341153532149765], 1e-10);
%=============================================================================
[b, a] = ellip(3, 1, 40, 0.35, 'high');
asserts.isapprox(b, [0.292959836855734 -0.823762314783269 0.823762314783269 -0.292959836855734], 1e-10);
asserts.isapprox(a, [1 -0.680709449030789 0.604802125037976 0.0520672707907607], 1e-10);
%=============================================================================
[b, a] = ellip(3, 1, 40, [0.2 0.5]);
asserts.isapprox(b, [0.0554808589120272 -0.0380050559155997 -0.0724889115353581 0 0.0724889115353581 0.0380050559155997 -0.0554808589120272], 1e-10);
asserts.isapprox(a, [1 -2.3279919174673 3.49026347920647 -3.4452868175047 2.63658552913009 -1.2535038373226 0.399132444644065], 1e-10);
%=============================================================================
[b, a] = ellip(3, 1, 40, [0.2 0.5], 'stop');
asserts.isapprox(b, [0.352119953404777 -1.05280456742709 2.07068137439767 -2.41858435477819 2.07068137439768 -1.0528045674271 0.352119953404778], 1e-10);
asserts.isapprox(a, [1 -2.04336572618182 2.49659609206906 -2.10752237031725 1.33951989744313 -0.373305393133307 0.00948666609271335], 1e-10);
%=============================================================================
[b, a] = ellip(4, 1, 40, 0.35);
asserts.isapprox(b, [0.0469777517705996 0.0595032607089106 0.0922824423908298 0.0595032607089105 0.0469777517705995], 1e-10);
asserts.isapprox(a, [1 -1.92338688164821 2.17189802559747 -1.26693938134056 0.360918162831415], 1e-10);
%=============================================================================
[z, p, k] = ellip(3, 1, 40, 0.35);
[bz, az] = zp2tf(z, p, k);
asserts.isapprox(bz, [0.0747730458009297 0.146777158945922 0.146777158945922 0.0747730458009297], 1e-10);
asserts.isapprox(az, [1 -1.26582639733789 1.05008033898135 -0.341153532149765], 1e-10);
%=============================================================================
asserts.checkerror('ellip(3, 1, 40, 0.4, ''stop'')', _('Cutoff frequency must be a scalar for lowpass and highpass filters.'));
asserts.checkerror('ellip(3, 1, 40, [0.2 0.5], ''high'')', _('Cutoff frequency must be a two-element vector for bandpass and bandstop filters.'));
