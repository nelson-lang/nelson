[b, g] = sgolay(2, 5);
asserts.isequal(size(b), [5 5]);
asserts.isequal(size(g), [5 3]);
asserts.isapprox(g(:, 2).', [-0.2 -0.1 0 0.1 0.2], 1e-12);
%=============================================================================
b = sgolay(2, 5, [1 2 3 2 1]);
REF = [0.8 0.466666666666667 -0.2 -0.2 0.133333333333334; ...
  0.233333333333333 0.4 0.4 0.0666666666666668 -0.0999999999999999; ...
  -0.0666666666666667 0.266666666666667 0.6 0.266666666666667 -0.0666666666666667; ...
  -0.0999999999999999 0.0666666666666668 0.4 0.4 0.233333333333333; ...
  0.133333333333334 -0.2 -0.2 0.466666666666667 0.8];
asserts.isapprox(b, REF, 1e-12);
