[s, sf, st, p] = spectrogram(sin((0:127)' * 0.1), 32, 16, 64, 10);
asserts.isequal(size(s), size(p));
asserts.isequal(length(sf), size(s, 1));
asserts.isequal(length(st), size(s, 2));
%=============================================================================
x = sin((0:31)' * 0.2);
[s, sf, st, p] = spectrogram(x, hamming(8), 4, 16, 10);
asserts.isequal(size(s), [9 7]);
asserts.isapprox(sf(1:5).', [0 0.625 1.25 1.875 2.5], 1e-12);
asserts.isapprox(st(1:4).', [0.4 0.8 1.2 1.6], 1e-12);
asserts.isapprox(real(s(1:5, 1)).', [2.37939694950247 -0.0169645726242999 -1.3566477561934 -0.019447452025915 0.198543450792935], 1e-12);
asserts.isapprox(imag(s(1:5, 1)).', [0 -2.07512452740221 0.00715319320564324 0.634707537781338 0.026927537455863], 1e-12);
asserts.isapprox(p(1:5, 1).', [0.203053218682364 0.308903923746544 0.132023836350163 0.0289241705693099 0.00287960649352294], 1e-12);
