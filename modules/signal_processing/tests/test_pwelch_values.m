[pxx, f] = pwelch(sin((0:127)' * 0.1), hamming(32), 16, 64, 10);
asserts.isequal(length(pxx), length(f));
asserts.isapprox(pxx(1:6).', [0.874251053953964 1.50531386394644 0.843637927539927 0.234802528321199 0.0214050391383867 0.000135742828822688], 1e-12);
asserts.isapprox(f(1:6).', [0 0.15625 0.3125 0.46875 0.625 0.78125], 1e-12);
%=============================================================================
x = sin((0:63)' * 0.1);
[pxx, f] = pwelch(x, hamming(16), 8, 32, 10, 'twosided');
asserts.isapprox(pxx(1:8).', [0.573607060754005 0.418890552584985 0.156917705290402 ...
  0.0261254777843866 0.0013196629271022 8.57029319391066e-06 ...
  3.67195852183564e-05 3.44615092076096e-05], 1e-12);
asserts.isapprox(f(1:8).', [0 0.3125 0.625 0.9375 1.25 1.5625 1.875 2.1875], 1e-12);
%=============================================================================
[pxx, f] = pwelch(x, hamming(16), 8, 32, 10, 'centered');
asserts.isapprox(pxx(1:8).', [3.03034759571222e-05 2.39851847947553e-05 ...
  3.1709482074291e-05 2.5220017581001e-05 3.44166994859819e-05 ...
  2.68304285152605e-05 3.7405733984403e-05 2.74692358742333e-05], 1e-12);
asserts.isapprox(f(1:8).', [-4.6875 -4.375 -4.0625 -3.75 -3.4375 -3.125 ...
  -2.8125 -2.5], 1e-12);
%=============================================================================
[pxx, f] = pwelch(x, hamming(16), 8, 32, 10, 'power');
asserts.isapprox(pxx(1:8).', [0.51155582139386 0.747152241885104 ...
  0.279885556204813 0.0465985904348217 0.00235381081867925 ...
  1.52863647411668e-05 6.54947223031964e-05 6.14671152269204e-05], 1e-12);
asserts.isapprox(f(1:8).', [0 0.3125 0.625 0.9375 1.25 1.5625 1.875 2.1875], 1e-12);
