y = cconv([1 2], [1 1], 2);
asserts.isapprox(y, [3 3], 1e-12);
%=============================================================================
y = cconv([1; 2], [1; 1], 2);
asserts.isapprox(y, [3; 3], 1e-12);
%=============================================================================
y = cconv([1 2], [1 1], 3);
asserts.isapprox(y, [1 3 2], 1e-12);
%=============================================================================
y = cconv([1 + i 2], [1 - i 3], 3);
asserts.isapprox(y, [2 5 + i 6], 1e-12);
