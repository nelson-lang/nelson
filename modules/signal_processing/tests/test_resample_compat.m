x = [1 2 3 4; 5 6 7 8];
y1 = resample(x, 2, 3, 'Dimension', 2);
y2 = resample(x, 4, 6, 'Dimension', 2);
asserts.isapprox(y1, y2, 1e-12);
%=============================================================================
y = resample([1 2 3 4], 1, 1, [1]);
asserts.isequal(y, [1 2 3 4]);
%=============================================================================
asserts.checkerror('resample(1:4, 2, 3, ''BadOption'', 1)', _('Unknown option.'));
asserts.checkerror('resample(1:4, 2, 3, ''Dimension'', 3)', _('Dimension must be 1 or 2.'));
