gd = grpdelay([1 1], 1, 16);
asserts.isapprox(gd(1:4), 0.5 * ones(4, 1), 1e-10);
%=============================================================================
[gd, w] = grpdelay([1 0.2], [1 -0.7], 8);
REF = [2.5; 0.956722904407162; 0.147093558613696; -0.135094804752494; ...
  -0.290397521941146; -0.415315830359896; -0.531125506980222; -0.624325452822726];
asserts.isapprox(gd, REF, 1e-12);
asserts.isapprox(w, (0:7)' * pi / 8, 1e-12);
%=============================================================================
[gd, f] = grpdelay([1 1], 1, 4, 'whole', 10);
asserts.isapprox(gd, 0.5 * ones(4, 1), 1e-12);
asserts.isapprox(f, [0; 2.5; 5; 7.5], 1e-12);
%=============================================================================
[gd, f] = grpdelay([1 0.5], [1 -0.25], 4, 10);
REF = [0.666666666666667; 0.469582873289067; 0.141176470588235; -0.359717915632853];
asserts.isapprox(gd, REF, 1e-12);
asserts.isapprox(f, [0; 1.25; 2.5; 3.75], 1e-12);
%=============================================================================
asserts.checkerror('grpdelay([1 1], 1, 4, 10, ''whole'')', _('Frequency range must be specified before sampling frequency.'));
%=============================================================================
[gd, w] = grpdelay([1 -1], 1, [0 pi]);
asserts.isapprox(gd, [0.5; 0.5], 1e-12);
asserts.isapprox(w, [0; pi], 1e-12);
%=============================================================================
asserts.checkerror('grpdelay([1], 0)', _('First denominator filter coefficient must be nonzero.'));
