x = sin((0:63)' * 0.1);
y = cos((0:63)' * 0.1);
[txy, f] = tfestimate(x, x, hamming(16), 8, 32, 10);
asserts.isapprox(real(txy(1:4)).', [1 1 1 1], 1e-12);
asserts.isapprox(imag(txy(1:4)).', [0 0 0 0], 1e-12);
asserts.isapprox(f(1:4).', [0 0.3125 0.625 0.9375], 1e-12);
%=============================================================================
[txy, f] = tfestimate(x, y, hamming(16), 8, 32, 10, 'twosided');
asserts.isapprox(real(txy(1:4)).', [-0.0018777063512666 -0.0017597390812026 ...
  -0.00141061927604183 -0.000864166800590474], 1e-12);
asserts.isapprox(imag(txy(1:4)).', [0 0.329476409111465 0.627611732060297 ...
  0.855988628437483], 1e-12);
asserts.isapprox(f(1:4).', [0 0.3125 0.625 0.9375], 1e-12);
%=============================================================================
asserts.checkerror('tfestimate(1:4, 1:4, hamming(8))', _('Signal length must be at least the window length.'));
