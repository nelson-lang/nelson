zi = filtic([1 1], 1, 3);
asserts.isequal(zi, 0);
%=============================================================================
zi = filtic(1, [1 -0.5], 2);
asserts.isequal(zi, 1);
%=============================================================================
zi = filtic([1 0.25], [1 -0.5], 2, 4);
asserts.isequal(zi, 2);
%=============================================================================
zi = filtic([0.2 0.3 0.4], [1 -0.5 0.25], [3 2], [5 4]);
asserts.isapprox(zi, [4.1; 1.25], 1e-12);
%=============================================================================
zi = filtic([1 2 3], [1 -0.2 0.1], [4 3 2], [7 6 5]);
asserts.isapprox(zi, [32.5; 20.6], 1e-12);
%=============================================================================
asserts.isequal(filtic([1 2], [1 -0.5], []), 0);
asserts.isequal(filtic([1 2], [1 -0.5], [], []), 0);
