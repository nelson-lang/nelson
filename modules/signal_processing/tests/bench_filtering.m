x = sin((0:1999)' * 0.02) + 0.1 * sin((0:1999)' * 0.25);
sos = [1 0.5 0.25 1 -0.3 0.1; 1 0 0 1 -0.2 0];
tic();
for k = 1:5
  y1 = sosfilt(sos, x);
  y2 = filtfilt([1 1 1] / 3, 1, x);
end
toc();
asserts.isequal(size(y1), size(x));
asserts.isequal(size(y2), size(x));
