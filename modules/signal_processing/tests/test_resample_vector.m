y = resample((1:10)', 2, 3);
asserts.isequal(size(y), [7 1]);
%=============================================================================
y = resample(1:6, 2, 3);
asserts.isapprox(y, [0.852480638657809 2.65129237383755 3.79290675135309 5.88164670300956], 1e-12);
%=============================================================================
y = resample((1:6)', 2, 3);
asserts.isapprox(y, [0.852480638657809; 2.65129237383755; 3.79290675135309; 5.88164670300956], 1e-12);
%=============================================================================
y = resample(1:6, 2, 3, 1);
asserts.isapprox(y, [0.99571163238276 2.5107209190431 3.98284652953104 5.52358602189482], 1e-12);
%=============================================================================
y = resample(1:6, 2, 3, 10, 5);
asserts.isapprox(y, [0.852480638657809 2.65129237383755 3.79290675135309 5.88164670300956], 1e-12);
%=============================================================================
y = resample(1:6, 2, 3, [1 1]);
asserts.isequal(y, [1 3 4 6]);
