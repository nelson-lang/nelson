x = sin((0:63)' * 0.1);
y = cos((0:63)' * 0.1);
[cxy, f] = mscohere(x, x, hamming(16), 8, 32, 10);
asserts.isapprox(cxy(1:4).', [1 1 1 1], 1e-12);
asserts.isapprox(f(1:4).', [0 0.3125 0.625 0.9375], 1e-12);
%=============================================================================
[cxy, f] = mscohere(x, y, hamming(16), 8, 32, 10, 'centered');
asserts.isapprox(cxy(1:4).', [0.00330451299188207 0.00905557375956793 ...
  0.031573613373237 0.0444991056085901], 1e-12);
asserts.isapprox(f(1:4).', [-4.6875 -4.375 -4.0625 -3.75], 1e-12);
%=============================================================================
asserts.checkerror('mscohere(1:4, 1:4, hamming(8))', _('Signal length must be at least the window length.'));
