y = hilbert([1 0 0 0]);
asserts.isequal(length(y), 4);
asserts.isapprox(real(y), [1 0 0 0], 1e-12);
asserts.isapprox(imag(y), [0 0.5 0 -0.5], 1e-12);
%=============================================================================
y = hilbert([1; 0; 0; 0]);
asserts.isapprox(real(y), [1; 0; 0; 0], 1e-12);
asserts.isapprox(imag(y), [0; 0.5; 0; -0.5], 1e-12);
%=============================================================================
y = hilbert([1 2; 3 4; 5 6]);
asserts.isapprox(real(y), [1 2; 3 4; 5 6], 1e-12);
asserts.isapprox(imag(y), [1.15470053837925 1.15470053837925; -2.3094010767585 -2.3094010767585; 1.15470053837925 1.15470053837925], 1e-12);
%=============================================================================
y = hilbert([1; 2; 3], 2);
asserts.isapprox(y, [1; 2], 1e-12);
%=============================================================================
y = hilbert([1 2 3], 5);
REF = [1 - 0.795147898066885i 2 - 1.231073414870101i 3 + 1.085764909269029i ...
  0 + 1.701301616704080i 0 - 0.760845213036123i];
asserts.isapprox(y, REF, 1e-12);
asserts.isequal(size(y), [1 5]);
