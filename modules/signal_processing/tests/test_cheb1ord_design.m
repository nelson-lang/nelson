[n, wn] = cheb1ord([0.3 0.6], [0.2 0.7], 1, 40);
asserts.isequal(n, 5);
asserts.isapprox(wn, [0.3 0.6], 1e-12);
%=============================================================================
[n, wn] = cheb1ord([0.2 0.7], [0.3 0.6], 1, 40);
asserts.isequal(n, 5);
asserts.isapprox(wn, [0.2 0.7], 1e-12);
