[c, lags] = xcov([1 2 3]);
asserts.isequal(length(c), length(lags));
%=============================================================================
[c, lags] = xcov([1 2 3], 1, 'biased');
asserts.isapprox(c, [0 0.66666667 0], 1e-6);
asserts.isequal(lags, [-1 0 1]);
%=============================================================================
[c, lags] = xcov([1 2 3], -1);
asserts.isapprox(c, [0 2 0], 1e-12);
asserts.isequal(lags, [-1 0 1]);
asserts.checkerror('xcov([1 2 3], 1.5)', _('Value must be an integer.'));
%=============================================================================
[c, lags] = xcov([1 2 3], [4 5 7]);
asserts.isapprox(c, [-1.66666666666667 0.333333333333333 3 -0.333333333333333 -1.33333333333333], 1e-12);
asserts.isequal(lags, [-2 -1 0 1 2]);
