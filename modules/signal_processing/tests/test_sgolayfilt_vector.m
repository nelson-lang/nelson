y = sgolayfilt((1:7)', 2, 5);
asserts.isapprox(y.', 1:7, 1e-10);
asserts.isapprox(sgolayfilt([1 2 3 2 1], 2, 5), ...
  [0.942857142857 2.22857142857 2.65714285714 2.22857142857 0.942857142857], 1e-10);
asserts.isapprox(sgolayfilt([1 2 3 2 1], 2, 5, [1 2 3 2 1]), ...
  [0.866666666666667 2.26666666666667 2.73333333333333 2.26666666666667 0.866666666666669], 1e-12);
