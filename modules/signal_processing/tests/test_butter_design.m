[b, a] = butter(2, 0.4);
asserts.isequal(length(b), 3);
asserts.isequal(length(a), 3);
asserts.isapprox(b, [0.20657208 0.41314417 0.20657208], 1e-7);
asserts.isapprox(a, [1 -0.36952738 0.19581571], 1e-7);
asserts.isequal(isstable(b, a), true);
%=============================================================================
[b, a] = butter(3, 0.35);
asserts.isapprox(b, [0.0717612038437818 0.215283611531346 0.215283611531346 0.0717612038437818], 1e-12);
asserts.isapprox(a, [1 -0.868220544221195 0.534404667070719 -0.0920944920992692], 1e-12);
%=============================================================================
[b, a] = butter(3, 0.35, 'high');
asserts.isapprox(b, [0.311839962923898 -0.935519888771694 0.935519888771694 -0.311839962923898], 1e-12);
asserts.isapprox(a, [1 -0.868220544221195 0.534404667070719 -0.0920944920992692], 1e-12);
%=============================================================================
[b, a] = butter(3, [0.2 0.5]);
asserts.isapprox(b, [0.0495329963572531 0 -0.148598989071759 0 0.148598989071759 0 -0.0495329963572531], 1e-12);
asserts.isapprox(a, [1 -2.12060287662656 2.72474920276848 -2.2895181180768 1.46624653317035 -0.565179212308266 0.137761301259893], 1e-12);
%=============================================================================
[b2, a2] = butter(3, [0.2 0.5], 'bandpass');
asserts.isapprox(b2, b, 1e-12);
asserts.isapprox(a2, a, 1e-12);
%=============================================================================
[b, a] = butter(3, [0.2 0.5], 'stop');
asserts.isapprox(b, [0.37445269259016 -1.1447590590384 2.2899258260092 -2.68578208893483 2.2899258260092 -1.1447590590384 0.37445269259016], 1e-12);
asserts.isapprox(a, [1 -2.12060287662656 2.72474920276848 -2.2895181180768 1.46624653317035 -0.565179212308266 0.137761301259893], 1e-12);
%=============================================================================
asserts.checkerror('butter(3, 0.4, ''stop'')', _('Cutoff frequency must be a scalar for lowpass and highpass filters.'));
asserts.checkerror('butter(3, [0.2 0.5], ''high'')', _('Cutoff frequency must be a two-element vector for bandpass and bandstop filters.'));
