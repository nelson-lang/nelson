x = [1 + i 2 - i; 3 4 + i];
y = sosfilt([1 0 0 1 0 0], x);
asserts.isequal(y, x);
%=============================================================================
y = sosfilt([1 0 0 1 0 0], x, 2);
asserts.isequal(y, x);
%=============================================================================
asserts.checkerror('sosfilt([1 2 3], [1 2])', _('SOS matrix must have six columns.'));
asserts.checkerror('sosfilt(ones(2, 5), [1 2])', _('SOS matrix must have six columns.'));
