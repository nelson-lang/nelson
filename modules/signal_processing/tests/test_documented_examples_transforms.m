% Documented examples are kept as executable documented cases.
%=============================================================================
c = xcorr([1 2 3]);
asserts.isequal(c, [3 8 14 8 3]);
%=============================================================================
c = xcov([1 2 3]);
asserts.isequal(c, [-1 0 2 0 -1]);
%=============================================================================
y = cconv([1 2], [1 1], 2);
asserts.isequal(y, [3 3]);
%=============================================================================
y = hilbert([1 0 0 0]);
asserts.isapprox(real(y), [1 0 0 0], 1e-12);
asserts.isapprox(imag(y), [0 0.5 0 -0.5], 1e-12);
