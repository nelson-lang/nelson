[h, w] = freqz([1 1], 1, 8);
asserts.isapprox(real(h).', [2 1.92387953251 1.70710678119 1.38268343237 ...
  1 0.617316567635 0.292893218813 0.0761204674887], 1e-10);
asserts.isapprox(imag(h).', [0 -0.382683432365 -0.707106781187 -0.923879532511 ...
  -1 -0.923879532511 -0.707106781187 -0.382683432365], 1e-10);
asserts.isapprox(w.', [0 0.392699081699 0.785398163397 1.1780972451 ...
  1.57079632679 1.96349540849 2.35619449019 2.74889357189], 1e-10);
