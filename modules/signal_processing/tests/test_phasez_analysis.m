p = phasez([1 1], 1, 4);
asserts.isapprox(p, [0; -pi / 8; -pi / 4; -3 * pi / 8], 1e-12);
%=============================================================================
[p, w] = phasez([1 0.5], [1 -0.25], 4);
REF = [0; -0.467020363671956; -0.70862627212767; -0.649580216802863];
asserts.isapprox(p, REF, 1e-12);
asserts.isapprox(w, [0; pi / 4; pi / 2; 3 * pi / 4], 1e-12);
%=============================================================================
[p, f] = phasez([1 1], 1, 4, 10, 'whole');
asserts.isapprox(p([1 2 4]), [0; -pi / 4; pi / 4], 1e-12);
asserts.istrue(isnan(p(3)));
asserts.isapprox(f, [0; 2.5; 5; 7.5], 1e-12);
%=============================================================================
[p, w] = phasez([1 -1], 1, [0 pi]);
asserts.istrue(isnan(p(1)));
asserts.istrue(abs(p(2)) < 1e-12);
asserts.isapprox(w, [0; pi], 1e-12);
