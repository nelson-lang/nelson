%=============================================================================
% rms squares its input, and in integer arithmetic both abs and the square
% saturate: the reduction must run in double whatever the input class.
%=============================================================================
M = uint8([10:30:70; 20:30:80; 30:30:90]);
asserts.isapprox(rms(M), ...
  [21.6024689946929 50.6622805119022 80.4155872120988], 1e-12);
asserts.isapprox(rms(M, 2), ...
  [46.9041575982343; 55.6776436283002; 64.8074069840786], 1e-12);
asserts.isapprox(rms(M, 'all'), 56.2731433871138, 1e-12);
asserts.isapprox(rms(M, [1 2]), 56.2731433871138, 1e-12);
%=============================================================================
asserts.isapprox(rms(M, 'double'), ...
  [21.6024689946929 50.6622805119022 80.4155872120988], 1e-12);
asserts.isapprox(rms(M, 'default'), ...
  [21.6024689946929 50.6622805119022 80.4155872120988], 1e-12);
%=============================================================================
asserts.isequal(class(rms(M)), 'double');
asserts.isequal(class(rms(M, 'double')), 'double');
asserts.isequal(class(rms(M, 'default')), 'double');
%=============================================================================
asserts.isapprox(rms(int16([100 200 300])), 216.024689946929, 1e-12);
asserts.isapprox(rms(int16([100 200 300]), 'all'), 216.024689946929, 1e-12);
asserts.isapprox(rms(int16([100 200 300]), 'omitnan'), 216.024689946929, 1e-12);
asserts.isequal(class(rms(int16([100 200 300]))), 'double');
%=============================================================================
N = int32([100000 200000; 300000 400000]);
asserts.isapprox(rms(N), [223606.797749979 316227.766016838], 1e-12);
asserts.isapprox(rms(N, 2), [158113.883008419; 353553.390593274], 1e-12);
asserts.isapprox(rms(N, 'all'), 273861.278752583, 1e-12);
asserts.isequal(class(rms(N)), 'double');
%=============================================================================
% abs(int8(-128)) saturates to 127 on its own, before the square.
asserts.isapprox(rms(int8(-128)), 128, 1e-12);
asserts.isapprox(rms(int8([100 -128 50])), 98.1223725762886, 1e-12);
%=============================================================================
asserts.isapprox(rms(int64([4000000000 5000000000])), 4527692569.06871, 1e-12);
asserts.isapprox(rms(uint64([4000000000 5000000000])), 4527692569.06871, 1e-12);
%=============================================================================
asserts.isapprox(rms(uint8([0 0 0])), 0, 1e-12);
asserts.isapprox(rms(uint16(300)), 300, 1e-12);
%=============================================================================
