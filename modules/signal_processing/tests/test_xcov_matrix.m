[c, lags] = xcov([1 2; 3 4]);
REF = [-1 -1 -1 -1; 2 2 2 2; -1 -1 -1 -1];
asserts.isequal(c, REF);
asserts.isequal(lags, [-1; 0; 1]);
%=============================================================================
[c, lags] = xcov([1 2; 3 4], 1, 'coeff');
REF = [-0.5 -0.5 -0.5 -0.5; 1 1 1 1; -0.5 -0.5 -0.5 -0.5];
asserts.isapprox(c, REF, 1e-12);
asserts.isequal(lags, [-1; 0; 1]);
