%=============================================================================
% Documented examples are kept as executable documented cases.
%=============================================================================
asserts.isapprox(rms([3 4]), 3.53553390593, 1e-11);
asserts.isequal(peak2peak([1 4 -2]), 6);
%=============================================================================
y = chirp([0 0.5 1], 0, 1, 1);
asserts.isapprox(y, [1 0.707106781187 -1], 1e-10);
%=============================================================================
t = [0 pi / 2 pi 3 * pi / 2 2 * pi];
asserts.isapprox(sawtooth(t), [-1 -0.5 0 0.5 -1], 1e-12);
asserts.isequal(square(t), [1 1 -1 -1 1]);
asserts.isequal(rectpuls([-0.5 0 0.5], 1), [1 1 0]);
asserts.isequal(tripuls([-0.5 0 0.5], 1), [0 1 0]);
%=============================================================================
y = medfilt1([1 100 2], 3);
asserts.isequal(y, [1 2 2]);
%=============================================================================
[b, g] = sgolay(2, 5);
asserts.isapprox(b(3, :), [-0.0857142857143 0.342857142857 0.485714285714 ...
  0.342857142857 -0.0857142857143], 1e-10);
asserts.isapprox(g(:, 1).', [-0.0857142857143 0.342857142857 0.485714285714 ...
  0.342857142857 -0.0857142857143], 1e-10);
asserts.isapprox(g(:, 2).', [-0.2 -0.1 0 0.1 0.2], 1e-12);
asserts.isapprox(g(:, 3).', [0.142857142857 -0.0714285714286 -0.142857142857 ...
  -0.0714285714286 0.142857142857], 1e-10);
%=============================================================================
y = sgolayfilt((1:7)', 2, 5);
asserts.isapprox(y.', [1 2 3 4 5 6 7], 1e-10);
%=============================================================================
y = sgolayfilt([1 2 3 2 1], 2, 5);
asserts.isapprox(y, [0.942857142857 2.22857142857 2.65714285714 ...
  2.22857142857 0.942857142857], 1e-10);
%=============================================================================
[y, idx] = hampel([1 1 10 1 1], 1, 2);
asserts.isequal(y, [1 1 1 1 1]);
asserts.isequal(idx, [false false true false false]);
%=============================================================================
