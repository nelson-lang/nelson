x = sin((0:63)' * 0.1);
y = cos((0:63)' * 0.1);
[pxy, f] = cpsd(x, y, hamming(16), 8, 32, 10);
asserts.isapprox(real(pxy(1:4)).', [-0.0010770656211091633 -0.0014742761522607037 -0.00044270227966978538 -0.000045153541101661653], 1e-12);
asserts.isapprox(imag(pxy(1:4)).', [0 -0.27602911015283599 -0.19696678561647313 -0.044726223791861933], 1e-12);
asserts.isapprox(f(1:4).', [0 0.3125 0.625 0.9375], 1e-12);
%=============================================================================
[pxy, f] = cpsd(x, y, hamming(16), 8, 32, 10, 'twosided');
asserts.isapprox(real(pxy(1:4)).', [-0.00107706562110916 -0.000737138076130352 ...
  -0.000221351139834893 -2.25767705508308e-05], 1e-12);
asserts.isapprox(imag(pxy(1:4)).', [0 -0.138014555076418 -0.0984833928082366 ...
  -0.022363111895931], 1e-12);
asserts.isapprox(f(1:4).', [0 0.3125 0.625 0.9375], 1e-12);
%=============================================================================
[pxy, f] = cpsd(x, y, hamming(16), 8, 32, 10, 'centered');
asserts.isapprox(1e8 * real(pxy(1:4)).', [-5.68188580066252 5.76908178780288 ...
  -5.87110431578289 5.94318205100535], 1e-10);
asserts.isapprox(1e6 * imag(pxy(1:4)).', [-1.53447506790323 2.5877630598635 ...
  -4.97520258836956 6.01936019725012], 1e-10);
asserts.isapprox(f(1:4).', [-4.6875 -4.375 -4.0625 -3.75], 1e-12);
%=============================================================================
asserts.checkerror('cpsd(1:4, 1:4, [], [], 4, 1, ''bad'')', _('Unsupported option.'));
