x = [1 2 3; 4 5 6];
asserts.isequal(peak2peak(x), [3 3 3]);
asserts.isequal(peak2peak(x, 2), [2; 2]);
%=============================================================================
x = [1 NaN 3; 4 5 6];
asserts.isapprox(peak2peak(x), [3 0 3], 1e-12);
asserts.isapprox(peak2peak(x, 'all'), 5, 1e-12);
asserts.isapprox(peak2peak(x, [1 2]), 5, 1e-12);
asserts.isapprox(peak2peak([1 + 2i 3 + 1i -2 + 4i]), -3 + 2i, 1e-12);
%=============================================================================
x = reshape(1:12, [2, 3, 2]);
asserts.isapprox(peak2peak(x, [1 3]), [7 7 7], 1e-12);
