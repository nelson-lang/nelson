moduleName = ['nelson_test_xmldocrenderimages_scripts_', strrep(createGUID(), '-', '_')];
moduleRoot = tempname();
if isdir(moduleRoot)
  rmdir(moduleRoot, 's');
end
mkdir(moduleRoot);
mkdir([moduleRoot, '/etc']);
filewrite([moduleRoot, '/etc/startup.m'], '');
filewrite([moduleRoot, '/etc/finish.m'], '');
mkdir([moduleRoot, '/help']);
mkdir([moduleRoot, '/help/en_US']);
mkdir([moduleRoot, '/help/en_US/xml']);
mkdir([moduleRoot, '/help/en_US/xml/nested']);
%=============================================================================
filewrite([moduleRoot, '/help/en_US/xml/chapter.xml'], ['<?xml version="1.0" encoding="UTF-8" ?>', newline, ...
'<xmldoc>', newline, ...
'  <language>en_US</language>', newline, ...
'  <module_name>', moduleName, '</module_name>', newline, ...
'  <chapter>Temporary module</chapter>', newline, ...
'</xmldoc>', newline]);
%=============================================================================
filewrite([moduleRoot, '/help/en_US/xml/nested/chapter.xml'], ['<?xml version="1.0" encoding="UTF-8" ?>', newline, ...
'<xmldoc>', newline, ...
'  <language>en_US</language>', newline, ...
'  <module_name>', moduleName, '</module_name>', newline, ...
'  <chapter>Nested pages</chapter>', newline, ...
'</xmldoc>', newline]);
%=============================================================================
filewrite([moduleRoot, '/help/en_US/xml/nested/sample.xml'], ['<?xml version="1.0" encoding="UTF-8" ?>', newline, ...
'<xmldoc>', newline, ...
'  <language>en_US</language>', newline, ...
'  <module_name>', moduleName, '</module_name>', newline, ...
'  <title>sample</title>', newline, ...
'  <keyword>sample</keyword>', newline, ...
'  <short_description>sample page.</short_description>', newline, ...
'  <syntax><syntax_item>sample</syntax_item></syntax>', newline, ...
'  <description><p>sample page.</p></description>', newline, ...
'  <examples>', newline, ...
'    <example_item>', newline, ...
'      <example_item_description>Generated nested image.</example_item_description>', newline, ...
'      <example_item_data><![CDATA[', newline, ...
'plot(1:3);', newline, ...
']]></example_item_data>', newline, ...
'      <example_item_img src="../../images/sample.svg" align="middle" generate="true" />', newline, ...
'    </example_item>', newline, ...
'  </examples>', newline, ...
'</xmldoc>', newline]);
%=============================================================================
mkdir([moduleRoot, '/help/en_US/images']);
filewrite([moduleRoot, '/help/en_US/images/sample.svg'], '<svg xmlns="http://www.w3.org/2000/svg"></svg>');
%=============================================================================
scriptRoot = tempname();
mkdir(scriptRoot);
[status, scriptFiles, msg] = __xmldocgenerateimages__([moduleRoot, '/help/en_US/xml/nested/sample.xml'], scriptRoot, false);
asserts.istrue(status, msg);
asserts.isequal(length(scriptFiles), 0);
[status, scriptFiles, msg] = __xmldocgenerateimages__([moduleRoot, '/help/en_US/xml/nested/sample.xml'], scriptRoot, true);
asserts.istrue(status, msg);
asserts.isequal(length(scriptFiles), 1);
scriptText = fileread(scriptFiles{1});
asserts.istrue(contains(scriptText, 'imageFigure = f;'));
asserts.istrue(contains(scriptText, "isgraphics(f) && ~isempty(get(f, 'Children'))"));
asserts.istrue(contains(scriptText, "isgraphics(fig) && ~isempty(get(fig, 'Children'))"));
asserts.istrue(contains(scriptText, 'saveas(imageFigure, imageDestination);'));
asserts.istrue(contains(scriptText, 'close(imageFigure);'));
asserts.isfalse(contains(scriptText, '/../'));
rmdir(scriptRoot, 's');
rmfile([moduleRoot, '/etc/startup.m']);
rmfile([moduleRoot, '/etc/finish.m']);
rmdir(moduleRoot, 's');
