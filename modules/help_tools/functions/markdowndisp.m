function markdowndisp(textToRender)
  narginchk(1, 1);
  nargoutchk(0, 0);

  if isStringScalar(textToRender)
    textToRender = convertStringsToChars(textToRender);
  end
  if ~ischar(textToRender) || ~isrow(textToRender)
    error('Nelson:markdowndisp:invalidInput', 'Input argument must be a string scalar or row character vector.');
  end

  mode = getnelsonmode();
  if ~strcmp(mode, 'GUI') && ~strcmp(mode, 'WEB_GUI') && ~strcmp(mode, 'WASM_TERMINAL')
    disp(textToRender);
    return
  end

  if contains(textToRender, char(8))
    error('Nelson:markdowndisp:backspaceNotSupported', 'Backspace character is not supported.');
  end

  html = markdown(textToRender, 'advanced');
  if strcmp(mode, 'WEB_GUI') || strcmp(mode, 'WASM_TERMINAL')
    % The web command window renders HTML and typesets LaTeX (KaTeX) itself,
    % so the raw markdown HTML is inserted directly; no MathJax pre-render.
    inserthtml(html);
    return
  end

  % Qt desktop: its rich-text terminal cannot run JavaScript, so LaTeX is
  % pre-rendered to SVG images through an offscreen MathJax webview.
  inserthtml(renderMarkdownHtml(html));
end
%=============================================================================
function renderedHtml = renderMarkdownHtml(html)
  if ~containsLatexMarkup(html)
    renderedHtml = html;
    return
  end


  [found, cached] = cachedRenderedHtml(html);
  if found
    renderedHtml = cached;
    return
  end

  template = buildRendererTemplate(html);
  try
    renderedHtml = __webview_render_html__(template);
  catch
    renderedHtml = html;
  end
  cachedRenderedHtml(html, renderedHtml);
end
%=============================================================================
function tf = containsLatexMarkup(html)
  tf = contains(html, '$') || contains(html, '\(') || contains(html, '\[');
end
%=============================================================================
function [found, renderedHtml] = cachedRenderedHtml(html, renderedHtmlToCache)
  persistent cacheKeys cacheValues
  if isempty(cacheKeys)
    cacheKeys = {};
    cacheValues = {};
  end

  found = false;
  renderedHtml = '';
  idx = find(strcmp(cacheKeys, html), 1);
  if nargin == 1
    if ~isempty(idx)
      found = true;
      renderedHtml = cacheValues{idx};
    end
    return
  end

  if ~isempty(idx)
    cacheValues{idx} = renderedHtmlToCache;
    return
  end
  cacheKeys{end + 1} = html;
  cacheValues{end + 1} = renderedHtmlToCache;
  if length(cacheKeys) > 64
    cacheKeys(1) = [];
    cacheValues(1) = [];
  end
end
%=============================================================================
function template = buildRendererTemplate(html)
  mathjax = loadMathJaxScript();
  template = ['<!DOCTYPE html>', newline(), ...
  '<html><head><meta charset="utf-8">', newline(), ...
  '<script>', newline(), ...
  'window.MathJax = {', newline(), ...
  '  tex: {inlineMath: [["$","$"], ["\\\\(","\\\\)"]], displayMath: [["$$","$$"], ["\\\\[","\\\\]"]]},', newline(), ...
  '  svg: {fontCache: "none"}', newline(), ...
  '};', newline(), ...
  'window.nelsonMarkdownReady = false;', newline(), ...
  '</script>', newline(), ...
  '<script>', newline(), ...
  mathjax, newline(), ...
  '</script>', newline(), ...
  '<script>', newline(), ...
  'function mathDimensionToPixels(value, scale) {', newline(), ...
  '  const match = String(value || "").match(/^([0-9.]+)([a-z]*)/i);', newline(), ...
  '  if (!match) { return 0; }', newline(), ...
  '  const number = Number(match[1]);', newline(), ...
  '  if (!Number.isFinite(number) || number <= 0) { return 0; }', newline(), ...
  '  const unit = match[2];', newline(), ...
  '  let pixels = number;', newline(), ...
  '  if (unit === "ex") { pixels = number * 8; }', newline(), ...
  '  else if (unit === "em") { pixels = number * 16; }', newline(), ...
  '  pixels = pixels * (scale || 1);', newline(), ...
  '  pixels = Math.max(1, Math.min(4096, Math.round(pixels)));', newline(), ...
  '  return pixels;', newline(), ...
  '}', newline(), ...
  'function replaceMathJaxSvg(root) {', newline(), ...
  '  root.querySelectorAll(''mjx-container[jax="SVG"]'').forEach(function(container) {', newline(), ...
  '    const svg = container.querySelector("svg");', newline(), ...
  '    if (!svg) { return; }', newline(), ...
  '    if (!svg.getAttribute("xmlns")) { svg.setAttribute("xmlns", "http://www.w3.org/2000/svg"); }', newline(), ...
  '    const displayMode = container.getAttribute("display") === "true";', newline(), ...
  '    const scale = displayMode ? 1.55 : 1.25;', newline(), ...
  '    const serialized = new XMLSerializer().serializeToString(svg);', newline(), ...
  '    const img = document.createElement("img");', newline(), ...
  '    img.setAttribute("src", "data:image/svg+xml;charset=utf-8," + encodeURIComponent(serialized));', newline(), ...
  '    img.setAttribute("alt", container.getAttribute("aria-label") || "");', newline(), ...
  '    const width = mathDimensionToPixels(svg.getAttribute("width"), scale);', newline(), ...
  '    const height = mathDimensionToPixels(svg.getAttribute("height"), scale);', newline(), ...
  '    if (width > 0) { img.setAttribute("width", String(width)); img.style.width = String(width) + "px"; }', newline(), ...
  '    if (height > 0) { img.setAttribute("height", String(height)); img.style.height = String(height) + "px"; }', newline(), ...
  '    img.style.maxWidth = "100%";', newline(), ...
  '    if (displayMode) {', newline(), ...
  '      img.style.display = "block";', newline(), ...
  '      img.style.margin = "0.75em 0";', newline(), ...
  '    } else {', newline(), ...
  '      img.style.verticalAlign = "-0.16em";', newline(), ...
  '    }', newline(), ...
  '    container.replaceWith(img);', newline(), ...
  '  });', newline(), ...
  '}', newline(), ...
  'window.addEventListener("load", function() {', newline(), ...
  '  const root = document.getElementById("nelson-markdowndisp-root");', newline(), ...
  '  const done = function() { replaceMathJaxSvg(root); window.nelsonMarkdownReady = true; };', newline(), ...
  '  if (window.MathJax && window.MathJax.typesetPromise) {', newline(), ...
  '    window.MathJax.typesetPromise([root]).then(done).catch(done);', newline(), ...
  '  } else {', newline(), ...
  '    done();', newline(), ...
  '  }', newline(), ...
  '});', newline(), ...
  '</script>', newline(), ...
  '</head><body><div id="nelson-markdowndisp-root">', newline(), ...
  html, newline(), ...
  '</div></body></html>'];
end
%=============================================================================
function script = loadMathJaxScript()
  persistent cachedScript
  if isempty(cachedScript)
    script = fileread([modulepath('help_tools'), '/resources/tex-svg.js']);
    script = strrep(script, '</script>', '<\/script>');
    cachedScript = script;
  else
    script = cachedScript;
  end
end
