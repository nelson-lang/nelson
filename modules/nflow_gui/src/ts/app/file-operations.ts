//=============================================================================
let runtimeInput: HTMLInputElement | null = null;
export function setRuntimeInput(el: HTMLInputElement | null): void {
  runtimeInput = el;
}
// Runtime lives in the DOM input, not state; fall back to the live element so
// save never loses an edit when the module reference was not wired up.
function readRuntimeValue(): string {
  const el =
    runtimeInput ||
    (typeof document !== 'undefined'
      ? (document.getElementById('runtimeInput') as HTMLInputElement | null)
      : null);
  return el?.value || '10';
}
//=============================================================================
export function sanitizeFilename(name: unknown): string {
  const base = String(name || 'nflow').trim() || 'nflow';
  return base.replace(/[^a-zA-Z0-9_-]+/g, '_');
}
//=============================================================================
export function sanitizeParamsForSave(params: unknown): unknown {
  if (!params || typeof params !== 'object') return params || {};
  const cleaned = { ...(params as Record<string, unknown>) } as Record<string, unknown>;
  // `_visible` is inspector UI state (expanded sections), not diagram data.
  try {
    if (cleaned._visible) delete cleaned._visible;
  } catch (e) {}
  return cleaned;
}
//=============================================================================
export function toJSON(data: unknown): string {
  try {
    return JSON.stringify(data, null, 2);
  } catch (_e) {
    return JSON.stringify(data);
  }
}
//=============================================================================
export function serializeBlock(block: Record<string, unknown>): Record<string, unknown> {
  return {
    id: block.id,
    type: block.type,
    x: Math.round(Number(block.x) || 0),
    y: Math.round(Number(block.y) || 0),
    rotation: block.rotation || 0,
    params: sanitizeParamsForSave(block.params || {}),
  };
}
//=============================================================================
export function serializeConnection(conn: Record<string, unknown>): Record<string, unknown> {
  const base: Record<string, unknown> = {
    from: conn.from,
    to: conn.to,
    fromIndex: conn.fromIndex ?? 0,
    toIndex: conn.toIndex ?? 0,
  };
  if (typeof conn.label === 'string' && conn.label.trim() !== '') base.label = conn.label;
  if (!Array.isArray(conn.points) || conn.points.length < 2) return base;
  const points = (conn.points as Array<Record<string, unknown>>)
    .map((point) => {
      const x = Number(point?.x);
      const y = Number(point?.y);
      return point?.pin ? [x, y, 1] : [x, y];
    })
    .filter(([x, y]) => Number.isFinite(x as number) && Number.isFinite(y as number));
  return points.length < 2 ? base : { ...base, points };
}
//=============================================================================
export interface DiagramSerializationOptions {
  savedAt?: string;
  savedBy?: string;
}
//=============================================================================
export function serializeDiagram(
  s: typeof state,
  options: DiagramSerializationOptions = {}
): Record<string, unknown> {
  const blocks = Array.from(s.blocks.values()).map((block) =>
    serializeBlock(block as Record<string, unknown>)
  );

  const connections = (s.connections as Array<Record<string, unknown>>).map(serializeConnection);

  const createdAt = s.created || options.savedAt || new Date().toISOString();
  const lastSavedBy = options.savedAt ? options.savedBy ?? s.author : s.lastSavedBy;
  const lastSavedAt = options.savedAt ?? s.lastSavedAt;

  const out: Record<string, unknown> = {
    version: s.modelVersion || '1.0.0',
    format: 'nflow-2',
    metadata: {
      author: s.author || '',
      createdBy: s.createdBy || s.author || '',
      created: createdAt,
      lastSavedBy: lastSavedBy || '',
      lastSavedAt: lastSavedAt || '',
      tool: 'Nelson nflow',
    },
    license: s.license || '',
    comments: s.comments || 'Generated by nflow',
    name: s.diagramName || 'nflow',
    blocks,
    connections,
    variables: s.variablesText || '',
    runtime: readRuntimeValue(),
    sampleTime: s.sampleTime || 0.01,
    autoRoute: s.autoRoute,
    locked: Boolean(s.locked),
  };
  // Only a non-default solver is written, so existing diagrams do not change.
  if (s.solver && s.solver !== 'discrete') {
    out.solver = s.solver;
    if (typeof s.relTol === 'number') out.relTol = s.relTol;
    if (typeof s.absTol === 'number') out.absTol = s.absTol;
    if (typeof s.maxStep === 'number' && s.maxStep > 0) out.maxStep = s.maxStep;
  }

  if (typeof s.realTime === 'boolean') {
    out.realTime = s.realTime;
  }

  // Only written when set, so existing diagrams do not change.
  if (typeof s.stopFcn === 'string' && s.stopFcn.trim()) {
    out.stopFcn = s.stopFcn;
  }

  try {
    if (s.canvasBackground && String(s.canvasBackground).trim()) {
      out.canvasBackground = String(s.canvasBackground).trim();
    }
  } catch (e) {}

  // A connection between two physical pins is an undirected node join: lift it
  // into the engine's `physicalWires` format (nflow_acausal_expand /
  // nflow_planar_expand). Physical pins live on the block instance (acausal +
  // physicalPins), set by the renderer. A purely causal diagram is unchanged.
  try {
    const byId = new Map<string, unknown>();
    for (const b of s.blocks.values()) {
      byId.set(String((b as Record<string, unknown>).id), b);
    }
    const lookup: PinInfoLookup = (blockId) =>
      blockPinInfoFromManifest(byId.get(blockId) as BlockManifest | undefined);
    const lifted = rewriteConnectionsToPhysicalWires(out.connections as EditorConnection[], lookup);
    if (lifted.physicalWires.length > 0) {
      out.connections = lifted.connections;
      out.physicalWires = lifted.physicalWires;
    }
  } catch (e) {}

  return out as Record<string, unknown>;
}
//=============================================================================
export function serializeDiagramForSave(
  s: typeof state,
  savedAt = new Date().toISOString()
): Record<string, unknown> {
  return serializeDiagram(s, { savedAt, savedBy: s.currentUser || s.author || '' });
}
//=============================================================================
export function commitSerializedSaveMetadata(
  s: typeof state,
  diagram: Record<string, unknown>
): void {
  const metadata = diagram.metadata as Record<string, unknown> | undefined;
  if (!metadata) return;
  s.modelVersion = typeof diagram.version === 'string' ? diagram.version : '1.0.0';
  s.created = typeof metadata.created === 'string' ? metadata.created : s.created;
  s.lastSavedBy = typeof metadata.lastSavedBy === 'string' ? metadata.lastSavedBy : s.lastSavedBy;
  s.lastSavedAt = typeof metadata.lastSavedAt === 'string' ? metadata.lastSavedAt : s.lastSavedAt;
  emitAppEvent('nf-model-metadata-change');
}
//=============================================================================
export function commitSerializedSaveMetadataFromText(s: typeof state, content: string): void {
  try {
    const diagram = JSON.parse(content) as Record<string, unknown>;
    commitSerializedSaveMetadata(s, diagram);
  } catch (_e) {
    // Low-level save helpers also accept non-diagram content in tests and integrations.
  }
}
