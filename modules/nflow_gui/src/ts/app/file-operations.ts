// Format generations this build reads. A missing `format` field means a file
// predating the identifier and is read as the current generation. Migration of
// older generations dispatches here, keyed on the `format` value.
const KNOWN_DIAGRAM_FORMATS = ['nflow-2', 'nblock-2'];
export function parseDiagram(text: string, _filename?: string): unknown {
  const data = parseJSON(text);
  const format =
    data && typeof data === 'object' ? (data as { format?: unknown }).format : undefined;
  // The pre-2 layout names block parameters differently and cannot be loaded.
  if (format === 'nflow-1' || format === 'nblock-1') {
    throw new Error(
      `Unsupported file format "${String(format)}". This file uses the legacy nflow-1 ` +
        `parameter layout; only nflow-2 files are supported.`
    );
  }
  if (typeof format === 'string' && format !== '' && !KNOWN_DIAGRAM_FORMATS.includes(format)) {
    throw new Error(
      `Unsupported file format "${format}". This file was probably created by a newer ` +
        `version of nflow; this version reads formats up to "nflow-2".`
    );
  }
  return data;
}
