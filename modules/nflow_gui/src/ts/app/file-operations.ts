export function serializeNBlock(
  diagramData: Record<string, unknown>,
  inputs: Array<{ name: string }>,
  outputs: Array<{ name: string }>,
  masked?: boolean,
  extra?: {
    description?: string;
    author?: string;
    exposedParams?: Record<string, unknown>;
    maskParameters?: Record<string, unknown>;
  }
): Record<string, unknown> {
  const createdDate = new Date().toISOString().slice(0, 10);
  const d = diagramData || {};
  const existingMeta = (d.metadata as Record<string, unknown> | undefined) || {};

  const out: Record<string, unknown> = {
    version: '1.0.0',
    format: 'nblock-2',
    name: d.name || 'subsystem',
    description: extra?.description ?? (d.description as string | undefined) ?? '',
    metadata: {
      author:
        extra?.author ??
        (existingMeta.author as string | undefined) ??
        (d.author as string | undefined) ??
        '',
      created: (existingMeta.created as string | undefined) ?? createdDate,
      tool: 'Nelson nflow',
    },
    masked: Boolean(masked),
    inputs: Array.isArray(inputs) ? inputs : [],
    outputs: Array.isArray(outputs) ? outputs : [],
    params: extra?.exposedParams ?? (d.params as Record<string, unknown> | undefined) ?? {},
    blocks: Array.isArray(d.blocks) ? d.blocks : [],
    connections: Array.isArray(d.connections) ? d.connections : [],
  };

  // Mask parameters travel with the block so its parameter set round-trips.
  const maskParameters =
    extra?.maskParameters ?? (d.maskParameters as Record<string, unknown> | undefined);
  if (maskParameters && typeof maskParameters === 'object' && Object.keys(maskParameters).length) {
    out.maskParameters = maskParameters;
  }

  if (d.variables !== undefined && d.variables !== '') out.variables = d.variables;
  if (d.sampleTime !== undefined) out.sampleTime = d.sampleTime;
  if (d.canvasBackground && String(d.canvasBackground).trim()) {
    out.canvasBackground = String(d.canvasBackground).trim();
  }

  return out;
}
