// TS ↔ native router parity spec.
//
// The fixtures corpus lives in modules/nflow_engine/tests/cpp/fixtures; the
// committed goldens there are generated by the NATIVE router (doctest binary
// nflow_router_tests, deterministic mode). This spec routes the same fixtures
// through the TS router pipeline and asserts point-exact equality against the
// same goldens, proving TS == C++ by transitivity.
//
// Parity levels:
//  - gridRoutes: raw computeWireRoutes output (pre-stub), exact match.
//  - routes: pixel points after enforcePortStubs (pre junction-normalization,
//    which the native routeWires does not apply), exact match.
//=============================================================================
/* eslint-disable @typescript-eslint/no-explicit-any */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { GRID_SIZE } from '../utils/geometry.js';
import { computeWireRoutes, computeSearchPadding } from './pathfinder.js';
import { buildRouter2Input, enforcePortStubs } from './post-process.js';
//=============================================================================
const specDir = path.dirname(fileURLToPath(import.meta.url));
const fixturesDir = path.resolve(specDir, '../../../../nflow_engine/tests/cpp/fixtures');
const goldenDir = path.join(fixturesDir, 'golden');
type FixtureConn = { from: string; to: string; fromIndex?: number; toIndex?: number };
type Fixture = {
  blocks: any[];
  connections: FixtureConn[];
  width: number;
  height: number;
};
//=============================================================================
function listFixtureNames(): string[] {
  return fs
    .readdirSync(fixturesDir)
    .filter((f) => f.endsWith('.json'))
    .map((f) => f.replace(/\.json$/, ''))
    .sort();
}
//=============================================================================
function readJson(file: string): any {
  return JSON.parse(fs.readFileSync(file, 'utf-8'));
}
//=============================================================================
function buildState(fixture: Fixture) {
  return {
    blocks: new Map(fixture.blocks.map((b: any) => [b.id, b])),
    connections: fixture.connections.map((c: any) => ({
      ...c,
      // Snapshot points are [x, y, (1)?] triplets; convert to runtime
      // objects with pin flags (mirrors what the GUI state holds).
      points: Array.isArray(c.points)
        ? c.points.map((pt: any) =>
            Number(pt[2]) === 1
              ? { x: Number(pt[0]), y: Number(pt[1]), pin: true }
              : { x: Number(pt[0]), y: Number(pt[1]) }
          )
        : undefined,
    })) as any[],
  };
}
//=============================================================================
/** Mirror of the settings routeWires (RouterEngine.cpp) applies. */
function nativeEquivalentSettings(width: number, height: number) {
  return {
    maxTimeMs: 4000,
    incremental: false,
    fullOptimize: true,
    searchPadding: computeSearchPadding(width, height),
    nearObstaclePenalty1: 2,
    nearObstaclePenalty2: 0,
    nearWirePenalty1: 3,
    nearWirePenalty2: 1,
    deterministic: true,
  };
}
//=============================================================================
function routeFixtureTs(fixture: Fixture) {
  const state = buildState(fixture);
  const { nodes, connections, obstacles, prevSolution } = buildRouter2Input(state as any);
  const settings = nativeEquivalentSettings(fixture.width, fixture.height);
  // prevSolution carries previous routes and pin flags, exactly what the
  // native routeWires receives via the snapshot's points.
  const result = computeWireRoutes({
    nodes,
    connections,
    obstacles,
    prevSolution: prevSolution as any,
    settings,
  });

  // Align with the fixture connections order (same convention as the native
  // routes/gridRoutes arrays).
  const gridRoutes: (number[][] | null)[] = [];
  const routes: ({ x: number; y: number }[] | null)[] = [];
  for (const conn of connections as any[]) {
    const wire = result.wires.get(conn.key);
    if (!wire || !Array.isArray(wire.points) || wire.points.length === 0) {
      gridRoutes.push(null);
      routes.push(null);
      continue;
    }
    gridRoutes.push(wire.points.map((p: any) => (p.pin ? [p.x, p.y, 1] : [p.x, p.y])));
    let pts = wire.points.map((p: any) => {
      const px: any = { x: p.x * GRID_SIZE, y: p.y * GRID_SIZE };
      if (p.pin) px.pin = true;
      return px;
    });
    pts = enforcePortStubs(state as any, conn.__ref, pts);
    routes.push(pts.map((p: any) => (p.pin ? { x: p.x, y: p.y, pin: true } : { x: p.x, y: p.y })));
  }
  return { gridRoutes, routes };
}
//=============================================================================
describe('router parity TS ↔ native (golden corpus)', () => {
  const names = listFixtureNames();

  it('has a non-empty fixtures corpus with goldens', () => {
    expect(names.length).toBeGreaterThan(0);
    for (const name of names) {
      expect(fs.existsSync(path.join(goldenDir, `${name}.routes.json`))).toBe(true);
    }
  });

  for (const name of names) {
    it(`matches native goldens for ${name}`, () => {
      const fixture = readJson(path.join(fixturesDir, `${name}.json`)) as Fixture;
      const golden = readJson(path.join(goldenDir, `${name}.routes.json`));
      const ts = routeFixtureTs(fixture);
      expect(ts.gridRoutes).toEqual(golden.gridRoutes);
      expect(ts.routes).toEqual(golden.routes);
    });

    it(`is byte-stable and order-independent for ${name}`, () => {
      const fixture = readJson(path.join(fixturesDir, `${name}.json`)) as Fixture;
      const first = JSON.stringify(routeFixtureTs(fixture));
      expect(JSON.stringify(routeFixtureTs(fixture))).toBe(first);

      if (fixture.connections.length >= 2) {
        const reversed: Fixture = {
          ...fixture,
          connections: [...fixture.connections].reverse(),
        };
        const rev = routeFixtureTs(reversed);
        const ref = JSON.parse(first);
        const n = fixture.connections.length;
        for (let i = 0; i < n; i++) {
          expect(rev.gridRoutes[n - 1 - i]).toEqual(ref.gridRoutes[i]);
          expect(rev.routes[n - 1 - i]).toEqual(ref.routes[i]);
        }
      }
    });
  }
});
