% Joint-free planarMechanicalIsland: a pure ODE (six differential states per
% body, no Lagrange multipliers) that now lowers through the unified RK4 seam.
% One body under gravity with a spring-damper to a world point, a signal-
% driven ForceX at an offset (torque coupling), a constant torque, and five
% sensors. Jointed islands stay rejected with the joint kind named.
%=============================================================================
[hasC, hasRust] = __nflow_codegen_support__('planarMechanicalIsland');
assert_istrue(hasC);
assert_istrue(hasRust);
%=============================================================================
comps = {...
  struct('kind', 'body', 'body', 0, 'm', 2, 'I', 0.5, 'x0', 0.1, 'y0', 0.2, ...
    'phi0', 0.1, 'vx0', 0.3, 'vy0', 0, 'w0', 0.2), ...
  struct('kind', 'springDamper', 'body', 0, 'ax', 0.1, 'ay', 0, ...
    'px', 0, 'py', 1, 'c', 5, 'd', 0.2), ...
  struct('kind', 'forceX', 'body', 0, 'ax', 0, 'ay', 0.05, 'port', 0), ...
  struct('kind', 'torque', 'body', 0, 'F', 0.3), ...
  struct('kind', 'positionSensorX', 'body', 0, 'outPort', 0), ...
  struct('kind', 'speedSensorY', 'body', 0, 'outPort', 1), ...
  struct('kind', 'framePositionY', 'body', 0, 'ax', 0.2, 'ay', 0, 'outPort', 2), ...
  struct('kind', 'distanceSensor', 'body', 0, 'px', 1, 'py', 0, 'outPort', 3), ...
  struct('kind', 'positionSensorPhi', 'body', 0, 'outPort', 4)};
pparams = struct('domain', 'planar', 'bodies', 1, 'gravity', 9.81, ...
  'components', {comps});
d = struct();
d.blocks = {...
  struct('id', 'clk', 'type', 'clock', 'inputs', 0, 'outputs', 1, 'params', struct()), ...
  struct('id', 'pi', 'type', 'planarMechanicalIsland', 'inputs', 1, 'outputs', 5, ...
    'params', pparams), ...
  struct('id', 'sx', 'type', 'labelSink', 'inputs', 1, 'outputs', 1, ...
    'params', struct('GotoTag', 'sx', 'isExternalPort', true)), ...
  struct('id', 'svy', 'type', 'labelSink', 'inputs', 1, 'outputs', 1, ...
    'params', struct('GotoTag', 'svy', 'isExternalPort', true)), ...
  struct('id', 'sfy', 'type', 'labelSink', 'inputs', 1, 'outputs', 1, ...
    'params', struct('GotoTag', 'sfy', 'isExternalPort', true)), ...
  struct('id', 'sd', 'type', 'labelSink', 'inputs', 1, 'outputs', 1, ...
    'params', struct('GotoTag', 'sd', 'isExternalPort', true)), ...
  struct('id', 'sphi', 'type', 'labelSink', 'inputs', 1, 'outputs', 1, ...
    'params', struct('GotoTag', 'sphi', 'isExternalPort', true)), ...
  struct('id', 'wx', 'type', 'toWorkspace', 'inputs', 1, 'outputs', 0, ...
    'params', struct('VariableName', 'nfpl_x', 'SaveFormat', 'Array', ...
      'Decimation', 1, 'MaxDataPoints', 'inf')), ...
  struct('id', 'wvy', 'type', 'toWorkspace', 'inputs', 1, 'outputs', 0, ...
    'params', struct('VariableName', 'nfpl_vy', 'SaveFormat', 'Array', ...
      'Decimation', 1, 'MaxDataPoints', 'inf')), ...
  struct('id', 'wfy', 'type', 'toWorkspace', 'inputs', 1, 'outputs', 0, ...
    'params', struct('VariableName', 'nfpl_fy', 'SaveFormat', 'Array', ...
      'Decimation', 1, 'MaxDataPoints', 'inf')), ...
  struct('id', 'wd', 'type', 'toWorkspace', 'inputs', 1, 'outputs', 0, ...
    'params', struct('VariableName', 'nfpl_d', 'SaveFormat', 'Array', ...
      'Decimation', 1, 'MaxDataPoints', 'inf')), ...
  struct('id', 'wphi', 'type', 'toWorkspace', 'inputs', 1, 'outputs', 0, ...
    'params', struct('VariableName', 'nfpl_phi', 'SaveFormat', 'Array', ...
      'Decimation', 1, 'MaxDataPoints', 'inf'))};
d.connections = {...
  struct('from', 'clk', 'to', 'pi', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'pi', 'to', 'sx', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'pi', 'to', 'wx', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'pi', 'to', 'svy', 'fromIndex', 1, 'toIndex', 0), ...
  struct('from', 'pi', 'to', 'wvy', 'fromIndex', 1, 'toIndex', 0), ...
  struct('from', 'pi', 'to', 'sfy', 'fromIndex', 2, 'toIndex', 0), ...
  struct('from', 'pi', 'to', 'wfy', 'fromIndex', 2, 'toIndex', 0), ...
  struct('from', 'pi', 'to', 'sd', 'fromIndex', 3, 'toIndex', 0), ...
  struct('from', 'pi', 'to', 'wd', 'fromIndex', 3, 'toIndex', 0), ...
  struct('from', 'pi', 'to', 'sphi', 'fromIndex', 4, 'toIndex', 0), ...
  struct('from', 'pi', 'to', 'wphi', 'fromIndex', 4, 'toIndex', 0)};
d.sampleTime = 0.05;
d.duration = 0.5;
d.solver = 'ode4';
d.variables = struct();
%=============================================================================
r = jsondecode(__nflow_simulate__(jsonencode(d)));
assert_isequal(r.status, 'done');
vx = evalin('base', 'nfpl_x');
vphi = evalin('base', 'nfpl_phi');
assert_isequal(vx(1), 0.1); % initial COM x
assert_isequal(vphi(1), 0.1); % initial phi
assert_istrue(all(isfinite(vx)) && all(isfinite(vphi)));
assert_istrue(abs(vx(end) - 0.1) > 1e-3); % the body moves
evalin('base', 'clear(''nfpl_x'', ''nfpl_vy'', ''nfpl_fy'', ''nfpl_d'', ''nfpl_phi'')');
%=============================================================================
f = [tempname(), '.nflow'];
[~, fstem] = fileparts(f);
fid = fopen(f, 'wt');
fwrite(fid, jsonencode(d));
fclose(fid);
nflow_codegenerate(f, tempdir(), false, 'C');
src = fileread([tempdir(), fstem, '/model.c']);
assert_istrue(isempty(strfind(src, 'unknown:')));
assert_istrue(~isempty(strfind(src, '__nflow_rhs'))); % RK4 seam, no downgrade
assert_istrue(~isempty(strfind(src, 'pl_x_pi_0')));
assert_istrue(~isempty(strfind(src, 'pl_x_pi_5')));
assert_istrue(~isempty(strfind(src, 'out_pi_p4 = ')));
nflow_codegenerate(f, tempdir(), false, 'rust');
srcR = fileread([tempdir(), fstem, '/src/lib.rs']);
assert_istrue(isempty(strfind(srcR, 'unknown:')));
assert_istrue(~isempty(strfind(srcR, 'pl_x_pi_0')));
rmfile(f);
%=============================================================================
% A jointed island stays rejected, naming the joint kind.
dj = d;
cj = comps;
cj{end + 1} = struct('kind', 'revolute', 'body', 0, 'ax', 0, 'ay', 0, ...
  'px', 0.1, 'py', 0.2);
dj.blocks{2}.params = struct('domain', 'planar', 'bodies', 1, 'gravity', 9.81, ...
  'components', {cj});
fj = [tempname(), '.nflow'];
fid = fopen(fj, 'wt');
fwrite(fid, jsonencode(dj));
fclose(fid);
ok = false;
try
  nflow_codegenerate(fj, tempdir(), false, 'C');
catch e
  ok = ~isempty(strfind(e.message, 'revolute'));
end
assert_istrue(ok);
rmfile(fj);
%=============================================================================
% Compiled numeric equivalence vs the simulator (both targets, ode4).
if __nflow_codegen_toolchain__('C')
  nflow_codegen_check_numeric(d, 'nfpl_num', 'C', ...
    {'sx', 'svy', 'sfy', 'sd', 'sphi'}, ...
    {'nfpl_x', 'nfpl_vy', 'nfpl_fy', 'nfpl_d', 'nfpl_phi'}, 5e-6, 1e-9);
  if __nflow_codegen_toolchain__('rust')
    nflow_codegen_check_numeric(d, 'nfpl_num', 'rust', ...
      {'sx', 'svy', 'sfy', 'sd', 'sphi'}, ...
      {'nfpl_x', 'nfpl_vy', 'nfpl_fy', 'nfpl_d', 'nfpl_phi'}, 5e-6, 1e-9);
  end
end
