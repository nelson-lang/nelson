% N-D concatenate now generates code: expansion is sim-equivalent and the
% generated C carries the per-element scalars.
d3 = struct();
d3.blocks = {struct('id', 'a', 'type', 'constant', 'inputs', 0, 'outputs', 1, 'params', struct('Value', 1:6)), ...
  struct('id', 'b', 'type', 'constant', 'inputs', 0, 'outputs', 1, 'params', struct('Value', 7:12)), ...
  struct('id', 'ra', 'type', 'reshape', 'inputs', 1, 'outputs', 1, 'params', struct('OutputDimensions', [2 3])), ...
  struct('id', 'rb', 'type', 'reshape', 'inputs', 1, 'outputs', 1, 'params', struct('OutputDimensions', [2 3])), ...
  struct('id', 'cat', 'type', 'concatenate', 'inputs', 2, 'outputs', 1, 'params', struct('ConcatenateDimension', 3)), ...
  struct('id', 'g', 'type', 'gain', 'inputs', 1, 'outputs', 1, 'params', struct('Gain', 2)), ...
  struct('id', 's', 'type', 'scope', 'inputs', 1, 'outputs', 0, 'params', struct())};
d3.connections = {struct('from', 'a', 'to', 'ra', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'b', 'to', 'rb', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'ra', 'to', 'cat', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'rb', 'to', 'cat', 'fromIndex', 0, 'toIndex', 1), ...
  struct('from', 'cat', 'to', 'g', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'g', 'to', 's', 'fromIndex', 0, 'toIndex', 0)};
d3.sampleTime = 0.01; d3.duration = 0.05; d3.variables = struct();
rv = jsondecode(__nflow_simulate__(jsonencode(d3)));
assert_isequal(rv.status, 'done');
ex = __nflow_expand_vector__(jsonencode(d3));
assert_isfalse(isfield(jsondecode(ex), 'error'));
re = jsondecode(__nflow_simulate__(ex));
assert_isequal(re.status, 'done');
% element k of the expanded gain equals element k of the vector gain
gv = rv.signals.g;
for k = 0:11
  assert_isequal(re.signals.(sprintf('g__e%d', k)), gv(k + 1));
end
%=============================================================================
% Switch codegen honors Threshold/Condition in BOTH targets (the Rust
% emitter used to hardcode `cond != 0.0`, ignoring both parameters and
% failing to compile against a typed control), and an exact-64 control
% signal is compared in double space with an explicit Rust cast.
dsw = struct();
dsw.blocks = {...
  struct('id', 'top', 'type', 'constant', 'inputs', 0, 'outputs', 1, 'params', struct('Value', 1)), ...
  struct('id', 'c', 'type', 'constant', 'inputs', 0, 'outputs', 1, ...
    'params', struct('Value', 5, 'OutDataType', 'int64')), ...
  struct('id', 'bot', 'type', 'constant', 'inputs', 0, 'outputs', 1, 'params', struct('Value', 2)), ...
  struct('id', 'sw', 'type', 'switch', 'inputs', 3, 'outputs', 1, ...
    'params', struct('Threshold', 0.5)), ...
  struct('id', 'y', 'type', 'labelSink', 'inputs', 1, 'outputs', 1, ...
    'params', struct('GotoTag', 'y', 'isExternalPort', true))};
dsw.connections = {...
  struct('from', 'top', 'to', 'sw', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'c', 'to', 'sw', 'fromIndex', 0, 'toIndex', 1), ...
  struct('from', 'bot', 'to', 'sw', 'fromIndex', 0, 'toIndex', 2), ...
  struct('from', 'sw', 'to', 'y', 'fromIndex', 0, 'toIndex', 0)};
dsw.sampleTime = 0.1;
dsw.duration = 0.3;
dsw.variables = struct();
f = [tempname(), '.nflow'];
[~, fstem] = fileparts(f);
fid = fopen(f, 'wt');
fwrite(fid, jsonencode(dsw));
fclose(fid);
nflow_codegenerate(f, tempdir(), false, 'C');
srcC = fileread([tempdir(), fstem, '/model.c']);
assert_istrue(~isempty(strfind(srcC, ' >= 0.5) ?')));
nflow_codegenerate(f, tempdir(), false, 'rust');
srcR = fileread([tempdir(), fstem, '/src/lib.rs']);
assert_istrue(~isempty(strfind(srcR, ' as f64) >= 0.5 {')));
assert_istrue(isempty(strfind(srcR, '!= 0.0_f64 {')));
rmfile(f);
