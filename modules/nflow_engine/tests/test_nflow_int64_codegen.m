% <--WEIGHT 64-->
% Exact int64/uint64 code generation (C and Rust): typed variables, exact
% literals, saturating helper calls, typed ModelOutput.
%=============================================================================
outdir = [tempdir, filesep, 'nflow_i64_codegen_test'];
if isdir(outdir)
  rmdir(outdir, 's');
end
mkdir(outdir);
% Raw JSON so the INT64-range literal survives (jsonencode would round it).
dj = ['{"blocks":[', ...
  '{"id":"c","type":"constant","inputs":0,"outputs":1,"params":{"Value":9007199254740995,"OutDataType":"int64"}},', ...
  '{"id":"g","type":"gain","inputs":1,"outputs":1,"params":{"Gain":3}},', ...
  '{"id":"y","type":"labelSink","inputs":1,"outputs":1,"params":{"GotoTag":"y"}}],', ...
  '"connections":[', ...
  '{"from":"c","to":"g","fromIndex":0,"toIndex":0},', ...
  '{"from":"g","to":"y","fromIndex":0,"toIndex":0}],', ...
  '"sampleTime":0.01,"duration":0.05,"variables":{}}'];
model = [outdir, filesep, 'i64.nflow'];
fid = fopen(model, 'wt');
fwrite(fid, dj);
fclose(fid);
nflow_codegenerate(model, outdir, false, 'C');
gen = fileread([outdir, filesep, 'i64', filesep, 'model.c']);
% Typed local variables + exact literal + saturating helper + typed output.
assert_istrue(~isempty(strfind(gen, 'int64_t out_c')));
assert_istrue(~isempty(strfind(gen, 'int64_t out_g')));
assert_istrue(~isempty(strfind(gen, '9007199254740995LL')));
assert_istrue(~isempty(strfind(gen, 'nflow_i64_sat_mul')));
assert_istrue(~isempty(strfind(gen, 'int64_t y;')));
%=============================================================================
% Rust mirror: i64 locals, saturating_mul, exact literal, typed output field.
nflow_codegenerate(model, outdir, false, 'rust');
genr = fileread([outdir, filesep, 'i64', filesep, 'src', filesep, 'lib.rs']);
assert_istrue(~isempty(strfind(genr, ': i64 = 0_i64')));
assert_istrue(~isempty(strfind(genr, '9007199254740995_i64')));
assert_istrue(~isempty(strfind(genr, 'saturating_mul')));
assert_istrue(~isempty(strfind(genr, 'pub y: i64,')));
