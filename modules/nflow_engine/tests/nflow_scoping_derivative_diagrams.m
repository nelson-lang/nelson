function [dd, dd2] = nflow_scoping_derivative_diagrams()
  dd = struct();
  dd.blocks = {...
    struct('id', 's', 'type', 'sine', 'inputs', 0, 'outputs', 1, ...
      'params', struct('Amplitude', 2, 'Frequency', 1)), ...
    struct('id', 'der', 'type', 'derivative', 'inputs', 1, 'outputs', 1, 'params', struct()), ...
    struct('id', 'yd', 'type', 'labelSink', 'inputs', 1, 'outputs', 1, ...
      'params', struct('GotoTag', 'yd', 'isExternalPort', true)), ...
    struct('id', 'wd', 'type', 'toWorkspace', 'inputs', 1, 'outputs', 0, ...
      'params', struct('VariableName', 'nfsd_y', 'SaveFormat', 'Array', ...
        'Decimation', 1, 'MaxDataPoints', 'inf'))};
  dd.connections = {...
    struct('from', 's', 'to', 'der', 'fromIndex', 0, 'toIndex', 0), ...
    struct('from', 'der', 'to', 'yd', 'fromIndex', 0, 'toIndex', 0), ...
    struct('from', 'der', 'to', 'wd', 'fromIndex', 0, 'toIndex', 0)};
  dd.sampleTime = 0.1;
  dd.duration = 1.0;
  dd.variables = struct();

  innerD = struct();
  innerD.blocks = {...
    struct('id', 'in1', 'type', 'labelSource', 'inputs', 0, 'outputs', 1, ...
      'params', struct('label', 'in1')), ...
    struct('id', 'der', 'type', 'derivative', 'inputs', 1, 'outputs', 1, 'params', struct()), ...
    struct('id', 'out1', 'type', 'labelSink', 'inputs', 1, 'outputs', 1, ...
      'params', struct('label', 'out1'))};
  innerD.connections = {...
    struct('from', 'in1', 'to', 'der', 'fromIndex', 0, 'toIndex', 0), ...
    struct('from', 'der', 'to', 'out1', 'fromIndex', 0, 'toIndex', 0)};
  innerD.externalInputs = {struct('id', 'in1', 'name', 'in1')};
  innerD.externalOutputs = {struct('id', 'out1', 'name', 'out1')};
  dd2 = dd;
  dd2.blocks{2} = struct('id', 'sub', 'type', 'subsystem', 'inputs', 1, 'outputs', 1, ...
    'params', struct('subsystem', innerD));
  dd2.connections = {...
    struct('from', 's', 'to', 'sub', 'fromIndex', 0, 'toIndex', 0), ...
    struct('from', 'sub', 'to', 'yd', 'fromIndex', 0, 'toIndex', 0), ...
    struct('from', 'sub', 'to', 'wd', 'fromIndex', 0, 'toIndex', 0)};
  dd2.blocks{4}.params.VariableName = 'nfsd2_y';
end
