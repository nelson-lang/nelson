% Product with multiplication and division on vector, integer and complex signals.
d = struct();
d.blocks = {struct('id','a','type','constant','inputs',0,'outputs',1,'params',struct('Value',[12 18])), ...
  struct('id','b','type','constant','inputs',0,'outputs',1,'params',struct('Value',2)), ...
  struct('id','c','type','constant','inputs',0,'outputs',1,'params',struct('Value',3)), ...
  struct('id','p','type','mult','inputs',3,'outputs',1,'params',struct('Inputs','*/*')), ...
  struct('id','s','type','scope','inputs',1,'outputs',0,'params',struct())};
d.connections = {struct('from','a','to','p','toIndex',0), struct('from','b','to','p','toIndex',1), ...
  struct('from','c','to','p','toIndex',2), struct('from','p','to','s')};
d.sampleTime = 0.01; d.duration = 0.1; d.variables = struct();
r = jsondecode(__nflow_simulate__(jsonencode(d)));
assert_isequal(r.status, 'done');
v = r.signals.p; if iscell(v), v = cell2mat(v); end
assert_isapprox(v(:)', [18 27], 1e-10);
% A matrix retains its shape during element-wise division.
md = struct();
md.blocks = {struct('id','a','type','constant','inputs',0,'outputs',1,'params',struct('Value',[4 8 12 16])), ...
  struct('id','shape','type','reshape','inputs',1,'outputs',1,'params',struct('OutputDimensions',[2 2])), ...
  struct('id','den','type','constant','inputs',0,'outputs',1,'params',struct('Value',2)), ...
  struct('id','p','type','mult','inputs',2,'outputs',1,'params',struct('Inputs','*/')), ...
  struct('id','s','type','scope','inputs',1,'outputs',0,'params',struct())};
md.connections = {struct('from','a','to','shape'), struct('from','shape','to','p','toIndex',0), ...
  struct('from','den','to','p','toIndex',1), struct('from','p','to','s')};
md.sampleTime = 0.01; md.duration = 0.1; md.variables = struct();
rm = jsondecode(__nflow_simulate__(jsonencode(md)));
assert_isequal(rm.status, 'done');
assert_isequal(rm.signalDims.p(:)', [2 2]);
mv = rm.signals.p; if iscell(mv), mv = cell2mat(mv); end
assert_isapprox(mv(:)', [2 4 6 8], 1e-10);
% Signed integer division uses the configured floor rounding.
d.blocks{1}.params.Value = [-13 19];
d.blocks{1}.params.OutDataType = 'int64';
d.blocks{2}.params.OutDataType = 'int64';
d.blocks{3}.params.OutDataType = 'int64';
r = jsondecode(__nflow_simulate__(jsonencode(d)));
assert_isequal(r.status, 'done');
v = r.signals.p; if iscell(v), v = cell2mat(v); end
assert_isequal(v(:)', [-21 27]);
% Complex: (8 + 4i) / (2 + 2i) * 3 = 9 - 3i.
d.blocks = {struct('id','ar','type','constant','inputs',0,'outputs',1,'params',struct('Value',8)), ...
  struct('id','ai','type','constant','inputs',0,'outputs',1,'params',struct('Value',4)), ...
  struct('id','br','type','constant','inputs',0,'outputs',1,'params',struct('Value',2)), ...
  struct('id','bi','type','constant','inputs',0,'outputs',1,'params',struct('Value',2)), ...
  struct('id','c','type','constant','inputs',0,'outputs',1,'params',struct('Value',3)), ...
  struct('id','a','type','realImagToComplex','inputs',2,'outputs',1,'params',struct()), ...
  struct('id','b','type','realImagToComplex','inputs',2,'outputs',1,'params',struct()), ...
  struct('id','p','type','mult','inputs',3,'outputs',1,'params',struct('Inputs','*/*')), ...
  struct('id','s','type','scope','inputs',1,'outputs',0,'params',struct())};
d.connections = {struct('from','ar','to','a','toIndex',0), struct('from','ai','to','a','toIndex',1), ...
  struct('from','br','to','b','toIndex',0), struct('from','bi','to','b','toIndex',1), ...
  struct('from','a','to','p','toIndex',0), struct('from','b','to','p','toIndex',1), ...
  struct('from','c','to','p','toIndex',2), struct('from','p','to','s')};
r = jsondecode(__nflow_simulate__(jsonencode(d)));
assert_isequal(r.status, 'done');
assert_isapprox(r.signals.p, 9, 1e-10);
assert_isapprox(r.signalsImag.p, -3, 1e-10);
