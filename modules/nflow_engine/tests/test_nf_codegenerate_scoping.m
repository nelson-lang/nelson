% Goto/From scoping parity. The runtime resolves labels PER LEVEL: an inner
% Goto/From pair is private to its subsystem. The flattener now prefixes
% inner explicit tags with the subsystem path, so two instances of the same
% library subsystem no longer share the LAST instance's signal in generated
% code (the label map used to be last-wins across the flattened diagram).
%=============================================================================
inner = struct();
inner.blocks = {...
  struct('id', 'xin', 'type', 'labelSource', 'inputs', 0, 'outputs', 1, ...
    'params', struct('label', 'xin')), ...
  struct('id', 'g', 'type', 'gain', 'inputs', 1, 'outputs', 1, ...
    'params', struct('Gain', 2)), ...
  struct('id', 'snk', 'type', 'labelSink', 'inputs', 1, 'outputs', 1, ...
    'params', struct('GotoTag', 'state')), ...
  struct('id', 'src', 'type', 'labelSource', 'inputs', 0, 'outputs', 1, ...
    'params', struct('GotoTag', 'state')), ...
  struct('id', 'out1', 'type', 'labelSink', 'inputs', 1, 'outputs', 1, ...
    'params', struct('label', 'out1'))};
inner.connections = {...
  struct('from', 'xin', 'to', 'g', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'g', 'to', 'snk', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'src', 'to', 'out1', 'fromIndex', 0, 'toIndex', 0)};
inner.externalInputs = {struct('id', 'xin', 'name', 'xin')};
inner.externalOutputs = {struct('id', 'out1', 'name', 'out1')};
d = struct();
d.blocks = {...
  struct('id', 'c1', 'type', 'constant', 'inputs', 0, 'outputs', 1, 'params', struct('Value', 1)), ...
  struct('id', 'c2', 'type', 'constant', 'inputs', 0, 'outputs', 1, 'params', struct('Value', 10)), ...
  struct('id', 'subA', 'type', 'subsystem', 'inputs', 1, 'outputs', 1, ...
    'params', struct('subsystem', inner)), ...
  struct('id', 'subB', 'type', 'subsystem', 'inputs', 1, 'outputs', 1, ...
    'params', struct('subsystem', inner)), ...
  struct('id', 'ya', 'type', 'labelSink', 'inputs', 1, 'outputs', 1, ...
    'params', struct('GotoTag', 'ya', 'isExternalPort', true)), ...
  struct('id', 'yb', 'type', 'labelSink', 'inputs', 1, 'outputs', 1, ...
    'params', struct('GotoTag', 'yb', 'isExternalPort', true)), ...
  struct('id', 'wa', 'type', 'toWorkspace', 'inputs', 1, 'outputs', 0, ...
    'params', struct('VariableName', 'nfsc_a', 'SaveFormat', 'Array', ...
      'Decimation', 1, 'MaxDataPoints', 'inf')), ...
  struct('id', 'wb', 'type', 'toWorkspace', 'inputs', 1, 'outputs', 0, ...
    'params', struct('VariableName', 'nfsc_b', 'SaveFormat', 'Array', ...
      'Decimation', 1, 'MaxDataPoints', 'inf'))};
d.connections = {...
  struct('from', 'c1', 'to', 'subA', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'c2', 'to', 'subB', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'subA', 'to', 'ya', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'subA', 'to', 'wa', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'subB', 'to', 'yb', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'subB', 'to', 'wb', 'fromIndex', 0, 'toIndex', 0)};
d.sampleTime = 0.1;
d.duration = 1.0;
d.variables = struct();
%=============================================================================
r = jsondecode(__nflow_simulate__(jsonencode(d)));
assert_isequal(r.status, 'done');
va = evalin('base', 'nfsc_a');
vb = evalin('base', 'nfsc_b');
assert_isequal(va(end), 2); % instance A reads ITS OWN inner Goto
assert_isequal(vb(end), 20); % instance B likewise
evalin('base', 'clear(''nfsc_a'', ''nfsc_b'')');
%=============================================================================
f = [tempname(), '.nflow'];
[~, fstem] = fileparts(f);
fid = fopen(f, 'wt');
fwrite(fid, jsonencode(d));
fclose(fid);
nflow_codegenerate(f, tempdir(), false, 'C');
src = fileread([tempdir(), fstem, '/model.c']);
assert_istrue(isempty(strfind(src, 'unknown:')));
rmfile(f);
%=============================================================================
% Compiled numeric equivalence (before the fix both columns read instance
% B's signal, so ya was 20 instead of 2).
if __nflow_codegen_toolchain__('C')
  nflow_codegen_check_numeric(d, 'nfsc_num', 'C', ...
    {'ya', 'yb'}, {'nfsc_a', 'nfsc_b'}, 0, 0);
  if __nflow_codegen_toolchain__('rust')
    nflow_codegen_check_numeric(d, 'nfsc_num', 'rust', ...
      {'ya', 'yb'}, {'nfsc_a', 'nfsc_b'}, 0, 0);
  end
end
