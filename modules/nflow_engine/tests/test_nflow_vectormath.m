% Causal parity fill (N8): vector math blocks (Coselica Blocks.Math.Vectors).
%   sumElements  : one vector -> scalar sum
%   dotProduct   : two vectors -> scalar
%   crossProduct : two 3-vectors -> 3-vector
% A dummy integrator gives the model a continuous state (the fixed-step solver
% requires one); the vector-math path is feedthrough and logged at t0.
%=============================================================================
function p = vm_write(json, stem)
  p = [tempname(), '.nflow'];
  fid = fopen(p, 'w'); fwrite(fid, json); fclose(fid);
end
%=============================================================================
% sumElements: [1 2 3] -> 6.
m = ['{"blocks":[', ...
  '{"id":"c","type":"constant","inputs":0,"outputs":1,"params":{"Value":[1,2,3]}},', ...
  '{"id":"s","type":"sumElements","inputs":1,"outputs":1,"params":{}},', ...
  '{"id":"ig","type":"integrator","inputs":1,"outputs":1,"params":{"InitialCondition":0}},', ...
  '{"id":"cc","type":"constant","inputs":0,"outputs":1,"params":{"Value":1}},', ...
  '{"id":"td","type":"toWorkspace","inputs":1,"outputs":0,"params":{"VariableName":"d"}},', ...
  '{"id":"tw","type":"toWorkspace","inputs":1,"outputs":0,"params":{"VariableName":"y"}}],', ...
  '"connections":[', ...
    '{"from":"c","to":"s","fromIndex":0,"toIndex":0},', ...
    '{"from":"s","to":"tw","fromIndex":0,"toIndex":0},', ...
    '{"from":"cc","to":"ig","fromIndex":0,"toIndex":0},', ...
    '{"from":"ig","to":"td","fromIndex":0,"toIndex":0}],', ...
  '"solver":"ode1","runtime":0.1,"sampleTime":0.1}'];
out = sim(vm_write(m, 'test_nflow_vm_sum'));
lg = out.logsout; nms = {lg.name};
y = lg(find(strcmp(nms, 'y'), 1)).values;
assert_istrue(abs(y(1) - 6.0) < 1e-12);
