% Conditional subsystems under the GLOBAL solver. A triggered and
% an enabled subsystem, driven by a control signal that crosses at t = 0.5, are
% run alongside a continuous integrator (so the ode4 solver path is exercised).
% The triggered subsystem's control is a zero-crossing surface under the solver
% loop (B2, last slice): the edge is located exactly at the crossing (t = 0.5,
% here a sample point) and the body fires there through Phase::EVENT, one
% sample EARLIER than the fixed-step engine, whose gate latches the edge at the
% first sample where the control is strictly positive (t = 0.6). The enabled
% (level-gated) subsystem has no surface and stays identical in both engines.
%=============================================================================
counter = struct();
counter.blocks = {...
  struct('id', 'one', 'type', 'constant', 'inputs', 0, 'outputs', 1, 'params', struct('Value', 1)), ...
  struct('id', 'acc', 'type', 'sum', 'inputs', 2, 'outputs', 1, 'params', struct('Inputs', '++')), ...
  struct('id', 'del', 'type', 'unitDelay', 'inputs', 1, 'outputs', 1, 'params', struct()), ...
  struct('id', 'cout', 'type', 'labelSink', 'inputs', 1, 'outputs', 1, ...
    'params', struct('gotoTag', 'y'))};
counter.connections = {...
  struct('from', 'one', 'to', 'acc', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'del', 'to', 'acc', 'fromIndex', 0, 'toIndex', 1), ...
  struct('from', 'acc', 'to', 'del', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'acc', 'to', 'cout', 'fromIndex', 0, 'toIndex', 0)};
counter.externalOutputs = {struct('id', 'cout', 'name', 'y')};

function d = build_model(counter, cp, varName, solver)
  inner = counter;
  inner.controlPort = cp;
  d = struct('blocks', {{...
    struct('id', 'r', 'type', 'ramp', 'inputs', 0, 'outputs', 1, 'params', struct('slope', 1)), ...
    struct('id', 'off', 'type', 'constant', 'inputs', 0, 'outputs', 1, 'params', struct('Value', -0.5)), ...
    struct('id', 'ctl', 'type', 'sum', 'inputs', 2, 'outputs', 1, 'params', struct('Inputs', '++')), ...
    struct('id', 'sub', 'type', 'subsystem', 'inputs', 1, 'outputs', 1, ...
      'params', struct('subsystem', inner, 'controlPort', cp)), ...
    struct('id', 'tw', 'type', 'toWorkspace', 'inputs', 1, 'outputs', 0, ...
      'params', struct('VariableName', varName, 'SaveFormat', 'Array', ...
      'Decimation', 1, 'MaxDataPoints', 'inf')), ...
    struct('id', 'c2', 'type', 'constant', 'inputs', 0, 'outputs', 1, 'params', struct('Value', 1)), ...
    struct('id', 'ig', 'type', 'integrator', 'inputs', 1, 'outputs', 1, 'params', struct()), ...
    struct('id', 'sc', 'type', 'scope', 'inputs', 1, 'outputs', 0, 'params', struct())}}, ...
    'connections', {{...
      struct('from', 'r', 'to', 'ctl', 'fromIndex', 0, 'toIndex', 0), ...
      struct('from', 'off', 'to', 'ctl', 'fromIndex', 0, 'toIndex', 1), ...
      struct('from', 'ctl', 'to', 'sub', 'fromIndex', 0, 'toIndex', 0), ...
      struct('from', 'sub', 'to', 'tw', 'fromIndex', 0, 'toIndex', 0), ...
      struct('from', 'c2', 'to', 'ig', 'fromIndex', 0, 'toIndex', 0), ...
      struct('from', 'ig', 'to', 'sc', 'fromIndex', 0, 'toIndex', 0)}}, ...
    'sampleTime', 0.1, 'duration', 1.0, 'solver', solver, 'variables', struct());
end
%=============================================================================
function v = run_get(d, varName)
  evalin('base', ['clear(''', varName, ''')']);
  r = jsondecode(__nflow_simulate__(jsonencode(d)));
  assert_isequal(r.status, 'done');
  v = evalin('base', varName); v = v(:)';
  evalin('base', ['clear(''', varName, ''')']);
end
%=============================================================================
% Triggered (rising): the counter increments once at the crossing and holds.
trigCp = struct('kind', 'trigger', 'triggerType', 'rising');
vd = run_get(build_model(counter, trigCp, 'tr_out', 'discrete'), 'tr_out');
vo = run_get(build_model(counter, trigCp, 'tr_out', 'ode4'), 'tr_out');
assert_isequal(numel(vo), 11);
% The control is t - 0.5: it reaches exactly 0.0 at t = 0.5, coming from below.
% A negative control arriving at zero IS a rising edge, so both engines fire
% there. The fixed-step path used to demand a strictly positive value and fired
% a sample later than the solver, which located the same edge at 0.5.
assert_istrue(max(abs(vd(1:5))) < 1e-9 && max(abs(vd(6:11) - 1)) < 1e-9);
assert_istrue(max(abs(vo(1:5))) < 1e-9 && max(abs(vo(6:11) - 1)) < 1e-9);
assert_istrue(max(abs(vo - vd)) < 1e-9); % the two engines now agree
assert_istrue(vo(1) == 0 && vo(end) == 1); % fired once at the rising edge
%=============================================================================
% Enabled (level): the counter runs only while the control is > 0 (t > 0.5),
% and holds its output when disabled.
enCp = struct('kind', 'enable');
ed = run_get(build_model(counter, enCp, 'en_out', 'discrete'), 'en_out');
eo = run_get(build_model(counter, enCp, 'en_out', 'ode4'), 'en_out');
assert_istrue(max(abs(eo - ed)) < 1e-9); % ode4 == discrete
assert_istrue(eo(1) == 0 && eo(end) > eo(1)); % held off, then counts up
