% lookupND: n-D lookup table. 3-D 2x2x2 column-major table T(i,j,k)=i+10j+100k.
% Feedthrough; logged at t0 (an integrator supplies the state the fixed-step
% solver requires).
%=============================================================================
function p = ln_write(json, stem)
  p = [tempname(), '.nflow'];
  fid = fopen(p, 'w'); fwrite(fid, json); fclose(fid);
end
%=============================================================================
function y = ln_eval(interp, u1, u2, u3)
  m = ['{"blocks":[', ...
    '{"id":"a","type":"constant","inputs":0,"outputs":1,"params":{"Value":', sprintf('%.15g', u1), '}},', ...
    '{"id":"b","type":"constant","inputs":0,"outputs":1,"params":{"Value":', sprintf('%.15g', u2), '}},', ...
    '{"id":"c","type":"constant","inputs":0,"outputs":1,"params":{"Value":', sprintf('%.15g', u3), '}},', ...
    '{"id":"f","type":"lookupND","inputs":3,"outputs":1,"params":{', ...
      '"NumberOfTableDimensions":3,', ...
      '"BreakpointsForDimension1":[0,1],"BreakpointsForDimension2":[0,1],"BreakpointsForDimension3":[0,1],', ...
      '"Table":[0,1,10,11,100,101,110,111],"InterpMethod":"', interp, '","ExtrapMethod":"Linear"}},', ...
    '{"id":"ig","type":"integrator","inputs":1,"outputs":1,"params":{"InitialCondition":0}},', ...
    '{"id":"td","type":"toWorkspace","inputs":1,"outputs":0,"params":{"VariableName":"d"}},', ...
    '{"id":"tw","type":"toWorkspace","inputs":1,"outputs":0,"params":{"VariableName":"y"}}],', ...
    '"connections":[', ...
      '{"from":"a","to":"f","fromIndex":0,"toIndex":0},', ...
      '{"from":"b","to":"f","fromIndex":0,"toIndex":1},', ...
      '{"from":"c","to":"f","fromIndex":0,"toIndex":2},', ...
      '{"from":"f","to":"tw","fromIndex":0,"toIndex":0},', ...
      '{"from":"a","to":"ig","fromIndex":0,"toIndex":0},', ...
      '{"from":"ig","to":"td","fromIndex":0,"toIndex":0}],', ...
    '"solver":"ode1","runtime":0.1,"sampleTime":0.1}'];
  out = sim(ln_write(m, 'test_nflow_lookupnd_eval'));
  lg = out.logsout; nms = {lg.name};
  y = lg(find(strcmp(nms, 'y'), 1)).values(1);
end
%=============================================================================
assert_istrue(abs(ln_eval('Linear point-slope', 0, 0, 0) - 0.0) < 1e-12);
assert_istrue(abs(ln_eval('Linear point-slope', 1, 1, 1) - 111.0) < 1e-12);
assert_istrue(abs(ln_eval('Linear point-slope', 0.5, 0.5, 0.5) - 55.5) < 1e-12);
assert_istrue(abs(ln_eval('Linear point-slope', 0.5, 0, 0) - 0.5) < 1e-12);
assert_istrue(abs(ln_eval('Linear point-slope', 0, 0.5, 0) - 5.0) < 1e-12);
assert_istrue(abs(ln_eval('Linear point-slope', 0, 0, 0.5) - 50.0) < 1e-12);
assert_istrue(abs(ln_eval('Nearest', 0.6, 0.4, 0.6) - 101.0) < 1e-12);
