% For-each subsystem code generation: the flattener unrolls the
% body N times, a selector slices each partitioned input to the iteration's
% channel, and a mux concatenates the outputs. Each unrolled copy is an
% independent block instance, so per-iteration state falls out for free. Models
% are written as raw JSON so the forEach "partition" array is a JSON array.
%=============================================================================
function p = foreach_cg_write(json, stem)
  p = [tempname(), '.nflow'];
  fid = fopen(p, 'w');
  fwrite(fid, json);
  fclose(fid);
end
%=============================================================================
% Stateless gain bank: partition [1,2,3,4] through gain 3 -> per element * 3.
gainModel = ['{"blocks":[', ...
  '{"id":"c","type":"constant","inputs":0,"outputs":1,"params":{"Value":[1,2,3,4]}},', ...
  '{"id":"sub","type":"subsystem","inputs":1,"outputs":1,"params":{', ...
    '"forEach":{"numIterations":4,"partition":[0]},"subsystem":{', ...
    '"blocks":[', ...
      '{"id":"in1","type":"labelSource","inputs":0,"outputs":1,"params":{"label":"in1"}},', ...
      '{"id":"g","type":"gain","inputs":1,"outputs":1,"params":{"Gain":3}},', ...
      '{"id":"out1","type":"labelSink","inputs":1,"outputs":1,"params":{"label":"out1"}}],', ...
    '"connections":[', ...
      '{"from":"in1","to":"g","fromIndex":0,"toIndex":0},', ...
      '{"from":"g","to":"out1","fromIndex":0,"toIndex":0}],', ...
    '"externalInputs":[{"id":"in1","name":"in1"}],', ...
    '"externalOutputs":[{"id":"out1","name":"out1"}]}}},', ...
  '{"id":"tw","type":"toWorkspace","inputs":1,"outputs":0,"params":{"VariableName":"y"}}],', ...
  '"connections":[', ...
    '{"from":"c","to":"sub","fromIndex":0,"toIndex":0},', ...
    '{"from":"sub","to":"tw","fromIndex":0,"toIndex":0}],', ...
  '"runtime":0.2,"sampleTime":0.1}'];
gfile = foreach_cg_write(gainModel, 'test_nf_cg_foreach_gain');
[~, gstem] = fileparts(gfile);
nflow_codegenerate(gfile, tempdir(), false);
gc = fileread([tempdir(), '/', gstem, '/model.c']);
% Four unrolled gain instances, each reading its own constant element * 3.
assert_istrue(~isempty(strfind(gc, 'out_c__e0 * 3')));
assert_istrue(~isempty(strfind(gc, 'out_c__e1 * 3')));
assert_istrue(~isempty(strfind(gc, 'out_c__e2 * 3')));
assert_istrue(~isempty(strfind(gc, 'out_c__e3 * 3')));
% The outer output concatenates the four channels (3,6,9,12 at t>0).
assert_istrue(~isempty(strfind(gc, 'out_tw__e3')));
%=============================================================================
% The same unroll is language-agnostic: Rust carries for-each too.
nflow_codegenerate(gfile, tempdir(), false, 'rust');
gr = fileread([tempdir(), '/', gstem, '/src/lib.rs']);
assert_istrue(~isempty(strfind(gr, 'out_sub_fe0_g')));
assert_istrue(~isempty(strfind(gr, 'out_sub_fe3_g')));
assert_istrue(~isempty(strfind(gr, 'out_c__e0')));
%=============================================================================
% Continuous per-iteration state: an integrator bank gives N distinct states.
intModel = ['{"blocks":[', ...
  '{"id":"c","type":"constant","inputs":0,"outputs":1,"params":{"Value":[1,2]}},', ...
  '{"id":"sub","type":"subsystem","inputs":1,"outputs":1,"params":{', ...
    '"forEach":{"numIterations":2,"partition":[0]},"subsystem":{', ...
    '"blocks":[', ...
      '{"id":"in1","type":"labelSource","inputs":0,"outputs":1,"params":{"label":"in1"}},', ...
      '{"id":"ig","type":"integrator","inputs":1,"outputs":1,"params":{"InitialCondition":0}},', ...
      '{"id":"out1","type":"labelSink","inputs":1,"outputs":1,"params":{"label":"out1"}}],', ...
    '"connections":[', ...
      '{"from":"in1","to":"ig","fromIndex":0,"toIndex":0},', ...
      '{"from":"ig","to":"out1","fromIndex":0,"toIndex":0}],', ...
    '"externalInputs":[{"id":"in1","name":"in1"}],', ...
    '"externalOutputs":[{"id":"out1","name":"out1"}]}}},', ...
  '{"id":"tw","type":"toWorkspace","inputs":1,"outputs":0,"params":{"VariableName":"y"}}],', ...
  '"connections":[', ...
    '{"from":"c","to":"sub","fromIndex":0,"toIndex":0},', ...
    '{"from":"sub","to":"tw","fromIndex":0,"toIndex":0}],', ...
  '"solver":"ode4","runtime":1.0,"sampleTime":0.1}'];
ifile = foreach_cg_write(intModel, 'test_nf_cg_foreach_int');
[~, istem] = fileparts(ifile);
nflow_codegenerate(ifile, tempdir(), false);
ic = fileread([tempdir(), '/', istem, '/model.c']);
% Two independent integrator states, one per iteration.
assert_istrue(~isempty(strfind(ic, 'int_sub_fe0_ig')));
assert_istrue(~isempty(strfind(ic, 'int_sub_fe1_ig')));
rmfile(gfile);
rmfile(ifile);
if isdir([tempdir(), '/', gstem])
  rmdir([tempdir(), '/', gstem], 's');
end
if isdir([tempdir(), '/', istem])
  rmdir([tempdir(), '/', istem], 's');
end
