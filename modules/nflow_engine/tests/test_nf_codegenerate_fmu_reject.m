% FMU (FMI Co-Simulation) blocks wrap a precompiled binary run by the FMU
% runtime and cannot be lowered to standalone C/Rust. Code generation must
% reject such a diagram explicitly instead of emitting a constant-0.0 output.
%=============================================================================
model = [tempname(), '.nflow'];
json = ['{', ...
  '"version":"1.0.0","format":"nflow-2","name":"FmuReject",', ...
  '"blocks":[', ...
  '{"id":"b1","type":"fmu","x":100,"y":100,"rotation":0,"params":{"path":"VanDerPol.fmu"}},', ...
  '{"id":"b2","type":"scope","x":300,"y":100,"rotation":0,"params":{}}', ...
  '],', ...
  '"connections":[{"from":"b1","fromPort":0,"to":"b2","toPort":0}]', ...
  '}'];
fid = fopen(model, 'wt');
fwrite(fid, json);
fclose(fid);
%=============================================================================
cmd = ['nflow_codegenerate(''', model, ''', tempdir(), false, ''C'')'];
assert_checkerror(cmd, _(['Code generation is not supported for FMU (FMI ', ...
  'Co-Simulation) blocks; the generated program cannot embed the FMU ', ...
  'runtime. Remove FMU blocks before generating code.']));
assert_checkerror(cmd, _(['Code generation is not supported for FMU (FMI ', ...
  'Co-Simulation) blocks; the generated program cannot embed the FMU ', ...
  'runtime. Remove FMU blocks before generating code.']), ...
  'Nelson:nflow_engine:codegenUnsupported:codeGenerationFmuBlocks');
%=============================================================================
% Same rejection for the Rust backend.
cmd = ['nflow_codegenerate(''', model, ''', tempdir(), false, ''rust'')'];
assert_checkerror(cmd, _(['Code generation is not supported for FMU (FMI ', ...
  'Co-Simulation) blocks; the generated program cannot embed the FMU ', ...
  'runtime. Remove FMU blocks before generating code.']));
%=============================================================================
rmfile(model);
