% A SampleTime on a feedthrough block (a gain) is now honored via sample-and-hold
% in the algebraic solve: the block latches its output at each rate
% hit and holds it between hits, instead of being rejected. The staircase-vs-input
% behavior is covered in detail by test_nflow_multirate_feedthrough; here a
% constant input just confirms the model runs (no "no state to hold" error) and
% produces the held constant.
dft = struct('blocks', {{...
  struct('id', 'c', 'type', 'constant', 'inputs', 0, 'outputs', 1, ...
    'params', struct('Value', 1)), ...
  struct('id', 'g', 'type', 'gain', 'inputs', 1, 'outputs', 1, ...
    'params', struct('Gain', 2, 'SampleTime', 0.2)), ...
  struct('id', 'w', 'type', 'toWorkspace', 'inputs', 1, 'outputs', 0, ...
    'params', struct('VariableName', 'qft', 'SaveFormat', 'Array', ...
    'Decimation', 1, 'MaxDataPoints', 'inf'))}}, ...
  'connections', {{...
    struct('from', 'c', 'to', 'g', 'fromIndex', 0, 'toIndex', 0), ...
    struct('from', 'g', 'to', 'w', 'fromIndex', 0, 'toIndex', 0)}}, ...
  'sampleTime', 0.1, 'duration', 0.5, 'solver', 'discrete', 'variables', struct());
rft = jsondecode(__nflow_simulate__(jsonencode(dft)));
assert_isequal(rft.status, 'done');
qft = evalin('base', 'qft'); qft = qft(:)';
