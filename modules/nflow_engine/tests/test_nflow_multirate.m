% A COMMENSURATE non-integer SampleTime is now accepted: the base
% step is refined to the GCD so every rate is integer. Base 0.1, SampleTime 0.25
% -> GCD 0.05 (factor 2), so the run succeeds at the refined base instead of
% erroring. Output follows at the refined grid (21 points over [0,1] at 0.05).
evalin('base', 'clear(''zbad'')');
dbad = struct('blocks', {{...
  struct('id', 'r', 'type', 'ramp', 'inputs', 0, 'outputs', 1, ...
    'params', struct('slope', 1)), ...
  struct('id', 'ud', 'type', 'unitDelay', 'inputs', 1, 'outputs', 1, ...
    'params', struct('InitialCondition', 0, 'SampleTime', 0.25)), ...
  struct('id', 'w', 'type', 'toWorkspace', 'inputs', 1, 'outputs', 0, ...
    'params', struct('VariableName', 'zbad', 'SaveFormat', 'Array', ...
    'Decimation', 1, 'MaxDataPoints', 'inf'))}}, ...
  'connections', {{...
    struct('from', 'r', 'to', 'ud', 'fromIndex', 0, 'toIndex', 0), ...
    struct('from', 'ud', 'to', 'w', 'fromIndex', 0, 'toIndex', 0)}}, ...
  'sampleTime', 0.1, 'duration', 1.0, 'solver', 'discrete', 'variables', struct());
rbad = jsondecode(__nflow_simulate__(jsonencode(dbad)));
assert_isequal(rbad.status, 'done');
zbad = evalin('base', 'zbad');
assert_isequal(numel(zbad(:)), 21); % refined base 0.05 => 21 samples over [0,1]
evalin('base', 'clear(''zbad'')');

%=============================================================================
% An INCOMMENSURATE SampleTime (irrational ratio to the base) still errors: the
% GCD refinement would be pathologically fine, so it is capped and the clear
% "not an integer multiple" diagnostic fires. Base 0.1, SampleTime sqrt(2)*0.1.
dinc = dbad;
dinc.blocks{2}.params.SampleTime = sqrt(2) * 0.1;
rinc = jsondecode(__nflow_simulate__(jsonencode(dinc)));
assert_isequal(rinc.status, 'error');
assert_istrue(~isempty(strfind(rinc.reason, 'not an integer multiple')));
assert_istrue(~isempty(strfind(rinc.reason, 'ud')));
