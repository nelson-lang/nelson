% Multi-rate holds a vector state, not just a scalar: a 2-wide unit delay at 2x
% the base step holds both lanes for two samples each. Two ramps (slopes 1 and
% 10) are muxed into the delay.
dvec = struct('blocks', {{...
  struct('id', 'r1', 'type', 'ramp', 'inputs', 0, 'outputs', 1, 'params', struct('slope', 1)), ...
  struct('id', 'r2', 'type', 'ramp', 'inputs', 0, 'outputs', 1, 'params', struct('slope', 10)), ...
  struct('id', 'm', 'type', 'mux', 'inputs', 2, 'outputs', 1, 'params', struct()), ...
  struct('id', 'ud', 'type', 'unitDelay', 'inputs', 1, 'outputs', 1, ...
    'params', struct('InitialCondition', 0, 'SampleTime', 0.2)), ...
  struct('id', 'w', 'type', 'toWorkspace', 'inputs', 1, 'outputs', 0, ...
    'params', struct('VariableName', 'vmr', 'SaveFormat', 'Array', ...
    'Decimation', 1, 'MaxDataPoints', 'inf'))}}, ...
  'connections', {{...
    struct('from', 'r1', 'to', 'm', 'fromIndex', 0, 'toIndex', 0), ...
    struct('from', 'r2', 'to', 'm', 'fromIndex', 0, 'toIndex', 1), ...
    struct('from', 'm', 'to', 'ud', 'fromIndex', 0, 'toIndex', 0), ...
    struct('from', 'ud', 'to', 'w', 'fromIndex', 0, 'toIndex', 0)}}, ...
  'sampleTime', 0.1, 'duration', 1.0, 'solver', 'discrete', 'variables', struct());
rv = jsondecode(__nflow_simulate__(jsonencode(dvec)));
