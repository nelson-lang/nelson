% A block that carries its own sample-time parameter (zoh/ddelay/foh/dtf/
% dstateSpace) gates its UPDATE on that parameter internally, exactly as the
% emitted C/Rust step does, so it takes no generic sub-rate schedule -- but it
% must still RUN. Rejecting it made every one of those blocks unusable: their
% sample time is the only thing that makes them hold, and it is the field the
% editor writes. Here a ramp held every 0.2 s on a 0.1 s base step must come
% back as a staircase, and each pair of samples must repeat.
dz = struct('blocks', {{...
  struct('id', 'r', 'type', 'ramp', 'inputs', 0, 'outputs', 1, 'params', struct('slope', 1)), ...
  struct('id', 'z', 'type', 'zoh', 'inputs', 1, 'outputs', 1, 'params', struct('SampleTime', 0.2)), ...
  struct('id', 'w', 'type', 'toWorkspace', 'inputs', 1, 'outputs', 0, ...
    'params', struct('VariableName', 'yz', 'SaveFormat', 'Array', ...
    'Decimation', 1, 'MaxDataPoints', 'inf'))}}, ...
  'connections', {{...
    struct('from', 'r', 'to', 'z', 'fromIndex', 0, 'toIndex', 0), ...
    struct('from', 'z', 'to', 'w', 'fromIndex', 0, 'toIndex', 0)}}, ...
  'sampleTime', 0.1, 'duration', 0.5, 'solver', 'discrete', 'variables', struct());
rz = jsondecode(__nflow_simulate__(jsonencode(dz)));
assert_isequal(rz.status, 'done');
yz = evalin('base', 'yz'); yz = yz(:)';
evalin('base', 'clear(''yz'')');
% Hold of 0.2 s over a 0.1 s base step on a unit ramp: a staircase of equal
% pairs. The value at a hit instant is the input taken THERE, so the pair
% starting at t = 0.2 reads 0.2 -- a hold is not a delay.
expectedZ = [0 0 0.2 0.2 0.4 0.4 0.6 0.6 0.8 0.8 1.0];
assert_istrue(numel(yz) == numel(expectedZ));
assert_istrue(max(abs(yz - expectedZ)) < 1e-9);
