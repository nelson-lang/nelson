% A SampleTime on a block nested inside a subsystem is not applied (the simulator
% runs subsystems as nested units, and per-block rates only cover top-level
% blocks). It is rejected with a clear diagnostic rather than silently ignored,
% so multi-rate has no silent no-op anywhere.
inner = struct('blocks', {{...
  struct('id', 'in1', 'type', 'labelSource', 'inputs', 0, 'outputs', 1, ...
    'params', struct('GotoTag', 'in1', 'isExternalPort', true)), ...
  struct('id', 'ud', 'type', 'unitDelay', 'inputs', 1, 'outputs', 1, ...
    'params', struct('InitialCondition', 0, 'SampleTime', 0.2)), ...
  struct('id', 'out1', 'type', 'labelSink', 'inputs', 1, 'outputs', 1, ...
    'params', struct('GotoTag', 'out1'))}}, ...
  'connections', {{...
    struct('from', 'in1', 'to', 'ud', 'fromIndex', 0, 'toIndex', 0), ...
    struct('from', 'ud', 'to', 'out1', 'fromIndex', 0, 'toIndex', 0)}});
dnest = struct('blocks', {{...
  struct('id', 'c', 'type', 'constant', 'inputs', 0, 'outputs', 1, 'params', struct('Value', 1)), ...
  struct('id', 'ss', 'type', 'subsystem', 'inputs', 1, 'outputs', 1, ...
    'params', struct('subsystem', inner)), ...
  struct('id', 's', 'type', 'scope', 'inputs', 1, 'outputs', 0, 'params', struct())}}, ...
  'connections', {{...
    struct('from', 'c', 'to', 'ss', 'fromIndex', 0, 'toIndex', 0), ...
    struct('from', 'ss', 'to', 's', 'fromIndex', 0, 'toIndex', 0)}}, ...
  'sampleTime', 0.1, 'duration', 0.5, 'solver', 'discrete', 'variables', struct());
rnest = jsondecode(__nflow_simulate__(jsonencode(dnest)));
assert_isequal(rnest.status, 'error');
assert_istrue(~isempty(strfind(rnest.reason, 'nested inside a subsystem')));
assert_istrue(~isempty(strfind(rnest.reason, 'ud')));
