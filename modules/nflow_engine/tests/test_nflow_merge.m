% L3: merge block. Recombines the outputs of mutually-exclusive conditional
% subsystems. Two enabled subsystems (A active for t<0.5 emitting 10, B active
% for t>=0.5 emitting 20) feed a merge; its output follows whichever branch ran
% this step: 10 then 20.
%=============================================================================
evalin('base', 'clear(''mg_out'')');

function s = const_subsystem(value)
  s = struct();
  s.blocks = {...
    struct('id', 'k', 'type', 'constant', 'inputs', 0, 'outputs', 1, ...
      'params', struct('Value', value)), ...
    struct('id', 'yout', 'type', 'labelSink', 'inputs', 1, 'outputs', 1, ...
      'params', struct('gotoTag', 'y'))};
  s.connections = {struct('from', 'k', 'to', 'yout', 'fromIndex', 0, 'toIndex', 0)};
  s.externalOutputs = {struct('id', 'yout', 'name', 'y')};
  s.controlPort = struct('kind', 'enable');
end

en = struct('kind', 'enable');
d = struct();
d.blocks = {...
  struct('id', 'clk', 'type', 'clock', 'inputs', 0, 'outputs', 1, 'params', struct()), ...
  struct('id', 'enA', 'type', 'compareToConstant', 'inputs', 1, 'outputs', 1, ...
    'params', struct('relop', 'lt', 'const', 0.5)), ...   % A enabled for t < 0.5
  struct('id', 'enB', 'type', 'compareToConstant', 'inputs', 1, 'outputs', 1, ...
    'params', struct('relop', 'ge', 'const', 0.5)), ...   % B enabled for t >= 0.5
  struct('id', 'subA', 'type', 'subsystem', 'inputs', 1, 'outputs', 1, ...
    'params', struct('subsystem', const_subsystem(10), 'controlPort', en)), ...
  struct('id', 'subB', 'type', 'subsystem', 'inputs', 1, 'outputs', 1, ...
    'params', struct('subsystem', const_subsystem(20), 'controlPort', en)), ...
  struct('id', 'mrg', 'type', 'merge', 'inputs', 2, 'outputs', 1, ...
    'params', struct('InitialOutput', 0)), ...
  struct('id', 'tw', 'type', 'toWorkspace', 'inputs', 1, 'outputs', 0, ...
    'params', struct('VariableName', 'mg_out', 'SaveFormat', 'Array', ...
    'Decimation', 1, 'MaxDataPoints', 'inf'))};
d.connections = {...
  struct('from', 'clk', 'to', 'enA', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'clk', 'to', 'enB', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'enA', 'to', 'subA', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'enB', 'to', 'subB', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'subA', 'to', 'mrg', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'subB', 'to', 'mrg', 'fromIndex', 0, 'toIndex', 1), ...
  struct('from', 'mrg', 'to', 'tw', 'fromIndex', 0, 'toIndex', 0)};
d.sampleTime = 0.1; d.duration = 1.0; d.variables = struct();

r = jsondecode(__nflow_simulate__(jsonencode(d)));
asserts.isequal(r.status, 'done');
v = evalin('base', 'mg_out');
v = v(:);
asserts.isequal(numel(v), 11);
% t < 0.5 : branch A active -> 10.
asserts.isapprox(v(1), 10.0, 0, 1e-9);
asserts.isapprox(v(5), 10.0, 0, 1e-9);
% t >= 0.5 : branch B active -> 20.
asserts.isapprox(v(6), 20.0, 0, 1e-9);
asserts.isapprox(v(end), 20.0, 0, 1e-9);

evalin('base', 'clear(''mg_out'')');
