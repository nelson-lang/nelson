% Family 9 -- pseudo-random source parity, and the complementary-filter block
% mix that ships as examples/causal/complementary_filter.nflow. The noise
% block seeds a deterministic LCG (rng_state = 1664525*rng_state + 1013904223,
% mapped to [-1, 1]); every backend and the interpreter MUST reproduce the
% same stream bit-for-bit. A Rust backend that used a different generator
% (xorshift32) silently diverged any diagram feeding a noise block -- the raw
% 'r' column catches that directly, and the 'f' column (noise + sine through a
% low-pass, summed with a high-pass of the integrated derivative + bias) is
% the same stateful-continuous chain the shipped demo drives into its scope.
