% Complex signals through the simulation engine.
%=============================================================================
% (1+3i, 2+4i) * (5+6i, 7+8i) : full complex product through mult, then the
% real magnitude through abs. Result JSON carries signalsImag/signalComplex.
d = struct();
d.blocks = {struct('id', 'ra', 'type', 'constant', 'inputs', 0, 'outputs', 1, 'params', struct('Value', [1 2])), ...
  struct('id', 'ia', 'type', 'constant', 'inputs', 0, 'outputs', 1, 'params', struct('Value', [3 4])), ...
  struct('id', 'rb', 'type', 'constant', 'inputs', 0, 'outputs', 1, 'params', struct('Value', [5 7])), ...
  struct('id', 'ib', 'type', 'constant', 'inputs', 0, 'outputs', 1, 'params', struct('Value', [6 8])), ...
  struct('id', 'ca', 'type', 'realImagToComplex', 'inputs', 2, 'outputs', 1, 'params', struct()), ...
  struct('id', 'cb', 'type', 'realImagToComplex', 'inputs', 2, 'outputs', 1, 'params', struct()), ...
  struct('id', 'm', 'type', 'mult', 'inputs', 2, 'outputs', 1, 'params', struct()), ...
  struct('id', 'mag', 'type', 'abs', 'inputs', 1, 'outputs', 1, 'params', struct()), ...
  struct('id', 's', 'type', 'scope', 'inputs', 1, 'outputs', 0, 'params', struct())};
d.connections = {struct('from', 'ra', 'to', 'ca', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'ia', 'to', 'ca', 'fromIndex', 0, 'toIndex', 1), ...
  struct('from', 'rb', 'to', 'cb', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'ib', 'to', 'cb', 'fromIndex', 0, 'toIndex', 1), ...
  struct('from', 'ca', 'to', 'm', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'cb', 'to', 'm', 'fromIndex', 0, 'toIndex', 1), ...
  struct('from', 'm', 'to', 'mag', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'mag', 'to', 's', 'fromIndex', 0, 'toIndex', 0)};
d.sampleTime = 0.01; d.duration = 0.05; d.variables = struct();
r = jsondecode(__nflow_simulate__(jsonencode(d)));
assert_isequal(r.status, 'done');
% (1+3i)*(5+6i) = 5+6i+15i-18 = -13+21i ; (2+4i)*(7+8i) = 14+16i+28i-32 = -18+44i
assert_isequal(nflow_test_sig(r, 'm'), [-13 -18]);
assert_isequal(nflow_test_sig_imag(r, 'm'), [21 44]);
assert_istrue(r.signalComplex.m(1));
assert_istrue(~r.signalComplex.mag(1));
za = abs(complex(-13, 21)); zb = abs(complex(-18, 44));
mv = nflow_test_sig(r, 'mag');
assert_istrue(max(abs(mv - [za zb])) < 1e-12);
%=============================================================================
% magnitude/angle round-trip: (m=2, a=pi/3) -> complex -> mag-angle back.
d2 = struct();
d2.blocks = {struct('id', 'mm', 'type', 'constant', 'inputs', 0, 'outputs', 1, 'params', struct('Value', 2)), ...
  struct('id', 'aa', 'type', 'constant', 'inputs', 0, 'outputs', 1, 'params', struct('Value', pi / 3)), ...
  struct('id', 'mk', 'type', 'magnitudeAngleToComplex', 'inputs', 2, 'outputs', 1, 'params', struct()), ...
  struct('id', 'cj', 'type', 'conjugate', 'inputs', 1, 'outputs', 1, 'params', struct()), ...
  struct('id', 'sp', 'type', 'complexToMagnitudeAngle', 'inputs', 1, 'outputs', 2, 'params', struct()), ...
  struct('id', 'd1', 'type', 'display', 'inputs', 1, 'outputs', 0, 'params', struct()), ...
  struct('id', 'd2', 'type', 'display', 'inputs', 1, 'outputs', 0, 'params', struct())};
d2.connections = {struct('from', 'mm', 'to', 'mk', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'aa', 'to', 'mk', 'fromIndex', 0, 'toIndex', 1), ...
  struct('from', 'mk', 'to', 'cj', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'cj', 'to', 'sp', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'sp', 'to', 'd1', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'sp', 'to', 'd2', 'fromIndex', 1, 'toIndex', 0)};
d2.sampleTime = 0.01; d2.duration = 0.05; d2.variables = struct();
r2 = jsondecode(__nflow_simulate__(jsonencode(d2)));
assert_isequal(r2.status, 'done');
% conj flips the angle: magnitude 2 (port 1), angle -pi/3 (port 2).
sp2 = r2.signals.sp;
assert_istrue(abs(sp2(1) - 2) < 1e-12);
assert_istrue(abs(sp2(2) - (-pi / 3)) < 1e-12);
%=============================================================================
% complex -> real+imag split recovers the parts.
d3 = struct();
d3.blocks = {struct('id', 'rr', 'type', 'constant', 'inputs', 0, 'outputs', 1, 'params', struct('Value', [1 2])), ...
  struct('id', 'ii', 'type', 'constant', 'inputs', 0, 'outputs', 1, 'params', struct('Value', [-3 5])), ...
  struct('id', 'ck', 'type', 'realImagToComplex', 'inputs', 2, 'outputs', 1, 'params', struct()), ...
  struct('id', 'sp', 'type', 'complexToRealImag', 'inputs', 1, 'outputs', 2, 'params', struct()), ...
  struct('id', 'd1', 'type', 'display', 'inputs', 1, 'outputs', 0, 'params', struct()), ...
  struct('id', 'd2', 'type', 'display', 'inputs', 1, 'outputs', 0, 'params', struct())};
d3.connections = {struct('from', 'rr', 'to', 'ck', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'ii', 'to', 'ck', 'fromIndex', 0, 'toIndex', 1), ...
  struct('from', 'ck', 'to', 'sp', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'sp', 'to', 'd1', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'sp', 'to', 'd2', 'fromIndex', 1, 'toIndex', 0)};
d3.sampleTime = 0.01; d3.duration = 0.05; d3.variables = struct();
r3 = jsondecode(__nflow_simulate__(jsonencode(d3)));
assert_isequal(r3.status, 'done');
sp = r3.signals.sp;
if iscell(sp)
  p1 = sp{1}(:)'; p2 = sp{2}(:)';
else
  p1 = sp(1, :); p2 = sp(2, :);
end
assert_isequal(p1, [1 2]);
assert_isequal(p2, [-3 5]);
