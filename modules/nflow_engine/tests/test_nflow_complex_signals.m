% A complex signal into a block without a complex path is a clean error.
d4 = struct();
d4.blocks = {struct('id', 'rr', 'type', 'constant', 'inputs', 0, 'outputs', 1, 'params', struct('Value', 1)), ...
  struct('id', 'ck', 'type', 'realImagToComplex', 'inputs', 2, 'outputs', 1, 'params', struct()), ...
  struct('id', 'u', 'type', 'unitDelay', 'inputs', 1, 'outputs', 1, 'params', struct()), ...
  struct('id', 's', 'type', 'scope', 'inputs', 1, 'outputs', 0, 'params', struct())};
d4.connections = {struct('from', 'rr', 'to', 'ck', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'ck', 'to', 'u', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'u', 'to', 's', 'fromIndex', 0, 'toIndex', 0)};
d4.sampleTime = 0.01; d4.duration = 0.05; d4.variables = struct();
r4 = jsondecode(__nflow_simulate__(jsonencode(d4)));
assert_isequal(r4.status, 'error');
assert_istrue(~isempty(strfind(r4.reason, 'complex')));
%=============================================================================
function v = nflow_test_sig(r, id)
  v = r.signals.(id);
  if iscell(v)
    v = cell2mat(v);
  end
  v = v(:)';
end
%=============================================================================
function v = nflow_test_sig_imag(r, id)
  v = r.signalsImag.(id);
  if iscell(v)
    v = cell2mat(v);
  end
  v = v(:)';
end
