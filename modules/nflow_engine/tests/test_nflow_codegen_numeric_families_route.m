% picks channel 1 (the sine) back out.
d = struct();
d.blocks = {...
  struct('id', 'sn', 'type', 'sine', 'inputs', 0, 'outputs', 1, ...
    'params', struct('Amplitude', 2, 'Frequency', 1)), ...
  struct('id', 'k', 'type', 'constant', 'inputs', 0, 'outputs', 1, 'params', struct('Value', 4)), ...
  struct('id', 'mx', 'type', 'mux', 'inputs', 2, 'outputs', 1, 'params', struct()), ...
  struct('id', 'sel', 'type', 'selector', 'inputs', 1, 'outputs', 1, 'params', struct('Indices', 1)), ...
  struct('id', 'y', 'type', 'labelSink', 'inputs', 1, 'outputs', 1, ...
    'params', struct('GotoTag', 'y', 'isExternalPort', true)), ...
