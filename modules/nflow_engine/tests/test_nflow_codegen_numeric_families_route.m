    'params', struct('VariableName', 'nfrt_y', 'SaveFormat', 'Array', 'Decimation', 1, 'MaxDataPoints', 'inf'))};
d.connections = {...
  struct('from', 'sn', 'to', 'mx', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'k', 'to', 'mx', 'fromIndex', 0, 'toIndex', 1), ...
  struct('from', 'mx', 'to', 'sel', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'sel', 'to', 'y', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'sel', 'to', 'tw', 'fromIndex', 0, 'toIndex', 0)};
