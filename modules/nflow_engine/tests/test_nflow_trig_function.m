% <--WEIGHT 2-->
% trigFunction: elementwise trigonometric function selected by a Function
% parameter (sin/cos/tan/asin/acos/atan/sinh/cosh/tanh/asinh/acosh/atanh).
% Feedthrough; logged at t0 (an integrator supplies the state the fixed-step
% solver requires).
%=============================================================================
function p = tf_write(json, stem)
  p = [tempname(), '.nflow'];
  fid = fopen(p, 'w'); fwrite(fid, json); fclose(fid);
end
%=============================================================================
function y = tf_eval(fn, value)
  m = ['{"blocks":[', ...
    '{"id":"c","type":"constant","inputs":0,"outputs":1,"params":{"Value":', ...
      sprintf('%.15g', value), '}},', ...
    '{"id":"f","type":"trigFunction","inputs":1,"outputs":1,"params":{"Function":"', fn, '"}},', ...
    '{"id":"ig","type":"integrator","inputs":1,"outputs":1,"params":{"InitialCondition":0}},', ...
    '{"id":"td","type":"toWorkspace","inputs":1,"outputs":0,"params":{"VariableName":"d"}},', ...
    '{"id":"tw","type":"toWorkspace","inputs":1,"outputs":0,"params":{"VariableName":"y"}}],', ...
    '"connections":[', ...
      '{"from":"c","to":"f","fromIndex":0,"toIndex":0},', ...
      '{"from":"f","to":"tw","fromIndex":0,"toIndex":0},', ...
      '{"from":"c","to":"ig","fromIndex":0,"toIndex":0},', ...
      '{"from":"ig","to":"td","fromIndex":0,"toIndex":0}],', ...
    '"solver":"ode1","runtime":0.1,"sampleTime":0.1}'];
  out = sim(tf_write(m, ['test_nflow_tf_', fn]));
  lg = out.logsout; nms = {lg.name};
  vals = lg(find(strcmp(nms, 'y'), 1)).values;
  y = vals(1);
end
%=============================================================================
function y = tf_atan2(u1, u2)
  % atan2(u1, u2): u1 on port 0, u2 on port 1.
  m = ['{"blocks":[', ...
    '{"id":"cy","type":"constant","inputs":0,"outputs":1,"params":{"Value":', sprintf('%.15g', u1), '}},', ...
    '{"id":"cx","type":"constant","inputs":0,"outputs":1,"params":{"Value":', sprintf('%.15g', u2), '}},', ...
    '{"id":"f","type":"trigFunction","inputs":2,"outputs":1,"params":{"Function":"atan2"}},', ...
    '{"id":"ig","type":"integrator","inputs":1,"outputs":1,"params":{"InitialCondition":0}},', ...
    '{"id":"td","type":"toWorkspace","inputs":1,"outputs":0,"params":{"VariableName":"d"}},', ...
    '{"id":"tw","type":"toWorkspace","inputs":1,"outputs":0,"params":{"VariableName":"y"}}],', ...
    '"connections":[', ...
      '{"from":"cy","to":"f","fromIndex":0,"toIndex":0},', ...
      '{"from":"cx","to":"f","fromIndex":0,"toIndex":1},', ...
      '{"from":"f","to":"tw","fromIndex":0,"toIndex":0},', ...
      '{"from":"cy","to":"ig","fromIndex":0,"toIndex":0},', ...
      '{"from":"ig","to":"td","fromIndex":0,"toIndex":0}],', ...
    '"solver":"ode1","runtime":0.1,"sampleTime":0.1}'];
  out = sim(tf_write(m, 'test_nflow_tf_atan2'));
  lg = out.logsout; nms = {lg.name};
  y = lg(find(strcmp(nms, 'y'), 1)).values(1);
end
%=============================================================================
function [s, c] = tf_sincos(u)
  % sincos: sin(u) on output port 0, cos(u) on output port 1.
  m = ['{"blocks":[', ...
    '{"id":"c","type":"constant","inputs":0,"outputs":1,"params":{"Value":', sprintf('%.15g', u), '}},', ...
    '{"id":"f","type":"trigFunction","inputs":1,"outputs":2,"params":{"Function":"sincos"}},', ...
    '{"id":"ig","type":"integrator","inputs":1,"outputs":1,"params":{"InitialCondition":0}},', ...
    '{"id":"td","type":"toWorkspace","inputs":1,"outputs":0,"params":{"VariableName":"d"}},', ...
    '{"id":"ts","type":"toWorkspace","inputs":1,"outputs":0,"params":{"VariableName":"s"}},', ...
    '{"id":"tc","type":"toWorkspace","inputs":1,"outputs":0,"params":{"VariableName":"co"}}],', ...
    '"connections":[', ...
      '{"from":"c","to":"f","fromIndex":0,"toIndex":0},', ...
      '{"from":"f","to":"ts","fromIndex":0,"toIndex":0},', ...
      '{"from":"f","to":"tc","fromIndex":1,"toIndex":0},', ...
      '{"from":"c","to":"ig","fromIndex":0,"toIndex":0},', ...
      '{"from":"ig","to":"td","fromIndex":0,"toIndex":0}],', ...
    '"solver":"ode1","runtime":0.1,"sampleTime":0.1}'];
  out = sim(tf_write(m, 'test_nflow_tf_sincos'));
  lg = out.logsout; nms = {lg.name};
  s = lg(find(strcmp(nms, 's'), 1)).values(1);
  c = lg(find(strcmp(nms, 'co'), 1)).values(1);
end
%=============================================================================
assert_istrue(abs(tf_eval('sin', pi / 6) - 0.5) < 1e-12);
assert_istrue(abs(tf_eval('cos', 0) - 1.0) < 1e-12);
assert_istrue(abs(tf_eval('tan', pi / 4) - 1.0) < 1e-12);
assert_istrue(abs(tf_eval('asin', 1) - pi / 2) < 1e-12);
assert_istrue(abs(tf_eval('acos', 1) - 0.0) < 1e-12);
assert_istrue(abs(tf_eval('atan', 1) - pi / 4) < 1e-12);
assert_istrue(abs(tf_eval('sinh', 0) - 0.0) < 1e-12);
assert_istrue(abs(tf_eval('cosh', 0) - 1.0) < 1e-12);
assert_istrue(abs(tf_eval('tanh', 0) - 0.0) < 1e-12);
assert_istrue(abs(tf_eval('asinh', 0) - 0.0) < 1e-12);
assert_istrue(abs(tf_eval('acosh', 1) - 0.0) < 1e-12);
assert_istrue(abs(tf_eval('atanh', 0) - 0.0) < 1e-12);
assert_istrue(abs(tf_atan2(1, 1) - pi / 4) < 1e-12);
assert_istrue(abs(tf_atan2(1, 0) - pi / 2) < 1e-12);
[s, c] = tf_sincos(pi / 6);
assert_istrue(abs(s - 0.5) < 1e-12);
assert_istrue(abs(c - cos(pi / 6)) < 1e-12);
