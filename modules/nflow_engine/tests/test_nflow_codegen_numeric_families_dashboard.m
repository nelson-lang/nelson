% ModelState field seeded with the dashboard value; the display signal
% binding is erased. Defaults must reproduce the simulator exactly.
parameterBinding = struct('kind', 'parameter', 'blockPath', {{'g'}}, ...
  'paramName', 'Gain', 'element', '');
signalBinding = struct('kind', 'signal', 'blockPath', {{'g'}}, ...
  'outputPortIndex', 1, 'frameProcessingMode', 'sample');
d = struct();
d.blocks = {...
  struct('id', 'c', 'type', 'constant', 'inputs', 0, 'outputs', 1, 'params', struct('Value', 2)), ...
  struct('id', 'g', 'type', 'gain', 'inputs', 1, 'outputs', 1, 'params', struct('Gain', 3)), ...
  struct('id', 'ui', 'type', 'dashboardSlider', 'inputs', 0, 'outputs', 0, ...
    'params', struct('Binding', parameterBinding, 'DashboardValue', 3)), ...
  struct('id', 'disp', 'type', 'dashboardDisplay', 'inputs', 0, 'outputs', 0, ...
    'params', struct('Binding', signalBinding, 'Format', 'short')), ...
  struct('id', 'y', 'type', 'labelSink', 'inputs', 1, 'outputs', 1, ...
    'params', struct('GotoTag', 'y', 'isExternalPort', true)), ...
  struct('id', 'tw', 'type', 'toWorkspace', 'inputs', 1, 'outputs', 0, ...
    'params', struct('VariableName', 'nfdb_y', 'SaveFormat', 'Array', 'Decimation', 1, 'MaxDataPoints', 'inf'))};
d.connections = {...
  struct('from', 'c', 'to', 'g', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'g', 'to', 'y', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'g', 'to', 'tw', 'fromIndex', 0, 'toIndex', 0)};
d.sampleTime = 0.1;
d.duration = 0.5;
d.variables = struct();
nflow_codegen_check_numeric(d, 'nffam_dash', 'C', {'y'}, {'nfdb_y'}, 0, 0);
