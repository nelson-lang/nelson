% A genuine algebraic loop (no latched block on the cycle) is iterated to a
% fixed point by the simulator, but generated code is straight-line: the loop
% members would be emitted once, in diagram order, producing numerically wrong
% output. Code generation must reject the model instead of emitting it.
%=============================================================================
model = [tempname(), '.nflow'];
json = ['{', ...
  '"version":"1.0.0","format":"nflow-2","name":"AlgLoopReject","sampleTime":0.1,', ...
  '"blocks":[', ...
  '{"id":"c","type":"constant","x":100,"y":100,"rotation":0,"params":{"Value":1}},', ...
  '{"id":"s","type":"sum","inputs":2,"outputs":1,"x":300,"y":100,"rotation":0,"params":{}},', ...
  '{"id":"g","type":"gain","x":500,"y":100,"rotation":0,"params":{"Gain":0.5}},', ...
  '{"id":"sc","type":"scope","x":700,"y":100,"rotation":0,"params":{}}', ...
  '],', ...
  '"connections":[{"from":"c","to":"s","fromIndex":0,"toIndex":0},', ...
  '{"from":"g","to":"s","fromIndex":0,"toIndex":1},', ...
  '{"from":"s","to":"g","fromIndex":0,"toIndex":0},', ...
  '{"from":"s","to":"sc","fromIndex":0,"toIndex":0}]', ...
  '}'];
fid = fopen(model, 'wt');
fwrite(fid, json);
fclose(fid);
%=============================================================================
expected = [_('Code generation: '), 'cannot solve the algebraic loop through or fed by ', ...
  'blocks ''s'', ''g'', ''sc'': the simulator iterates it to a fixed point but generated ', ...
  'code is straight-line. Break the loop with a unitDelay or memory block, or simulate ', ...
  'this model instead.'];
cmd = ['nflow_codegenerate(''', model, ''', tempdir(), false, ''C'')'];
assert_checkerror(cmd, expected);
%=============================================================================
% Same rejection for the Rust backend.
cmd = ['nflow_codegenerate(''', model, ''', tempdir(), false, ''rust'')'];
assert_checkerror(cmd, expected);
%=============================================================================
rmfile(model);
%=============================================================================
% Control: the same feedback loop broken by a unitDelay (a latched block) is
% NOT an algebraic loop -- the ordering resolves through the latch and
% generation must keep succeeding for both targets.
model = [tempname(), '.nflow'];
[~, modelstem] = fileparts(model);
json = ['{', ...
  '"version":"1.0.0","format":"nflow-2","name":"AlgLoopLatched","sampleTime":0.1,', ...
  '"blocks":[', ...
  '{"id":"c","type":"constant","x":100,"y":100,"rotation":0,"params":{"Value":1}},', ...
  '{"id":"s","type":"sum","inputs":2,"outputs":1,"x":300,"y":100,"rotation":0,"params":{}},', ...
  '{"id":"ud","type":"unitDelay","inputs":1,"outputs":1,"x":500,"y":100,"rotation":0,"params":{}},', ...
  '{"id":"g","type":"gain","x":500,"y":200,"rotation":0,"params":{"Gain":0.5}},', ...
  '{"id":"sc","type":"scope","x":700,"y":100,"rotation":0,"params":{}}', ...
  '],', ...
  '"connections":[{"from":"c","to":"s","fromIndex":0,"toIndex":0},', ...
  '{"from":"s","to":"ud","fromIndex":0,"toIndex":0},', ...
  '{"from":"ud","to":"g","fromIndex":0,"toIndex":0},', ...
  '{"from":"g","to":"s","fromIndex":0,"toIndex":1},', ...
  '{"from":"s","to":"sc","fromIndex":0,"toIndex":0}]', ...
  '}'];
fid = fopen(model, 'wt');
fwrite(fid, json);
fclose(fid);
%=============================================================================
nflow_codegenerate(model, tempdir(), false, 'C');
generated = [tempdir(), modelstem, '/model.c'];
assert_istrue(isfile(generated));
src = fileread(generated);
assert_istrue(isempty(strfind(src, 'unknown:')));
%=============================================================================
nflow_codegenerate(model, tempdir(), false, 'rust');
generatedRust = [tempdir(), modelstem, '/src/lib.rs'];
assert_istrue(isfile(generatedRust));
%=============================================================================
rmfile(model);
