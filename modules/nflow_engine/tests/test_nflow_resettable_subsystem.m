% B2 (resettable subsystem): a resettable subsystem runs every step; on a reset
% event (a control edge) all internal states return to their initial conditions.
% Inner counter (+1 per step). A rising reset edge at t=0.5 drops the counter
% back to its initial value, then it counts up again.
%=============================================================================
evalin('base', 'clear(''rs_out'')');

inner = struct();
inner.blocks = {...
  struct('id', 'one', 'type', 'constant', 'inputs', 0, 'outputs', 1, 'params', struct('Value', 1)), ...
  struct('id', 'acc', 'type', 'sum', 'inputs', 2, 'outputs', 1, 'params', struct('Inputs', '++')), ...
  struct('id', 'del', 'type', 'unitDelay', 'inputs', 1, 'outputs', 1, 'params', struct()), ...
  struct('id', 'cout', 'type', 'labelSink', 'inputs', 1, 'outputs', 1, ...
    'params', struct('gotoTag', 'y'))};
inner.connections = {...
  struct('from', 'one', 'to', 'acc', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'del', 'to', 'acc', 'fromIndex', 0, 'toIndex', 1), ...
  struct('from', 'acc', 'to', 'del', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'acc', 'to', 'cout', 'fromIndex', 0, 'toIndex', 0)};
inner.externalOutputs = {struct('id', 'cout', 'name', 'y')};
inner.controlPort = struct('kind', 'reset', 'resetTriggerType', 'rising');

d = struct();
d.blocks = {...
  struct('id', 'clk', 'type', 'clock', 'inputs', 0, 'outputs', 1, 'params', struct()), ...
  struct('id', 'rst', 'type', 'compareToConstant', 'inputs', 1, 'outputs', 1, ...
    'params', struct('relop', 'ge', 'const', 0.5)), ...   % rising reset edge at t=0.5
  struct('id', 'sub', 'type', 'subsystem', 'inputs', 1, 'outputs', 1, ...
    'params', struct('subsystem', inner, ...
    'controlPort', struct('kind', 'reset', 'resetTriggerType', 'rising'))), ...
  struct('id', 'tw', 'type', 'toWorkspace', 'inputs', 1, 'outputs', 0, ...
    'params', struct('VariableName', 'rs_out', 'SaveFormat', 'Array', ...
    'Decimation', 1, 'MaxDataPoints', 'inf'))};
d.connections = {...
  struct('from', 'clk', 'to', 'rst', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'rst', 'to', 'sub', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'sub', 'to', 'tw', 'fromIndex', 0, 'toIndex', 0)};
d.sampleTime = 0.1; d.duration = 1.0; d.variables = struct();

r = jsondecode(__nflow_simulate__(jsonencode(d)));
asserts.isequal(r.status, 'done');
v = evalin('base', 'rs_out');
v = v(:);
asserts.isequal(numel(v), 11);
% Counts up 1..5 over the first half.
asserts.isapprox(v(5), 5.0, 0, 1e-9); % t=0.4
% The reset edge at t=0.5 drops the counter back to its initial value.
asserts.isapprox(v(6), 1.0, 0, 1e-9); % t=0.5, reset
asserts.istrue(v(6) < v(5)); % the reset actually dropped it
% Then it counts up again.
asserts.istrue(v(end) > v(6));

evalin('base', 'clear(''rs_out'')');
