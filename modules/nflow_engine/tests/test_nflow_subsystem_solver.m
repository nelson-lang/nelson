% A2.1: a subsystem's internal continuous state must be integrated by the
% global solver, so a hierarchical diagram gives the SAME trajectory as the
% equivalent flattened one. Model: x' = -x, x(0) = 1  =>  x(t) = exp(-t).
%=============================================================================

evalin('base', 'clear(''flat_out'')');
evalin('base', 'clear(''hier_out'')');

% --- Flattened: integrator(init 1) -> gain(-1) -> back to the integrator ---
flat = struct();
flat.blocks = {...
  struct('id', 'int', 'type', 'integrator', 'inputs', 1, 'outputs', 1, ...
    'params', struct('InitialCondition', 1)), ...
  struct('id', 'g', 'type', 'gain', 'inputs', 1, 'outputs', 1, ...
    'params', struct('Gain', -1)), ...
  struct('id', 'tw', 'type', 'toWorkspace', 'inputs', 1, 'outputs', 0, ...
    'params', struct('VariableName', 'flat_out', 'SaveFormat', 'Structure With Time', ...
    'Decimation', 1, 'MaxDataPoints', 'inf'))};
flat.connections = {...
  struct('from', 'int', 'to', 'g', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'g', 'to', 'int', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'int', 'to', 'tw', 'fromIndex', 0, 'toIndex', 0)};
flat.sampleTime = 0.01; flat.duration = 1.0; flat.variables = struct(); flat.solver = 'ode4';
rF = jsondecode(__nflow_simulate__(jsonencode(flat)));
asserts.isequal(rF.status, 'done');

% --- Hierarchical: the same integrator+gain feedback inside a subsystem ---
inner = struct();
inner.blocks = {...
  struct('id', 'int', 'type', 'integrator', 'inputs', 1, 'outputs', 1, ...
    'params', struct('InitialCondition', 1)), ...
  struct('id', 'g', 'type', 'gain', 'inputs', 1, 'outputs', 1, ...
    'params', struct('Gain', -1)), ...
  struct('id', 'yout', 'type', 'labelSink', 'inputs', 1, 'outputs', 1, ...
    'params', struct('gotoTag', 'y'))};
inner.connections = {...
  struct('from', 'int', 'to', 'g', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'g', 'to', 'int', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'int', 'to', 'yout', 'fromIndex', 0, 'toIndex', 0)};
inner.externalOutputs = {struct('id', 'yout', 'name', 'y')};

hier = struct();
hier.blocks = {...
  struct('id', 'sub', 'type', 'subsystem', 'inputs', 0, 'outputs', 1, ...
    'params', struct('subsystem', inner)), ...
  struct('id', 'tw', 'type', 'toWorkspace', 'inputs', 1, 'outputs', 0, ...
    'params', struct('VariableName', 'hier_out', 'SaveFormat', 'Structure With Time', ...
    'Decimation', 1, 'MaxDataPoints', 'inf'))};
hier.connections = {struct('from', 'sub', 'to', 'tw', 'fromIndex', 0, 'toIndex', 0)};
hier.sampleTime = 0.01; hier.duration = 1.0; hier.variables = struct(); hier.solver = 'ode4';
rH = jsondecode(__nflow_simulate__(jsonencode(hier)));
asserts.isequal(rH.status, 'done');

flat_out = evalin('base', 'flat_out');
hier_out = evalin('base', 'hier_out');
vf = flat_out.signals.values(:);
vh = hier_out.signals.values(:);

% Both must match the analytic solution exp(-t) at t = 1...
asserts.isapprox(vf(end), exp(-1.0), 0, 1e-4);
asserts.isapprox(vh(end), exp(-1.0), 0, 1e-4);
% ...and, crucially, the hierarchical trajectory must equal the flattened one.
asserts.isequal(numel(vf), numel(vh));
asserts.isapprox(vh, vf, 0, 1e-9);

evalin('base', 'clear(''flat_out'')');
evalin('base', 'clear(''hier_out'')');
