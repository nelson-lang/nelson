% DAE (IDAS) backend. solver = "dae" routes the simulation
% through the RHS-based solver loop to the IDAS backend (OdeCore::IdasSession).
% The loop assembles the residual F(t,x,x') = x' - f(x,u) (every state
% differential), so an ODE model runs through IDAS in residual form and matches
% the explicit ode4 trajectory. A model with no continuous state has no residual
% and reports a clear error.
%=============================================================================
function p = dae_write(json, stem)
  p = [tempname(), '.nflow'];
  fid = fopen(p, 'w'); fwrite(fid, json); fclose(fid);
end
%=============================================================================
function j = dae_ramp_model(solver)
  % Integrator of a constant 1 (x' = 1, x0 = 0) -> x(t) = t.
  j = ['{"blocks":[', ...
    '{"id":"c","type":"constant","inputs":0,"outputs":1,"params":{"Value":1}},', ...
    '{"id":"ig","type":"integrator","inputs":1,"outputs":1,"params":{"InitialCondition":0}},', ...
    '{"id":"tw","type":"toWorkspace","inputs":1,"outputs":0,"params":{"VariableName":"y"}}],', ...
    '"connections":[', ...
      '{"from":"c","to":"ig","fromIndex":0,"toIndex":0},', ...
      '{"from":"ig","to":"tw","fromIndex":0,"toIndex":0}],', ...
    '"solver":"', solver, '","runtime":1.0,"sampleTime":0.1}'];
end
%=============================================================================
% The DAE backend integrates the ODE model and matches ode4 / the analytical
% ramp x(t) = t (x(0.5) = 0.5, x(1) = 1).
outDae = sim(dae_write(dae_ramp_model('dae'), 'test_nflow_dae_ramp'));
vDae = outDae.logsout(1).values;
assert_istrue(abs(vDae(end) - 1.0) < 1e-6);
assert_istrue(abs(vDae(round(numel(vDae) / 2)) - 0.5) < 1e-6);

outOde4 = sim(dae_write(dae_ramp_model('ode4'), 'test_nflow_dae_ode4'));
vOde4 = outOde4.logsout(1).values;
assert_istrue(max(abs(vDae(:) - vOde4(:))) < 1e-5); % dae matches ode4
%=============================================================================
% A model with no continuous state has no residual -> clear error.
noState = ['{"blocks":[', ...
  '{"id":"c","type":"constant","inputs":0,"outputs":1,"params":{"Value":1}},', ...
  '{"id":"g","type":"gain","inputs":1,"outputs":1,"params":{"Gain":2}},', ...
  '{"id":"tw","type":"toWorkspace","inputs":1,"outputs":0,"params":{"VariableName":"y"}}],', ...
  '"connections":[', ...
    '{"from":"c","to":"g","fromIndex":0,"toIndex":0},', ...
    '{"from":"g","to":"tw","fromIndex":0,"toIndex":0}],', ...
  '"solver":"dae","runtime":0.5,"sampleTime":0.1}'];
msg = '';
try
  sim(dae_write(noState, 'test_nflow_dae_nostate'));
catch e
  msg = e.message;
end
assert_istrue(~isempty(strfind(msg, 'residual')) || ~isempty(strfind(msg, 'continuous')));
%=============================================================================
% Genuine index-1 DAE: a differential state x' = -x (x0 = 1) plus an
% algebraic constraint block cz whose input g = z - 3x is driven to zero, so the
% algebraic state z = 3x. Expect x(1) = e^{-1} and z = 3x throughout.
constraintModel = ['{"blocks":[', ...
  '{"id":"ig","type":"integrator","inputs":1,"outputs":1,"params":{"InitialCondition":1}},', ...
  '{"id":"gm1","type":"gain","inputs":1,"outputs":1,"params":{"Gain":-1}},', ...
  '{"id":"gm3","type":"gain","inputs":1,"outputs":1,"params":{"Gain":-3}},', ...
  '{"id":"cz","type":"constraint","inputs":1,"outputs":1,"params":{"InitialCondition":3}},', ...
  '{"id":"sg","type":"sum","inputs":2,"outputs":1,"params":{}},', ...
  '{"id":"twx","type":"toWorkspace","inputs":1,"outputs":0,"params":{"VariableName":"x"}},', ...
  '{"id":"twz","type":"toWorkspace","inputs":1,"outputs":0,"params":{"VariableName":"z"}}],', ...
  '"connections":[', ...
  '{"from":"ig","to":"gm1","fromIndex":0,"toIndex":0},', ...
  '{"from":"gm1","to":"ig","fromIndex":0,"toIndex":0},', ...
  '{"from":"ig","to":"gm3","fromIndex":0,"toIndex":0},', ...
  '{"from":"cz","to":"sg","fromIndex":0,"toIndex":0},', ...
  '{"from":"gm3","to":"sg","fromIndex":0,"toIndex":1},', ...
  '{"from":"sg","to":"cz","fromIndex":0,"toIndex":0},', ...
  '{"from":"ig","to":"twx","fromIndex":0,"toIndex":0},', ...
  '{"from":"cz","to":"twz","fromIndex":0,"toIndex":0}],', ...
  '"solver":"dae","runtime":1.0,"sampleTime":0.1}'];
outC = sim(dae_write(constraintModel, 'test_nflow_dae_constraint'));
lc = outC.logsout;
ncn = {lc.name};
vx = lc(find(strcmp(ncn, 'x'), 1)).values;
vz = lc(find(strcmp(ncn, 'z'), 1)).values;
assert_istrue(abs(vx(end) - exp(-1)) < 1e-5); % differential state
assert_istrue(max(abs(vz(:) - 3 * vx(:))) < 1e-5); % algebraic constraint z = 3x
%=============================================================================
% A charging RC circuit as an index-1 DAE (a real acausal physical model): a
% differential capacitor voltage v_c (C v_c' = i, C = 1) and an algebraic current
% i defined by KVL v_s - R i - v_c = 0 (v_s = 1, R = 1). Exact charging curve
% v_c(t) = 1 - e^{-t}, current i(t) = e^{-t}.
rc = ['{"blocks":[', ...
  '{"id":"vs","type":"constant","inputs":0,"outputs":1,"params":{"Value":1}},', ...
  '{"id":"vc","type":"integrator","inputs":1,"outputs":1,"params":{"InitialCondition":0}},', ...
  '{"id":"ci","type":"constraint","inputs":1,"outputs":1,"params":{"InitialCondition":1}},', ...
  '{"id":"gni","type":"gain","inputs":1,"outputs":1,"params":{"Gain":-1}},', ...
  '{"id":"gnvc","type":"gain","inputs":1,"outputs":1,"params":{"Gain":-1}},', ...
  '{"id":"sg","type":"sum","inputs":3,"outputs":1,"params":{}},', ...
  '{"id":"twvc","type":"toWorkspace","inputs":1,"outputs":0,"params":{"VariableName":"vc"}},', ...
  '{"id":"twi","type":"toWorkspace","inputs":1,"outputs":0,"params":{"VariableName":"i"}}],', ...
  '"connections":[', ...
  '{"from":"ci","to":"vc","fromIndex":0,"toIndex":0},', ...
  '{"from":"ci","to":"gni","fromIndex":0,"toIndex":0},', ...
  '{"from":"vc","to":"gnvc","fromIndex":0,"toIndex":0},', ...
  '{"from":"vs","to":"sg","fromIndex":0,"toIndex":0},', ...
  '{"from":"gni","to":"sg","fromIndex":0,"toIndex":1},', ...
  '{"from":"gnvc","to":"sg","fromIndex":0,"toIndex":2},', ...
  '{"from":"sg","to":"ci","fromIndex":0,"toIndex":0},', ...
  '{"from":"vc","to":"twvc","fromIndex":0,"toIndex":0},', ...
  '{"from":"ci","to":"twi","fromIndex":0,"toIndex":0}],', ...
  '"solver":"dae","runtime":1.0,"sampleTime":0.1}'];
outR = sim(dae_write(rc, 'test_nflow_dae_rc'));
lr = outR.logsout;
nr = {lr.name};
vc = lr(find(strcmp(nr, 'vc'), 1)).values;
ii = lr(find(strcmp(nr, 'i'), 1)).values;
assert_istrue(abs(vc(end) - (1 - exp(-1))) < 1e-5); % v_c(1) = 1 - e^{-1}
assert_istrue(abs(ii(end) - exp(-1)) < 1e-5); % i(1) = e^{-1}
%=============================================================================
% P1.1 (Part A): a DISCONTINUOUS source driving the same index-1 RC island.
% A step source (v_s = 0 for t < 0.5, then 1) makes the algebraic branch current
% jump at t = 0.5; without recomputing consistent initial conditions on the
% solver cold-restart (IDACalcIC in IdasSession::reinit) IDA fails its first
% post-jump step. v_c stays 0 until 0.5, then charges 1 - e^{-(t-0.5)}; at t = 1
% v_c = 1 - e^{-0.5} (~0.3935). The step lands exactly on a 0.05 sample, so the
% root==output-time path (consistent-state pull after reinit) is exercised too.
rcStep = ['{"blocks":[', ...
  '{"id":"vs","type":"step","inputs":0,"outputs":1,"params":{"Time":0.5}},', ...
  '{"id":"vc","type":"integrator","inputs":1,"outputs":1,"params":{"InitialCondition":0}},', ...
  '{"id":"ci","type":"constraint","inputs":1,"outputs":1,"params":{"InitialCondition":0}},', ...
  '{"id":"gni","type":"gain","inputs":1,"outputs":1,"params":{"Gain":-1}},', ...
  '{"id":"gnvc","type":"gain","inputs":1,"outputs":1,"params":{"Gain":-1}},', ...
  '{"id":"sg","type":"sum","inputs":3,"outputs":1,"params":{}},', ...
  '{"id":"twvc","type":"toWorkspace","inputs":1,"outputs":0,"params":{"VariableName":"vcs"}},', ...
  '{"id":"twi","type":"toWorkspace","inputs":1,"outputs":0,"params":{"VariableName":"is"}}],', ...
  '"connections":[', ...
  '{"from":"ci","to":"vc","fromIndex":0,"toIndex":0},', ...
  '{"from":"ci","to":"gni","fromIndex":0,"toIndex":0},', ...
  '{"from":"vc","to":"gnvc","fromIndex":0,"toIndex":0},', ...
  '{"from":"vs","to":"sg","fromIndex":0,"toIndex":0},', ...
  '{"from":"gni","to":"sg","fromIndex":0,"toIndex":1},', ...
  '{"from":"gnvc","to":"sg","fromIndex":0,"toIndex":2},', ...
  '{"from":"sg","to":"ci","fromIndex":0,"toIndex":0},', ...
  '{"from":"vc","to":"twvc","fromIndex":0,"toIndex":0},', ...
  '{"from":"ci","to":"twi","fromIndex":0,"toIndex":0}],', ...
  '"solver":"dae","runtime":1.0,"sampleTime":0.05}'];
outS = sim(dae_write(rcStep, 'test_nflow_dae_rc_step')); % must not error at t = 0.5
ls = outS.logsout;
ns = {ls.name};
ts = ls(find(strcmp(ns, 'vcs'), 1)).time;
vcs = ls(find(strcmp(ns, 'vcs'), 1)).values;
kBefore = find(ts < 0.5 - 1e-9, 1, 'last');
assert_istrue(abs(vcs(kBefore)) < 1e-3); % v_c ~ 0 before the step
assert_istrue(abs(vcs(end) - (1 - exp(-0.5))) < 1e-3); % v_c(1) = 1 - e^{-0.5}
%=============================================================================
% P1.1 (Part B): a SQUARE wave (sign-based, flips every half period) driving the
% RC island. Each edge is a scheduled discontinuity where the algebraic current
% reverses; the solver stops just before every edge and restarts consistently.
% With R = C = 1 and a 1 Hz square (half period 0.5), v_c charges toward the
% source on each half-period. A square wave opens its period on the LOW half,
% so the first half-period discharges: v_c(0.5^-) = -(1 - e^{-0.5}) (~-0.3935),
% then it charges. The whole trajectory must stay finite and bounded.
rcSq = ['{"blocks":[', ...
  '{"id":"vs","type":"signalGenerator","inputs":0,"outputs":1,', ...
    '"params":{"Waveform":"square","Frequency":1,"Amplitude":1}},', ...
  '{"id":"vc","type":"integrator","inputs":1,"outputs":1,"params":{"InitialCondition":0}},', ...
  '{"id":"ci","type":"constraint","inputs":1,"outputs":1,"params":{"InitialCondition":1}},', ...
  '{"id":"gni","type":"gain","inputs":1,"outputs":1,"params":{"Gain":-1}},', ...
  '{"id":"gnvc","type":"gain","inputs":1,"outputs":1,"params":{"Gain":-1}},', ...
  '{"id":"sg","type":"sum","inputs":3,"outputs":1,"params":{}},', ...
  '{"id":"twvc","type":"toWorkspace","inputs":1,"outputs":0,"params":{"VariableName":"vcq"}}],', ...
  '"connections":[', ...
  '{"from":"ci","to":"vc","fromIndex":0,"toIndex":0},', ...
  '{"from":"ci","to":"gni","fromIndex":0,"toIndex":0},', ...
  '{"from":"vc","to":"gnvc","fromIndex":0,"toIndex":0},', ...
  '{"from":"vs","to":"sg","fromIndex":0,"toIndex":0},', ...
  '{"from":"gni","to":"sg","fromIndex":0,"toIndex":1},', ...
  '{"from":"gnvc","to":"sg","fromIndex":0,"toIndex":2},', ...
  '{"from":"sg","to":"ci","fromIndex":0,"toIndex":0},', ...
  '{"from":"vc","to":"twvc","fromIndex":0,"toIndex":0}],', ...
  '"solver":"dae","runtime":2.0,"sampleTime":0.02}'];
outQ = sim(dae_write(rcSq, 'test_nflow_dae_rc_square')); % must not error at any edge
lq = outQ.logsout;
nq = {lq.name};
tq = lq(find(strcmp(nq, 'vcq'), 1)).time;
vcq = lq(find(strcmp(nq, 'vcq'), 1)).values;
assert_istrue(all(isfinite(vcq(:)))); % no NaN / Inf across the edges
assert_istrue(max(abs(vcq(:))) < 1.0); % bounded by the source amplitude
kHalf = find(abs(tq - 0.5) < 1e-9, 1);
assert_istrue(abs(vcq(kHalf) + (1 - exp(-0.5))) < 5e-3); % first (low) half-period peak
assert_istrue((max(vcq(:)) - min(vcq(:))) > 0.3); % it actually oscillates
