% A1.1 / A1.2: robust algebraic-loop resolution.
%   A1.1: a legitimate direct-feedback loop converges (numeric tolerance),
%         instead of raising a spurious "did not converge" hard error.
%   A1.2: an algebraic loop nested inside a continuous dynamic is solved to
%         convergence at each RHS evaluation, so the trajectory matches the
%         analytic solution under a global solver (ode4).
%=============================================================================

%=============================================================================
% A1.1: s = u - 0.5*s  =>  s = u / 1.5 = 2 for u = 3. The gain output feeds
% back into the sum, forming a direct algebraic loop.
%=============================================================================
evalin('base', 'clear(''alg_out'')');
dA = struct();
dA.blocks = {...
  struct('id', 'u', 'type', 'constant', 'inputs', 0, 'outputs', 1, ...
    'params', struct('Value', 3)), ...
  struct('id', 's', 'type', 'sum', 'inputs', 2, 'outputs', 1, ...
    'params', struct('Inputs', '+-')), ...
  struct('id', 'g', 'type', 'gain', 'inputs', 1, 'outputs', 1, ...
    'params', struct('Gain', 0.5)), ...
  struct('id', 'tw', 'type', 'toWorkspace', 'inputs', 1, 'outputs', 0, ...
    'params', struct('VariableName', 'alg_out', 'SaveFormat', 'Array', ...
    'Decimation', 1, 'MaxDataPoints', 'inf'))};
dA.connections = {...
  struct('from', 'u', 'to', 's', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'g', 'to', 's', 'fromIndex', 0, 'toIndex', 1), ...
  struct('from', 's', 'to', 'g', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 's', 'to', 'tw', 'fromIndex', 0, 'toIndex', 0)};
dA.sampleTime = 0.1; dA.duration = 1.0; dA.variables = struct();
rA = jsondecode(__nflow_simulate__(jsonencode(dA)));
asserts.isequal(rA.status, 'done'); % converged, no hard algebraic-loop error
alg_out = evalin('base', 'alg_out');
asserts.isapprox(alg_out(end), 2.0, 0, 1e-7);

%=============================================================================
% A1.2: integrator x with x' = a, where a is a nested algebraic loop:
%   s1 = r - x ;  a = s1 - 0.5*a  =>  a = s1 / 1.5 = (r - x)/1.5.
% So x' = (r - x)/1.5, i.e. x(t) = r*(1 - exp(-t/1.5)) for x(0) = 0, r = 1.
% Under ode4 the RHS must solve the loop to convergence for the trajectory to
% match; a single algebraic pass would be silently wrong.
%=============================================================================
evalin('base', 'clear(''alg_traj'')');
dB = struct();
dB.blocks = {...
  struct('id', 'r', 'type', 'constant', 'inputs', 0, 'outputs', 1, ...
    'params', struct('Value', 1)), ...
  struct('id', 'x', 'type', 'integrator', 'inputs', 1, 'outputs', 1, ...
    'params', struct('InitialCondition', 0)), ...
  struct('id', 's1', 'type', 'sum', 'inputs', 2, 'outputs', 1, ...
    'params', struct('Inputs', '+-')), ...
  struct('id', 's2', 'type', 'sum', 'inputs', 2, 'outputs', 1, ...
    'params', struct('Inputs', '+-')), ...
  struct('id', 'g2', 'type', 'gain', 'inputs', 1, 'outputs', 1, ...
    'params', struct('Gain', 0.5)), ...
  struct('id', 'tw', 'type', 'toWorkspace', 'inputs', 1, 'outputs', 0, ...
    'params', struct('VariableName', 'alg_traj', 'SaveFormat', 'Structure With Time', ...
    'Decimation', 1, 'MaxDataPoints', 'inf'))};
dB.connections = {...
  struct('from', 'r', 'to', 's1', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'x', 'to', 's1', 'fromIndex', 0, 'toIndex', 1), ...
  struct('from', 's1', 'to', 's2', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'g2', 'to', 's2', 'fromIndex', 0, 'toIndex', 1), ...
  struct('from', 's2', 'to', 'g2', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 's2', 'to', 'x', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'x', 'to', 'tw', 'fromIndex', 0, 'toIndex', 0)};
dB.sampleTime = 0.01; dB.duration = 1.0; dB.variables = struct(); dB.solver = 'ode4';
rB = jsondecode(__nflow_simulate__(jsonencode(dB)));
asserts.isequal(rB.status, 'done');
alg_traj = evalin('base', 'alg_traj');
xend = alg_traj.signals.values(end);
beta = 1.0 / 1.5;
asserts.isapprox(xend, 1.0 - exp(-beta * 1.0), 0, 1e-4);

evalin('base', 'clear(''alg_out'')');
evalin('base', 'clear(''alg_traj'')');
