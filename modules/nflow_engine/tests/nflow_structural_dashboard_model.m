function d = nflow_structural_dashboard_model()
  binding = struct('kind', 'parameter', 'blockPath', {{'delay'}}, ...
    'paramName', 'DelayTime', 'element', '');
  d = struct();
  d.blocks = {...
    struct('id', 'source', 'type', 'constant', 'inputs', 0, 'outputs', 1, ...
      'params', struct('Value', 2)), ...
    struct('id', 'delay', 'type', 'delay', 'inputs', 1, 'outputs', 1, ...
      'params', struct('DelayTime', 0.1)), ...
    struct('id', 'y', 'type', 'labelSink', 'inputs', 1, 'outputs', 0, ...
      'params', struct('label', 'y')), ...
    struct('id', 'delay_control', 'type', 'dashboardSlider', 'inputs', 0, 'outputs', 0, ...
      'params', struct('Binding', binding, 'DashboardValue', 0.1))};
  d.connections = {...
    struct('from', 'source', 'to', 'delay', 'fromIndex', 0, 'toIndex', 0), ...
    struct('from', 'delay', 'to', 'y', 'fromIndex', 0, 'toIndex', 0)};
  d.sampleTime = 0.1;
  d.duration = 0.2;
  d.variables = struct();
end
