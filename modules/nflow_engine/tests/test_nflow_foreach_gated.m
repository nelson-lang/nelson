% A for-each subsystem that ALSO carries a control port. Its branch returned
% before the gate was ever read, so the gate was accepted and then ignored: the
% body ran every step whatever the control said, in all three phases. A gate
% that is written and then dropped in silence is the worst of the three
% possible behaviours - worse than refusing it - so it is honoured now, the way
% composing a for-each inside a gated subsystem would behave.
%
% Code generation follows for free: the flattener inlines the body once with
% its vector wires and the vector-expansion pass makes one scalar replica per
% element, each carrying the gate chain like any other member.
%=============================================================================
function d = fe_doc(varName, gated)
  inner = struct();
  inner.blocks = {...
    struct('id', 'in1', 'type', 'labelSource', 'inputs', 0, 'outputs', 1, ...
      'params', struct('label', 'in1')), ...
    struct('id', 'dl', 'type', 'unitDelay', 'inputs', 1, 'outputs', 1, ...
      'params', struct('InitialCondition', 0)), ...
    struct('id', 'ad', 'type', 'sum', 'inputs', 2, 'outputs', 1, ...
      'params', struct('Inputs', '++')), ...
    struct('id', 'out1', 'type', 'labelSink', 'inputs', 1, 'outputs', 1, ...
      'params', struct('label', 'out1'))};
  inner.connections = {...
    struct('from', 'in1', 'to', 'ad', 'fromIndex', 0, 'toIndex', 0), ...
    struct('from', 'dl', 'to', 'ad', 'fromIndex', 0, 'toIndex', 1), ...
    struct('from', 'ad', 'to', 'dl', 'fromIndex', 0, 'toIndex', 0), ...
    struct('from', 'ad', 'to', 'out1', 'fromIndex', 0, 'toIndex', 0)};
  inner.externalInputs = {struct('id', 'in1', 'name', 'in1')};
  inner.externalOutputs = {struct('id', 'out1', 'name', 'out1')};
  subParams = struct('subsystem', inner, ...
    'forEach', struct('numIterations', 3, 'partition', {{0}}));
  nin = 1;
  if gated
    inner.controlPort = struct('kind', 'enable');
    subParams = struct('subsystem', inner, ...
      'controlPort', struct('kind', 'enable'), ...
      'forEach', struct('numIterations', 3, 'partition', {{0}}));
    nin = 2;
  end
  blocks = {...
    struct('id', 'c1', 'type', 'constant', 'inputs', 0, 'outputs', 1, ...
      'params', struct('Value', 1)), ...
    struct('id', 'c2', 'type', 'constant', 'inputs', 0, 'outputs', 1, ...
      'params', struct('Value', 2)), ...
    struct('id', 'c3', 'type', 'constant', 'inputs', 0, 'outputs', 1, ...
      'params', struct('Value', 3)), ...
    struct('id', 'mx', 'type', 'mux', 'inputs', 3, 'outputs', 1, ...
      'params', struct('Inputs', 3)), ...
    struct('id', 'e', 'type', 'pulse', 'inputs', 0, 'outputs', 1, ...
      'params', struct('Amplitude', 1, 'Period', 0.4, 'Width', 50.0, ...
        'StartTime', 0, 'Offset', 0)), ...
    struct('id', 's', 'type', 'subsystem', 'inputs', nin, 'outputs', 1, ...
      'params', subParams), ...
    struct('id', 'dm', 'type', 'demux', 'inputs', 1, 'outputs', 3, ...
      'params', struct('Outputs', 3)), ...
    struct('id', 'y', 'type', 'labelSink', 'inputs', 1, 'outputs', 1, ...
      'params', struct('GotoTag', 'y', 'isExternalPort', true)), ...
    struct('id', 'tw', 'type', 'toWorkspace', 'inputs', 1, 'outputs', 0, ...
      'params', struct('VariableName', varName, 'SaveFormat', 'Array', ...
        'Decimation', 1, 'MaxDataPoints', 'inf'))};
  conns = {...
    struct('from', 'c1', 'to', 'mx', 'fromIndex', 0, 'toIndex', 0), ...
    struct('from', 'c2', 'to', 'mx', 'fromIndex', 0, 'toIndex', 1), ...
    struct('from', 'c3', 'to', 'mx', 'fromIndex', 0, 'toIndex', 2), ...
    struct('from', 'mx', 'to', 's', 'fromIndex', 0, 'toIndex', 0), ...
    struct('from', 's', 'to', 'dm', 'fromIndex', 0, 'toIndex', 0), ...
    struct('from', 'dm', 'to', 'y', 'fromIndex', 1, 'toIndex', 0), ...
    struct('from', 'dm', 'to', 'tw', 'fromIndex', 1, 'toIndex', 0)};
  if gated
    conns{end + 1} = struct('from', 'e', 'to', 's', 'fromIndex', 0, 'toIndex', 1);
  end
  d = struct();
  d.blocks = blocks;
  d.connections = conns;
  d.sampleTime = 0.1;
  d.duration = 1.0;
  d.variables = struct();
end
%=============================================================================
% Ungated: channel 2 accumulates 2 per step, unchanged by any of this.
dU = fe_doc('nffe_u', false);
rU = jsondecode(__nflow_simulate__(jsonencode(dU)));
assert_isequal(rU.status, 'done');
yU = evalin('base', 'nffe_u'); yU = yU(:)';
assert_istrue(max(abs(yU(1:6) - [2 4 6 8 10 12])) < 1e-9);
evalin('base', 'clear(''nffe_u'')');
%=============================================================================
% Gated by a pulse of period 0.4 s at a step of 0.1: two steps on, two off.
% The accumulation stops while the gate is shut instead of running through it.
dG = fe_doc('nffe_g', true);
rG = jsondecode(__nflow_simulate__(jsonencode(dG)));
assert_isequal(rG.status, 'done');
yG = evalin('base', 'nffe_g'); yG = yG(:)';
assert_istrue(max(abs(yG(1:6) - [2 4 4 4 6 8])) < 1e-9);
evalin('base', 'clear(''nffe_g'')');
%=============================================================================
if __nflow_codegen_toolchain__('C')
  nflow_codegen_check_numeric(dU, 'nffe_un', 'C', {'y'}, {'nffe_u'}, 5e-6, 1e-9);
  nflow_codegen_check_numeric(dG, 'nffe_gn', 'C', {'y'}, {'nffe_g'}, 5e-6, 1e-9);
  if __nflow_codegen_toolchain__('rust')
    nflow_codegen_check_numeric(dG, 'nffe_gn', 'rust', {'y'}, {'nffe_g'}, 5e-6, 1e-9);
  end
end
%=============================================================================
% A for-ITERATOR is a different thing and keeps its reject: its body runs N
% times WITHIN one step, carrying state from one iteration to the next, while
% the flattener inlines a body once. Measured, not assumed: let through, a
% 3-iteration accumulator generated code adding 1 per step where the simulation
% adds 3.
innerI = struct();
innerI.blocks = {...
  struct('id', 'in1', 'type', 'labelSource', 'inputs', 0, 'outputs', 1, ...
    'params', struct('label', 'in1')), ...
  struct('id', 'dl', 'type', 'unitDelay', 'inputs', 1, 'outputs', 1, ...
    'params', struct('InitialCondition', 0)), ...
  struct('id', 'ad', 'type', 'sum', 'inputs', 2, 'outputs', 1, ...
    'params', struct('Inputs', '++')), ...
  struct('id', 'out1', 'type', 'labelSink', 'inputs', 1, 'outputs', 1, ...
    'params', struct('label', 'out1'))};
innerI.connections = {...
  struct('from', 'in1', 'to', 'ad', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'dl', 'to', 'ad', 'fromIndex', 0, 'toIndex', 1), ...
  struct('from', 'ad', 'to', 'dl', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'ad', 'to', 'out1', 'fromIndex', 0, 'toIndex', 0)};
innerI.externalInputs = {struct('id', 'in1', 'name', 'in1')};
innerI.externalOutputs = {struct('id', 'out1', 'name', 'out1')};
innerI.controlPort = struct('kind', 'forIterator', 'IterationLimit', 3, ...
  'ResetStates', 'held');
dI = struct();
dI.blocks = {...
  struct('id', 'u', 'type', 'constant', 'inputs', 0, 'outputs', 1, ...
    'params', struct('Value', 1)), ...
  struct('id', 's', 'type', 'subsystem', 'inputs', 1, 'outputs', 1, ...
    'params', struct('subsystem', innerI, 'controlPort', ...
      struct('kind', 'forIterator', 'IterationLimit', 3, 'ResetStates', 'held'))), ...
  struct('id', 'tw', 'type', 'toWorkspace', 'inputs', 1, 'outputs', 0, ...
    'params', struct('VariableName', 'nffe_i', 'SaveFormat', 'Array', ...
      'Decimation', 1, 'MaxDataPoints', 'inf'))};
dI.connections = {...
  struct('from', 'u', 'to', 's', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 's', 'to', 'tw', 'fromIndex', 0, 'toIndex', 0)};
dI.sampleTime = 0.1;
dI.duration = 0.5;
dI.variables = struct();
rI = jsondecode(__nflow_simulate__(jsonencode(dI)));
assert_isequal(rI.status, 'done');
yI = evalin('base', 'nffe_i'); yI = yI(:)';
assert_istrue(max(abs(yI(1:3) - [3 6 9])) < 1e-9); % three iterations per step
evalin('base', 'clear(''nffe_i'')');
fI = [tempname(), '.nflow'];
fid = fopen(fI, 'wt');
fwrite(fid, jsonencode(dI));
fclose(fid);
msgI = '';
try
  nflow_codegenerate(fI, tempdir(), false, 'C');
catch eI
  msgI = eI.message;
end
rmfile(fI);
assert_istrue(~isempty(strfind(lower(msgI), 'conditional')));
