function d = nflow_dashboard_model()
  parameterBinding = struct('kind', 'parameter', 'blockPath', {{'gain'}}, ...
    'paramName', 'Gain', 'element', '');
  signalBinding = struct('kind', 'signal', 'blockPath', {{'gain'}}, ...
    'outputPortIndex', 1, 'frameProcessingMode', 'sample');
  d = struct();
  d.blocks = {...
    struct('id', 'source', 'type', 'constant', 'inputs', 0, 'outputs', 1, ...
      'params', struct('Value', 2)), ...
    struct('id', 'gain', 'type', 'gain', 'inputs', 1, 'outputs', 1, ...
      'params', struct('Gain', 3)), ...
    struct('id', 'y', 'type', 'labelSink', 'inputs', 1, 'outputs', 0, ...
      'params', struct('label', 'y')), ...
    struct('id', 'legacy_display', 'type', 'display', 'inputs', 1, 'outputs', 0, ...
      'params', struct()), ...
    struct('id', 'control_ui', 'type', 'dashboardSlider', 'inputs', 0, 'outputs', 0, ...
      'params', struct('Binding', parameterBinding, 'DashboardValue', 3)), ...
    struct('id', 'display_ui', 'type', 'dashboardDisplay', 'inputs', 0, 'outputs', 0, ...
      'params', struct('Binding', signalBinding, 'Format', 'short'))};
  d.connections = {...
    struct('from', 'source', 'to', 'gain', 'fromIndex', 0, 'toIndex', 0), ...
    struct('from', 'gain', 'to', 'y', 'fromIndex', 0, 'toIndex', 0), ...
    struct('from', 'gain', 'to', 'legacy_display', 'fromIndex', 0, 'toIndex', 0)};
  d.sampleTime = 0.1;
  d.duration = 0.2;
  d.variables = struct();
end
