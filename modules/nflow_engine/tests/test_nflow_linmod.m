% linmod: numerical linearization about the post-INIT operating
% point. The expected result is analytical; a linear model linearizes to itself, so the
% returned A, B, C, D match the block's own matrices to finite-difference
% precision. The model input is an external-port label source (isExternalPort).
%=============================================================================
function f = write_model(blocks, connections)
  d = struct('blocks', {blocks}, 'connections', {connections}, ...
    'sampleTime', 0.01, 'runtime', 1.0, 'variables', struct());
  f = [tempname(), '.nflow'];
  fid = fopen(f, 'wt');
  fwrite(fid, jsonencode(d));
  fclose(fid);
end
%=============================================================================
function blocks = ss_model(ssblock)
  % No scope block: the model's output is a Label Sink; linmod auto-injects the
  % scope the engine requires.
  blocks = {...
    struct('id', 'u', 'type', 'labelSource', 'inputs', 0, 'outputs', 1, ...
      'params', struct('label', 'u', 'isExternalPort', true)), ...
    ssblock, ...
    struct('id', 'y', 'type', 'labelSink', 'inputs', 1, 'outputs', 0, ...
      'params', struct('label', 'y'))};
end
%=============================================================================
function conns = ss_conns()
  conns = {...
    struct('from', 'u', 'to', 'ss', 'fromIndex', 0, 'toIndex', 0), ...
    struct('from', 'ss', 'to', 'y', 'fromIndex', 0, 'toIndex', 0)};
end
%=============================================================================
% Scalar SISO state space: A=-2, B=1, C=1, D=0.5 -> linmod returns them exactly.
ss1 = struct('id', 'ss', 'type', 'stateSpace', 'inputs', 1, 'outputs', 1, ...
  'params', struct('A', -2, 'B', 1, 'C', 1, 'D', 0.5));
f = write_model(ss_model(ss1), ss_conns());
[A, B, C, D] = linmod(f);
assert_isequal(size(A), [1 1]);
assert_istrue(abs(A - (-2)) < 1e-6);
assert_istrue(abs(B - 1) < 1e-6);
assert_istrue(abs(C - 1) < 1e-6);
assert_istrue(abs(D - 0.5) < 1e-6);
% Operating-point arguments are accepted; a linear model's Jacobians do not
% depend on the point, so A/B/C/D are unchanged.
[Ap, Bp, Cp, Dp] = linmod(f, 3, 2);
assert_istrue(abs(Ap - (-2)) < 1e-6);
assert_istrue(abs(Bp - 1) < 1e-6);
assert_istrue(abs(Cp - 1) < 1e-6);
assert_istrue(abs(Dp - 0.5) < 1e-6);
%=============================================================================
% 2x2 state space A = [0 1; -2 -3], B = [0; 1], C = [1 0], D = 0.
ss2 = struct('id', 'ss', 'type', 'stateSpace', 'inputs', 1, 'outputs', 1, ...
  'params', struct('A', {{0, 1, -2, -3}}, 'B', {{0, 1}}, 'C', {{1, 0}}, 'D', 0));
f = write_model(ss_model(ss2), ss_conns());
[A2, B2, C2, D2] = linmod(f);
assert_isequal(size(A2), [2 2]);
assert_istrue(max(abs(A2(:) - [0; -2; 1; -3])) < 1e-6); % column-major of [0 1;-2 -3]
assert_istrue(max(abs(B2(:) - [0; 1])) < 1e-6);
assert_istrue(max(abs(C2(:) - [1; 0])) < 1e-6);
assert_istrue(abs(D2) < 1e-6);
%=============================================================================
% A plain integrator: xdot = u (state), y = x -> A = 0, B = 1, C = 1, D = 0.
blocks = {...
  struct('id', 'u', 'type', 'labelSource', 'inputs', 0, 'outputs', 1, ...
    'params', struct('label', 'u', 'isExternalPort', true)), ...
  struct('id', 'ig', 'type', 'integrator', 'inputs', 1, 'outputs', 1, 'params', struct()), ...
  struct('id', 'y', 'type', 'labelSink', 'inputs', 1, 'outputs', 0, ...
    'params', struct('label', 'y')), ...
  struct('id', 'sc', 'type', 'scope', 'inputs', 1, 'outputs', 0, 'params', struct())};
conns = {...
  struct('from', 'u', 'to', 'ig', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'ig', 'to', 'y', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'ig', 'to', 'sc', 'fromIndex', 0, 'toIndex', 0)};
f = write_model(blocks, conns);
[Ai, Bi, Ci, Di] = linmod(f);
assert_isequal(size(Ai), [1 1]);
assert_istrue(abs(Ai) < 1e-6);
assert_istrue(abs(Bi - 1) < 1e-6);
assert_istrue(abs(Ci - 1) < 1e-6);
assert_istrue(abs(Di) < 1e-6);
%=============================================================================
% Nonlinear block, operating-point dependence: a saturation y = sat(u, -1, 1)
% has no continuous state (nx = 0) but a feedthrough D = dy/du that depends on
% the point: 1 inside the band, 0 when saturated. This is the core reason to
% linearize a nonlinear model, so it must be captured.
satBlocks = {...
  struct('id', 'u', 'type', 'labelSource', 'inputs', 0, 'outputs', 1, ...
    'params', struct('label', 'u', 'isExternalPort', true)), ...
  struct('id', 'sat', 'type', 'saturation', 'inputs', 1, 'outputs', 1, ...
    'params', struct('LowerLimit', -1, 'UpperLimit', 1)), ...
  struct('id', 'y', 'type', 'labelSink', 'inputs', 1, 'outputs', 0, ...
    'params', struct('label', 'y'))};
satConns = {...
  struct('from', 'u', 'to', 'sat', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'sat', 'to', 'y', 'fromIndex', 0, 'toIndex', 0)};
fsat = write_model(satBlocks, satConns);
[As, ~, ~, Din] = linmod(fsat, [], 0); % in the band: dy/du = 1
assert_isequal(size(As), [0 0]);
assert_istrue(abs(Din - 1) < 1e-6);
[~, ~, ~, Dsat] = linmod(fsat, [], 2); % saturated: dy/du = 0
assert_istrue(abs(Dsat) < 1e-6);
%=============================================================================
% MIMO: 2 inputs, 2 outputs, 1 state -> exercises multi-column B/D and
% multi-row C/D. Model: x' = u1 + 2*u2, y1 = x, y2 = 3*u1, giving
% A=[0], B=[1 2], C=[1;0], D=[0 0;3 0]. Inputs/outputs keep block order
% (u1,u2 -> columns; y1,y2 -> rows).
mimoBlocks = {...
  struct('id', 'u1', 'type', 'labelSource', 'inputs', 0, 'outputs', 1, ...
    'params', struct('label', 'u1', 'isExternalPort', true)), ...
  struct('id', 'u2', 'type', 'labelSource', 'inputs', 0, 'outputs', 1, ...
    'params', struct('label', 'u2', 'isExternalPort', true)), ...
  struct('id', 'g2', 'type', 'gain', 'inputs', 1, 'outputs', 1, 'params', struct('Gain', 2)), ...
  struct('id', 's', 'type', 'sum', 'inputs', 2, 'outputs', 1, 'params', struct()), ...
  struct('id', 'ig', 'type', 'integrator', 'inputs', 1, 'outputs', 1, 'params', struct()), ...
  struct('id', 'g3', 'type', 'gain', 'inputs', 1, 'outputs', 1, 'params', struct('Gain', 3)), ...
  struct('id', 'y1', 'type', 'labelSink', 'inputs', 1, 'outputs', 0, 'params', struct('label', 'y1')), ...
  struct('id', 'y2', 'type', 'labelSink', 'inputs', 1, 'outputs', 0, 'params', struct('label', 'y2'))};
mimoConns = {...
  struct('from', 'u2', 'to', 'g2', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'u1', 'to', 's', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'g2', 'to', 's', 'fromIndex', 0, 'toIndex', 1), ...
  struct('from', 's', 'to', 'ig', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'ig', 'to', 'y1', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'u1', 'to', 'g3', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'g3', 'to', 'y2', 'fromIndex', 0, 'toIndex', 0)};
fmimo = write_model(mimoBlocks, mimoConns);
[Am, Bm, Cm, Dm] = linmod(fmimo);
assert_isequal(size(Bm), [1 2]);
assert_isequal(size(Cm), [2 1]);
assert_isequal(size(Dm), [2 2]);
assert_istrue(abs(Am) < 1e-6);
assert_istrue(max(abs(Bm(:) - [1; 2])) < 1e-6);
assert_istrue(max(abs(Cm(:) - [1; 0])) < 1e-6);
assert_istrue(max(abs(Dm(:) - [0; 3; 0; 0])) < 1e-6); % column-major of [0 0;3 0]
%=============================================================================
% A continuous state nested inside a subsystem: the recursive state gather finds
% it (nx, A) and its coupling to the outputs across the subsystem boundary (C) is
% captured too. Model raw-JSON is passed straight to the engine (no jsondecode
% round-trip, which would homogenize the heterogeneous nested block array), so an
% internal integrator driven by a constant gives A = 0 and C = 1.
sinner = struct();
sinner.blocks = {...
  struct('id', 'k', 'type', 'constant', 'inputs', 0, 'outputs', 1, 'params', struct('Value', 1)), ...
  struct('id', 'ig', 'type', 'integrator', 'inputs', 1, 'outputs', 1, 'params', struct()), ...
  struct('id', 'yo', 'type', 'labelSink', 'inputs', 1, 'outputs', 1, 'params', struct('gotoTag', 'yo'))};
sinner.connections = {...
  struct('from', 'k', 'to', 'ig', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'ig', 'to', 'yo', 'fromIndex', 0, 'toIndex', 0)};
sinner.externalOutputs = {struct('id', 'yo', 'name', 'yo')};
snb = {...
  struct('id', 'sub', 'type', 'subsystem', 'inputs', 0, 'outputs', 1, ...
    'params', struct('subsystem', sinner)), ...
  struct('id', 'y', 'type', 'labelSink', 'inputs', 1, 'outputs', 0, 'params', struct('label', 'y'))};
snc = {struct('from', 'sub', 'to', 'y', 'fromIndex', 0, 'toIndex', 0)};
fsub = write_model(snb, snc);
[Asub, ~, Csub, ~] = linmod(fsub);
assert_isequal(size(Asub), [1 1]); % the nested integrator state is found
assert_istrue(abs(Asub) < 1e-6); % x' = const -> A = d(x')/dx = 0
assert_istrue(abs(Csub - 1) < 1e-6); % y = x across the subsystem boundary -> C = 1
%=============================================================================
% An external input crossing INTO a subsystem couples through to the nested
% state (B) and the nested output flows back out (C): expect A = 0, B = 1, C = 1,
% D = 0 for an external input -> subsystem -> internal integrator -> output.
binner = struct();
binner.blocks = {...
  struct('id', 'in1', 'type', 'labelSource', 'inputs', 0, 'outputs', 1, 'params', struct('label', 'in1')), ...
  struct('id', 'ig', 'type', 'integrator', 'inputs', 1, 'outputs', 1, 'params', struct()), ...
  struct('id', 'out1', 'type', 'labelSink', 'inputs', 1, 'outputs', 1, 'params', struct('label', 'out1'))};
binner.connections = {...
  struct('from', 'in1', 'to', 'ig', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'ig', 'to', 'out1', 'fromIndex', 0, 'toIndex', 0)};
binner.externalInputs = {struct('id', 'in1', 'name', 'in1')};
binner.externalOutputs = {struct('id', 'out1', 'name', 'out1')};
bnb = {...
  struct('id', 'u', 'type', 'labelSource', 'inputs', 0, 'outputs', 1, ...
    'params', struct('label', 'u', 'isExternalPort', true)), ...
  struct('id', 'sub', 'type', 'subsystem', 'inputs', 1, 'outputs', 1, ...
    'params', struct('subsystem', binner)), ...
  struct('id', 'y', 'type', 'labelSink', 'inputs', 1, 'outputs', 0, 'params', struct('label', 'y'))};
bnc = {...
  struct('from', 'u', 'to', 'sub', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'sub', 'to', 'y', 'fromIndex', 0, 'toIndex', 0)};
fbsub = write_model(bnb, bnc);
[Ab, Bb, Cb, Db] = linmod(fbsub);
assert_isequal(size(Ab), [1 1]);
assert_istrue(abs(Ab) < 1e-6); % internal integrator -> A = 0
assert_istrue(abs(Bb - 1) < 1e-6); % external input crosses in -> B = 1
assert_istrue(abs(Cb - 1) < 1e-6); % nested output crosses out -> C = 1
assert_istrue(abs(Db) < 1e-6); % no direct feedthrough -> D = 0
