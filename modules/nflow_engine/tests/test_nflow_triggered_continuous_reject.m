% L3: a triggered subsystem executes only at discrete trigger edges, so it
% cannot hold continuous states (there is no defined integration between edges).
% A triggered subsystem containing an integrator must be rejected with a clear
% diagnostic, in both solver paths, rather than integrated meaninglessly.
%=============================================================================

% Inner diagram: a continuous integrator (holds a continuous state).
inner = struct();
inner.blocks = {...
  struct('id', 'one', 'type', 'constant', 'inputs', 0, 'outputs', 1, ...
    'params', struct('Value', 1)), ...
  struct('id', 'ig', 'type', 'integrator', 'inputs', 1, 'outputs', 1, ...
    'params', struct('InitialCondition', 0)), ...
  struct('id', 'yout', 'type', 'labelSink', 'inputs', 1, 'outputs', 1, ...
    'params', struct('gotoTag', 'y'))};
inner.connections = {...
  struct('from', 'one', 'to', 'ig', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'ig', 'to', 'yout', 'fromIndex', 0, 'toIndex', 0)};
inner.externalOutputs = {struct('id', 'yout', 'name', 'y')};
inner.controlPort = struct('kind', 'trigger', 'triggerType', 'rising');

d = struct();
d.blocks = {...
  struct('id', 'clk', 'type', 'clock', 'inputs', 0, 'outputs', 1, 'params', struct()), ...
  struct('id', 'cmp', 'type', 'compareToConstant', 'inputs', 1, 'outputs', 1, ...
    'params', struct('relop', 'ge', 'const', 0.5)), ...
  struct('id', 'sub', 'type', 'subsystem', 'inputs', 1, 'outputs', 1, ...
    'params', struct('subsystem', inner, ...
    'controlPort', struct('kind', 'trigger', 'triggerType', 'rising'))), ...
  struct('id', 'tw', 'type', 'toWorkspace', 'inputs', 1, 'outputs', 0, ...
    'params', struct('VariableName', 'trc_out', 'SaveFormat', 'Array', ...
    'Decimation', 1, 'MaxDataPoints', 'inf'))};
d.connections = {...
  struct('from', 'clk', 'to', 'cmp', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'cmp', 'to', 'sub', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'sub', 'to', 'tw', 'fromIndex', 0, 'toIndex', 0)};
d.sampleTime = 0.1; d.duration = 1.0; d.variables = struct();

% Legacy fixed-step path: rejected.
r = jsondecode(__nflow_simulate__(jsonencode(d)));
asserts.isequal(r.status, 'error');
asserts.istrue(~isempty(strfind(lower(r.reason), 'continuous')));
asserts.istrue(~isempty(strfind(lower(r.reason), 'triggered')));

% Global-solver path: rejected identically (same validation, before the branch).
d.solver = 'ode4';
r2 = jsondecode(__nflow_simulate__(jsonencode(d)));
asserts.isequal(r2.status, 'error');
asserts.istrue(~isempty(strfind(lower(r2.reason), 'continuous')));
