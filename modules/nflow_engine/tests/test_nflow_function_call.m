% L5: function-call network. A functionCallGenerator drives a functionCall
% subsystem NumberOfIterations times per step. The callee holds a unit-delay
% counter that increments by 1 each time it runs, so its output rises by
% NumberOfIterations (3) every step: 3, 6, 9, ... 33 over 11 samples.
%=============================================================================
evalin('base', 'clear(''fc_out'')');

inner = struct();
inner.blocks = {...
  struct('id', 'one', 'type', 'constant', 'inputs', 0, 'outputs', 1, 'params', struct('Value', 1)), ...
  struct('id', 'acc', 'type', 'sum', 'inputs', 2, 'outputs', 1, 'params', struct('Inputs', '++')), ...
  struct('id', 'del', 'type', 'unitDelay', 'inputs', 1, 'outputs', 1, 'params', struct()), ...
  struct('id', 'cout', 'type', 'labelSink', 'inputs', 1, 'outputs', 1, ...
    'params', struct('gotoTag', 'y'))};
inner.connections = {...
  struct('from', 'one', 'to', 'acc', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'del', 'to', 'acc', 'fromIndex', 0, 'toIndex', 1), ...
  struct('from', 'acc', 'to', 'del', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'acc', 'to', 'cout', 'fromIndex', 0, 'toIndex', 0)};
inner.externalOutputs = {struct('id', 'cout', 'name', 'y')};
inner.controlPort = struct('kind', 'functionCall');

d = struct();
d.blocks = {...
  struct('id', 'gen', 'type', 'functionCallGenerator', 'inputs', 0, 'outputs', 1, ...
    'params', struct('NumberOfIterations', 3)), ...
  struct('id', 'sub', 'type', 'subsystem', 'inputs', 1, 'outputs', 1, ...
    'params', struct('subsystem', inner, 'controlPort', struct('kind', 'functionCall'))), ...
  struct('id', 'tw', 'type', 'toWorkspace', 'inputs', 1, 'outputs', 0, ...
    'params', struct('VariableName', 'fc_out', 'SaveFormat', 'Array', ...
    'Decimation', 1, 'MaxDataPoints', 'inf'))};
d.connections = {...
  struct('from', 'gen', 'to', 'sub', 'fromIndex', 0, 'toIndex', 0), ...   % event -> control port
  struct('from', 'sub', 'to', 'tw', 'fromIndex', 0, 'toIndex', 0)};
d.sampleTime = 0.1; d.duration = 1.0; d.variables = struct();

r = jsondecode(__nflow_simulate__(jsonencode(d)));
asserts.isequal(r.status, 'done');
v = evalin('base', 'fc_out');
v = v(:);
asserts.isequal(numel(v), 11);
% Each step invokes the callee 3 times -> counter climbs by 3 per sample.
asserts.isapprox(v(1), 3.0, 0, 1e-9);
asserts.isapprox(v(2), 6.0, 0, 1e-9);
asserts.isapprox(v(end), 33.0, 0, 1e-9);
for k = 2:numel(v)
  asserts.isapprox(v(k) - v(k - 1), 3.0, 0, 1e-9);
end

evalin('base', 'clear(''fc_out'')');
%=============================================================================
% Callee output feeding a downstream ALGEBRAIC block (not just a sink). The
% subsystem output goes through a gain of 10 before To Workspace. Because a
% functionCall subsystem is not in the schedule, its output-consumer edge is
% redirected to the driving generator, so the gain is ordered after the
% generator fires and reads the fresh counter: 10*[3,6,...] = [30,60,...].
evalin('base', 'clear(''fc_g'')');
dg = struct();
dg.blocks = {...
  struct('id', 'gen', 'type', 'functionCallGenerator', 'inputs', 0, 'outputs', 1, ...
    'params', struct('NumberOfIterations', 3)), ...
  struct('id', 'sub', 'type', 'subsystem', 'inputs', 1, 'outputs', 1, ...
    'params', struct('subsystem', inner, 'controlPort', struct('kind', 'functionCall'))), ...
  struct('id', 'g', 'type', 'gain', 'inputs', 1, 'outputs', 1, 'params', struct('Gain', 10)), ...
  struct('id', 'tw', 'type', 'toWorkspace', 'inputs', 1, 'outputs', 0, ...
    'params', struct('VariableName', 'fc_g', 'SaveFormat', 'Array', ...
    'Decimation', 1, 'MaxDataPoints', 'inf'))};
dg.connections = {...
  struct('from', 'gen', 'to', 'sub', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'sub', 'to', 'g', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'g', 'to', 'tw', 'fromIndex', 0, 'toIndex', 0)};
dg.sampleTime = 0.1; dg.duration = 1.0; dg.variables = struct();
rg = jsondecode(__nflow_simulate__(jsonencode(dg)));
asserts.isequal(rg.status, 'done');
vg = evalin('base', 'fc_g'); vg = vg(:)';
asserts.isapprox(vg, 10 * (3:3:33), 0, 1e-9);
evalin('base', 'clear(''fc_g'')');
