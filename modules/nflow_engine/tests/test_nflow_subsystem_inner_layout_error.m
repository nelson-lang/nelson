% Regression: a signal layout that fails validation was refused at the top level
% but built on inside a subsystem. The inner buffers were then sized from a
% layout that had already failed, the phases wrote past them, and the process
% died - after the run, on an unrelated free, with nothing pointing at the
% diagram. The same diagram is now refused wherever it sits, naming the block.
%=============================================================================
inner = struct();
inner.blocks = {...
  struct('id', 'in1', 'type', 'labelSource', 'x', 40, 'y', 60, 'rotation', 0, ...
    'params', struct('label', 'in1')), ...
  struct('id', 'k', 'type', 'constant', 'x', 40, 'y', 160, 'rotation', 0, ...
    'params', struct('Value', 3)), ...
  struct('id', 'm', 'type', 'mux', 'x', 200, 'y', 110, 'rotation', 0, ...
    'inputs', 2, 'outputs', 1, 'params', struct('Inputs', 2)), ...
  struct('id', 'e', 'type', 'expression', 'x', 360, 'y', 110, 'rotation', 0, ...
    'params', struct('Expr', 'u(1)+u(2)')), ...
  struct('id', 'out1', 'type', 'labelSink', 'x', 520, 'y', 110, 'rotation', 0, ...
    'params', struct('label', 'out1'))};
inner.connections = {...
  struct('from', 'in1', 'to', 'm', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'k', 'to', 'm', 'fromIndex', 0, 'toIndex', 1), ...
  struct('from', 'm', 'to', 'e', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'e', 'to', 'out1', 'fromIndex', 0, 'toIndex', 0)};
inner.externalInputs = {struct('id', 'in1', 'name', 'in1')};
inner.externalOutputs = {struct('id', 'out1', 'name', 'out1')};

doc = struct();
doc.version = '1.0.0';
doc.format = 'nflow-2';
doc.name = 'subsystem_inner_layout_error';
doc.runtime = 0.05;
doc.sampleTime = 0.01;
doc.blocks = {...
  struct('id', 'c', 'type', 'constant', 'x', 40, 'y', 110, 'rotation', 0, ...
    'params', struct('Value', 5)), ...
  struct('id', 's', 'type', 'subsystem', 'x', 240, 'y', 110, 'rotation', 0, ...
    'inputs', 1, 'outputs', 1, 'params', struct('name', 'S', 'subsystem', inner)), ...
  struct('id', 'tw', 'type', 'toWorkspace', 'x', 440, 'y', 110, 'rotation', 0, ...
    'params', struct('VariableName', 'y_sub', 'SaveFormat', 'Array', ...
    'Decimation', 1, 'MaxDataPoints', 'inf'))};
doc.connections = {...
  struct('from', 'c', 'to', 's', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 's', 'to', 'tw', 'fromIndex', 0, 'toIndex', 0)};

model = [tempname(), '.nflow'];
fid = fopen(model, 'wt');
fwrite(fid, jsonencode(doc));
fclose(fid);
msg = '';
try
  sim(model);
catch e
  msg = e.message;
end
asserts.istrue(~isempty(strfind(msg, 'expression')));
asserts.istrue(~isempty(strfind(msg, 'vector')));
rmfile(model);
