% busAssignment used to hit the unknownTypes error. The vector expansion now
% erases it like busSelector: elements covered by an assigned member's packed
% region rewire to the replacement port, everything else passes the base bus
% through. Bus {a, pos (width 2), count}; assign pos <- [30 40] and
% count <- 99; a passes through.
%=============================================================================
[hasC, hasRust] = __nflow_codegen_support__('busAssignment');
assert_istrue(hasC);
assert_istrue(hasRust);
%=============================================================================
d = struct();
d.blocks = {...
  struct('id', 'a', 'type', 'constant', 'inputs', 0, 'outputs', 1, 'params', struct('Value', 1)), ...
  struct('id', 'p', 'type', 'constant', 'inputs', 0, 'outputs', 1, 'params', struct('Value', [1 2])), ...
  struct('id', 'cnt', 'type', 'constant', 'inputs', 0, 'outputs', 1, 'params', struct('Value', 7)), ...
  struct('id', 'bc', 'type', 'busCreator', 'inputs', 3, 'outputs', 1, ...
    'params', struct('MemberNames', {{'a', 'pos', 'count'}})), ...
  struct('id', 'rp', 'type', 'constant', 'inputs', 0, 'outputs', 1, 'params', struct('Value', [30 40])), ...
  struct('id', 'rc', 'type', 'constant', 'inputs', 0, 'outputs', 1, 'params', struct('Value', 99)), ...
  struct('id', 'ba', 'type', 'busAssignment', 'inputs', 3, 'outputs', 1, ...
    'params', struct('AssignedSignals', {{'pos', 'count'}})), ...
  struct('id', 'sel', 'type', 'busSelector', 'inputs', 1, 'outputs', 3, ...
    'params', struct('SelectedSignals', {{'a', 'pos', 'count'}})), ...
  struct('id', 'dm', 'type', 'demux', 'inputs', 1, 'outputs', 2, 'params', struct()), ...
  struct('id', 'ya', 'type', 'labelSink', 'inputs', 1, 'outputs', 1, ...
    'params', struct('GotoTag', 'ya', 'isExternalPort', true)), ...
  struct('id', 'y0', 'type', 'labelSink', 'inputs', 1, 'outputs', 1, ...
    'params', struct('GotoTag', 'y0', 'isExternalPort', true)), ...
  struct('id', 'y1', 'type', 'labelSink', 'inputs', 1, 'outputs', 1, ...
    'params', struct('GotoTag', 'y1', 'isExternalPort', true)), ...
  struct('id', 'yc', 'type', 'labelSink', 'inputs', 1, 'outputs', 1, ...
    'params', struct('GotoTag', 'yc', 'isExternalPort', true)), ...
  struct('id', 'wa', 'type', 'toWorkspace', 'inputs', 1, 'outputs', 0, ...
    'params', struct('VariableName', 'nfba_a', 'SaveFormat', 'Array', ...
      'Decimation', 1, 'MaxDataPoints', 'inf')), ...
  struct('id', 'w0', 'type', 'toWorkspace', 'inputs', 1, 'outputs', 0, ...
    'params', struct('VariableName', 'nfba_p0', 'SaveFormat', 'Array', ...
      'Decimation', 1, 'MaxDataPoints', 'inf')), ...
  struct('id', 'w1', 'type', 'toWorkspace', 'inputs', 1, 'outputs', 0, ...
    'params', struct('VariableName', 'nfba_p1', 'SaveFormat', 'Array', ...
      'Decimation', 1, 'MaxDataPoints', 'inf')), ...
  struct('id', 'wc', 'type', 'toWorkspace', 'inputs', 1, 'outputs', 0, ...
    'params', struct('VariableName', 'nfba_c', 'SaveFormat', 'Array', ...
      'Decimation', 1, 'MaxDataPoints', 'inf'))};
d.connections = {...
  struct('from', 'a', 'to', 'bc', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'p', 'to', 'bc', 'fromIndex', 0, 'toIndex', 1), ...
  struct('from', 'cnt', 'to', 'bc', 'fromIndex', 0, 'toIndex', 2), ...
  struct('from', 'bc', 'to', 'ba', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'rp', 'to', 'ba', 'fromIndex', 0, 'toIndex', 1), ...
  struct('from', 'rc', 'to', 'ba', 'fromIndex', 0, 'toIndex', 2), ...
  struct('from', 'ba', 'to', 'sel', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'sel', 'to', 'ya', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'sel', 'to', 'wa', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'sel', 'to', 'dm', 'fromIndex', 1, 'toIndex', 0), ...
  struct('from', 'sel', 'to', 'yc', 'fromIndex', 2, 'toIndex', 0), ...
  struct('from', 'sel', 'to', 'wc', 'fromIndex', 2, 'toIndex', 0), ...
  struct('from', 'dm', 'to', 'y0', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'dm', 'to', 'w0', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'dm', 'to', 'y1', 'fromIndex', 1, 'toIndex', 0), ...
  struct('from', 'dm', 'to', 'w1', 'fromIndex', 1, 'toIndex', 0)};
d.sampleTime = 0.1;
d.duration = 0.5;
d.variables = struct();
%=============================================================================
r = jsondecode(__nflow_simulate__(jsonencode(d)));
assert_isequal(r.status, 'done');
va = evalin('base', 'nfba_a');
v0 = evalin('base', 'nfba_p0');
v1 = evalin('base', 'nfba_p1');
vc = evalin('base', 'nfba_c');
assert_isequal(va(1), 1);
assert_isequal(v0(1), 30);
assert_isequal(v1(1), 40);
assert_isequal(vc(1), 99);
evalin('base', 'clear(''nfba_a'', ''nfba_p0'', ''nfba_p1'', ''nfba_c'')');
%=============================================================================
f = [tempname(), '.nflow'];
[~, fstem] = fileparts(f);
fid = fopen(f, 'wt');
fwrite(fid, jsonencode(d));
fclose(fid);
nflow_codegenerate(f, tempdir(), false, 'C');
src = fileread([tempdir(), fstem, '/model.c']);
assert_istrue(isempty(strfind(src, 'unknown:')));
% Unassigned member passes the base through; assigned members rewire to the
% replacement ports (pos elements 0/1, then count).
assert_istrue(~isempty(strfind(src, 'out_ya = out_a;')));
assert_istrue(~isempty(strfind(src, 'out_y0 = out_rp__e0;')));
assert_istrue(~isempty(strfind(src, 'out_y1 = out_rp__e1;')));
assert_istrue(~isempty(strfind(src, 'out_yc = out_rc;')));
nflow_codegenerate(f, tempdir(), false, 'rust');
srcR = fileread([tempdir(), fstem, '/src/lib.rs']);
assert_istrue(isempty(strfind(srcR, 'unknown:')));
rmfile(f);
if isdir([tempdir(), fstem])
  rmdir([tempdir(), fstem], 's');
end
%=============================================================================
% Compiled numeric equivalence vs the simulator (both targets).
if __nflow_codegen_toolchain__('C')
  nflow_codegen_check_numeric(d, 'nfba_num', 'C', ...
    {'ya', 'y0', 'y1', 'yc'}, {'nfba_a', 'nfba_p0', 'nfba_p1', 'nfba_c'}, 0, 0);
  if __nflow_codegen_toolchain__('rust')
    nflow_codegen_check_numeric(d, 'nfba_num', 'rust', ...
      {'ya', 'y0', 'y1', 'yc'}, {'nfba_a', 'nfba_p0', 'nfba_p1', 'nfba_c'}, 0, 0);
  end
end
