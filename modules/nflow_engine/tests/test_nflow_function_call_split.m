% L5: functionCallSplit fans one function-call out to several callee
% subsystems, in output-port order. A generator drives a split with two outputs,
% each wired to a counter callee; both counters advance once per step -> both
% outputs are 1, 2, 3, ... 11.
%=============================================================================
evalin('base', 'clear(''fcs_a'')');
evalin('base', 'clear(''fcs_b'')');

function s = counter_callee()
  s = struct();
  s.blocks = {...
    struct('id', 'one', 'type', 'constant', 'inputs', 0, 'outputs', 1, 'params', struct('Value', 1)), ...
    struct('id', 'acc', 'type', 'sum', 'inputs', 2, 'outputs', 1, 'params', struct('Inputs', '++')), ...
    struct('id', 'del', 'type', 'unitDelay', 'inputs', 1, 'outputs', 1, 'params', struct()), ...
    struct('id', 'cout', 'type', 'labelSink', 'inputs', 1, 'outputs', 1, ...
      'params', struct('gotoTag', 'y'))};
  s.connections = {...
    struct('from', 'one', 'to', 'acc', 'fromIndex', 0, 'toIndex', 0), ...
    struct('from', 'del', 'to', 'acc', 'fromIndex', 0, 'toIndex', 1), ...
    struct('from', 'acc', 'to', 'del', 'fromIndex', 0, 'toIndex', 0), ...
    struct('from', 'acc', 'to', 'cout', 'fromIndex', 0, 'toIndex', 0)};
  s.externalOutputs = {struct('id', 'cout', 'name', 'y')};
  s.controlPort = struct('kind', 'functionCall');
end

fc = struct('kind', 'functionCall');
d = struct();
d.blocks = {...
  struct('id', 'gen', 'type', 'functionCallGenerator', 'inputs', 0, 'outputs', 1, ...
    'params', struct('NumberOfIterations', 1)), ...
  struct('id', 'spl', 'type', 'functionCallSplit', 'inputs', 1, 'outputs', 2, 'params', struct()), ...
  struct('id', 'subA', 'type', 'subsystem', 'inputs', 1, 'outputs', 1, ...
    'params', struct('subsystem', counter_callee(), 'controlPort', fc)), ...
  struct('id', 'subB', 'type', 'subsystem', 'inputs', 1, 'outputs', 1, ...
    'params', struct('subsystem', counter_callee(), 'controlPort', fc)), ...
  struct('id', 'twA', 'type', 'toWorkspace', 'inputs', 1, 'outputs', 0, ...
    'params', struct('VariableName', 'fcs_a', 'SaveFormat', 'Array', 'Decimation', 1, 'MaxDataPoints', 'inf')), ...
  struct('id', 'twB', 'type', 'toWorkspace', 'inputs', 1, 'outputs', 0, ...
    'params', struct('VariableName', 'fcs_b', 'SaveFormat', 'Array', 'Decimation', 1, 'MaxDataPoints', 'inf'))};
d.connections = {...
  struct('from', 'gen', 'to', 'spl', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'spl', 'to', 'subA', 'fromIndex', 0, 'toIndex', 0), ...   % split out 0 -> A
  struct('from', 'spl', 'to', 'subB', 'fromIndex', 1, 'toIndex', 0), ...   % split out 1 -> B
  struct('from', 'subA', 'to', 'twA', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'subB', 'to', 'twB', 'fromIndex', 0, 'toIndex', 0)};
d.sampleTime = 0.1; d.duration = 1.0; d.variables = struct();

r = jsondecode(__nflow_simulate__(jsonencode(d)));
asserts.isequal(r.status, 'done');
a = evalin('base', 'fcs_a'); a = a(:);
b = evalin('base', 'fcs_b'); b = b(:);
asserts.isequal(numel(a), 11);
asserts.isequal(numel(b), 11);
% Both callees run once per step -> counters 1..11.
asserts.isapprox(a(1), 1.0, 0, 1e-9);
asserts.isapprox(a(end), 11.0, 0, 1e-9);
asserts.isapprox(b(1), 1.0, 0, 1e-9);
asserts.isapprox(b(end), 11.0, 0, 1e-9);
asserts.isequal(a, b);

evalin('base', 'clear(''fcs_a'')');
evalin('base', 'clear(''fcs_b'')');
