% Regression: under a continuous solver, the pass that RECORDS a sample ran a
% single ordered sweep of the algebraic blocks instead of the SCC-scoped solve
% the rhs and the fixed-step path both use. An algebraic loop was therefore
% logged at its first iterate: y = 1 + 0.5 y came back as 1 instead of 2, with
% no warning, while the state trajectory around it stayed correct. The same
% diagram on the fixed-step path already answered 2, so the two paths disagreed.
%=============================================================================
doc = struct();
doc.version = '1.0.0';
doc.format = 'nflow-2';
doc.name = 'algebraic_loop_under_solver';
doc.runtime = 0.5;
doc.sampleTime = 0.01;
doc.blocks = {...
  struct('id', 'c', 'type', 'constant', 'x', 40, 'y', 100, 'rotation', 0, ...
    'params', struct('Value', 1)), ...
  struct('id', 's', 'type', 'sum', 'x', 240, 'y', 100, 'rotation', 0, ...
    'params', struct('Inputs', '++')), ...
  struct('id', 'g', 'type', 'gain', 'x', 440, 'y', 220, 'rotation', 0, ...
    'params', struct('Gain', 0.5)), ...
  struct('id', 'tw', 'type', 'toWorkspace', 'x', 640, 'y', 100, 'rotation', 0, ...
    'params', struct('VariableName', 'y_loop', 'SaveFormat', 'Array', ...
    'Decimation', 1, 'MaxDataPoints', 'inf')), ...
  struct('id', 'ci', 'type', 'constant', 'x', 40, 'y', 320, 'rotation', 0, ...
    'params', struct('Value', 1)), ...
  struct('id', 'i', 'type', 'integrator', 'x', 240, 'y', 320, 'rotation', 0, ...
    'params', struct('InitialCondition', 0)), ...
  struct('id', 'tw2', 'type', 'toWorkspace', 'x', 440, 'y', 320, 'rotation', 0, ...
    'params', struct('VariableName', 'z_state', 'SaveFormat', 'Array', ...
    'Decimation', 1, 'MaxDataPoints', 'inf'))};
doc.connections = {...
  struct('from', 'c', 'to', 's', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 's', 'to', 'g', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'g', 'to', 's', 'fromIndex', 0, 'toIndex', 1), ...
  struct('from', 's', 'to', 'tw', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'ci', 'to', 'i', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'i', 'to', 'tw2', 'fromIndex', 0, 'toIndex', 0)};

model = [tempname(), '.nflow'];
fid = fopen(model, 'wt');
fwrite(fid, jsonencode(doc));
fclose(fid);

% The loop settles at the same fixed point whichever path runs the diagram.
outFixed = sim(model);
asserts.isapprox(outFixed.y_loop(end), 2, 1e-6, 1e-6);

solvers = {'ode1', 'ode4', 'ode45'};
for k = 1:numel(solvers)
  out = sim(model, 'Solver', solvers{k});
  asserts.isapprox(out.y_loop(end), 2, 1e-6, 1e-6);
  asserts.isapprox(out.z_state(end), 0.5, 1e-6, 1e-6);
end
rmfile(model);
