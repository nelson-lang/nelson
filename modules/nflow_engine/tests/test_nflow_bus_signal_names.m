d = ['{"blocks":[', ...
  '{"id":"a","type":"constant","inputs":0,"outputs":1,"params":{"Value":4}},', ...
  '{"id":"b","type":"constant","inputs":0,"outputs":1,"params":{"Value":7}},', ...
  '{"id":"bus","type":"busCreator","inputs":2,"outputs":1,"params":{}},', ...
  '{"id":"sel","type":"busSelector","inputs":1,"outputs":2,"params":{"SelectedSignals":["altitude","speed"]}},', ...
  '{"id":"s1","type":"scope","inputs":1,"outputs":0,"params":{}},', ...
  '{"id":"s2","type":"scope","inputs":1,"outputs":0,"params":{}}],', ...
  '"connections":[', ...
  '{"from":"a","to":"bus","toIndex":0,"label":"altitude"},', ...
  '{"from":"b","to":"bus","toIndex":1,"label":"speed"},', ...
  '{"from":"bus","to":"sel"},', ...
  '{"from":"sel","to":"s1","fromIndex":0},', ...
  '{"from":"sel","to":"s2","fromIndex":1}],"sampleTime":0.01,"runtime":0.1}'];
result = jsondecode(__nflow_simulate__(d));
assert_isequal(result.status, 'done');
info = result.signalBus.bus;
if iscell(info), info = info{1}; end
assert_isequal(info.members(1).name, 'altitude');
assert_isequal(info.members(2).name, 'speed');
