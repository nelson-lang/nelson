% B2 (enabled subsystem): a subsystem executes only while its control signal is
% > 0. When disabled, its external outputs hold their last value and its internal
% state is frozen. Control = 1 for t < 0.5 then 0: the inner integrator ramps to
% 0.4 then holds, instead of ramping to 1.0 as it would without gating.
%=============================================================================
evalin('base', 'clear(''en_out'')');

inner = struct();
inner.blocks = {...
  struct('id', 'c', 'type', 'constant', 'inputs', 0, 'outputs', 1, ...
    'params', struct('Value', 1)), ...
  struct('id', 'int', 'type', 'integrator', 'inputs', 1, 'outputs', 1, ...
    'params', struct('InitialCondition', 0)), ...
  struct('id', 'yout', 'type', 'labelSink', 'inputs', 1, 'outputs', 1, ...
    'params', struct('gotoTag', 'y'))};
inner.connections = {...
  struct('from', 'c', 'to', 'int', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'int', 'to', 'yout', 'fromIndex', 0, 'toIndex', 0)};
inner.externalOutputs = {struct('id', 'yout', 'name', 'y')};
inner.controlPort = struct('kind', 'enable');

d = struct();
d.blocks = {...
  struct('id', 'clk', 'type', 'clock', 'inputs', 0, 'outputs', 1, 'params', struct()), ...
  struct('id', 'cmp', 'type', 'compareToConstant', 'inputs', 1, 'outputs', 1, ...
    'params', struct('relop', 'lt', 'const', 0.5)), ...
  struct('id', 'sub', 'type', 'subsystem', 'inputs', 1, 'outputs', 1, ...
    'params', struct('subsystem', inner, 'controlPort', struct('kind', 'enable'))), ...
  struct('id', 'tw', 'type', 'toWorkspace', 'inputs', 1, 'outputs', 0, ...
    'params', struct('VariableName', 'en_out', 'SaveFormat', 'Array', ...
    'Decimation', 1, 'MaxDataPoints', 'inf'))};
d.connections = {...
  struct('from', 'clk', 'to', 'cmp', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'cmp', 'to', 'sub', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'sub', 'to', 'tw', 'fromIndex', 0, 'toIndex', 0)};
d.sampleTime = 0.1; d.duration = 1.0; d.variables = struct();

r = jsondecode(__nflow_simulate__(jsonencode(d)));
asserts.isequal(r.status, 'done');
v = evalin('base', 'en_out');
v = v(:);
asserts.isequal(numel(v), 11);
asserts.isapprox(v(1), 0.0, 0, 1e-9); % t=0
asserts.isapprox(v(5), 0.4, 0, 1e-9); % t=0.4, last enabled sample
% Disabled from t=0.5 on: the output holds and the state is frozen.
asserts.isapprox(v(end), 0.4, 0, 1e-9); % held, NOT ramped to ~1.0
asserts.istrue(max(v) <= 0.4 + 1e-9); % never keeps integrating while disabled

evalin('base', 'clear(''en_out'')');
