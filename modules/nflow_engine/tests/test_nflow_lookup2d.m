% lookup2D: 2-D lookup table. Column-major 2x2 table T(0,0)=0, T(1,0)=10,
% T(0,1)=100, T(1,1)=110 over breakpoints [0 1] x [0 1]. Feedthrough; logged
% at t0 (an integrator supplies the state the fixed-step solver requires).
%=============================================================================
function p = l2_write(json, stem)
  p = [tempname(), '.nflow'];
  fid = fopen(p, 'w'); fwrite(fid, json); fclose(fid);
end
%=============================================================================
function y = l2_eval(interp, u1, u2)
  m = ['{"blocks":[', ...
    '{"id":"a","type":"constant","inputs":0,"outputs":1,"params":{"Value":', sprintf('%.15g', u1), '}},', ...
    '{"id":"b","type":"constant","inputs":0,"outputs":1,"params":{"Value":', sprintf('%.15g', u2), '}},', ...
    '{"id":"f","type":"lookup2D","inputs":2,"outputs":1,"params":{', ...
      '"BreakpointsForDimension1":[0,1],"BreakpointsForDimension2":[0,1],', ...
      '"Table":[0,10,100,110],"InterpMethod":"', interp, '","ExtrapMethod":"Linear"}},', ...
    '{"id":"ig","type":"integrator","inputs":1,"outputs":1,"params":{"InitialCondition":0}},', ...
    '{"id":"td","type":"toWorkspace","inputs":1,"outputs":0,"params":{"VariableName":"d"}},', ...
    '{"id":"tw","type":"toWorkspace","inputs":1,"outputs":0,"params":{"VariableName":"y"}}],', ...
    '"connections":[', ...
      '{"from":"a","to":"f","fromIndex":0,"toIndex":0},', ...
      '{"from":"b","to":"f","fromIndex":0,"toIndex":1},', ...
      '{"from":"f","to":"tw","fromIndex":0,"toIndex":0},', ...
      '{"from":"a","to":"ig","fromIndex":0,"toIndex":0},', ...
      '{"from":"ig","to":"td","fromIndex":0,"toIndex":0}],', ...
    '"solver":"ode1","runtime":0.1,"sampleTime":0.1}'];
  out = sim(l2_write(m, 'test_nflow_lookup2d_eval'));
  lg = out.logsout; nms = {lg.name};
  y = lg(find(strcmp(nms, 'y'), 1)).values(1);
end
%=============================================================================
assert_istrue(abs(l2_eval('Linear point-slope', 0, 0) - 0.0) < 1e-12);
assert_istrue(abs(l2_eval('Linear point-slope', 1, 1) - 110.0) < 1e-12);
assert_istrue(abs(l2_eval('Linear point-slope', 0.5, 0) - 5.0) < 1e-12);
assert_istrue(abs(l2_eval('Linear point-slope', 0, 0.5) - 50.0) < 1e-12);
assert_istrue(abs(l2_eval('Linear point-slope', 0.5, 0.5) - 55.0) < 1e-12);
assert_istrue(abs(l2_eval('Flat', 0.7, 0.7) - 0.0) < 1e-12);
assert_istrue(abs(l2_eval('Nearest', 0.6, 0.4) - 10.0) < 1e-12);
