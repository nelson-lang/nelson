% For-each subsystem: the body runs numIterations times over the
% partitioned inputs, an unpartitioned input is broadcast, and the outputs are
% concatenated. Stateless bodies are targeted; a state-bearing / mis-sized body
% is rejected at compile time. Models are written as raw JSON so the forEach
% "partition" array is exactly a JSON array (jsonencode of a length-1 vector
% would be a bare number).
%=============================================================================
function p = foreach_write(json, stem)
  p = [tempname(), '.nflow'];
  fid = fopen(p, 'w');
  fwrite(fid, json);
  fclose(fid);
end
%=============================================================================
% Partition a width-4 input through an inner gain 3: element-wise 3 * input.
gainModel = ['{"blocks":[', ...
  '{"id":"c","type":"constant","inputs":0,"outputs":1,"params":{"Value":[1,2,3,4]}},', ...
  '{"id":"sub","type":"subsystem","inputs":1,"outputs":1,"params":{', ...
    '"forEach":{"numIterations":4,"partition":[0]},"subsystem":{', ...
    '"blocks":[', ...
      '{"id":"in1","type":"labelSource","inputs":0,"outputs":1,"params":{"label":"in1"}},', ...
      '{"id":"g","type":"gain","inputs":1,"outputs":1,"params":{"Gain":3}},', ...
      '{"id":"out1","type":"labelSink","inputs":1,"outputs":1,"params":{"label":"out1"}}],', ...
    '"connections":[', ...
      '{"from":"in1","to":"g","fromIndex":0,"toIndex":0},', ...
      '{"from":"g","to":"out1","fromIndex":0,"toIndex":0}],', ...
    '"externalInputs":[{"id":"in1","name":"in1"}],', ...
    '"externalOutputs":[{"id":"out1","name":"out1"}]}}},', ...
  '{"id":"tw","type":"toWorkspace","inputs":1,"outputs":0,"params":{"VariableName":"y"}}],', ...
  '"connections":[', ...
    '{"from":"c","to":"sub","fromIndex":0,"toIndex":0},', ...
    '{"from":"sub","to":"tw","fromIndex":0,"toIndex":0}],', ...
  '"runtime":0.2,"sampleTime":0.1}'];
outG = sim(foreach_write(gainModel, 'test_nflow_foreach_gain'));
vG = outG.logsout(1).values;
assert_isequal(size(vG, 2), 4); % concatenated to width 4
assert_istrue(max(abs(vG(end, :) - [3 6 9 12])) < 1e-9);
%=============================================================================
% Broadcast: a second, unpartitioned input reaches every iteration. Partition
% [1,2,3,4] + broadcast 10 -> [11,12,13,14].
bcastModel = ['{"blocks":[', ...
  '{"id":"c","type":"constant","inputs":0,"outputs":1,"params":{"Value":[1,2,3,4]}},', ...
  '{"id":"k","type":"constant","inputs":0,"outputs":1,"params":{"Value":10}},', ...
  '{"id":"sub","type":"subsystem","inputs":2,"outputs":1,"params":{', ...
    '"forEach":{"numIterations":4,"partition":[0]},"subsystem":{', ...
    '"blocks":[', ...
      '{"id":"in1","type":"labelSource","inputs":0,"outputs":1,"params":{"label":"in1"}},', ...
      '{"id":"in2","type":"labelSource","inputs":0,"outputs":1,"params":{"label":"in2"}},', ...
      '{"id":"s","type":"sum","inputs":2,"outputs":1,"params":{}},', ...
      '{"id":"out1","type":"labelSink","inputs":1,"outputs":1,"params":{"label":"out1"}}],', ...
    '"connections":[', ...
      '{"from":"in1","to":"s","fromIndex":0,"toIndex":0},', ...
      '{"from":"in2","to":"s","fromIndex":0,"toIndex":1},', ...
      '{"from":"s","to":"out1","fromIndex":0,"toIndex":0}],', ...
    '"externalInputs":[{"id":"in1","name":"in1"},{"id":"in2","name":"in2"}],', ...
    '"externalOutputs":[{"id":"out1","name":"out1"}]}}},', ...
  '{"id":"tw","type":"toWorkspace","inputs":1,"outputs":0,"params":{"VariableName":"y"}}],', ...
  '"connections":[', ...
    '{"from":"c","to":"sub","fromIndex":0,"toIndex":0},', ...
    '{"from":"k","to":"sub","fromIndex":0,"toIndex":1},', ...
    '{"from":"sub","to":"tw","fromIndex":0,"toIndex":0}],', ...
  '"runtime":0.2,"sampleTime":0.1}'];
outB = sim(foreach_write(bcastModel, 'test_nflow_foreach_bcast'));
vB = outB.logsout(1).values;
assert_istrue(max(abs(vB(end, :) - [11 12 13 14])) < 1e-9);
%=============================================================================
% Per-iteration discrete state: a unit-delay body keeps independent
% history per channel. Partition [1,2,3,4] through a unit delay: sample 1 is the
% initial condition [0 0 0 0], and from sample 2 each channel shows its OWN
% delayed value [1 2 3 4] -- a shared (aliased) state would repeat one channel's
% value (whichever iteration ran last).
delayModel = strrep(gainModel, ...
  '{"id":"g","type":"gain","inputs":1,"outputs":1,"params":{"Gain":3}}', ...
  '{"id":"g","type":"unitDelay","inputs":1,"outputs":1,"params":{}}');
outD = sim(foreach_write(delayModel, 'test_nflow_foreach_delay'));
vD = outD.logsout(1).values;
assert_isequal(size(vD, 2), 4);
assert_istrue(max(abs(vD(1, :) - [0 0 0 0])) < 1e-9); % initial condition
assert_istrue(max(abs(vD(2, :) - [1 2 3 4])) < 1e-9); % independent per-channel delay
assert_istrue(max(abs(vD(end, :) - [1 2 3 4])) < 1e-9);
%=============================================================================
% Per-iteration CONTINUOUS state: an integrator body integrates each
% channel independently under the solver. Partition [1,2,3,4] -> channel k
% integrates the constant k, so at t = 1 (initial condition 0) the output is
% [1,2,3,4]; a shared global state would not separate the channels. StateLayout
% lays out N * nx_inner and each iteration writes its own xdot slice.
intModel = ['{"blocks":[', ...
  '{"id":"c","type":"constant","inputs":0,"outputs":1,"params":{"Value":[1,2,3,4]}},', ...
  '{"id":"sub","type":"subsystem","inputs":1,"outputs":1,"params":{', ...
    '"forEach":{"numIterations":4,"partition":[0]},"subsystem":{', ...
    '"blocks":[', ...
      '{"id":"in1","type":"labelSource","inputs":0,"outputs":1,"params":{"label":"in1"}},', ...
      '{"id":"ig","type":"integrator","inputs":1,"outputs":1,"params":{"InitialCondition":0}},', ...
      '{"id":"out1","type":"labelSink","inputs":1,"outputs":1,"params":{"label":"out1"}}],', ...
    '"connections":[', ...
      '{"from":"in1","to":"ig","fromIndex":0,"toIndex":0},', ...
      '{"from":"ig","to":"out1","fromIndex":0,"toIndex":0}],', ...
    '"externalInputs":[{"id":"in1","name":"in1"}],', ...
    '"externalOutputs":[{"id":"out1","name":"out1"}]}}},', ...
  '{"id":"tw","type":"toWorkspace","inputs":1,"outputs":0,"params":{"VariableName":"y"}}],', ...
  '"connections":[', ...
    '{"from":"c","to":"sub","fromIndex":0,"toIndex":0},', ...
    '{"from":"sub","to":"tw","fromIndex":0,"toIndex":0}],', ...
  '"solver":"ode4","runtime":1.0,"sampleTime":0.01}'];
outI = sim(foreach_write(intModel, 'test_nflow_foreach_int'));
vI = outI.logsout(1).values;
assert_isequal(size(vI, 2), 4);
assert_istrue(max(abs(vI(end, :) - [1 2 3 4])) < 1e-6); % independent integration
midRow = round(size(vI, 1) / 2);
assert_istrue(max(abs(vI(midRow, :) - 0.5 * [1 2 3 4])) < 5e-2); % genuine ramp, not passthrough
%=============================================================================
% A partitioned input whose width is not a multiple of numIterations errors.
badModel = strrep(strrep(gainModel, '"Value":[1,2,3,4]', '"Value":[1,2,3]'), ...
  '"numIterations":4', '"numIterations":2');
msg2 = '';
try
  sim(foreach_write(badModel, 'test_nflow_foreach_bad'));
catch e
  msg2 = e.message;
end
assert_istrue(~isempty(strfind(msg2, 'not a positive multiple')));
