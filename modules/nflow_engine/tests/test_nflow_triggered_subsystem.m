% B2 (triggered subsystem): a triggered subsystem executes exactly ONCE per
% control edge, not every step while the control is high. Inner counter (adds 1
% per execution via a unit delay). A single rising edge at t=0.5 => the counter
% reaches 1 and holds at 1, rather than incrementing every step to ~5.
%=============================================================================
evalin('base', 'clear(''tg_out'')');

inner = struct();
inner.blocks = {...
  struct('id', 'one', 'type', 'constant', 'inputs', 0, 'outputs', 1, ...
    'params', struct('Value', 1)), ...
  struct('id', 'acc', 'type', 'sum', 'inputs', 2, 'outputs', 1, ...
    'params', struct('Inputs', '++')), ...
  struct('id', 'd', 'type', 'unitDelay', 'inputs', 1, 'outputs', 1, 'params', struct()), ...
  struct('id', 'cout', 'type', 'labelSink', 'inputs', 1, 'outputs', 1, ...
    'params', struct('gotoTag', 'y'))};
inner.connections = {...
  struct('from', 'one', 'to', 'acc', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'd', 'to', 'acc', 'fromIndex', 0, 'toIndex', 1), ...
  struct('from', 'acc', 'to', 'd', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'acc', 'to', 'cout', 'fromIndex', 0, 'toIndex', 0)};
inner.externalOutputs = {struct('id', 'cout', 'name', 'y')};
inner.controlPort = struct('kind', 'trigger', 'triggerType', 'rising');

d = struct();
d.blocks = {...
  struct('id', 'clk', 'type', 'clock', 'inputs', 0, 'outputs', 1, 'params', struct()), ...
  struct('id', 'cmp', 'type', 'compareToConstant', 'inputs', 1, 'outputs', 1, ...
    'params', struct('relop', 'ge', 'const', 0.5)), ...
  struct('id', 'sub', 'type', 'subsystem', 'inputs', 1, 'outputs', 1, ...
    'params', struct('subsystem', inner, ...
    'controlPort', struct('kind', 'trigger', 'triggerType', 'rising'))), ...
  struct('id', 'tw', 'type', 'toWorkspace', 'inputs', 1, 'outputs', 0, ...
    'params', struct('VariableName', 'tg_out', 'SaveFormat', 'Array', ...
    'Decimation', 1, 'MaxDataPoints', 'inf'))};
d.connections = {...
  struct('from', 'clk', 'to', 'cmp', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'cmp', 'to', 'sub', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'sub', 'to', 'tw', 'fromIndex', 0, 'toIndex', 0)};
d.sampleTime = 0.1; d.duration = 1.0; d.variables = struct();

r = jsondecode(__nflow_simulate__(jsonencode(d)));
asserts.isequal(r.status, 'done');
v = evalin('base', 'tg_out');
v = v(:);
asserts.isequal(numel(v), 11);
asserts.isapprox(v(5), 0.0, 0, 1e-9); % t=0.4, no edge yet -> counter 0
asserts.isapprox(v(6), 1.0, 0, 1e-9); % t=0.5, single rising edge -> executed once
asserts.isapprox(v(end), 1.0, 0, 1e-9); % held: NOT re-firing every step
asserts.istrue(max(v) <= 1.0 + 1e-9); % exactly one execution over the run

evalin('base', 'clear(''tg_out'')');
