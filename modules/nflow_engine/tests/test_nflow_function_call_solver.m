% Function-call network under the GLOBAL solver. A
% functionCallGenerator drives a functionCall subsystem (a unit-delay counter)
% NumberOfIterations times per major step, alongside a continuous integrator so
% the ode4 solver path is exercised. The generator fires its callees once per
% major step (in recordAt) and never during the side-effect-free rhs / root
% evaluations, so the counter climbs by NumberOfIterations (3) per sample under
% ode4 exactly as under the discrete/fixed-step engine.
%=============================================================================
inner = struct();
inner.blocks = {...
  struct('id', 'one', 'type', 'constant', 'inputs', 0, 'outputs', 1, 'params', struct('Value', 1)), ...
  struct('id', 'acc', 'type', 'sum', 'inputs', 2, 'outputs', 1, 'params', struct('Inputs', '++')), ...
  struct('id', 'del', 'type', 'unitDelay', 'inputs', 1, 'outputs', 1, 'params', struct()), ...
  struct('id', 'cout', 'type', 'labelSink', 'inputs', 1, 'outputs', 1, ...
    'params', struct('gotoTag', 'y'))};
inner.connections = {...
  struct('from', 'one', 'to', 'acc', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'del', 'to', 'acc', 'fromIndex', 0, 'toIndex', 1), ...
  struct('from', 'acc', 'to', 'del', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'acc', 'to', 'cout', 'fromIndex', 0, 'toIndex', 0)};
inner.externalOutputs = {struct('id', 'cout', 'name', 'y')};
inner.controlPort = struct('kind', 'functionCall');

mk = @(solver) struct('blocks', {{...
  struct('id', 'gen', 'type', 'functionCallGenerator', 'inputs', 0, 'outputs', 1, ...
    'params', struct('NumberOfIterations', 3)), ...
  struct('id', 'sub', 'type', 'subsystem', 'inputs', 1, 'outputs', 1, ...
    'params', struct('subsystem', inner, 'controlPort', struct('kind', 'functionCall'))), ...
  struct('id', 'tw', 'type', 'toWorkspace', 'inputs', 1, 'outputs', 0, ...
    'params', struct('VariableName', 'fc_out', 'SaveFormat', 'Array', ...
    'Decimation', 1, 'MaxDataPoints', 'inf')), ...
  struct('id', 'c2', 'type', 'constant', 'inputs', 0, 'outputs', 1, 'params', struct('Value', 1)), ...
  struct('id', 'ig', 'type', 'integrator', 'inputs', 1, 'outputs', 1, 'params', struct()), ...
  struct('id', 'sc', 'type', 'scope', 'inputs', 1, 'outputs', 0, 'params', struct())}}, ...
  'connections', {{...
    struct('from', 'gen', 'to', 'sub', 'fromIndex', 0, 'toIndex', 0), ...
    struct('from', 'sub', 'to', 'tw', 'fromIndex', 0, 'toIndex', 0), ...
    struct('from', 'c2', 'to', 'ig', 'fromIndex', 0, 'toIndex', 0), ...
    struct('from', 'ig', 'to', 'sc', 'fromIndex', 0, 'toIndex', 0)}}, ...
  'sampleTime', 0.1, 'duration', 1.0, 'solver', solver, 'variables', struct());
%=============================================================================
% Under ode4 the run is accepted (no longer rejected) and the counter matches
% the discrete engine step for step.
evalin('base', 'clear(''fc_out'')');
r4 = jsondecode(__nflow_simulate__(jsonencode(mk('ode4'))));
assert_isequal(r4.status, 'done');
v4 = evalin('base', 'fc_out'); v4 = v4(:)';

evalin('base', 'clear(''fc_out'')');
rd = jsondecode(__nflow_simulate__(jsonencode(mk('discrete'))));
assert_isequal(rd.status, 'done');
vd = evalin('base', 'fc_out'); vd = vd(:)';

assert_isequal(numel(v4), 11);
assert_istrue(max(abs(v4 - vd)) < 1e-9); % ode4 == discrete
assert_istrue(max(abs(v4 - (3:3:33))) < 1e-9); % 3, 6, 9, ... 33
