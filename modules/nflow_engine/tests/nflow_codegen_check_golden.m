% Shared golden-source harness for the per-block codegen tests (not a test
% itself: no test_ prefix, so the runner does not collect it).
%
%   nflow_codegen_check_golden(category, diagram_names)
%
% category       subdirectory of modules/nflow_gui/tests holding the .nflow
%                fixtures (e.g. 'math'); the goldens live apart from the
%                fixtures, in <category>/golden/<stem>.c.
% diagram_names  cell of fixture stems (e.g. {'test_abs', 'test_gain'}).
%
% Each fixture is regenerated with nflow_codegenerate (C, includeMain) into
% tempdir and its model.c is compared to the golden after normalization:
% CRLF folded to LF, trailing whitespace trimmed, and the version masked in
% the banner line (it embeds NFLOW_PRODUCT_VERSION; goldens must not churn
% on a product-version bump). Goldens are stored in that normalized form.
%
% To regenerate the goldens intentionally (same variable as the b2b golden
% spec), run the test_nf_codegenerate_* scripts with:
%   setenv('NFLOW_UPDATE_GOLDEN', '1')
%=============================================================================
function nflow_codegen_check_golden(category, diagram_names)
  try
    fixtures_root = modulepath('nflow_gui', 'tests');
  catch
    fixtures_root = [nelsonroot(), '/modules/nflow_gui/tests'];
  end
  fixtures_dir = [fixtures_root, filesep, category];
  golden_dir = [fixtures_dir, filesep, 'golden'];
  update = strcmp(getenv('NFLOW_UPDATE_GOLDEN'), '1');
  for i = 1:numel(diagram_names)
    stem = diagram_names{i};
    nflow_codegenerate([fixtures_dir, filesep, stem, '.nflow'], tempdir(), true);
    generated_file = [tempdir(), stem, filesep, 'model.c'];
    assert_istrue(isfile(generated_file));
    generated = normalize_generated(generated_file);
    golden_file = [golden_dir, filesep, stem, '.c'];
    if update
      if ~isdir(golden_dir)
        mkdir(golden_dir);
      end
      fid = fopen(golden_file, 'wb');
      fwrite(fid, generated);
      fclose(fid);
      continue;
    end
    assert_istrue(isfile(golden_file));
    golden = normalize_generated(golden_file);
    if ~strcmp(generated, golden)
      error('nflow_codegen_check_golden: %s differs from golden %s', ...
        generated_file, golden_file);
    end
  end
end
%=============================================================================
function txt = normalize_generated(filename)
  txt = fileread(filename);
  txt = strrep(txt, sprintf('\r\n'), sprintf('\n'));
  txt = regexprep(txt, '/\* Generated by NFlow [^\n]*\*/', '/* Generated by NFlow */');
  txt = [strtrim(txt), sprintf('\n')];
end
