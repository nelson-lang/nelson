% Spline lookups used to emit a 0.0 "not code-generated" marker. The
% generators now bake the axis-0 coefficients per innermost table column and
% reduce every outer axis at run time through shared generated helpers
% (nflow_spl_solve / nflow_spl_val, emitted once). Three spline blocks in one
% model: lookup2D cubic (Linear extrap, inputs sweeping past both edges),
% lookup2D Akima (Clip), and a 3-D lookupND cubic (Clip).
%=============================================================================
t2 = [0 1 4 9, 2 4 8 14, 4 7 12 19]; % z = x^2 + x*y + 2*y on x=0:3, y=0:2
tnd = zeros(1, 27); % t(i,j,k) = i^2 + 2j + 3k + i*j*k on {0,1,2}^3
idx = 1;
for k = 0:2
  for j = 0:2
    for i = 0:2
      tnd(idx) = i ^ 2 + 2 * j + 3 * k + i * j * k;
      idx = idx + 1;
    end
  end
end
d = struct();
d.blocks = {...
  struct('id', 'clk', 'type', 'clock', 'inputs', 0, 'outputs', 1, 'params', struct()), ...
  struct('id', 'e1', 'type', 'expression', 'inputs', 1, 'outputs', 1, ...
    'params', struct('Expr', 'u * 8 - 0.5')), ...
  struct('id', 'e2', 'type', 'expression', 'inputs', 1, 'outputs', 1, ...
    'params', struct('Expr', 'u * 4')), ...
  struct('id', 'e3', 'type', 'expression', 'inputs', 1, 'outputs', 1, ...
    'params', struct('Expr', 'u * 5 - 0.25')), ...
  struct('id', 'lc', 'type', 'lookup2D', 'inputs', 2, 'outputs', 1, ...
    'params', struct('BreakpointsForDimension1', [0 1 2 3], ...
      'BreakpointsForDimension2', [0 1 2], 'Table', t2, ...
      'InterpMethod', 'Cubic spline', 'ExtrapMethod', 'Linear')), ...
  struct('id', 'la', 'type', 'lookup2D', 'inputs', 2, 'outputs', 1, ...
    'params', struct('BreakpointsForDimension1', [0 1 2 3], ...
      'BreakpointsForDimension2', [0 1 2], 'Table', t2, ...
      'InterpMethod', 'Akima spline', 'ExtrapMethod', 'Clip')), ...
  struct('id', 'ln', 'type', 'lookupND', 'inputs', 3, 'outputs', 1, ...
    'params', struct('NumberOfTableDimensions', 3, ...
      'BreakpointsForDimension1', [0 1 2], 'BreakpointsForDimension2', [0 1 2], ...
      'BreakpointsForDimension3', [0 1 2], 'Table', tnd, ...
      'InterpMethod', 'Cubic spline', 'ExtrapMethod', 'Clip')), ...
  struct('id', 'yc', 'type', 'labelSink', 'inputs', 1, 'outputs', 1, ...
    'params', struct('GotoTag', 'yc', 'isExternalPort', true)), ...
  struct('id', 'ya', 'type', 'labelSink', 'inputs', 1, 'outputs', 1, ...
    'params', struct('GotoTag', 'ya', 'isExternalPort', true)), ...
  struct('id', 'yn', 'type', 'labelSink', 'inputs', 1, 'outputs', 1, ...
    'params', struct('GotoTag', 'yn', 'isExternalPort', true)), ...
  struct('id', 'wc', 'type', 'toWorkspace', 'inputs', 1, 'outputs', 0, ...
    'params', struct('VariableName', 'nfsp_c', 'SaveFormat', 'Array', ...
      'Decimation', 1, 'MaxDataPoints', 'inf')), ...
  struct('id', 'wa', 'type', 'toWorkspace', 'inputs', 1, 'outputs', 0, ...
    'params', struct('VariableName', 'nfsp_a', 'SaveFormat', 'Array', ...
      'Decimation', 1, 'MaxDataPoints', 'inf')), ...
  struct('id', 'wn', 'type', 'toWorkspace', 'inputs', 1, 'outputs', 0, ...
    'params', struct('VariableName', 'nfsp_n', 'SaveFormat', 'Array', ...
      'Decimation', 1, 'MaxDataPoints', 'inf'))};
d.connections = {...
  struct('from', 'clk', 'to', 'e1', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'clk', 'to', 'e2', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'clk', 'to', 'e3', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'e1', 'to', 'lc', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'e2', 'to', 'lc', 'fromIndex', 0, 'toIndex', 1), ...
  struct('from', 'e1', 'to', 'la', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'e2', 'to', 'la', 'fromIndex', 0, 'toIndex', 1), ...
  struct('from', 'e3', 'to', 'ln', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'e2', 'to', 'ln', 'fromIndex', 0, 'toIndex', 1), ...
  struct('from', 'e3', 'to', 'ln', 'fromIndex', 0, 'toIndex', 2), ...
  struct('from', 'lc', 'to', 'yc', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'lc', 'to', 'wc', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'la', 'to', 'ya', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'la', 'to', 'wa', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'ln', 'to', 'yn', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'ln', 'to', 'wn', 'fromIndex', 0, 'toIndex', 0)};
d.sampleTime = 0.02;
d.duration = 0.5;
d.variables = struct();
%=============================================================================
r = jsondecode(__nflow_simulate__(jsonencode(d)));
assert_isequal(r.status, 'done');
vc = evalin('base', 'nfsp_c');
assert_istrue(all(isfinite(vc)));
assert_istrue(abs(vc(end)) > 1); % swept well into the table
evalin('base', 'clear(''nfsp_c'', ''nfsp_a'', ''nfsp_n'')');
%=============================================================================
f = [tempname(), '.nflow'];
[~, fstem] = fileparts(f);
fid = fopen(f, 'wt');
fwrite(fid, jsonencode(d));
fclose(fid);
nflow_codegenerate(f, tempdir(), false, 'C');
src = fileread([tempdir(), fstem, '/model.c']);
assert_istrue(isempty(strfind(src, 'not code-generated')));
assert_istrue(~isempty(strfind(src, 'nflow_spl_solve')));
assert_istrue(~isempty(strfind(src, 'nflow_spl_val')));
% Helpers are shared: exactly one definition despite three spline blocks.
assert_isequal(numel(strfind(src, 'static double nflow_spl_val(')), 1);
nflow_codegenerate(f, tempdir(), false, 'rust');
srcR = fileread([tempdir(), fstem, '/src/lib.rs']);
assert_istrue(isempty(strfind(srcR, 'not code-generated')));
assert_isequal(numel(strfind(srcR, 'fn nflow_spl_val(')), 1);
rmfile(f);
%=============================================================================
% Compiled numeric equivalence vs the simulator (both targets).
if __nflow_codegen_toolchain__('C')
  nflow_codegen_check_numeric(d, 'nfsp_num', 'C', ...
    {'yc', 'ya', 'yn'}, {'nfsp_c', 'nfsp_a', 'nfsp_n'}, 5e-6, 1e-9);
  if __nflow_codegen_toolchain__('rust')
    nflow_codegen_check_numeric(d, 'nfsp_num', 'rust', ...
      {'yc', 'ya', 'yn'}, {'nfsp_c', 'nfsp_a', 'nfsp_n'}, 5e-6, 1e-9);
  end
end
