% Composition under the global solver. A single ode4
% run drives, together: a function-call subsystem (a unit-delay counter fired
% twice per major step), a multi-rate discrete block (a unit delay at 2x the base
% step), and a continuous integrator. Each depends on a different piece of the
% solver loop -- ctx.sideEffectFree gating the callee firing, updateRate gating
% the sub-rate discrete update, and the RK4 integrating the continuous state --
% so this confirms they coexist without interfering. The function-call and
% multi-rate results match the fixed-step engine step for step, and the
% integrator matches its analytic value.
%=============================================================================
ctr = struct();
ctr.blocks = {...
  struct('id', 'one', 'type', 'constant', 'inputs', 0, 'outputs', 1, 'params', struct('Value', 1)), ...
  struct('id', 'acc', 'type', 'sum', 'inputs', 2, 'outputs', 1, 'params', struct('Inputs', '++')), ...
  struct('id', 'del', 'type', 'unitDelay', 'inputs', 1, 'outputs', 1, 'params', struct()), ...
  struct('id', 'co', 'type', 'labelSink', 'inputs', 1, 'outputs', 1, 'params', struct('gotoTag', 'y'))};
ctr.connections = {...
  struct('from', 'one', 'to', 'acc', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'del', 'to', 'acc', 'fromIndex', 0, 'toIndex', 1), ...
  struct('from', 'acc', 'to', 'del', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'acc', 'to', 'co', 'fromIndex', 0, 'toIndex', 0)};
ctr.externalOutputs = {struct('id', 'co', 'name', 'y')};
fcSub = ctr;
fcSub.controlPort = struct('kind', 'functionCall');

mk = @(solver) struct('blocks', {{...
  struct('id', 'gen', 'type', 'functionCallGenerator', 'inputs', 0, 'outputs', 1, ...
    'params', struct('NumberOfIterations', 2)), ...
  struct('id', 'sub', 'type', 'subsystem', 'inputs', 1, 'outputs', 1, ...
    'params', struct('subsystem', fcSub, 'controlPort', struct('kind', 'functionCall'))), ...
  struct('id', 'twf', 'type', 'toWorkspace', 'inputs', 1, 'outputs', 0, ...
    'params', struct('VariableName', 'cfc', 'SaveFormat', 'Array', 'Decimation', 1, 'MaxDataPoints', 'inf')), ...
  struct('id', 'rmp', 'type', 'ramp', 'inputs', 0, 'outputs', 1, 'params', struct('slope', 1)), ...
  struct('id', 'ud', 'type', 'unitDelay', 'inputs', 1, 'outputs', 1, ...
    'params', struct('InitialCondition', 0, 'SampleTime', 0.2)), ...
  struct('id', 'twm', 'type', 'toWorkspace', 'inputs', 1, 'outputs', 0, ...
    'params', struct('VariableName', 'cmr', 'SaveFormat', 'Array', 'Decimation', 1, 'MaxDataPoints', 'inf')), ...
  struct('id', 'c', 'type', 'constant', 'inputs', 0, 'outputs', 1, 'params', struct('Value', 2)), ...
  struct('id', 'ig', 'type', 'integrator', 'inputs', 1, 'outputs', 1, 'params', struct()), ...
  struct('id', 'twi', 'type', 'toWorkspace', 'inputs', 1, 'outputs', 0, ...
    'params', struct('VariableName', 'cig', 'SaveFormat', 'Array', 'Decimation', 1, 'MaxDataPoints', 'inf'))}}, ...
  'connections', {{...
    struct('from', 'gen', 'to', 'sub', 'fromIndex', 0, 'toIndex', 0), ...
    struct('from', 'sub', 'to', 'twf', 'fromIndex', 0, 'toIndex', 0), ...
    struct('from', 'rmp', 'to', 'ud', 'fromIndex', 0, 'toIndex', 0), ...
    struct('from', 'ud', 'to', 'twm', 'fromIndex', 0, 'toIndex', 0), ...
    struct('from', 'c', 'to', 'ig', 'fromIndex', 0, 'toIndex', 0), ...
    struct('from', 'ig', 'to', 'twi', 'fromIndex', 0, 'toIndex', 0)}}, ...
  'sampleTime', 0.1, 'duration', 1.0, 'solver', solver, 'variables', struct());
%=============================================================================
function [fc, mr, ig] = run_case(d)
  evalin('base', 'clear(''cfc'', ''cmr'', ''cig'')');
  r = jsondecode(__nflow_simulate__(jsonencode(d)));
  assert_isequal(r.status, 'done');
  fc = evalin('base', 'cfc'); fc = fc(:)';
  mr = evalin('base', 'cmr'); mr = mr(:)';
  ig = evalin('base', 'cig'); ig = ig(:)';
end
%=============================================================================
[fc4, mr4, ig4] = run_case(mk('ode4'));
[fcd, mrd, ~] = run_case(mk('discrete'));

% Function-call counter fires twice per step under ode4, matching discrete.
assert_isequal(numel(fc4), 11);
assert_istrue(max(abs(fc4 - fcd)) < 1e-9);
assert_istrue(max(abs(fc4 - (2:2:22))) < 1e-9);
% Multi-rate staircase, same on both paths.
assert_istrue(max(abs(mr4 - mrd)) < 1e-9);
assert_istrue(max(abs(mr4 - [0 0 0 0.2 0.2 0.4 0.4 0.6 0.6 0.8 0.8])) < 1e-9);
% Continuous state: integral of the constant 2 over [0, 1] = 2.
assert_istrue(abs(ig4(end) - 2.0) < 1e-9);
