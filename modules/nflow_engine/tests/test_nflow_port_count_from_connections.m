% The editor writes each block's port counts as block fields, but a model written
% by hand or by script usually leaves them out. The top level then kept the
% default single port and every wire past the first was silently dropped: a
% two-output subsystem delivered its first output and a flat zero for the second,
% and a demux carrying only its 'Outputs' parameter demuxed into one port. Inner
% diagrams already inferred the counts from the wires; the top level does now too.
%=============================================================================
% A subsystem with two external outputs, no 'outputs' field on the block.
inner = struct();
inner.blocks = {...
  struct('id', 'in1', 'type', 'labelSource', 'x', 60, 'y', 60, 'rotation', 0, ...
    'params', struct('label', 'in1')), ...
  struct('id', 'g2', 'type', 'gain', 'x', 220, 'y', 60, 'rotation', 0, ...
    'params', struct('Gain', 2)), ...
  struct('id', 'g5', 'type', 'gain', 'x', 220, 'y', 200, 'rotation', 0, ...
    'params', struct('Gain', 5)), ...
  struct('id', 'out1', 'type', 'labelSink', 'x', 380, 'y', 60, 'rotation', 0, ...
    'params', struct('label', 'out1')), ...
  struct('id', 'out2', 'type', 'labelSink', 'x', 380, 'y', 200, 'rotation', 0, ...
    'params', struct('label', 'out2'))};
inner.connections = {...
  struct('from', 'in1', 'to', 'g2', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'in1', 'to', 'g5', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'g2', 'to', 'out1', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'g5', 'to', 'out2', 'fromIndex', 0, 'toIndex', 0)};
inner.externalInputs = {struct('id', 'in1', 'name', 'in1')};
inner.externalOutputs = {struct('id', 'out1', 'name', 'out1'), ...
  struct('id', 'out2', 'name', 'out2')};

doc = struct();
doc.version = '1.0.0';
doc.format = 'nflow-2';
doc.name = 'ports_from_connections';
doc.runtime = 0.05;
doc.sampleTime = 0.01;
doc.blocks = {...
  struct('id', 'c', 'type', 'constant', 'x', 40, 'y', 160, 'rotation', 0, ...
    'params', struct('Value', 3)), ...
  struct('id', 'sub', 'type', 'subsystem', 'x', 220, 'y', 160, 'rotation', 0, ...
    'params', struct('name', 'Inner', 'subsystem', inner)), ...
  struct('id', 'w1', 'type', 'toWorkspace', 'x', 420, 'y', 100, 'rotation', 0, ...
    'params', struct('VariableName', 'y_p1', 'SaveFormat', 'Array', ...
    'Decimation', 1, 'MaxDataPoints', 'inf')), ...
  struct('id', 'w2', 'type', 'toWorkspace', 'x', 420, 'y', 240, 'rotation', 0, ...
    'params', struct('VariableName', 'y_p2', 'SaveFormat', 'Array', ...
    'Decimation', 1, 'MaxDataPoints', 'inf'))};
doc.connections = {...
  struct('from', 'c', 'to', 'sub', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'sub', 'to', 'w1', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'sub', 'to', 'w2', 'fromIndex', 1, 'toIndex', 0)};

model = [tempname(), '.nflow'];
fid = fopen(model, 'wt');
fwrite(fid, jsonencode(doc));
fclose(fid);
out = sim(model);
asserts.isapprox(out.y_p1(end), 6, 0, 1e-9);
% The second output used to come back as a flat zero.
asserts.isapprox(out.y_p2(end), 15, 0, 1e-9);
rmfile(model);
%=============================================================================
% A demux whose port count lives only in its 'Outputs' parameter.
doc2 = struct();
doc2.version = '1.0.0';
doc2.format = 'nflow-2';
doc2.name = 'demux_outputs_param';
doc2.runtime = 0.05;
doc2.sampleTime = 0.01;
doc2.blocks = {...
  struct('id', 'a', 'type', 'constant', 'x', 40, 'y', 100, 'rotation', 0, ...
    'params', struct('Value', 7)), ...
  struct('id', 'b', 'type', 'constant', 'x', 40, 'y', 220, 'rotation', 0, ...
    'params', struct('Value', 9)), ...
  struct('id', 'm', 'type', 'mux', 'x', 220, 'y', 160, 'rotation', 0, ...
    'params', struct('Inputs', 2)), ...
  struct('id', 'd', 'type', 'demux', 'x', 380, 'y', 160, 'rotation', 0, ...
    'params', struct('Outputs', 2)), ...
  struct('id', 'w1', 'type', 'toWorkspace', 'x', 560, 'y', 100, 'rotation', 0, ...
    'params', struct('VariableName', 'y_d1', 'SaveFormat', 'Array', ...
    'Decimation', 1, 'MaxDataPoints', 'inf')), ...
  struct('id', 'w2', 'type', 'toWorkspace', 'x', 560, 'y', 240, 'rotation', 0, ...
    'params', struct('VariableName', 'y_d2', 'SaveFormat', 'Array', ...
    'Decimation', 1, 'MaxDataPoints', 'inf'))};
doc2.connections = {...
  struct('from', 'a', 'to', 'm', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'b', 'to', 'm', 'fromIndex', 0, 'toIndex', 1), ...
  struct('from', 'm', 'to', 'd', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'd', 'to', 'w1', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'd', 'to', 'w2', 'fromIndex', 1, 'toIndex', 0)};

model2 = [tempname(), '.nflow'];
fid = fopen(model2, 'wt');
fwrite(fid, jsonencode(doc2));
fclose(fid);
out2 = sim(model2);
asserts.isapprox(out2.y_d1(end), 7, 0, 1e-9);
asserts.isapprox(out2.y_d2(end), 9, 0, 1e-9);
rmfile(model2);
