% Exact-64 and complex signals crossing a subsystem boundary (both ways):
% the seed carries the full descriptor and every storage lane marshals.
%=============================================================================
% uint64 through a subsystem: UINT64_MAX passes exactly (raw JSON keeps the
% literal exact; the value is unrepresentable in a double).
inner = ['{"blocks":[', ...
  '{"id":"in1","type":"labelSource","inputs":0,"outputs":1,"params":{"GotoTag":"in1","isExternalPort":true}},', ...
  '{"id":"g","type":"gain","inputs":1,"outputs":1,"params":{"Gain":1}},', ...
  '{"id":"out1","type":"labelSink","inputs":1,"outputs":1,"params":{"GotoTag":"out1"}}],', ...
  '"connections":[', ...
  '{"from":"in1","to":"g","fromIndex":0,"toIndex":0},', ...
  '{"from":"g","to":"out1","fromIndex":0,"toIndex":0}],', ...
  '"externalInputs":[{"id":"in1","name":"in1"}],', ...
  '"externalOutputs":[{"id":"out1","name":"out1"}]}'];
dj = ['{"blocks":[', ...
  '{"id":"c","type":"constant","inputs":0,"outputs":1,"params":{"Value":18446744073709551615,"OutDataType":"uint64"}},', ...
  '{"id":"sub","type":"subsystem","inputs":1,"outputs":1,"params":{"subsystem":', inner, '}},', ...
  '{"id":"sc","type":"scope","inputs":1,"outputs":0,"params":{}}],', ...
  '"connections":[', ...
  '{"from":"c","to":"sub","fromIndex":0,"toIndex":0},', ...
  '{"from":"sub","to":"sc","fromIndex":0,"toIndex":0}],', ...
  '"sampleTime":0.01,"duration":0.05,"variables":{}}'];
raw = __nflow_simulate__(dj);
r = jsondecode(raw);
assert_isequal(r.status, 'done');
assert_isequal(r.signalTypes.sub{1}, 'uint64');
% the exact digits survive the boundary round-trip
assert_istrue(~isempty(strfind(raw, '18446744073709551615')));
