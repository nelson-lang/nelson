% complex through a subsystem: (3+4i) crosses in, gain 2 inside, |6+8i| = 10.
d2 = struct();
sub2 = struct();
sub2.blocks = {struct('id', 'in1', 'type', 'labelSource', 'inputs', 0, 'outputs', 1, 'params', struct('GotoTag', 'in1', 'isExternalPort', true)), ...
  struct('id', 'g', 'type', 'gain', 'inputs', 1, 'outputs', 1, 'params', struct('Gain', 2)), ...
  struct('id', 'out1', 'type', 'labelSink', 'inputs', 1, 'outputs', 1, 'params', struct('GotoTag', 'out1'))};
sub2.connections = {struct('from', 'in1', 'to', 'g', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'g', 'to', 'out1', 'fromIndex', 0, 'toIndex', 0)};
sub2.externalInputs = {struct('id', 'in1', 'name', 'in1')};
sub2.externalOutputs = {struct('id', 'out1', 'name', 'out1')};
d2.blocks = {struct('id', 'rr', 'type', 'constant', 'inputs', 0, 'outputs', 1, 'params', struct('Value', 3)), ...
  struct('id', 'ii', 'type', 'constant', 'inputs', 0, 'outputs', 1, 'params', struct('Value', 4)), ...
  struct('id', 'ck', 'type', 'realImagToComplex', 'inputs', 2, 'outputs', 1, 'params', struct()), ...
  struct('id', 'sub', 'type', 'subsystem', 'inputs', 1, 'outputs', 1, 'params', struct('subsystem', sub2)), ...
  struct('id', 'mag', 'type', 'abs', 'inputs', 1, 'outputs', 1, 'params', struct()), ...
  struct('id', 'sc', 'type', 'scope', 'inputs', 1, 'outputs', 0, 'params', struct())};
d2.connections = {struct('from', 'rr', 'to', 'ck', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'ii', 'to', 'ck', 'fromIndex', 0, 'toIndex', 1), ...
  struct('from', 'ck', 'to', 'sub', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'sub', 'to', 'mag', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'mag', 'to', 'sc', 'fromIndex', 0, 'toIndex', 0)};
d2.sampleTime = 0.01; d2.duration = 0.05; d2.variables = struct();
r2 = jsondecode(__nflow_simulate__(jsonencode(d2)));
assert_isequal(r2.status, 'done');
assert_istrue(r2.signalComplex.sub(1));
assert_isequal(r2.signals.sub, 6);
assert_isequal(r2.signalsImag.sub, 8);
assert_isequal(r2.signals.mag, 10);
