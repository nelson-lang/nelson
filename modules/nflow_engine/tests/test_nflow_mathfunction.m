% <--WEIGHT 2-->
% Causal parity fill (N8): the mathFunction block applies an elementwise
% function selected by params.Function (sin/cos/.../sqrt/sign). It covers the
% Coselica Blocks.Math scalar-function set in one block and is feedthrough.
%=============================================================================
function p = mf_write(json, stem)
  p = [tempname(), '.nflow'];
  fid = fopen(p, 'w'); fwrite(fid, json); fclose(fid);
end
%=============================================================================
function y = mf_eval(fn, value)
  % A dummy integrator gives the model a continuous state (the fixed-step
  % solver requires one); the mathFunction path is independent and logged at t0.
  m = ['{"blocks":[', ...
    '{"id":"c","type":"constant","inputs":0,"outputs":1,"params":{"Value":', ...
      sprintf('%.15g', value), '}},', ...
    '{"id":"f","type":"mathFunction","inputs":1,"outputs":1,"params":{"Function":"', fn, '"}},', ...
    '{"id":"ig","type":"integrator","inputs":1,"outputs":1,"params":{"InitialCondition":0}},', ...
    '{"id":"td","type":"toWorkspace","inputs":1,"outputs":0,"params":{"VariableName":"d"}},', ...
    '{"id":"tw","type":"toWorkspace","inputs":1,"outputs":0,"params":{"VariableName":"y"}}],', ...
    '"connections":[', ...
      '{"from":"c","to":"f","fromIndex":0,"toIndex":0},', ...
      '{"from":"f","to":"tw","fromIndex":0,"toIndex":0},', ...
      '{"from":"c","to":"ig","fromIndex":0,"toIndex":0},', ...
      '{"from":"ig","to":"td","fromIndex":0,"toIndex":0}],', ...
    '"solver":"ode1","runtime":0.1,"sampleTime":0.1}'];
  out = sim(mf_write(m, ['test_nflow_mf_', fn]));
  lg = out.logsout; nms = {lg.name};
  vals = lg(find(strcmp(nms, 'y'), 1)).values;
  y = vals(1);
end
%=============================================================================
function y = mf_eval2(fn, u1, u2)
  % Two-input functions (pow/hypot/rem/mod): u1 on port 0, u2 on port 1.
  m = ['{"blocks":[', ...
    '{"id":"c1","type":"constant","inputs":0,"outputs":1,"params":{"Value":', sprintf('%.15g', u1), '}},', ...
    '{"id":"c2","type":"constant","inputs":0,"outputs":1,"params":{"Value":', sprintf('%.15g', u2), '}},', ...
    '{"id":"f","type":"mathFunction","inputs":2,"outputs":1,"params":{"Function":"', fn, '"}},', ...
    '{"id":"ig","type":"integrator","inputs":1,"outputs":1,"params":{"InitialCondition":0}},', ...
    '{"id":"td","type":"toWorkspace","inputs":1,"outputs":0,"params":{"VariableName":"d"}},', ...
    '{"id":"tw","type":"toWorkspace","inputs":1,"outputs":0,"params":{"VariableName":"y"}}],', ...
    '"connections":[', ...
      '{"from":"c1","to":"f","fromIndex":0,"toIndex":0},', ...
      '{"from":"c2","to":"f","fromIndex":0,"toIndex":1},', ...
      '{"from":"f","to":"tw","fromIndex":0,"toIndex":0},', ...
      '{"from":"c1","to":"ig","fromIndex":0,"toIndex":0},', ...
      '{"from":"ig","to":"td","fromIndex":0,"toIndex":0}],', ...
    '"solver":"ode1","runtime":0.1,"sampleTime":0.1}'];
  out = sim(mf_write(m, ['test_nflow_mf2_', fn]));
  lg = out.logsout; nms = {lg.name};
  y = lg(find(strcmp(nms, 'y'), 1)).values(1);
end
%=============================================================================
assert_istrue(abs(mf_eval('sqrt', 9) - 3.0) < 1e-12);
assert_istrue(abs(mf_eval('exp', 0) - 1.0) < 1e-12);
assert_istrue(abs(mf_eval('log', exp(2)) - 2.0) < 1e-12);
assert_istrue(abs(mf_eval('log10', 1000) - 3.0) < 1e-12);
assert_istrue(abs(mf_eval('sin', pi / 6) - 0.5) < 1e-12);
assert_istrue(abs(mf_eval('cos', 0) - 1.0) < 1e-12);
assert_istrue(abs(mf_eval('tanh', 0) - 0.0) < 1e-12);
assert_istrue(abs(mf_eval('atan', 1) - pi / 4) < 1e-12);
assert_istrue(abs(mf_eval('sign', -7) - (-1.0)) < 1e-12);
assert_istrue(abs(mf_eval('sign', 0) - 0.0) < 1e-12);
assert_istrue(abs(mf_eval('10^u', 2) - 100.0) < 1e-12);
assert_istrue(abs(mf_eval('square', -3) - 9.0) < 1e-12);
assert_istrue(abs(mf_eval('reciprocal', 4) - 0.25) < 1e-12);
assert_istrue(abs(mf_eval2('pow', 2, 3) - 8.0) < 1e-12);
assert_istrue(abs(mf_eval2('hypot', 3, 4) - 5.0) < 1e-12);
assert_istrue(abs(mf_eval2('rem', -7, 3) - (-1.0)) < 1e-12);
assert_istrue(abs(mf_eval2('mod', -7, 3) - 2.0) < 1e-12);
assert_istrue(abs(mf_eval2('mod', 7, -3) - (-2.0)) < 1e-12);
