% An enabled subsystem inside an enabled subsystem, generated. This used to be
% refused - one level was the documented limit - although the flattener already
% handed every inner member the whole CHAIN of gates it runs under
% (params.__nfgGates) and the generators already wrapped an emission in as many
% guards as the chain is long. The refusal was the only thing in the way.
%
% Two bodies, because they take different paths through the generator: a unit
% delay lowers onto the fused step, an integrator onto the packed RK4 state
% where a closed gate has to freeze its derivative instead. Each is compared
% with the simulation sample by sample.
%=============================================================================
function d = nested_doc(varName, withSolver, innerContinuous)
  if innerContinuous
    body = struct('id', 'i', 'type', 'integrator', 'inputs', 1, 'outputs', 1, ...
      'params', struct('InitialCondition', 0));
  else
    body = struct('id', 'i', 'type', 'unitDelay', 'inputs', 1, 'outputs', 1, ...
      'params', struct('InitialCondition', 0));
  end
  inner = struct();
  inner.blocks = {...
    struct('id', 'in1', 'type', 'labelSource', 'inputs', 0, 'outputs', 1, ...
      'params', struct('label', 'in1')), ...
    body, ...
    struct('id', 'out1', 'type', 'labelSink', 'inputs', 1, 'outputs', 1, ...
      'params', struct('label', 'out1'))};
  inner.connections = {...
    struct('from', 'in1', 'to', 'i', 'fromIndex', 0, 'toIndex', 0), ...
    struct('from', 'i', 'to', 'out1', 'fromIndex', 0, 'toIndex', 0)};
  inner.externalInputs = {struct('id', 'in1', 'name', 'in1')};
  inner.externalOutputs = {struct('id', 'out1', 'name', 'out1')};
  inner.controlPort = struct('kind', 'enable');
  mid = struct();
  mid.blocks = {...
    struct('id', 'in1', 'type', 'labelSource', 'inputs', 0, 'outputs', 1, ...
      'params', struct('label', 'in1')), ...
    struct('id', 'in2', 'type', 'labelSource', 'inputs', 0, 'outputs', 1, ...
      'params', struct('label', 'in2')), ...
    struct('id', 't', 'type', 'subsystem', 'inputs', 2, 'outputs', 1, ...
      'params', struct('subsystem', inner, 'controlPort', struct('kind', 'enable'))), ...
    struct('id', 'out1', 'type', 'labelSink', 'inputs', 1, 'outputs', 1, ...
      'params', struct('label', 'out1'))};
  mid.connections = {...
    struct('from', 'in1', 'to', 't', 'fromIndex', 0, 'toIndex', 0), ...
    struct('from', 'in2', 'to', 't', 'fromIndex', 0, 'toIndex', 1), ...
    struct('from', 't', 'to', 'out1', 'fromIndex', 0, 'toIndex', 0)};
  mid.externalInputs = {struct('id', 'in1', 'name', 'in1'), ...
    struct('id', 'in2', 'name', 'in2')};
  mid.externalOutputs = {struct('id', 'out1', 'name', 'out1')};
  mid.controlPort = struct('kind', 'enable');
  d = struct();
  d.blocks = {...
    struct('id', 'u', 'type', 'constant', 'inputs', 0, 'outputs', 1, ...
      'params', struct('Value', 1)), ...
    struct('id', 'e1', 'type', 'pulse', 'inputs', 0, 'outputs', 1, ...
      'params', struct('Amplitude', 1, 'Period', 0.4, 'Width', 50.0, ...
        'StartTime', 0, 'Offset', 0)), ...
    struct('id', 'e2', 'type', 'pulse', 'inputs', 0, 'outputs', 1, ...
      'params', struct('Amplitude', 1, 'Period', 0.2, 'Width', 50.0, ...
        'StartTime', 0, 'Offset', 0)), ...
    struct('id', 's', 'type', 'subsystem', 'inputs', 3, 'outputs', 1, ...
      'params', struct('subsystem', mid, 'controlPort', struct('kind', 'enable'))), ...
    struct('id', 'y', 'type', 'labelSink', 'inputs', 1, 'outputs', 1, ...
      'params', struct('GotoTag', 'y', 'isExternalPort', true)), ...
    struct('id', 'tw', 'type', 'toWorkspace', 'inputs', 1, 'outputs', 0, ...
      'params', struct('VariableName', varName, 'SaveFormat', 'Array', ...
        'Decimation', 1, 'MaxDataPoints', 'inf'))};
  d.connections = {...
    struct('from', 'u', 'to', 's', 'fromIndex', 0, 'toIndex', 0), ...
    struct('from', 'e2', 'to', 's', 'fromIndex', 0, 'toIndex', 1), ...
    struct('from', 'e1', 'to', 's', 'fromIndex', 0, 'toIndex', 2), ...
    struct('from', 's', 'to', 'y', 'fromIndex', 0, 'toIndex', 0), ...
    struct('from', 's', 'to', 'tw', 'fromIndex', 0, 'toIndex', 0)};
  d.sampleTime = 0.01;
  d.duration = 1.0;
  d.variables = struct();
  if withSolver
    d.solver = 'ode4';
  end
end
%=============================================================================
% Fused path: a unit delay under two enables.
dA = nested_doc('nfcn_a', false, false);
rA = jsondecode(__nflow_simulate__(jsonencode(dA)));
assert_isequal(rA.status, 'done');
yA = evalin('base', 'nfcn_a');
assert_istrue(all(isfinite(yA)));
% The two gates are pulses of 0.4 s and 0.2 s, so the pair is open on the first
% quarter of every 0.4 s and the body holds the rest of the time: the output
% must actually move, and it must also stop.
assert_istrue(max(yA) > 0.5);
assert_istrue(any(diff(yA) == 0));
evalin('base', 'clear(''nfcn_a'')');
%=============================================================================
fA = [tempname(), '.nflow'];
[~, stemA] = fileparts(fA);
fid = fopen(fA, 'wt');
fwrite(fid, jsonencode(dA));
fclose(fid);
nflow_codegenerate(fA, tempdir(), false, 'C');
srcA = fileread([tempdir(), stemA, '/model.c']);
assert_istrue(isempty(strfind(srcA, 'unknown:')));
% Two gates: the outer one guards the inner gate's own emission, and both guard
% the members. One boundary hold per level, each latching under its own gate.
assert_istrue(numel(strfind(srcA, 'out_s__nfg != 0.0')) >= 2);
assert_istrue(numel(strfind(srcA, 'out_s_t__nfg != 0.0')) >= 2);
assert_istrue(~isempty(strfind(srcA, 's->ch_s__nfh0')));
assert_istrue(~isempty(strfind(srcA, 's->ch_s_t__nfh0')));
rmfile(fA);
%=============================================================================
% RK4 seam: an integrator under two enables. A closed gate freezes its packed
% derivative, and the mask has to read the WHOLE chain.
dB = nested_doc('nfcn_b', true, true);
rB = jsondecode(__nflow_simulate__(jsonencode(dB)));
assert_isequal(rB.status, 'done');
yB = evalin('base', 'nfcn_b');
assert_istrue(all(isfinite(yB)));
assert_istrue(max(yB) > 0.05);
evalin('base', 'clear(''nfcn_b'')');
fB = [tempname(), '.nflow'];
[~, stemB] = fileparts(fB);
fid = fopen(fB, 'wt');
fwrite(fid, jsonencode(dB));
fclose(fid);
nflow_codegenerate(fB, tempdir(), false, 'C');
srcB = fileread([tempdir(), stemB, '/model.c']);
assert_istrue(isempty(strfind(srcB, 'unknown:')));
assert_istrue(~isempty(strfind(srcB, '__nflow_rhs'))); % on the RK4 path
assert_istrue(~isempty(strfind(srcB, '__xdot[0] = 0.0;'))); % freeze mask
% The freeze reads both gates, not just the innermost.
assert_istrue(~isempty(strfind(srcB, ' && ')));
rmfile(fB);
%=============================================================================
% A control port carried by the SPEC ROOT alone, with no mirror on the host
% block's params: the shape a subsystem exported through the block packager
% has. The flattener reads the port wherever the spec keeps it, so this lowers
% like any other gate instead of being turned away - and, more to the point, it
% is no longer at risk of being silently dropped.
inner3 = struct();
inner3.blocks = {...
  struct('id', 'in1', 'type', 'labelSource', 'inputs', 0, 'outputs', 1, ...
    'params', struct('label', 'in1')), ...
  struct('id', 'g', 'type', 'gain', 'inputs', 1, 'outputs', 1, ...
    'params', struct('Gain', 3)), ...
  struct('id', 'out1', 'type', 'labelSink', 'inputs', 1, 'outputs', 1, ...
    'params', struct('label', 'out1'))};
inner3.connections = {...
  struct('from', 'in1', 'to', 'g', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'g', 'to', 'out1', 'fromIndex', 0, 'toIndex', 0)};
inner3.externalInputs = {struct('id', 'in1', 'name', 'in1')};
inner3.externalOutputs = {struct('id', 'out1', 'name', 'out1')};
inner3.controlPort = struct('kind', 'enable'); % the ONLY place it is written
dR = struct();
dR.blocks = {...
  struct('id', 'u', 'type', 'ramp', 'inputs', 0, 'outputs', 1, ...
    'params', struct('slope', 1)), ...
  struct('id', 'e', 'type', 'pulse', 'inputs', 0, 'outputs', 1, ...
    'params', struct('Amplitude', 1, 'Period', 0.4, 'Width', 50.0, ...
      'StartTime', 0, 'Offset', 0)), ...
  struct('id', 's', 'type', 'subsystem', 'inputs', 2, 'outputs', 1, ...
    'params', struct('subsystem', inner3)), ...
  struct('id', 'y', 'type', 'labelSink', 'inputs', 1, 'outputs', 1, ...
    'params', struct('GotoTag', 'y', 'isExternalPort', true)), ...
  struct('id', 'tw', 'type', 'toWorkspace', 'inputs', 1, 'outputs', 0, ...
    'params', struct('VariableName', 'nfcn_r', 'SaveFormat', 'Array', ...
      'Decimation', 1, 'MaxDataPoints', 'inf'))};
dR.connections = {...
  struct('from', 'u', 'to', 's', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'e', 'to', 's', 'fromIndex', 0, 'toIndex', 1), ...
  struct('from', 's', 'to', 'y', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 's', 'to', 'tw', 'fromIndex', 0, 'toIndex', 0)};
dR.sampleTime = 0.01;
dR.duration = 1.0;
dR.variables = struct();
rR = jsondecode(__nflow_simulate__(jsonencode(dR)));
assert_isequal(rR.status, 'done');
yR = evalin('base', 'nfcn_r');
% The gate really is in force: the output holds while the pulse is low.
assert_istrue(any(diff(yR) == 0));
evalin('base', 'clear(''nfcn_r'')');
fR = [tempname(), '.nflow'];
[~, stemR] = fileparts(fR);
fid = fopen(fR, 'wt');
fwrite(fid, jsonencode(dR));
fclose(fid);
nflow_codegenerate(fR, tempdir(), false, 'C');
srcR = fileread([tempdir(), stemR, '/model.c']);
assert_istrue(isempty(strfind(srcR, 'unknown:')));
assert_istrue(~isempty(strfind(srcR, 's__nfg'))); % the gate was found
assert_istrue(~isempty(strfind(srcR, 's->ch_s__nfh0'))); % and its boundary hold
rmfile(fR);
%=============================================================================
if __nflow_codegen_toolchain__('C')
  nflow_codegen_check_numeric(dR, 'nfcn_rnum', 'C', {'y'}, {'nfcn_r'}, 5e-6, 1e-9);
  nflow_codegen_check_numeric(dA, 'nfcn_anum', 'C', {'y'}, {'nfcn_a'}, 5e-6, 1e-9);
  nflow_codegen_check_numeric(dB, 'nfcn_bnum', 'C', {'y'}, {'nfcn_b'}, 5e-6, 1e-9);
  if __nflow_codegen_toolchain__('rust')
    nflow_codegen_check_numeric(dA, 'nfcn_anum', 'rust', {'y'}, {'nfcn_a'}, 5e-6, 1e-9);
    nflow_codegen_check_numeric(dB, 'nfcn_bnum', 'rust', {'y'}, {'nfcn_b'}, 5e-6, 1e-9);
  end
end
