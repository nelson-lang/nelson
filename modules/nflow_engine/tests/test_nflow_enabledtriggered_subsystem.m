% B2 (enableTrigger subsystem): a trigger edge is honored ONLY while the enable
% is > 0. Two subsystems share the same trigger (a single rising edge at t=0.5)
% but different enable windows: one is enabled at the edge (fires, counter=1),
% the other is not yet enabled at the edge (misses it, counter=0).
%=============================================================================
evalin('base', 'clear(''et_on'')');
evalin('base', 'clear(''et_off'')');

function s = counter_subsystem()
  s = struct();
  s.blocks = {...
    struct('id', 'one', 'type', 'constant', 'inputs', 0, 'outputs', 1, ...
      'params', struct('Value', 1)), ...
    struct('id', 'acc', 'type', 'sum', 'inputs', 2, 'outputs', 1, ...
      'params', struct('Inputs', '++')), ...
    struct('id', 'del', 'type', 'unitDelay', 'inputs', 1, 'outputs', 1, 'params', struct()), ...
    struct('id', 'cout', 'type', 'labelSink', 'inputs', 1, 'outputs', 1, ...
      'params', struct('gotoTag', 'y'))};
  s.connections = {...
    struct('from', 'one', 'to', 'acc', 'fromIndex', 0, 'toIndex', 0), ...
    struct('from', 'del', 'to', 'acc', 'fromIndex', 0, 'toIndex', 1), ...
    struct('from', 'acc', 'to', 'del', 'fromIndex', 0, 'toIndex', 0), ...
    struct('from', 'acc', 'to', 'cout', 'fromIndex', 0, 'toIndex', 0)};
  s.externalOutputs = {struct('id', 'cout', 'name', 'y')};
  s.controlPort = struct('kind', 'enableTrigger', 'triggerType', 'rising');
end

cp = struct('kind', 'enableTrigger', 'triggerType', 'rising');

d = struct();
d.blocks = {...
  struct('id', 'clk', 'type', 'clock', 'inputs', 0, 'outputs', 1, 'params', struct()), ...
  struct('id', 'trig', 'type', 'compareToConstant', 'inputs', 1, 'outputs', 1, ...
    'params', struct('relop', 'ge', 'const', 0.5)), ...    % rising edge at t=0.5
  struct('id', 'enOn', 'type', 'compareToConstant', 'inputs', 1, 'outputs', 1, ...
    'params', struct('relop', 'ge', 'const', 0.3)), ...    % enabled at the edge
  struct('id', 'enOff', 'type', 'compareToConstant', 'inputs', 1, 'outputs', 1, ...
    'params', struct('relop', 'ge', 'const', 0.6)), ...    % NOT enabled at the edge
  struct('id', 'subOn', 'type', 'subsystem', 'inputs', 2, 'outputs', 1, ...
    'params', struct('subsystem', counter_subsystem(), 'controlPort', cp)), ...
  struct('id', 'subOff', 'type', 'subsystem', 'inputs', 2, 'outputs', 1, ...
    'params', struct('subsystem', counter_subsystem(), 'controlPort', cp)), ...
  struct('id', 'twOn', 'type', 'toWorkspace', 'inputs', 1, 'outputs', 0, ...
    'params', struct('VariableName', 'et_on', 'SaveFormat', 'Array', ...
    'Decimation', 1, 'MaxDataPoints', 'inf')), ...
  struct('id', 'twOff', 'type', 'toWorkspace', 'inputs', 1, 'outputs', 0, ...
    'params', struct('VariableName', 'et_off', 'SaveFormat', 'Array', ...
    'Decimation', 1, 'MaxDataPoints', 'inf'))};
d.connections = {...
  struct('from', 'clk', 'to', 'trig', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'clk', 'to', 'enOn', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'clk', 'to', 'enOff', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'enOn', 'to', 'subOn', 'fromIndex', 0, 'toIndex', 0), ...   % enable port
  struct('from', 'trig', 'to', 'subOn', 'fromIndex', 0, 'toIndex', 1), ...   % trigger port
  struct('from', 'enOff', 'to', 'subOff', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'trig', 'to', 'subOff', 'fromIndex', 0, 'toIndex', 1), ...
  struct('from', 'subOn', 'to', 'twOn', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'subOff', 'to', 'twOff', 'fromIndex', 0, 'toIndex', 0)};
d.sampleTime = 0.1; d.duration = 1.0; d.variables = struct();

r = jsondecode(__nflow_simulate__(jsonencode(d)));
asserts.isequal(r.status, 'done');
vOn = evalin('base', 'et_on');
vOff = evalin('base', 'et_off');
% Enabled at the t=0.5 edge: the trigger is honored -> counter reaches 1.
asserts.isapprox(vOn(end), 1.0, 0, 1e-9);
% Not enabled at the edge: the trigger is missed -> counter stays 0.
asserts.isapprox(vOff(end), 0.0, 0, 1e-9);

evalin('base', 'clear(''et_on'')');
evalin('base', 'clear(''et_off'')');
