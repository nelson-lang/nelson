% Electrical / thermal acausal islands are solved as a DAE by the IDAS runtime;
% code generation must reject them explicitly instead of emitting a constant-0.0
% output. The mechanicalTranslationalIsland is a pure ODE and DOES generate
% (unified RK4 seam). Purely structural (no solver run needed).
%=============================================================================
model = [tempname(), '.nflow'];
[~, modelstem] = fileparts(model);
%=============================================================================
% physicalIsland with a SIGNAL-MODULATED (variable R) element -> rejected for
% both C and Rust: LTV elements are outside the embedded-Newton tier.
islandMsg = _(['Code generation for this physical (acausal) island is not supported: ', ...
  'the embedded-Newton lowering (C and Rust) covers resistor/conductor/capacitor/', ...
  'inductor/source/sensor/diode/radiation islands, but this one uses a component ', ...
  'kind outside that set. Simulate these models with the ''dae'' solver instead.']);
json = ['{"version":"1.0.0","format":"nflow-2","name":"IslandReject",', ...
  '"blocks":[', ...
  '{"id":"b1","type":"physicalIsland","inputs":1,"outputs":1,"x":100,"y":100,"rotation":0,', ...
  '"params":{"domain":"electrical","nodes":3,"components":[', ...
    '{"kind":"vsource","a":1,"b":0,"V":1},', ...
    '{"kind":"variableResistor","a":1,"b":2,"port":0},', ...
    '{"kind":"resistor","a":2,"b":0,"R":1},', ...
    '{"kind":"voltageSensor","a":2,"b":0,"outPort":0}]}},', ...
  '{"id":"b2","type":"scope","x":300,"y":100,"rotation":0,"params":{}}],', ...
  '"connections":[{"from":"b1","fromPort":0,"to":"b2","toPort":0}]}'];
fid = fopen(model, 'wt'); fwrite(fid, json); fclose(fid);
assert_checkerror(['nflow_codegenerate(''', model, ''', tempdir(), false, ''C'')'], islandMsg);
assert_checkerror(['nflow_codegenerate(''', model, ''', tempdir(), false, ''rust'')'], islandMsg);
%=============================================================================
% A PURELY-ALGEBRAIC non-linear island (diode rectifier, no C/L) generates in
% both C and Rust via the embedded-Newton solver.
rect = ['{"version":"1.0.0","format":"nflow-2","name":"RectGen","blocks":[', ...
  '{"id":"src","type":"sine","inputs":0,"outputs":1,"params":{"Amplitude":2,"Frequency":1}},', ...
  '{"id":"blk","type":"physicalIsland","inputs":1,"outputs":1,"params":{', ...
    '"domain":"electrical","nodes":3,"components":[', ...
      '{"kind":"vsource","a":1,"b":0,"port":0},', ...
      '{"kind":"diode","a":1,"b":2,"Is":1e-9,"Vt":0.04},', ...
      '{"kind":"resistor","a":2,"b":0,"R":1000},', ...
      '{"kind":"voltageSensor","a":2,"b":0,"outPort":0}]}},', ...
  '{"id":"y","type":"labelSink","inputs":1,"outputs":1,', ...
  '"params":{"GotoTag":"vout","isExternalPort":true}}],', ...
  '"connections":[{"from":"src","to":"blk","fromIndex":0,"toIndex":0},', ...
  '{"from":"blk","to":"y","fromIndex":0,"toIndex":0}],', ...
  '"solver":"ode4","runtime":2,"sampleTime":0.005}'];
rmodel = [tempname(), '.nflow'];
[~, rmodelstem] = fileparts(rmodel);
fid = fopen(rmodel, 'wt'); fwrite(fid, rect); fclose(fid);
nflow_codegenerate(rmodel, tempdir(), false, 'C');
rc = fileread([tempdir(), rmodelstem, '/model.c']);
assert_istrue(~isempty(strfind(rc, '__isl_res_blk'))); % residual helper
assert_istrue(~isempty(strfind(rc, 'for (int __it'))); % Newton loop
assert_istrue(isempty(strfind(rc, '"physicalIsland"')));
% Rust generates too (embedded Newton mirror).
nflow_codegenerate(rmodel, tempdir(), false, 'rust');
rr = fileread([tempdir(), rmodelstem, '/src/lib.rs']);
assert_istrue(~isempty(strfind(rr, 'fn __isl_res_blk'))); % Rust residual fn
assert_istrue(~isempty(strfind(rr, 'libm::exp'))); % diode via libm
rmfile(rmodel);
%=============================================================================
% A NON-LINEAR + DIFFERENTIAL island (diode rectifier with a smoothing
% capacitor) also generates in C and Rust: the embedded solver adds an implicit
% backward-Euler step (the state carries the capacitor's v_C, and the residual
% helper takes the previous state + dt).
rectC = strrep(rect, '"name":"RectGen"', '"name":"RectCGen"');
rectC = strrep(rectC, '{"kind":"resistor","a":2,"b":0,"R":1000},', ...
  '{"kind":"resistor","a":2,"b":0,"R":1000},{"kind":"capacitor","a":2,"b":0,"C":1e-3,"ic":0},');
cmodel = [tempname(), '.nflow'];
[~, cmodelstem] = fileparts(cmodel);
fid = fopen(cmodel, 'wt'); fwrite(fid, rectC); fclose(fid);
nflow_codegenerate(cmodel, tempdir(), false, 'C');
ccg = fileread([tempdir(), cmodelstem, '/model.c']);
assert_istrue(~isempty(strfind(ccg, '__isl_res_blk')));
assert_istrue(~isempty(strfind(ccg, 'xprev'))); % backward-Euler
assert_istrue(isempty(strfind(ccg, '"physicalIsland"')));
nflow_codegenerate(cmodel, tempdir(), false, 'rust');
rcg = fileread([tempdir(), cmodelstem, '/src/lib.rs']);
assert_istrue(~isempty(strfind(rcg, 'fn __isl_res_blk')));
assert_istrue(~isempty(strfind(rcg, 'xprev'))); % backward-Euler
rmfile(cmodel);
%=============================================================================
% A SWITCH island is non-linear (mode-dependent), so the linear
% reduction skips it and it lowers through the embedded-Newton in both C
% and Rust -- exercising the controlled/coupling stamp set. (A LINEAR
% controlled-source island, e.g. a VCVS amplifier, is instead reduced to a
% state-space block; either way it generates, never rejects.)
sw = ['{"version":"1.0.0","format":"nflow-2","name":"SwGen","blocks":[', ...
  '{"id":"src","type":"constant","inputs":0,"outputs":1,"params":{"Value":5}},', ...
  '{"id":"ctl","type":"constant","inputs":0,"outputs":1,"params":{"Value":1}},', ...
  '{"id":"blk","type":"physicalIsland","inputs":2,"outputs":1,"params":{', ...
    '"domain":"electrical","nodes":3,"components":[', ...
      '{"kind":"vsource","a":1,"b":0,"port":0},{"kind":"switch","a":1,"b":2,"port":1},', ...
      '{"kind":"resistor","a":2,"b":0,"R":1},{"kind":"voltageSensor","a":2,"b":0,"outPort":0}]}},', ...
  '{"id":"y","type":"labelSink","inputs":1,"outputs":1,"params":{"GotoTag":"o","isExternalPort":true}}],', ...
  '"connections":[{"from":"src","to":"blk","fromIndex":0,"toIndex":0},', ...
  '{"from":"ctl","to":"blk","fromIndex":0,"toIndex":1},', ...
  '{"from":"blk","to":"y","fromIndex":0,"toIndex":0}],"solver":"ode4","runtime":1,"sampleTime":0.01}'];
smodel = [tempname(), '.nflow'];
[~, smodelstem] = fileparts(smodel);
fid = fopen(smodel, 'wt'); fwrite(fid, sw); fclose(fid);
nflow_codegenerate(smodel, tempdir(), false, 'C');
scg = fileread([tempdir(), smodelstem, '/model.c']);
assert_istrue(~isempty(strfind(scg, '__isl_res_blk'))); % embedded Newton
assert_istrue(~isempty(strfind(scg, '> 0.5)'))); % switch mode branch
assert_istrue(isempty(strfind(scg, '"physicalIsland"')));
nflow_codegenerate(smodel, tempdir(), false, 'rust');
srg = fileread([tempdir(), smodelstem, '/src/lib.rs']);
assert_istrue(~isempty(strfind(srg, 'fn __isl_res_blk')));
assert_istrue(~isempty(strfind(srg, '> 0.5'))); % Rust switch branch
rmfile(smodel);
%=============================================================================
% mechanicalTranslationalIsland -> NOT rejected: a pure ODE, it lowers to C and
% Rust through the unified RK4 seam. Generation must succeed and emit
% the island's packed state and force balance.
json = ['{"version":"1.0.0","format":"nflow-2","name":"MechCg",', ...
  '"blocks":[', ...
  '{"id":"isl","type":"mechanicalTranslationalIsland","inputs":0,"outputs":1,', ...
  '"x":100,"y":100,"rotation":0,', ...
  '"params":{"domain":"translational","nodes":2,"components":[', ...
    '{"kind":"mass","node":1,"m":1,"s0":1,"v0":0},', ...
    '{"kind":"spring","a":1,"b":0,"k":4},', ...
    '{"kind":"damper","a":1,"b":0,"d":1},', ...
    '{"kind":"positionSensor","node":1,"outPort":0}]}},', ...
  '{"id":"y","type":"labelSink","inputs":1,"outputs":1,', ...
  '"params":{"GotoTag":"y","isExternalPort":true}}],', ...
  '"connections":[{"from":"isl","to":"y","fromIndex":0,"toIndex":0}],', ...
  '"solver":"ode4","runtime":1.0,"sampleTime":0.05}'];
fid = fopen(model, 'wt'); fwrite(fid, json); fclose(fid);
outdir = [tempdir(), modelstem];
nflow_codegenerate(model, tempdir(), false, 'C');
cc = fileread([outdir, '/model.c']);
assert_istrue(~isempty(strfind(cc, 'mech_x_isl_0'))); % packed position state
assert_istrue(~isempty(strfind(cc, 'mech_x_isl_1'))); % packed velocity state
assert_istrue(~isempty(strfind(cc, '__fm_isl_0'))); % force accumulator
assert_istrue(~isempty(strfind(cc, 'out_isl = s->mech_x_isl_0'))); % position sensor
nflow_codegenerate(model, tempdir(), false, 'rust');
rr = fileread([outdir, '/src/lib.rs']);
assert_istrue(~isempty(strfind(rr, 'mech_x_isl_0')));
assert_istrue(~isempty(strfind(rr, 'out_isl = s.mech_x_isl_0')));
%=============================================================================
rmfile(model);
