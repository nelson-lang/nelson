% multiportSwitch: control input (port 0, one-based) selects one of the data
% inputs (ports 1..N). Feedthrough; logged at t0 (an integrator supplies the
% state the fixed-step solver requires).
%=============================================================================
function p = ms_write(json, stem)
  p = [tempname(), '.nflow'];
  fid = fopen(p, 'w'); fwrite(fid, json); fclose(fid);
end
%=============================================================================
function y = ms_eval(ctrl)
  m = ['{"blocks":[', ...
    '{"id":"k","type":"constant","inputs":0,"outputs":1,"params":{"Value":', sprintf('%.15g', ctrl), '}},', ...
    '{"id":"d1","type":"constant","inputs":0,"outputs":1,"params":{"Value":10}},', ...
    '{"id":"d2","type":"constant","inputs":0,"outputs":1,"params":{"Value":20}},', ...
    '{"id":"d3","type":"constant","inputs":0,"outputs":1,"params":{"Value":30}},', ...
    '{"id":"f","type":"multiportSwitch","inputs":4,"outputs":1,"params":{}},', ...
    '{"id":"ig","type":"integrator","inputs":1,"outputs":1,"params":{"InitialCondition":0}},', ...
    '{"id":"td","type":"toWorkspace","inputs":1,"outputs":0,"params":{"VariableName":"d"}},', ...
    '{"id":"tw","type":"toWorkspace","inputs":1,"outputs":0,"params":{"VariableName":"y"}}],', ...
    '"connections":[', ...
      '{"from":"k","to":"f","fromIndex":0,"toIndex":0},', ...
      '{"from":"d1","to":"f","fromIndex":0,"toIndex":1},', ...
      '{"from":"d2","to":"f","fromIndex":0,"toIndex":2},', ...
      '{"from":"d3","to":"f","fromIndex":0,"toIndex":3},', ...
      '{"from":"f","to":"tw","fromIndex":0,"toIndex":0},', ...
      '{"from":"k","to":"ig","fromIndex":0,"toIndex":0},', ...
      '{"from":"ig","to":"td","fromIndex":0,"toIndex":0}],', ...
    '"solver":"ode1","runtime":0.1,"sampleTime":0.1}'];
  out = sim(ms_write(m, 'test_nflow_multiport_switch_eval'));
  lg = out.logsout; nms = {lg.name};
  y = lg(find(strcmp(nms, 'y'), 1)).values(1);
end
%=============================================================================
assert_istrue(abs(ms_eval(1) - 10.0) < 1e-12);
assert_istrue(abs(ms_eval(2) - 20.0) < 1e-12);
assert_istrue(abs(ms_eval(3) - 30.0) < 1e-12);
assert_istrue(abs(ms_eval(0) - 10.0) < 1e-12);
assert_istrue(abs(ms_eval(9) - 30.0) < 1e-12);
% A fractional control selects the port its integer PART names: 1.6 is still
% port 1, and port 2 begins at 2.0.
assert_istrue(abs(ms_eval(1.6) - 10.0) < 1e-12);
assert_istrue(abs(ms_eval(2.0) - 20.0) < 1e-12);
assert_istrue(abs(ms_eval(2.9) - 20.0) < 1e-12);
