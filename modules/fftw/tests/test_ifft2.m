X = [1 2 3; 4 5 6];
Y = ifft2(fft2(X));
asserts.isapprox(Y, X, 1e-12);
Y = ifft2(fft2(X, 4, 5), 4, 5);
asserts.isequal(size(Y), [4 5]);
asserts.isapprox(Y(1:2, 1:3), X, 1e-12);
