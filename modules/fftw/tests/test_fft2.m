asserts.isequal(nargin('fft2'), 3);
asserts.isequal(nargout('fft2'), 1);
%=============================================================================
R = fft2(ones(3, 0));
REF = zeros(3, 0);
asserts.isequal(R, REF);
%=============================================================================
R = fft2(1:5);
REF = [15.0000 + 0.0000i, -2.5000 + 3.4410i, -2.5000 + 0.8123i, -2.5000 - 0.8123i, -2.5000 - 3.4410i];
asserts.isapprox(R, REF, 1e-4);
%=============================================================================
R = fft2(eye(3, 3));
REF = [3.0000 0 0;
  0 0.0000 3.0000;
  0 3.0000 0.0000];
asserts.isapprox(R, REF, 1e-4);
%=============================================================================
R = fft2(Inf);
REF = Inf;
asserts.isequal(R, REF);
%=============================================================================
R = fft2(NaN);
REF = NaN;
asserts.isequal(R, REF);
%=============================================================================
R = fft2(eye(5, 5), 2, 3);
REF = [2.0000 + 0.0000i 0.5000 - 0.8660i 0.5000 + 0.8660i;
  0.0000 + 0.0000i 1.5000 + 0.8660i 1.5000 - 0.8660i];
asserts.isapprox(R, REF, 1e-4);
%=============================================================================
asserts.isequal(fft2(eye(2)), [2 0; 0 2]);
