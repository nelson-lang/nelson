xml_filename = [tempname(), '.xml'];
xsd_filename = [tempname(), '.xsd'];
xslt_filename = [tempname(), '.xslt'];
txt_filename = [tempname(), '.txt'];
%=============================================================================
xml_text = ['<?xml version="1.0" encoding="UTF-8"?>', newline(), ...
  '<root><row id="a">1</row><row id="b">2</row></root>'];
filewrite(xml_filename, xml_text);
doc = xmlread(xml_filename);
asserts.isequal(class(doc), 'xmlDocument');
root = doc.getDocumentElement();
asserts.isequal(root.getTagName(), "root");
asserts.isequal(doc.getElementsByTagName('row').getLength(), 2);
serialized = xmlwrite(doc);
asserts.istrue(contains(serialized, '<root>'));
%=============================================================================
xsd_text = ['<?xml version="1.0" encoding="UTF-8"?>', newline(), ...
  '<xs:schema xmlns:xs="http://www.w3.org/2001/XMLSchema">', newline(), ...
  '  <xs:element name="root">', newline(), ...
  '    <xs:complexType>', newline(), ...
  '      <xs:sequence>', newline(), ...
  '        <xs:element name="row" maxOccurs="unbounded">', newline(), ...
  '          <xs:complexType>', newline(), ...
  '            <xs:simpleContent>', newline(), ...
  '              <xs:extension base="xs:string">', newline(), ...
  '                <xs:attribute name="id" type="xs:string" use="required"/>', newline(), ...
  '              </xs:extension>', newline(), ...
  '            </xs:simpleContent>', newline(), ...
  '          </xs:complexType>', newline(), ...
  '        </xs:element>', newline(), ...
  '      </xs:sequence>', newline(), ...
  '    </xs:complexType>', newline(), ...
  '  </xs:element>', newline(), ...
  '</xs:schema>'];
filewrite(xsd_filename, xsd_text);
[is_valid, errors] = xmlchecker(xml_filename, xsd_filename);
asserts.istrue(is_valid);
asserts.istrue(isempty(errors));
%=============================================================================
xslt_text = ['<?xml version="1.0" encoding="UTF-8"?>', newline(), ...
  '<xsl:stylesheet xmlns:xsl="http://www.w3.org/1999/XSL/Transform" version="1.0">', newline(), ...
  '  <xsl:output method="text" encoding="UTF-8"/>', newline(), ...
  '  <xsl:template match="/">', newline(), ...
  '    <xsl:for-each select="/root/row"><xsl:value-of select="."/>;</xsl:for-each>', newline(), ...
  '  </xsl:template>', newline(), ...
  '</xsl:stylesheet>'];
filewrite(xslt_filename, xslt_text);
asserts.istrue(xmltransform(xml_filename, xslt_filename, txt_filename));
asserts.isequal(fileread(txt_filename), '1;2;');
asserts.isequal(xslt(xml_filename, xslt_filename, '-tostring'), '1;2;');
%=============================================================================
rmfile(xml_filename);
rmfile(xsd_filename);
rmfile(xslt_filename);
rmfile(txt_filename);
