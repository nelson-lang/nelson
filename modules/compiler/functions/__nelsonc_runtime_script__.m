function lines = __nelsonc_runtime_script__(stage, payload, output, plan, options)
  name = ['Nelson Runtime ', plan.runtimeVersion, ' (', plan.architecture, ')'];
  identity = ['Runtime-', plan.architecture, '-', plan.engineFingerprint];
  lines = __nelsonc_inno_setup__(output, name, plan.runtimeVersion, identity, options.InstallerName, options.Compression);
  key = ['Software\Nelson\Runtime\', plan.architecture, '\', plan.engineFingerprint];
  lines = [lines, {...
    'DefaultDirName={code:RuntimeDirectory}', 'DisableDirPage=auto', ...
    ['SetupMutex=Nelson-', identity], ...
    '[Files]', ...
    ['Source: "', parameter(fullfile(stage, 'runtime-package.ini')), '"; Flags: dontcopy touch'], ...
    ['Source: "', parameter(fullfile(payload, '*')), '"; DestDir: "{code:InstallTargetDir}"; Excludes: "\runtime.json,\modules\modules.m"; Flags: onlyifdoesntexist recursesubdirs createallsubdirs touch'], ...
    'Source: "{tmp}\runtime-install.ini"; DestDir: "{code:InstallTargetDir}"; ExternalSize: 0; Flags: external ignoreversion', ...
    'Source: "{tmp}\runtime.json"; DestDir: "{code:InstallTargetDir}"; ExternalSize: 0; Flags: external ignoreversion', ...
    'Source: "{tmp}\modules.m"; DestDir: "{code:InstallTargetDir}\modules"; ExternalSize: 0; Flags: external ignoreversion', ...
    '[Registry]', ...
    ['Root: HKA64; Subkey: "', key, '"; ValueType: string; ValueName: "Root"; ValueData: "{app}"; Check: not PortableInstall'], ...
    '[Code]', 'function RuntimeDirectory(Param: String): String;', 'begin', ...
    '  if IsAdminInstallMode then Result := ExpandConstant(''{commonpf64}'')', ...
    '  else Result := ExpandConstant(''{localappdata}'');', ...
    ['  Result := Result + ''\Nelson\Runtime\', plan.engineFingerprint, ''';'], 'end;', ...
    'function PortableInstall: Boolean;', 'begin', ...
    '  Result := ExpandConstant(''{param:PORTABLE|0}'') = ''1'';', 'end;', ...
    'function RuntimeLockName: String;', 'begin', ...
    ['  Result := ''Global\Nelson-', identity, '-operation'';'], 'end;', ...
    'function RuntimeRegistryKey: String;', 'begin', ['  Result := ''', key, ''';'], 'end;'}];
  code = fileread(fullfile(modulepath('compiler'), 'resources', 'runtime-install.iss'));
  paths = fileread(fullfile(modulepath('compiler'), 'resources', 'installer-paths.iss'));
  code = strrep(code, '// INSTALLER_PATH_CODE', paths);
  recovery = fileread(fullfile(modulepath('compiler'), 'resources', 'runtime-recovery.iss'));
  code = strrep(code, '// RUNTIME_RECOVERY_CODE', recovery);
  lines{end + 1} = code;
end

function value = parameter(value)
  value = strrep(strrep(value, '{', '{{'), '"', '""');
end
