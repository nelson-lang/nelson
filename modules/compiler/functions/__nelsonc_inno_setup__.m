function lines = __nelsonc_inno_setup__(output, name, version, identity, filename, compression)
  architecture = 'x64compatible';
  if strcmp(computer('arch'), 'woa64')
    architecture = 'arm64';
  end
  lines = [{'#preproc builtin'}, native_path(), {'[Setup]', ['AppId=Nelson-', identity], ...
    ['AppName=', strrep(name, '{', '{{')], ['AppVersion=', version], ...
    ['VersionInfoVersion=', version], 'DisableProgramGroupPage=yes', ...
    'PrivilegesRequired=admin', 'PrivilegesRequiredOverridesAllowed=dialog commandline', ...
    ['ArchitecturesAllowed=', architecture], ['ArchitecturesInstallIn64BitMode=', architecture], ...
    ['OutputDir=', output], ['OutputBaseFilename=', filename], ...
    'TimeStampsInUTC=yes', 'TouchDate=1980-01-01', 'TouchTime=00:00:00', ...
    ['Compression=', compression_directive(compression)], 'SolidCompression=yes', 'SetupLogging=yes', ...
    'CloseApplications=no', 'RestartApplications=no', 'ChangesEnvironment=no', ...
    'CreateUninstallRegKey=not PortableInstall', 'Uninstallable=yes', 'WizardStyle=modern'}];
end

function lines = native_path()
  lines = {'[Code]', 'function InstallNativePath(Name: String): String;', 'begin', ...
    '  Result := Name;', '  if Copy(Name, 1, 4) = ''\\?\'' then Exit;', ...
    '  if Copy(Name, 1, 2) = ''\\'' then Result := ''\\?\UNC\'' + Copy(Name, 3, Length(Name))', ...
    '  else Result := ''\\?\'' + Name;', 'end;', ...
    'function InstallTargetDir(Param: String): String;', 'begin', ...
    '  Result := InstallNativePath(ExpandConstant(''{app}''));', 'end;'};
end

function value = compression_directive(compression)
  % Inno Setup payload compression: 'none' disables it, the others select an LZMA2 level.
  if strcmp(compression, 'none')
    value = 'none';
  else
    value = ['lzma2/', compression];
  end
end
