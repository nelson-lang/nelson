rng('twister64');
%=============================================================================
R = rand(3, 4);
REF = [0.7868 0.9467 0.2513 0.3447;
    0.2505 0.0193 0.0227 0.2742;
    0.7107 0.4049 0.5206 0.5610];
asserts.isapprox(R, REF, 1e-4);
%=============================================================================
R = rand(3, 4);
REF = [0.1400 0.8571 0.7443 0.3201;
    0.5439 0.4998 0.2492 0.9105;
    0.5219 0.4194 0.2393 0.1648];
