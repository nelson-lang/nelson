rng('twister')
%=============================================================================
R = rand(3, 4);
REF = [0.8147 0.9134 0.2785 0.9649;
    0.9058 0.6324 0.5469 0.1576;
    0.1270 0.0975 0.9575 0.9706];
asserts.isapprox(R, REF, 1e-4);
%=============================================================================
R = rand(3, 4);
REF = [0.9572 0.1419 0.7922 0.0357;
    0.4854 0.4218 0.9595 0.8491;
    0.8003 0.9157 0.6557 0.9340];
