% Every function terminator produces a synthetic exit statement, and the
% position recorded for it is not a real source position: it lands on an
% unrelated line, and on a different one when the same content is analyzed
% under another path. Requiring the keyword to end the statement text of its
% line is what makes those positions harmless. Analysing several copies guards
% both the false positive and the stability of the reported positions.
manyFunctionsSource = ['y = nelson_lint_many_001(1);', newline(), 'disp(y);', newline()];
for k = 1:150
  manyFunctionsSource = [manyFunctionsSource, ...
    'function r = nelson_lint_many_', sprintf('%03d', k), '(v)', newline(), ...
    '  r = v + 1;', newline(), ...
    '  if r > 100', newline(), ...
    '    r = 100;', newline(), ...
    '    return', newline(), ...
    '  end', newline(), ...
    '  r = r * 2;', newline(), ...
    'end', newline()];
end
manySignature = '';
for copyIndex = 1:8
  manyDirectory = [tempname(), '_many'];
  mkdir(manyDirectory);
  manyFile = fullfile(manyDirectory, 'nelson_lint_many_functions.m');
  filewrite(manyFile, manyFunctionsSource);
  issues = checkcode(manyFile, '-struct', '-id');
  asserts.isfalse(any(strcmp({issues.id}, 'NLS0003')));
  signature = '';
  for issueIndex = 1:numel(issues)
    signature = [signature, issues(issueIndex).id, '@', int2str(issues(issueIndex).line), ';'];
  end
  if copyIndex == 1
    manySignature = signature;
  else
    asserts.isequal(signature, manySignature);
  end
end
