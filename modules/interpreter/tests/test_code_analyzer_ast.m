functionNameMismatchFile = fullfile(fixtureDirectory, 'nelson_lint_expected_name.m');
filewrite(functionNameMismatchFile, ...
  ['function y = nelson_lint_actual_name(x)', newline(), ...
  'y = x;', newline(), ...
  'end', newline()]);
diagnostics = __code_analyzer__(functionNameMismatchFile, false, '', false, true, false, false);
ids = {diagnostics.CheckID};
nameMismatchIndex = find(strcmp(ids, 'NLS0002'), 1);
asserts.istrue(~isempty(nameMismatchIndex));
asserts.isequal(diagnostics(nameMismatchIndex).Fixability, 'safe');
asserts.istrue(numel(diagnostics(nameMismatchIndex).Fixes) >= 1);
asserts.isequal(diagnostics(nameMismatchIndex).Fixes(1).ReplacementText, ...
  'nelson_lint_expected_name');

