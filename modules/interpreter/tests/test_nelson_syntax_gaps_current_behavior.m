asserts.isequal(parsestring(sprintf('classdef MyClass\nend')), 'classdef');
asserts.isequal(parsestring(sprintf('classdef (Abstract) MyClass < handle\nend')), 'classdef');
compact_method_classdef = sprintf(['classdef MyClass\n', ...
  '  methods\n', ...
  '    function y = plus(a, b), y = a.Value + b.Value; end\n', ...
  '  end\n', ...
  'end']);
asserts.isequal(parsestring(compact_method_classdef), 'classdef');
compact_method_lines = [...
  "classdef MyClass"; ...
  "  methods"; ...
  "    function y = plus(a, b), y = a.Value + b.Value; end"; ...
  "  end"; ...
  "end"];
asserts.isequal(parsestring(join(compact_method_lines, newline())), 'classdef');
asserts.isequal(parsestring(sprintf('classdef\nend')), 'error');
asserts.isequal(parsestring(sprintf('classdef MissingEnd\nproperties\n  X\nend')), 'error');
%=============================================================================
asserts.isequal(parsestring(sprintf('properties\n  X\nend')), 'error');
asserts.isequal(parsestring(sprintf('methods\n  f()\nend')), 'error');
asserts.isequal(parsestring(sprintf('events\n  Changed\nend')), 'error');
asserts.isequal(parsestring(sprintf('enumeration\n  One\nend')), 'error');
%=============================================================================
nested_function = sprintf(['function y = outer(x)\n', ...
  '  y = inner(x);\n', ...
  '  function z = inner(t)\n', ...
  '    z = t + 1;\n', ...
  '  end\n', ...
  'end']);
asserts.isequal(parsestring(nested_function), 'function');
%=============================================================================
script_local_function = sprintf(['x = helper(41);\n', ...
  'function y = helper(x)\n', ...
  '  y = x + 1;\n', ...
  'end']);
asserts.isequal(parsestring(script_local_function), 'script');
%=============================================================================
asserts.isequal(parsestring('import package.ClassName'), 'script');
asserts.isequal(parsestring('import package.*'), 'script');
asserts.isequal(parsestring('global X Y'), 'script');
%=============================================================================
persistent_function = sprintf(['function y = counter()\n', ...
  '  persistent n\n', ...
  '  y = 1;\n', ...
  'end']);
asserts.isequal(parsestring(persistent_function), 'function');
%=============================================================================
asserts.isequal(parsestring(sprintf('spmd\n  x = 1;\nend')), 'error');
%=============================================================================
asserts.isequal(parsestring('x = f().Field;'), 'script');
asserts.isequal(parsestring('x = f()(1);'), 'script');
asserts.isequal(parsestring('x = f(){1};'), 'script');
%=============================================================================
arguments_repeating = sprintf(['function y = f(x)\n', ...
  'arguments (Repeating)\n', ...
  '  x double\n', ...
  'end\n', ...
  'y = x;\n', ...
  'end']);
asserts.isequal(parsestring(arguments_repeating), 'function');
%=============================================================================
arguments_namevalue = sprintf(['function y = f(opts)\n', ...
  'arguments\n', ...
  '  opts.Method (1,1) string = "linear"\n', ...
  'end\n', ...
  'y = opts.Method;\n', ...
  'end']);
asserts.isequal(parsestring(arguments_namevalue), 'function');
arguments_namevalue_nested = sprintf(['function y = f(opts)\n', ...
  'arguments\n', ...
  '  opts.Inner.Value double = 7\n', ...
  'end\n', ...
  'y = opts.Inner.Value;\n', ...
  'end']);
asserts.isequal(parsestring(arguments_namevalue_nested), 'function');
arguments_namevalue_bad_dot = sprintf(['function y = f(opts)\n', ...
  'arguments\n', ...
  '  opts. double = 7\n', ...
  'end\n', ...
  'y = opts;\n', ...
  'end']);
% The native arguments front-end parses the block permissively and defers any
% structural violation to call time (runtime), so a malformed entry no longer
% fails at parse: the function definition is accepted.
asserts.isequal(parsestring(arguments_namevalue_bad_dot), 'function');
