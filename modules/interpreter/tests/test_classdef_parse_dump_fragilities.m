% Parity check, text-fragility cases (fragilities F1-F3). These are
% the inputs where naive line/character scanning historically went wrong: a
% block keyword inside a comment, block keywords inside a string literal, and
% line continuations inside the header and a property entry. The current parser
% handles them; the exact canonical dumps are pinned here so a future native
% front-end must reproduce them byte for byte.
%=============================================================================
% F1: a block keyword appearing in a comment must not open a block.
f1 = sprintf(['classdef F1\n' ...
  '  properties\n' ...
  '    A = 1\n' ...
  '  end\n' ...
  '  %% methods here is only a comment\n' ...
  '  methods\n' ...
  '    function r = m(obj)\n' ...
  '      r = 1;\n' ...
  '    end\n' ...
  '  end\n' ...
  'end\n']);
expected_f1 = sprintf(['class=F1\n' ...
  'attributes=\n' ...
  'superclasses=\n' ...
  'property=A;attrs=;default=1;validation=;defining=F1\n' ...
  'method=m;static=0;attrs=;line=7;srclen=45\n' ...
  'localfns=0\n']);
asserts.isequal(__classdef_introspect__('parse_dump', f1), expected_f1);
%=============================================================================
% F2: block keywords inside a string literal must stay part of the value.
f2 = sprintf(['classdef F2\n' ...
  '  properties\n' ...
  '    Label = ''end methods properties''\n' ...
  '  end\n' ...
  'end\n']);
expected_f2 = sprintf(['class=F2\n' ...
  'attributes=\n' ...
  'superclasses=\n' ...
  'property=Label;attrs=;default=''end methods properties'';validation=;defining=F2\n' ...
  'localfns=0\n']);
asserts.isequal(__classdef_introspect__('parse_dump', f2), expected_f2);
%=============================================================================
% F3: line continuations in the superclass list and a property entry fold into
% a single logical line before structural parsing.
f3 = sprintf(['classdef F3 < ...\n' ...
  '   handle\n' ...
  '  properties\n' ...
  '    V (1, ...\n' ...
  '       3) double = [1 2 3]\n' ...
  '  end\n' ...
  'end\n']);
expected_f3 = sprintf(['class=F3\n' ...
  'attributes=\n' ...
  'superclasses=handle\n' ...
  'property=V;attrs=;default=[1 2 3];validation=(1, 3) double;defining=F3\n' ...
  'localfns=0\n']);
asserts.isequal(__classdef_introspect__('parse_dump', f3), expected_f3);
%=============================================================================
% F4: a continuation "..." followed by trailing comment text still folds the
% next line into the value (the "..." is not required to end the line).
f4 = sprintf(['classdef F4\n' ...
  '  properties\n' ...
  '    A = 1 + ... trailing comment\n' ...
  '        2\n' ...
  '  end\n' ...
  'end\n']);
expected_f4 = sprintf(['class=F4\n' ...
  'attributes=\n' ...
  'superclasses=\n' ...
  'property=A;attrs=;default=1 + 2;validation=;defining=F4\n' ...
  'localfns=0\n']);
asserts.isequal(__classdef_introspect__('parse_dump', f4), expected_f4);
