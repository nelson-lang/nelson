fixtureDirectory = tempname();
mkdir(fixtureDirectory);
fixtureDirectoryCleanup = onCleanup(@() rmdir(fixtureDirectory, 's')); %#ok<NASGU>
classdefDuplicateProperty = fullfile(fixtureDirectory, 'NelsonLintClassdefDuplicateProperty.m');
filewrite(classdefDuplicateProperty, ...
  ['classdef NelsonLintClassdefDuplicateProperty', newline(), ...
  '  properties', newline(), ...
  '    Value', newline(), ...
  '  end', newline(), ...
  '  properties (Access = private)', newline(), ...
  '    Value = 1', newline(), ...
  '  end', newline(), ...
  'end', newline()]);
issues = checkcode(classdefDuplicateProperty, '-struct', '-id');
ids = {issues.id};
lineNumbers = [issues.line];
messages = {issues.message};
asserts.istrue(any(strcmp(ids, 'NLS0031') & lineNumbers == 6 ...
  & contains(messages, '''Value''')));
diagnostics = __code_analyzer__(classdefDuplicateProperty, false, '', false, true, false, false);
ids = {diagnostics.CheckID};
duplicatePropertyIndex = find(strcmp(ids, 'NLS0031'), 1);
asserts.istrue(~isempty(duplicatePropertyIndex));
asserts.isequal(diagnostics(duplicatePropertyIndex).Fixability, 'none');
asserts.isequal(numel(diagnostics(duplicatePropertyIndex).Fixes), 0);

