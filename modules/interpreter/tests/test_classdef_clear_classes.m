[nelson_exe, execute_option] = nelson_cli_command_for_test();
%=============================================================================
code = ['try, path_test=[modulepath(''interpreter'',''tests''), ''/classdef'']; ', ...
        'addpath(path_test); ', ...
        'h=ClassdefCounter(3); ', ...
        'plainValue=42; ', ...
        'clear classes; ', ...
        'asserts.isfalse(isvar(''h'')); ', ...
        'asserts.istrue(isvar(''plainValue'')); ', ...
        'asserts.isequal(plainValue, 42); ', ...
        'exit(0); catch, exit(1); end'];
cmd = [nelson_exe, execute_option, '"', code, '"'];
status = system(cmd, 60);
asserts.isequal(status, 0);
