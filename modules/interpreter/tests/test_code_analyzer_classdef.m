fixtureDirectory = tempname();
mkdir(fixtureDirectory);
fixtureDirectoryCleanup = onCleanup(@() rmdir(fixtureDirectory, 's')); %#ok<NASGU>
duplicateMethodFile = fullfile(fixtureDirectory, 'NelsonLintClassdefDuplicateMethod.m');
filewrite(duplicateMethodFile, ...
  ['classdef NelsonLintClassdefDuplicateMethod', newline(), ...
  '  methods', newline(), ...
  '    function r = compute(obj)', newline(), ...
  '      r = 1;', newline(), ...
  '    end', newline(), ...
  '    function r = compute(obj, x)', newline(), ...
  '      r = x;', newline(), ...
  '    end', newline(), ...
  '  end', newline(), ...
  'end', newline()]);
issues = checkcode(duplicateMethodFile, '-struct', '-id');
ids = {issues.id};
lineNumbers = [issues.line];
messages = {issues.message};
asserts.istrue(any(strcmp(ids, 'NLS0032') & lineNumbers == 6 ...
  & contains(messages, '''compute''')));

