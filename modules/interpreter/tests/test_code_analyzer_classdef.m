duplicateEventFile = fullfile(fixtureDirectory, 'NelsonLintClassdefDuplicateEvent.m');
filewrite(duplicateEventFile, ...
  ['classdef NelsonLintClassdefDuplicateEvent', newline(), ...
  '  events', newline(), ...
  '    ValueChanged', newline(), ...
  '  end', newline(), ...
  '  events (NotifyAccess = private)', newline(), ...
  '    ValueChanged', newline(), ...
  '  end', newline(), ...
  'end', newline()]);
issues = checkcode(duplicateEventFile, '-struct', '-id');
ids = {issues.id};
lineNumbers = [issues.line];
messages = {issues.message};
asserts.istrue(any(strcmp(ids, 'NLS0033') & lineNumbers == 6 ...
  & contains(messages, '''ValueChanged''')));
diagnostics = __code_analyzer__(duplicateEventFile, false, '', false, true, false, false);
ids = {diagnostics.CheckID};
duplicateEventIndex = find(strcmp(ids, 'NLS0033'), 1);
asserts.istrue(~isempty(duplicateEventIndex));
asserts.isequal(diagnostics(duplicateEventIndex).Fixability, 'safe');
asserts.istrue(numel(diagnostics(duplicateEventIndex).Fixes) >= 1);
asserts.isequal(diagnostics(duplicateEventIndex).Fixes(1).LineStart, 6);
asserts.isequal(diagnostics(duplicateEventIndex).Fixes(1).ReplacementText, '');

