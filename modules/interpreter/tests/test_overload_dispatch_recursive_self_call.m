%=============================================================================
% A function calling itself with a class object in a later argument dispatches
% to the class method like any other call.
%=============================================================================
path_test = [tempdir(), createGUID()];
mkdir(path_test);
filewrite([path_test, '/OverloadDispatchRecursive.m'], ...
  ["classdef OverloadDispatchRecursive"; ...
  "  methods"; ...
  "    function r = overloadDispatchRecFoo(varargin)"; ...
  "      r = 'value method';"; ...
  "    end"; ...
  "  end"; ...
  "end"]);
filewrite([path_test, '/OverloadDispatchRecursiveHandle.m'], ...
  ["classdef OverloadDispatchRecursiveHandle < handle"; ...
  "  methods"; ...
  "    function r = overloadDispatchRecFoo(varargin)"; ...
  "      r = 'handle method';"; ...
  "    end"; ...
  "  end"; ...
  "end"]);
filewrite([path_test, '/overloadDispatchRecFoo.m'], ...
  ["function r = overloadDispatchRecFoo(n, x)"; ...
  "  if n == 0"; ...
  "    r = 'plain function';"; ...
  "  elseif n == 1"; ...
  "    r = overloadDispatchRecFoo(0, OverloadDispatchRecursive());"; ...
  "  elseif n == 2"; ...
  "    r = overloadDispatchRecFoo(0, OverloadDispatchRecursiveHandle());"; ...
  "  else"; ...
  "    r = overloadDispatchRecFoo(n - 1, x);"; ...
  "  end"; ...
  "end"]);
addpath(path_test);
%=============================================================================
asserts.isequal(overloadDispatchRecFoo(0, 5), 'plain function');
asserts.isequal(overloadDispatchRecFoo(1, 5), 'value method');
asserts.isequal(overloadDispatchRecFoo(2, 5), 'handle method');
asserts.isequal(overloadDispatchRecFoo(4, 5), 'handle method');
%=============================================================================
rmpath(path_test);
rmdir(path_test, 's');
