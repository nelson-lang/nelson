counter = ClassdefCounter(2);
asserts.isequal(class(counter), 'ClassdefCounter');
asserts.istrue(ishandle(counter));
asserts.istrue(isobject(counter));
asserts.istrue(isvalid(counter));
asserts.istrue(isa(counter, 'ClassdefCounter'));
asserts.istrue(isa(counter, 'handle'));
asserts.isequal(counter.Count, 2);
asserts.isequal(counter.secretCount(), -5);
counter.setSecretCount(-6);
asserts.isequal(counter.secretCount(), -6);
asserts.isequal(counter.protectedCount(), 100);
asserts.isequal(counter.ReadOnlyCount, 77);
counter.setReadOnlyCount(78);
asserts.isequal(counter.ReadOnlyCount, 78);
asserts.checkerror('counter.ReadOnlyCount = 79;', 'Cannot set property: ReadOnlyCount');
counter.WriteOnlyCount = 89;
asserts.isequal(counter.writeOnlyCount(), 89);
asserts.checkerror('counter.WriteOnlyCount;', 'Cannot get property: WriteOnlyCount');
asserts.checkerror('counter.SecretCount;', 'Cannot get property: SecretCount');
asserts.checkerror('counter.SecretCount = -7;', 'Cannot set property: SecretCount');
asserts.checkerror('counter.ProtectedCount;', 'Cannot get property: ProtectedCount');
asserts.checkerror('counter.ProtectedCount = 101;', 'Cannot set property: ProtectedCount');
sameCounter = counter;
sameCounter.increment(3);
asserts.isequal(counter.Count, 5);
sameCounter.Count = 9;
asserts.isequal(counter.Count, 9);
asserts.isequal(counter.LastEvent, '');
counterStruct = struct(counter);
asserts.isequal(counterStruct.Count, 9);
asserts.isequal(fieldnames(counter), properties(counter));
counterProps = properties(counter);
asserts.istrue(any(strcmp(counterProps, 'ReadOnlyCount')));
asserts.isfalse(any(strcmp(counterProps, 'SecretCount')));
asserts.isfalse(any(strcmp(counterProps, 'ProtectedCount')));
asserts.isfalse(any(strcmp(counterProps, 'WriteOnlyCount')));
asserts.istrue(isprop(counter, 'Count'));
asserts.istrue(ismethod(counter, 'increment'));
counterEvents = events(counter);
asserts.istrue(any(strcmp(counterEvents, 'CountChanged')));
asserts.istrue(any(strcmp(counterEvents, 'ObjectBeingDestroyed')));
counterArrayA = ClassdefCounter(12);
counterArrayB = ClassdefCounter(13);
counterArray = [counterArrayA, counterArrayB];
counterArrayProps = properties(counterArray);
asserts.istrue(any(strcmp(counterArrayProps, 'Count')));
asserts.isfalse(any(strcmp(counterArrayProps, 'SecretCount')));
counterArrayMethods = methods(counterArray);
asserts.istrue(any(strcmp(counterArrayMethods, 'increment')));
asserts.istrue(any(strcmp(fieldnames(counterArray), 'Count')));
asserts.istrue(any(strcmp(events(counterArray), 'CountChanged')));
asserts.istrue(ismethod(counterArray, 'increment'));
asserts.isfalse(ismethod(counterArray, 'missingMethod'));
asserts.isequal(isprop(counterArray, 'Count'), [true, true]);
asserts.isequal(isprop(counterArray, 'SecretCount'), [true, true]);
asserts.isequal(isprop(counterArray, 'missingProperty'), [false, false]);
delete(counterArray);
expandedCounters(3) = ClassdefCounter(21);
