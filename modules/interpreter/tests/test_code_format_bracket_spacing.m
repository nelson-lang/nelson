% A bracket keeps the author's space before it after the validators of an
% arguments or properties declaration ("x(1, 1) double {mustBePositive}")
% and after the parameters of an anonymous function ("@(a) {a, a}").
workdir = tempname();
mkdir(workdir);
workdirCleanup = onCleanup(@() rmdir(workdir, 's')); %#ok<NASGU>
nl = char(10);
expected = ['function y = bs_case(x, n)', nl, ...
  '  arguments', nl, ...
  '    x(1, 1) double {mustBePositive} = 1', nl, ...
  '    n {mustBeInteger, mustBeMember(n, [1, 3])} = 1', nl, ...
  '  end', nl, ...
  '  f = @(a, b) {a + b; a - b};', nl, ...
  '  g = @() {};', nl, ...
  '  h = @(a) [a, a];', nl, ...
  '  k = @(a)[a, a];', nl, ...
  '  y = {f(x, n), g(), h(x), k(n)};', nl, ...
  'end', nl];
fixtureFile = [workdir, '/bs_case.m'];
classSource = ['classdef bs_class', nl, ...
  '  properties', nl, ...
  '    Count(1, 1) double {mustBeInteger, mustBePositive} = 1', nl, ...
  '    Name {mustBeText} = ''a''', nl, ...
  '  end', nl, ...
  '  methods', nl, ...
  '    function r = pairs(obj)', nl, ...
  '      f = @(a) {a, obj.Count};', nl, ...
  '      r = f(obj.Name);', nl, ...
  '    end', nl, ...
  '  end', nl, ...
  'end', nl];
classFile = [workdir, '/bs_class.m'];
%=============================================================================
% Already formatted: unchanged by smartindent.
filewrite(fixtureFile, expected);
smartindent(fixtureFile, 2, false, true);
formatted = strrep(fileread(fixtureFile, 'char', 'native'), char([13, 10]), nl);
asserts.isequal(formatted, expected);
filewrite(classFile, classSource);
smartindent(classFile, 2, false, true);
formatted = strrep(fileread(classFile, 'char', 'native'), char([13, 10]), nl);
asserts.isequal(formatted, classSource);
%=============================================================================
formatCommand = nelson_tool_command_for_test('nelson-format');
filewrite(fixtureFile, expected);
[status, output] = system([formatCommand, ' --check "', fixtureFile, '"']);
asserts.isequal(status, 0);
asserts.isequal(output, '');
[status, output] = system([formatCommand, ' --check "', classFile, '"']);
asserts.isequal(status, 0);
asserts.isequal(output, '');
