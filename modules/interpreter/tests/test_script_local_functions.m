% Interleaved local functions execute, in script order, with the expected values.
path_test = [tempdir(), createGUID()];
mkdir(path_test);
filename = [path_test, '/interleaved_local_run_test.m'];
filewrite(filename, ["interleavedOrder = {};"; ...
  "interleavedOrder{end + 1} = 'start';"; ...
  "interleavedA = interleavedRunFirst(10);"; ...
  "interleavedOrder{end + 1} = 'mid';"; ...
  "function y = interleavedRunFirst(x)"; ...
  "  y = x * 2;"; ...
  "end"; ...
  "interleavedB = interleavedRunSecond(interleavedA);"; ...
  "function z = interleavedRunSecond(x)"; ...
  "  z = x - 1;"; ...
  "end"; ...
  "interleavedOrder{end + 1} = 'end';"]);
run(filename);
asserts.isequal(interleavedA, 20);
asserts.isequal(interleavedB, 19);
asserts.isequal(interleavedOrder, {'start', 'mid', 'end'});
rmdir(path_test, 's');
%=============================================================================
% One-line local functions are accepted (',' or ';' after the signature).
asserts.isequal(parsestring('function y = f(x), y = x; end'), 'function');
asserts.isequal(parsestring('function y = f(x); y = x; end'), 'function');
asserts.isequal(parsestring('function f(), disp(1); end'), 'function');
asserts.isequal(parsestring('function [a] = f(), a = 1; end'), 'function');
