%=============================================================================
% Script statements are allowed after a local function definition.
script_after_local = sprintf(['a = afterHelper(1);\n', ...
  'function y = afterHelper(x)\n', ...
  '  y = x + 1;\n', ...
  'end\n', ...
  'b = a + 1;']);
asserts.isequal(parsestring(script_after_local), 'script');
%=============================================================================
% Local function definitions may be freely interleaved with script statements.
interleaved_local = sprintf(['a = 10;\n', ...
  'function y = interleavedFirst(x)\n', ...
  '  y = x * 2;\n', ...
  'end\n', ...
  'b = interleavedFirst(a);\n', ...
  'function z = interleavedSecond(x)\n', ...
  '  z = x - 1;\n', ...
  'end\n', ...
  'c = interleavedSecond(b);']);
asserts.isequal(parsestring(interleaved_local), 'script');
%=============================================================================
% A local function nested inside a control-flow block is still rejected.
local_in_if_then_script = sprintf(['x = 1;\n', ...
  'if true\n', ...
  '  function y = badInsideIf(a)\n', ...
  '    y = a;\n', ...
  '  end\n', ...
  'end\n', ...
  'z = 2;']);
asserts.isequal(parsestring(local_in_if_then_script), 'error');
