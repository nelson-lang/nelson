%=============================================================================
addpath(path_test);
clear classes;
a = MyClass(42);
asserts.isequal(a.Value, 42);
a0 = MyClass();
asserts.isequal(a0.Value, []);
%=============================================================================
p = Person("Ada", 31);
asserts.isequal(p.Age, 31);
asserts.isequal(p.Name, "Ada");
p.Name = 'Grace';
asserts.isequal(p.Name, "Grace");
p.Name = "Katherine";
asserts.isequal(p.Name, "Katherine");
%=============================================================================
c = Car("MyCar", "Toyota");
asserts.isequal(c.Name, "MyCar");
asserts.isequal(c.Brand, "Toyota");
carOutput = evalc('c.start();');
asserts.istrue(contains(carOutput, 'MyCar started'));
asserts.istrue(contains(carOutput, 'Car brand: Toyota'));
%=============================================================================
t = TemperatureSensor("T1");
asserts.isequal(t.Id, "T1");
asserts.isequal(t.read(), 25);
%=============================================================================
counterA = Counter();
asserts.isequal(counterA.Value, 0);
counterB = counterA;
counterA.increment();
asserts.isequal(counterB.Value, 1);
emptyHandle = EmptyCtorHandle();
asserts.isequal(emptyHandle.Value, 7);
%=============================================================================
c1 = Config();
asserts.isequal(c1.Mode, "default");
c1.Mode = "fast";
c1.Options = struct('limit', 5);
c2 = copy(c1);
c2.Mode = "safe";
asserts.isfalse(c1 == c2);
asserts.isequal(c1.Mode, "fast");
asserts.isequal(c2.Mode, "safe");
asserts.isequal(c2.Options.limit, 5);
%=============================================================================
point = Point2D(3.5, 4.2);
pointOutput = evalc('display(point);');
asserts.istrue(contains(pointOutput, 'Point2D: (3.50, 4.20)'));
pointImplicitOutput = evalc('point');
asserts.istrue(contains(pointImplicitOutput, 'Point2D: (3.50, 4.20)'));
%=============================================================================
device = LoggableDevice("Pump");
device.addLog("Started");
deviceCopy = copy(device);
deviceCopy.addLog("Copied");
asserts.isequal(numel(device.Log), 1);
asserts.isequal(numel(deviceCopy.Log), 2);
deviceOutput = evalc('display(device);');
asserts.istrue(contains(deviceOutput, 'LoggableDevice: Pump (1 log entries)'));
%=============================================================================
rmpath(path_test);
rmdir(path_test, 's');
clear classes;
