workdir = tempname();
mkdir(workdir);

longLineFile = [workdir, '/long_line_case.m'];
filewrite(longLineFile, ['function y = long_line_case(x)', newline(), ...
  'veryLongVariableName = 12345678901234567890;', newline(), ...
  'y = x;', newline(), ...
  'end', newline()]);

configWarning = [workdir, '/warning_config.json'];
filewrite(configWarning, ['{', newline(), ...
  '  "version": 2,', newline(), ...
  '  "rules": {', newline(), ...
  '    "NLS0012": { "level": "warning", "options": { "maxLineLength": 20 } }', newline(), ...
  '  }', newline(), ...
  '}']);
diagnostics = __code_analyzer__(longLineFile, false, configWarning, false, true, false, false);
ids = {diagnostics.CheckID};
severities = {diagnostics.Severity};
lineLengthIndex = find(strcmp(ids, 'NLS0012'), 1);
asserts.istrue(~isempty(lineLengthIndex));
asserts.isequal(severities{lineLengthIndex}, 'warning');

