% <--WEIGHT 4-->
fixtureDirectory = tempname();
mkdir(fixtureDirectory);
addpath(fixtureDirectory);
systemBase = ['mat', 'lab.System'];
%=============================================================================
filewrite([fixtureDirectory, '/ClassdefPlainNontunable.m'], ...
  ["classdef ClassdefPlainNontunable"; ...
  "  properties (Nontunable)"; ...
  "    Value = 1"; ...
  "  end"; ...
  "end"]);
rehash();
asserts.checkerror('ClassdefPlainNontunable();', 'Invalid classdef attribute: Nontunable');
clear classes;
%=============================================================================
filewrite([fixtureDirectory, '/ClassdefUnknownPropertyAttribute.m'], ...
  ["classdef ClassdefUnknownPropertyAttribute"; ...
  "  properties (BogusAttribute)"; ...
  "    Value = 1"; ...
  "  end"; ...
  "end"]);
rehash();
asserts.checkerror('ClassdefUnknownPropertyAttribute();', ...
  'Invalid classdef attribute: BogusAttribute');
clear classes;
%=============================================================================
filewrite([fixtureDirectory, '/ClassdefSystemNontunable.m'], ...
  ['classdef ClassdefSystemNontunable < ', systemBase, newline(), ...
  '  properties (Nontunable)', newline(), ...
  '    Value = 1', newline(), ...
  '  end', newline(), ...
  '  properties (Nontunable = false, Access = public)', newline(), ...
  '    MutableValue = 2', newline(), ...
  '  end', newline(), ...
  'end']);
rehash();
obj = ClassdefSystemNontunable();
asserts.isequal(obj.Value, 1);
asserts.isequal(obj.MutableValue, 2);
meta = metaclass(obj);
names = {meta.PropertyList.Name};
valueProperty = meta.PropertyList(find(strcmp(names, 'Value')));
mutableProperty = meta.PropertyList(find(strcmp(names, 'MutableValue')));
asserts.istrue(valueProperty.Nontunable);
asserts.isfalse(mutableProperty.Nontunable);
asserts.istrue(any(strcmp(valueProperty.Attributes, 'Nontunable')));
%=============================================================================
filewrite([fixtureDirectory, '/ClassdefSystemSetProperties.m'], ...
  ['classdef ClassdefSystemSetProperties < ', systemBase, newline(), ...
  '  properties (Nontunable)', newline(), ...
  '    Value = 1', newline(), ...
  '  end', newline(), ...
  '  methods', newline(), ...
  '    function obj = ClassdefSystemSetProperties(varargin)', newline(), ...
  '      setProperties(obj, nargin, varargin{:});', newline(), ...
  '    end', newline(), ...
  '  end', newline(), ...
  'end']);
rehash();
configuredObj = ClassdefSystemSetProperties('Value', 9);
asserts.isequal(configuredObj.Value, 9);
defaultObj = ClassdefSystemSetProperties();
asserts.isequal(defaultObj.Value, 1);
asserts.checkerror('ClassdefSystemSetProperties("Value");', ...
  _('Property arguments must be name-value pairs.'));
%=============================================================================
filewrite([fixtureDirectory, '/ClassdefSystemNontunableBase.m'], ...
  ['classdef ClassdefSystemNontunableBase < ', systemBase, newline(), ...
  'end']);
filewrite([fixtureDirectory, '/ClassdefSystemNontunableChild.m'], ...
  ["classdef ClassdefSystemNontunableChild < ClassdefSystemNontunableBase"; ...
  "  properties (Nontunable)"; ...
  "    ChildValue = 3"; ...
  "  end"; ...
  "end"]);
rehash();
childObj = ClassdefSystemNontunableChild();
asserts.isequal(childObj.ChildValue, 3);
childMeta = metaclass(childObj);
childNames = {childMeta.PropertyList.Name};
childProperty = childMeta.PropertyList(find(strcmp(childNames, 'ChildValue')));
asserts.istrue(childProperty.Nontunable);
%=============================================================================
filewrite([fixtureDirectory, '/ClassdefSystemNontunableBadValue.m'], ...
  ['classdef ClassdefSystemNontunableBadValue < ', systemBase, newline(), ...
  '  properties (Nontunable = bogus)', newline(), ...
  '    Value = 1', newline(), ...
  '  end', newline(), ...
  'end']);
rehash();
asserts.checkerror('ClassdefSystemNontunableBadValue();', ...
  'Invalid classdef attribute value: Nontunable = bogus');
clear classes;
%=============================================================================
rmpath(fixtureDirectory);
rmdir(fixtureDirectory, 's');
