fixtureDirectory = tempname();
mkdir(fixtureDirectory);
cleanupFixtures = onCleanup(@() rmdir(fixtureDirectory, 's')); %#ok<NASGU>
readabilityChecks = fullfile(fixtureDirectory, 'nelson_lint_readability_checks.m');
filewrite(readabilityChecks, ['function nelson_lint_readability_checks(x)', newline(), ...
  'disp(sprintf(''value: %d'', x));', newline(), ...
  'error(sprintf(''bad value: %d'', x));', newline(), ...
  'display(sprintf(''visible: %d'', x));', newline(), ...
  'warning(sprintf(''warn value: %d'', x));', newline(), ...
  'msg = ''disp(sprintf(''''ignored''''))'';', newline(), ...
  'eval(''x = x + 1'');', newline(), ...
  'evalin(''caller'', ''x = x + 1'');', newline(), ...
  'assignin(''base'', ''x'', x);', newline(), ...
  'load(''workspace_data.mat'');', newline(), ...
  'load workspace_data.mat', newline(), ...
  'data = load(''workspace_data.mat'');', newline(), ...
  'end', newline()]);
issues = checkcode(readabilityChecks, '-struct', '-id');
ids = {issues.id};
lineNumbers = [issues.line];
asserts.istrue(any(strcmp(ids, 'NLS0017') & lineNumbers == 2));
asserts.istrue(any(strcmp(ids, 'NLS0018') & lineNumbers == 3));
asserts.istrue(any(strcmp(ids, 'NLS0017') & lineNumbers == 4));
asserts.istrue(any(strcmp(ids, 'NLS0018') & lineNumbers == 5));
asserts.isfalse(any(strcmp(ids, 'NLS0017') & lineNumbers == 6));
asserts.istrue(any(strcmp(ids, 'NLS0022') & lineNumbers == 7));
asserts.istrue(any(strcmp(ids, 'NLS0022') & lineNumbers == 8));
asserts.istrue(any(strcmp(ids, 'NLS0022') & lineNumbers == 9));
asserts.istrue(any(strcmp(ids, 'NLS0022') & lineNumbers == 10));
asserts.istrue(any(strcmp(ids, 'NLS0022') & lineNumbers == 11));
asserts.isfalse(any(strcmp(ids, 'NLS0022') & lineNumbers == 12));
diagnostics = __code_analyzer__(readabilityChecks, false, '', false, true, false, false);
ids = {diagnostics.CheckID};
displayIndex = find(strcmp(ids, 'NLS0017'), 1);
asserts.istrue(~isempty(displayIndex));
asserts.isequal(diagnostics(displayIndex).Fixability, 'safe');
asserts.istrue(numel(diagnostics(displayIndex).Fixes) >= 1);
asserts.isequal(diagnostics(displayIndex).Fixes(1).ReplacementText, ...
  'fprintf(''value: %d\n'', x)');
sprintfIndex = find(strcmp(ids, 'NLS0018'), 1);
asserts.istrue(~isempty(sprintfIndex));
asserts.isequal(diagnostics(sprintfIndex).Fixability, 'safe');
asserts.istrue(numel(diagnostics(sprintfIndex).Fixes) >= 1);
asserts.isequal(diagnostics(sprintfIndex).Fixes(1).ReplacementText, '''bad value: %d'', x');

