%=============================================================================
% Between two classes, a class listed in the other's InferiorClasses loses the
% dispatch whatever its position; without a relation the leftmost object wins.
%=============================================================================
path_test = [tempdir(), createGUID()];
mkdir(path_test);
filewrite([path_test, '/OverloadDispatchInferior.m'], ...
  ["classdef OverloadDispatchInferior"; ...
  "  methods"; ...
  "    function r = overloadDispatchRankFoo(varargin)"; ...
  "      r = 'inferior';"; ...
  "    end"; ...
  "  end"; ...
  "end"]);
filewrite([path_test, '/OverloadDispatchSuperior.m'], ...
  ["classdef (InferiorClasses = {?OverloadDispatchInferior}) OverloadDispatchSuperior"; ...
  "  methods"; ...
  "    function r = overloadDispatchRankFoo(varargin)"; ...
  "      r = 'superior';"; ...
  "    end"; ...
  "  end"; ...
  "end"]);
filewrite([path_test, '/OverloadDispatchUnrelated.m'], ...
  ["classdef OverloadDispatchUnrelated < handle"; ...
  "  methods"; ...
  "    function r = overloadDispatchRankFoo(varargin)"; ...
  "      r = 'unrelated';"; ...
  "    end"; ...
  "  end"; ...
  "end"]);
addpath(path_test);
%=============================================================================
a = OverloadDispatchInferior();
b = OverloadDispatchSuperior();
u = OverloadDispatchUnrelated();
asserts.isequal(overloadDispatchRankFoo(a, b), 'superior');
asserts.isequal(overloadDispatchRankFoo(b, a), 'superior');
asserts.isequal(overloadDispatchRankFoo(5, a, b), 'superior');
asserts.isequal(overloadDispatchRankFoo(a, 5, b), 'superior');
asserts.isequal(overloadDispatchRankFoo(a, a), 'inferior');
%=============================================================================
% no precedence relation: leftmost object
asserts.isequal(overloadDispatchRankFoo(a, u), 'inferior');
asserts.isequal(overloadDispatchRankFoo(u, a), 'unrelated');
asserts.isequal(overloadDispatchRankFoo(5, u, b), 'unrelated');
%=============================================================================
rmpath(path_test);
rmdir(path_test, 's');
%=============================================================================
