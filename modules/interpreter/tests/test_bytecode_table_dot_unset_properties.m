% The table dot fast path must fall back to the generic path while the
% Properties of a table object is not a scalar struct with the fields it
% needs (inside the constructor before its first assignment, or inside
% set.Properties). The fixture class is named table on purpose: it is
% written to a temporary directory so that it only shadows the table class
% in this test.
%=============================================================================
fixtureDir = tempname();
mkdir(fixtureDir);
lines = { ...
'classdef table', ...
'  properties', ...
'    data', ...
'    Version', ...
'    Properties', ...
'    Trace', ...
'  end', ...
'  methods', ...
'    function obj = table()', ...
'      obj.data = struct(''x'', 1);', ...
'      obj.Trace = {class(obj.Properties)};', ...
'      obj.Properties = struct(''Other'', 2);', ...
'      obj.Trace{end + 1} = class(obj.Properties);', ...
'      obj.Properties = struct(''VariableNames'', {{''x''}});', ...
'    end', ...
'    function obj = set.Properties(obj, value)', ...
'      obj.Trace{end + 1} = class(obj.Properties);', ...
'      obj.Properties = value;', ...
'    end', ...
'  end', ...
'end'};
filewrite([fixtureDir, '/table.m'], strjoin(lines, char(10)));
addpath(fixtureDir);
%=============================================================================
T = table();
trace = T.Trace;
properties = T.Properties;
clear('T');
%=============================================================================
rmpath(fixtureDir);
rmdir(fixtureDir, 's');
%=============================================================================
asserts.isequal(trace, {'double', 'double', 'struct', 'struct'});
asserts.isequal(properties, struct('VariableNames', {{'x'}}));
