function [a, b, c] = bytecode_local_multi_output(x)
  [~, b, c] = localSplit(x);
  a = x;
end
%=============================================================================
function [a, b, c] = localSplit(x)
  a = x;
  b = x + 1;
  c = x + 2;
end
