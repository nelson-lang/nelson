%=============================================================================
function issues = lintIssues(directory, name, lines)
  filename = fullfile(directory, [name, '.m']);
  filewrite(filename, [strjoin(lines, newline()), newline()]);
  found = checkcode(filename, '-struct', '-id');
  issues = struct('id', {found.id}, 'line', {found.line}, 'message', {found.message});
end
