fixtureDirectory = tempname();
mkdir(fixtureDirectory);
fixtureDirectoryCleanup = onCleanup(@() rmdir(fixtureDirectory, 's')); %#ok<NLS0004>
%=============================================================================
% A multiple assignment from a call without parentheses must not crash.
issues = lintIssues(fixtureDirectory, 'nelson_lint_multicall', {...
  'function nelson_lint_multicall(x)', ...
  '[a, b] = peaks;', ...
  '[c, d] = size(x);', ...
  'disp(a + b + c + d);', ...
  'end'});
asserts.istrue(isempty(issues));
