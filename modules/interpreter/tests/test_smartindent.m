complexFile = fullfile(fixtureDirectory, 'smartindent_complex.m');
complexInput = ['function r = smartindent_complex(x)', char(10), ...
  'msg = ''if end else'' % while in comment', char(10), ...
  'switch x', char(10), ...
  'case 1', char(10), ...
  'try', char(10), ...
  'r = msg', char(10), ...
  'catch', char(10), ...
  'r = "catch end"', char(10), ...
  'end', char(10), ...
  'otherwise', char(10), ...
  'r = "otherwise"', char(10), ...
  'end', char(10), ...
  'end'];
complexExpected = ['function r = smartindent_complex(x)', char(10), ...
  '  msg = ''if end else'' % while in comment', char(10), ...
  '  switch x', char(10), ...
  '    case 1', char(10), ...
  '      try', char(10), ...
  '        r = msg', char(10), ...
  '      catch', char(10), ...
  '        r = "catch end"', char(10), ...
  '      end', char(10), ...
  '    otherwise', char(10), ...
  '      r = "otherwise"', char(10), ...
  '  end', char(10), ...
  'end'];
filewrite(complexFile, complexInput);
smartindent(complexFile);
asserts.isequal(strrep(fileread(complexFile, 'char', 'native'), char([13, 10]), char(10)), complexExpected);

