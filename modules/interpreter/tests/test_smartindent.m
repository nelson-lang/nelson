% Contextual class block names remain ordinary identifiers in executable code.
contextualFile = fullfile(fixtureDirectory, 'smartindent_contextual.m');
contextualInput = ['properties=[1 2];', char(10), ...
  'properties(1)=3;', char(10), ...
  'properties', char(10), ...
  'methods=struct(''value'',4);', char(10), ...
  'methods.value=methods.value+1;', char(10), ...
  'events={6};', char(10), ...
  'events{1}=events{1}+1;', char(10), ...
  'enumeration=@(x)x+8;', char(10), ...
  'enumeration(1);', char(10), ...
  'arguments=[9 10];', char(10), ...
  'arguments(1)=11;'];
contextualExpected = ['properties = [1 2];', char(10), ...
  'properties(1) = 3;', char(10), ...
  'properties', char(10), ...
  'methods = struct(''value'', 4);', char(10), ...
  'methods.value = methods.value + 1;', char(10), ...
  'events = {6};', char(10), ...
  'events{1} = events{1} + 1;', char(10), ...
  'enumeration = @(x) x + 8;', char(10), ...
  'enumeration(1);', char(10), ...
  'arguments = [9 10];', char(10), ...
  'arguments(1) = 11;'];
filewrite(contextualFile, contextualInput);
smartindent(contextualFile, 2, false, false);
asserts.isequal(strrep(fileread(contextualFile, 'char', 'native'), char([13, 10]), char(10)), contextualInput);
smartindent(contextualFile, 2, false, true);
asserts.isequal(strrep(fileread(contextualFile, 'char', 'native'), char([13, 10]), char(10)), contextualExpected);
smartindent(contextualFile, 2, false, true);
asserts.isequal(strrep(fileread(contextualFile, 'char', 'native'), char([13, 10]), char(10)), contextualExpected);
contextualOutput = evalc('run(contextualFile);');
asserts.isequal(properties, [3 2]);
asserts.isequal(methods.value, 5);
asserts.isequal(events{1}, 7);
asserts.isequal(enumeration(1), 9);
asserts.isequal(arguments, [11 10]);

% A lexer token covering an arguments block must not duplicate its source lines.
argumentsFile = fullfile(fixtureDirectory, 'smartindent_arguments_probe.m');
argumentsInput = ['function y = smartindent_arguments_probe(x)', char(10), ...
  'arguments', char(10), ...
  'x = 1', char(10), ...
  'end', char(10), ...
  'properties=[x 2];', char(10), ...
  'properties(1)=properties(1)+1;', char(10), ...
  'y=properties(1);', char(10), ...
  'end'];
argumentsExpected = ['function y = smartindent_arguments_probe(x)', char(10), ...
  '  arguments', char(10), ...
  '    x = 1', char(10), ...
  '  end', char(10), ...
  '  properties = [x 2];', char(10), ...
  '  properties(1) = properties(1) + 1;', char(10), ...
  '  y = properties(1);', char(10), ...
  'end'];
filewrite(argumentsFile, argumentsInput);
smartindent(argumentsFile, 2, false, true);
asserts.isequal(strrep(fileread(argumentsFile, 'char', 'native'), char([13, 10]), char(10)), argumentsExpected);
smartindent(argumentsFile, 2, false, true);
asserts.isequal(strrep(fileread(argumentsFile, 'char', 'native'), char([13, 10]), char(10)), argumentsExpected);
addpath(fixtureDirectory);
asserts.isequal(smartindent_arguments_probe(3), 4);
rmpath(fixtureDirectory);

