% <--REUSE PROCESS-->
%=============================================================================
% A bracketed left-hand side with a single target behaves as a plain
% assignment for any right-hand side expression.
%=============================================================================
s = [10 20 30];
%=============================================================================
[a] = s(1);
assert_isequal(a, 10);
%=============================================================================
[a] = s;
assert_isequal(a, [10 20 30]);
%=============================================================================
[a] = s(1) + s(2);
assert_isequal(a, 30);
%=============================================================================
[a] = (s(1));
assert_isequal(a, 10);
%=============================================================================
[a] = -s(2);
assert_isequal(a, -20);
%=============================================================================
c = {7, 8, 9};
[d] = c{2};
assert_isequal(d, 8);
%=============================================================================
[a] = deal(5);
assert_isequal(a, 5);
%=============================================================================
[a] = max([3 9 2]);
assert_isequal(a, 9);
%=============================================================================
% Single target with parenthesized indexing stays a plain indexed assignment.
%=============================================================================
v = [0 0 0];
[v(2)] = 7;
assert_isequal(v, [0 7 0]);
%=============================================================================
v = [0 0 0];
[v(3)] = s(1) + 5;
assert_isequal(v, [0 0 15]);
%=============================================================================
% Multiple targets keep the multiple-output function call behavior.
%=============================================================================
[m, n] = size([1 2 3; 4 5 6]);
assert_isequal(m, 2);
assert_isequal(n, 3);
%=============================================================================
[p, q] = deal(2, 1);
assert_isequal(p, 2);
assert_isequal(q, 1);
%=============================================================================
% A single brace target expands as a comma-list (multiple outputs).
%=============================================================================
D = {0, 0};
[D{1:2}] = deal(10, 20);
assert_isequal(D, {10, 20});
%=============================================================================
% An invalid multiple-output right-hand side is rejected.
%=============================================================================
assert_checkerror('eval(''[a, b] = 5;'')', _('Expecting a function call on the right hand side of a multiple assignment'));
