% <--WEIGHT 8-->
path_test = [modulepath('interpreter', 'tests'), '/classdef'];
addpath(path_test);
%=============================================================================
reload_dir = tempname();
if ~isdir(reload_dir)
  mkdir(reload_dir);
end
reload_file = [reload_dir, '/ClassdefReloadable.m'];
reloadSource = ["classdef ClassdefReloadable"; ...
  "  properties"; ...
  "    Payload = 1"; ...
  "  end"; ...
  "  properties (Constant)"; ...
  "    Version = 1"; ...
  "    ObsoleteConstant = 101"; ...
  "  end"; ...
  "  methods"; ...
  "    function r = value(obj)"; ...
  "      r = 1;"; ...
  "    end"; ...
  "  end"; ...
  "  methods (Static)"; ...
  "    function r = staticValue()"; ...
  "      r = 10;"; ...
  "    end"; ...
  "    function r = oldStatic()"; ...
  "      r = 100;"; ...
  "    end"; ...
  "  end"; ...
  "end"];
filewrite(reload_file, reloadSource);
addpath(reload_dir);
reloadObj = ClassdefReloadable();
asserts.isequal(reloadObj.value(), 1);
asserts.isequal(reloadObj.Payload, 1);
asserts.isequal(ClassdefReloadable.Version, 1);
asserts.isequal(ClassdefReloadable.ObsoleteConstant, 101);
asserts.isequal(ClassdefReloadable.staticValue(), 10);
asserts.isequal(ClassdefReloadable.oldStatic(), 100);
reloadMeta = metaclass('ClassdefReloadable');
asserts.istrue(any(strcmp({reloadMeta.PropertyList.Name}, 'Payload')));
asserts.istrue(any(strcmp({reloadMeta.PropertyList.Name}, 'Version')));
asserts.istrue(any(strcmp({reloadMeta.PropertyList.Name}, 'ObsoleteConstant')));
asserts.istrue(any(strcmp({reloadMeta.MethodList.Name}, 'staticValue')));
asserts.istrue(any(strcmp({reloadMeta.MethodList.Name}, 'oldStatic')));
reloadSource = ["classdef ClassdefReloadable"; ...
  "  properties"; ...
  "    Payload = 2"; ...
  "    ExtraInstance = 3"; ...
  "  end"; ...
  "  properties (Constant)"; ...
  "    Version = 2"; ...
  "    Extra = 202"; ...
  "  end"; ...
  "  methods"; ...
  "    function r = value(obj)"; ...
  "      r = 2;"; ...
  "    end"; ...
  "  end"; ...
  "  methods (Static)"; ...
  "    function r = staticValue()"; ...
  "      r = 20;"; ...
  "    end"; ...
  "    function r = newStatic()"; ...
  "      r = 200;"; ...
  "    end"; ...
  "  end"; ...
  "end"];
filewrite(reload_file, reloadSource);
clear classes;
reloadObj = ClassdefReloadable();
asserts.isequal(reloadObj.value(), 2);
asserts.isequal(reloadObj.Payload, 2);
asserts.isequal(reloadObj.ExtraInstance, 3);
asserts.isequal(ClassdefReloadable.Version, 2);
asserts.isequal(ClassdefReloadable.Extra, 202);
asserts.isequal(ClassdefReloadable.staticValue(), 20);
asserts.isequal(ClassdefReloadable.newStatic(), 200);
reloadMeta = metaclass('ClassdefReloadable');
asserts.istrue(any(strcmp({reloadMeta.PropertyList.Name}, 'Payload')));
asserts.istrue(any(strcmp({reloadMeta.PropertyList.Name}, 'ExtraInstance')));
asserts.istrue(any(strcmp({reloadMeta.PropertyList.Name}, 'Version')));
asserts.istrue(any(strcmp({reloadMeta.PropertyList.Name}, 'Extra')));
asserts.isfalse(any(strcmp({reloadMeta.PropertyList.Name}, 'ObsoleteConstant')));
asserts.istrue(any(strcmp({reloadMeta.MethodList.Name}, 'staticValue')));
asserts.istrue(any(strcmp({reloadMeta.MethodList.Name}, 'newStatic')));
asserts.isfalse(any(strcmp({reloadMeta.MethodList.Name}, 'oldStatic')));
try
  ClassdefReloadable.ObsoleteConstant;
  error('Obsolete constant should be unavailable after clear classes.');
catch M
  asserts.istrue(contains(M.message, 'No such property') ...
    || contains(M.message, 'Undefined classdef member') ...
    || contains(M.message, _('Undefined variable or function:')));
end
try
  ClassdefReloadable.oldStatic();
  error('Obsolete static method should be unavailable after clear classes.');
catch M
  asserts.istrue(contains(M.message, 'No such property') ...
    || contains(M.message, 'Function not found') ...
    || contains(M.message, _('Function not found.')) ...
    || contains(M.message, 'Undefined classdef member') ...
    || contains(M.message, 'Undefined') ...
    || contains(M.message, _('Undefined variable or function:')));
end
reloadNested = struct('object', reloadObj, 'payload', {{ClassdefReloadable()}});
reloadSaveFile = [tempname(), '.nh5'];
save(reloadSaveFile, 'reloadNested');
clear reloadNested reloadObj;
clear classes;
load(reloadSaveFile);
asserts.isequal(class(reloadNested.object), 'ClassdefReloadable');
asserts.isequal(reloadNested.object.Payload, 2);
asserts.isequal(reloadNested.object.ExtraInstance, 3);
asserts.isequal(class(reloadNested.payload{1}), 'ClassdefReloadable');
asserts.isequal(reloadNested.payload{1}.Payload, 2);
asserts.isequal(reloadNested.payload{1}.value(), 2);
rmfile(reloadSaveFile);
rmpath(reload_dir);
rmdir(reload_dir, 's');
%=============================================================================
invalid_runtime_dir = tempname();
if ~isdir(invalid_runtime_dir)
  mkdir(invalid_runtime_dir);
end
addpath(invalid_runtime_dir);
filewrite([invalid_runtime_dir, '/ClassdefInvalidAttributeRuntime.m'], ...
  ["classdef (Bogus) ClassdefInvalidAttributeRuntime"; ...
  "end"]);
rehash();
asserts.checkerror('ClassdefInvalidAttributeRuntime();', 'Invalid classdef attribute: Bogus');
clear classes;
asserts.isequal(parsefile([path_test, '/ClassdefInvalidAccessRuntime.m']), 'error');
clear classes;
filewrite([invalid_runtime_dir, '/ClassdefMissingSuperclassRuntime.m'], ...
  ["classdef ClassdefMissingSuperclassRuntime < ClassdefNoSuchBaseRuntime"; ...
  "end"]);
rehash();
asserts.checkerror('ClassdefMissingSuperclassRuntime();', ...
  'Superclass not found: ClassdefNoSuchBaseRuntime');
clear classes;
rmpath(invalid_runtime_dir);
rmdir(invalid_runtime_dir, 's');
%=============================================================================
rmpath(path_test);
