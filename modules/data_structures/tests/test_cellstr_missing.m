% cellstr converts <missing> to empty text
%=============================================================================
c = cellstr(string(missing));
assert_isequal(c, {''});
assert_isequal(class(c{1}), 'char');
assert_isequal(size(c{1}), [0 0]);
%=============================================================================
c = cellstr(["a" missing; "b" "c"]);
assert_isequal(c, {'a', ''; 'b', 'c'});
%=============================================================================
s = "a";
s(3) = "c";
assert_isequal(cellstr(s), {'a', '', 'c'});
