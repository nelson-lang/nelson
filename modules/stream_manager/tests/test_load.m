folder = tempname();
mkdir(folder);
filename = fullfile(folder, 'load_direct.nh5');
%=============================================================================
A = magic(3);
B = 'load direct test';
save(filename, 'A', 'B');
clear A B;
%=============================================================================
st = load(filename);
asserts.isequal(st.A, magic(3));
asserts.isequal(st.B, 'load direct test');
%=============================================================================
load(filename, 'A');
asserts.isequal(A, magic(3));
%=============================================================================
rmfile(filename);
rmdir(folder);
