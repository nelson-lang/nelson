asserts.isequal(nanmax([1 NaN 5 NaN 3]), 5);
%=============================================================================
[m, i] = nanmax([3 NaN 5; 2 8 NaN], [], 1);
asserts.isequal(m, [3 8 5]);
asserts.isequal(i, [1 2 1]);
%=============================================================================
[m, i] = nanmax([3 NaN 5; 2 8 NaN], [], 2);
asserts.isequal(m, [5; 8]);
asserts.isequal(i, [3; 2]);
%=============================================================================
asserts.isequal(nanmax([1 NaN 5], [2 3 NaN]), [2 3 5]);
%=============================================================================
asserts.isequal(nanmax([NaN NaN]), NaN);
