X = randn(3000, 30);
tic();
R = corr(X);
t = toc();
asserts.isequal(size(R), [30 30]);
asserts.istrue(t >= 0);
%=============================================================================
X(1:29:end) = NaN;
tic();
R = corr(X, 'Rows', 'pairwise');
t = toc();
asserts.isequal(size(R), [30 30]);
asserts.istrue(t >= 0);
%=============================================================================
Y = randn(3000, 12);
tic();
R = corr(X(:, 1:12), Y, 'Type', 'Spearman', 'Rows', 'pairwise');
t = toc();
asserts.isequal(size(R), [12 12]);
asserts.istrue(t >= 0);
