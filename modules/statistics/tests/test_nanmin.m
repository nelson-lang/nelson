asserts.isequal(nanmin([4 NaN 1 NaN 3]), 1);
%=============================================================================
[m, i] = nanmin([3 NaN 5; 2 8 NaN], [], 1);
asserts.isequal(m, [2 8 5]);
asserts.isequal(i, [2 2 1]);
%=============================================================================
[m, i] = nanmin([3 NaN 5; 2 8 NaN], [], 2);
asserts.isequal(m, [3; 2]);
asserts.isequal(i, [1; 1]);
%=============================================================================
asserts.isequal(nanmin([1 NaN 5], [2 3 NaN]), [1 3 5]);
%=============================================================================
asserts.isequal(nanmin([NaN NaN]), NaN);
