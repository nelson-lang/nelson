X = rand(40000, 8);
X(1:19:end) = NaN;
tic();
Y = nanmedian(X);
t = toc();
asserts.isequal(size(Y), [1 8]);
asserts.istrue(t >= 0);
%=============================================================================
A = rand(60, 40, 8);
A(1:29:end) = NaN;
tic();
Z = nanmedian(A, [1 2]);
t = toc();
asserts.isequal(size(Z), [1 1 8]);
asserts.istrue(t >= 0);
