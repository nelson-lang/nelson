asserts.isequal(nargin('expcdf'), 3);
asserts.isequal(nargout('expcdf'), 1);
%=============================================================================
x = [-1 0 0.5 2 Inf];
mu = [1 1 2 3 4];
R = expcdf(x, mu);
REF = [0 0 0.221199216928595 0.486582880967408 1];
asserts.isapprox(R, REF, 1e-12);
%=============================================================================
R = expcdf(x, mu, 'upper');
REF = [1 1 0.778800783071405 0.513417119032592 0];
asserts.isapprox(R, REF, 1e-12);
%=============================================================================
R = expcdf([0 1 2]);
asserts.isapprox(R, [0 0.632120558828558 0.864664716763387], 1e-12);
%=============================================================================
R = expcdf(single(x), single(mu));
asserts.isequal(class(R), 'single');
asserts.isapprox(R, single([0 0 0.221199216928595 0.486582880967408 1]), 1e-6);
%=============================================================================
R = expcdf([NaN 1 1], [1 -1 NaN]);
asserts.istrue(all(isnan(R)));
%=============================================================================
R = expcdf([], []);
asserts.isequal(size(R), [0 0]);
%=============================================================================
asserts.checkerror('expcdf(ones(2), ones(3))', _('Size mismatch on input arguments'));
asserts.checkerror('expcdf(1, 1, ''bad'')', sprintf(_('Invalid %s distribution option.'), 'exponential'));
asserts.checkerror('expcdf({1}, 1)', sprintf(_('%s must be real numeric.'), 'X'));
asserts.checkerror('expcdf(1, {1})', sprintf(_('%s must be real numeric.'), 'MU'));
%=============================================================================
asserts.isapprox(expcdf(2, 4), 1 - exp(-0.5), 1e-12);
