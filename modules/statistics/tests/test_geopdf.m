asserts.isequal(nargin('geopdf'), 2);
asserts.isequal(nargout('geopdf'), 1);
%=============================================================================
x = [0 1 2 5];
R = geopdf(x, 0.25);
asserts.isapprox(R, [0.25 0.1875 0.140625 0.059326171875], 1e-15);
%=============================================================================
R = geopdf([0 1 2], [0.25 0.5 1]);
asserts.isapprox(R, [0.25 0.25 0], 1e-15);
%=============================================================================
R = geopdf(single([0 1 2]), single(0.25));
asserts.isequal(class(R), 'single');
asserts.isapprox(double(R), [0.25 0.1875 0.140625], 1e-7);
%=============================================================================
R = geopdf([-1 1.5 Inf NaN 0 0], [0.25 0.25 0.25 0.25 -0.1 1.1]);
asserts.isapprox(R(1:3), [0 0 0], 1e-15);
asserts.istrue(all(isnan(R(4:6))));
R = geopdf([0 1], [0 1]);
asserts.isapprox(R, [0 0], 1e-15);
%=============================================================================
R = geopdf([], []);
asserts.isequal(size(R), [0 0]);
%=============================================================================
asserts.checkerror('geopdf(ones(2), ones(3))', _('Size mismatch on input arguments'));
asserts.checkerror('geopdf({1}, 0.5)', sprintf(_('%s must be real numeric.'), 'X'));
asserts.checkerror('geopdf(1, {0.5})', _('P must be a numeric array in the range [0,1].'));
%=============================================================================
asserts.isapprox(geopdf(2, 0.25), 0.75 ^ 2 * 0.25, 1e-12);
asserts.istrue(isnan(geopdf(0, -0.1)));
