asserts.isequal(nargin('chi2inv'), 2);
asserts.isequal(nargout('chi2inv'), 1);
%=============================================================================
p = [0.025 0.5 0.975];
R = chi2inv(p, 4);
REF = [0.484418557087930 3.35669398003332 11.1432867818778];
asserts.isapprox(R, REF, 1e-11);
%=============================================================================
p = [0 0.001 0.025 0.5 0.975 1];
v = [1 2 3 4 5 6];
R = chi2inv(p, v);
REF = [0 0.00200100066716707 0.215795282623898 ...
       3.35669398003332 12.8325019940302 Inf];
asserts.isapprox(R(1:5), REF(1:5), 1e-11);
asserts.istrue(isinf(R(6)) && R(6) > 0);
%=============================================================================
R = chi2inv(single([0.025 0.5 0.975]), single([1 2 3]));
asserts.isequal(class(R), 'single');
asserts.isapprox(R, single([0.000982069117175255 1.38629436111989 9.34840360449615]), 1e-5);
%=============================================================================
R = chi2inv([-0.1 1.1 NaN 0 1], 2);
asserts.istrue(all(isnan(R(1:3))));
asserts.isequal(R(4), 0);
asserts.istrue(isinf(R(5)) && R(5) > 0);
%=============================================================================
R = chi2inv([], []);
asserts.isequal(size(R), [0 0]);
%=============================================================================
asserts.checkerror('chi2inv(ones(2), ones(3))', _('Size mismatch on input arguments'));
asserts.checkerror('chi2inv({0.5}, 2)', sprintf(_('%s must be real numeric.'), 'P'));
asserts.checkerror('chi2inv(0.5, {2})', sprintf(_('%s must be real numeric.'), 'V'));
%=============================================================================
asserts.isapprox(chi2inv(chi2cdf(2, 4), 4), 2, 1e-12);
