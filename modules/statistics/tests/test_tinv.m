asserts.isequal(nargin('tinv'), 2);
asserts.isequal(nargout('tinv'), 1);
%=============================================================================
p = [0 0.025 0.5 0.975 1];
v = [1 2 5 10 Inf];
R = tinv(p, v);
REF = [-Inf -4.30265272974946 0 2.22813885198627 Inf];
asserts.istrue(isinf(R(1)) && R(1) < 0);
asserts.isapprox(R(2:4), REF(2:4), 1e-11);
asserts.istrue(isinf(R(5)) && R(5) > 0);
%=============================================================================
R = tinv(0.5, [1 2 5 10 Inf]);
asserts.isequal(R, [0 0 0 0 0]);
%=============================================================================
R = tinv([0.5 0.975], Inf);
REF = [0 1.95996398454005];
asserts.isapprox(R, REF, 1e-12);
%=============================================================================
R = tinv(single([0.025 0.5 0.975]), single([1 2 5]));
asserts.isequal(class(R), 'single');
asserts.isapprox(R, single([-12.7062047364321 0 2.57058183563631]), 1e-5);
asserts.isequal(tinv(single(0.5), single([1 2 5])), single([0 0 0]));
%=============================================================================
R = tinv([-0.1 1.1 NaN 0 1], 5);
asserts.istrue(all(isnan(R(1:3))));
asserts.istrue(isinf(R(4)) && R(4) < 0);
asserts.istrue(isinf(R(5)) && R(5) > 0);
%=============================================================================
R = tinv([], []);
asserts.isequal(size(R), [0 0]);
%=============================================================================
asserts.checkerror('tinv(ones(2), ones(3))', _('Size mismatch on input arguments'));
asserts.checkerror('tinv({0.5}, 2)', sprintf(_('%s must be real numeric.'), 'P'));
asserts.checkerror('tinv(0.5, {2})', sprintf(_('%s must be real numeric.'), 'V'));
%=============================================================================
asserts.isequal(tinv(0.5, 5), 0);
