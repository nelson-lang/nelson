n = 1000;
X = randn(n, 8);
Y = randn(n, 5);
Z = randn(n, 3);
tic();
R = partialcorri(Y, X, Z);
t = toc();
asserts.isequal(size(R), [5 8]);
asserts.istrue(t >= 0);
%=============================================================================
tic();
R = partialcorri(Y, X, 'Type', 'Spearman');
t = toc();
asserts.isequal(size(R), [5 8]);
asserts.istrue(t >= 0);
