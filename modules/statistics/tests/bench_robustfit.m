n = 3000;
X = randn(n, 6);
beta = [4; -2; 1; 0.5; -0.25; 0.75; 1.5];
y = [ones(n, 1), X] * beta + 0.1 * randn(n, 1);
y(1:200:end) = y(1:200:end) + 12;
tic();
[b, stats] = robustfit(X, y);
t = toc();
asserts.isequal(size(b), [7 1]);
asserts.isequal(length(stats.resid), n);
asserts.istrue(t >= 0);
