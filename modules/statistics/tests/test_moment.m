asserts.isequal(nargin('moment'), -3);
asserts.isequal(nargout('moment'), 1);
%=============================================================================
X = [0.5377 -0.4336 0.7254 1.4090 0.4889; ...
     1.8339 0.3426 -0.0631 1.4172 1.0347; ...
    -2.2588 3.5784 0.7147 0.6715 0.7269; ...
     0.8622 2.7694 -0.2050 -1.2075 -0.3034; ...
     0.3188 -1.3499 -0.1241 0.7172 0.2939; ...
    -1.3077 3.0349 1.4897 1.6302 -0.7873];
m = moment(X, 3);
asserts.isapprox(m, [-1.114317297123259 -0.997267318261260 0.123395588389407 ...
                    -1.102322260825926 -0.104560266348759], 1e-12);
%=============================================================================
A = zeros(4, 3, 2);
A(:, :, 1) = [0.5377 0.3188 3.5784; ...
              1.8339 -1.3077 2.7694; ...
             -2.2588 -0.4336 -1.3499; ...
              0.8622 0.3426 3.0349];
A(:, :, 2) = [0.7254 -0.1241 0.6715; ...
             -0.0631 1.4897 -1.2075; ...
              0.7147 1.4090 0.7172; ...
             -0.2050 1.4172 1.6302];
M1 = moment(A, 4);
asserts.isapprox(M1(:, :, 1), [11.442394531893287 0.355338544936619 33.673184429093418], 1e-12);
asserts.isapprox(M1(:, :, 2), [0.036041892279158 0.490179723794366 2.382081633264558], 1e-12);
M2 = moment(A, 4, 2);
asserts.isapprox(M2(:, :, 1), [7.347356173805583; 13.870057013328696; ...
                              0.462418667468267; 2.773986910844348], 1e-12);
asserts.isapprox(M2(:, :, 2), [0.034127792361341; 2.239000243299763; ...
                              0.017089642572040; 0.676673019602859], 1e-12);
M3 = moment(A, 4, 3);
expectedM3 = [0.000077577737192 0.002404931653211 4.462727663348193; ...
              0.809374170930063 3.827351062099657 15.633589351405227; ...
              4.885981167353441 0.720450728183816 1.141105937836488; ...
              0.081070580662682 0.083342660921864 0.243340472518548];
asserts.isapprox(M3(:), expectedM3(:), 1e-12);
asserts.isapprox(moment(A, 3, 'all'), 0.243116207471213, 1e-12);
M4 = moment(A, 3, [1 2]);
asserts.isequal(size(M4), [1 1 2]);
asserts.isapprox(M4(:), [0.600181036053087; -0.347464028593259], 1e-12);
M5 = moment(A, 3, [2 3]);
asserts.isapprox(M5(:), [2.755144864879407; 0.044319105006906; ...
                        -0.758406484945074; 0.533977440121500], 1e-12);
%=============================================================================
asserts.istrue(all(abs(moment([1 2 3], 1)) < 1e-12));
asserts.isapprox(moment([1 2 3], 2), 2 / 3, 1e-12);
M6 = moment([1 2 3], 3, 3);
asserts.isequal(size(M6), [1 3]);
asserts.isequal(M6, [0 0 0]);
asserts.istrue(isnan(moment([1 NaN 3], 2)));
S = moment(single([1 2 4 8]), 2);
asserts.isequal(class(S), 'single');
asserts.isapprox(double(S), 7.1875, 1e-6);
%=============================================================================
asserts.checkerror('moment()', _('Not enough input arguments.'));
asserts.checkerror('moment([1 2])', _('Not enough input arguments.'));
asserts.checkerror('moment({1}, 2)', sprintf(_('%s must be a real numeric array.'), 'X'));
asserts.checkerror('moment([1 2], 0)', sprintf(_('%s must be a positive integer scalar.'), 'ORDER'));
asserts.checkerror('moment([1 2], 1.5)', sprintf(_('%s must be a positive integer scalar.'), 'ORDER'));
asserts.checkerror('moment([1 2], 2, 0)', _('Dimension must be a positive integer scalar, vector, or ''all''.'));
asserts.checkerror('moment([1 2], 2, ''bad'')', _('Dimension must be a positive integer scalar, vector, or ''all''.'));
