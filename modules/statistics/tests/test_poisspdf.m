asserts.isequal(nargin('poisspdf'), 2);
asserts.isequal(nargout('poisspdf'), 1);
%=============================================================================
x = [0 1 2 5 10];
lambda = [0.5 1 2 4 8];
R = poisspdf(x, lambda);
REF = [0.606530659712633 0.367879441171442 0.270670566473225 ...
       0.156293451850532 0.0992615338315354];
asserts.isapprox(R, REF, 1e-12);
%=============================================================================
R = poisspdf([0 1 1.5 -1], 2);
asserts.isapprox(R, [0.135335283236613 0.270670566473225 0 0], 1e-12);
%=============================================================================
R = poisspdf([0 1], 0);
asserts.isequal(R, [1 0]);
%=============================================================================
R = poisspdf(single(x), single(lambda));
asserts.isequal(class(R), 'single');
asserts.isapprox(R, single(REF), 1e-6);
%=============================================================================
R = poisspdf([NaN 1 1], [2 -1 NaN]);
asserts.istrue(all(isnan(R)));
%=============================================================================
R = poisspdf([], []);
asserts.isequal(size(R), [0 0]);
%=============================================================================
asserts.checkerror('poisspdf(ones(2), ones(3))', _('Size mismatch on input arguments'));
asserts.checkerror('poisspdf({1}, 2)', sprintf(_('%s must be real numeric.'), 'X'));
asserts.checkerror('poisspdf(1, {2})', _('LAMBDA must be a nonnegative numeric array.'));
%=============================================================================
asserts.isapprox(poisspdf(3, 3), exp(-3) * 27 / 6, 1e-12);
asserts.istrue(isnan(poisspdf(1, -1)));
