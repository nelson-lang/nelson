asserts.isequal(nargin('partialcorr'), -2);
asserts.isequal(nargout('partialcorr'), 2);
%=============================================================================
X = [1 2 3 4; 2 3 4 8; 3 5 6 9; 4 7 8 13; 5 11 10 17; 6 13 12 20];
[R, P] = partialcorr(X);
REF = [1 -0.702812720609497 0.898176062283386 0.743236728824047; ...
       -0.702812720609497 1 0.846475251355421 0.654653670707977; ...
       0.898176062283386 0.846475251355421 1 -0.521064659987864; ...
       0.743236728824047 0.654653670707977 -0.521064659987864 1];
asserts.isapprox(R, REF, 1e-12);
REFP = [0 0.297187279390503 0.101823937716614 0.256763271175953; ...
        0.297187279390503 0 0.153524748644578 0.345346329292023; ...
        0.101823937716614 0.153524748644578 0 0.478935340012136; ...
        0.256763271175953 0.345346329292023 0.478935340012136 0];
asserts.isapprox(P, REFP, 1e-12);
%=============================================================================
Z = [1 0; 1 1; 2 1; 2 0; 3 1; 3 0];
[R, P] = partialcorr(X(:, 1:3), Z);
REF = [1 0.768221279597376 0.986393923832144; ...
       0.768221279597376 1 0.863014469346935; ...
       0.986393923832144 0.863014469346935 1];
asserts.isapprox(R, REF, 1e-12);
REFP = [0 0.231778720402624 0.013606076167856; ...
        0.231778720402624 0 0.136985530653065; ...
        0.013606076167856 0.136985530653065 0];
asserts.isapprox(P, REFP, 1e-12);
%=============================================================================
Y = [6 4; 5 8; 4 10; 3 13; 2 18; 1 21];
[R, P] = partialcorr(X(:, 1:2), Y, Z, 'Tail', 'right');
asserts.isapprox(R, [-1 0.941741911594837; -0.768221279597376 0.938783490773443], 1e-12);
asserts.isapprox(P, [1 0.029129044202581; 0.884110639798688 0.030608254613278], 1e-12);
%=============================================================================
R = partialcorr(X(:, 1:3), Z, 'Type', 'Spearman');
asserts.isapprox(R, ones(3, 3), 1e-12);
%=============================================================================
Xn = X;
Xn(3, 2) = NaN;
R = partialcorr(Xn(:, 1:3), Z, 'Rows', 'all');
asserts.isapprox(R, [1 NaN 0.986393923832144; NaN NaN NaN; 0.986393923832144 NaN 1], 1e-12);
R = partialcorr(Xn(:, 1:3), Z, 'Rows', 'complete');
REF = [1 0.794066667176744 0.992583333970930; ...
       0.794066667176744 1 0.862068965517241; ...
       0.992583333970930 0.862068965517241 1];
asserts.isapprox(R, REF, 1e-12);
%=============================================================================
asserts.checkerror('partialcorr()', _('Not enough input arguments.'));
asserts.checkerror('partialcorr({1})', sprintf(_('%s must be a real numeric matrix.'), 'X'));
asserts.checkerror('partialcorr([1; 2], {1})', sprintf(_('%s must be a real numeric matrix.'), 'Z'));
asserts.checkerror('partialcorr([1; 2], [1; 2], {1})', sprintf(_('%s must be a real numeric matrix.'), 'Z'));
asserts.checkerror('partialcorr([1; 2], [1 2])', sprintf(_('%s must have the same number of rows.'), 'X, Y, and Z'));
asserts.checkerror('partialcorr([1; 2], ''Type'', ''kendall'')', sprintf(_('%s has an unsupported value.'), 'TYPE'));
asserts.checkerror('partialcorr([1; 2], ''Rows'', ''bad'')', sprintf(_('%s has an unsupported value.'), 'ROWS'));
asserts.checkerror('partialcorr([1; 2], ''Tail'', ''bad'')', sprintf(_('%s has an unsupported value.'), 'TAIL'));
