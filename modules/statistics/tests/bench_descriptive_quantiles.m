n = 12000;
p = 12;
X = randn(n, p);
tic();
Q = quantile(X, [0.1 0.5 0.9], 1);
t1 = toc();
asserts.isequal(size(Q), [3 p]);
asserts.istrue(t1 >= 0);
%=============================================================================
tic();
P = prctile(X, [25 50 75], 1);
t2 = toc();
asserts.isequal(size(P), [3 p]);
asserts.istrue(t2 >= 0);
%=============================================================================
tic();
R = iqr(X, 1);
t3 = toc();
asserts.isequal(size(R), [1 p]);
asserts.istrue(t3 >= 0);
%=============================================================================
tic();
Z = zscore(X, 0, 1);
t4 = toc();
asserts.isequal(size(Z), [n p]);
asserts.istrue(t4 >= 0);
