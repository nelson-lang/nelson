X = rand(2000, 6);
Y = rand(500, 6);
tic();
[idx, D] = rangesearch(X, Y, 0.4);
t = toc();
asserts.isequal(size(idx), [500 1]);
asserts.isequal(size(D), [500 1]);
asserts.istrue(t >= 0);
