asserts.isequal(nargin('tpdf'), 2);
asserts.isequal(nargout('tpdf'), 1);
%=============================================================================
x = [-3 -1 0 1 3];
v = [1 2 5 10 Inf];
R = tpdf(x, v);
REF = [0.0318309886183791 0.192450089729875 0.379606689822494 ...
       0.230361989229139 0.00443184841193801];
asserts.isapprox(R, REF, 1e-12);
%=============================================================================
R = tpdf([0 1], Inf);
REF = [0.398942280401433 0.241970724519143];
asserts.isapprox(R, REF, 1e-12);
%=============================================================================
R = tpdf(single(x), single(v));
asserts.isequal(class(R), 'single');
asserts.isapprox(R, single([0.0318309886183791 0.192450089729875 0.379606689822494 ...
                           0.230361989229139 0.00443184841193801]), 1e-6);
%=============================================================================
R = tpdf([-Inf Inf NaN 0 1], [5 5 5 -1 NaN]);
asserts.isequal(R(1), 0);
asserts.isequal(R(2), 0);
asserts.istrue(all(isnan(R(3:5))));
%=============================================================================
R = tpdf([], []);
asserts.isequal(size(R), [0 0]);
%=============================================================================
asserts.checkerror('tpdf(ones(2), ones(3))', _('Size mismatch on input arguments'));
asserts.checkerror('tpdf({1}, 2)', sprintf(_('%s must be real numeric.'), 'X'));
asserts.checkerror('tpdf(1, {2})', sprintf(_('%s must be real numeric.'), 'V'));
%=============================================================================
asserts.isapprox(tpdf(0, 1), 1 / pi, 1e-12);
