X = randn(50000, 12);
tic();
Y = trimmean(X, 20);
t = toc();
asserts.isequal(size(Y), [1 12]);
asserts.istrue(t >= 0);
%=============================================================================
A = randn(90, 70, 10);
tic();
Z = trimmean(A, 10, [1 2]);
t = toc();
asserts.isequal(size(Z), [1 1 10]);
asserts.istrue(t >= 0);
