n = 100000;
rng(0);
x = raylrnd(2, n, 1);
%=============================================================================
tic();
[phat, pci] = raylfit(x);
t_fit = toc();
asserts.isequal(size(phat), [1 1]);
asserts.isequal(size(pci), [2 1]);
%=============================================================================
tic();
[nlogL, avar] = rayllike(phat, x);
t_like = toc();
asserts.isequal(size(nlogL), [1 1]);
asserts.isequal(size(avar), [1 1]);
%=============================================================================
asserts.istrue(all([t_fit t_like] >= 0));
