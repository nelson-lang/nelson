x = [2 4 4 4 5 5 7 9];
%=============================================================================
[n, c] = hist(x, 3);
assert_isequal(n, [4 2 2]);
assert_isapprox(c, [3.1666666666666665 5.5 7.833333333333333], 1e-10);
%=============================================================================
n = hist(x);
assert_isequal(n, [1 0 3 0 2 0 0 1 0 1]);
%=============================================================================
[n, c] = hist(x, [3 5 7]);
assert_isequal(n, [4 2 2]);
assert_isequal(c, [3 5 7]);
%=============================================================================
n = hist(x, 4);
assert_isequal(n, [1 5 1 1]);
%=============================================================================
n = hist([1 1 1], 1);
assert_isequal(n, 3);
