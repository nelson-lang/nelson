asserts.isequal(nargin('poisscdf'), 3);
asserts.isequal(nargout('poisscdf'), 1);
%=============================================================================
x = [0 1 2 5 10];
lambda = [0.5 1 2 4 8];
R = poisscdf(x, lambda);
REF = [0.606530659712633 0.735758882342885 0.676676416183063 ...
       0.785130387030405 0.815885792558547];
asserts.isapprox(R, REF, 1e-12);
%=============================================================================
R = poisscdf(x, lambda, 'upper');
REF = [0.393469340287367 0.264241117657115 0.323323583816937 ...
       0.214869612969595 0.184114207441453];
asserts.isapprox(R, REF, 1e-12);
%=============================================================================
R = poisscdf([1.5 -1 Inf], 2);
asserts.isapprox(R(1:2), [0.406005849709838 0], 1e-12);
asserts.isequal(R(3), 1);
%=============================================================================
R = poisscdf([0 1], 0);
asserts.isequal(R, [1 1]);
%=============================================================================
R = poisscdf(single(x), single(lambda));
asserts.isequal(class(R), 'single');
asserts.isapprox(R, single([0.606530659712633 0.735758882342885 0.676676416183063 ...
                           0.785130387030405 0.815885792558547]), 1e-6);
%=============================================================================
R = poisscdf([NaN 1 1], [2 -1 NaN]);
asserts.istrue(all(isnan(R)));
%=============================================================================
R = poisscdf([], []);
asserts.isequal(size(R), [0 0]);
%=============================================================================
asserts.checkerror('poisscdf(ones(2), ones(3))', _('Size mismatch on input arguments'));
asserts.checkerror('poisscdf(1, 2, ''bad'')', sprintf(_('Invalid %s distribution option.'), 'Poisson'));
asserts.checkerror('poisscdf({1}, 2)', sprintf(_('%s must be real numeric.'), 'X'));
asserts.checkerror('poisscdf(1, {2})', _('LAMBDA must be a nonnegative numeric array.'));
%=============================================================================
asserts.isapprox(poisscdf(2, 3), exp(-3) * (1 + 3 + 9 / 2), 1e-12);
