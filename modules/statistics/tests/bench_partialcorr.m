X = randn(1000, 12);
Z = randn(1000, 4);
tic();
R = partialcorr(X, Z);
t = toc();
asserts.isequal(size(R), [12 12]);
asserts.istrue(t >= 0);
%=============================================================================
Y = randn(1000, 8);
tic();
R = partialcorr(X(:, 1:6), Y, Z, 'Type', 'Spearman');
t = toc();
asserts.isequal(size(R), [6 8]);
asserts.istrue(t >= 0);
