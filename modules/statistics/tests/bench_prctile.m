A = rand(200000, 8);
tic();
P = prctile(A, [10 50 90]);
t1 = toc();
asserts.isequal(size(P), [3 8]);
asserts.istrue(t1 >= 0);
%=============================================================================
tic();
P = prctile(A, [25 50 75], 1);
t2 = toc();
asserts.isequal(size(P), [3 8]);
asserts.istrue(t2 >= 0);
%=============================================================================
B = rand(200, 120, 10);
tic();
P = prctile(B, [25 75], [1 2]);
t3 = toc();
asserts.isequal(size(P), [2 1 10]);
asserts.istrue(t3 >= 0);
%=============================================================================
tic();
P = prctile(B, [5 50 95], 'all');
t4 = toc();
asserts.isequal(size(P), [3 1]);
asserts.istrue(t4 >= 0);
