asserts.isequal(nargin('gaminv'), 3);
asserts.isequal(nargout('gaminv'), 1);
%=============================================================================
p = [0 0.025 0.5 0.975 1];
a = [0.5 1 2 3 5];
b = [1 2 2 4 1];
R = gaminv(p, a, b);
REF = [0 0.0506356159685797 3.35669398003332 28.8987506708958 Inf];
asserts.isapprox(R(1:4), REF(1:4), 1e-11);
asserts.istrue(isinf(R(5)) && R(5) > 0);
%=============================================================================
R = gaminv([0.025 0.5 0.975], [1 2 3]);
asserts.isapprox(R, [0.0253178079842899 1.67834699001666 7.22468766772351], 1e-11);
%=============================================================================
R = gaminv(single([0.025 0.5 0.975]), single([1 2 3]), single([1 2 4]));
asserts.isequal(class(R), 'single');
asserts.isapprox(R, single([0.0253178079842899 3.35669398003332 28.8987506708958]), 1e-5);
%=============================================================================
R = gaminv([-0.1 1.1 NaN 0 1], 2, 1);
asserts.istrue(all(isnan(R(1:3))));
asserts.isequal(R(4), 0);
asserts.istrue(isinf(R(5)) && R(5) > 0);
%=============================================================================
R = gaminv([], [], []);
asserts.isequal(size(R), [0 0]);
%=============================================================================
asserts.checkerror('gaminv(ones(2), ones(3), 1)', _('Size mismatch on input arguments'));
asserts.checkerror('gaminv({0.5}, 2, 1)', sprintf(_('%s must be real numeric.'), 'P'));
asserts.checkerror('gaminv(0.5, {2}, 1)', sprintf(_('%s must be real numeric.'), 'A'));
asserts.checkerror('gaminv(0.5, 2, {1})', sprintf(_('%s must be real numeric.'), 'B'));
%=============================================================================
asserts.isapprox(gaminv(gamcdf(2, 3, 2), 3, 2), 2, 1e-12);
