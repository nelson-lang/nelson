asserts.isequal(nargin('tcdf'), 3);
asserts.isequal(nargout('tcdf'), 1);
%=============================================================================
x = [-3 -1 0 1 3];
v = [1 2 5 10 Inf];
R = tcdf(x, v);
REF = [0.102416382349567 0.211324865405187 0.5 ...
       0.829553433848970 0.998650101968370];
asserts.isapprox(R, REF, 1e-12);
%=============================================================================
R = tcdf(x, v, 'upper');
REF = [0.897583617650433 0.788675134594813 0.5 ...
       0.170446566151030 0.00134989803163010];
asserts.isapprox(R, REF, 1e-12);
%=============================================================================
R = tcdf([0 1], Inf);
REF = [0.5 0.841344746068543];
asserts.isapprox(R, REF, 1e-12);
%=============================================================================
R = tcdf(single(x), single(v));
asserts.isequal(class(R), 'single');
asserts.isapprox(R, single([0.102416382349567 0.211324865405187 0.5 ...
                           0.829553433848970 0.998650101968370]), 1e-6);
%=============================================================================
R = tcdf([-Inf Inf NaN 0], [5 5 5 -1]);
asserts.isequal(R(1), 0);
asserts.isequal(R(2), 1);
asserts.istrue(isnan(R(3)));
asserts.istrue(isnan(R(4)));
%=============================================================================
R = tcdf([], []);
asserts.isequal(size(R), [0 0]);
%=============================================================================
asserts.checkerror('tcdf(ones(2), ones(3))', _('Size mismatch on input arguments'));
asserts.checkerror('tcdf(1, 2, ''bad'')', sprintf(_('Invalid %s distribution option.'), 't'));
asserts.checkerror('tcdf({1}, 2)', sprintf(_('%s must be real numeric.'), 'X'));
asserts.checkerror('tcdf(1, {2})', sprintf(_('%s must be real numeric.'), 'V'));
%=============================================================================
asserts.isapprox(tcdf(0, 5), 0.5, 1e-12);
asserts.isequal(tcdf(0, [1 2 5 10 Inf]), [0.5 0.5 0.5 0.5 0.5]);
asserts.istrue(isnan(tcdf(1, 0)));
