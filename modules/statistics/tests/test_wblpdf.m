asserts.isequal(nargin('wblpdf'), 3);
asserts.isequal(nargout('wblpdf'), 1);
%=============================================================================
asserts.isapprox(wblpdf(3), 0.049787068367863944, 1e-15);
R = wblpdf(3, 2, 1:5);
E = [0.11156508007421491 0.1580988368427965 0.11548614930187286 0.04272557913552879 0.006373548910733305];
asserts.isapprox(R, E, 1e-15);
%=============================================================================
R = wblpdf([0 2 4 Inf], 2, 3);
E = [0 0.5518191617571635 0.0020127757674150712 0];
asserts.isapprox(R, E, 1e-15);
R = wblpdf(0, 2, 0.5);
asserts.istrue(isinf(R) && R > 0);
%=============================================================================
R = wblpdf(single([0 2 4]), single(2), single(3));
asserts.isequal(class(R), 'single');
asserts.isapprox(double(R), [0 0.5518191617571635 0.0020127757674150712], 1e-7);
%=============================================================================
R = wblpdf([1 NaN 1 1], [1 1 NaN 0], [1 1 1 1]);
asserts.isapprox(R(1), 0.36787944117144233, 1e-15);
asserts.istrue(all(isnan(R(2:4))));
%=============================================================================
R = wblpdf([], [], []);
asserts.isequal(size(R), [0 0]);
%=============================================================================
asserts.checkerror('wblpdf(ones(2), ones(3), 1)', _('Size mismatch on input arguments'));
asserts.checkerror('wblpdf({1}, 1, 1)', sprintf(_('%s must be real numeric.'), 'X'));
asserts.checkerror('wblpdf(1, {1}, 1)', sprintf(_('%s must be real numeric.'), 'A'));
asserts.checkerror('wblpdf(1, 1, {1})', sprintf(_('%s must be real numeric.'), 'B'));
