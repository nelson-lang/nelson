asserts.isequal(nargin('ridge'), 4);
asserts.isequal(nargout('ridge'), 1);
%=============================================================================
y = [1; 2.1; 2.9; 4.2; 5.1; 5.9];
X = [(1:6)' [2; 1; 4; 3; 7; 6]];
k = [0 0.5 2];
B = ridge(y, X, k);
REF = [1.931067418331108 1.474858987419841 1.029667697263223; ...
       -0.083082492093666 0.278537919750650 0.490328831097363];
asserts.isapprox(B, REF, 1e-12);
%=============================================================================
B0 = ridge(y, X, k, 0);
REF = [0.058115183246072 0.313222810285159 0.795644987699877; ...
       1.032198952879582 0.788345289247055 0.550380535055351; ...
       -0.035863874345551 0.120235307134822 0.211658210332103];
asserts.isapprox(B0, REF, 1e-12);
%=============================================================================
y2 = y;
y2(3) = NaN;
X2 = X;
X2(5, 2) = NaN;
B = ridge(y2, X2, [0 1], 0);
REF = [0.120000000000001 0.657333146382502; ...
       1.080000000000000 0.545989904655076; ...
       -0.110000000000000 0.289399887829501];
asserts.isapprox(B, REF, 1e-12);
%=============================================================================
asserts.isequal(size(ridge(y, X, [], 0)), [3 0]);
asserts.isequal(size(ridge(y, X, [])), [2 0]);
B = ridge(y, [ones(6, 1) X], 1);
asserts.isapprox(B, [0; 1.259431755220751; 0.408588517580220], 1e-12);
%=============================================================================
asserts.checkerror('ridge()', _('Not enough input arguments.'));
asserts.checkerror('ridge({1}, [1], 0)', sprintf(_('%s must be a real numeric vector.'), 'Y'));
asserts.checkerror('ridge([1], {1}, 0)', sprintf(_('%s must be a real numeric matrix.'), 'X'));
asserts.checkerror('ridge([1; 2], [1], 0)', sprintf(_('%s must have the same number of rows.'), 'Y and X'));
asserts.checkerror('ridge([1; 2], [1; 2], -1)', sprintf(_('%s must be a nonnegative numeric vector.'), 'K'));
asserts.checkerror('ridge([1; 2], [1; 2], 1, 2)', sprintf(_('%s must be 0 or 1.'), 'SCALED'));
