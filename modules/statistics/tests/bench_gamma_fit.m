n = 100000;
rng(0);
x = gamrnd(2, 3, n, 1);
%=============================================================================
tic();
[phat, pci] = gamfit(x);
t_fit = toc();
asserts.isequal(size(phat), [1 2]);
asserts.isequal(size(pci), [2 2]);
%=============================================================================
tic();
[nlogL, avar] = gamlike(phat, x);
t_like = toc();
asserts.isequal(size(nlogL), [1 1]);
asserts.isequal(size(avar), [2 2]);
%=============================================================================
asserts.istrue(all([t_fit t_like] >= 0));
