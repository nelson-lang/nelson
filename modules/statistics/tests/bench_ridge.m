n = 12000;
p = 20;
X = randn(n, p);
beta = (1:p)' / p;
y = X * beta + 0.05 * randn(n, 1);
k = 0:0.25:5;
tic();
B = ridge(y, X, k);
t = toc();
asserts.isequal(size(B), [p length(k)]);
asserts.istrue(t >= 0);
%=============================================================================
tic();
B0 = ridge(y, X, k, 0);
t = toc();
asserts.isequal(size(B0), [p + 1 length(k)]);
asserts.istrue(t >= 0);
