x = randi(200, 100000, 1);
y = randi(50, 100000, 1);
tic();
T = crosstab(x, y);
t = toc();
asserts.isequal(size(T), [200 50]);
asserts.isequal(sum(T(:)), length(x));
asserts.istrue(t >= 0);
