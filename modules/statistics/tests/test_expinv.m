asserts.isequal(nargin('expinv'), 2);
asserts.isequal(nargout('expinv'), 1);
%=============================================================================
p = [0 0.025 0.5 0.975 1];
mu = [1 1 2 3 4];
R = expinv(p, mu);
REF = [0 0.0253178079842899 1.38629436111989 11.0666383623418 Inf];
asserts.isapprox(R(1:4), REF(1:4), 1e-12);
asserts.istrue(isinf(R(5)) && R(5) > 0);
%=============================================================================
R = expinv([0 0.5 0.975]);
asserts.isapprox(R, [0 0.693147180559945 3.68887945411394], 1e-12);
%=============================================================================
R = expinv(single([0.025 0.5 0.975]), single([1 2 3]));
asserts.isequal(class(R), 'single');
asserts.isapprox(R, single([0.0253178079842899 1.38629436111989 11.0666383623418]), 1e-5);
%=============================================================================
R = expinv([-0.1 1.1 NaN 0 1], 2);
asserts.istrue(all(isnan(R(1:3))));
asserts.isequal(R(4), 0);
asserts.istrue(isinf(R(5)) && R(5) > 0);
%=============================================================================
R = expinv([], []);
asserts.isequal(size(R), [0 0]);
%=============================================================================
asserts.checkerror('expinv(ones(2), ones(3))', _('Size mismatch on input arguments'));
asserts.checkerror('expinv({0.5}, 1)', sprintf(_('%s must be real numeric.'), 'P'));
asserts.checkerror('expinv(0.5, {1})', sprintf(_('%s must be real numeric.'), 'MU'));
%=============================================================================
asserts.isapprox(expinv(1 - exp(-0.5), 4), 2, 1e-12);
