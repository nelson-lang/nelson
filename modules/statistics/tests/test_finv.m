asserts.isequal(nargin('finv'), 3);
asserts.isequal(nargout('finv'), 1);
%=============================================================================
p = [0 0.025 0.5 0.975 1];
v1 = [1 2 5 10 4];
v2 = [5 10 20 30 6];
R = finv(p, v1, v2);
REF = [0 0.0253820154514797 0.900376483272752 ...
       2.51119130135695 Inf];
asserts.isapprox(R(1:4), REF(1:4), 1e-11);
asserts.istrue(isinf(R(5)) && R(5) > 0);
%=============================================================================
R = finv([0.25 0.5 0.75], [Inf 5 Inf], [5 Inf Inf]);
asserts.isapprox(R, [0.754639550691218 0.870292038219105 1], 1e-12);
%=============================================================================
R = finv(single([0.025 0.5 0.975]), single([1 2 5]), single([5 10 20]));
asserts.isequal(class(R), 'single');
asserts.isapprox(R, single([0.00108477764761470 0.743491774985175 ...
                           3.28905584568041]), 1e-5);
%=============================================================================
R = finv([-0.1 1.1 NaN 0 1], 2, 5);
asserts.istrue(all(isnan(R(1:3))));
asserts.isequal(R(4), 0);
asserts.istrue(isinf(R(5)) && R(5) > 0);
%=============================================================================
R = finv([], [], []);
asserts.isequal(size(R), [0 0]);
%=============================================================================
asserts.checkerror('finv(ones(2), ones(3), 1)', _('Size mismatch on input arguments'));
asserts.checkerror('finv({0.5}, 2, 3)', sprintf(_('%s must be real numeric.'), 'P'));
asserts.checkerror('finv(0.5, {2}, 3)', sprintf(_('%s must be real numeric.'), 'V1'));
asserts.checkerror('finv(0.5, 2, {3})', sprintf(_('%s must be real numeric.'), 'V2'));
