asserts.isequal(nargin('chi2cdf'), 3);
asserts.isequal(nargout('chi2cdf'), 1);
%=============================================================================
x = [0.5 1 2 5];
R = chi2cdf(x, 4);
REF = [0.0264990211607439 0.0902040104310499 ...
       0.264241117657115 0.712702504816354];
asserts.isapprox(R, REF, 1e-12);
R = chi2cdf(x, 4, 'upper');
REF = [0.973500978839256 0.909795989568950 ...
       0.735758882342885 0.287297495183646];
asserts.isapprox(R, REF, 1e-12);
%=============================================================================
x = [0 0.5 1 2 5 10];
v = [1 2 3 4 5 6];
R = chi2cdf(x, v);
REF = [0 0.221199216928595 0.198748043098799 ...
       0.264241117657115 0.584119813004491 0.875347980516914];
asserts.isapprox(R, REF, 1e-12);
%=============================================================================
R = chi2cdf(x, v, 'upper');
REF = [1 0.778800783071405 0.801251956901201 ...
       0.735758882342885 0.415880186995509 0.124652019483081];
asserts.isapprox(R, REF, 1e-12);
%=============================================================================
R = chi2cdf(single(x), single(v));
asserts.isequal(class(R), 'single');
asserts.isapprox(R, single([0 0.221199216928595 0.198748043098799 ...
                           0.264241117657115 0.584119813004491 0.875347980516914]), 1e-6);
%=============================================================================
R = chi2cdf([-1 0 Inf NaN 1], [2 2 2 2 NaN]);
asserts.isequal(R(1), 0);
asserts.isequal(R(2), 0);
asserts.isequal(R(3), 1);
asserts.istrue(isnan(R(4)));
asserts.istrue(isnan(R(5)));
%=============================================================================
R = chi2cdf([], []);
asserts.isequal(size(R), [0 0]);
%=============================================================================
asserts.checkerror('chi2cdf(ones(2), ones(3))', _('Size mismatch on input arguments'));
asserts.checkerror('chi2cdf(1, 2, ''bad'')', sprintf(_('Invalid %s distribution option.'), 'chi-square'));
asserts.checkerror('chi2cdf({1}, 2)', sprintf(_('%s must be real numeric.'), 'X'));
asserts.checkerror('chi2cdf(1, {2})', sprintf(_('%s must be real numeric.'), 'V'));
%=============================================================================
asserts.isapprox(chi2cdf(2, 4), 1 - 2 * exp(-1), 1e-12);
