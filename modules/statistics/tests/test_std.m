% <--WEIGHT 2-->
% <--REUSE PROCESS-->
%=============================================================================
asserts.isequal(nargin('std'), -1);
asserts.isequal(nargout('std'), -1);
%=============================================================================
R = std([1, 2, 3], 0, 1);
REF = [0 0 0];
asserts.isequal(R, REF);
%=============================================================================
A = [4 -7 3; 1 4 -2; 10 7 9];
R = std(A);
REF = [4.5826 7.3711 5.5076];
asserts.isapprox(R, REF, 1e-4);
%=============================================================================
A = [4 -2 1; 9 5 7];
R = std(A, 0, 1);
REF = [3.5355 4.9497 4.2426];
asserts.isapprox(R, REF, 1e-4);
%=============================================================================
A = [4 -2 1; 9 5 7];
R = std(A, 0, 2);
REF = [3; 2];
asserts.isapprox(R, REF, 1e-4);
%=============================================================================
asserts.checkerror('std()', _('Not enough input arguments.'))
%=============================================================================
asserts.isequal(std(36), 0);
%=============================================================================
asserts.isequal(std([1 2 3]), 1);
%=============================================================================
[S, M] = std([1 2 3]);
asserts.isequal(S, 1);
asserts.isequal(M, 2);
%=============================================================================
[S, M] = std([1 2; 3 4; 5 6], 0, 1);
asserts.isapprox(S, [2 2], 1e-12);
asserts.isequal(M, [3 4]);
%=============================================================================
[S, M] = std([1 2 3], [1 2 3]);
asserts.isapprox(S, sqrt(5 / 9), 1e-12);
asserts.isapprox(M, 14 / 6, 1e-12);
%=============================================================================
X = logical([1 0 1; 0 1 0]);
S = std(X);
assert_istrue(isa(S, 'double'));
asserts.isapprox(S, [0.7071067811865476 0.7071067811865476 0.7071067811865476], 1e-12);
%=============================================================================
[S, M] = std('abc');
assert_istrue(isa(S, 'double'));
assert_istrue(isa(M, 'double'));
asserts.isequal(S, 1);
asserts.isequal(M, 98);
%=============================================================================
asserts.isequal(std(uint64([1 2 3])), 1);
%=============================================================================
X = sparse([1 0 2; 0 3 0]);
[S, M] = std(X);
assert_istrue(issparse(S));
assert_istrue(issparse(M));
asserts.isapprox(full(S), [0.7071067811865476 2.121320343559642 1.414213562373095], 1e-12);
asserts.isapprox(full(M), [0.5 1.5 1], 1e-12);
%=============================================================================
X = sparse(single([1 0 2; 0 3 0]));
S = std(X);
assert_istrue(isa(S, 'single'));
assert_istrue(issparse(S));
asserts.isapprox(double(full(S)), [0.7071067690849304 2.121320247650146 1.414213538169861], 1e-6);
%=============================================================================
X = sparse(logical([1 0 1; 0 1 0]));
S = std(X);
assert_istrue(isa(S, 'double'));
assert_istrue(issparse(S));
asserts.isapprox(full(S), [0.7071067811865476 0.7071067811865476 0.7071067811865476], 1e-12);
%=============================================================================
X = sparse([1 + 2i 0 2; 0 3 - 4i 0]);
[S, M] = std(X);
assert_istrue(isa(S, 'double'));
assert_istrue(issparse(S));
assert_istrue(issparse(M));
asserts.isapprox(full(S), [1.58113883008419 3.535533905932738 1.414213562373095], 1e-12);
asserts.isapprox(full(M), [0.5 + 1i 1.5 - 2i 1], 1e-12);
%=============================================================================
X = sparse([1 0 2; 0 3 0]);
[S, M] = std(X, [1 2]);
assert_istrue(issparse(S));
assert_istrue(issparse(M));
asserts.isapprox(full(S), [0.4714045207910317 1.414213562373095 0.9428090415820634], 1e-12);
asserts.isapprox(full(M), [0.3333333333333333 2 0.6666666666666666], 1e-12);
%=============================================================================
% 'all' option
assert_isapprox(std([1 2 3; 4 5 6], 0, 'all'), sqrt(3.5), 1e-10);
%=============================================================================
% vector of dimensions (vecdim)
A = reshape(1:24, [2 3 4]);
assert_isequal(size(std(A, 0, [1 2])), [1 1 4]);
assert_isapprox(std(A, 0, [1 2]), reshape(sqrt([3.5 3.5 3.5 3.5]), [1 1 4]), 1e-10);
assert_isapprox(std(A, 0, [1 3]), sqrt([362 / 7 362 / 7 362 / 7]), 1e-10);
assert_isequal(std(A, 0, [1 2 3]), std(A, 0, 'all'));
