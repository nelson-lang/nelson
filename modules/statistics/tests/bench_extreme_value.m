n = 100000;
x = linspace(-5, 5, n);
p = linspace(0.001, 0.999, n);
mu = 0.5;
sigma = 2;
%=============================================================================
tic();
y = evpdf(x, mu, sigma);
t_pdf = toc();
asserts.isequal(size(y), size(x));
%=============================================================================
tic();
c = evcdf(x, mu, sigma);
t_cdf = toc();
asserts.isequal(size(c), size(x));
%=============================================================================
tic();
q = evinv(p, mu, sigma);
t_inv = toc();
asserts.isequal(size(q), size(p));
%=============================================================================
rng(0);
tic();
r = evrnd(mu, sigma, 1, n);
t_rnd = toc();
asserts.isequal(size(r), [1 n]);
%=============================================================================
tic();
[m, v] = evstat(mu + zeros(1, n), sigma);
t_stat = toc();
asserts.isequal(size(m), [1 n]);
asserts.isequal(size(v), [1 n]);
%=============================================================================
asserts.istrue(all([t_pdf t_cdf t_inv t_rnd t_stat] >= 0));
