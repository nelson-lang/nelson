asserts.isequal(nargin('evpdf'), 3);
asserts.isequal(nargout('evpdf'), 1);
%=============================================================================
x = [-Inf -2 -1 0 1 2 Inf NaN];
R = evpdf(x);
E = [0 0.1182049515931431 0.2546463800435825 0.3678794411714423 ...
     0.1793740787340172 0.004566281420127915 0 NaN];
asserts.isapprox(R(1:7), E(1:7), 1e-15);
asserts.istrue(isnan(R(8)));
%=============================================================================
R = evpdf([-2 -1 0 1 2], [0 0 1 1 2], [1 2 1 3 2]);
E = [0.1182049515931431 0.1653521494452090 0.2546463800435825 ...
     0.1226264803904808 0.1839397205857212];
asserts.isapprox(R, E, 1e-15);
%=============================================================================
R = evpdf(single([-2 -1 0 1 2]), single(0), single(1));
asserts.isequal(class(R), 'single');
asserts.isapprox(double(R), [0.1182049515931431 0.2546463800435825 ...
                            0.3678794411714423 0.1793740787340172 ...
                            0.004566281420127915], 1e-7);
%=============================================================================
R = evpdf([1 NaN 1 1], [0 0 NaN 0], [1 1 1 0]);
asserts.isapprox(R(1), 0.1793740787340172, 1e-15);
asserts.istrue(all(isnan(R(2:4))));
%=============================================================================
R = evpdf([]);
asserts.isequal(size(R), [0 0]);
R = evpdf([], [], []);
asserts.isequal(size(R), [0 0]);
%=============================================================================
asserts.checkerror('evpdf(ones(2), ones(3), 1)', _('Size mismatch on input arguments'));
asserts.checkerror('evpdf({1}, 0, 1)', sprintf(_('%s must be real numeric.'), 'X'));
asserts.checkerror('evpdf(1, {0}, 1)', sprintf(_('%s must be real numeric.'), 'MU'));
asserts.checkerror('evpdf(1, 0, {1})', sprintf(_('%s must be real numeric.'), 'SIGMA'));
