asserts.isequal(nargin('exppdf'), 2);
asserts.isequal(nargout('exppdf'), 1);
%=============================================================================
x = [-1 0 0.5 2 Inf];
mu = [1 1 2 3 4];
R = exppdf(x, mu);
REF = [0 1 0.389400391535702 0.171139039677531 0];
asserts.isapprox(R, REF, 1e-12);
%=============================================================================
R = exppdf([0 1 2]);
asserts.isapprox(R, [1 0.367879441171442 0.135335283236613], 1e-12);
%=============================================================================
R = exppdf(single(x), single(mu));
asserts.isequal(class(R), 'single');
asserts.isapprox(R, single(REF), 1e-6);
%=============================================================================
R = exppdf([NaN 1 1], [1 -1 NaN]);
asserts.istrue(all(isnan(R)));
%=============================================================================
R = exppdf([], []);
asserts.isequal(size(R), [0 0]);
%=============================================================================
asserts.checkerror('exppdf(ones(2), ones(3))', _('Size mismatch on input arguments'));
asserts.checkerror('exppdf({1}, 1)', sprintf(_('%s must be real numeric.'), 'X'));
asserts.checkerror('exppdf(1, {1})', sprintf(_('%s must be real numeric.'), 'MU'));
%=============================================================================
asserts.isapprox(exppdf(2, 4), exp(-0.5) / 4, 1e-12);
