X = rand(80000, 12);
X(1:17:end) = NaN;
tic();
Y = nansum(X);
t = toc();
asserts.isequal(size(Y), [1 12]);
asserts.istrue(t >= 0);
%=============================================================================
A = rand(120, 80, 10);
A(1:23:end) = NaN;
tic();
Z = nansum(A, [1 2]);
t = toc();
asserts.isequal(size(Z), [1 1 10]);
asserts.istrue(t >= 0);
