X = rand(80000, 12);
X(1:17:end) = NaN;
tic();
Y = nanmax(X);
t = toc();
asserts.isequal(size(Y), [1 12]);
asserts.istrue(t >= 0);
%=============================================================================
tic();
[Y, I] = nanmax(X, [], 2);
t = toc();
asserts.isequal(size(Y), [80000 1]);
asserts.isequal(size(I), [80000 1]);
asserts.istrue(t >= 0);
