asserts.isequal(nargin('raylstat'), 1);
asserts.isequal(nargout('raylstat'), 2);
%=============================================================================
[m, v] = raylstat(2);
asserts.isapprox(m, 2.5066282746310002, 1e-15);
asserts.isapprox(v, 1.7168146928204138, 1e-15);
%=============================================================================
[m, v] = raylstat([1 2]);
asserts.isapprox(m, [1.2533141373155001 2.5066282746310002], 1e-15);
asserts.isapprox(v, [0.42920367320510344 1.7168146928204138], 1e-15);
%=============================================================================
[m, v] = raylstat(single([1 2]));
asserts.isequal(class(m), 'single');
asserts.isequal(class(v), 'single');
asserts.isapprox(double(m), [1.2533141373155001 2.5066282746310002], 1e-6);
asserts.isapprox(double(v), [0.42920367320510344 1.7168146928204138], 1e-6);
%=============================================================================
[m, v] = raylstat([1 0 -1 NaN]);
asserts.isapprox(m(1), 1.2533141373155001, 1e-15);
asserts.istrue(all(isnan(m(2:4))));
asserts.istrue(all(isnan(v(2:4))));
%=============================================================================
[m, v] = raylstat([]);
asserts.isequal(size(m), [0 0]);
asserts.isequal(size(v), [0 0]);
%=============================================================================
asserts.checkerror('raylstat()', _('Not enough input arguments.'));
asserts.checkerror('raylstat({1})', sprintf(_('%s must be real numeric.'), 'B'));
