X = randn(80000, 12);
tic();
Y = kurtosis(X);
t = toc();
asserts.isequal(size(Y), [1 12]);
asserts.istrue(t >= 0);
%=============================================================================
A = randn(120, 80, 10);
tic();
Z = kurtosis(A, 1, [1 2]);
t = toc();
asserts.isequal(size(Z), [1 1 10]);
asserts.istrue(t >= 0);
