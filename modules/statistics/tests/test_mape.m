assert_isapprox(mape([1 2 4], [1 2 3]), 11.111111111111111, 1e-12);
assert_isapprox(mape([1 2; 3 4], [2 2; 3 6]), [25 16.666666666666668], 1e-12);
assert_isequal(mape([1 2], [0 2]), Inf);
assert_isapprox(mape([1 NaN 4], [1 2 3], 'omitnan'), 16.666666666666668, 1e-12);
assert_isapprox(mape([1 2; 3 4], [2 2; 3 6], 'all'), 20.833333333333336, 1e-12);
assert_isapprox(mape([1 2; 3 4], [2 2; 3 6], 2), [25; 16.666666666666668], 1e-12);
assert_isapprox(mape([1 2 4], [1 2 3], 'Weights', [1 1 2]), 16.666666666666668, 1e-12);
assert_isequal(class(mape(single([1 2]), [1 3])), 'single');
