rng(0);
X = randn(80000, 16);
tic();
y = mad(X);
t = toc();
asserts.isequal(size(y), [1 16]);
asserts.istrue(all(isfinite(y)));
asserts.istrue(t < 10);
%=============================================================================
Y = randn(120, 80, 20);
tic();
y2 = mad(Y, 1, [1 2]);
t2 = toc();
asserts.isequal(size(y2), [1 1 20]);
asserts.istrue(all(isfinite(y2(:))));
asserts.istrue(t2 < 10);
