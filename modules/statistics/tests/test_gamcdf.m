asserts.isequal(nargin('gamcdf'), 4);
asserts.isequal(nargout('gamcdf'), 1);
%=============================================================================
x = [0 0.5 1 2 5];
a = [0.5 1 2 3 5];
b = [1 2 2 4 1];
R = gamcdf(x, a, b);
REF = [0 0.221199216928595 0.0902040104310499 ...
       0.0143876779669707 0.559506714934788];
asserts.isapprox(R, REF, 1e-12);
%=============================================================================
R = gamcdf(x, a, b, 'upper');
REF = [1 0.778800783071405 0.909795989568950 ...
       0.985612322033029 0.440493285065212];
asserts.isapprox(R, REF, 1e-12);
%=============================================================================
R = gamcdf([0 1 2], [1 2 3]);
asserts.isapprox(R, [0 0.264241117657115 0.323323583816936], 1e-12);
%=============================================================================
R = gamcdf(single(x), single(a), single(b));
asserts.isequal(class(R), 'single');
asserts.isapprox(R, single([0 0.221199216928595 0.0902040104310499 ...
                           0.0143876779669707 0.559506714934788]), 1e-6);
%=============================================================================
R = gamcdf([-1 Inf NaN 1 1], [2 2 2 -1 2], [1 1 1 1 NaN]);
asserts.isequal(R(1), 0);
asserts.isequal(R(2), 1);
asserts.istrue(all(isnan(R(3:5))));
%=============================================================================
R = gamcdf([], [], []);
asserts.isequal(size(R), [0 0]);
%=============================================================================
asserts.checkerror('gamcdf(ones(2), ones(3), 1)', _('Size mismatch on input arguments'));
asserts.checkerror('gamcdf(1, 2, 1, ''bad'')', sprintf(_('Invalid %s distribution option.'), 'gamma'));
asserts.checkerror('gamcdf({1}, 2, 1)', sprintf(_('%s must be real numeric.'), 'X'));
asserts.checkerror('gamcdf(1, {2}, 1)', sprintf(_('%s must be real numeric.'), 'A'));
asserts.checkerror('gamcdf(1, 2, {1})', sprintf(_('%s must be real numeric.'), 'B'));
%=============================================================================
asserts.isapprox(gamcdf(2, 3, 2), 1 - 2.5 * exp(-1), 1e-12);
