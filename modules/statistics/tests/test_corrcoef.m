% <--REUSE PROCESS-->
%=============================================================================
asserts.isequal(nargin('corrcoef'), 1);
asserts.isequal(nargout('corrcoef'), 1);
%=============================================================================
R = corrcoef(magic(4));
REF = [1.0000 -0.9776 -0.9069 0.7978;
  -0.9776 1.0000 0.9753 -0.9069;
  -0.9069 0.9753 1.0000 -0.9776;
  0.7978 -0.9069 -0.9776 1.0000];
asserts.isapprox(R, REF, 1e-4);
%=============================================================================
R = corrcoef(magic(4) + 2i);
REF = [1.0000 -0.9776 -0.9069 0.7978;
  -0.9776 1.0000 0.9753 -0.9069;
  -0.9069 0.9753 1.0000 -0.9776;
  0.7978 -0.9069 -0.9776 1.0000];
asserts.isapprox(R, REF, 1e-4);
%=============================================================================
R = corrcoef(single(magic(4)));
REF = [1.0000 -0.9776 -0.9069 0.7978;
  -0.9776 1.0000 0.9753 -0.9069;
  -0.9069 0.9753 1.0000 -0.9776;
  0.7978 -0.9069 -0.9776 1.0000];
asserts.isapprox(R, single(REF), 1e-4);
%=============================================================================
R = corrcoef([]);
asserts.istrue(isnan(R));
%=============================================================================
R = corrcoef(zeros(0, 3));
REF = zeros(3, 3) * NaN;
asserts.isequal(R, REF);
%=============================================================================
R = corrcoef(1);
REF = NaN;
asserts.isequal(R, REF);
%=============================================================================
R = corrcoef([1, 2, 3]);
asserts.istrue(R == 1 || R == 0);
%=============================================================================
asserts.checkerror('R = corrcoef(ones(3,4,3));', _('Inputs must be 2-D.'));
