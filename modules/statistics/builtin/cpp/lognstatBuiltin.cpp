#include "lognstatBuiltin.hpp"
#include "StatisticsDistributions.hpp"
#include "InputOutputArgumentsCheckers.hpp"
//=============================================================================
using namespace Nelson;
//=============================================================================
ArrayOfVector
Nelson::StatisticsGateway::lognstatBuiltin(int nLhs, const ArrayOfVector& argIn)
{
    nargincheck(argIn, 2, 2);
    nargoutcheck(nLhs, 0, 2);
    LognormalStatResult result = LognormalStat(argIn);
    ArrayOfVector retval;
    retval << result.mean;
    if (nLhs > 1) {
        retval << result.variance;
    }
    return retval;
}
