function k = at(ch, labels)
  k = find(labels == ch);
end
%=============================================================================
% Closed ellipse outline, swept clockwise, y pointing down.
function pts = ellipse(cx, cy, rx, ry)
  t = linspace(-pi / 2, 3 * pi / 2, 41)';
  pts = [cx + rx * cos(t), cy + ry * sin(t)];
end
