% Extra hand shapes for the characters people write in several ways.
function variants = addAlternates(variants, labels)
  variants{at('1', labels)}{end + 1} = {[0.50 0.16; 0.50 0.86]};
  variants{at('1', labels)}{end + 1} = {[0.40 0.26; 0.50 0.14; 0.50 0.86]};
  % Long upstroke flag from mid-height (a very common hand "1"), the shape most
  % often mistaken for a 4; with and without a base serif.
  variants{at('1', labels)}{end + 1} = {[0.32 0.52; 0.52 0.16; 0.52 0.86]};
  variants{at('1', labels)}{end + 1} = {[0.32 0.52; 0.52 0.16; 0.52 0.86], ...
    [0.40 0.86; 0.64 0.86]};
  variants{at('4', labels)}{end + 1} = {[0.60 0.14; 0.30 0.60; 0.72 0.60], ...
    [0.60 0.14; 0.60 0.86]};
  variants{at('7', labels)}{end + 1} = {[0.33 0.16; 0.68 0.16; 0.44 0.86], ...
    [0.38 0.52; 0.56 0.52]};
  variants{at('0', labels)}{end + 1} = {ellipse(0.5, 0.5, 0.16, 0.36), ...
    [0.40 0.66; 0.60 0.34]};
  variants{at('J', labels)}{end + 1} = {[0.60 0.14; 0.60 0.68; 0.52 0.83; ...
    0.40 0.84; 0.32 0.72]};
  variants{at('Z', labels)}{end + 1} = {[0.34 0.14; 0.68 0.14; 0.34 0.86; 0.68 0.86], ...
    [0.40 0.50; 0.60 0.50]};
  % A rounder figure-eight with a clear waist: a straight-left "8" is otherwise
  % easily mistaken for a B (stacked loops with aligned left edges look like a
  % B stem, so that shape is deliberately not used here).
  variants{at('8', labels)}{end + 1} = {[0.52 0.15; 0.39 0.22; 0.39 0.35; 0.50 0.45; ...
    0.63 0.56; 0.63 0.75; 0.50 0.85; 0.37 0.75; 0.37 0.57; 0.50 0.45; ...
    0.61 0.35; 0.60 0.22; 0.52 0.15]};
end
