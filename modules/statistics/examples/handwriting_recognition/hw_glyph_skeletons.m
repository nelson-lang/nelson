% Stroke skeletons for 0-9 and A-Z, authored as polylines in a [0 1] box with y
% pointing down. They read like handwriting rather than a printed font, which is
% what the mouse input looks like. labels is a 1-by-36 char row; variants{i} is
% a cell of one or more skeletons for that label (several common hand shapes for
% ambiguous characters), and each skeleton is a cell of N-by-2 [x y] strokes.
function [labels, variants] = hw_glyph_skeletons()
  labels = ['0':'9', 'A':'Z'];
  g = baseShapes();
  fields = fieldnames(g);
  variants = cell(1, numel(fields));
  for i = 1:numel(fields)
    variants{i} = {g.(fields{i})};
  end
  variants = addAlternates(variants, labels);
end
