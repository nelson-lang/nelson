A = [1 2; 3 4];
B = [5; 6];
%=============================================================================
asserts.isequal(horzcat(A, B), [1 2 5; 3 4 6]);
asserts.isequal([A, B], [1 2 5; 3 4 6]);
%=============================================================================
asserts.isequal(horzcat("a", "b"), ["a", "b"]);
%=============================================================================
A = single([1 2 3]);
R = horzcat(A, single(4));
asserts.isequal(class(R), 'single');
asserts.isequal(R, single([1 2 3 4]));
%=============================================================================
A = int32([1 2 3]);
R = horzcat(A, int32(4));
asserts.isequal(class(R), 'int32');
asserts.isequal(R, int32([1 2 3 4]));
%=============================================================================
R = horzcat([1 + 2i, 3 + 4i], 5 + 6i);
asserts.isequal(R, [1 + 2i, 3 + 4i, 5 + 6i]);
