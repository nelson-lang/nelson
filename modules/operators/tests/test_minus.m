asserts.isequal([1 2; 3 4] - 1, [0 1; 2 3]);
asserts.isequal(10 - [1 2; 3 4], [9 8; 7 6]);
%=============================================================================
asserts.isequal(int32(1) - int32(2), int32(-1));
%=============================================================================
A = [1 2 3];
B = [1 4 7; 2 5 8];
asserts.isequal(A - B, [0 -2 -4; -1 -3 -5]);
asserts.isequal(B - A, [0 2 4; 1 3 5]);
%=============================================================================
A = [1; 2];
B = [1 3 5; 2 4 6];
asserts.isequal(A - B, [0 -2 -4; 0 -2 -4]);
asserts.isequal(B - A, [0 2 4; 0 2 4]);
