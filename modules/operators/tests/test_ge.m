asserts.isequal(nargin('ge'), 2)
asserts.isequal(nargout('ge'), 1)
%=============================================================================
asserts.istrue(ge(1, 1));
asserts.istrue(ge(logical(1), logical(1)));
asserts.istrue(ge(string(1), string(1)));
%=============================================================================
A = ["Nel", NaN, "son"];
B = ["Nel", NaN, "son"];
R = (A >= B);
REF = [true false true];
asserts.isequal(R, REF);
%=============================================================================
A = ["Nel", NaN, "son"];
B = ["Nel", "son"];
asserts.checkerror('A >= B', [_('Size mismatch on arguments to arithmetic operator'), ' >=']);
%=============================================================================
R = ("" >= "r");
asserts.isfalse(R);
%=============================================================================
R = ("" >= "");
asserts.istrue(R);
%=============================================================================
R = ("r" >= "");
asserts.istrue(R);
%=============================================================================
A = ["r", "", "rff"];
B = "r";
R = (A >= B);
REF = logical([1 0 1]);
asserts.isequal(R, REF);
%=============================================================================
B = ["r", "", "rff"];
A = "r";
R = (A >= B);
REF = logical([1 1 0]);
asserts.isequal(R, REF);
%=============================================================================
A = ["r", "rff", ""; "dd", "c", "mm"];
B = ["r", "rff", ""; "dd", "c", "mm"];
R = (A >= B);
REF = logical(ones(2, 3));
asserts.isequal(R, REF);
%=============================================================================
A = ["r", "rff", ""; "dd", "c", "mm"];
B = "r";
R = (A >= B);
REF = logical([1 1 0; 0 0 0]);
asserts.isequal(R, REF);
%=============================================================================
B = ["r", "rff", ""; "dd", "c", "mm"];
A = "r";
R = (A >= B);
REF = logical([1 0 1; 1 1 1]);
asserts.isequal(R, REF);
%=============================================================================
% compatibility size
%=============================================================================
A = [1 2; 3 4; 5 6];
B = [1; 2; 3];
R = (A >= B);
REF = logical([1 1; 1 1; 1 1]);
asserts.isequal(R, REF);
%=============================================================================
A = [1 2; 3 4; 5 6];
B = [1; 2; 3];
R = (B >= A);
REF = logical([1 0; 0 0; 0 0]);
asserts.isequal(R, REF);
%=============================================================================
B = [1; 2];
A = [1 2 3];
R = (A >= B);
REF = logical([1 1 1; 0 1 1]);
asserts.isequal(R, REF);
%=============================================================================
A = [1; 2];
B = [1 2 3];
R = (A >= B);
REF = logical([1 0 0; 1 1 0]);
asserts.isequal(R, REF);
%=============================================================================
A = [1; 2] + i;
B = [1 2 3] + i;
R = (A >= B);
REF = logical([1 0 0; 1 1 0]);
asserts.isequal(R, REF);
%=============================================================================
B = [1; 2] + i;
A = [1 2 3] + i;
R = (A >= B);
REF = logical([1 1 1; 0 1 1]);
asserts.isequal(R, REF);
%=============================================================================
A = [1 2 3];
B = [1 0 3];
R = (A >= B);
REF = logical([1 1 1]);
asserts.isequal(R, REF);
%=============================================================================
A = [1 2 3];
B = [1 0 3];
R = (B >= A);
REF = logical([1 0 1]);
asserts.isequal(R, REF);
%=============================================================================
A = 1 + 2i;
B = 1 + 2i;
R = (A >= B);
asserts.istrue(R);
%=============================================================================
A = 1 + 2i;
B = 1 + 2i;
R = (B >= A);
asserts.istrue(R);
%=============================================================================
A = ones(1, 2, 3);
B = [1:3];
asserts.checkerror('A >= B', [_('Size mismatch on arguments to arithmetic operator'), ' >=']);
%=============================================================================
A = [1 2 3];
B = [1 2 3 4];
asserts.checkerror('A >= B', [_('Size mismatch on arguments to arithmetic operator'), ' >=']);
%=============================================================================
A = ["apple", "orange", "tomato"];
B = 'orange';
R = (A >= B);
REF = logical([0 1 1]);
asserts.isequal(R, REF);
%=============================================================================
A = [1 2; 3 4];
B = [1; 3];
R = A >= B;
REF = logical([1, 1;
  1, 1]);
asserts.isequal(R, REF);
%=============================================================================
B = [1 2; 3 4];
A = [1; 3];
R = A >= B;
REF = logical([1, 0;
  1, 0]);
asserts.isequal(R, REF);
%=============================================================================
