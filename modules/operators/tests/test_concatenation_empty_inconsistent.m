% Two empty operands of inconsistent 2-D sizes: an operand with no dimension
% above 1 yields to the other one, two operands empty along the concatenated
% dimension keep the larger one, anything else gives 0x0.
addpath(modulepath('operators', 'tests'));
makers = {@(d) zeros(d); ...
          @(d) true(d); ...
          @(d) zeros(d, 'int8'); ...
          @(d) repmat('a', d); ...
          @(d) repmat({1}, d); ...
          @(d) repmat(struct('v', 1), d); ...
          @(d) VertcatOrderValueFixture.empty(d); ...
          @(d) VertcatOrderHandleFixture.empty(d)};
%=============================================================================
% {size of A, direction, size of B, expected size}
cases = {[0 1], 'h', [2 0], [2 0]; ...
         [2 0], 'h', [0 1], [2 0]; ...
         [1 0], 'h', [0 2], [0 2]; ...
         [0 2], 'h', [1 0], [0 2]; ...
         [1 0], 'h', [2 0], [2 0]; ...
         [3 0], 'h', [4 0], [4 0]; ...
         [4 0], 'h', [0 1], [4 0]; ...
         [0 1], 'h', [1 0], [0 0]; ...
         [0 3], 'h', [2 0], [0 0]; ...
         [0 1], 'v', [0 2], [0 2]; ...
         [0 2], 'v', [0 1], [0 2]; ...
         [0 3], 'v', [0 4], [0 4]; ...
         [0 1], 'v', [2 0], [2 0]; ...
         [1 0], 'v', [0 2], [0 2]; ...
         [0 1], 'v', [1 0], [0 0]; ...
         [0 2], 'v', [2 0], [0 0]; ...
         [0 1], 'h', [0 0 3], [0 0]};
for m = 1:size(makers, 1)
  for c = 1:size(cases, 1)
    A = makers{m}(cases{c, 1});
    B = makers{m}(cases{c, 3});
    if strcmp(cases{c, 2}, 'h')
      R = [A, B];
    else
      R = [A; B];
    end
    assert_isequal(size(R), cases{c, 4});
    assert_isequal(class(R), class(A));
  end
end
