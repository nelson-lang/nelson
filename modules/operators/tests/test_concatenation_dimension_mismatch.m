% Every concatenation of arrays with inconsistent sizes raises the same
% identifier and message, whatever the types and the syntax.
addpath(modulepath('operators', 'tests'));
msg = _('Dimensions of arrays being concatenated are not consistent.');
id = 'Nelson:catenate:dimensionMismatch';
s1 = struct('v', 1);
s2 = [s1, s1];
s2c = reshape(s2, [2 1]);
v1 = VertcatOrderValueFixture(1);
v2 = [v1, v1];
v2c = reshape(v2, [2 1]);
h1 = VertcatOrderHandleFixture(1);
h2 = [h1, h1];
h2c = reshape(h2, [2 1]);
cmds = {'[1 2; 1 2 3]', '[[1; 2], [1 2 3]]', '[1:3; 1:2; 1:3]', ...
        'vertcat([1 2], [1 2 3])', 'horzcat([1; 2], [1 2 3])', ...
        'cat(1, [1 2], [1 2 3])', 'cat(2, [1; 2], [1 2 3])', ...
        'cat(3, [1 2], [1 2 3])', 'cat(4, zeros(2, 2), zeros(3, 2))', ...
        '[zeros(2, 2, 2), zeros(2, 2, 3)]', '[zeros(1, 2, 2); zeros(1, 2)]', ...
        '[true true; true]', '[int8([1 2]); int8(1)]', '[single([1 2]); 1]', ...
        '[1i 2; 3]', '[''ab''; ''c'']', '["a" "b"; "c"]', '[{1, 2}; {1}]', ...
        '[{1}, {1; 2}]', '[1 2; int8([1 2 3])]', '[1 2; ''abc'']', ...
        '[1 2; true]', '[1; {1, 2}]', '[{1, 2}; 1]', '[1 2; "a"]', ...
        '[s2; s1]', '[s2c, s1]', 'cat(3, s2, s1)', ...
        '[v2; v1]', '[v2c, v1]', 'cat(3, v2, v1)', ...
        '[h2; h1]', '[h2c, h1]', 'cat(3, h2, h1)', ...
        '[sparse([1 2]); sparse([1 2 3])]', '[sparse([1 2]), sparse([1; 2])]', ...
        '[sparse([true true]); sparse([true true true])]', ...
        '[sparse([true true]), sparse([true; true])]', ...
        '[1 2; sparse([1 2 3])]', ...
        'cell2mat({[1 2], [3; 4]})', 'cell2mat({[1 2]; [3 4 5]})'};
for k = 1:numel(cmds)
  assert_checkerror(cmds{k}, msg, id);
end
