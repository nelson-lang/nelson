%=============================================================================
% non-integer powers of defective matrices use a Schur method: exact and silent
%=============================================================================
cases = {};
cases(end + 1, :) = {[2 1; 0 2], 0.5, [1.4142135623730951 0.35355339059327373; 0 1.4142135623730951], 1e-15};
cases(end + 1, :) = {[2 1; 0 2], 1.5, [2.8284271247461903 2.1213203435596428; 0 2.8284271247461903], 1e-15};
cases(end + 1, :) = {[2 1; 0 2], -0.5, [0.70710678118654746 -0.17677669529663687; 0 0.70710678118654746], 1e-15};
cases(end + 1, :) = {[2 1; 0 2], 2.5, [5.6568542494923806 7.0710678118654755; 0 5.6568542494923806], 1e-15};
cases(end + 1, :) = {[2 1; 0 2], 0.7, [1.6245047927124709 0.5685766774493648; 0 1.6245047927124709], 1e-15};
cases(end + 1, :) = {[1 1; 0 1], 0.5, [1 0.5; 0 1], 1e-15};
%=============================================================================
J = [2 1 0; 0 2 1; 0 0 2];
REF = [1.2599210498948732 0.20998684164914549 -0.034997806941524254;
       0 1.2599210498948732 0.20998684164914549;
       0 0 1.2599210498948732];
cases(end + 1, :) = {J, 1/3, REF, 1e-14};
REF = [1.4142135623730951 0.35355339059327373 -0.044194173824159216;
       0 1.4142135623730951 0.35355339059327373;
       0 0 1.4142135623730951];
cases(end + 1, :) = {J, 0.5, REF, 1e-14};
REF = [3.2490095854249419 2.7616581476112003 0.48329017583196016;
       0 3.2490095854249419 2.7616581476112003;
       0 0 3.2490095854249419];
cases(end + 1, :) = {J, 1.7, REF, 1e-14};
%=============================================================================
% complex and negative eigenvalues give complex results
d = 0.70710678118654757 + 0.70710678118654757i;
cases(end + 1, :) = {[1i 1; 0 1i], 0.5, [d (0.35355339059327373 - 0.35355339059327373i); 0 d], 1e-15};
d = 0.72364852960641046 + 0.99601675292581215i;
cases(end + 1, :) = {[-2 1; 0 -2], 0.3, [d (-0.10854727944096153 - 0.14940251293887183i); 0 d], 1e-15};
R = [-1 1; 0 -1] ^ 0.5;
asserts.isequal(R, [1i -0.5i; 0 1i]);
R = [2 1 0; 0 2 0; 0 0 -1] ^ 0.5;
REF = [1.4142135623730951 0.35355339059327373 0; 0 1.4142135623730951 0; 0 0 1i];
asserts.isfalse(isreal(R));
asserts.isapprox(R, REF, 1e-15);
cases(end + 1, :) = {[2 1 0; 0 2 0; 0 0 5], 0.5, ...
  [1.4142135623730951 0.35355339059327373 0; 0 1.4142135623730951 0; 0 0 2.2360679774997898], 1e-15};
%=============================================================================
% dense defective matrix: real result
P = [1 2 0; 0 1 3; 1 0 1];
A = [1 1 1; 0 1 1; 0 0 1] * P / P;
cases(end + 1, :) = {A, 0.5, [1 0.5 0.375; 0 1 0.5; 0 0 1], 1e-12};
%=============================================================================
% singular defective matrices have no power: non-finite entries, no warning
lastwarn('');
R = [0 1; 0 0] ^ 0.5;
asserts.isequal(lastwarn(), '');
asserts.isequal(R, [0 Inf; 0 0]);
asserts.isequal([0 1; 0 0] ^ -0.5, [Inf -Inf; 0 Inf]);
asserts.istrue(isequaln([0 1; 0 0] ^ 1.5, [0 NaN; 0 NaN]));
R = [0 1 0; 0 0 1; 0 0 0] ^ 0.5;
asserts.isequal(lastwarn(), '');
asserts.isequal(R(1, 2), Inf);
asserts.isequal(R(2, 3), Inf);
asserts.istrue(isnan(R(1, 3)));
R = [0 1 0; 0 0 0; 0 0 3] ^ 0.5;
asserts.isequal(R(1, 2), Inf);
asserts.istrue(isnan(R(1, 3)));
asserts.isapprox(R(3, 3), sqrt(3), 1e-15);
%=============================================================================
% single precision
R = single([2 1; 0 2]) ^ 0.5;
asserts.isequal(class(R), 'single');
asserts.isapprox(R, single([1.41421354 0.353553385; 0 1.41421354]), 1e-6);
R = single([2 1 0; 0 2 1; 0 0 2]) ^ (1/3);
asserts.isapprox(double(R), [1.25992107 0.209986851 -0.0349978134; 0 1.25992107 0.209986851; 0 0 1.25992107], 1e-6);
%=============================================================================
% diagonalizable matrices keep the eigen decomposition
cases(end + 1, :) = {[0 -1; 1 0], 0.5, 0.70710678118654746 * [1 -1; 1 1], 1e-15};
REF = [1.2761391384285634+0.43294026119273826i 0.45403664726447435-0.21282692764251859i;
       -0.070942309214172827-0.15134554908815812i 1.285600069088376+0.059306853802249336i];
cases(end + 1, :) = {[1+2i 3; -1i 2], 0.3, REF, 1e-14};
REF = [1.3763819204711731 0.32491969623290612i; -0.32491969623290617i 1.7013016167040795];
cases(end + 1, :) = {[2 1i; -1i 3], 0.5, REF, 1e-14};
R = [1 1i; 1i 2] ^ 0.5;
REF = [1.0745699318235418 0.39331989319032867i; 0.39331989319032867i 1.4678898250138706];
asserts.isapprox(R, REF, 1e-14);
cases(end + 1, :) = {single([1 1i; 1i 2]), 0.5, single(REF), 1e-6};
lastwarn('');
R = [1 NaN; 0 1] ^ 0.5;
asserts.isequal(lastwarn(), '');
asserts.istrue(all(isnan(R(:))));
%=============================================================================
% a ^ B keeps the eigen decomposition, a defective B does not warn
lastwarn('');
R = 2 ^ [1 1; 0 1];
asserts.isequal(lastwarn(), '');
asserts.isequal(R, [2 0; 0 2]);
R = 2 ^ [0 1; 0 0];
asserts.isequal(lastwarn(), '');
asserts.isequal(R, eye(2));
R = (-2) ^ [2 1; 1 3];
REF = [0.54636683200890634-4.9206790651557935i 2.412165380548847-4.0314700263864163i;
       2.412165380548847-4.0314700263864154i 2.958532212557754-8.9521490915422088i];
asserts.isapprox(R, REF, 1e-14);
%=============================================================================
% sparse operands: same values as full ones, A ^ p stays sparse, a ^ B is full
lastwarn('');
R = sparse([2 1; 0 2]) ^ 0.5;
asserts.isequal(lastwarn(), '');
asserts.istrue(issparse(R));
asserts.isapprox(full(R), [1.4142135623730951 0.35355339059327373; 0 1.4142135623730951], 1e-15);
R = sparse([2 1; 0 2]) ^ -0.5;
asserts.isapprox(full(R), [0.70710678118654746 -0.17677669529663687; 0 0.70710678118654746], 1e-15);
R = sparse([-1 1; 0 -1]) ^ 0.5;
asserts.istrue(issparse(R));
asserts.isequal(full(R), [1i -0.5i; 0 1i]);
R = sparse([2 1 0; 0 2 1; 0 0 2]) ^ (1/3);
REF = [1.2599210498948732 0.20998684164914549 -0.034997806941524254;
       0 1.2599210498948732 0.20998684164914549;
       0 0 1.2599210498948732];
asserts.isapprox(full(R), REF, 1e-14);
asserts.isequal(full(sparse([0 1; 0 0]) ^ 0.5), [0 Inf; 0 0]);
R = sparse([0 -1; 1 0]) ^ 0.5;
asserts.istrue(issparse(R) && isreal(R));
asserts.isapprox(full(R), 0.70710678118654746 * [1 -1; 1 1], 1e-15);
R = sparse([1+2i 3; -1i 2]) ^ 0.3;
REF = [1.2761391384285634+0.43294026119273826i 0.45403664726447435-0.21282692764251859i;
       -0.070942309214172827-0.15134554908815812i 1.285600069088376+0.059306853802249336i];
asserts.isapprox(full(R), REF, 1e-14);
R = 2 ^ sparse([1 2; 3 4]);
asserts.isfalse(issparse(R));
asserts.isapprox(R, [10.48273938962865 14.151878828320637; 21.227818242480954 31.710557632109609], 1e-14);
asserts.isequal(2 ^ sparse([0 1; 1 0]), [1.25 0.75; 0.75 1.25]);
% a complex diagonal is not Hermitian: its imaginary part is kept
R = [1+1i 0; 0 4] ^ 0.5;
asserts.isapprox(R, [1.09868411346781+0.455089860562227i 0; 0 2], 1e-14);
%=============================================================================
for k = 1:size(cases, 1)
  [A, p, REF, tol] = cases{k, :};
  lastwarn('');
  R = A ^ p;
  [msg, id] = lastwarn();
  asserts.isequal(id, '');
  asserts.isequal(class(R), class(REF));
  asserts.isequal(isreal(R), isreal(REF));
  asserts.isapprox(R, REF, tol);
end
