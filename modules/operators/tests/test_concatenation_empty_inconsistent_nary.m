% Three or more empty operands of inconsistent sizes, read from left to right:
% two operands with no dimension above 1 give 0x0 that later operands can
% join, two larger operands not both empty along the concatenated dimension
% give 0x0 that ignores later 2-D operands, and once a mismatch involves an
% N-D operand every later mismatch gives 0x0 that later operands can join.
addpath(modulepath('operators', 'tests'));
makers = {@(d) zeros(d); ...
          @(d) true(d); ...
          @(d) zeros(d, 'int8'); ...
          @(d) repmat('a', d); ...
          @(d) repmat("a", d); ...
          @(d) repmat({1}, d); ...
          @(d) repmat(struct('v', 1), d); ...
          @(d) VertcatOrderValueFixture.empty(d); ...
          @(d) VertcatOrderHandleFixture.empty(d)};
%=============================================================================
% {direction, sizes of the operands, expected size}
cases = {'h', {[0 1], [1 0], [0 1]}, [0 1]; ...
         'h', {[0 1], [1 0], [1 0]}, [0 0]; ...
         'h', {[0 1], [1 0], [2 0]}, [2 0]; ...
         'h', {[0 1], [0 1], [0 1]}, [0 3]; ...
         'h', {[0 0], [0 1], [0 2]}, [0 3]; ...
         'h', {[2 0], [1 0], [3 0]}, [3 0]; ...
         'h', {[0 2], [2 0], [0 1]}, [0 0]; ...
         'h', {[0 2], [2 0], [3 0]}, [0 0]; ...
         'h', {[0 1], [0 1 2], [0 1]}, [0 1]; ...
         'h', {[0 1], [0 1 2], [2 0]}, [0 0]; ...
         'h', {[0 1], [0 1 2], [3 0]}, [0 0]; ...
         'h', {[0 1 2], [0 1 2], [0 0]}, [0 2 2]; ...
         'h', {[0 2], [2 0], [0 0 2], [0 1]}, [0 1]; ...
         'h', {[0 1], [0 3 0], [0 1], [1 0]}, [0 0]; ...
         'h', {[0 1], [1 0], [0 1], [2 0]}, [2 0]; ...
         'v', {[1 0], [0 1], [0 2]}, [0 2]; ...
         'v', {[0 1], [1 0], [0 1]}, [0 0]; ...
         'v', {[0 1], [1 0], [3 0]}, [3 0]; ...
         'v', {[0 1], [0 1 2], [3 0]}, [3 0]; ...
         'v', {[0 1], [0 1 2], [0 2]}, [0 0]; ...
         'v', {[0 2], [2 0], [1 0]}, [0 0]; ...
         'v', {[1 0], [2 0], [0 1]}, [3 0]; ...
         'v', {[1 0 2], [1 0 2], [0 0]}, [2 0 2]; ...
         'v', {[0 2], [2 0], [1 0 2], [2 0]}, [2 0]; ...
         'v', {[0 2], [0 3], [0 1]}, [0 3]};
for m = 1:size(makers, 1)
  for c = 1:size(cases, 1)
    operands = cellfun(makers{m}, cases{c, 2}, 'UniformOutput', false);
    if strcmp(cases{c, 1}, 'h')
      R = [operands{:}];
      F = horzcat(operands{:});
    else
      R = vertcat(operands{:});
      F = R;
    end
    assert_isequal(size(R), cases{c, 3});
    assert_isequal(size(F), cases{c, 3});
    assert_isequal(class(R), class(operands{1}));
  end
end
%=============================================================================
% Sparse operands follow the same rule.
for c = 1:size(cases, 1)
  sizes = cases{c, 2};
  if all(cellfun(@numel, sizes) == 2)
    operands = cellfun(@(d) sparse(zeros(d)), sizes, 'UniformOutput', false);
    if strcmp(cases{c, 1}, 'h')
      R = [operands{:}];
    else
      R = vertcat(operands{:});
    end
    assert_isequal(size(R), cases{c, 3});
    assert_istrue(issparse(R));
  end
end
%=============================================================================
e = @(d) function_handle.empty(d);
R = [e([1 0]), e([0 1]), e([1 0])];
assert_isequal(class(R), 'function_handle');
assert_isequal(size(R), [0 0]);
