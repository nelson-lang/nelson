% Same empty operand rules for every type: next to a non-empty array, a 2-D
% empty operand is dropped while an N-D one (1x0x2, 0x0x2) must have
% consistent dimensions; two empty operands never raise an error.
addpath(modulepath('operators', 'tests'));
msg = _('Dimensions of arrays being concatenated are not consistent.');
id = 'Nelson:catenate:dimensionMismatch';
v1 = VertcatOrderValueFixture(1);
h1 = VertcatOrderHandleFixture(1);
% {maker of non-empty arrays, maker of empty arrays}
makers = {@(d) ones(d), @(d) ones(d); ...
          @(d) true(d), @(d) true(d); ...
          @(d) ones(d, 'int8'), @(d) ones(d, 'int8'); ...
          @(d) repmat('a', d), @(d) repmat('a', d); ...
          @(d) repmat("a", d), @(d) repmat("a", d); ...
          @(d) repmat({1}, d), @(d) repmat({1}, d); ...
          @(d) repmat(struct('v', 1), d), @(d) repmat(struct('v', 1), d); ...
          @(d) reshape(v1(ones(1, prod(d))), d), @(d) VertcatOrderValueFixture.empty(d); ...
          @(d) reshape(h1(ones(1, prod(d))), d), @(d) VertcatOrderHandleFixture.empty(d)};
%=============================================================================
% {size of A, direction, size of B, expected size or [] for an error}
cases = {[1 0 2], 'h', [1 2], []; ...
         [1 2], 'h', [1 0 2], []; ...
         [1 0 2], 'v', [2 1], []; ...
         [0 0 2], 'h', [1 2], []; ...
         [0 0 2], 'v', [1 2], []; ...
         [1 2 0], 'v', [1 2], []; ...
         [1 0 2], 'h', [1 2 2], [1 2 2]; ...
         [0 2 2], 'v', [1 2 2], [1 2 2]; ...
         [0 3], 'h', [1 2], [1 2]; ...
         [0 3], 'v', [1 2], [1 2]; ...
         [1 0], 'h', [1 2], [1 2]; ...
         [1 0], 'v', [2 1], [2 1]; ...
         [2 0], 'h', [2 1], [2 1]; ...
         [2 0], 'v', [2 1], [2 1]; ...
         [2 0], 'h', [1 2], [1 2]; ...
         [2 1], 'h', [2 0], [2 1]; ...
         [0 3], 'h', [0 2], [0 5]; ...
         [3 0], 'h', [3 0], [3 0]; ...
         [2 0], 'v', [3 0], [5 0]; ...
         [0 3], 'v', [0 3], [0 3]; ...
         [1 0 2], 'h', [1 0 2], [1 0 2]; ...
         [1 0 2], 'v', [2 0 2], [3 0 2]; ...
         [0 0 2], 'h', [0 0], [0 0 2]; ...
         [0 0], 'h', [0 0 2], [0 0 2]; ...
         [1 0 2], 'h', [1 0 3], [0 0]; ...
         [1 0 2], 'h', [1 0], [0 0]; ...
         [2 0], 'h', [0 2], [0 0]};
for m = 1:size(makers, 1)
  for c = 1:size(cases, 1)
    A = makers{m, 1 + any(cases{c, 1} == 0)}(cases{c, 1});
    B = makers{m, 1 + any(cases{c, 3} == 0)}(cases{c, 3});
    if strcmp(cases{c, 2}, 'h')
      cmd = '[A, B]';
    else
      cmd = '[A; B]';
    end
    if isempty(cases{c, 4})
      assert_checkerror(cmd, msg, id);
    else
      R = eval(cmd);
      assert_isequal(size(R), cases{c, 4});
      assert_isequal(class(R), class(A));
    end
  end
end
%=============================================================================
A = reshape(1:2, [1 2]);
assert_isequal([zeros(2, 0), A, zeros(3, 0)], A);
assert_isequal([A; zeros(0, 3); A], [A; A]);
assert_checkerror('[zeros(1, 0, 2), zeros(1, 0, 2), A]', msg, id);
assert_checkerror('horzcat(zeros(1, 0, 2), A)', msg, id);
assert_checkerror('vertcat(zeros(1, 0, 2), A)', msg, id);
assert_checkerror('[cell(1, 0, 2), {1, 2}]', msg, id);
%=============================================================================
% cat along a dimension >= 3 only drops 0x0 operands.
assert_isequal(cat(3, [], A), A);
assert_isequal(cat(3, A, zeros(1, 2, 0)), A);
assert_isequal(size(cat(3, zeros(0, 3), zeros(0, 3))), [0 3 2]);
assert_isequal(cat(3, A, zeros(1, 2, 0), A), cat(3, A, A));
assert_checkerror('cat(3, zeros(1, 0), A)', msg, id);
assert_checkerror('cat(3, zeros(1, 0, 2), A)', msg, id);
assert_checkerror('cat(3, zeros(0, 0, 2), A)', msg, id);
assert_checkerror('cat(3, cell(1, 0), {1, 2})', msg, id);
assert_checkerror('cat(3, repmat(struct(''v'', 1), 1, 0), struct(''v'', {1, 2}))', msg, id);
