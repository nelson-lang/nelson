% <-- Short Description -->
% colon with int64 operands truncated the bounds to int32
%=============================================================================
r = int64(5000000000):int64(5000000002);
asserts.isequal(class(r), 'int64');
asserts.isequal(numel(r), 3);
asserts.isequal(r(1), int64(5000000000));
asserts.isequal(r(2), int64(5000000001));
asserts.isequal(r(3), int64(5000000002));
%=============================================================================
r = int64(5000000000):int64(2):int64(5000000004);
asserts.isequal(numel(r), 3);
asserts.isequal(r(3), int64(5000000004));
%=============================================================================
% small ranges still work
asserts.isequal(int64(1):int64(3), int64([1 2 3]));
