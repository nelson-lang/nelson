%=============================================================================
A = 3;
B = 4;
asserts.isequal(A + B, 7);
%=============================================================================
asserts.isequal(3 + [], []);
%=============================================================================
asserts.isequal([] + 3, []);
%=============================================================================
asserts.isequal(3 + ones(3, 0), zeros(3, 0));
%=============================================================================
asserts.isequal(ones(3, 0) + 3, zeros(3, 0));
%=============================================================================
A = [1 2; 3 4];
B = [5 6; 7 8];
R = A + B;
REF = [6 8; 10 12];
asserts.isequal(R, REF);
%=============================================================================
A = [1 2; 3 4];
B = 10;
R1 = A + B;
R2 = B + A;
REF = [11, 12; 13, 14];
asserts.isequal(R1, R2);
asserts.isequal(R1, REF);
%=============================================================================
A = [0 10; 10 0];
R = A + 20;
REF = [20 30; 30 20];
asserts.isequal(R, REF);
%=============================================================================
A = [10 0; 20 40];
B = [50 90; 20 10];
R = A + B;
REF = [60 90; 40 50];
asserts.isequal(R, REF);
%=============================================================================
A = [10, 20, 30, 40];
B = [50; 60; 70];
R1 = A + B;
R2 = B + A;
asserts.isequal(R1, R2);
REF = [60 70 80 90;
  70 80 90 100;
  80 90 100 110];
asserts.isequal(R1, REF);
%=============================================================================
A = [10 20 30; 40 50 60];
B = [10; 100];
R1 = A + B;
R2 = B + A;
asserts.isequal(R1, R2);
REF = [20 30 40; 140 150 160];
asserts.isequal(R1, REF);
%=============================================================================
R1 = [1:3] + [1:3]';
R2 = [1:3]' + [1:3];
asserts.isequal(R1, R2);
REF = [2 3 4;
  3 4 5;
  4 5 6];
asserts.isequal(R1, REF);
%=============================================================================
A = [1:3]';
B = [1:4];
R = A + B;
REF = [2 3 4 5;
  3 4 5 6;
  4 5 6 7];
asserts.isequal(R, REF);
%=============================================================================
A = [1:4]';
B = [1:3];
R = A + B;
REF = [2 3 4;
  3 4 5;
  4 5 6;
  5 6 7];
asserts.isequal(R, REF);
%=============================================================================
A = reshape(1:(3 * 4 * 2), 3, 4, 2);
B = 1:5;
asserts.checkerror('R = A + B;', [_('Size mismatch on arguments to arithmetic operator'), ' +']);
%=============================================================================
R = [1; 3] + [1 2 3 4; 4 5 6 7];
REF = [2 3 4 5; 7 8 9 10];
asserts.isequal(R, REF);
%=============================================================================
A = [1, 3; 2, 4];
B = [1 2 3 4; 4 5 6 7];
asserts.checkerror('R = A + B;', [_('Size mismatch on arguments to arithmetic operator'), ' +']);
%=============================================================================
R = [1 2 3 4] + [1 2 3 4; 4 5 6 7];
REF = [2 4 6 8; 5 7 9 11];
asserts.isequal(R, REF);
%=============================================================================
R = [1 2 3 4; 4 5 6 7] + [1 2 3 4];
REF = [2 4 6 8; 5 7 9 11];
asserts.isequal(R, REF);
%=============================================================================
R = [1 2 3 4; 4 5 6 7] + [1; 2];
REF = [2 3 4 5; 6 7 8 9];
asserts.isequal(R, REF);
%=============================================================================
A = [10 20 30; 40 50 60];
B = [1 2 3];
R = A + B;
REF = [11 22 33; 41 52 63];
asserts.isequal(R, REF);
%=============================================================================
B = [10 20 30; 40 50 60];
A = [1 2 3];
R = A + B;
REF = [11 22 33; 41 52 63];
asserts.isequal(R, REF);
%=============================================================================
A = ones(3, 1);
B = ones(4, 1);
asserts.checkerror('A + B', [_('Size mismatch on arguments to arithmetic operator'), ' +']);
%=============================================================================
R = reshape(1:(4 * 4 * 2), 4, 4, 2) + [1; 2; 3; 4];
REF1 = [2 6 10 14;
  4 8 12 16;
  6 10 14 18;
  8 12 16 20];
asserts.isequal(R(:, :, 1), REF1);
%=============================================================================
REF2 = [18 22 26 30;
  20 24 28 32;
  22 26 30 34;
  24 28 32 36];
asserts.isequal(R(:, :, 2), REF2);
%=============================================================================
A = reshape(1:(3 * 4 * 2), 3, 4, 2);
B = 1:4;
R = A + B;
REF_1 = [2 6 10 14;
  3 7 11 15;
  4 8 12 16];
asserts.isequal(R(:, :, 1), REF_1);
REF_2 = [14 18 22 26;
  15 19 23 27;
  16 20 24 28];
asserts.isequal(R(:, :, 2), REF_2);
%=============================================================================
R = char(65) + char(1);
asserts.isequal(class(R), 'double');
asserts.isequal(R, 66);
%=============================================================================
R = char(65) + 1;
asserts.isequal(class(R), 'double');
asserts.isequal(R, 66);
%=============================================================================
R = 1 + char(65);
asserts.isequal(class(R), 'double');
asserts.isequal(R, 66);
%=============================================================================
R = char([65 66]) + [1 2];
asserts.isequal(class(R), 'double');
asserts.isequal(R, [66 68]);
%=============================================================================
R = char(65) + true;
asserts.isequal(class(R), 'double');
asserts.isequal(R, 66);
%=============================================================================
