%=============================================================================
R = 0i;
asserts.istrue(isreal(R));
%=============================================================================
R = 0 * i;
asserts.istrue(isreal(R));
%=============================================================================
R = i * 0;
asserts.istrue(isreal(R));
%=============================================================================
R = 0 .* i;
asserts.istrue(isreal(R));
%=============================================================================
R = i .* 0;
asserts.istrue(isreal(R));
%=============================================================================
R = i .* 0;
asserts.istrue(isreal(R));
%=============================================================================
R = 0 .* i;
asserts.istrue(isreal(R));
%=============================================================================
R = [0 * i 1];
asserts.istrue(isreal(R));
%=============================================================================
R = [0i 1];
asserts.istrue(isreal(R));
%=============================================================================
R = complex([0 * i]);
asserts.isfalse(isreal(R));
%=============================================================================
R = [eps * i 1];
asserts.isfalse(isreal(R));
%=============================================================================
R = 0 * [i i];
asserts.istrue(isreal(R));
%=============================================================================
R = 0 * [i 0i];
asserts.istrue(isreal(R));
%=============================================================================
R = [0 0] * [2; 3];
asserts.istrue(isreal(R));
%=============================================================================
R = [0i 0] * [2; 3];
asserts.istrue(isreal(R));
%=============================================================================
R = [complex(0, 0) 0] * [2; 3];
asserts.istrue(isreal(R));
%=============================================================================
R = [1 2 3 4] .* 2i;
asserts.isfalse(isreal(R));
%=============================================================================
R = 2i .* [1 2 3 4];
asserts.isfalse(isreal(R));
