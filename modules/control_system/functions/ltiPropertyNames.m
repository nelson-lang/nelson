function props = ltiPropertyNames(className)
  switch className
    case 'tf'
      props = {'Numerator'; 'Denominator'; 'Variable'; 'IODelay'; ...
        'InputDelay'; 'OutputDelay'; 'InputName'; 'InputUnit'; 'InputGroup'; ...
        'OutputName'; 'OutputUnit'; 'OutputGroup'; 'Notes'; 'UserData'; ...
        'Name'; 'Ts'; 'TimeUnit'; 'SamplingGrid'};
    case 'ss'
      props = {'A'; 'B'; 'C'; 'D'; 'E'; 'Offsets'; 'Scaled'; 'StateName'; ...
        'StatePath'; 'StateUnit'; 'InternalDelay'; 'InputDelay'; 'OutputDelay'; ...
        'InputName'; 'InputUnit'; 'InputGroup'; 'OutputName'; 'OutputUnit'; ...
        'OutputGroup'; 'Notes'; 'UserData'; 'Name'; 'Ts'; 'TimeUnit'; ...
        'SamplingGrid'};
    case 'zpk'
      props = {'Z'; 'P'; 'K'; 'Variable'; 'IODelay'; ...
        'InputDelay'; 'OutputDelay'; 'InputName'; 'InputUnit'; 'InputGroup'; ...
        'OutputName'; 'OutputUnit'; 'OutputGroup'; 'Notes'; 'UserData'; ...
        'Name'; 'Ts'; 'TimeUnit'; 'SamplingGrid'};
    otherwise
      error('Nelson:control_system:invalidType', '%s expected.', 'LTI model');
  end
end
