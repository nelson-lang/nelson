% <--WEIGHT 2-->
num = [3 4];
den = [3 1 5];
Ts = 0.2;
sys = tf(num, den, Ts);
R = sys / sys;
num_REF = [9 15 19 20];
den_REF = [9 15 19 20];
REF = tf(num_REF, den_REF, Ts);
asserts.isequal(R, REF);
%=============================================================================
R = tf(2) / sys;
asserts.isequal(R.Ts, Ts);
R = tf('z') / sys;
asserts.isequal(R.Ts, Ts);
