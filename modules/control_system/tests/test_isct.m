asserts.isequal(nargin('isct'), 1);
asserts.isequal(nargout('isct'), 1);
%=============================================================================
A = [-10 0 0; 10 / 2 -1 0; 10 / 2 0 -1];
B = [10 0; 0 -10; 0 10];
C = [0 0 1; 1 1 0];
D = zeros(size(C, 1), size(B, 2));
Ts = 0.2;
S = ss(A, B, C, D, Ts);
asserts.isfalse(isct(S))
%=============================================================================
A = [-10 0 0; 10 / 2 -1 0; 10 / 2 0 -1];
B = [10 0; 0 -10; 0 10];
C = [0 0 1; 1 1 0];
D = zeros(size(C, 1), size(B, 2));
S = ss(A, B, C, D);
asserts.istrue(isct(S))
%=============================================================================
S = tf(4.7, [1 -4.43]);
asserts.istrue(isct(S));
%=============================================================================
S = tf(4.7, [1 -4.43], 0.5);
asserts.isfalse(isct(S));
%=============================================================================
S = tf(3);
asserts.istrue(isct(S))
