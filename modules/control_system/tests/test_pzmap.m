G = tf([1 2], [1 3 2]);
[p, z] = pzmap(G);
asserts.isequal(p, pole(G));
asserts.isequal(z, zero(G));
asserts.isequal(size(p), [2, 1]);
asserts.isequal(size(z), [1, 1]);
asserts.isapprox(sort(p), [-2; -1], 1e-12);
asserts.isapprox(sort(z), -2, 1e-12);
%=============================================================================
G = tf([1 2], [1 3 2]);
p = pzmap(G);
asserts.isequal(p, pole(G));
%=============================================================================
f = figure();
G = tf([1 2], [1 3 2]);
pzmap(G);
close(f);
%=============================================================================
f = figure();
G = tf(1, [1 0.5 1]);
pzmap(G);
close(f);
%=============================================================================
asserts.checkerror('pzmap(1)', sprintf(_('%s expected.'), 'LTI model'));
