header = sprintf('\ttimetable timerange subscript:\n\n\t\tSelect timetable rows with times in the ');
%=============================================================================
txt = evalc('S1 = timerange(seconds(1), seconds(2))');
expected = [sprintf('\nS1 = \n\n'), header, sprintf('half-open interval:\n'), ...
  sprintf('\t\t  Starting at, including:   1 sec\n'), ...
  sprintf('\t\t  Ending at, but excluding: 2 sec\n\n')];
assert_isequal(txt, expected);
txt = evalc('disp(S1)');
expected = [header, sprintf('half-open interval:\n'), ...
  sprintf('\t\t  Starting at, including:   1 sec\n'), ...
  sprintf('\t\t  Ending at, but excluding: 2 sec\n\n')];
assert_isequal(txt, expected);
%=============================================================================
txt = evalc('disp(timerange(seconds(1), seconds(2), ''closed''))');
assert_isequal(txt, [header, sprintf('closed interval:\n'), ...
  sprintf('\t\t  Starting at, including: 1 sec\n'), ...
  sprintf('\t\t  Ending at, including:   2 sec\n\n')]);
txt = evalc('disp(timerange(datetime(2020, 1, 1), datetime(2020, 1, 5), ''open''))');
assert_isequal(txt, [header, sprintf('open interval:\n'), ...
  sprintf('\t\t  Starting at, but excluding: 01-Jan-2020 00:00:00\n'), ...
  sprintf('\t\t  Ending at, but excluding:   05-Jan-2020 00:00:00\n\n')]);
txt = evalc('disp(timerange(''-inf'', seconds(5), ''openleft''))');
assert_isequal(txt, [header, sprintf('half-open interval:\n'), ...
  sprintf('\t\t  Starting at, but excluding: -Inf sec\n'), ...
  sprintf('\t\t  Ending at, including:       5 sec\n\n')]);
txt = evalc('disp(timerange(datetime(2020, 1, 1), ''month''))');
assert_isequal(txt, [header, sprintf('half-open interval:\n'), ...
  sprintf('\t\t  Starting at, including:   01-Jan-2020 00:00:00\n'), ...
  sprintf('\t\t  Ending at, but excluding: 01-Feb-2020 00:00:00\n\n')]);
txt = evalc('disp(timerange(''2020-01-01'', ''2020-02-01'', ''closedright''))');
assert_isequal(txt, [header, sprintf('half-open interval:\n'), ...
  sprintf('\t\t  Starting at, but excluding: 01-Jan-2020 00:00:00\n'), ...
  sprintf('\t\t  Ending at, including:       01-Feb-2020 00:00:00\n\n')]);
txt = evalc('disp(timerange(minutes(1), ''inf''))');
assert_isequal(txt, [header, sprintf('half-open interval:\n'), ...
  sprintf('\t\t  Starting at, including:   1 min\n'), ...
  sprintf('\t\t  Ending at, but excluding: Inf min\n\n')]);
txt = evalc('disp(timerange(''-inf'', datetime(2020, 1, 1, 10, 30, 0)))');
assert_isequal(txt, [header, sprintf('half-open interval:\n'), ...
  sprintf('\t\t  Starting at, including:   -Inf\n'), ...
  sprintf('\t\t  Ending at, but excluding: 01-Jan-2020 10:30:00\n\n')]);
txt = evalc('disp(timerange(hours(1), minutes(90), ''closed''))');
assert_isequal(txt, [header, sprintf('closed interval:\n'), ...
  sprintf('\t\t  Starting at, including: 1 hr\n'), ...
  sprintf('\t\t  Ending at, including:   90 min\n\n')]);
%=============================================================================
% the limits keep selecting the same rows
TT = timetable(seconds((1:5)'), (1:5)', 'VariableNames', {'A'});
assert_isequal(TT(timerange(seconds(2), seconds(4), 'closed'), :).A, [2; 3; 4]);
%=============================================================================
txt = evalc('w = withtol(seconds(2), seconds(0.1))');
expected = [sprintf('\nw = \n\n\ttimetable withtol subscript:\n\n'), ...
  sprintf('\t\tSelect timetable rows matching the following times:\n\n'), ...
  sprintf('\t\t2 sec\n\t\twith tolerance of +/- 0.1 sec\n\n')];
assert_isequal(txt, expected);
