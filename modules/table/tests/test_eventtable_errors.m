assert_checkerror('eventtable(seconds([1; 2]), ''EventLengths'', seconds([1; 2]), ''EventEnds'', seconds([2; 3]))', ...
  'Specify either event lengths or event ends but not both.', 'Nelson:eventtable:bothLengthsAndEnds');
assert_checkerror('eventtable(seconds([1; 2]), ''EventLengths'', [1; 2])', ...
  'Event lengths variable must be a duration or calendarDuration column vector.', 'Nelson:eventtable:invalidLengthsVariable');
assert_checkerror('eventtable(seconds([1; 2]), ''EventEnds'', [1; 2])', ...
  'Event ends variable must be a datetime or duration column vector.', 'Nelson:eventtable:invalidEndsVariable');
assert_checkerror('eventtable(datetime(2022, 1, [1; 2]), ''EventEnds'', seconds([1; 2]))', ...
  'Event ends variable must be the same data type as the event table row times.', 'Nelson:eventtable:incompatibleEndsRowTimes');
assert_checkerror('eventtable(seconds([1; 2]), ''EventLabelsVariable'', ''x'')', ...
  '''EventLabelsVariable'' name-value pair is only supported when the first input is a timetable.', 'Nelson:eventtable:firstInputMustBeTimetable');
%=============================================================================
TT = timetable(seconds([1; 2]), {'a'; 'b'}, seconds([1; 2]));
assert_checkerror('eventtable(TT, ''EventLabelsVariable'', 2)', ...
  'Event labels variable must not be a datetime, duration, or calendarDuration variable.', 'Nelson:eventtable:invalidLabelsVariableTime');
assert_checkerror('eventtable(TT, ''EventLabelsVariable'', ''Var1'', ''EventLabels'', {''x''; ''y''})', ...
  'Specify either event labels or an event labels variable.', 'Nelson:eventtable:bothValueAndVariable');
assert_checkerror('eventtable(TT, ''EventLengthsVariable'', ''Var1'')', ...
  'Event lengths variable must be a duration or calendarDuration column vector.', 'Nelson:eventtable:invalidLengthsVariable');
assert_checkerror('eventtable(TT, ''EventLabelsVariable'', ''Nope'')', ...
  'Unrecognized table variable name ''Nope''.', 'Nelson:eventtable:unrecognizedVariable');
%=============================================================================
% the event variables set through Properties are checked
ET = eventtable(timetable(seconds([1; 2]), [10; 20], [5; 6]));
assert_checkerror('ET.Properties.EventLengthsVariable = ''Var2'';', ...
  'Event lengths variable must be a duration or calendarDuration column vector.', 'Nelson:eventtable:invalidLengthsVariable');
assert_checkerror('ET.Properties.EventEndsVariable = ''Var2'';', ...
  'Event ends variable must be a datetime or duration column vector.', 'Nelson:eventtable:invalidEndsVariable');
assert_checkerror('ET.Properties.EventLabelsVariable = ''Zzz'';', ...
  'Unrecognized table variable name ''Zzz''.', 'Nelson:eventtable:unrecognizedVariable');
assert_checkerror('ET.Properties.EventLabelsVariable = 3;', ...
  'Variable index exceeds table dimensions.', 'Nelson:eventtable:varIndexOutOfRange');
assert_isequal(ET.Properties.EventLabelsVariable, []);
