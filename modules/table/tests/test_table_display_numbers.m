%=============================================================================
% Numbers in a table are shown one by one in their shortest form: 5
% significant digits (15 in format long, 7 for single), integers in full.
%=============================================================================
format('compact');
format('short');
%=============================================================================
T = table([1; -2.5; NaN]);
R = evalc('disp(T)');
REF = sprintf('    Var1\n    ____\n       1\n    -2.5\n     NaN\n');
assert_isequal(R, REF);
%=============================================================================
T = table([1.5; 2]);
R = evalc('disp(T)');
REF = sprintf('    Var1\n    ____\n    1.5 \n      2 \n');
assert_isequal(R, REF);
%=============================================================================
T = table([pi; 123456; 1e10; 0.001; 1000.5]);
R = evalc('disp(T)');
REF = sprintf(['       Var1   \n', ...
  '    __________\n', ...
  '        3.1416\n', ...
  '    1.2346e+05\n', ...
  '         1e+10\n', ...
  '         0.001\n', ...
  '        1000.5\n']);
assert_isequal(R, REF);
%=============================================================================
T = table([99999.5; 12345.6; 9.99999; -0; 1e-5; 1e100]);
R = evalc('disp(T)');
REF = sprintf(['     Var1 \n', ...
  '    ______\n', ...
  '     1e+05\n', ...
  '     12346\n', ...
  '        10\n', ...
  '         0\n', ...
  '     1e-05\n', ...
  '    1e+100\n']);
assert_isequal(R, REF);
%=============================================================================
T = table([Inf; -Inf; NaN]);
R = evalc('disp(T)');
REF = sprintf('    Var1\n    ____\n     Inf\n    -Inf\n     NaN\n');
assert_isequal(R, REF);
%=============================================================================
T = table(single([1.5; pi; 1e10]));
R = evalc('disp(T)');
REF = sprintf('     Var1 \n    ______\n       1.5\n    3.1416\n     1e+10\n');
assert_isequal(R, REF);
%=============================================================================
T = table(uint64([18446744073709551615; 1]));
R = evalc('disp(T)');
REF = sprintf(['            Var1        \n', ...
  '    ____________________\n', ...
  '    18446744073709551615\n', ...
  '                       1\n']);
assert_isequal(R, REF);
%=============================================================================
T = table(int32([-5; 123456789]));
R = evalc('disp(T)');
REF = sprintf('      Var1   \n    _________\n           -5\n    123456789\n');
assert_isequal(R, REF);
%=============================================================================
T = table([1 2.5; 3 4]);
R = evalc('disp(T)');
REF = sprintf('      Var1  \n    ________\n    1    2.5\n    3      4\n');
assert_isequal(R, REF);
%=============================================================================
T = table([pi 1e10; 1 2]);
R = evalc('disp(T)');
REF = sprintf(['          Var1      \n', ...
  '    ________________\n', ...
  '    3.1416     1e+10\n', ...
  '         1         2\n']);
assert_isequal(R, REF);
%=============================================================================
T = table([1.5; 2], [3; 4], {'a'; 'b'});
R = evalc('disp(T)');
REF = sprintf(['    Var1    Var2    Var3 \n', ...
  '    ____    ____    _____\n', ...
  '    1.5      3      {''a''}\n', ...
  '      2      4      {''b''}\n']);
assert_isequal(R, REF);
%=============================================================================
T = table([1.5 + 2.25i; pi]);
R = evalc('disp(T)');
REF = sprintf(['        Var1    \n', ...
  '    ____________\n', ...
  '       1.5+2.25i\n', ...
  '    3.1416+0i   \n']);
assert_isequal(R, REF);
%=============================================================================
T = table([1 - 2i; NaN + 1i]);
R = evalc('disp(T)');
REF = sprintf('     Var1 \n    ______\n      1-2i\n    NaN+1i\n');
assert_isequal(R, REF);
%=============================================================================
TT = timetable(seconds([1; 2]), [1.5; -2]);
R = evalc('disp(TT)');
REF = sprintf('    Time     Var1\n    _____    ____\n    1 sec    1.5 \n    2 sec     -2 \n');
assert_isequal(R, REF);
%=============================================================================
format('long');
T = table([pi; 1.5; 123456; 0.0001]);
R = evalc('disp(T)');
REF = sprintf(['          Var1      \n', ...
  '    ________________\n', ...
  '    3.14159265358979\n', ...
  '                 1.5\n', ...
  '              123456\n', ...
  '              0.0001\n']);
format('short');
assert_isequal(R, REF);
%=============================================================================
format('long');
T = table(single([pi; 1.5]));
R = evalc('disp(T)');
REF = sprintf('      Var1  \n    ________\n    3.141593\n         1.5\n');
format('short');
assert_isequal(R, REF);
%=============================================================================
format('shortG');
T = table([pi; 1.5; -2]);
R = evalc('disp(T)');
REF = sprintf('     Var1 \n    ______\n    3.1416\n       1.5\n        -2\n');
format('short');
assert_isequal(R, REF);
