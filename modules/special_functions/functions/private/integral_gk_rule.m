% Nodes and weights of the 15-point Kronrod rule and of the embedded
% 7-point Gauss rule.
%=============================================================================
function [nodes, wk, wgw] = integral_gk_rule()
  xgk = [0.991455371120813, 0.949107912342759, 0.864864423359769, ...
    0.741531185599394, 0.586087235467691, 0.405845151377397, ...
    0.207784955007898, 0.000000000000000];
  wgk = [0.022935322010529, 0.063092092629979, 0.104790010322250, ...
    0.140653259715525, 0.169004726639267, 0.190350578064785, ...
    0.204432940075298, 0.209482141084728];
  wg = [0.129484966168870, 0.279705391489277, 0.381830050505119, ...
    0.417959183673469];
  nodes = [-xgk(1:7), xgk(8), fliplr(xgk(1:7))];
  wk = [wgk(1:7), wgk(8), fliplr(wgk(1:7))];
  wgw = zeros(1, 15);
  wgw([2, 14]) = wg(1);
  wgw([4, 12]) = wg(2);
  wgw([6, 10]) = wg(3);
  wgw(8) = wg(4);
end
