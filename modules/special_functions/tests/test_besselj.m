  _('NU and Z must have the same size, or one of them must be a scalar.'), ...
  'Nelson:special_functions:besselSizeMismatch');
asserts.checkerror('besselj(1 + 2i, 3)', _('NU must be real.'), 'Nelson:special_functions:besselNuMustBeReal');
asserts.checkerror('besselj(int8(1), 3)', _('Input arguments must be single or double.'), ...
  'Nelson:special_functions:singleOrDoubleExpected');
asserts.checkerror('besselj(1, sparse(3))', _('dense type for all input arguments expected.'), ...
  'Nelson:special_functions:denseExpected');
asserts.checkerror('besselj(1, 2, 2)', _('SCALE must be equal to 0 or 1.'), ...
  'Nelson:special_functions:invalidScale');
asserts.checkerror('[a, b] = besselj(1, 2)', _('Too many output arguments.'));
