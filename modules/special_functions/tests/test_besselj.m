%=============================================================================
% integer orders on the negative axis stay real
R = besselj([0 1 2 3], -2.5);
asserts.istrue(isreal(R));
asserts.isequal(R, [1 -1 1 -1] .* besselj([0 1 2 3], 2.5));
asserts.isequal(besselj(-3, 2.5), -besselj(3, 2.5));
% non integer orders on the negative axis are complex
asserts.isfalse(isreal(besselj(0.5, -1)));
%=============================================================================
% scalar expansion and shapes
asserts.isequal(size(besselj(1, ones(2, 3, 2))), [2 3 2]);
asserts.isequal(size(besselj([0 1; 2 3], 4)), [2 2]);
asserts.isequal(besselj([0 1 2], 3), [besselj(0, 3), besselj(1, 3), besselj(2, 3)]);
asserts.isequal(size(besselj(1, zeros(0, 3))), [0 3]);
asserts.isequal(size(besselj([], 1)), [0 0]);
%=============================================================================
% single precision
R = besselj(1, single(2));
asserts.isequal(class(R), 'single');
asserts.isequal(R, single(0.576724827));
asserts.isequal(class(besselj(single(1), 2)), 'single');
%=============================================================================
% special values
asserts.isequal(besselj(0, 0), 1);
asserts.isequal(besselj(2, 0), 0);
asserts.isequal(besselj(-0.5, 0), Inf);
asserts.istrue(isnan(besselj(1, NaN)));
asserts.istrue(isnan(besselj(NaN, 1)));
asserts.istrue(isnan(besselj(0, Inf)));
asserts.isequal(besselj(1e6, 1), 0);
asserts.isapprox(besselj(0, 1e10), 2.1755917502468918e-06, 1e-13);
asserts.isapprox(besselj(1, 1e18), -6.2700719140944109e-10, 1e-13);
%=============================================================================
