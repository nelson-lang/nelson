asserts.isequal(nargin('quadgk'), -4);
asserts.isequal(nargout('quadgk'), -1);
%=============================================================================
R = quadgk(@(x) x .^ 2, 0, 1);
asserts.isapprox(R, 1 / 3, 1e-12);
%=============================================================================
[R, errbnd] = quadgk(@(x) exp(-x .^ 2), 0, Inf);
asserts.isapprox(R, sqrt(pi) / 2, 1e-8);
asserts.istrue(errbnd >= 0);
%=============================================================================
R = quadgk(@(x) log(x), 0, 1);
asserts.isapprox(R, -1, 1e-6);
%=============================================================================
R = quadgk(@(z) 1 ./ (2 .* z - 1), 1, 1, 'Waypoints', [1 + 1i, 0 + 1i, 0 - 1i, 1 - 1i]);
asserts.isapprox(R, pi * 1i, 1e-8, 1e-8);
%=============================================================================
asserts.checkerror('quadgk(3, 0, 1)', _('First argument must be a function handle.'), 'Nelson:special_functions:funArgNotHandle');
