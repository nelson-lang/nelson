n = 10;
tic();
for k = 1:n
  q = integral3(@(x, y, z) x .^ 2 + y .^ 2 + z .^ 2, 0, 1, 0, 1, 0, 1);
end
toc();
asserts.isapprox(q, 1, 1e-10);
