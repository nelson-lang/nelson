asserts.checkerror('besseli(int8(1), 3)', _('Input arguments must be single or double.'), ...
  'Nelson:special_functions:singleOrDoubleExpected');
asserts.checkerror('besseli(1, sparse(3))', _('dense type for all input arguments expected.'), ...
  'Nelson:special_functions:denseExpected');
asserts.checkerror('besseli(1, 2, 0.5)', _('SCALE must be equal to 0 or 1.'), ...
  'Nelson:special_functions:invalidScale');
