% integer orders: I(-n, x) = I(n, x)
asserts.isequal(besseli(-3, 2.5), besseli(3, 2.5));
asserts.isequal(besseli(3, -2.5), -besseli(3, 2.5));
asserts.istrue(isreal(besseli(2, -2.5)));
asserts.isfalse(isreal(besseli(0.5, -1)));
%=============================================================================
% overflow and scaling
asserts.isequal(besseli(0, 800), Inf);
asserts.isapprox(besseli(1, 800, 1), 0.014098125406526996, 1e-13);
asserts.isequal(besseli(0, Inf), Inf);
asserts.isequal(besseli(1, 0), 0);
asserts.isequal(besseli(-0.5, 0), Inf);
%=============================================================================
% single precision
R = besseli(2, single(1.5));
asserts.isequal(class(R), 'single');
asserts.isequal(R, single(0.337834626));
asserts.isequal(besseli(1, single(200)), single(Inf));
