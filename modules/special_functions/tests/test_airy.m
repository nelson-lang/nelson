% one argument form is Ai
z = [-3 0 1.5];
asserts.isequal(airy(z), airy(0, z));
asserts.istrue(isreal(airy(2, [-10 0 10])));
% scaled Ai is complex on the negative axis, scaled Bi stays real
asserts.isfalse(isreal(airy(0, -2, 1)));
asserts.istrue(isreal(airy(2, -2, 1)));
%=============================================================================
% special values
asserts.isequal(airy(0, Inf), 0);
asserts.isequal(airy(2, Inf), Inf);
asserts.istrue(isnan(airy(0, NaN)));
asserts.isequal(size(airy(0, ones(2, 3))), [2 3]);
%=============================================================================
% single precision
R = airy(single(1.25));
asserts.isequal(class(R), 'single');
asserts.isequal(R, single(0.0996445417));
