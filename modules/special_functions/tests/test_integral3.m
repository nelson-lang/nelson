asserts.isequal(nargin('integral3'), -8);
asserts.isequal(nargout('integral3'), 1);
%=============================================================================
R = integral3(@(x, y, z) y .* sin(x) + z .* cos(x), 0, pi, 0, 1, -1, 1);
asserts.isapprox(R, 2, 1e-10);
%=============================================================================
R = integral3(@(x, y, z) x .^ 2 + y .^ 2 + z .^ 2, 0, 1, 0, 1, 0, 1);
asserts.isapprox(R, 1, 1e-10);
%=============================================================================
R = integral3(@(x, y, z) x .* cos(y) + x .^ 2 .* cos(z), ...
  - 1, 1, @(x) - sqrt(1 - x .^ 2), @(x) sqrt(1 - x .^ 2), ...
  @(x, y) - sqrt(1 - x .^ 2 - y .^ 2), @(x, y) sqrt(1 - x .^ 2 - y .^ 2));
asserts.isapprox(R, 0.779555454655971, 1e-4);
%=============================================================================
R = integral3(@(x, y, z) x + y + z, 0, 1, 0, @(x) x, 0, @(x, y) y);
asserts.isapprox(R, 0.25, 1e-10);
%=============================================================================
asserts.checkerror('integral3(3, 0, 1, 0, 1, 0, 1)', _('First argument must be a function handle.'), 'Nelson:special_functions:funArgNotHandle');
