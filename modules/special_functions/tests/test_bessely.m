  _('NU and Z must have the same size, or one of them must be a scalar.'), ...
  'Nelson:special_functions:besselSizeMismatch');
asserts.checkerror('bessely(1 + 2i, 3)', _('NU must be real.'), 'Nelson:special_functions:besselNuMustBeReal');
asserts.checkerror('bessely(int8(1), 3)', _('Input arguments must be single or double.'), ...
  'Nelson:special_functions:singleOrDoubleExpected');
asserts.checkerror('bessely(1, sparse(3))', _('dense type for all input arguments expected.'), ...
  'Nelson:special_functions:denseExpected');
asserts.checkerror('bessely(1, 2, [1 1])', _('SCALE must be equal to 0 or 1.'), ...
  'Nelson:special_functions:invalidScale');
