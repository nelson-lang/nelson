%=============================================================================
% integer orders: Y(-n, x) = (-1)^n Y(n, x)
asserts.isequal(bessely(-3, 2.5), -bessely(3, 2.5));
asserts.isequal(bessely(-2, 2.5), bessely(2, 2.5));
% the negative axis gives complex values, also for integer orders
asserts.isfalse(isreal(bessely(1, -1)));
asserts.istrue(isreal(bessely(1, [1 2 3])));
%=============================================================================
% scalar expansion and shapes
asserts.isequal(size(bessely(1, ones(2, 3, 2))), [2 3 2]);
asserts.isequal(bessely([0 1 2], 3), [bessely(0, 3), bessely(1, 3), bessely(2, 3)]);
%=============================================================================
% single precision
R = bessely(0, single(3.5));
asserts.isequal(class(R), 'single');
asserts.isequal(R, single(0.189021945));
%=============================================================================
% special values
asserts.isequal(bessely(0, 0), -Inf);
asserts.isequal(bessely(-1.5, 0), -Inf);
asserts.isequal(bessely(2.5, 1e-300), Inf);
asserts.istrue(isnan(bessely(1, NaN)));
asserts.isapprox(bessely(0, 1e5), 0.0018467661588650642, 1e-12);
