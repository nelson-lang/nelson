%=============================================================================
% K is even in the order
asserts.isequal(besselk(-2.5, 3), besselk(2.5, 3));
asserts.isfalse(isreal(besselk(1, -1)));
% closed form for half integer order
x = [0.5 2 7.5];
asserts.isapprox(besselk(0.5, x), sqrt(pi ./ (2 * x)) .* exp(-x), 1e-14);
%=============================================================================
% special values
asserts.isequal(besselk(0, 0), Inf);
asserts.isequal(besselk(1, Inf), 0);
asserts.isequal(besselk(1, 1000), 0);
asserts.istrue(isnan(besselk(1, NaN)));
%=============================================================================
% single precision
R = besselk(0.5, single(4));
asserts.isequal(class(R), 'single');
asserts.isequal(R, single(0.011477625));
