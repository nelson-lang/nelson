asserts.isequal(besselh(2, z), besselh(2, 1, z));
asserts.isfalse(isreal(besselh(0, 1)));
%=============================================================================
% negative real axis: H1(nu, -x) = -exp(-1i*pi*nu) * H2(nu, x)
nu = 2.25;
asserts.isapprox(besselh(nu, 1, -3), -exp(-1i * pi * nu) * besselh(nu, 2, 3), 1e-14);
%=============================================================================
% special values
asserts.istrue(isnan(besselh(0, 0)));
asserts.isequal(class(besselh(1, single(2))), 'single');
asserts.isequal(class(besselh(1, single(1), 2)), 'double');
