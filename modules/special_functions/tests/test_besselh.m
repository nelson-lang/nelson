  'Nelson:special_functions:singleOrDoubleExpected');
asserts.checkerror('besselh(1, sparse(3))', _('dense type for all input arguments expected.'), ...
  'Nelson:special_functions:denseExpected');
asserts.checkerror('besselh(1, 3, 2)', _('K must be equal to 1 or 2.'), ...
  'Nelson:special_functions:besselhInvalidKind');
asserts.checkerror('besselh(1, 1.5, 2)', _('K must be equal to 1 or 2.'), ...
  'Nelson:special_functions:besselhInvalidKind');
