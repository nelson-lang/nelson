asserts.checkerror('besselh([1 2], [1 2 3])', ...
  _('NU and Z must have the same size, or one of them must be a scalar.'), ...
  'Nelson:special_functions:besselSizeMismatch');
asserts.checkerror('besselh(1 + 2i, 3)', _('NU must be real.'), 'Nelson:special_functions:besselNuMustBeReal');
