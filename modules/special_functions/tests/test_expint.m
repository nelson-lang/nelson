assert_isapprox(expint([0.1 1 2 5 10 50]), [1.82292395841939 0.21938393439552 0.0489005107080611 0.00114829559127533 4.15696892968535e-06 3.78326402955046e-24], 1e-13);
assert_isequal(expint(0), Inf);
assert_isapprox(expint([-1 -2]), [-1.89511781635594-3.14159265358979i, -4.95423435600189-3.14159265358979i], 1e-13);
assert_isapprox(expint([1+1i, -1+2i, 1i]), [0.000281624451981354-0.179324535039359i, -1.04216770816494+0.559908772348081i, -0.337403922900968-0.624713256427714i], 1e-13);
z = [-30+1i, -10+10i, -5+20i, 3-40i, -20+0.5i, 0.5+0.5i, -1-1i, 30+30i, -60];
R = [-209840771895.5993+303224387102.12415i, 1576.1504265768501+433.77763904754079i, -7.0789514293925588-1.6102177171960592i, ...
     -0.00099972835368728505-0.00072979526761768267i, -22789165.335691635+11676954.225937655i, 0.25786645713798378-0.39669043545581528i, ...
     -1.764625985563854+0.75382280207927077i, 1.7316045841744069e-15+1.3065678019487304e-15i, -1.936182213929276e+24-3.1415926535897931i];
assert_isapprox(expint(z), R, 1e-13);
assert_isapprox(expint(700), 1.40651876623403e-307, 1e-13);
assert_isapprox(expint(1e-10), 22.4486352651389, 1e-14);
y = expint([Inf -Inf NaN]);
assert_istrue(isnan(real(y(1))));
assert_isequal(imag(y(2)), -pi);
assert_istrue(isnan(y(3)));
assert_istrue(isnan(expint(Inf)));
R = expint(single(1));
assert_isequal(class(R), 'single');
assert_isapprox(R, single(0.219383934395520), 1e-6);
assert_checkerror('expint(int8(1))', _('X must be a single or double array.'));
