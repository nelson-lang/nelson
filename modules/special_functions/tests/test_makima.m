asserts.isequal(nargin('makima'), 3);
asserts.isequal(nargout('makima'), 1);
%=============================================================================
x = [0 1 2.5 3.6 5 7 8.1 10];
y = cos(x);
xq = [0 .25 2.5 4 10];
R = makima(x, y, xq);
REF = [1 0.931138361025038 -0.801143615546934 -0.625240322585953 -0.839071529076452];
asserts.isapprox(R, REF, 1e-12);
%=============================================================================
pp = makima(-2:2, [1 1 0 1 1]);
asserts.isequal(pp.form, 'pp');
asserts.isequal(pp.pieces, 4);
asserts.isequal(pp.order, 4);
asserts.isapprox(pp.coefs(2, :), [1.571428571428571 -2.142857142857143 -0.428571428571429 1], 1e-12);
asserts.isapprox(ppval(pp, 0), 0, 1e-12);
