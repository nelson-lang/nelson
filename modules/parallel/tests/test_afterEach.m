pool = backgroundPool();
clear futures;
for k = 1:3
  futures(k) = parfeval(pool, str2func('@(x) x * 10'), 1, k);
end
after = afterEach(futures, str2func('@(x) x / 10'), 1);
result = fetchOutputs(after);
%=============================================================================
asserts.isequal(result, [1; 2; 3]);
%=============================================================================
cancelAll(pool.FevalQueue);
