asserts.isequal(nargin('degtorad'), -1);
asserts.isequal(nargout('degtorad'), 1);
%=============================================================================
x = -180;
R = degtorad(x);
REF = -pi;
asserts.isequal(R, REF);
%=============================================================================
x = 180;
R = degtorad(x);
REF = pi;
asserts.isequal(R, REF);
%=============================================================================
R = degtorad([0, 90, 180, 270, 360]);
REF = [0, pi/2, pi, 3*pi/2, 2*pi];
asserts.isequal(R, REF);
%=============================================================================
R = degtorad(single(180));
REF = single(pi);
asserts.isequal(R, REF);
%=============================================================================
R = degtorad([180; 90]);
REF = [pi; pi/2];
asserts.isequal(R, REF);
%=============================================================================
assert_isequal(degtorad(180), deg2rad(180));
%=============================================================================
assert_checkerror('degtorad(int8(1))', _('Input must be single or double.'), 'Nelson:trigonometric_functions:nonFloatInput');
