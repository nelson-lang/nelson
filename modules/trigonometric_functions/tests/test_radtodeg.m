asserts.isequal(nargin('radtodeg'), -1);
asserts.isequal(nargout('radtodeg'), 1);
%=============================================================================
x = -pi;
R = radtodeg(x);
REF = -180;
asserts.isequal(R, REF);
%=============================================================================
x = pi;
R = radtodeg(x);
REF = 180;
asserts.isequal(R, REF);
%=============================================================================
R = radtodeg([0, pi/2, pi, 3*pi/2, 2*pi]);
REF = [0, 90, 180, 270, 360];
asserts.isequal(R, REF);
%=============================================================================
R = radtodeg(single(pi));
REF = single(180);
asserts.isequal(R, REF);
%=============================================================================
R = radtodeg([pi; pi/2]);
REF = [180; 90];
asserts.isequal(R, REF);
%=============================================================================
assert_isequal(radtodeg(pi), rad2deg(pi));
%=============================================================================
assert_checkerror('radtodeg(int8(1))', _('Input must be single or double.'), 'Nelson:trigonometric_functions:nonFloatInput');
