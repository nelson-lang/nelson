assert_isequal([wrapTo180(190) wrapTo180(180) wrapTo180(-180) wrapTo180(360)], [-170 180 -180 0]);
%=============================================================================
assert_isequal([wrapTo360(-10) wrapTo360(0) wrapTo360(360) wrapTo360(720)], [350 0 360 360]);
%=============================================================================
assert_isapprox([wrapToPi(4) wrapToPi(pi) wrapToPi(-pi)], [4 - 2 * pi, pi, -pi], 1e-12);
%=============================================================================
assert_isapprox([wrapTo2Pi(-1) wrapTo2Pi(0) wrapTo2Pi(2 * pi)], [2 * pi - 1, 0, 2 * pi], 1e-12);
%=============================================================================
assert_isequal(wrapTo180([190 -190]), [-170 170]);
%=============================================================================
assert_isequal(wrapTo360([-10 370]), [350 10]);
