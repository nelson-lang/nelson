asserts.isequal(nargin('cart2sph'), -1);
asserts.isequal(nargout('cart2sph'), -1);
%=============================================================================
x = [1 1 1 1; -1 -1 -1 -1];
y = [1 1 -1 -1; 1 1 -1 -1];
z = [1 -1 1 -1; 1 -1 1 -1];
[az, el, r] = cart2sph(x, y, z);
az_REF = [0.7854 0.7854 -0.7854 -0.7854;
  2.3562 2.3562 -2.3562 -2.3562];
el_REF = [0.6155 -0.6155 0.6155 -0.6155;
  0.6155 -0.6155 0.6155 -0.6155];
r_REF = [1.7321 1.7321 1.7321 1.7321;
  1.7321 1.7321 1.7321 1.7321];
asserts.isapprox(az, az_REF, 1e-4);
asserts.isapprox(el, el_REF, 1e-4);
asserts.isapprox(r, r_REF, 1e-4);
