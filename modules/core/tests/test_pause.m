% <--WEIGHT 2-->
asserts.isequal(nargin('pause'), 1);
asserts.isequal(nargout('pause'), 1);
%=============================================================================
s = pause('query');
asserts.isequal(s, 'on');
%=============================================================================
tic(); pause(0.2); t = toc();
asserts.istrue(t > 0.1);
asserts.istrue(t < 2);
%=============================================================================
tic(); pause(0.01); t = toc();
asserts.istrue(t < 0.5);
%=============================================================================
pause('off')
tic(); pause(30); t = toc();
asserts.istrue(t < 1);
%=============================================================================
pause('on');
