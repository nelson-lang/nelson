assert_isequal(trapz([1 2 3 4]), 7.5);
%=============================================================================
assert_isequal(trapz([1 2; 3 4; 5 6]), [6 8]);
%=============================================================================
assert_isequal(trapz([1 2; 3 4; 5 6], 2), [1.5; 3.5; 5.5]);
%=============================================================================
assert_isequal(trapz([0 1 2 3], [1 1 1 1]), 3);
%=============================================================================
assert_isequal(trapz([0 2 4], [0 4 8]), 16);
%=============================================================================
assert_isequal(trapz([1 2 3 4], 2), 7.5);
%=============================================================================
assert_isequal(trapz(5), 0);
%=============================================================================
R = trapz(0:0.1:pi, sin(0:0.1:pi));
assert_isapprox(R, 1.997468926590933, 1e-9);
%=============================================================================
assert_isequal(trapz(reshape(1:8, 2, 4)), [1.5 3.5 5.5 7.5]);
