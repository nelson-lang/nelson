Y = pagepinv(cat(3, [1 2; 2 4], [1 0; 0 2]));
assert_isequal(size(Y), [2 2 2]);
assert_isapprox(Y(:), [0.04; 0.08; 0.08; 0.16; 1; 0; 0; 0.5], 1e-12);
Y = pagepinv(cat(3, [1 2; 2 4.0001], eye(2)), 1e-3);
assert_isapprox(Y(:), [0.0399981; 0.0799978; 0.0799978; 0.159999; 1; 0; 0; 1], 1e-5);
assert_isequal(size(pagepinv(ones(3, 2, 4))), [2 3 4]);
