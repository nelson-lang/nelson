assert_isequal(cumtrapz([1 2 3 4]), [0 1.5 4 7.5]);
%=============================================================================
assert_isequal(cumtrapz([0 2 4], [0 4 8]), [0 4 16]);
%=============================================================================
assert_isequal(cumtrapz([1 2; 3 4; 5 6]), [0 0; 2 3; 6 8]);
%=============================================================================
assert_isequal(cumtrapz([1 2; 3 4; 5 6], 2), [0 1.5; 0 3.5; 0 5.5]);
%=============================================================================
assert_isequal(cumtrapz(7), 0);
%=============================================================================
R = cumtrapz(0:0.5:2, (0:0.5:2) .^ 2);
assert_isequal(R, [0 0.0625 0.375 1.1875 2.75]);
