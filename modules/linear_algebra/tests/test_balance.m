% <--WEIGHT 2-->
% <--REUSE PROCESS-->
asserts.isequal(nargin('balance'), 2);
asserts.isequal(nargout('balance'), 3);
%=============================================================================
A = [1 100 10000; .01 1 100; .0001 .01 1];
% The diagonal scaling returned by balance for a real matrix is only defined up
% to a uniform power-of-two factor: different LAPACK backends (and even
% different Apple Accelerate versions) converge to equally valid scalings that
% differ by a constant power of two. The balanced matrix B (the similarity-
% invariant result) is identical across backends, so the scale is validated
% through its defining invariants: every entry is an exact power of two and the
% diagonal similarity reproduces A.
isPow2 = @(v) all(abs(log2(abs(v(:))) - round(log2(abs(v(:))))) < 1e-9);
%=============================================================================
[T, B] = balance(A);
asserts.istrue(isPow2(diag(T)));
asserts.isapprox(T * B / T, A, 1e-9);
%=============================================================================
B_REF = [1.0000 1.5625 1.2207;
  0.6400 1.0000 0.7812;
  0.8192 1.2800 1.0000];
asserts.isapprox(B, B_REF, 1e-3);
%=============================================================================
[S, P, B] = balance(A);
asserts.istrue(isPow2(S));
%=============================================================================
P_REF = [1; 2; 3];
asserts.isapprox(P, P_REF, 1e-3);
%=============================================================================
B_REF = [1.0000 1.5625 1.2207;
  0.6400 1.0000 0.7812;
  0.8192 1.2800 1.0000];
asserts.isapprox(B, B_REF, 1e-3);
%=============================================================================
B = balance(A);
B_REF = [1.0000 1.5625 1.2207;
  0.6400 1.0000 0.7812;
  0.8192 1.2800 1.0000];
asserts.isapprox(B, B_REF, 1e-3);
%=============================================================================
B = balance(A, 'noperm');
B_REF = [1.0000 1.5625 1.2207;
  0.6400 1.0000 0.7812;
  0.8192 1.2800 1.0000];
asserts.isapprox(B, B_REF, 1e-3);
%=============================================================================
[T, B] = balance(A, 'noperm');
asserts.istrue(isPow2(diag(T)));
asserts.isapprox(T * B / T, A, 1e-9);
%=============================================================================
[S, P, B] = balance(A, 'noperm');
asserts.istrue(isPow2(S));
P_REF = [1; 2; 3];
asserts.isapprox(P, P_REF, 1e-3);
B_REF = [1.0000 1.5625 1.2207;
  0.6400 1.0000 0.7812;
  0.8192 1.2800 1.0000];
asserts.isapprox(B, B_REF, 1e-3);
%=============================================================================
