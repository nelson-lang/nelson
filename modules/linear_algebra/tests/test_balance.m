  0.6400 1.0000 0.7812;
  0.8192 1.2800 1.0000];
asserts.isapprox(B, single(B_REF), 1e-3);
%=============================================================================
[S, P, B] = balance(A);
asserts.istrue(isPow2(S));
%=============================================================================
P_REF = [1; 2; 3];
asserts.isapprox(P, single(P_REF), 1e-3);
%=============================================================================
B_REF = [1.0000 1.5625 1.2207;
  0.6400 1.0000 0.7812;
  0.8192 1.2800 1.0000];
asserts.isapprox(B, single(B_REF), 1e-3);
%=============================================================================
B = balance(A);
B_REF = [1.0000 1.5625 1.2207;
  0.6400 1.0000 0.7812;
