  8.0000e-02 + 8.0000e+00i 1.0000e+00 + 1.0000e+00i 6.2500e+00 + 6.2500e-02i;
  1.2800e-02 + 1.2800e+02i 1.6000e-01 + 1.6000e+01i 1.0000e+00 + 1.0000e+00i];
