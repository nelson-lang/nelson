%=============================================================================
[S, P, B] = balance([]);
asserts.isequal(S, []);
asserts.isequal(P, []);
asserts.isequal(B, []);
%=============================================================================
B = balance([], 'noperm');
asserts.isequal(B, []);
%=============================================================================
M2 = [1 100; 0.01 1];
[scaleValues, permutationValues, balancedMatrix] = balance(M2);
asserts.isequal(permutationValues, [1; 2]);
if ismac()
  % LAPACK only guarantees the balancing to within a factor of two of optimal,
  % so Apple Accelerate and Intel MKL pick different (equally valid) power-of-
  % two scalings for this matrix. Check the defining invariants instead of the
  % MKL-specific values: a diagonal power-of-two similarity that reproduces M2.
  D2 = diag(scaleValues);
  asserts.istrue(all(abs(log2(scaleValues) - round(log2(scaleValues))) < 1e-9));
  asserts.isapprox(D2 * balancedMatrix / D2, M2, 1e-12);
else
  asserts.isapprox(scaleValues, [16; 0.25], 1e-12);
  asserts.isapprox(balancedMatrix, [1 1.5625; 0.64 1], 1e-12);
end
