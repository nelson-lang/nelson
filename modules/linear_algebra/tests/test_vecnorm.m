% <--REUSE PROCESS-->
x = [2 2 2];
n = vecnorm(x);
asserts.isapprox(n, 3.4641, 1e-4);
%=============================================================================
n = vecnorm(x, 1);
asserts.isapprox(n, 6, 1e-4);
%=============================================================================
A = [2 0 1; -1 1 0; -3 3 0];
n = vecnorm(A);
asserts.isapprox(n, [3.7417 3.1623 1.0000], 1e-4);
%=============================================================================
A = [0 1 2; 3 4 5];
n = vecnorm(A);
asserts.isapprox(n, [3.0000 4.1231 5.3852], 1e-4);
%=============================================================================
A = [0 1 2; 3 4 5];
n = vecnorm(A, 2, 2);
asserts.isapprox(n, [2.2361; 7.0711], 1e-4);
%=============================================================================
A = [0 1 2; 3 4 5];
n = vecnorm(A, Inf);
asserts.isapprox(n, [3 4 5], 1e-4);
%=============================================================================
asserts.isequal(vecnorm([3 4; 0 0], 2, 2), [5; 0]);
