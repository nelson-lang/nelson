%=============================================================================
% Expected values are listed explicitly below.
%=============================================================================
% a row vector of perfect squares has a constant discrete Laplacian
assert_isequal(del2([1 4 9 16]), [0.5 0.5 0.5 0.5]);
%=============================================================================
% a column vector stays a column
assert_isequal(del2([1; 4; 9; 16]), [0.5; 0.5; 0.5; 0.5]);
%=============================================================================
% a scalar spacing divides by h^2
assert_isequal(del2([1 4 9 16], 2), [0.125 0.125 0.125 0.125]);
%=============================================================================
% del2 of magic(4)
REF = [15 -5.5 -6.5 9; ...
        0.5 -5 -3 3.5; ...
       -3.5 3 5 -0.5; ...
         -9 6.5 5.5 -15];
assert_isequal(del2(magic(4)), REF);
%=============================================================================
% del2(U, h) with a single spacing
REF = [3.75 -1.375 -1.625 2.25; ...
       0.125 -1.25 -0.75 0.875; ...
      -0.875 0.75 1.25 -0.125; ...
       -2.25 1.625 1.375 -3.75];
assert_isequal(del2(magic(4), 2), REF);
%=============================================================================
% del2(U, hx, hy) with separate column and row spacings
R = del2(magic(4), 2, 3);
REF = [2.39583333333333 -0.0902777777777777 -0.409722222222222 1.10416666666667; ...
       -0.395833333333333 -0.798611111111111 -0.368055555555556 0.5625; ...
                  -0.5625 0.368055555555556 0.798611111111111 0.395833333333333; ...
        -1.10416666666667 0.409722222222222 0.0902777777777777 -2.39583333333333];
assert_isapprox(R, REF, 1e-12);
%=============================================================================
% a 3x3 matrix with second-difference edge extrapolation
REF = [0 0 0.25; 0 0 0.25; 0.25 0.25 0.5];
assert_isequal(del2([1 2 3; 4 5 6; 7 8 10]), REF);
%=============================================================================
% a scalar and a two-element vector have a zero Laplacian
assert_isequal(del2(5), 0);
assert_isequal(del2([1 5]), [0 0]);
%=============================================================================
% a symmetric spike keeps its extrapolated ends
assert_isequal(del2([0 0 1 0 0]), [1 0.25 -0.5 0.25 1]);
%=============================================================================
% a cubic ramp has a linear Laplacian
assert_isequal(del2([0 1 8 27 64]), [0 1.5 3 4.5 6]);
%=============================================================================
% a 2xN matrix: the size-2 dimension contributes nothing
assert_isequal(del2([1 2 4 8; 0 1 3 9]), [0 0.25 0.5 0.75; -0.5 0.25 1 1.75]);
%=============================================================================
% a 3-D array divides by 2*ndims = 6
U = zeros(3, 3, 3);
U(2, 2, 2) = 1;
L = del2(U);
assert_isequal(L(2, 2, 2), -1);
assert_isapprox(L(2, 2, 1), -1 / 3, 1e-12);
%=============================================================================
% the class of the input is preserved
R = del2(single([1 4 9 16]));
assert_isequal(class(R), 'single');
assert_isequal(R, single([0.5 0.5 0.5 0.5]));
