X = pagelsqminnorm(cat(3, [1 2; 2 4], [1 0; 0 2]), cat(3, [1; 2], [1; 1]));
assert_isequal(size(X), [2 1 2]);
assert_isapprox(X(:), [0.2; 0.4; 1; 0.5], 1e-12);
X = pagelsqminnorm(cat(3, [1 2; 2 4], [1 0; 0 2]), [1; 2]);
assert_isapprox(X(:), [0.2; 0.4; 1; 1], 1e-12);
