%=============================================================================
% <--PYTHON ENVIRONMENT REQUIRED-->
%=============================================================================
A = pyrun('', 'A', 'A', int32(3));
B = pyrun('', 'B', 'B', int32(2));
%=============================================================================
asserts.checkerror('A + ''ff'' ', [_('TypeError: unsupported operand type(s) for +: ''int'' and ''str'''), char(10)])
%=============================================================================
R = A + B;
asserts.isequal(R.double(), 5);
%=============================================================================
R = A + 3.5;
asserts.isequal(R, 6.5);
%=============================================================================
% __pos__
R = +A;
asserts.isequal(R, A);
%=============================================================================
% __neg__
R = -A;
asserts.isequal(R.double(), -3);
%=============================================================================
% __mul__
R = A * B;
asserts.isequal(R.double(), 6);
%=============================================================================
% __truediv__
R = A / B;
asserts.isequal(R, 1.5);
%=============================================================================
% __pow__
R = A ^ B;
asserts.isequal(R.double(), 9);
%=============================================================================
% __gt__
R = A > B;
asserts.istrue(R);
%=============================================================================
% __ge__
R = A >= B;
asserts.istrue(R);
%=============================================================================
% __le__
R = A <= B;
asserts.isfalse(R);
%=============================================================================
% __ne__
R = A ~= B;
asserts.istrue(R);
%=============================================================================
% __lt__
R = A < B;
asserts.isfalse(R);
%=============================================================================
% __add__
R = A + B;
asserts.isequal(R.double(), 5);
%=============================================================================
% __sub__
R = A - B;
asserts.isequal(R.double(), 1);
%=============================================================================
% __eq__
R = (A == B);
asserts.isfalse(R);
%=============================================================================
% __mod__
R = mod(A, B);
asserts.isequal(R.double(), 1);
%=============================================================================
