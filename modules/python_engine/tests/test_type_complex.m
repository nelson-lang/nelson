% <--PYTHON ENVIRONMENT REQUIRED-->
%=============================================================================
R = pyrun('R = complex(3, 2)', "R");
asserts.isequal(R, 3 + 2i);
%=============================================================================
R = py.complex(real= 1, imag= 2);
asserts.isequal(R, 1 + 2i);
%=============================================================================
P = pyrun("import builtins as P", "P");
R = P.complex(real= 1, imag= 2);
asserts.isequal(R, 1 + 2i);
%=============================================================================
R = py.complex(pyargs('real', 3, 'imag', 4));
asserts.isequal(R, 3 + 4i);
%=============================================================================
R = py.complex(5, pyargs('imag', 6));
asserts.isequal(R, 5 + 6i);
