% Write a figure to a single self-contained HTML file. The file inlines the
% client-only replayer bundle and the figure scene, so it opens in any browser
% with no engine and no server (file://) and stays interactive offline: 3D
% rotate and zoom, 2D pan and zoom, double-click to reset.
% Internal figure/notebook plumbing, not part of the public graphics surface.
function saveFigureHtml(fig, filename)
  narginchk(2, 2);
  nargoutchk(0, 0);

  % Export the figure scene as nelson-figure JSON through a temporary file.
  sceneFile = [tempname(), '.json'];
  cleaner = onCleanup(@() removeIfPresent(sceneFile));
  __web_figure_scene__(fig, sceneFile);
  sceneJson = fileread(sceneFile);

  bundle = readReplayerBundle();
  html = buildStandaloneHtml(bundle, sceneJson);
  filewrite(filename, html);
end
%=============================================================================
function bundle = readReplayerBundle()
  % gui and graphics are sibling modules, so resolve the bundle relative to
  % this file: up to the modules directory, then into the gui frontend. This
  % holds in a source tree and in an install, where the layout is preserved.
  here = fileparts(mfilename('fullpath'));
  modulesDir = here;
  for k = 1:5
    modulesDir = fileparts(modulesDir);
  end
  bundlePath = [modulesDir, ...
    '/gui/dist-replayer/nelson-figure-replayer.js'];
  if ~isfile(bundlePath)
    error('Nelson:graphics:replayerBundleMissing', ...
      'Replayer bundle not found: %s. Build it with: npm run build:replayer.', ...
      bundlePath);
  end
  % Neutralize the ES export so the inlined module exposes activate as a global
  % without any import or export statement. The local name is minified, so the
  % token is captured from the trailing export block.
  bundle = fileread(bundlePath);
  bundle = regexprep(bundle, ...
    'export\s*\{\s*(\w+)\s+as\s+activate\s*\}\s*;?\s*$', ...
    ';globalThis.__nelsonActivate=$1;');
end
%=============================================================================
function html = buildStandaloneHtml(bundle, sceneJson)
  % The script body holds the bundle, the scene and a bootstrap that calls the
  % replayer exactly as a notebook host does. Any literal end-of-script token in
  % bundle string data or scene text is masked so it cannot close the element.
  body = [bundle, newline(), newline(), ...
    'const __nelsonScene = ', sceneJson, ';', newline(), ...
    bootstrapSource()];
  body = regexprep(body, '</(script)', '<\\/$1', 'ignorecase');
  html = [ ...
    '<!doctype html>', newline(), ...
    '<html>', newline(), ...
    '<head>', newline(), ...
    '<meta charset="utf-8" />', newline(), ...
    '<title>Nelson figure</title>', newline(), ...
    '<style>', newline(), ...
    'html,body{margin:0;height:100%;background:#fff;font-family:sans-serif;}', newline(), ...
    '#fig{width:100vw;height:100vh;display:flex;align-items:center;justify-content:center;}', newline(), ...
    '#err{color:#b00;padding:16px;}', newline(), ...
    '</style>', newline(), ...
    '</head>', newline(), ...
    '<body>', newline(), ...
    '<div id="fig"></div>', newline(), ...
    '<script type="module">', newline(), ...
    body, newline(), ...
    '</script>', newline(), ...
    '</body>', newline(), ...
    '</html>', newline()];
end
%=============================================================================
function src = bootstrapSource()
  src = [ ...
    'try {', newline(), ...
    '  const api = globalThis.__nelsonActivate();', newline(), ...
    '  const outputItem = {', newline(), ...
    '    id: "nelson-figure",', newline(), ...
    '    mime: "application/vnd.nelson.figure+json",', newline(), ...
    '    json: () => __nelsonScene,', newline(), ...
    '    text: () => JSON.stringify(__nelsonScene),', newline(), ...
    '  };', newline(), ...
    '  await api.renderOutputItem(outputItem, document.getElementById("fig"));', newline(), ...
    '} catch (e) {', newline(), ...
    '  const d = document.createElement("div");', newline(), ...
    '  d.id = "err";', newline(), ...
    '  d.textContent = "Replayer error: " + (e && e.message ? e.message : String(e));', newline(), ...
    '  document.body.appendChild(d);', newline(), ...
    '}'];
end
%=============================================================================
function removeIfPresent(f)
  if isfile(f)
    delete(f);
  end
end
