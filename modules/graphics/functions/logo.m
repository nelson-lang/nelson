function varargout = logo()
  % Display the L-shaped membrane logo in a new figure.
  Z = 160 * membrane(1, 100);
  f = figure();
  ax = axes('Parent', f);
  s = surf(Z, 'EdgeColor', 'none', 'Parent', ax);
  set(ax, 'XLim', [-101 301], ...
    'YLim', [-101 301], ...
    'ZLim', [-153.4 260], ...
    'CameraPosition', [-145.5 -229.7 283.6], ...
    'CameraTarget', [77.4 60.2 63.9], ...
    'CameraUpVector', [0 0 1], ...
    'CameraViewAngle', 36.7, ...
    'Position', [0 0 1 1], ...
    'DataAspectRatio', [1 1 0.9]);
  l1 = light('Parent', ax);
  set(l1, 'Position', [160 400 80], 'Style', 'local', 'Color', [0 0.8 0.8]);
  l2 = light('Parent', ax);
  set(l2, 'Position', [0.5 -1 0.4], 'Color', [0.8 0.8 0]);
  set(s, 'FaceColor', [0.9 0.2 0.2], ...
    'FaceLighting', 'gouraud', ...
    'AmbientStrength', 0.3, ...
    'DiffuseStrength', 0.6, ...
    'BackFaceLighting', 'lit', ...
    'SpecularStrength', 1, ...
    'SpecularColorReflectance', 1, ...
    'SpecularExponent', 7);
  set(ax, 'XTick', [], 'YTick', [], 'ZTick', [], 'Color', 'k');
  if nargout > 0
    varargout{1} = f;
  end
end
