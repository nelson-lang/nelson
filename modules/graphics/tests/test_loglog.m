f = figure();
x = logspace(-1, 2);
y = 2 .^ x;
loglog(x, y)
grid on
%=============================================================================
f = figure();
x = logspace(-1, 2, 10000);
y = 5 + 3 * sin(x);
loglog(x, y);
%=============================================================================
f = figure();
x = logspace(-1, 2, 20);
y = 10 .^ x;
loglog(x, y, 's', 'MarkerFaceColor', [0 0.447 0.741])
grid on
%=============================================================================
f = figure();
x = logspace(-1, 2, 10000);
hold on
y1 = 5 + 3 * sin(x / 4);
y2 = 5 - 3 * sin(x / 4);
loglog(x, y1)
loglog(x, y2, '--')
hold off
legend('Signal 1', 'Signal 2', 'Location', 'northwest')
%=============================================================================
f = figure();
y = [0.001 0.01 0.1 1 10 100];
loglog(y)
grid on
%=============================================================================
y = [0.0010 0.0100 0.1000
  0.0100 0.1000 1.0000
  0.1000 1.0000 10.0000
  1.0000 10.5000 100.0000
  10.0000 100.0000 1000.0000];
h = loglog(y);
grid on
%=============================================================================
f = figure('Visible', 'off');
x = 1:100;
y = x .^ 2;
loglog(x, y);
drawnow();
ax = gca();
asserts.isequal(ax.XScale, 'log');
asserts.isequal(ax.YScale, 'log');
asserts.isequal(char(ax.XMinorTick), 'on');
asserts.isequal(char(ax.YMinorTick), 'on');
close(f);
