f = figure('Visible', 'off');
plot3(1:10, 1:10, (1:10) / 4);
ax = gca();
zticks(0:0.5:2.5);
ztickformat('%.2f');
assert_isequal(ztickformat(), '%.2f');
assert_isequal(ax.ZTickLabelFormat, '%.2f');
drawnow();
assert_isequal(ax.ZTickLabel', {'0.00', '0.50', '1.00', '1.50', '2.00', '2.50'});
ztickformat(ax, '%.1f');
drawnow();
assert_isequal(ax.ZTickLabel', {'0.0', '0.5', '1.0', '1.5', '2.0', '2.5'});
close(f);
