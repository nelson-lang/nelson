% Automatic CameraViewAngle: the projected data box fills the axes along the
% dimension where it is relatively larger, and the angle is the one that
% extent subtends at the camera. No correction for the axes aspect ratio: an
% edge-on view of the stretched box gives 2 * atand(1 / (10 * sqrt(3))) in
% any axes, square or not.
%=============================================================================
edgeOn = 2 * atand(1 / (10 * sqrt(3)));
asserts.isapprox(edgeOn, 6.6086, 1e-3);
%=============================================================================
cases = { ...
  % Automatic aspect: the box is a unit cube whatever the limits.
  [640 640], 'surf(peaks(30));', 10.3396; ...
  [640 640], 'surf(peaks(30)); view([90 0]);', edgeOn; ...
  [640 640], 'surf(peaks(30)); view([0 0]);', edgeOn; ...
  [640 640], 'surf(peaks(30)); view([90 0]); axis tight;', edgeOn; ...
  [640 640], 'surf(peaks(30)); view([30 0]);', 9.0189; ...
  [640 640], 'surf(peaks(30)); view([90 45]);', 9.3357; ...
  [640 640], 'surf(peaks(30)); view([0 90]);', edgeOn; ...
  [640 640], '[x, y, z] = sphere(40); surf(x, y, z); daspect([1 1 1]); axis tight;', 10.3396; ...
  % Non-square axes: the edge-on cube still subtends the same angle, and the
  % default view is limited by the width in a tall axes.
  [800 400], 'surf(peaks(30)); view([90 0]);', edgeOn; ...
  [400 800], 'surf(peaks(30)); view([90 0]);', edgeOn; ...
  [800 400], 'surf(peaks(30));', 10.3396; ...
  [400 800], 'surf(peaks(30));', 9.2561; ...
  [640 640], 'surf(peaks(30)); view([90 0]); set(gca, ''Position'', [0.1 0.1 0.8 0.4]);', edgeOn; ...
  [640 640], 'surf(peaks(30)); view([90 0]); set(gca, ''Position'', [0.1 0.1 0.4 0.8]);', edgeOn; ...
  % Manual plot box aspect ratio.
  [640 640], 'surf(peaks(30)); pbaspect([2 1 1]);', 10.2434; ...
  [640 640], 'surf(peaks(30)); pbaspect([2 1 1]); view([90 0]);', 4.6756; ...
  [640 640], 'surf(peaks(30)); pbaspect([1 2 1]); view([90 0]);', 9.3357; ...
  % Manual data aspect ratio with tight limits: the real box is projected.
  [640 640], 'surf(peaks(30)); daspect([1 1 1]); axis tight;', 10.6843; ...
  [640 640], 'surf(peaks(30)); daspect([1 1 1]); axis tight; view([90 0]);', 7.6310; ...
  [640 640], 'surf(peaks(30)); daspect([1 1 1]); axis tight; view([0 90]);', 7.6310; ...
  [640 640], 'image(rand(10)); axis image;', 8.0099; ...
};
for k = 1:size(cases, 1)
  f = figure('Visible', 'off');
  f.Position(3:4) = cases{k, 1};
  eval(cases{k, 2});
  ax = gca();
  drawnow();
  asserts.isequal(ax.CameraViewAngleMode, 'auto');
  asserts.isapprox(ax.CameraViewAngle, cases{k, 3}, 1e-3);
  close(f);
end
%=============================================================================
% The straight top view keeps the camera on the z axis at the general distance.
f = figure('Visible', 'off');
f.Position(3:4) = [640 640];
surf(peaks(30));
daspect([1 1 1]);
axis tight
view([0 90]);
ax = gca();
drawnow();
asserts.isapprox(ax.CameraPosition(1:2), ax.CameraTarget(1:2), 1e-12);
asserts.isapprox(norm(ax.CameraPosition - ax.CameraTarget), 217.4181, 1e-3);
close(f);
