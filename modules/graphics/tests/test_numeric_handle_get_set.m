%=============================================================================
% Numeric graphics handles: 0 is the root object, N is the figure numbered N.
%=============================================================================
assert_isequal(get(0, 'Type'), 'root');
assert_isequal(get(0, 'ScreenSize'), get(groot(), 'ScreenSize'));
%=============================================================================
set(0, 'Units', 'pixels');
assert_isequal(get(0, 'Units'), 'pixels');
%=============================================================================
f = figure();
c = get(0, 'Children');
assert_istrue(any(c == f));
%=============================================================================
n = get(f, 'Number');
assert_isequal(get(n, 'Color'), get(f, 'Color'));
set(n, 'Color', [1 0 0]);
assert_isequal(get(f, 'Color'), [1 0 0]);
%=============================================================================
assert_checkerror('get(999999, ''Color'')', getString(message('Nelson:graphics:invalidHandle')));
%=============================================================================
close(f);
