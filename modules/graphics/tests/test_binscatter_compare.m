rng(42);
x = randn(1000, 1);
y = 2 * x + randn(1000, 1);
f = figure('Visible', 'off');
h = binscatter(x, y, [20 10]);
asserts.istrue(isgraphics(h, 'binscatter'));
asserts.isequal(h.NumBins, [20 10]);
asserts.isequal(sum(h.Values(:)), 1000);
drawnow();
frame = getframe(f);
render_assert_not_blank(frame.cdata);
close(f);
%=============================================================================
f = figure('Visible', 'off');
h = binscatter([0.1 0.2 0.8 1.2 1.8 1.9], ...
  [0.1 0.9 0.8 1.2 1.1 1.9], [2 2], 'XLimits', [0 2], 'YLimits', [0 2]);
asserts.isequal(h.Values, [3 0; 0 3]);
close(f);
