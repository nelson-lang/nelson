close all;
f = figure('Visible', 'off');
surf(peaks(20));
ax = gca();
%=============================================================================
u = camup();
asserts.isequal(size(u), [1 3]);
asserts.isequal(camup(ax), get(ax, 'CameraUpVector'));
%=============================================================================
camup(ax, [0 0 1]);
asserts.isequal(camup(ax), [0 0 1]);
asserts.isequal(char(get(ax, 'CameraUpVectorMode')), 'manual');
%=============================================================================
camup(ax, 'auto');
asserts.isequal(char(camup(ax, 'mode')), 'auto');
%=============================================================================
asserts.checkerror('camup(gca(), ''bad'')', 'Value must be ''auto'', ''manual'' or ''mode''.');
