tic()
f = figure();
f.Color = [1, 1, 1];

x = linspace(0, 12, 600).';
y = zeros(numel(x), 32);
for k = 1:size(y, 2)
  y(:, k) = 0.1 + 0.02 * k + 0.04 * sin(k * x / 5) .^ 2;
end
area(x, y, 'EdgeColor', 'none');
axis tight;
drawnow();
toc()
close(f);
