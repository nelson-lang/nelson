f = figure('Visible', 'off', 'Position', [100 100 560 420]);
Z = peaks(50);
surface(Z);
drawnow();
ax = gca();
asserts.isapprox(ax.ZLim, [min(Z(:)) max(Z(:))], 1e-12);
asserts.isapprox(ax.DataAspectRatio, [3.43183191289405 3.43183191289405 1], 1e-12);
asserts.isapprox(ax.PlotBoxAspectRatio, [1 0.788709677419355 0.788709677419355], 1e-12);
close(f);
