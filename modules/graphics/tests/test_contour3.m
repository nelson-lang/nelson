figure();
x = linspace(-2 * pi, 2 * pi);
y = linspace(0, 4 * pi);
[X, Y] = meshgrid(x, y);
Z = sin(X) + cos(Y);
contour3(X, Y, Z);
%=============================================================================
f = figure('Visible', 'off');
[X, Y, Z] = sphere(50);
contour3(X, Y, Z);
ax = gca();
asserts.isequal(ax.XTick, -1:0.5:1);
asserts.isequal(ax.YTick, -0.5:0.5:0.5);
close(f);
