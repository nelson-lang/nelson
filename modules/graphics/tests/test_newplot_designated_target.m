% A high level plotting call must start its new plot in the axes it was handed,
% not in the current axes: the designated axes is cleared, the current axes is
% left alone, and the current axes does not change.
%
% The witness is found back by Tag and never by handle: a freed handle id is
% handed out again to the next object created, so isgraphics() on a stale handle
% answers for whatever object now holds that id.
%=============================================================================
statements = {...
  'plot(ax1, [1 2 3], [1 2 3])', ...
  'plot3(ax1, [1 2 3], [1 2 3], [1 2 3])', ...
  'bar(ax1, [1 2 3])', ...
  'stem(ax1, [1 2 3])', ...
  'stairs(ax1, [1 2 3])', ...
  'area(ax1, [1 2 3])', ...
  'errorbar(ax1, [1 2 3], [1 2 3], [0.1 0.1 0.1])', ...
  'surf(ax1, peaks(5))', ...
  'mesh(ax1, peaks(5))', ...
  'meshz(ax1, peaks(5))', ...
  'waterfall(ax1, peaks(5))', ...
  'contour(ax1, peaks(5))', ...
  'contourf(ax1, peaks(5))', ...
  'scatter(ax1, [1 2 3], [1 2 3])', ...
  'scatter3(ax1, [1 2 3], [1 2 3], [1 2 3])', ...
  'histogram(ax1, [1 2 2 3 3 3])', ...
  'histogram2(ax1, [1 2 3], [1 2 3])', ...
  'binscatter(ax1, [1 2 3], [1 2 3])', ...
  'imagesc(ax1, magic(4))', ...
  'image(ax1, magic(4))', ...
  'pie(ax1, [1 2 3])', ...
  'ribbon(ax1, peaks(5))', ...
  'stem3(ax1, [1 2 3], [1 2 3], [1 2 3])', ...
  'fsurf(ax1, @(x, y) x + y, [0 1 0 1])', ...
  'quiver(ax1, [1 2], [1 2], [1 1], [1 1])', ...
  'fill(ax1, [0 1 1 0], [0 0 1 1], ''r'')', ...
  'surfc(ax1, peaks(5))', ...
  'surfl(ax1, peaks(5))', ...
  'meshc(ax1, peaks(5))', ...
  'cylinder(ax1, 1)', ...
  'sphere(ax1, 5)'};
%=============================================================================
% The target is designated by the leading argument: it is cleared, and only it.
for k = 1:numel(statements)
  statement = statements{k};
  f = figure('Visible', 'off');
  ax1 = axes('Parent', f, 'Position', [0.1 0.1 0.3 0.3]);
  ax2 = axes('Parent', f, 'Position', [0.5 0.5 0.3 0.3]);
  line('Parent', ax1, 'XData', [0 1], 'YData', [0 1], 'Tag', 'TARGETW');
  line('Parent', ax2, 'XData', [0 1], 'YData', [0 1], 'Tag', 'BYSTANDERW');
  eval(statement);
  assert_istrue(isempty(findobj(ax1, 'Tag', 'TARGETW')), ...
    [statement, ' must clear the axes it was given.']);
  assert_isequal(numel(findobj(ax2, 'Tag', 'BYSTANDERW')), 1, ...
    [statement, ' must not touch the current axes.']);
  assert_istrue(numel(ax1.Children) >= 1, ...
    [statement, ' must draw in the axes it was given.']);
  assert_isequal(gca(), ax2, [statement, ' must not change the current axes.']);
  close(f);
end
%=============================================================================
% NextPlot 'add' (hold on) keeps the existing children in place.
for k = 1:numel(statements)
  statement = statements{k};
  f = figure('Visible', 'off');
  ax1 = axes('Parent', f, 'Position', [0.1 0.1 0.3 0.3]);
  ax2 = axes('Parent', f, 'Position', [0.5 0.5 0.3 0.3]);
  set(ax1, 'NextPlot', 'add');
  line('Parent', ax1, 'XData', [0 1], 'YData', [0 1], 'Tag', 'TARGETW');
  eval(statement);
  assert_isequal(numel(findobj(ax1, 'Tag', 'TARGETW')), 1, ...
    [statement, ' must not clear the axes while NextPlot is add.']);
  assert_isequal(gca(), ax2, [statement, ' must not change the current axes.']);
  close(f);
end
%=============================================================================
% NextPlot 'replacechildren' clears the children too.
for k = 1:numel(statements)
  statement = statements{k};
  f = figure('Visible', 'off');
  ax1 = axes('Parent', f, 'Position', [0.1 0.1 0.3 0.3]);
  axes('Parent', f, 'Position', [0.5 0.5 0.3 0.3]);
  set(ax1, 'NextPlot', 'replacechildren');
  line('Parent', ax1, 'XData', [0 1], 'YData', [0 1], 'Tag', 'TARGETW');
  eval(statement);
  assert_istrue(isempty(findobj(ax1, 'Tag', 'TARGETW')), ...
    [statement, ' must clear the children while NextPlot is replacechildren.']);
  close(f);
end
