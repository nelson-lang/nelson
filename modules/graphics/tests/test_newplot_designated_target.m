  'surf(peaks(5), ''Parent'', ax1)', ...
  'surfc(peaks(5), ''Parent'', ax1)', ...
  'meshc(peaks(5), ''Parent'', ax1)', ...
  'contour(peaks(5), ''Parent'', ax1)', ...
  'contourf(peaks(5), ''Parent'', ax1)', ...
  'scatter([1 2 3], [1 2 3], ''Parent'', ax1)', ...
  'scatter3([1 2 3], [1 2 3], [1 2 3], ''Parent'', ax1)', ...
  'histogram([1 2 2 3 3 3], ''Parent'', ax1)', ...
  'histogram2([1 2 3], [1 2 3], ''Parent'', ax1)', ...
