msg = _('Specify double or single values in the range [0, 1].');
assert_checkerror('fliplightness([2 0 0])', msg);
assert_checkerror('fliplightness([2 0 0])', msg, 'Nelson:graphics:fliplightness:OutOfRange');
assert_checkerror('fliplightness([NaN 0 0])', msg, 'Nelson:graphics:fliplightness:OutOfRange');
assert_checkerror('fliplightness([-0.1 0 0])', msg, 'Nelson:graphics:fliplightness:OutOfRange');
%=============================================================================
msg = _('Specify a color array as an m-by-3 RGB matrix or an m-by-n-by-3 truecolor array.');
assert_checkerror('fliplightness([1 0])', msg);
assert_checkerror('fliplightness([1 0])', msg, 'Nelson:graphics:fliplightness:InvalidNumericShape');
assert_checkerror('fliplightness([1; 0; 0])', msg, 'Nelson:graphics:fliplightness:InvalidNumericShape');
assert_checkerror('fliplightness(zeros(2, 2, 3, 2))', msg, 'Nelson:graphics:fliplightness:InvalidNumericShape');
%=============================================================================
msg = _('Specify colors as a three-column matrix of RGB triplets, a character vector, a cell-array of character vectors, or a string array.');
