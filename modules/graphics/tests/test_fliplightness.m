% hexadecimal codes keep their type, color names give RGB triplets
R = fliplightness('#808080');
assert_isequal(R, '#929292');
R = fliplightness("#FF8800");
assert_isequal(R, "#974E00");
R = fliplightness('#F80');
assert_isequal(R, '#974E00');
R = fliplightness(["#808080" "#c8b4a0"]);
assert_isequal(R, ["#929292" "#655442"]);
R = fliplightness({'#808080', '#C8B4A0'; '#1E3C5A', '#FFF'});
assert_isequal(R, {'#929292', '#655442'; '#B1D4F9', '#000000'});
R = fliplightness('r');
assert_istrue(max(abs(R - [0.999299410499385, 0.079035900652058, 0.0499654780289804])) < 1e-2);
R = fliplightness(["#FF8800", "blue"]);
assert_isequal(size(R), [2 3]);
assert_istrue(max(abs(R(2, :) - [0.587803632599662, 0.722995068899987, 0.999911719390385])) < 1e-2);
