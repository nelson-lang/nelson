rng('default') % For reproducibility
figure();
x = rand(50, 5);
y = randn(50, 5) + (5:5:25);
s = scatter(x, y, 'filled');
asserts.isequal(size(s), [1 5]);
asserts.isequal(s(1).CData, [0.0660 0.4430 0.7450]);
asserts.isequal(s(2).CData, [0.8660 0.3290 0]);
asserts.isequal(s(3).CData, [0.9290 0.6940 0.1250]);
asserts.isequal(s(4).CData, [0.5210 0.0860 0.8190]);
asserts.isequal(s(5).CData, [0.2310 0.6660 0.1960]);
