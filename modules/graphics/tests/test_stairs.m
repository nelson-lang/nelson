X = linspace(0, 4 * pi, 50)';
Y = [0.5 * cos(X), 2 * cos(X)];
[xb, yb] = stairs(X, Y);
asserts.isequal(size(xb), [99 2]);
asserts.isequal(size(yb), [99 2]);
%=============================================================================
h = stairs(X, Y);
asserts.isequal(h(1).Type, 'stair');
asserts.istrue(all(isgraphics(h, 'stair')));
close all;
