x = 0:pi / 100:2 * pi;
y1 = sin(x);
y2 = sin(x - 0.25);
y3 = sin(x - 0.5);
%=============================================================================
f = figure();
L = plot(x, y1, x, y2, '--', x, y3, ':');
asserts.isequal(size(L), [3 1]);
asserts.isequal(L(1).LineStyle, '-');
asserts.isequal(L(2).LineStyle, '--');
asserts.isequal(L(3).LineStyle, ':');
%=============================================================================
f = figure();
L = plot(x, y1, 'g', x, y2, 'b--o', x, y3, 'c*');
asserts.isequal(size(L), [3 1]);
%=============================================================================
f = figure();
x = linspace(0, 10);
y = sin(x);
L = plot(x, y, '-o');
asserts.isequal(size(L), [1 1]);
asserts.isequal(L(1).LineStyle, '-');
close all;
