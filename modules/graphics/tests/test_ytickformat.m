f = figure('Visible', 'off');
plot(1:10, (1:10) / 4);
ax = gca();
ylim([-0.5 3]);
yticks(0:0.5:2.5);
ytickformat('%.2f');
assert_isequal(ytickformat(), '%.2f');
assert_isequal(ax.YTickLabelFormat, '%.2f');
drawnow();
assert_isequal(ax.YTickLabel', {'0.00', '0.50', '1.00', '1.50', '2.00', '2.50'});
ytickformat('percentage');
drawnow();
assert_isequal(ax.YTickLabel', {'0%', '0.5%', '1%', '1.5%', '2%', '2.5%'});
ytickformat(ax, '%.1f');
drawnow();
assert_isequal(ax.YTickLabel', {'0.0', '0.5', '1.0', '1.5', '2.0', '2.5'});
close(f);
