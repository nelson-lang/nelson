f = figure();
x = logspace(-1, 2);
semilogx(x, x);
grid on
%=============================================================================
f = figure();
x = logspace(-1, 2, 15);
y = 13 + x;
semilogx(x, y, 'x', 'MarkerFaceColor', [0 0.447 0.741])
grid on
%=============================================================================
f = figure();
x = logspace(-1, 2);
y = x;
y(30) = NaN;
semilogx(x, y)
%=============================================================================
f = figure('Visible', 'off');
x = 1:100;
y1 = x .^ 2;
y2 = x .^ 3;
semilogx(y1, x, '--', y2, x);
legend('x^2', 'x^3', 'Location', 'northwest');
drawnow();
ax = gca();
asserts.isequal(ax.XScale, 'log');
asserts.isequal(char(ax.XMinorTick), 'on');
asserts.isequal(ax.XTick, [1 10 100 1000 10000 100000 1000000]);
asserts.isequal(ax.XTickLabel, {'10^{0}'; '10^{1}'; '10^{2}'; '10^{3}'; '10^{4}'; ...
  '10^{5}'; '10^{6}'});
close(f);
