close all;
f = figure('Visible', 'off');
surf(peaks(20));
ax = gca();
%=============================================================================
t = camtarget();
asserts.isequal(size(t), [1 3]);
asserts.isequal(camtarget(ax), get(ax, 'CameraTarget'));
%=============================================================================
camtarget(ax, [1 2 3]);
asserts.isequal(camtarget(ax), [1 2 3]);
asserts.isequal(char(get(ax, 'CameraTargetMode')), 'manual');
%=============================================================================
camtarget(ax, 'auto');
asserts.isequal(char(camtarget(ax, 'mode')), 'auto');
%=============================================================================
asserts.checkerror('camtarget(gca(), ''bad'')', 'Value must be ''auto'', ''manual'' or ''mode''.');
