f = figure();
ax1 = subplot(2, 1, 1);
x = linspace(0, 10);
y1 = sin(x);
plot(x, y1)
ax2 = subplot(2, 1, 2);
y2 = sin(5 * x);
plot(x, y2)
asserts.isapprox(ax1.Position, [0.13 0.583837209302326 0.775 0.341162790697674], 1e-12);
asserts.isapprox(ax2.Position, [0.13 0.11 0.775 0.341162790697674], 1e-12);
close all;
