% spy() takes a matrix and an optional style, and nothing else. Handed anything
% else it has to say which argument it rejects instead of failing somewhere
% inside on a value it should never have accepted.
%=============================================================================
f = figure('Visible', 'off');
ax1 = axes('Parent', f);
%=============================================================================
% spy() draws the sparsity pattern of its first argument: it takes no target,
% so an axes there is not a target, it is a matrix that is not one.
notAMatrix = {...
  'spy(ax1, eye(3))', ...
  'spy(ax1, sparse(eye(3)))', ...
  'spy(ax1)', ...
  'spy({1, 2})', ...
  'spy(struct(''a'', 1))', ...
  'spy(''abc'')'};
for k = 1:numel(notAMatrix)
  assert_checkerror(notAMatrix{k}, getString(message('Nelson:spy:invalidMatrix')), ...
    'Nelson:spy:invalidMatrix');
end
%=============================================================================
% The marker size is a size, not whatever was left in the argument list.
notAMarkerSize = {...
  'spy(eye(3), [1 2])', ...
  'spy(eye(3), -1)', ...
  'spy(eye(3), ax1)', ...
  'spy(eye(3), Inf)', ...
  'spy(eye(3), NaN)', ...
  'spy(eye(3), ''r'', [1 2])'};
for k = 1:numel(notAMarkerSize)
  assert_checkerror(notAMarkerSize{k}, getString(message('Nelson:spy:invalidMarkerSize')), ...
    'Nelson:spy:invalidMarkerSize');
end
%=============================================================================
close(f);
%=============================================================================
% The accepted forms keep working.
accepted = {...
  'spy(eye(3))', ...
  'spy(sparse(eye(3)))', ...
  'spy(eye(3) > 0)', ...
  'spy(single(eye(3)))', ...
  'spy(int8(eye(3)))', ...
  'spy(ones(2, 2, 2))', ...
  'spy(eye(3) + 1i)', ...
  'spy(zeros(3))', ...
  'spy([])', ...
  'spy(sparse([]))', ...
  'spy(eye(3), 0)', ...
  'spy(eye(3), 12)', ...
  'spy(eye(3), 12.5)', ...
  'spy(eye(3), int8(12))', ...
  'spy(eye(3), ''r*'')', ...
  'spy(eye(3), ''r'', 12)', ...
  'spy(eye(3), 12, ''r'')'};
for k = 1:numel(accepted)
  f = figure('Visible', 'off');
  eval([accepted{k}, ';']);
  assert_istrue(numel(gca().Children) >= 1, [accepted{k}, ' must draw.']);
  close(f);
end
%=============================================================================
% spy() draws in the current axes and leaves the others alone.
f = figure('Visible', 'off');
ax1 = axes('Parent', f, 'Position', [0.1 0.1 0.3 0.3]);
ax2 = axes('Parent', f, 'Position', [0.5 0.5 0.3 0.3]);
line('Parent', ax1, 'XData', [0 1], 'YData', [0 1], 'Tag', 'BYSTANDERW');
spy(eye(3));
assert_isequal(numel(findobj(ax1, 'Tag', 'BYSTANDERW')), 1);
assert_isequal(gca(), ax2);
assert_istrue(numel(ax2.Children) >= 1);
close(f);
