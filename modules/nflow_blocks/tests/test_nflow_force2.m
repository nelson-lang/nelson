% Force2 / Torque2 (Coselica): an equal and opposite signal-driven force/torque
% between two flanges (+F on a, -F on b). Native mechanicalTranslationalIsland
% kind `force2`.
%=============================================================================
% <--SEQUENTIAL TEST REQUIRED-->
%=============================================================================
% Two free unit masses pushed apart by Force2(F=5): a_A = +5, a_B = -5, so at
% t = 1 s each has moved 0.5 * 5 = 2.5 in opposite directions.
d = ['{"version":"1.0.0","format":"nflow-2","name":"F2","blocks":[', ...
  '{"id":"src","type":"constant","inputs":0,"outputs":1,"params":{"Value":5}},', ...
  '{"id":"A","type":"Mass","params":{"m":1,"s0":0,"v0":0}},', ...
  '{"id":"B","type":"Mass","params":{"m":1,"s0":0,"v0":0}},', ...
  '{"id":"F","type":"Force2","inputs":1,"params":{}},', ...
  '{"id":"PA","type":"PositionSensor","params":{}},', ...
  '{"id":"PB","type":"PositionSensor","params":{}},', ...
  '{"id":"sa","type":"scope","inputs":1,"outputs":0,"params":{}},', ...
  '{"id":"sb","type":"scope","inputs":1,"outputs":0,"params":{}}],', ...
  '"connections":[{"from":"src","to":"F","fromIndex":0,"toIndex":0},', ...
  '{"from":"PA","to":"sa","fromIndex":0,"toIndex":0},', ...
  '{"from":"PB","to":"sb","fromIndex":0,"toIndex":0}],', ...
  '"physicalWires":[{"pins":["A.flange","F.a","PA.flange"]},', ...
  '{"pins":["B.flange","F.b","PB.flange"]}],', ...
  '"solver":"dae","runtime":1,"sampleTime":0.02}'];
r = jsondecode(__nflow_simulate__(NFlow.internal.acausalExpand(d)));
assert_isequal(r.status, 'done');
assert_isapprox(r.scopes(1).series(end), 2.5, 5e-2); % +0.5 F t^2
assert_isapprox(r.scopes(2).series(end), -2.5, 5e-2); % opposite
%=============================================================================
% Torque2 twin: two inertias with an equal/opposite torque tau = 3.
d = ['{"version":"1.0.0","format":"nflow-2","name":"T2","blocks":[', ...
  '{"id":"src","type":"constant","inputs":0,"outputs":1,"params":{"Value":3}},', ...
  '{"id":"A","type":"Inertia","params":{"J":1,"phi0":0,"w0":0}},', ...
  '{"id":"B","type":"Inertia","params":{"J":1,"phi0":0,"w0":0}},', ...
  '{"id":"T","type":"Torque2","inputs":1,"params":{}},', ...
  '{"id":"WA","type":"RotSpeedSensor","params":{}},', ...
  '{"id":"WB","type":"RotSpeedSensor","params":{}},', ...
  '{"id":"sa","type":"scope","inputs":1,"outputs":0,"params":{}},', ...
  '{"id":"sb","type":"scope","inputs":1,"outputs":0,"params":{}}],', ...
  '"connections":[{"from":"src","to":"T","fromIndex":0,"toIndex":0},', ...
  '{"from":"WA","to":"sa","fromIndex":0,"toIndex":0},', ...
  '{"from":"WB","to":"sb","fromIndex":0,"toIndex":0}],', ...
  '"physicalWires":[{"pins":["A.flange","T.a","WA.flange"]},', ...
  '{"pins":["B.flange","T.b","WB.flange"]}],', ...
  '"solver":"dae","runtime":1,"sampleTime":0.02}'];
r = jsondecode(__nflow_simulate__(NFlow.internal.acausalExpand(d)));
assert_isequal(r.status, 'done');
assert_isapprox(r.scopes(1).series(end), 3.0, 5e-2); % w_A = tau/J * t
assert_isapprox(r.scopes(2).series(end), -3.0, 5e-2); % opposite
