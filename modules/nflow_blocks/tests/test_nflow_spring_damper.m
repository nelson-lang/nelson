% <--WEIGHT 2-->
% SpringDamper / RotSpringDamper: NFlow.internal.acausalExpand splits each into a
% PARALLEL spring + damper sharing the same physical net (pure .m, no engine
% build), so a mass / inertia on one settles with a damped oscillation.
%=============================================================================
% <--SEQUENTIAL TEST REQUIRED-->
%=============================================================================
% Translational: a mass on a SpringDamper to a wall -> damped oscillation.
d = ['{"version":"1.0.0","format":"nflow-2","name":"SD","blocks":[', ...
  '{"id":"M","type":"Mass","params":{"m":1,"s0":1,"v0":0}},', ...
  '{"id":"SD","type":"SpringDamper","params":{"k":10,"d":0.5}},', ...
  '{"id":"W","type":"Fixed","params":{"s0":0}},', ...
  '{"id":"PS","type":"PositionSensor","params":{}},', ...
  '{"id":"sc","type":"scope","inputs":1,"outputs":0,"params":{}}],', ...
  '"connections":[{"from":"PS","to":"sc","fromIndex":0,"toIndex":0}],', ...
  '"physicalWires":[{"pins":["M.flange","SD.a","PS.flange"]},{"pins":["SD.b","W.flange"]}],', ...
  '"solver":"dae","runtime":10,"sampleTime":0.05}'];
ex = NFlow.internal.acausalExpand(d);
assert_istrue(isempty(strfind(ex, '"SpringDamper"'))); % composite is split
r = jsondecode(__nflow_simulate__(ex));
assert_isequal(r.status, 'done');
v = r.scopes(1).series(:);
assert_isapprox(v(1), 1.0, 1e-6); % starts at s0
early = max(abs(v(1:40)));
late = max(abs(v(end - 40:end)));
assert_istrue(late < early * 0.6); % clearly damped
%=============================================================================
% Rotational: an inertia on a RotSpringDamper to a fixed frame -> damped.
d = ['{"version":"1.0.0","format":"nflow-2","name":"RSD","blocks":[', ...
  '{"id":"J","type":"Inertia","params":{"J":1,"phi0":1,"w0":0}},', ...
  '{"id":"SD","type":"RotSpringDamper","params":{"c":10,"d":0.5}},', ...
  '{"id":"W","type":"RotFixed","params":{"phi0":0}},', ...
  '{"id":"AS","type":"AngleSensor","params":{}},', ...
  '{"id":"sc","type":"scope","inputs":1,"outputs":0,"params":{}}],', ...
  '"connections":[{"from":"AS","to":"sc","fromIndex":0,"toIndex":0}],', ...
  '"physicalWires":[{"pins":["J.flange","SD.a","AS.flange"]},{"pins":["SD.b","W.flange"]}],', ...
  '"solver":"dae","runtime":10,"sampleTime":0.05}'];
ex = NFlow.internal.acausalExpand(d);
assert_istrue(isempty(strfind(ex, '"RotSpringDamper"')));
r = jsondecode(__nflow_simulate__(ex));
assert_isequal(r.status, 'done');
v = r.scopes(1).series(:);
assert_istrue(max(abs(v(end - 40:end))) < max(abs(v(1:40))) * 0.6);
%=============================================================================
% MassWithWeight: expands to Mass + ConstantForce(-m g); a free one free-falls
% s(t) = s0 - 0.5 g t^2.
d = ['{"version":"1.0.0","format":"nflow-2","name":"MW","blocks":[', ...
  '{"id":"M","type":"MassWithWeight","params":{"m":2,"g":9.81,"s0":0,"v0":0}},', ...
  '{"id":"PS","type":"PositionSensor","params":{}},', ...
  '{"id":"sc","type":"scope","inputs":1,"outputs":0,"params":{}}],', ...
  '"connections":[{"from":"PS","to":"sc","fromIndex":0,"toIndex":0}],', ...
  '"physicalWires":[{"pins":["M.flange","PS.flange"]}],', ...
  '"solver":"dae","runtime":1,"sampleTime":0.02}'];
ex = NFlow.internal.acausalExpand(d);
assert_istrue(isempty(strfind(ex, 'MassWithWeight')));
r = jsondecode(__nflow_simulate__(ex));
assert_isequal(r.status, 'done');
v = r.scopes(1).series(:);
assert_isapprox(v(end), -0.5 * 9.81, 5e-2); % s(1) = -0.5 g
