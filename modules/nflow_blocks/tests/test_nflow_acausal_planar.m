% 6) Double pendulum (body-to-body Revolute): two uniform rods of length 1
%    (m = 1, I = 1/12, COM at the centre). Rod 0's proximal end (-0.5, 0) is
%    pinned to the world origin; rod 1's proximal end (-0.5, 0) is pinned to rod
%    0's distal end (0.5, 0). Released horizontal from rest. This is a chaotic
%    multibody system with no simple closed form, so correctness is checked two
%    reference-free ways: total mechanical energy is conserved (ideal joints do no
%    work; E(0) = 0) and BOTH pin constraints stay satisfied.
Ir = 1 / 12;
% Twelve logged channels: {kind, body, variable name}. Built programmatically
% into one toWorkspace per channel (nflow toWorkspace takes a single input).
chans = {...
  'positionSensorX', 0, 'x0'; 'positionSensorY', 0, 'y0'; 'positionSensorPhi', 0, 'p0'; ...
  'speedSensorX', 0, 'vx0'; 'speedSensorY', 0, 'vy0'; 'speedSensorOmega', 0, 'w0'; ...
  'positionSensorX', 1, 'x1'; 'positionSensorY', 1, 'y1'; 'positionSensorPhi', 1, 'p1'; ...
  'speedSensorX', 1, 'vx1'; 'speedSensorY', 1, 'vy1'; 'speedSensorOmega', 1, 'w1'};
comps = {...
  struct('kind', 'body', 'body', 0, 'm', 1, 'I', Ir, 'x0', 0.5, 'y0', 0, 'phi0', 0), ...
  struct('kind', 'body', 'body', 1, 'm', 1, 'I', Ir, 'x0', 1.5, 'y0', 0, 'phi0', 0), ...
  struct('kind', 'revolute', 'body', 0, 'ax', -0.5, 'ay', 0, 'px', 0, 'py', 0), ...
  struct('kind', 'revolute', 'body', 1, 'ax', -0.5, 'ay', 0, 'body2', 0, 'ax2', 0.5, 'ay2', 0)};
nc = size(chans, 1);
for k = 1:nc
  comps{end + 1} = struct('kind', chans{k, 1}, 'body', chans{k, 2}, 'outPort', k - 1);
end
isl = struct('id', 'isl', 'type', 'planarMechanicalIsland', 'inputs', 0, 'outputs', nc, ...
  'params', struct('domain', 'planar', 'bodies', 2, 'gravity', 9.81, ...
                   'baumgarte', 30, 'components', {comps}));
blocks = {isl};
conns = {};
for k = 1:nc
  blocks{end + 1} = struct('id', ['tw', int2str(k)], 'type', 'toWorkspace', ...
    'inputs', 1, 'outputs', 0, 'params', struct('VariableName', chans{k, 3}));
  conns{end + 1} = struct('from', 'isl', 'to', ['tw', int2str(k)], ...
    'fromIndex', k - 1, 'toIndex', 0);
end
doc = struct('blocks', {blocks}, 'connections', {conns}, ...
  'solver', 'dae', 'runtime', 2.0, 'sampleTime', 0.01);
out = sim(pl_write(jsonencode(doc), 'test_nflow_planar_double'));
lg = out.logsout; nms = {lg.name};
getv = @(nm) lg(find(strcmp(nms, nm), 1)).values;
x0 = getv('x0'); y0 = getv('y0'); p0 = getv('p0');
vx0 = getv('vx0'); vy0 = getv('vy0'); w0 = getv('w0');
x1 = getv('x1'); y1 = getv('y1'); p1 = getv('p1');
vx1 = getv('vx1'); vy1 = getv('vy1'); w1 = getv('w1');
x0 = x0(:); y0 = y0(:); p0 = p0(:); vx0 = vx0(:); vy0 = vy0(:); w0 = w0(:);
x1 = x1(:); y1 = y1(:); p1 = p1(:); vx1 = vx1(:); vy1 = vy1(:); w1 = w1(:);
% Total mechanical energy (KE + PE); ideal joints conserve it, E(0) = 0.
E = 0.5 * (vx0 .^ 2 + vy0 .^ 2) + 0.5 * Ir * w0 .^ 2 ...
  + 0.5 * (vx1 .^ 2 + vy1 .^ 2) + 0.5 * Ir * w1 .^ 2 ...
  + 9.81 * y0 + 9.81 * y1;
assert_istrue(max(abs(E)) < 5e-2);
% Pin O: rod 0 proximal end (-0.5,0) stays at the origin.
pOx = x0 - 0.5 * cos(p0);
pOy = y0 - 0.5 * sin(p0);
assert_istrue(max(abs(pOx)) < 1e-2);
assert_istrue(max(abs(pOy)) < 1e-2);
% Pin 1: rod 0 distal end = rod 1 proximal end.
d0x = x0 + 0.5 * cos(p0); d0y = y0 + 0.5 * sin(p0);
a1x = x1 - 0.5 * cos(p1); a1y = y1 - 0.5 * sin(p1);
assert_istrue(max(abs(d0x - a1x)) < 1e-2);
assert_istrue(max(abs(d0y - a1y)) < 1e-2);
