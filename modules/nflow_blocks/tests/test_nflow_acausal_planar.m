% 4) Physical pendulum (Revolute joint): a body (m = 1, I = 0.1) has a
%    body-fixed point a = (1, 0) from its COM pinned to the world origin. With
%    the pin at the origin, COM = -R(phi) a, so the body is a physical pendulum
%    of length L = 1. Released horizontally (phi0 = 0, COM at (-1, 0)) it swings
%    under gravity. The reduced Lagrangian equation is
%        (I + m L^2) phi'' = m g L cos(phi),
%    integrated independently with ode45 for comparison. The DAE solves the full
%    constrained Newton equations (Baumgarte only stabilises drift), so the two
%    must agree.
m = 1; L = 1; I = 0.1;
coef = m * g * L / (I + m * L ^ 2);
odef = @(tt, z)[z(2); coef * cos(z(1))];
[tref, zref] = ode45(odef, [0 2], [0; 0]);
pend = ['{"blocks":[', ...
  '{"id":"isl","type":"planarMechanicalIsland","inputs":0,"outputs":1,"params":{', ...
    '"domain":"planar","bodies":1,"gravity":9.81,"baumgarte":30,"components":[', ...
      '{"kind":"body","body":0,"m":1,"I":0.1,"x0":-1,"y0":0,"phi0":0},', ...
      '{"kind":"revolute","body":0,"ax":1,"ay":0,"px":0,"py":0},', ...
      '{"kind":"positionSensorPhi","body":0,"outPort":0}]}},', ...
  '{"id":"twP","type":"toWorkspace","inputs":1,"outputs":0,"params":{"VariableName":"PH"}}],', ...
  '"connections":[{"from":"isl","to":"twP","fromIndex":0,"toIndex":0}],', ...
  '"solver":"dae","runtime":2.0,"sampleTime":0.02}'];
out = sim(pl_write(pend, 'test_nflow_planar_pendulum'));
lg = out.logsout; nms = {lg.name};
PH = lg(find(strcmp(nms, 'PH'), 1)).values;
t = linspace(0, 2, numel(PH))';
phiRef = interp1(tref, zref(:, 1), t);
assert_istrue(max(abs(PH(:) - phiRef)) < 5e-3);
