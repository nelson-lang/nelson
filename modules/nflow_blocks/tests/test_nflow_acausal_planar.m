assert_istrue(max(abs(RY(:) - (-Lrod * cos(thRef)))) < 1e-2);
% Rod length stays exactly L throughout.
assert_istrue(max(abs(sqrt(RX(:) .^ 2 + RY(:) .^ 2) - Lrod)) < 1e-2);
% CutForce: the rod tension (Lagrange multiplier) obeys T = 3 m g cos(theta) =
