% <--WEIGHT 2-->
% Acausal palette N7 (planar 2-D multibody). The planarMechanicalIsland block
% integrates rigid bodies in absolute centre-of-mass coordinates
% (xc, yc, phi, vx, vy, w) with gravity at the COM (down = -y). A free body is a
% plain ODE with exact closed-form solutions; a Revolute joint adds a
% Baumgarte-stabilised pin constraint whose motion is checked against an
% independent Lagrangian ode45. Every case runs under the `dae` solver.
%=============================================================================
function p = pl_write(json, stem)
  p = [tempname(), '.nflow'];
  fid = fopen(p, 'w'); fwrite(fid, json); fclose(fid);
end
