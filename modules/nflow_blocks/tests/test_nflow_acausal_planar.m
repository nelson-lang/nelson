  '{"id":"isl","type":"planarMechanicalIsland","inputs":0,"outputs":3,"params":{', ...
    '"domain":"planar","bodies":1,"gravity":9.81,"baumgarte":30,"components":[', ...
      '{"kind":"body","body":0,"m":1,"I":0.1,"x0":1,"y0":0,"phi0":0},', ...
      '{"kind":"distanceJoint","body":0,"ax":0,"ay":0,"body2":-1,"px":0,"py":0,"length":1,"outPortF":2},', ...
      '{"kind":"positionSensorX","body":0,"outPort":0},', ...
      '{"kind":"positionSensorY","body":0,"outPort":1}]}},', ...
  '{"id":"twX","type":"toWorkspace","inputs":1,"outputs":0,"params":{"VariableName":"RX"}},', ...
  '{"id":"twY","type":"toWorkspace","inputs":1,"outputs":0,"params":{"VariableName":"RY"}},', ...
  '{"id":"twF","type":"toWorkspace","inputs":1,"outputs":0,"params":{"VariableName":"RF"}}],', ...
  '"connections":[', ...
    '{"from":"isl","to":"twX","fromIndex":0,"toIndex":0},', ...
    '{"from":"isl","to":"twY","fromIndex":1,"toIndex":0},', ...
    '{"from":"isl","to":"twF","fromIndex":2,"toIndex":0}],', ...
  '"solver":"dae","runtime":2.0,"sampleTime":0.02}'];
