% 9) Simple pendulum via a DistanceJoint (rigid rod). A body's COM is held at a
%    fixed distance L = 1 from the world origin by a rod; the rod attaches at the
%    COM so rotation is decoupled (phi stays 0) and the COM swings as a simple
%    pendulum. With COM = (L sin(theta), -L cos(theta)) the reduced equation is
