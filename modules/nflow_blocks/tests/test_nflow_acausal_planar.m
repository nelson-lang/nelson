% 11) Rolling wheel: a uniform disk (m = 1, R = 1, I = 0.5) rolls without
%     slipping down a 30-degree incline under gravity. The no-slip rolling
%     acceleration is a = g sin(alpha) / (1 + I/(m R^2)) = 9.81*0.5/1.5 = 3.27,
%     so the COM follows center0 + 0.5 a t^2 * d, with the surface tangent
%     d = (cos a, -sin a), normal n = (sin a, cos a), center0 = R n.
al = pi / 6; dxA = cos(al); dyA = -sin(al); nx = sin(al); ny = cos(al);
aRoll = 9.81 * sin(al) / (1 + 0.5 / (1 * 1)); % = 3.27
roll = ['{"blocks":[', ...
  '{"id":"isl","type":"planarMechanicalIsland","inputs":0,"outputs":2,"params":{', ...
    '"domain":"planar","bodies":1,"gravity":9.81,"baumgarte":30,"components":[', ...
      '{"kind":"body","body":0,"m":1,"I":0.5,"x0":', sprintf('%.15g', nx), ...
        ',"y0":', sprintf('%.15g', ny), ',"phi0":0},', ...
      '{"kind":"rollingWheel","body":0,"dx":', sprintf('%.15g', dxA), ...
        ',"dy":', sprintf('%.15g', dyA), ',"px":0,"py":0,"radius":1},', ...
      '{"kind":"positionSensorX","body":0,"outPort":0},', ...
      '{"kind":"positionSensorY","body":0,"outPort":1}]}},', ...
  '{"id":"tX","type":"toWorkspace","inputs":1,"outputs":0,"params":{"VariableName":"WX"}},', ...
  '{"id":"tY","type":"toWorkspace","inputs":1,"outputs":0,"params":{"VariableName":"WY"}}],', ...
  '"connections":[', ...
    '{"from":"isl","to":"tX","fromIndex":0,"toIndex":0},', ...
    '{"from":"isl","to":"tY","fromIndex":1,"toIndex":0}],', ...
  '"solver":"dae","runtime":0.6,"sampleTime":0.02}'];
out = sim(pl_write(roll, 'test_nflow_planar_roll'));
lg = out.logsout; nms = {lg.name};
WX = lg(find(strcmp(nms, 'WX'), 1)).values(:);
WY = lg(find(strcmp(nms, 'WY'), 1)).values(:);
t = linspace(0, 0.6, numel(WX))';
sRoll = 0.5 * aRoll * t .^ 2;
assert_istrue(max(abs(WX - (nx + sRoll * dxA))) < 1e-2);
assert_istrue(max(abs(WY - (ny + sRoll * dyA))) < 1e-2);
