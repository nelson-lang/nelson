% <--WEIGHT 2-->
% Mechanical waveform sources SineForce / RampForce / SineTorque / RampTorque
% (Coselica): continuous signal-driven force/torque on a flange, delivered via
% the same waveform expansion pre-pass as the electrical sources (causal
% sine/ramp -> Force/Torque), no engine change.
%=============================================================================
% <--SEQUENTIAL TEST REQUIRED-->
%=============================================================================
% RampForce of slope 2 N/s on a 1 kg mass: F = 2 t, so a = 2 t and the velocity
% is v = t^2. At t = 1 s the mass speed should be about 1 m/s.
d = ['{"version":"1.0.0","format":"nflow-2","name":"RF","blocks":[', ...
  '{"id":"F1","type":"RampForce","params":{"Slope":2,"StartTime":0}},', ...
  '{"id":"M1","type":"Mass","params":{"m":1}},', ...
  '{"id":"SS","type":"SpeedSensor","params":{}},', ...
  '{"id":"sc","type":"scope","inputs":1,"outputs":0,"params":{}}],', ...
  '"connections":[{"from":"SS","to":"sc","fromIndex":0,"toIndex":0}],', ...
  '"physicalWires":[{"pins":["F1.flange","M1.flange","SS.flange"]}],', ...
  '"solver":"ode4","runtime":1.0,"sampleTime":0.05}'];
r = jsondecode(__nflow_simulate__(NFlow.internal.acausalExpand(d)));
assert_isequal(r.status, 'done');
v_end = abs(r.scopes(1).series(end));
assert_istrue(v_end > 0.7 && v_end < 1.3); % v(1 s) ~ 1 m/s (v = t^2)
%=============================================================================
% SineTorque of amplitude 3 N.m at 1 Hz on a 1 kg.m^2 inertia: the speed must
% oscillate (change sign) rather than grow, so max-min spans a clear band.
d2 = ['{"version":"1.0.0","format":"nflow-2","name":"ST","blocks":[', ...
  '{"id":"T1","type":"SineTorque","params":{"Amplitude":3,"Frequency":1,"Phase":0}},', ...
  '{"id":"J1","type":"Inertia","params":{"J":1}},', ...
  '{"id":"WS","type":"RotSpeedSensor","params":{}},', ...
  '{"id":"sc","type":"scope","inputs":1,"outputs":0,"params":{}}],', ...
  '"connections":[{"from":"WS","to":"sc","fromIndex":0,"toIndex":0}],', ...
  '"physicalWires":[{"pins":["T1.flange","J1.flange","WS.flange"]}],', ...
  '"solver":"ode4","runtime":2.0,"sampleTime":0.02}'];
r = jsondecode(__nflow_simulate__(NFlow.internal.acausalExpand(d2)));
assert_isequal(r.status, 'done');
w = r.scopes(1).series;
assert_istrue(max(w) > 0.1 && min(w) < 0.05); % oscillates, does not run away
%=============================================================================
% Damped-sine and trapezoid variants run to completion and move their load.
variants = {'ExpSineForce', '"Amplitude":2,"Frequency":2,"Damping":0.5,"Phase":0', 'Mass', 'SpeedSensor'; ...
  'TrapezoidForce', '"Amplitude":2,"Rising":0.2,"Width":0.3,"Falling":0.2,"Period":1', 'Mass', 'SpeedSensor'; ...
  'ExpSineTorque', '"Amplitude":2,"Frequency":2,"Damping":0.5,"Phase":0', 'Inertia', 'RotSpeedSensor'; ...
  'TrapezoidTorque', '"Amplitude":2,"Rising":0.2,"Width":0.3,"Falling":0.2,"Period":1', 'Inertia', 'RotSpeedSensor'};
for i = 1:size(variants, 1)
  dv = ['{"version":"1.0.0","format":"nflow-2","name":"V","blocks":[', ...
    '{"id":"F1","type":"', variants{i, 1}, '","params":{', variants{i, 2}, '}},', ...
    '{"id":"M1","type":"', variants{i, 3}, '","params":{}},', ...
    '{"id":"SS","type":"', variants{i, 4}, '","params":{}},', ...
    '{"id":"sc","type":"scope","inputs":1,"outputs":0,"params":{}}],', ...
    '"connections":[{"from":"SS","to":"sc","fromIndex":0,"toIndex":0}],', ...
    '"physicalWires":[{"pins":["F1.flange","M1.flange","SS.flange"]}],', ...
    '"solver":"ode4","runtime":1.0,"sampleTime":0.05}'];
  rv = jsondecode(__nflow_simulate__(NFlow.internal.acausalExpand(dv)));
  assert_isequal(rv.status, 'done');
  assert_istrue(any(abs(rv.scopes(1).series) > 1e-6));
end
