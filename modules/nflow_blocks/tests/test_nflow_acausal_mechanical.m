% Acausal palette N4: the native mechanicalTranslationalIsland block. 1-D
% translational mechanics with (position, velocity) states per mass node and
% force as the through-variable. Analytic / ode45 checks.
%=============================================================================
function p = me_write(json, stem)
  p = [tempname(), '.nflow'];
  fid = fopen(p, 'w'); fwrite(fid, json); fclose(fid);
end
%=============================================================================
% 1) Mass-spring-damper (m=1, k=4, d=1) released from s0=1, v0=0 against a fixed
%    wall (node 0). Underdamped: wn=2, zeta=d/(2 sqrt(k m))=0.25, wd=wn sqrt(1-z^2).
%    s(t) = e^{-z wn t} (cos wd t + (z wn / wd) sin wd t).
msd = ['{"blocks":[', ...
  '{"id":"isl","type":"mechanicalTranslationalIsland","inputs":0,"outputs":2,"params":{', ...
    '"domain":"translational","nodes":2,"components":[', ...
      '{"kind":"mass","node":1,"m":1,"s0":1,"v0":0},', ...
      '{"kind":"spring","a":1,"b":0,"k":4},', ...
      '{"kind":"damper","a":1,"b":0,"d":1},', ...
      '{"kind":"positionSensor","node":1,"outPort":0},', ...
      '{"kind":"speedSensor","node":1,"outPort":1}]}},', ...
  '{"id":"tws","type":"toWorkspace","inputs":1,"outputs":0,"params":{"VariableName":"s"}},', ...
  '{"id":"twv","type":"toWorkspace","inputs":1,"outputs":0,"params":{"VariableName":"v"}}],', ...
  '"connections":[', ...
    '{"from":"isl","to":"tws","fromIndex":0,"toIndex":0},', ...
    '{"from":"isl","to":"twv","fromIndex":1,"toIndex":0}],', ...
  '"solver":"dae","runtime":8.0,"sampleTime":0.05}'];
out = sim(me_write(msd, 'test_nflow_mech_msd'));
lg = out.logsout; nms = {lg.name};
s = lg(find(strcmp(nms, 's'), 1)).values;
v = lg(find(strcmp(nms, 'v'), 1)).values;
t = linspace(0, 8, numel(s))';
wn = 2; zeta = 0.25; wd = wn * sqrt(1 - zeta ^ 2);
sref = exp(-zeta * wn * t) .* (cos(wd * t) + (zeta * wn / wd) * sin(wd * t));
assert_istrue(max(abs(s(:) - sref)) < 2e-3);
% velocity is the analytic derivative; cross-check numerically at mid samples
assert_istrue(abs(v(1)) < 1e-6); % released from rest
%=============================================================================
% 2) Step force on a damped mass (m=2, d=3, no spring): F=6 from rest.
%    Terminal velocity v_inf = F/d = 2; v(t) = 2 (1 - e^{-(d/m) t}) = 2(1-e^{-1.5t}).
stepf = ['{"blocks":[', ...
  '{"id":"isl","type":"mechanicalTranslationalIsland","inputs":0,"outputs":1,"params":{', ...
    '"domain":"translational","nodes":2,"components":[', ...
      '{"kind":"mass","node":1,"m":2,"s0":0,"v0":0},', ...
      '{"kind":"damper","a":1,"b":0,"d":3},', ...
      '{"kind":"force","node":1,"F":6},', ...
      '{"kind":"speedSensor","node":1,"outPort":0}]}},', ...
  '{"id":"twv","type":"toWorkspace","inputs":1,"outputs":0,"params":{"VariableName":"v"}}],', ...
  '"connections":[{"from":"isl","to":"twv","fromIndex":0,"toIndex":0}],', ...
  '"solver":"dae","runtime":4.0,"sampleTime":0.05}'];
out = sim(me_write(stepf, 'test_nflow_mech_stepf'));
lg = out.logsout; nms = {lg.name};
v = lg(find(strcmp(nms, 'v'), 1)).values;
t = linspace(0, 4, numel(v))';
vref = 2 * (1 - exp(-1.5 * t));
assert_istrue(max(abs(v(:) - vref)) < 2e-3);
%=============================================================================
% 3) Two masses coupled by a spring (m1=1, m2=1, k=2), no damping, no wall.
%    Momentum conserves (starts at rest with an initial stretch): m1 v1 + m2 v2 = 0.
%    Start s1=0, s2=1 (spring stretched by 1); the centre of mass stays put at 0.5.
two = ['{"blocks":[', ...
  '{"id":"isl","type":"mechanicalTranslationalIsland","inputs":0,"outputs":2,"params":{', ...
    '"domain":"translational","nodes":3,"components":[', ...
      '{"kind":"mass","node":1,"m":1,"s0":0,"v0":0},', ...
      '{"kind":"mass","node":2,"m":1,"s0":1,"v0":0},', ...
      '{"kind":"spring","a":1,"b":2,"k":2},', ...
      '{"kind":"positionSensor","node":1,"outPort":0},', ...
      '{"kind":"positionSensor","node":2,"outPort":1}]}},', ...
  '{"id":"tw1","type":"toWorkspace","inputs":1,"outputs":0,"params":{"VariableName":"s1"}},', ...
  '{"id":"tw2","type":"toWorkspace","inputs":1,"outputs":0,"params":{"VariableName":"s2"}}],', ...
  '"connections":[', ...
    '{"from":"isl","to":"tw1","fromIndex":0,"toIndex":0},', ...
    '{"from":"isl","to":"tw2","fromIndex":1,"toIndex":0}],', ...
  '"solver":"dae","runtime":10.0,"sampleTime":0.05}'];
out = sim(me_write(two, 'test_nflow_mech_two'));
lg = out.logsout; nms = {lg.name};
s1 = lg(find(strcmp(nms, 's1'), 1)).values;
s2 = lg(find(strcmp(nms, 's2'), 1)).values;
% centre of mass (m1 s1 + m2 s2)/(m1+m2) stays at 0.5 for all time
com = (s1(:) + s2(:)) / 2;
assert_istrue(max(abs(com - 0.5)) < 2e-3);
%=============================================================================
% 4) Ideal gear (rotational): two inertias J1=1 (node1), J2=1 (node2) coupled
%    by a gear ratio 2 (phi1 = 2 phi2), constant torque T=1.25 on node1. Folded
%    inertia J_eff = J1 + J2 (1/2)^2 = 1.25, so w1' = T/J_eff = 1 => w1(t) = t,
%    and w2 = w1/2.
gear = ['{"blocks":[', ...
  '{"id":"isl","type":"mechanicalTranslationalIsland","inputs":0,"outputs":2,"params":{', ...
    '"domain":"rotational","nodes":3,"components":[', ...
      '{"kind":"mass","node":1,"m":1,"s0":0,"v0":0},', ...
      '{"kind":"mass","node":2,"m":1,"s0":0,"v0":0},', ...
      '{"kind":"gear","a":1,"b":2,"ratio":2},', ...
      '{"kind":"force","node":1,"F":1.25},', ...
      '{"kind":"speedSensor","node":1,"outPort":0},', ...
      '{"kind":"speedSensor","node":2,"outPort":1}]}},', ...
  '{"id":"tw1","type":"toWorkspace","inputs":1,"outputs":0,"params":{"VariableName":"w1"}},', ...
  '{"id":"tw2","type":"toWorkspace","inputs":1,"outputs":0,"params":{"VariableName":"w2"}}],', ...
  '"connections":[', ...
    '{"from":"isl","to":"tw1","fromIndex":0,"toIndex":0},', ...
    '{"from":"isl","to":"tw2","fromIndex":1,"toIndex":0}],', ...
  '"solver":"dae","runtime":2.0,"sampleTime":0.05}'];
out = sim(me_write(gear, 'test_nflow_mech_gear'));
lg = out.logsout; nms = {lg.name};
w1 = lg(find(strcmp(nms, 'w1'), 1)).values;
w2 = lg(find(strcmp(nms, 'w2'), 1)).values;
t = linspace(0, 2, numel(w1))';
assert_istrue(max(abs(w1(:) - t)) < 2e-3); % w1 = t
assert_istrue(max(abs(w2(:) - t / 2)) < 2e-3); % w2 = w1/2
%=============================================================================
% 5) Prescribed acceleration (Accelerate source): a flange driven by a constant
%    acceleration signal 2. From rest, v(t) = 2t and s(t) = t^2 (position and
%    speed sensors on the driven node).
acc = ['{"blocks":[', ...
  '{"id":"a2","type":"constant","inputs":0,"outputs":1,"params":{"Value":2}},', ...
  '{"id":"isl","type":"mechanicalTranslationalIsland","inputs":1,"outputs":2,"params":{', ...
    '"domain":"translational","nodes":2,"components":[', ...
      '{"kind":"accelerate","node":1,"port":0,"s0":0,"v0":0},', ...
      '{"kind":"positionSensor","node":1,"outPort":0},', ...
      '{"kind":"speedSensor","node":1,"outPort":1}]}},', ...
  '{"id":"a2b","type":"constant","inputs":0,"outputs":1,"params":{"Value":2}},', ...
  '{"id":"tws","type":"toWorkspace","inputs":1,"outputs":0,"params":{"VariableName":"s"}},', ...
  '{"id":"twv","type":"toWorkspace","inputs":1,"outputs":0,"params":{"VariableName":"v"}}],', ...
  '"connections":[', ...
    '{"from":"a2","to":"isl","fromIndex":0,"toIndex":0},', ...
    '{"from":"isl","to":"tws","fromIndex":0,"toIndex":0},', ...
    '{"from":"isl","to":"twv","fromIndex":1,"toIndex":0}],', ...
  '"solver":"dae","runtime":2.0,"sampleTime":0.05}'];
out = sim(me_write(acc, 'test_nflow_mech_accel'));
lg = out.logsout; nms = {lg.name};
