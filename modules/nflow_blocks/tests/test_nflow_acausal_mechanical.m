assert_istrue(max(abs(s(:) - t .^ 2)) < 2e-3); % s = t^2
%=============================================================================
% Regularised Coulomb friction (N6, the robust smooth model - no events). A mass
% (m = 1) launched at v0 = 10 against dry friction Fc = 2 decelerates at a
% constant a = -Fc/m = -2 while sliding (v >> vEps), so v(t) = 10 - 2 t until it
% coasts to rest near t = 5 and stays there (friction vanishes as v -> 0, so it
% does not reverse). vEps = 1e-3 keeps the model smooth.
fri = ['{"blocks":[', ...
  '{"id":"isl","type":"mechanicalTranslationalIsland","inputs":0,"outputs":1,"params":{', ...
    '"domain":"translational","nodes":2,"components":[', ...
      '{"kind":"mass","node":1,"m":1,"s0":0,"v0":10},', ...
      '{"kind":"friction","a":1,"Fc":2,"vEps":0.001},', ...
      '{"kind":"speedSensor","node":1,"outPort":0}]}},', ...
  '{"id":"twv","type":"toWorkspace","inputs":1,"outputs":0,"params":{"VariableName":"vf"}}],', ...
  '"connections":[{"from":"isl","to":"twv","fromIndex":0,"toIndex":0}],', ...
  '"solver":"dae","runtime":6.0,"sampleTime":0.02}'];
out = sim(me_write(fri, 'test_nflow_mech_friction'));
lg = out.logsout; nms = {lg.name};
vf = lg(find(strcmp(nms, 'vf'), 1)).values(:);
t = linspace(0, 6, numel(vf))';
% Sliding phase (v well above vEps): v(t) = 10 - 2 t to tanh accuracy.
sliding = (10 - 2 * t) > 0.2;
assert_istrue(max(abs(vf(sliding) - (10 - 2 * t(sliding)))) < 5e-3);
% Coasts to rest and stays (never reverses past a small band).
assert_istrue(vf(end) > -0.05 && vf(end) < 0.2);
%=============================================================================
% Clutch (N6 stick-slip, robust smooth model). Two flywheels J1 = 1 (w0 = 10)
% and J2 = 2 (w0 = 0) are joined by an engaged clutch. Its friction couple
% drives them to a common speed; with no external torque the total momentum
% J1 w1 + J2 w2 = 10 is conserved, so the stuck speed is 10/(1+2) = 3.333.
clu = ['{"blocks":[', ...
  '{"id":"isl","type":"mechanicalTranslationalIsland","inputs":0,"outputs":2,"params":{', ...
    '"domain":"translational","nodes":3,"components":[', ...
      '{"kind":"mass","node":1,"m":1,"v0":10},', ...
      '{"kind":"mass","node":2,"m":2,"v0":0},', ...
      '{"kind":"clutch","a":1,"b":2,"Fc":5,"vEps":0.001},', ...
      '{"kind":"speedSensor","node":1,"outPort":0},', ...
      '{"kind":"speedSensor","node":2,"outPort":1}]}},', ...
  '{"id":"tw1","type":"toWorkspace","inputs":1,"outputs":0,"params":{"VariableName":"w1"}},', ...
  '{"id":"tw2","type":"toWorkspace","inputs":1,"outputs":0,"params":{"VariableName":"w2"}}],', ...
  '"connections":[', ...
    '{"from":"isl","to":"tw1","fromIndex":0,"toIndex":0},', ...
    '{"from":"isl","to":"tw2","fromIndex":1,"toIndex":0}],', ...
  '"solver":"dae","runtime":8.0,"sampleTime":0.02}'];
out = sim(me_write(clu, 'test_nflow_mech_clutch'));
lg = out.logsout; nms = {lg.name};
w1 = lg(find(strcmp(nms, 'w1'), 1)).values(:);
w2 = lg(find(strcmp(nms, 'w2'), 1)).values(:);
mom = 1 * w1 + 2 * w2; % total momentum, conserved
assert_istrue(max(abs(mom - 10)) < 5e-2);
assert_istrue(abs(w1(end) - 10 / 3) < 0.1); % both reach the common speed
assert_istrue(abs(w2(end) - 10 / 3) < 0.1);
assert_istrue(abs(w1(end) - w2(end)) < 0.05); % stuck together
