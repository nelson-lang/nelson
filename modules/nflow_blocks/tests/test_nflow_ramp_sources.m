% Ramp sources RampVoltage / RampCurrent (Coselica RampVoltage / RampCurrent):
% v = Slope (t - StartTime) for t >= StartTime. Delivered via the waveform
% expansion pre-pass (causal ramp -> SignalVoltage / SignalCurrent), no engine
% change. The value is continuous (StartTime = 0 gives a pure linear ramp), so
% the variable-step DAE solver handles it without edge trouble.
%=============================================================================
% <--SEQUENTIAL TEST REQUIRED-->
%=============================================================================
% A RampVoltage of slope 2 V/s directly across a voltage sensor: at t the reading
% must equal 2 t. Check the final sample near t = 1 s reads about 2 V.
d = ['{"version":"1.0.0","format":"nflow-2","name":"Ramp","blocks":[', ...
  '{"id":"V1","type":"RampVoltage","params":{"Slope":2,"StartTime":0}},', ...
  '{"id":"R1","type":"Resistor","params":{"R":10}},', ...
  '{"id":"G","type":"Ground","params":{}},', ...
  '{"id":"VS","type":"VoltageSensor","params":{}},', ...
  '{"id":"sc","type":"scope","inputs":1,"outputs":0,"params":{}}],', ...
  '"connections":[{"from":"VS","to":"sc","fromIndex":0,"toIndex":0}],', ...
  '"physicalWires":[{"pins":["V1.p","R1.p","VS.p"]},', ...
  '{"pins":["V1.n","R1.n","VS.n","G.p"]}],', ...
  '"solver":"dae","runtime":1.0,"sampleTime":0.05}'];
r = jsondecode(__nflow_simulate__(NFlow.internal.acausalExpand(d)));
assert_isequal(r.status, 'done');
v_end = r.scopes(1).series(end);
assert_istrue(abs(v_end - 2.0) < 0.2); % v(1 s) ~ 2 V (slope 2)
% and monotonically increasing across the run
s = r.scopes(1).series;
assert_istrue(s(end) > s(1) + 1.5);
%=============================================================================
% RampCurrent of slope 1 A/s into a 5-ohm resistor: the sensed voltage is
% i R = 5 t, so near t = 1 s the reading is about 5 V.
d2 = ['{"version":"1.0.0","format":"nflow-2","name":"RampI","blocks":[', ...
  '{"id":"I1","type":"RampCurrent","params":{"Slope":1,"StartTime":0}},', ...
  '{"id":"R1","type":"Resistor","params":{"R":5}},', ...
  '{"id":"G","type":"Ground","params":{}},', ...
  '{"id":"VS","type":"VoltageSensor","params":{}},', ...
  '{"id":"sc","type":"scope","inputs":1,"outputs":0,"params":{}}],', ...
  '"connections":[{"from":"VS","to":"sc","fromIndex":0,"toIndex":0}],', ...
  '"physicalWires":[{"pins":["I1.p","R1.p","VS.p"]},', ...
  '{"pins":["I1.n","R1.n","VS.n","G.p"]}],', ...
  '"solver":"dae","runtime":1.0,"sampleTime":0.05}'];
r = jsondecode(__nflow_simulate__(NFlow.internal.acausalExpand(d2)));
assert_isequal(r.status, 'done');
assert_istrue(abs(abs(r.scopes(1).series(end)) - 5.0) < 0.5);
