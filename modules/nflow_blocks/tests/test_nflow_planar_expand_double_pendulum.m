% <--WEIGHT 8-->
% Double pendulum authored the palette way (body-to-body PlanarRevolute):
% two uniform rods (m = 1, I = 1/12) each with "prox" (-0.5,0) and "dist"
% (0.5,0) frames. Rod 0's prox is pinned to the world; rod 0's dist to rod
% 1's prox. Released horizontal; ideal joints conserve energy (E(0) = 0).
Ir = 1 / 12;
frA = struct('prox', [-0.5, 0], 'dist', [0.5, 0]);
d2 = struct();
d2.blocks = {...
  struct('id', 'wld', 'type', 'PlanarWorld', 'params', struct('gravity', 9.81)), ...
  struct('id', 'r0', 'type', 'PlanarBody', 'params', struct('m', 1, 'I', Ir, ...
         'x0', 0.5, 'y0', 0, 'phi0', 0, 'frames', frA)), ...
  struct('id', 'r1', 'type', 'PlanarBody', 'params', struct('m', 1, 'I', Ir, ...
         'x0', 1.5, 'y0', 0, 'phi0', 0, 'frames', frA)), ...
  struct('id', 'j0', 'type', 'PlanarRevolute', 'params', struct()), ...
  struct('id', 'j1', 'type', 'PlanarRevolute', 'params', struct()), ...
  struct('id', 'sy0', 'type', 'PlanarPositionSensor', 'params', struct('axis', 'y')), ...
  struct('id', 'sy1', 'type', 'PlanarPositionSensor', 'params', struct('axis', 'y')), ...
  struct('id', 'sw0', 'type', 'PlanarVelocitySensor', 'params', struct('axis', 'omega')), ...
  struct('id', 'sw1', 'type', 'PlanarVelocitySensor', 'params', struct('axis', 'omega')), ...
  struct('id', 'svx0', 'type', 'PlanarVelocitySensor', 'params', struct('axis', 'x')), ...
  struct('id', 'svy0', 'type', 'PlanarVelocitySensor', 'params', struct('axis', 'y')), ...
  struct('id', 'svx1', 'type', 'PlanarVelocitySensor', 'params', struct('axis', 'x')), ...
  struct('id', 'svy1', 'type', 'PlanarVelocitySensor', 'params', struct('axis', 'y'))};
tws = {'sy0', 'Y0'; 'sy1', 'Y1'; 'sw0', 'W0'; 'sw1', 'W1'; ...
       'svx0', 'VX0'; 'svy0', 'VY0'; 'svx1', 'VX1'; 'svy1', 'VY1'};
for k = 1:size(tws, 1)
  d2.blocks{end + 1} = struct('id', ['t', tws{k, 1}], 'type', 'toWorkspace', ...
    'inputs', 1, 'outputs', 0, 'params', struct('VariableName', tws{k, 2}));
end
d2.physicalWires = {...
  struct('pins', {{'wld.frame', 'j0.a'}}), ...
  struct('pins', {{'j0.b', 'r0.prox'}}), ...
  struct('pins', {{'r0.dist', 'j1.a'}}), ...
  struct('pins', {{'j1.b', 'r1.prox'}}), ...
  struct('pins', {{'r0.com', 'sy0.a', 'sw0.a', 'svx0.a', 'svy0.a'}}), ...
  struct('pins', {{'r1.com', 'sy1.a', 'sw1.a', 'svx1.a', 'svy1.a'}})};
d2.connections = {};
for k = 1:size(tws, 1)
  d2.connections{end + 1} = struct('from', tws{k, 1}, 'to', ['t', tws{k, 1}], ...
    'fromIndex', 0, 'toIndex', 0);
end
d2.solver = 'dae'; d2.runtime = 2.0; d2.sampleTime = 0.01;
out = sim(nflow_blocks_write_json(d2, 'test_planar_expand_double'));
lg = out.logsout; nms = {lg.name};
gv = @(nm) lg(find(strcmp(nms, nm), 1)).values;
Y0 = gv('Y0'); Y1 = gv('Y1'); W0 = gv('W0'); W1 = gv('W1');
VX0 = gv('VX0'); VY0 = gv('VY0'); VX1 = gv('VX1'); VY1 = gv('VY1');
E = 0.5 * (VX0(:) .^ 2 + VY0(:) .^ 2) + 0.5 * Ir * W0(:) .^ 2 ...
  + 0.5 * (VX1(:) .^ 2 + VY1(:) .^ 2) + 0.5 * Ir * W1(:) .^ 2 ...
  + 9.81 * Y0(:) + 9.81 * Y1(:);
assert_istrue(max(abs(E)) < 5e-2);
