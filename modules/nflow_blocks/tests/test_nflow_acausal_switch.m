% Acausal palette N6 (events, tier-C starter): the ideal switch. Control > 0.5
% closes the switch (short); otherwise it opens (i = 0). Two static checks
% pin the two modes; the control is a signal input driven by a constant block.
%=============================================================================
function p = sw_write(json, stem)
  p = [tempname(), '.nflow'];
  fid = fopen(p, 'w'); fwrite(fid, json); fclose(fid);
end
%=============================================================================
function j = switched_rc(ctrlValue, ic)
  % V(1) - switch(1-2, control) - R(1) - C(1F, ic) - ground, voltmeter on C.
  j = ['{"blocks":[', ...
    '{"id":"ctl","type":"constant","inputs":0,"outputs":1,"params":{"Value":', ...
      sprintf('%.15g', ctrlValue), '}},', ...
    '{"id":"isl","type":"physicalIsland","inputs":1,"outputs":1,"params":{', ...
      '"domain":"electrical","nodes":4,"components":[', ...
        '{"kind":"vsource","a":1,"b":0,"V":1},', ...
        '{"kind":"switch","a":1,"b":3,"port":0},', ...
        '{"kind":"resistor","a":3,"b":2,"R":1},', ...
        sprintf('{"kind":"capacitor","a":2,"b":0,"C":1,"ic":%.15g},', ic), ...
        '{"kind":"voltageSensor","a":2,"b":0,"outPort":0}]}},', ...
    '{"id":"tw","type":"toWorkspace","inputs":1,"outputs":0,"params":{"VariableName":"vc"}}],', ...
    '"connections":[', ...
      '{"from":"ctl","to":"isl","fromIndex":0,"toIndex":0},', ...
      '{"from":"isl","to":"tw","fromIndex":0,"toIndex":0}],', ...
    '"solver":"dae","runtime":3.0,"sampleTime":0.1}'];
end
%=============================================================================
% Closed (control = 1): the RC charges from 0 toward the source, vc = 1 - e^{-t}.
out = sim(sw_write(switched_rc(1, 0), 'test_nflow_switch_closed'));
lg = out.logsout; nms = {lg.name};
vc = lg(find(strcmp(nms, 'vc'), 1)).values;
t = linspace(0, 3, numel(vc))';
assert_istrue(max(abs(vc(:) - (1 - exp(-t)))) < 1e-3);
%=============================================================================
% Open (control = 0): the source is disconnected, so the capacitor holds its
% initial charge (ic = 0.5) for all time.
out = sim(sw_write(switched_rc(0, 0.5), 'test_nflow_switch_open'));
lg = out.logsout; nms = {lg.name};
vc = lg(find(strcmp(nms, 'vc'), 1)).values;
assert_istrue(max(abs(vc(:) - 0.5)) < 1e-4);
%=============================================================================
% Dynamic control by a CONTINUOUS signal: a ramp (slope 1) crosses the 0.5
% threshold at t = 0.5, closing the switch; the RC (R = C = 1, ic = 0) then
% charges as 1 - exp(-(t - 0.5)). The switch control threshold is a
% zero-crossing surface, so the DAE stops and reinitialises at the flip instead
% of failing to step across the topology change.
mdyn = ['{"blocks":[', ...
  '{"id":"ctl","type":"ramp","inputs":0,"outputs":1,"params":{"slope":1}},', ...
  '{"id":"isl","type":"physicalIsland","inputs":1,"outputs":1,"params":{', ...
    '"domain":"electrical","nodes":4,"components":[', ...
      '{"kind":"vsource","a":1,"b":0,"V":1},', ...
      '{"kind":"switch","a":1,"b":3,"port":0},', ...
      '{"kind":"resistor","a":3,"b":2,"R":1},', ...
      '{"kind":"capacitor","a":2,"b":0,"C":1,"ic":0},', ...
      '{"kind":"voltageSensor","a":2,"b":0,"outPort":0}]}},', ...
  '{"id":"tw","type":"toWorkspace","inputs":1,"outputs":0,"params":{"VariableName":"vc"}}],', ...
  '"connections":[', ...
    '{"from":"ctl","to":"isl","fromIndex":0,"toIndex":0},', ...
    '{"from":"isl","to":"tw","fromIndex":0,"toIndex":0}],', ...
  '"solver":"dae","runtime":3.0,"sampleTime":0.02}'];
out = sim(sw_write(mdyn, 'test_nflow_switch_dyn'));
lg = out.logsout; nms = {lg.name};
vc = lg(find(strcmp(nms, 'vc'), 1)).values;
t = linspace(0, 3, numel(vc))';
ref = (t > 0.5) .* (1 - exp(-(t - 0.5)));
assert_istrue(max(abs(vc(:) - ref)) < 5e-3);
