%=============================================================================
% 7) Ideal op-amp non-inverting amplifier: Vin=1 at in+, feedback Rf(1)/Rg(1)
%    from out to in- to ground. Vout = Vin (1 + Rf/Rg) = 2 V.
%    Nodes: 1 = Vin / in+, 2 = in-, 3 = out.
oa = ['{"blocks":[', ...
  '{"id":"isl","type":"physicalIsland","inputs":0,"outputs":1,"params":{', ...
    '"domain":"electrical","nodes":4,"components":[', ...
      '{"kind":"vsource","a":1,"b":0,"V":1},', ...
      '{"kind":"opAmp","a":1,"b":2,"c":3},', ...
      '{"kind":"resistor","a":3,"b":2,"R":1},', ...        % Rf
      '{"kind":"resistor","a":2,"b":0,"R":1},', ...        % Rg
      '{"kind":"voltageSensor","a":3,"b":0,"outPort":0}]}},', ...
  '{"id":"tw","type":"toWorkspace","inputs":1,"outputs":0,"params":{"VariableName":"vo"}}],', ...
