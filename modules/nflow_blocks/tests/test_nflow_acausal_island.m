% Acausal palette N2: the native physicalIsland block assembles an electrical
% netlist and feeds the DAE (IDAS) solver an MNA residual over its own mixed
% differential/algebraic state slice. End-to-end analytic checks, matching the
% N1 `.m` lowering (NFlow.internal.acausalLower) but through the single C++ block.
%=============================================================================
function p = isl_write(json, stem)
  p = [tempname(), '.nflow'];
  fid = fopen(p, 'w'); fwrite(fid, json); fclose(fid);
end
%=============================================================================
% 1) RC charging circuit: V(1V, node1-0) - R(1, node1-node2) - C(1F, node2-0).
%    Ammeter is the vsource branch current i(t) = e^{-t}; v_C(t) = 1 - e^{-t}.
%    The block has 0 inputs and 2 outputs: [vc (voltageSensor), i (curr via
%    a currentSensor in series)]. Series ammeter: split node1 into 1 (source)
%    and 3 (post-ammeter), ammeter between them.
rc = ['{"blocks":[', ...
  '{"id":"isl","type":"physicalIsland","inputs":0,"outputs":2,"params":{', ...
    '"domain":"electrical","nodes":4,"components":[', ...
      '{"kind":"vsource","a":1,"b":0,"V":1},', ...
      '{"kind":"currentSensor","a":1,"b":3,"outPort":1},', ...
      '{"kind":"resistor","a":3,"b":2,"R":1},', ...
      '{"kind":"capacitor","a":2,"b":0,"C":1,"ic":0},', ...
      '{"kind":"voltageSensor","a":2,"b":0,"outPort":0}]}},', ...
  '{"id":"twvc","type":"toWorkspace","inputs":1,"outputs":0,"params":{"VariableName":"vc"}},', ...
  '{"id":"twi","type":"toWorkspace","inputs":1,"outputs":0,"params":{"VariableName":"i"}}],', ...
  '"connections":[', ...
    '{"from":"isl","to":"twvc","fromIndex":0,"toIndex":0},', ...
    '{"from":"isl","to":"twi","fromIndex":1,"toIndex":0}],', ...
  '"solver":"dae","runtime":1.0,"sampleTime":0.1}'];
out = sim(isl_write(rc, 'test_nflow_island_rc'));
lg = out.logsout;
nms = {lg.name};
vc = lg(find(strcmp(nms, 'vc'), 1)).values;
ii = lg(find(strcmp(nms, 'i'), 1)).values;
t = linspace(0, 1, numel(vc))';
assert_istrue(max(abs(vc(:) - (1 - exp(-t)))) < 1e-4);
assert_istrue(max(abs(ii(:) - exp(-t))) < 1e-4);
%=============================================================================
% 2) Series RLC step (R=1, L=1, C=1, V=1): v_C(t) = 1 - e^{-t/2}(cos(wd t) +
%    (1/sqrt3) sin(wd t)), wd = sqrt(3)/2. Nodes: 1 source, 2 R|L, 3 L|C.
rlc = ['{"blocks":[', ...
  '{"id":"isl","type":"physicalIsland","inputs":0,"outputs":1,"params":{', ...
    '"domain":"electrical","nodes":4,"components":[', ...
      '{"kind":"vsource","a":1,"b":0,"V":1},', ...
      '{"kind":"resistor","a":1,"b":2,"R":1},', ...
      '{"kind":"inductor","a":2,"b":3,"L":1,"ic":0},', ...
      '{"kind":"capacitor","a":3,"b":0,"C":1,"ic":0},', ...
      '{"kind":"voltageSensor","a":3,"b":0,"outPort":0}]}},', ...
  '{"id":"twvc","type":"toWorkspace","inputs":1,"outputs":0,"params":{"VariableName":"vc"}}],', ...
  '"connections":[{"from":"isl","to":"twvc","fromIndex":0,"toIndex":0}],', ...
  '"solver":"dae","runtime":5.0,"sampleTime":0.1}'];
out = sim(isl_write(rlc, 'test_nflow_island_rlc'));
lg = out.logsout;
nms = {lg.name};
vc = lg(find(strcmp(nms, 'vc'), 1)).values;
t = linspace(0, 5, numel(vc))';
wd = sqrt(3) / 2;
vref = 1 - exp(-t / 2) .* (cos(wd * t) + (1 / sqrt(3)) * sin(wd * t));
assert_istrue(max(abs(vc(:) - vref)) < 5e-4);
%=============================================================================
% 3) Signal-driven source: a sine voltage sin(2 pi t) across R(2)+C(0.5) reads
%    the block's input port 0. Cross-check the native island against the N1 `.m`
%    lowering is done separately; here assert the RC low-pass gain/lag numerically
%    against an independent ode45 reference of C v' = (u - v)/R.
u = @(tt) sin(2 * pi * tt);
R = 2; C = 0.5;
odefun = @(tt, v)(u(tt) - v) / (R * C);
[tref, vrefode] = ode45(odefun, [0 2], 0);
drv = ['{"blocks":[', ...
  '{"id":"src","type":"sine","inputs":0,"outputs":1,"params":{"Amplitude":1,"Frequency":1,"Phase":0,"Bias":0}},', ...
  '{"id":"isl","type":"physicalIsland","inputs":1,"outputs":1,"params":{', ...
    '"domain":"electrical","nodes":3,"components":[', ...
      '{"kind":"vsource","a":1,"b":0,"port":0},', ...
      '{"kind":"resistor","a":1,"b":2,"R":2},', ...
      '{"kind":"capacitor","a":2,"b":0,"C":0.5,"ic":0},', ...
      '{"kind":"voltageSensor","a":2,"b":0,"outPort":0}]}},', ...
  '{"id":"twvc","type":"toWorkspace","inputs":1,"outputs":0,"params":{"VariableName":"vc"}}],', ...
  '"connections":[', ...
    '{"from":"src","to":"isl","fromIndex":0,"toIndex":0},', ...
    '{"from":"isl","to":"twvc","fromIndex":0,"toIndex":0}],', ...
  '"solver":"dae","runtime":2.0,"sampleTime":0.05}'];
out = sim(isl_write(drv, 'test_nflow_island_driven'));
lg = out.logsout;
nms = {lg.name};
vc = lg(find(strcmp(nms, 'vc'), 1)).values;
t = linspace(0, 2, numel(vc))';
vcheck = interp1(tref, vrefode, t);
assert_istrue(max(abs(vc(:) - vcheck)) < 5e-3);
%=============================================================================
% 4) VCVS voltage amplifier (gain 3): V(1V) at node1; VCVS output node2 driven
%    by 3*(e1-0); loaded by R(1k) to ground. Steady output e2 = 3 V. Ammeter-free
%    static check through a voltmeter on node2.
amp = ['{"blocks":[', ...
  '{"id":"isl","type":"physicalIsland","inputs":0,"outputs":1,"params":{', ...
    '"domain":"electrical","nodes":3,"components":[', ...
      '{"kind":"vsource","a":1,"b":0,"V":1},', ...
      '{"kind":"vcvs","a":2,"b":0,"c":1,"d":0,"gain":3},', ...
      '{"kind":"resistor","a":2,"b":0,"R":1000},', ...
      '{"kind":"voltageSensor","a":2,"b":0,"outPort":0}]}},', ...
  '{"id":"twvo","type":"toWorkspace","inputs":1,"outputs":0,"params":{"VariableName":"vo"}}],', ...
  '"connections":[{"from":"isl","to":"twvo","fromIndex":0,"toIndex":0}],', ...
  '"solver":"dae","runtime":0.5,"sampleTime":0.1}'];
out = sim(isl_write(amp, 'test_nflow_island_vcvs'));
lg = out.logsout; nms = {lg.name};
vo = lg(find(strcmp(nms, 'vo'), 1)).values;
assert_istrue(max(abs(vo(:) - 3.0)) < 1e-6);
%=============================================================================
% 5) Ideal transformer (n=2): primary V(1V) at node1, transformer primary
%    (1-0) secondary (2-0), resistor load R(1) on secondary. Steady secondary
%    voltage v2 = v1/n = 0.5 V (constant, purely algebraic island).
xf = ['{"blocks":[', ...
  '{"id":"isl","type":"physicalIsland","inputs":0,"outputs":1,"params":{', ...
    '"domain":"electrical","nodes":3,"components":[', ...
      '{"kind":"vsource","a":1,"b":0,"V":1},', ...
      '{"kind":"transformer","a":1,"b":0,"c":2,"d":0,"n":2},', ...
      '{"kind":"resistor","a":2,"b":0,"R":1},', ...
      '{"kind":"voltageSensor","a":2,"b":0,"outPort":0}]}},', ...
  '{"id":"tw","type":"toWorkspace","inputs":1,"outputs":0,"params":{"VariableName":"v2"}}],', ...
  '"connections":[{"from":"isl","to":"tw","fromIndex":0,"toIndex":0}],', ...
  '"solver":"dae","runtime":0.5,"sampleTime":0.1}'];
