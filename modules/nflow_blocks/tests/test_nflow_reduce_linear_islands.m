% The acausal code-generation pre-pass: a LINEAR single-input /
% single-output electrical island is swapped for the equivalent reduced state-
% space block; a non-linear island and an island-free model are left untouched.
%=============================================================================
mkdiag = @(blk)['{"version":"1.0.0","format":"nflow-2","name":"M","blocks":[', ...
  '{"id":"u","type":"constant","inputs":0,"outputs":1,"params":{"Value":1}},', blk, ',', ...
  '{"id":"y","type":"labelSink","inputs":1,"outputs":1,', ...
  '"params":{"GotoTag":"y","isExternalPort":true}}],', ...
  '"connections":[{"from":"u","to":"blk","fromIndex":0,"toIndex":0},', ...
  '{"from":"blk","to":"y","fromIndex":0,"toIndex":0}],', ...
  '"solver":"ode4","runtime":10,"sampleTime":0.05}'];
%=============================================================================
% A linear RLC island is reduced to a state-space block.
rlc = ['{"id":"blk","type":"physicalIsland","inputs":1,"outputs":1,', ...
  '"x":300,"y":200,"rotation":0,"params":{', ...
  '"domain":"electrical","nodes":4,"components":[', ...
    '{"kind":"vsource","a":1,"b":0,"port":0},', ...
    '{"kind":"resistor","a":1,"b":2,"R":1},', ...
    '{"kind":"inductor","a":2,"b":3,"L":1,"ic":0},', ...
    '{"kind":"capacitor","a":3,"b":0,"C":1,"ic":0},', ...
    '{"kind":"voltageSensor","a":3,"b":0,"outPort":0}]}}'];
reduced = NFlow.internal.reduceLinearIslands(mkdiag(rlc));
assert_istrue(isempty(strfind(reduced, 'physicalIsland')));
assert_istrue(~isempty(strfind(reduced, '"stateSpace"')));
% The replacement keeps the block id and layout, and carries a 2x2 A with the
% RLC characteristic polynomial (s^2 + s + 1).
d = jsondecode(reduced);
ssb = [];
for i = 1:numel(d.blocks)
  if iscell(d.blocks); b = d.blocks{i}; else; b = d.blocks(i); end
  if strcmp(b.type, 'stateSpace'); ssb = b; end
end
assert_istrue(~isempty(ssb));
assert_isequal(ssb.id, 'blk');
A = reshape(ssb.params.A(:), 2, 2).'; % row-major 2x2
assert_isapprox(trace(A), -1, 1e-9);
assert_isapprox(det(A), 1, 1e-9);
%=============================================================================
% A non-linear island (a diode) is NOT reduced (left for the codegen reject).
diode = ['{"id":"blk","type":"physicalIsland","inputs":1,"outputs":1,"params":{', ...
  '"domain":"electrical","nodes":3,"components":[', ...
    '{"kind":"vsource","a":1,"b":0,"port":0},', ...
    '{"kind":"diode","a":1,"b":2,"Is":1e-9,"Vt":0.04},', ...
    '{"kind":"resistor","a":2,"b":0,"R":1000},', ...
    '{"kind":"voltageSensor","a":2,"b":0,"outPort":0}]}}'];
keep = NFlow.internal.reduceLinearIslands(mkdiag(diode));
assert_istrue(~isempty(strfind(keep, 'physicalIsland')));
assert_istrue(isempty(strfind(keep, '"stateSpace"')));
%=============================================================================
% A model with no island is returned unchanged.
plain = ['{"version":"1.0.0","format":"nflow-2","name":"P","blocks":[', ...
  '{"id":"k","type":"constant","inputs":0,"outputs":1,"params":{"Value":1}},', ...
  '{"id":"ig","type":"integrator","inputs":1,"outputs":1,"params":{}}],', ...
  '"connections":[{"from":"k","to":"ig","fromIndex":0,"toIndex":0}],', ...
  '"solver":"ode4","runtime":1,"sampleTime":0.1}'];
assert_isequal(NFlow.internal.reduceLinearIslands(plain), plain);
