% Signal-actuated friction brakes Brake (translational) / RotBrake (rotational),
% Coselica. Native mechanical-island kind brake: a Coulomb friction to ground
% whose peak force is set by the input signal, regularised by tanh (no stick-slip
% events) so the fixed-step ode4 handles it. Sim + RK4 C/Rust codegen.
%=============================================================================
% <--SEQUENTIAL TEST REQUIRED-->
%=============================================================================
% A 1 kg mass moving at 5 m/s is braked by a constant 10 N actuation: the friction
% opposes the motion and brings the mass to rest.
d = ['{"version":"1.0.0","format":"nflow-2","name":"BR","blocks":[', ...
  '{"id":"M","type":"Mass","params":{"m":1,"s0":0,"v0":5}},', ...
  '{"id":"K","type":"constant","outputs":1,"params":{"Value":10}},', ...
  '{"id":"B","type":"Brake","params":{"vEps":0.01}},', ...
  '{"id":"SS","type":"SpeedSensor","params":{}},', ...
  '{"id":"sc","type":"scope","inputs":1,"outputs":0,"params":{}}],', ...
  '"connections":[{"from":"K","to":"B","fromIndex":0,"toIndex":0},', ...
  '{"from":"SS","to":"sc","fromIndex":0,"toIndex":0}],', ...
  '"physicalWires":[{"pins":["M.flange","B.flange","SS.flange"]}],', ...
  '"solver":"ode4","runtime":2.0,"sampleTime":0.02}'];
r = jsondecode(__nflow_simulate__(NFlow.internal.acausalExpand(d)));
assert_isequal(r.status, 'done');
v = r.scopes(1).series;
assert_istrue(v(1) > 4.5); % starts near 5 m/s
assert_istrue(abs(v(end)) < 0.2); % braked to rest
%=============================================================================
% With no actuation (brake force 0) the mass coasts at its initial speed.
d2 = strrep(d, '"Value":10', '"Value":0');
r2 = jsondecode(__nflow_simulate__(NFlow.internal.acausalExpand(d2)));
assert_isequal(r2.status, 'done');
assert_istrue(abs(r2.scopes(1).series(end) - 5) < 0.1); % coasts at 5 m/s
%=============================================================================
% Rotational RotBrake: a 1 kg.m^2 inertia spinning at 8 rad/s is braked by a
% constant 6 N.m actuation and stops.
d3 = ['{"version":"1.0.0","format":"nflow-2","name":"RB","blocks":[', ...
  '{"id":"J","type":"Inertia","params":{"J":1,"phi0":0,"w0":8}},', ...
  '{"id":"K","type":"constant","outputs":1,"params":{"Value":6}},', ...
  '{"id":"B","type":"RotBrake","params":{"w_eps":0.01}},', ...
  '{"id":"WS","type":"RotSpeedSensor","params":{}},', ...
  '{"id":"sc","type":"scope","inputs":1,"outputs":0,"params":{}}],', ...
  '"connections":[{"from":"K","to":"B","fromIndex":0,"toIndex":0},', ...
  '{"from":"WS","to":"sc","fromIndex":0,"toIndex":0}],', ...
  '"physicalWires":[{"pins":["J.flange","B.flange","WS.flange"]}],', ...
  '"solver":"ode4","runtime":3.0,"sampleTime":0.02}'];
r3 = jsondecode(__nflow_simulate__(NFlow.internal.acausalExpand(d3)));
assert_isequal(r3.status, 'done');
assert_istrue(r3.scopes(1).series(1) > 7); % starts near 8 rad/s
assert_istrue(abs(r3.scopes(1).series(end)) < 0.2); % braked to rest
