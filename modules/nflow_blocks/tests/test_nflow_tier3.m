% Niche blocks: logicalOperator, wrapToZero, polynomial.
% Row = {type, params-struct, inputs-cell, expected}. Compact (low-whitespace)
% form on purpose. A single input => unary block; two inputs => binary block.
%=============================================================================
cases = {...
  {'logicalOperator', struct('Operator', 'AND'), {1, 1}, 1}, ...
  {'logicalOperator', struct('Operator', 'AND'), {1, 0}, 0}, ...
  {'logicalOperator', struct('Operator', 'OR'), {0, 1}, 1}, ...
  {'logicalOperator', struct('Operator', 'NAND'), {1, 1}, 0}, ...
  {'logicalOperator', struct('Operator', 'NOR'), {0, 0}, 1}, ...
  {'logicalOperator', struct('Operator', 'XOR'), {1, 0}, 1}, ...
  {'logicalOperator', struct('Operator', 'XNOR'), {1, 1}, 1}, ...
  {'logicalOperator', struct('Operator', 'NOT'), {0}, 1}, ...
  {'logicalOperator', struct('Operator', 'NOT'), {5}, 0}, ...
  {'wrapToZero', struct('Threshold', 5), {3}, 3}, ...
  {'wrapToZero', struct('Threshold', 5), {7}, 0}, ...
  {'wrapToZero', struct('Threshold', 5), {5}, 5}, ...
  {'wrapToZero', struct('Threshold', 5), {5.001}, 0}, ...
  {'polynomial', struct('Coefficients', [1 -2 3]), {2}, 3}, ...
  {'polynomial', struct('Coefficients', [2 0 -1]), {3}, 17}, ...
  {'polynomial', struct('Coefficients', [4]), {10}, 4}};
for k = 1:numel(cases)
  c = cases{k}; type = c{1}; params = c{2}; ins = c{3}; expected = c{4}; n = numel(ins);
  blocks = {};
  conns = {};
  for j = 1:n
    blocks{end + 1} = struct('id', ['c' int2str(j)], 'type', 'constant', 'inputs', 0, 'outputs', 1, 'params', struct('Value', ins{j}));
    conns{end + 1} = struct('from', ['c' int2str(j)], 'to', 'g', 'fromIndex', 0, 'toIndex', j - 1);
  end
  blocks{end + 1} = struct('id', 'g', 'type', type, 'inputs', n, 'outputs', 1, 'params', params);
  blocks{end + 1} = struct('id', 'w', 'type', 'toWorkspace', 'inputs', 1, 'outputs', 0, 'params', struct('VariableName', 't3_out', 'SaveFormat', 'Array', 'Decimation', 1, 'MaxDataPoints', 'inf'));
  conns{end + 1} = struct('from', 'g', 'to', 'w', 'fromIndex', 0, 'toIndex', 0);
  d = struct(); d.blocks = blocks; d.connections = conns;
  d.sampleTime = 0.1; d.duration = 0.2; d.solver = 'discrete'; d.variables = struct();
  res = jsondecode(__nflow_simulate__(jsonencode(d)));
  assert_isequal(res.status, 'done');
  y = evalin('base', 't3_out'); y = y(:)';
  assert_isequal(y(1), expected);
end
