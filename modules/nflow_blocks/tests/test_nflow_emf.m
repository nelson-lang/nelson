% <--WEIGHT 2-->
% Electro-mechanical converter EMF (Coselica EMF): couples an electrical port to
% a rotational flange with back-emf v = k w and motor torque tau = k i. Second
% cross-domain block, delivered by the NFlow.internal.acausalExpand pre-pass (ax_expand_emf)
% with no engine change: a SignalVoltage(= k w) in series with a CurrentSensor on
% the electrical side, a RotSpeedSensor and a Torque on the flange, bridged
% through the causal signal layer. The two-way loop is broken by the inertia's
% speed state.
%
% NOTE the DAE solver is required: the electrical DAE island sits next to a
% mechanical ODE island, and ode4 does not solve the electrical algebraic part.
%=============================================================================
% <--SEQUENTIAL TEST REQUIRED-->
%=============================================================================
% DC motor spin-up: a 10 V supply through a 1-ohm armature resistance drives an
% EMF (k = 1) turning a 0.1 kg.m^2 inertia. The back-emf limits the no-load speed
% to w -> V/k = 10 rad/s (the current, i = (V - k w)/R, decays to zero), with the
% first-order time constant J R / k^2 = 0.1 s.
d = ['{"version":"1.0.0","format":"nflow-2","name":"DCM","blocks":[', ...
  '{"id":"V1","type":"ConstantVoltage","params":{"V":10}},', ...
  '{"id":"R1","type":"Resistor","params":{"R":1}},', ...
  '{"id":"M","type":"EMF","params":{"k":1}},', ...
  '{"id":"G","type":"Ground","params":{}},', ...
  '{"id":"J1","type":"Inertia","params":{"J":0.1}},', ...
  '{"id":"WS","type":"RotSpeedSensor","params":{}},', ...
  '{"id":"sc","type":"scope","inputs":1,"outputs":0,"params":{}}],', ...
  '"connections":[{"from":"WS","to":"sc","fromIndex":0,"toIndex":0}],', ...
  '"physicalWires":[{"pins":["V1.p","R1.p"]},', ...
  '{"pins":["R1.n","M.p"]},', ...
  '{"pins":["V1.n","M.n","G.p"]},', ...
  '{"pins":["M.flange","J1.flange","WS.flange"]}],', ...
  '"solver":"dae","runtime":1.0,"sampleTime":0.1}'];
r = jsondecode(__nflow_simulate__(NFlow.internal.acausalExpand(d)));
assert_isequal(r.status, 'done');
w = r.scopes(1).series;
assert_istrue(abs(w(end) - 10) < 0.5); % settles at V/k = 10
assert_istrue(abs(w(2) - 6.32) < 1.0); % ~63% after one time constant
assert_istrue(w(1) < 1.0); % started from rest
%=============================================================================
% Halving k halves the electrical-to-mechanical coupling, so the no-load speed
% w -> V/k doubles (heads toward 20 rad/s; the time constant J R / k^2 = 0.4 s
% grows too, so at 1 s it is still climbing past the k = 1 steady speed of 10).
d2 = strrep(d, '"k":1', '"k":0.5');
r2 = jsondecode(__nflow_simulate__(NFlow.internal.acausalExpand(d2)));
assert_isequal(r2.status, 'done');
assert_istrue(r2.scopes(1).series(end) > 16); % well above the k = 1 speed of 10
%=============================================================================
% TranslationalEMF is the linear counterpart (back-emf v = k v_flange, force
% F = k i): the same 10 V / 1 ohm drive on a 0.1 kg mass settles at v -> V/k = 10.
d3 = ['{"version":"1.0.0","format":"nflow-2","name":"LM","blocks":[', ...
  '{"id":"V1","type":"ConstantVoltage","params":{"V":10}},', ...
  '{"id":"R1","type":"Resistor","params":{"R":1}},', ...
  '{"id":"M","type":"TranslationalEMF","params":{"k":1}},', ...
  '{"id":"G","type":"Ground","params":{}},', ...
  '{"id":"MS","type":"Mass","params":{"m":0.1}},', ...
  '{"id":"VS","type":"SpeedSensor","params":{}},', ...
  '{"id":"sc","type":"scope","inputs":1,"outputs":0,"params":{}}],', ...
  '"connections":[{"from":"VS","to":"sc","fromIndex":0,"toIndex":0}],', ...
  '"physicalWires":[{"pins":["V1.p","R1.p"]},{"pins":["R1.n","M.p"]},', ...
  '{"pins":["V1.n","M.n","G.p"]},{"pins":["M.flange","MS.flange","VS.flange"]}],', ...
  '"solver":"dae","runtime":1.0,"sampleTime":0.1}'];
r3 = jsondecode(__nflow_simulate__(NFlow.internal.acausalExpand(d3)));
assert_isequal(r3.status, 'done');
assert_istrue(abs(r3.scopes(1).series(end) - 10) < 0.5); % linear motor settles at V/k
