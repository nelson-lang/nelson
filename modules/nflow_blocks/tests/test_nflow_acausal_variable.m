% Acausal palette: signal-driven variable components (VariableResistor /
% VariableConductor) whose value is set by an input signal each step.
%=============================================================================
function p = va_write(json, stem)
  p = [tempname(), '.nflow'];
  fid = fopen(p, 'w'); fwrite(fid, json); fclose(fid);
end
%=============================================================================
% Divider: V(1) - variableResistor(R from signal 2) - load R(2) - ground.
% e2 = V * Rload / (R + Rload) = 1 * 2 / (2 + 2) = 0.5 V.
m = ['{"blocks":[', ...
  '{"id":"rc","type":"constant","inputs":0,"outputs":1,"params":{"Value":2}},', ...
  '{"id":"isl","type":"physicalIsland","inputs":1,"outputs":1,"params":{', ...
    '"domain":"electrical","nodes":3,"components":[', ...
      '{"kind":"vsource","a":1,"b":0,"V":1},', ...
      '{"kind":"variableResistor","a":1,"b":2,"port":0},', ...
      '{"kind":"resistor","a":2,"b":0,"R":2},', ...
      '{"kind":"voltageSensor","a":2,"b":0,"outPort":0}]}},', ...
  '{"id":"tw","type":"toWorkspace","inputs":1,"outputs":0,"params":{"VariableName":"v2"}}],', ...
  '"connections":[', ...
    '{"from":"rc","to":"isl","fromIndex":0,"toIndex":0},', ...
    '{"from":"isl","to":"tw","fromIndex":0,"toIndex":0}],', ...
  '"solver":"dae","runtime":0.5,"sampleTime":0.1}'];
out = sim(va_write(m, 'test_nflow_var_divider'));
lg = out.logsout; nms = {lg.name};
v2 = lg(find(strcmp(nms, 'v2'), 1)).values;
assert_istrue(max(abs(v2(:) - 0.5)) < 1e-6);
%=============================================================================
% Time-varying: R = 1 + t (ramp), so e2 = 2 / (R + 2) = 2 / (3 + t).
% Check the endpoint at t = 0.5: e2 = 2 / 3.5.
mv = ['{"blocks":[', ...
  '{"id":"rc","type":"ramp","inputs":0,"outputs":1,"params":{"slope":1,"start":0}},', ...
  '{"id":"b","type":"bias","inputs":1,"outputs":1,"params":{"Bias":1}},', ...
  '{"id":"isl","type":"physicalIsland","inputs":1,"outputs":1,"params":{', ...
    '"domain":"electrical","nodes":3,"components":[', ...
      '{"kind":"vsource","a":1,"b":0,"V":1},', ...
      '{"kind":"variableResistor","a":1,"b":2,"port":0},', ...
      '{"kind":"resistor","a":2,"b":0,"R":2},', ...
      '{"kind":"voltageSensor","a":2,"b":0,"outPort":0}]}},', ...
  '{"id":"tw","type":"toWorkspace","inputs":1,"outputs":0,"params":{"VariableName":"v2"}}],', ...
  '"connections":[', ...
    '{"from":"rc","to":"b","fromIndex":0,"toIndex":0},', ...
    '{"from":"b","to":"isl","fromIndex":0,"toIndex":0},', ...
    '{"from":"isl","to":"tw","fromIndex":0,"toIndex":0}],', ...
  '"solver":"dae","runtime":0.5,"sampleTime":0.05}'];
out = sim(va_write(mv, 'test_nflow_var_ramp'));
lg = out.logsout; nms = {lg.name};
v2 = lg(find(strcmp(nms, 'v2'), 1)).values;
t = linspace(0, 0.5, numel(v2))';
assert_istrue(max(abs(v2(:) - 2 ./ (3 + t))) < 1e-4);
%=============================================================================
% VariableCapacitor with a CONSTANT C=1 must reproduce fixed-capacitor RC
% charging (validates the exact charge Q formulation): V(1) - R(1) - Cvar(1) -
% ground => vc = 1 - e^{-t}.
mc = ['{"blocks":[', ...
  '{"id":"cc","type":"constant","inputs":0,"outputs":1,"params":{"Value":1}},', ...
  '{"id":"isl","type":"physicalIsland","inputs":1,"outputs":1,"params":{', ...
    '"domain":"electrical","nodes":3,"components":[', ...
      '{"kind":"vsource","a":1,"b":0,"V":1},', ...
      '{"kind":"resistor","a":1,"b":2,"R":1},', ...
      '{"kind":"variableCapacitor","a":2,"b":0,"port":0,"ic":0},', ...
      '{"kind":"voltageSensor","a":2,"b":0,"outPort":0}]}},', ...
  '{"id":"tw","type":"toWorkspace","inputs":1,"outputs":0,"params":{"VariableName":"vc"}}],', ...
  '"connections":[', ...
    '{"from":"cc","to":"isl","fromIndex":0,"toIndex":0},', ...
    '{"from":"isl","to":"tw","fromIndex":0,"toIndex":0}],', ...
  '"solver":"dae","runtime":1.0,"sampleTime":0.05}'];
out = sim(va_write(mc, 'test_nflow_var_cap'));
lg = out.logsout; nms = {lg.name};
vc = lg(find(strcmp(nms, 'vc'), 1)).values;
t = linspace(0, 1, numel(vc))';
assert_istrue(max(abs(vc(:) - (1 - exp(-t)))) < 1e-3);
%=============================================================================
% VariableInductor with a CONSTANT L=1 must reproduce fixed-inductor RL current
% (validates the exact flux phi formulation): V(1) - ammeter - R(1) - Lvar(1) -
% ground => i = 1 - e^{-t}.
ml = ['{"blocks":[', ...
  '{"id":"lc","type":"constant","inputs":0,"outputs":1,"params":{"Value":1}},', ...
  '{"id":"isl","type":"physicalIsland","inputs":1,"outputs":1,"params":{', ...
    '"domain":"electrical","nodes":4,"components":[', ...
      '{"kind":"vsource","a":1,"b":0,"V":1},', ...
      '{"kind":"currentSensor","a":1,"b":3,"outPort":0},', ...
      '{"kind":"resistor","a":3,"b":2,"R":1},', ...
      '{"kind":"variableInductor","a":2,"b":0,"port":0,"ic":0}]}},', ...
  '{"id":"tw","type":"toWorkspace","inputs":1,"outputs":0,"params":{"VariableName":"i"}}],', ...
  '"connections":[', ...
    '{"from":"lc","to":"isl","fromIndex":0,"toIndex":0},', ...
    '{"from":"isl","to":"tw","fromIndex":0,"toIndex":0}],', ...
  '"solver":"dae","runtime":1.0,"sampleTime":0.05}'];
out = sim(va_write(ml, 'test_nflow_var_ind'));
lg = out.logsout; nms = {lg.name};
ii = lg(find(strcmp(nms, 'i'), 1)).values;
t = linspace(0, 1, numel(ii))';
assert_istrue(max(abs(ii(:) - (1 - exp(-t)))) < 1e-3);
