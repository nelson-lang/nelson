% Contact elements ElastoGap (translational) and ElastoBacklash (rotational),
% Coselica / Modelica. Native mechanical-island kinds elastoGap / backlash, both
% smooth/continuous (tanh-gated contact, branchless dead zone) so the fixed-step
% ode4 handles them without events. Sim + RK4 C/Rust codegen.
%=============================================================================
% <--SEQUENTIAL TEST REQUIRED-->
%=============================================================================
% ElastoGap: a mass at s0 = 0.5 (just at the gap edge) is pushed toward a wall by
% a constant force of 2 N. The one-sided contact spring (c = 100) stops it near
% s = s_rel0 - F/c = 0.48 instead of letting it fall through; damping (d = 5)
% settles the motion.
d = ['{"version":"1.0.0","format":"nflow-2","name":"EG","blocks":[', ...
  '{"id":"W","type":"Fixed","params":{"s0":0}},', ...
  '{"id":"M","type":"Mass","params":{"m":1,"s0":0.5,"v0":0}},', ...
  '{"id":"EG","type":"ElastoGap","params":{"c":100,"d":5,"s_rel0":0.5}},', ...
  '{"id":"F","type":"ConstantForce","params":{"F":-2}},', ...
  '{"id":"PS","type":"PositionSensor","params":{}},', ...
  '{"id":"sc","type":"scope","inputs":1,"outputs":0,"params":{}}],', ...
  '"connections":[{"from":"PS","to":"sc","fromIndex":0,"toIndex":0}],', ...
  '"physicalWires":[{"pins":["M.flange","EG.a","F.flange","PS.flange"]},', ...
  '{"pins":["W.flange","EG.b"]}],', ...
  '"solver":"ode4","runtime":4.0,"sampleTime":0.02}'];
r = jsondecode(__nflow_simulate__(NFlow.internal.acausalExpand(d)));
assert_isequal(r.status, 'done');
sfin = r.scopes(1).series(end);
assert_istrue(sfin > 0.40 && sfin < 0.50); % held by contact near 0.48
assert_istrue(min(r.scopes(1).series) > 0.35); % never falls through the wall
%=============================================================================
% Removing the contact, the same force makes the mass fall through well past the
% wall (position goes strongly negative), confirming the contact did the work.
d2 = strrep(d, '{"id":"EG","type":"ElastoGap","params":{"c":100,"d":5,"s_rel0":0.5}},', '');
d2 = strrep(d2, '"M.flange","EG.a","F.flange"', '"M.flange","F.flange"');
d2 = strrep(d2, ',{"pins":["W.flange","EG.b"]}', '');
r2 = jsondecode(__nflow_simulate__(NFlow.internal.acausalExpand(d2)));
assert_isequal(r2.status, 'done');
assert_istrue(r2.scopes(1).series(end) < -1); % no contact: falls through
%=============================================================================
% ElastoBacklash: a constant torque of 1 N.m on an inertia (J = 1) connected
% through a rotational backlash (stiffness c = 50, play b = 0.4 rad) to a fixed
% support. The inertia turns freely across the half-play (0.2 rad), then the
% elastic torque engages and it settles where c (phi - b/2) = tau, i.e. phi ~
% 0.2 + 1/50 = 0.22 rad.
d3 = ['{"version":"1.0.0","format":"nflow-2","name":"EB","blocks":[', ...
  '{"id":"S","type":"RotFixed","params":{"phi0":0}},', ...
  '{"id":"J","type":"Inertia","params":{"J":1,"phi0":0,"w0":0}},', ...
  '{"id":"EB","type":"ElastoBacklash","params":{"c":50,"b":0.4}},', ...
  '{"id":"T","type":"ConstantTorque","params":{"tau":1}},', ...
  '{"id":"D","type":"RotDamper","params":{"d":2}},', ...
  '{"id":"AS","type":"AngleSensor","params":{}},', ...
  '{"id":"sc","type":"scope","inputs":1,"outputs":0,"params":{}}],', ...
  '"connections":[{"from":"AS","to":"sc","fromIndex":0,"toIndex":0}],', ...
  '"physicalWires":[{"pins":["J.flange","EB.a","T.flange","D.a","AS.flange"]},', ...
  '{"pins":["S.flange","EB.b","D.b"]}],', ...
  '"solver":"ode4","runtime":8.0,"sampleTime":0.02}'];
r3 = jsondecode(__nflow_simulate__(NFlow.internal.acausalExpand(d3)));
assert_isequal(r3.status, 'done');
phifin = r3.scopes(1).series(end);
assert_istrue(phifin > 0.20 && phifin < 0.28); % engaged just past the half-play
