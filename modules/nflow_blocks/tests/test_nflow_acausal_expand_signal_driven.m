% <--WEIGHT 4-->
% Signal-driven source: a SignalVoltage component fed by a sine block, across
% R(2) + C(0.5), authored the GUI way. The expansion must rewire the sine ->
% component connection to the island's input port. Reference: ode45 of
% C v' = (u - v)/R with u = sin(2 pi t).
u = @(tt) sin(2 * pi * tt);
odef = @(tt, v)(u(tt) - v) / (2 * 0.5);
[tref, vref] = ode45(odef, [0 2], 0);
docD = struct();
docD.blocks = {...
  struct('id', 'SRC', 'type', 'sine', 'inputs', 0, 'outputs', 1, ...
    'params', struct('Amplitude', 1, 'Frequency', 1, 'Phase', 0, 'Bias', 0)), ...
  struct('id', 'V1', 'type', 'SignalVoltage', 'params', struct()), ...
  struct('id', 'R1', 'type', 'Resistor', 'params', struct('R', 2)), ...
  struct('id', 'C1', 'type', 'Capacitor', 'params', struct('C', 0.5, 'v0', 0)), ...
  struct('id', 'VS', 'type', 'VoltageSensor', 'params', struct()), ...
  struct('id', 'G', 'type', 'Ground', 'params', struct()), ...
  struct('id', 'tw', 'type', 'toWorkspace', 'inputs', 1, 'outputs', 0, 'params', struct('VariableName', 'vc'))};
docD.physicalWires = {...
  struct('pins', {{'V1.p', 'R1.p'}}), ...
  struct('pins', {{'R1.n', 'C1.p', 'VS.p'}}), ...
  struct('pins', {{'C1.n', 'V1.n', 'VS.n', 'G.p'}})};
docD.connections = {...
  struct('from', 'SRC', 'to', 'V1', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'VS', 'to', 'tw', 'fromIndex', 0, 'toIndex', 0)};
docD.solver = 'dae'; docD.runtime = 2.0; docD.sampleTime = 0.05;
out3 = sim(nflow_blocks_write_json(jsonencode(docD), 'test_nflow_expand_driven'));
lg3 = out3.logsout; nms3 = {lg3.name};
vc3 = lg3(find(strcmp(nms3, 'vc'), 1)).values;
t3 = linspace(0, 2, numel(vc3))';
assert_istrue(max(abs(vc3(:) - interp1(tref, vref, t3))) < 5e-3);
