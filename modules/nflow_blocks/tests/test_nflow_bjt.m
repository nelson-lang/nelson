% <--WEIGHT 2-->
% Bipolar transistors NPN / PNP (Coselica NPN / PNP): Ebers-Moll stateless
% three-terminal devices. Native physicalIsland kinds npn / pnp (nonlinear,
% embedded-Newton). Pins C (collector), B (base), E (emitter).
%=============================================================================
% <--SEQUENTIAL TEST REQUIRED-->
%=============================================================================
% NPN current mirror-of-sorts: a base current forced through a resistor from a
% supply biases the transistor on; the collector, tied to the supply through a
% large resistor, should be pulled well below the supply as the transistor sinks
% the amplified base current. We check that the collector node sits far below the
% 12 V rail (transistor conducting), not near it (transistor off).
d = ['{"version":"1.0.0","format":"nflow-2","name":"NPNamp","blocks":[', ...
  '{"id":"VCC","type":"ConstantVoltage","params":{"V":12}},', ...
  '{"id":"RB","type":"Resistor","params":{"R":100000}},', ...
  '{"id":"RC","type":"Resistor","params":{"R":1000}},', ...
  '{"id":"Q","type":"NPN","params":{"Is":1e-15,"Vt":0.025,"Bf":100,"Br":1}},', ...
  '{"id":"G","type":"Ground","params":{}},', ...
  '{"id":"VS","type":"VoltageSensor","params":{}},', ...
  '{"id":"sc","type":"scope","inputs":1,"outputs":0,"params":{}}],', ...
  '"connections":[{"from":"VS","to":"sc","fromIndex":0,"toIndex":0}],', ...
  '"physicalWires":[{"pins":["VCC.p","RB.p","RC.p"]},', ...
  '{"pins":["RB.n","Q.B"]},', ...
  '{"pins":["RC.n","Q.C","VS.p"]},', ...
  '{"pins":["VCC.n","Q.E","VS.n","G.p"]}],', ...
  '"solver":"dae","runtime":0.1,"sampleTime":0.02}'];
r = jsondecode(__nflow_simulate__(NFlow.internal.acausalExpand(d)));
assert_isequal(r.status, 'done');
vc = r.scopes(1).series(end); % collector-emitter voltage
assert_istrue(vc > 0 && vc < 11); % conducting: pulled below the 12 V rail
%=============================================================================
% Cutoff sanity: with the base left open (no base resistor, base tied to emitter)
% the transistor is off and the collector sits at the full supply.
d2 = ['{"version":"1.0.0","format":"nflow-2","name":"NPNoff","blocks":[', ...
  '{"id":"VCC","type":"ConstantVoltage","params":{"V":12}},', ...
  '{"id":"RC","type":"Resistor","params":{"R":1000}},', ...
  '{"id":"Q","type":"NPN","params":{"Is":1e-15,"Vt":0.025,"Bf":100,"Br":1}},', ...
  '{"id":"G","type":"Ground","params":{}},', ...
  '{"id":"VS","type":"VoltageSensor","params":{}},', ...
  '{"id":"sc","type":"scope","inputs":1,"outputs":0,"params":{}}],', ...
  '"connections":[{"from":"VS","to":"sc","fromIndex":0,"toIndex":0}],', ...
  '"physicalWires":[{"pins":["VCC.p","RC.p"]},', ...
  '{"pins":["RC.n","Q.C","VS.p"]},', ...
  '{"pins":["VCC.n","Q.E","Q.B","VS.n","G.p"]}],', ...
  '"solver":"dae","runtime":0.1,"sampleTime":0.02}'];
r = jsondecode(__nflow_simulate__(NFlow.internal.acausalExpand(d2)));
assert_isequal(r.status, 'done');
assert_istrue(r.scopes(1).series(end) > 11.9); % off: collector at the rail
