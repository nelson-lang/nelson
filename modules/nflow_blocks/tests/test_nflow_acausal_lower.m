% 4) Topology validation: actionable rejects.
% 4a) island without ground
comps = {...
  struct('id', 'V1', 'type', 'vsource', 'params', struct('V', 1)), ...
  struct('id', 'R1', 'type', 'resistor', 'params', struct('R', 1))};
conns = {{'V1.p', 'R1.p'}, {'V1.n', 'R1.n'}};
assert_istrue(strcmp(aw_error_id(comps, conns), 'Nelson:nflow:acausalNoGround:island'));
% 4b) capacitor directly across a voltage source (C/V loop through ground)
comps = {...
  struct('id', 'V1', 'type', 'vsource', 'params', struct('V', 1)), ...
  struct('id', 'C1', 'type', 'capacitor', 'params', struct('C', 1)), ...
  struct('id', 'G', 'type', 'ground')};
conns = {{'V1.p', 'C1.p'}, {'V1.n', 'C1.n', 'G.p'}};
assert_istrue(strcmp(aw_error_id(comps, conns), 'Nelson:nflow:acausalCapVLoop'));
% 4c) node fed only by inductor + current source (index-2)
comps = {...
  struct('id', 'I1', 'type', 'isource', 'params', struct('I', 1)), ...
  struct('id', 'L1', 'type', 'inductor', 'params', struct('L', 1)), ...
  struct('id', 'G', 'type', 'ground')};
conns = {{'I1.n', 'L1.p'}, {'I1.p', 'L1.n', 'G.p'}};
assert_istrue(strcmp(aw_error_id(comps, conns), 'Nelson:nflow:acausalInductorNode'));
% 4d) voltmeter with a dangling pin (no current-carrying branch on its node)
comps = {...
  struct('id', 'V1', 'type', 'vsource', 'params', struct('V', 1)), ...
  struct('id', 'R1', 'type', 'resistor', 'params', struct('R', 1)), ...
  struct('id', 'VS', 'type', 'voltageSensor'), ...
  struct('id', 'G', 'type', 'ground')};
conns = {{'V1.p', 'R1.p', 'VS.p'}, {'V1.n', 'R1.n', 'G.p'}};
assert_istrue(strcmp(aw_error_id(comps, conns), 'Nelson:nflow:acausalDanglingNode'));
