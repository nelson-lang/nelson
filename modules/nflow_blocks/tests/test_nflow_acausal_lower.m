% <--WEIGHT 8-->
% Acausal palette N1 (POC): NFlow.internal.acausalLower lowers an electrical netlist
% (components + pin connections) to a DAE diagram over the existing blocks,
% simulated with solver "dae". References are analytical circuit responses.
%=============================================================================
function p = aw_write(json, stem)
  p = [tempname(), '.nflow'];
  fid = fopen(p, 'w'); fwrite(fid, json); fclose(fid);
end
%=============================================================================
function id = aw_error_id(components, connections)
  id = '';
  try
    NFlow.internal.acausalLower(components, connections);
  catch e
    id = e.identifier;
  end
end
%=============================================================================
% 1) RC charging circuit: V(1V) - ammeter - R(1) - C(1F, ic=0) - ground.
%    v_C(t) = 1 - e^{-t}, series current i(t) = e^{-t}.
%    Both lowering vehicles ('blocks' DAE soup and 'island' native C++) must
%    match the same analytic reference.
comps = {...
  struct('id', 'V1', 'type', 'vsource', 'params', struct('V', 1)), ...
  struct('id', 'A1', 'type', 'currentSensor', 'params', struct('name', 'i')), ...
  struct('id', 'R1', 'type', 'resistor', 'params', struct('R', 1)), ...
  struct('id', 'C1', 'type', 'capacitor', 'params', struct('C', 1, 'ic', 0)), ...
  struct('id', 'VS', 'type', 'voltageSensor', 'params', struct('name', 'vc')), ...
  struct('id', 'G', 'type', 'ground')};
conns = {...
  {'V1.p', 'A1.p'}, ...
  {'A1.n', 'R1.p'}, ...
  {'R1.n', 'C1.p', 'VS.p'}, ...
  {'C1.n', 'V1.n', 'VS.n', 'G.p'}};
for vh = {'blocks', 'island'}
  [json, info] = NFlow.internal.acausalLower(comps, conns, ...
    struct('runtime', 1, 'sampleTime', 0.1, 'vehicle', vh{1}));
  assert_istrue(info.numNodes >= 4);
  out = sim(aw_write(json, ['test_nflow_acausal_rc_', vh{1}]));
  lg = out.logsout;
  nms = {lg.name};
  vc = lg(find(strcmp(nms, 'vc'), 1)).values;
  ii = lg(find(strcmp(nms, 'i'), 1)).values;
  t = linspace(0, 1, numel(vc))';
  assert_istrue(max(abs(vc(:) - (1 - exp(-t)))) < 1e-4);
  assert_istrue(max(abs(ii(:) - exp(-t))) < 1e-4);
end
