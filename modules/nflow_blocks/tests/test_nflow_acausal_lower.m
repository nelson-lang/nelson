% 2) Current divider (pure algebraic island): I = 3A into R1(1) || R2(2).
%    Top-node potential e = 3 * (1*2/(1+2)) = 2 V at every sample.
comps = {...
  struct('id', 'I1', 'type', 'isource', 'params', struct('I', 3)), ...
  struct('id', 'R1', 'type', 'resistor', 'params', struct('R', 1)), ...
  struct('id', 'R2', 'type', 'resistor', 'params', struct('R', 2)), ...
  struct('id', 'PS', 'type', 'potentialSensor', 'params', struct('name', 'e')), ...
  struct('id', 'G', 'type', 'ground')};
conns = {...
  {'I1.n', 'R1.p', 'R2.p', 'PS.p'}, ...
  {'I1.p', 'R1.n', 'R2.n', 'G.p'}};
json = NFlow.internal.acausalLower(comps, conns, struct('runtime', 0.5, 'sampleTime', 0.1));
out = sim(aw_write(json, 'test_nflow_acausal_divider'));
lg = out.logsout;
nms = {lg.name};
ev = lg(find(strcmp(nms, 'e'), 1)).values;
assert_istrue(max(abs(ev(:) - 2.0)) < 1e-5);
%=============================================================================
% 3) Series RLC step (R=1, L=1, C=1, V=1): underdamped charging,
%    v_C(t) = 1 - e^{-t/2} (cos(wd t) + (1/sqrt(3)) sin(wd t)), wd = sqrt(3)/2.
comps = {...
  struct('id', 'V1', 'type', 'vsource', 'params', struct('V', 1)), ...
  struct('id', 'R1', 'type', 'resistor', 'params', struct('R', 1)), ...
  struct('id', 'L1', 'type', 'inductor', 'params', struct('L', 1, 'ic', 0)), ...
  struct('id', 'C1', 'type', 'capacitor', 'params', struct('C', 1, 'ic', 0)), ...
  struct('id', 'VS', 'type', 'voltageSensor', 'params', struct('name', 'vc')), ...
  struct('id', 'G', 'type', 'ground')};
conns = {...
  {'V1.p', 'R1.p'}, ...
  {'R1.n', 'L1.p'}, ...
  {'L1.n', 'C1.p', 'VS.p'}, ...
  {'C1.n', 'V1.n', 'VS.n', 'G.p'}};
for vh = {'blocks', 'island'}
  json = NFlow.internal.acausalLower(comps, conns, ...
    struct('runtime', 5, 'sampleTime', 0.1, 'vehicle', vh{1}));
  out = sim(aw_write(json, ['test_nflow_acausal_rlc_', vh{1}]));
  lg = out.logsout;
  nms = {lg.name};
  vc = lg(find(strcmp(nms, 'vc'), 1)).values;
  t = linspace(0, 5, numel(vc))';
  wd = sqrt(3) / 2;
  vref = 1 - exp(-t / 2) .* (cos(wd * t) + (1 / sqrt(3)) * sin(wd * t));
  assert_istrue(max(abs(vc(:) - vref)) < 5e-4);
end
