% One-way clutch Freewheel (Coselica OneWayClutch): transmits a coupling torque
% only while flange a overruns flange b (slip = w_a - w_b > 0), driving them to a
% common speed, and freewheels otherwise. Native mechanical-island kind freewheel,
% regularised by a tanh gate on the slip (no mode-switching events). Sim + RK4
% C/Rust codegen.
%=============================================================================
% <--SEQUENTIAL TEST REQUIRED-->
%=============================================================================
% Engage: flange a is driven at a constant 5 rad/s while the driven inertia b
% starts at rest. Since a overruns b (slip > 0) the clutch couples and pulls b up
% to the drive speed.
d = ['{"version":"1.0.0","format":"nflow-2","name":"FW","blocks":[', ...
  '{"id":"A","type":"ConstantRotSpeed","params":{"w":5,"phi0":0}},', ...
  '{"id":"FW","type":"Freewheel","params":{"d":100,"w_eps":0.01}},', ...
  '{"id":"B","type":"Inertia","params":{"J":1,"phi0":0,"w0":0}},', ...
  '{"id":"WS","type":"RotSpeedSensor","params":{}},', ...
  '{"id":"sc","type":"scope","inputs":1,"outputs":0,"params":{}}],', ...
  '"connections":[{"from":"WS","to":"sc","fromIndex":0,"toIndex":0}],', ...
  '"physicalWires":[{"pins":["A.flange","FW.a"]},', ...
  '{"pins":["FW.b","B.flange","WS.flange"]}],', ...
  '"solver":"ode4","runtime":2.0,"sampleTime":0.02}'];
r = jsondecode(__nflow_simulate__(NFlow.internal.acausalExpand(d)));
assert_isequal(r.status, 'done');
assert_istrue(r.scopes(1).series(1) < 1); % driven flange starts at rest
assert_istrue(abs(r.scopes(1).series(end) - 5) < 0.3); % coupled up to the drive speed
%=============================================================================
% Freewheel: flange a is held at rest while the driven inertia b already spins at
% 5 rad/s. Now a lags b (slip < 0), so the clutch disengages and b keeps spinning
% -- a bidirectional coupling would instead drag it to rest.
d2 = ['{"version":"1.0.0","format":"nflow-2","name":"FW2","blocks":[', ...
  '{"id":"A","type":"ConstantRotSpeed","params":{"w":0,"phi0":0}},', ...
  '{"id":"FW","type":"Freewheel","params":{"d":100,"w_eps":0.01}},', ...
  '{"id":"B","type":"Inertia","params":{"J":1,"phi0":0,"w0":5}},', ...
  '{"id":"WS","type":"RotSpeedSensor","params":{}},', ...
  '{"id":"sc","type":"scope","inputs":1,"outputs":0,"params":{}}],', ...
  '"connections":[{"from":"WS","to":"sc","fromIndex":0,"toIndex":0}],', ...
  '"physicalWires":[{"pins":["A.flange","FW.a"]},', ...
  '{"pins":["FW.b","B.flange","WS.flange"]}],', ...
  '"solver":"ode4","runtime":2.0,"sampleTime":0.02}'];
r2 = jsondecode(__nflow_simulate__(NFlow.internal.acausalExpand(d2)));
assert_isequal(r2.status, 'done');
assert_istrue(r2.scopes(1).series(end) > 4.5); % freewheels: b keeps spinning
