% The acausal components as a user writes them - named pins joined by physical
% wires, expanded into an island and integrated as a DAE - against the answer
% that can be written down for each system. Four domains in one pass:
% electrical (first order, second order, purely resistive, transformer),
% thermal, translational and rotational, the last including the gear
% constraint.
%
% Each system was chosen because it has a closed form, so the check leans on no
% other simulation: an error in the island assembly, in the DAE residual or in
% a component equation moves the answer away from the formula.
%=============================================================================
function y = ac_run(blocks, wires, probe, stop, dt)
  d = struct();
  d.version = '1.0.0';
  d.format = 'nflow-2';
  d.name = 'acausal_closed_form';
  d.runtime = stop;
  d.sampleTime = dt;
  d.solver = 'dae';
  b = blocks;
  b{end + 1} = struct('id', 'tw', 'type', 'toWorkspace', 'x', 0, 'y', 0, ...
    'rotation', 0, 'params', struct('VariableName', 'y_acf', ...
    'SaveFormat', 'Array', 'Decimation', 1, 'MaxDataPoints', 'inf'));
  for k = 1:numel(b)
    b{k}.x = 80 + 110 * k;
    b{k}.y = 100;
  end
  d.blocks = b;
  d.connections = {struct('from', probe, 'to', 'tw', 'fromIndex', 0, 'toIndex', 0)};
  pw = {};
  for k = 1:numel(wires)
    w = struct();
    w.pins = wires{k};
    pw{end + 1} = w;
  end
  d.physicalWires = pw;
  model = [tempname(), '.nflow'];
  fid = fopen(model, 'wt');
  fwrite(fid, jsonencode(d));
  fclose(fid);
  out = sim(model);
  rmfile(model);
  y = [out.tout(:), out.y_acf(:)];
  evalin('base', 'clear(''y_acf'')');
end
function c = ac(id, type, params)
  c = struct('id', id, 'type', type, 'x', 0, 'y', 0, 'rotation', 0, 'params', params);
end
function ac_close(y, fn, atol, rtol)
  worst = 0;
  for k = 1:size(y, 1)
    want = fn(y(k, 1));
    tol = atol + rtol * max(abs(want), abs(y(k, 2)));
    worst = max(worst, abs(y(k, 2) - want) / tol);
  end
  assert_istrue(worst <= 1);
end
%=============================================================================
% Electrical, first order: a capacitor charging through a resistor reaches
% V (1 - exp(-t / RC)).
R = 2; C = 0.5;
y = ac_run({...
  ac('V1', 'ConstantVoltage', struct('V', 1)), ...
  ac('R1', 'Resistor', struct('R', R)), ...
  ac('C1', 'Capacitor', struct('C', C, 'v0', 0)), ...
  ac('VS', 'VoltageSensor', struct()), ...
  ac('G', 'Ground', struct())}, ...
  {{'V1.p', 'R1.p'}, {'R1.n', 'C1.p', 'VS.p'}, {'G.p', 'V1.n', 'C1.n', 'VS.n'}}, ...
  'VS', 4, 0.005);
ac_close(y, @(t) 1 - exp(-t / (R * C)), 1e-4, 2e-3);
%=============================================================================
% Electrical, second order: the series RLC with R = L = C = 1 is underdamped,
% alpha = 1/2 and omega_d = sqrt(3)/2.
alpha = 0.5;
wd = sqrt(3) / 2;
y = ac_run({...
  ac('V1', 'ConstantVoltage', struct('V', 1)), ...
  ac('R1', 'Resistor', struct('R', 1)), ...
  ac('L1', 'Inductor', struct('L', 1, 'i0', 0)), ...
  ac('C1', 'Capacitor', struct('C', 1, 'v0', 0)), ...
  ac('VS', 'VoltageSensor', struct()), ...
  ac('G', 'Ground', struct())}, ...
  {{'V1.p', 'R1.p'}, {'R1.n', 'L1.p'}, {'L1.n', 'C1.p', 'VS.p'}, ...
    {'G.p', 'V1.n', 'C1.n', 'VS.n'}}, 'VS', 4, 0.005);
ac_close(y, @(t) 1 - exp(-alpha * t) * (cos(wd * t) + (alpha / wd) * sin(wd * t)), ...
  1e-4, 2e-3);
%=============================================================================
% Purely resistive: 6 ohm over (3 ohm in series with a short, in parallel with
% a 1/6 S conductor) divides 12 V down to 3 V, and the idle branch carries
% nothing at all.
y = ac_run({...
  ac('V1', 'ConstantVoltage', struct('V', 12)), ...
  ac('R1', 'Resistor', struct('R', 6)), ...
  ac('R2', 'Resistor', struct('R', 3)), ...
  ac('K1', 'Conductor', struct('G', 1 / 6)), ...
  ac('SH', 'Short', struct()), ...
  ac('ID', 'Idle', struct()), ...
  ac('VS', 'VoltageSensor', struct()), ...
  ac('G', 'Ground', struct())}, ...
  {{'V1.p', 'R1.p'}, {'R1.n', 'R2.p', 'K1.p', 'ID.p', 'VS.p'}, ...
    {'R2.n', 'SH.p'}, {'G.p', 'V1.n', 'SH.n', 'K1.n', 'ID.n', 'VS.n'}}, ...
  'VS', 0.5, 0.005);
ac_close(y, @(t) 3, 1e-9, 1e-9);
%=============================================================================
% An ideal transformer of ratio 2 delivers half its primary voltage.
y = ac_run({...
  ac('V1', 'ConstantVoltage', struct('V', 10)), ...
  ac('T1', 'IdealTransformer', struct('n', 2)), ...
  ac('R2', 'Resistor', struct('R', 5)), ...
  ac('VS', 'VoltageSensor', struct()), ...
  ac('G', 'Ground', struct()), ...
  ac('G2', 'Ground', struct())}, ...
  {{'V1.p', 'T1.p1'}, {'G.p', 'V1.n', 'T1.n1'}, ...
    {'T1.p2', 'R2.p', 'VS.p'}, {'G2.p', 'T1.n2', 'R2.n', 'VS.n'}}, ...
  'VS', 0.5, 0.005);
ac_close(y, @(t) 5, 1e-9, 1e-9);
%=============================================================================
% Thermal: a heat capacity behind a conductor relaxes towards the boundary
% temperature with a time constant C / G.
G_ = 2; Cth = 0.5; T0 = 300; Tinf = 400;
y = ac_run({...
  ac('TS', 'FixedTemperature', struct('T', Tinf)), ...
  ac('K1', 'ThermalConductor', struct('G', G_)), ...
  ac('C1', 'HeatCapacitor', struct('C', Cth, 'T0', T0)), ...
  ac('TM', 'TemperatureSensor', struct())}, ...
  {{'TS.port', 'K1.a'}, {'K1.b', 'C1.port', 'TM.port'}}, 'TM', 2, 0.005);
ac_close(y, @(t) Tinf + (T0 - Tinf) * exp(-t / (Cth / G_)), 1e-4, 2e-3);
%=============================================================================
% Translational: a mass on a spring and a damper under a constant force.
m = 1; dmp = 0.5; k = 4; F = 1;
a2 = dmp / (2 * m);
wd2 = sqrt(k / m - a2 ^ 2);
y = ac_run({...
  ac('F1', 'ConstantForce', struct('F', F)), ...
  ac('M1', 'Mass', struct('m', m, 's0', 0, 'v0', 0)), ...
  ac('S1', 'Spring', struct('k', k)), ...
  ac('D1', 'Damper', struct('d', dmp)), ...
  ac('W', 'Fixed', struct('s0', 0)), ...
  ac('PS', 'PositionSensor', struct())}, ...
  {{'F1.flange', 'M1.flange', 'S1.a', 'D1.a', 'PS.flange'}, ...
    {'S1.b', 'D1.b', 'W.flange'}}, 'PS', 4, 0.005);
ac_close(y, ...
  @(t)(F / k) * (1 - exp(-a2 * t) * (cos(wd2 * t) + (a2 / wd2) * sin(wd2 * t))), ...
  1e-4, 2e-3);
%=============================================================================
% Rotational with a gear: IdealGear holds phi_a = ratio phi_b, so the second
% shaft appears at the first divided by ratio^2. With J1 = 1, J2 = 2, a ratio
% of 1/2 and c = 4, the first shaft carries J = 9 against c = 16 and swings
% undamped about tau / 16.
J1 = 1; J2 = 2; ratio = 0.5; cg = 4; tg = 1;
Jeq = J1 + J2 / ratio ^ 2;
ceq = cg / ratio ^ 2;
w0g = sqrt(ceq / Jeq);
y = ac_run({...
  ac('T1', 'ConstantTorque', struct('tau', tg)), ...
  ac('JA', 'Inertia', struct('J', J1, 'phi0', 0, 'w0', 0)), ...
  ac('GR', 'IdealGear', struct('ratio', ratio)), ...
  ac('JB', 'Inertia', struct('J', J2, 'phi0', 0, 'w0', 0)), ...
  ac('S1', 'RotSpring', struct('c', cg)), ...
  ac('W', 'RotFixed', struct('phi0', 0)), ...
  ac('AS', 'AngleSensor', struct())}, ...
  {{'T1.flange', 'JA.flange', 'GR.a', 'AS.flange'}, ...
    {'GR.b', 'JB.flange', 'S1.a'}, {'S1.b', 'W.flange'}}, 'AS', 4, 0.005);
ac_close(y, @(t)(tg / ceq) * (1 - cos(w0g * t)), 1e-4, 2e-3);
