% Prescribed-velocity sources Speed / ConstantSpeed (Coselica Speed / Constant-
% Speed) and their rotational RotSpeed / ConstantRotSpeed. Native mechanical-island
% kind prescribedSpeed: the flange velocity is driven directly by a signal (Speed)
% or a constant (ConstantSpeed), the position integrating s' = v_prescribed. The
% velocity state is unused; sensors and dampers read the prescribed value.
%=============================================================================
% <--SEQUENTIAL TEST REQUIRED-->
%=============================================================================
% ConstantSpeed of 2 m/s: the speed sensor reads 2 throughout and the position
% sensor ramps s = 2 t, so at t = 1 s the flange has moved 2 m.
d = ['{"version":"1.0.0","format":"nflow-2","name":"CS","blocks":[', ...
  '{"id":"V1","type":"ConstantSpeed","params":{"v":2,"s0":0}},', ...
  '{"id":"PS","type":"PositionSensor","params":{}},', ...
  '{"id":"SS","type":"SpeedSensor","params":{}},', ...
  '{"id":"scp","type":"scope","inputs":1,"outputs":0,"params":{}},', ...
  '{"id":"scv","type":"scope","inputs":1,"outputs":0,"params":{}}],', ...
  '"connections":[{"from":"PS","to":"scp","fromIndex":0,"toIndex":0},', ...
  '{"from":"SS","to":"scv","fromIndex":0,"toIndex":0}],', ...
  '"physicalWires":[{"pins":["V1.flange","PS.flange","SS.flange"]}],', ...
  '"solver":"ode4","runtime":1.0,"sampleTime":0.05}'];
r = jsondecode(__nflow_simulate__(NFlow.internal.acausalExpand(d)));
assert_isequal(r.status, 'done');
assert_istrue(abs(r.scopes(2).series(end) - 2) < 1e-6); % speed held at 2
assert_istrue(abs(r.scopes(1).series(end) - 2) < 0.05); % position s = 2 t -> 2
%=============================================================================
% ConstantSpeed drives an attached mass regardless of its inertia: the source
% dominates, so the mass moves at exactly 2 m/s (a plain force balance would let
% inertia lag). Same rig with a 5 kg mass on the flange.
d2 = ['{"version":"1.0.0","format":"nflow-2","name":"CSM","blocks":[', ...
  '{"id":"V1","type":"ConstantSpeed","params":{"v":2,"s0":0}},', ...
  '{"id":"M1","type":"Mass","params":{"m":5}},', ...
  '{"id":"SS","type":"SpeedSensor","params":{}},', ...
  '{"id":"scv","type":"scope","inputs":1,"outputs":0,"params":{}}],', ...
  '"connections":[{"from":"SS","to":"scv","fromIndex":0,"toIndex":0}],', ...
  '"physicalWires":[{"pins":["V1.flange","M1.flange","SS.flange"]}],', ...
  '"solver":"ode4","runtime":1.0,"sampleTime":0.05}'];
r2 = jsondecode(__nflow_simulate__(NFlow.internal.acausalExpand(d2)));
assert_isequal(r2.status, 'done');
assert_istrue(abs(r2.scopes(1).series(end) - 2) < 1e-6); % mass forced to 2 m/s
%=============================================================================
% Signal-driven Speed: a constant source of 3 fed into Speed makes the flange
% move at 3 m/s (the velocity tracks the input exactly).
d3 = ['{"version":"1.0.0","format":"nflow-2","name":"SPD","blocks":[', ...
  '{"id":"K3","type":"constant","outputs":1,"params":{"Value":3}},', ...
  '{"id":"V1","type":"Speed","params":{"s0":0}},', ...
  '{"id":"SS","type":"SpeedSensor","params":{}},', ...
  '{"id":"scv","type":"scope","inputs":1,"outputs":0,"params":{}}],', ...
  '"connections":[{"from":"K3","to":"V1","fromIndex":0,"toIndex":0},', ...
  '{"from":"SS","to":"scv","fromIndex":0,"toIndex":0}],', ...
  '"physicalWires":[{"pins":["V1.flange","SS.flange"]}],', ...
  '"solver":"ode4","runtime":0.5,"sampleTime":0.05}'];
r3 = jsondecode(__nflow_simulate__(NFlow.internal.acausalExpand(d3)));
assert_isequal(r3.status, 'done');
assert_istrue(abs(r3.scopes(1).series(end) - 3) < 1e-6); % velocity tracks signal
%=============================================================================
