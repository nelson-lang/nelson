% xml = NFlow.internal.acausalGenerateHelp(componentName, lang)
%
% Acausal palette N0.2: the per-block help-page generator. Emits a well-formed
% Nelson help XML page for one catalog component, generated from the
% single-source catalog (name, domain, pins, params, description). This is the
% N0.2 help scaffold: N5 writes the pages under
% modules/nflow_blocks/help/{en_US,fr_FR}/xml/<group>/<name>.xml, then an author
% expands the prose. nflow help pages use <history_version>1.0.0 (repo rule).
%
% componentName: a name from NFlow.internal.acausalCatalog (e.g. 'Resistor').
% lang: 'en_US' (default) | 'fr_FR', setting the <language> tag and a translated
%       lead sentence; the structured tables are language-neutral.
%=============================================================================
function xml = acausalGenerateHelp(componentName, lang)
  if nargin < 2
    lang = 'en_US';
  end
  catalog = NFlow.internal.acausalCatalog();
  idx = 0;
  for k = 1:numel(catalog)
    if strcmp(catalog(k).name, componentName)
      idx = k; break
    end
  end
  if idx == 0
    error('Nelson:nflow:acausalHelpUnknown', ...
      'Unknown acausal component ''%s''.', componentName);
  end
  c = catalog(idx);

  % Physical-pin rows.
  pinRows = {};
  for pp = 1:numel(c.pins)
    pinRows{end + 1} = sprintf(...
      '<tr><td>%s</td><td>%s pin (%s domain, undirected)</td></tr>', ...
      c.pins{pp}{1}, c.domain, c.domain); %#ok<AGROW>
  end
  % Parameter rows.
  paramRows = {};
  for qq = 1:numel(c.params)
    pm = c.params{qq};
    paramRows{end + 1} = sprintf(...
      '<tr><td><code>%s</code></td><td>%.15g</td><td>%s</td></tr>', ...
      pm{1}, pm{3}, pm{4}); %#ok<AGROW>
  end
  if isempty(paramRows)
    paramRows = {'<tr><td>(none)</td><td></td><td></td></tr>'};
  end

  lead = c.desc;
  if strcmp(lang, 'fr_FR')
    lead = ['Composant acausal (', c.domain, '). ', c.desc];
  end
  islandNote = sprintf(...
    ['Acausal component: lowered to a %s block by NFlow.internal.acausalExpand. "dae" is the ', ...
     'default solver; the fixed-step loop and the native explicit solvers ', ...
     '(ode1/ode4/ode45) are also supported.'], ...
    c.island);

  xml = [...
    '<?xml version="1.0" encoding="UTF-8"?>', newline, ...
    '<xmldoc>', newline, ...
    '  <copyright>SAME AS NELSON SOFTWARE</copyright>', newline, ...
    '  <language>', lang, '</language>', newline, ...
    '  <keyword>', c.name, '</keyword>', newline, ...
    '  <keyword_alias>block:', c.name, '</keyword_alias>', newline, ...
    '  <short_description>', esc(c.desc), '</short_description>', newline, ...
    '  <syntax><syntax_item>Acausal component: ', c.name, '</syntax_item></syntax>', newline, ...
    '  <param_input><param_input_item><param_name>physical pins</param_name>', ...
    '<param_description>', num2str(numel(c.pins)), ' physical pin(s), ', c.domain, ' domain.', ...
    '</param_description></param_input_item></param_input>', newline, ...
    '  <param_output><param_output_item><param_name>signal ports</param_name>', ...
    '<param_description>', sig_desc(c), '</param_description></param_output_item></param_output>', newline, ...
    '  <description>', newline, ...
    '    <p>', esc(lead), '</p>', newline, ...
    '    <p>', islandNote, '</p>', newline, ...
    '    <p><b>Domain</b>: ', c.domain, ' &#8212; group ', c.group, '.</p>', newline, ...
    '    <p><b>Physical pins</b></p>', newline, ...
    '    <table border="1"><thead><tr><th>Pin</th><th>Role</th></tr></thead><tbody>', ...
    strjoin(pinRows, ''), '</tbody></table>', newline, ...
    '    <p><b>Parameters</b></p>', newline, ...
    '    <table border="1"><thead><tr><th>Parameter</th><th>Default</th><th>Unit</th></tr></thead><tbody>', ...
    strjoin(paramRows, ''), '</tbody></table>', newline, ...
    '    <p><b>Implementation Sources</b></p>', newline, ...
    '    <source_code label="Catalog" path="modules/nflow_blocks/functions/+NFlow/+internal/acausalCatalog.m" language="matlab" start="entry(''', c.name, '''" end="'');"/>', newline, ...
    '  </description>', newline, ...
    '  <used_function/>', newline, ...
    '  <bibliography/>', newline, ...
    '  <see_also><see_also_item><link linkend="${nflow_engine}acausal_user_guide">acausal user guide</link></see_also_item></see_also>', newline, ...
    '  <history><history_item><history_version>1.0.0</history_version>', ...
    '<history_description>initial version</history_description></history_item></history>', newline, ...
    '  <authors><author_item>Allan CORNET</author_item></authors>', newline, ...
    '</xmldoc>', newline];
end
%=============================================================================
function d = sig_desc(c)
  parts = {};
  if ~isempty(c.signalIn)
    parts{end + 1} = ['input ', c.signalIn]; %#ok<AGROW>
  end
  if ~isempty(c.signalOut)
    parts{end + 1} = ['output (', c.signalOut, ' sensor)']; %#ok<AGROW>
  end
  if isempty(parts)
    d = 'none (pure physical component).';
  else
    d = [strjoin(parts, ', '), '.'];
  end
end
%=============================================================================
function o = esc(s)
  o = strrep(s, '&', '&amp;');
  o = strrep(o, '<', '&lt;');
  o = strrep(o, '>', '&gt;');
end
