% catalog = NFlow.internal.planarCatalog()
%
% Acausal palette N7: the single-source registry of the planar 2-D multibody
% palette blocks (the frame-connected authoring model consumed by
% NFlow.internal.planarExpand). Each entry describes a palette block: its frame pins,
% parameters, whether it emits a signal output (sensors), and a one-line
% description. Help pages (NFlow.internal.planarGenerateHelp) and parity accounting are
% generated from here, so a new planar block is one row, not scattered code.
%
% Fields:
%   name    palette block type (e.g. 'PlanarRevolute')
%   group   palette group ('World'|'Parts'|'Joints'|'Sensors'|'Forces')
%   frames  cell of frame-pin names (e.g. {'a','b'})
%   params  cell of {name, default, unit} rows
%   signal  '' | 'output' (sensors emit one signal port)
%   desc    one-line description
%=============================================================================
function catalog = planarCatalog()
  c = {};
  c{end + 1} = pl_entry('PlanarWorld', 'World', {'frame'}, ...
    {{'gravity', 9.81, 'm/s2'}}, '', ...
    'Inertial world with uniform gravity (down = -y); provides a fixed frame at the origin.');
  c{end + 1} = pl_entry('PlanarFixed', 'World', {'frame'}, ...
    {{'x', 0, 'm'}, {'y', 0, 'm'}}, '', ...
    'Frame rigidly fixed at the world point (x, y).');
  c{end + 1} = pl_entry('PlanarBody', 'Parts', {'com', '<named frames>'}, ...
    {{'m', 1, 'kg'}, {'I', 1, 'kg.m2'}, {'x0', 0, 'm'}, {'y0', 0, 'm'}, ...
     {'phi0', 0, 'rad'}, {'vx0', 0, 'm/s'}, {'vy0', 0, 'm/s'}, {'w0', 0, 'rad/s'}}, '', ...
    'Rigid body: mass m, central inertia I; six states (xc, yc, phi, vx, vy, w). Named frames are body-fixed offsets from the COM.');
  c{end + 1} = pl_entry('PlanarPointMass', 'Parts', {'com'}, ...
    {{'m', 1, 'kg'}, {'x0', 0, 'm'}, {'y0', 0, 'm'}, {'vx0', 0, 'm/s'}, {'vy0', 0, 'm/s'}}, '', ...
    'Point mass (no orientation): four states (xc, yc, vx, vy); attach joints at its point.');
  c{end + 1} = pl_entry('PlanarRevolute', 'Joints', {'a', 'b'}, {}, '', ...
    'Revolute (pin) joint: frames a and b share position, free relative rotation.');
  c{end + 1} = pl_entry('PlanarPrismatic', 'Joints', {'a', 'b'}, ...
    {{'dx', 1, '1'}, {'dy', 0, '1'}}, '', ...
    'Prismatic joint: frame b slides along the world axis (dx, dy) through frame a, relative rotation locked.');
  c{end + 1} = pl_entry('PlanarDistance', 'Joints', {'a', 'b'}, ...
    {{'length', 1, 'm'}}, '', ...
    'Rigid rod: holds a fixed distance L between the points at frames a and b.');
  c{end + 1} = pl_entry('PlanarRollingWheel', 'Joints', {'a'}, ...
    {{'dx', 1, '1'}, {'dy', 0, '1'}, {'px', 0, 'm'}, {'py', 0, 'm'}, {'radius', 1, 'm'}}, '', ...
    'Wheel at frame a rolls without slipping on the fixed surface line (px,py)+(dx,dy), staying at height radius.');
  c{end + 1} = pl_entry('PlanarPositionSensor', 'Sensors', {'a'}, ...
    {{'axis', 'x', 'x|y|phi'}}, 'output', ...
    'Absolute position of the frame-a point along the chosen axis (x, y) or the body angle (phi).');
  c{end + 1} = pl_entry('PlanarVelocitySensor', 'Sensors', {'a'}, ...
    {{'axis', 'x', 'x|y|omega'}}, 'output', ...
    'Absolute velocity of the frame-a point along the chosen axis (x, y) or the angular velocity (omega).');
  c{end + 1} = pl_entry('PlanarAccelerationSensor', 'Sensors', {'a'}, ...
    {{'axis', 'x', 'x|y|alpha'}}, 'output', ...
    'Absolute acceleration of the body at frame a along the chosen axis (x, y) or the angular acceleration (alpha).');
  c{end + 1} = pl_entry('PlanarRelPositionSensor', 'Sensors', {'a', 'b'}, ...
    {{'axis', 'x', 'x|y'}}, 'output', ...
    'Relative position of the frame-a point minus the frame-b point along the chosen axis (x, y).');
  c{end + 1} = pl_entry('PlanarDistanceSensor', 'Sensors', {'a', 'b'}, {}, 'output', ...
    'Distance between the points at frames a and b.');
  c{end + 1} = pl_entry('PlanarSpringDamper', 'Forces', {'a', 'b'}, ...
    {{'c', 100, 'N/m'}, {'d', 1, 'N.s/m'}}, '', ...
    'Linear 2D spring-damper between the points at frames a and b: F = -(c dr + d dv).');
  c{end + 1} = pl_entry('PlanarSpring', 'Forces', {'a', 'b'}, ...
    {{'c', 100, 'N/m'}}, '', ...
    'Linear 2D spring between the points at frames a and b: F = -c dr.');
  c{end + 1} = pl_entry('PlanarDamper', 'Forces', {'a', 'b'}, ...
    {{'d', 10, 'N.s/m'}}, '', ...
    'Linear 2D damper between the points at frames a and b: F = -d dv.');
  c{end + 1} = pl_entry('PlanarForce', 'Forces', {'a'}, ...
    {{'fx', 0, 'N'}, {'fy', 0, 'N'}}, '', ...
    'External world force (fx, fy) applied at the frame-a point (adds a torque when offset from the COM).');
  c{end + 1} = pl_entry('PlanarTorque', 'Forces', {'a'}, ...
    {{'tau', 0, 'N.m'}}, '', ...
    'External torque tau applied to the body at frame a.');
  c{end + 1} = pl_entry('PlanarRelativeTorque', 'Forces', {'a', 'b'}, ...
    {{'tau', 0, 'N.m'}}, '', ...
    'Actuator torque: +tau on the body at frame a, -tau on the body at frame b (drives a joint).');

  catalog = [c{:}];
end
%=============================================================================
function e = pl_entry(name, group, frames, params, signal, desc)
  e = struct('name', name, 'group', group, 'frames', {frames}, ...
    'params', {params}, 'signal', signal, 'desc', desc);
end
