% svg = NFlow.internal.planarGenerateIcon(name)
%
% Acausal palette N7/N5: the per-block icon generator for the planar 2-D
% multibody palette. Emits a polished, self-contained 72x72 SVG palette icon per
% planar block, composed from a clean-room symbol kit (rigid body, pin joint,
% slider, rod, wheel, point mass, world, sensors, forces). Deterministic and
% generated from NFlow.internal.planarCatalog, in the planar (purple) domain tint.
%
% name: a block name from NFlow.internal.planarCatalog (e.g. 'PlanarRevolute').
%=============================================================================
function svg = planarGenerateIcon(name)
  catalog = NFlow.internal.planarCatalog();
  found = false;
  for k = 1:numel(catalog)
    if strcmp(catalog(k).name, name)
      found = true; break
    end
  end
  if ~found
    error('Nelson:nflow:planarIconUnknown', 'Unknown planar block ''%s''.', name);
  end
  bg = '#EEEDFE'; tint = '#AFA9EC'; ink = '#3C3489';
  sym = pl_icon_symbol(name, ink);
  svg = [...
    '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 72 72" width="72" height="72">', newline, ...
    '  <rect x="1" y="1" width="70" height="70" rx="14" fill="', bg, ...
    '" stroke="', tint, '" stroke-width="1.5"/>', newline, ...
    sym, newline, ...
    '</svg>', newline];
end
%=============================================================================
function s = pl_line(x1, y1, x2, y2, k)
  s = sprintf(['<line x1="%g" y1="%g" x2="%g" y2="%g" stroke="%s" ', ...
    'stroke-width="2" stroke-linecap="round"/>'], x1, y1, x2, y2, k);
end
function s = pl_txt(t, k)
  s = sprintf(['<text x="36" y="42" text-anchor="middle" font-family="Georgia,serif" ', ...
    'font-size="20" font-style="italic" fill="%s">%s</text>'], k, t);
end
%=============================================================================
function s = pl_icon_symbol(name, k)
  switch name
    case 'PlanarBody'
      s = ['  ', sprintf('<rect x="22" y="24" width="28" height="24" rx="2" fill="none" stroke="%s" stroke-width="2"/>', k), ...
        sprintf('<circle cx="36" cy="36" r="2.5" fill="%s"/>', k)];
    case 'PlanarPointMass'
      s = ['  ', sprintf('<circle cx="36" cy="36" r="6" fill="%s"/>', k)];
    case 'PlanarWorld'
      s = ['  ', pl_line(20, 52, 52, 52, k), pl_line(20, 52, 20, 22, k), ...
        sprintf('<path d="M20 26 L16 34 L24 34 Z" fill="%s"/>', k), ...
        sprintf('<path d="M48 52 L48 44 L56 48 Z" fill="%s"/>', k)];
    case 'PlanarFixed'
      s = ['  ', pl_line(22, 30, 50, 30, k), ...
        pl_line(24, 30, 20, 36, k), pl_line(31, 30, 27, 36, k), ...
        pl_line(38, 30, 34, 36, k), pl_line(45, 30, 41, 36, k), ...
        pl_line(36, 30, 36, 46, k)];
    case 'PlanarRevolute'
      s = ['  ', pl_line(16, 36, 30, 36, k), pl_line(42, 36, 56, 36, k), ...
        sprintf('<circle cx="36" cy="36" r="7" fill="none" stroke="%s" stroke-width="2"/>', k), ...
        sprintf('<circle cx="36" cy="36" r="2" fill="%s"/>', k)];
    case 'PlanarPrismatic'
      s = ['  ', sprintf('<rect x="16" y="40" width="40" height="6" rx="1" fill="none" stroke="%s" stroke-width="2"/>', k), ...
        sprintf('<rect x="28" y="26" width="16" height="12" rx="2" fill="none" stroke="%s" stroke-width="2"/>', k)];
    case 'PlanarDistance'
      s = ['  ', sprintf('<circle cx="20" cy="36" r="3" fill="%s"/>', k), ...
        pl_line(20, 36, 52, 36, k), ...
        sprintf('<circle cx="52" cy="36" r="3" fill="%s"/>', k)];
    case 'PlanarSpringDamper'
      s = ['  ', sprintf('<circle cx="16" cy="36" r="3" fill="%s"/>', k), ...
        pl_line(16, 36, 22, 36, k), ...
        sprintf(['<path d="M22 36 L26 30 L30 42 L34 30 L38 42 L42 36" ', ...
          'fill="none" stroke="%s" stroke-width="2"/>'], k), ...
        pl_line(42, 36, 52, 36, k), ...
        sprintf('<circle cx="52" cy="36" r="3" fill="%s"/>', k)];
    case 'PlanarSpring'
      s = ['  ', sprintf('<circle cx="16" cy="36" r="3" fill="%s"/>', k), ...
        pl_line(16, 36, 22, 36, k), ...
        sprintf(['<path d="M22 36 L26 30 L30 42 L34 30 L38 42 L42 36" ', ...
          'fill="none" stroke="%s" stroke-width="2"/>'], k), ...
        pl_line(42, 36, 52, 36, k), ...
        sprintf('<circle cx="52" cy="36" r="3" fill="%s"/>', k)];
    case 'PlanarDamper'
      s = ['  ', sprintf('<circle cx="16" cy="36" r="3" fill="%s"/>', k), ...
        pl_line(16, 36, 28, 36, k), ...
        sprintf('<rect x="28" y="30" width="12" height="12" fill="none" stroke="%s" stroke-width="2"/>', k), ...
        pl_line(34, 30, 34, 42, k), pl_line(40, 36, 52, 36, k), ...
        sprintf('<circle cx="52" cy="36" r="3" fill="%s"/>', k)];
    case 'PlanarRollingWheel'
      s = ['  ', sprintf('<circle cx="36" cy="30" r="10" fill="none" stroke="%s" stroke-width="2"/>', k), ...
        sprintf('<circle cx="36" cy="30" r="2" fill="%s"/>', k), ...
        pl_line(18, 44, 54, 44, k), ...
        pl_line(20, 44, 16, 50, k), pl_line(30, 44, 26, 50, k), ...
        pl_line(40, 44, 36, 50, k), pl_line(50, 44, 46, 50, k)];
    case 'PlanarForce'
      s = ['  ', pl_line(18, 36, 48, 36, k), ...
        sprintf('<path d="M46 30 L56 36 L46 42 Z" fill="%s"/>', k)];
    case 'PlanarTorque'
      s = ['  ', sprintf(['<path d="M24 44 A16 16 0 1 1 48 44" fill="none" ', ...
        'stroke="%s" stroke-width="2"/>'], k), ...
        sprintf('<path d="M44 40 L50 46 L42 48 Z" fill="%s"/>', k)];
    case 'PlanarRelativeTorque'
      s = ['  ', sprintf(['<path d="M26 42 A14 14 0 0 1 46 42" fill="none" ', ...
        'stroke="%s" stroke-width="2"/>'], k), ...
        sprintf('<path d="M44 38 L49 44 L41 45 Z" fill="%s"/>', k), ...
        sprintf('<path d="M28 38 L23 44 L31 45 Z" fill="%s"/>', k)];
    case 'PlanarPositionSensor'
      s = ['  ', pl_sensor('x', k)];
    case 'PlanarVelocitySensor'
      s = ['  ', pl_sensor('v', k)];
    case 'PlanarAccelerationSensor'
      s = ['  ', pl_sensor('a', k)];
    case 'PlanarRelPositionSensor'
      s = ['  ', pl_sensor('r', k)];
    case 'PlanarDistanceSensor'
      s = ['  ', pl_sensor('d', k)];
    otherwise
      s = ['  ', pl_txt(upper(name(7)), k)]; % drop the "Planar" prefix
  end
end
%=============================================================================
function s = pl_sensor(letter, k)
  % Modelica multibody-sensor style: a rectangular housing with the symbol.
  s = [sprintf('<rect x="19" y="26" width="34" height="20" rx="2" fill="none" stroke="%s" stroke-width="2"/>', k), ...
    sprintf(['<text x="36" y="41" text-anchor="middle" font-family="Georgia,serif" ', ...
    'font-size="14" fill="%s">%s</text>'], k, letter)];
end
