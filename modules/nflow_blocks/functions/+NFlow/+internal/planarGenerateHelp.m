% xml = NFlow.internal.planarGenerateHelp(blockName, lang)
%
% Acausal palette N7: the per-block help-page generator for the planar 2-D
% multibody palette. Emits a well-formed Nelson help XML page for one planar
% block, generated from the single-source NFlow.internal.planarCatalog (name, group,
% frames, params, description). N5 writes the pages under
% modules/nflow_blocks/help/{en_US,fr_FR}/xml/planar/<name>.xml. nflow help
% pages use <history_version>1.0.0 (repo rule).
%
% blockName: a name from NFlow.internal.planarCatalog (e.g. 'PlanarRevolute').
% lang: 'en_US' (default) | 'fr_FR', setting the <language> tag and a translated
%       lead sentence; the structured tables are language-neutral.
%=============================================================================
function xml = planarGenerateHelp(blockName, lang)
  if nargin < 2
    lang = 'en_US';
  end
  catalog = NFlow.internal.planarCatalog();
  idx = 0;
  for k = 1:numel(catalog)
    if strcmp(catalog(k).name, blockName)
      idx = k; break
    end
  end
  if idx == 0
    error('Nelson:nflow:planarHelpUnknown', ...
      'Unknown planar block ''%s''.', blockName);
  end
  c = catalog(idx);

  frameRows = {};
  for pp = 1:numel(c.frames)
    frameRows{end + 1} = sprintf(...
      '<tr><td>%s</td><td>planar frame connector (position + orientation)</td></tr>', ...
      esc(c.frames{pp})); %#ok<AGROW>
  end
  paramRows = {};
  for qq = 1:numel(c.params)
    pm = c.params{qq};
    paramRows{end + 1} = sprintf(...
      '<tr><td><code>%s</code></td><td>%s</td><td>%s</td></tr>', ...
      pm{1}, num2str(pm{2}), esc(pm{3})); %#ok<AGROW>
  end
  if isempty(paramRows)
    paramRows = {'<tr><td>(none)</td><td></td><td></td></tr>'};
  end

  lead = c.desc;
  if strcmp(lang, 'fr_FR')
    lead = ['Bloc multibody planaire 2D (groupe ', c.group, '). ', c.desc];
  end
  if isempty(c.signal)
    sigDesc = 'none (structural block).';
  else
    sigDesc = 'one signal output port (sensor reading).';
  end

  xml = [...
    '<?xml version="1.0" encoding="UTF-8"?>', newline, ...
    '<xmldoc>', newline, ...
    '  <copyright>SAME AS NELSON SOFTWARE</copyright>', newline, ...
    '  <language>', lang, '</language>', newline, ...
    '  <keyword>', c.name, '</keyword>', newline, ...
    '  <keyword_alias>block:', c.name, '</keyword_alias>', newline, ...
    '  <short_description>', esc(c.desc), '</short_description>', newline, ...
    '  <syntax><syntax_item>Planar multibody block: ', c.name, '</syntax_item></syntax>', newline, ...
    '  <param_input><param_input_item><param_name>frame connectors</param_name>', ...
    '<param_description>', num2str(numel(c.frames)), ' planar frame pin(s).', ...
    '</param_description></param_input_item></param_input>', newline, ...
    '  <param_output><param_output_item><param_name>signal ports</param_name>', ...
    '<param_description>', sigDesc, '</param_description></param_output_item></param_output>', newline, ...
    '  <description>', newline, ...
    '    <p>', esc(lead), '</p>', newline, ...
    '    <p>Planar block: lowered to a native <code>planarMechanicalIsland</code> by NFlow.internal.planarExpand. <code>dae</code> is the default solver (a jointed multibody island requires it; a joint-free one also runs under <code>ode1</code>/<code>ode4</code>/<code>ode45</code>).</p>', newline, ...
    '    <p><b>Group</b>: ', esc(c.group), '.</p>', newline, ...
    '    <p><b>Frame connectors</b></p>', newline, ...
    '    <table border="1"><thead><tr><th>Frame</th><th>Role</th></tr></thead><tbody>', ...
    strjoin(frameRows, ''), '</tbody></table>', newline, ...
    '    <p><b>Parameters</b></p>', newline, ...
    '    <table border="1"><thead><tr><th>Parameter</th><th>Default</th><th>Unit</th></tr></thead><tbody>', ...
    strjoin(paramRows, ''), '</tbody></table>', newline, ...
    '    <p><b>Implementation Sources</b></p>', newline, ...
    '    <source_code label="Catalog" path="modules/nflow_blocks/functions/+NFlow/+internal/planarCatalog.m" language="matlab" start="entry(''', c.name, '''" end="'');"/>', newline, ...
    '    <source_code label="Expansion" path="modules/nflow_engine/functions/NFlow.internal.planarExpand.m" language="matlab"/>', newline, ...
    '  </description>', newline, ...
    '  <used_function/>', newline, ...
    '  <bibliography/>', newline, ...
    '  <see_also><see_also_item><link linkend="${nflow_engine}acausal_user_guide">acausal user guide</link></see_also_item></see_also>', newline, ...
    '  <history><history_item><history_version>1.0.0</history_version>', ...
    '<history_description>initial version</history_description></history_item></history>', newline, ...
    '  <authors><author_item>Allan CORNET</author_item></authors>', newline, ...
    '</xmldoc>', newline];
end
%=============================================================================
function o = esc(s)
  o = strrep(s, '&', '&amp;');
  o = strrep(o, '<', '&lt;');
  o = strrep(o, '>', '&gt;');
end
