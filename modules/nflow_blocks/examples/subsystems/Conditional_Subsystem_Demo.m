% Conditional subsystems demo (enabled / triggered).
%
% A subsystem with params.controlPort runs conditionally: the control signal is
% wired to an input port appended AFTER the data ports (data first, control
% last). See modules/nflow_engine/docs/conditional-subsystems.md.
%
% This script builds two small models and runs them headless with
% __nflow_simulate__, printing the gated output so the behavior is visible.
%=============================================================================

% --- Enabled: an inner integrator runs only while the control is > 0 ----------
inner = struct();
inner.blocks = {...
  struct('id', 'c', 'type', 'constant', 'inputs', 0, 'outputs', 1, 'params', struct('Value', 1)), ...
  struct('id', 'int', 'type', 'integrator', 'inputs', 1, 'outputs', 1, ...
    'params', struct('InitialCondition', 0)), ...
  struct('id', 'yout', 'type', 'labelSink', 'inputs', 1, 'outputs', 1, ...
    'params', struct('gotoTag', 'y'))};
inner.connections = {...
  struct('from', 'c', 'to', 'int', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'int', 'to', 'yout', 'fromIndex', 0, 'toIndex', 0)};
inner.externalOutputs = {struct('id', 'yout', 'name', 'y')};
inner.controlPort = struct('kind', 'enable');

d = struct();
d.blocks = {...
  struct('id', 'clk', 'type', 'clock', 'inputs', 0, 'outputs', 1, 'params', struct()), ...
  struct('id', 'cmp', 'type', 'compareToConstant', 'inputs', 1, 'outputs', 1, ...
    'params', struct('relop', 'lt', 'const', 0.5)), ...
  struct('id', 'sub', 'type', 'subsystem', 'inputs', 1, 'outputs', 1, ...
    'params', struct('subsystem', inner, 'controlPort', struct('kind', 'enable'))), ...
  struct('id', 'tw', 'type', 'toWorkspace', 'inputs', 1, 'outputs', 0, ...
    'params', struct('VariableName', 'enabled_y', 'SaveFormat', 'Array', ...
    'Decimation', 1, 'MaxDataPoints', 'inf'))};
d.connections = {...
  struct('from', 'clk', 'to', 'cmp', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'cmp', 'to', 'sub', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'sub', 'to', 'tw', 'fromIndex', 0, 'toIndex', 0)};
d.sampleTime = 0.1; d.duration = 1.0; d.variables = struct();
jsondecode(__nflow_simulate__(jsonencode(d)));
disp('Enabled subsystem (integrator ramps while t < 0.5, then holds):');
disp(evalin('base', 'enabled_y')');

% --- Triggered: an inner counter increments once per rising control edge ------
inner2 = struct();
inner2.blocks = {...
  struct('id', 'one', 'type', 'constant', 'inputs', 0, 'outputs', 1, 'params', struct('Value', 1)), ...
  struct('id', 'acc', 'type', 'sum', 'inputs', 2, 'outputs', 1, 'params', struct('Inputs', '++')), ...
  struct('id', 'del', 'type', 'unitDelay', 'inputs', 1, 'outputs', 1, 'params', struct()), ...
  struct('id', 'cout', 'type', 'labelSink', 'inputs', 1, 'outputs', 1, ...
    'params', struct('gotoTag', 'y'))};
inner2.connections = {...
  struct('from', 'one', 'to', 'acc', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'del', 'to', 'acc', 'fromIndex', 0, 'toIndex', 1), ...
  struct('from', 'acc', 'to', 'del', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'acc', 'to', 'cout', 'fromIndex', 0, 'toIndex', 0)};
inner2.externalOutputs = {struct('id', 'cout', 'name', 'y')};
inner2.controlPort = struct('kind', 'trigger', 'triggerType', 'rising');

d2 = struct();
d2.blocks = {...
  struct('id', 'clk', 'type', 'clock', 'inputs', 0, 'outputs', 1, 'params', struct()), ...
  struct('id', 'cmp', 'type', 'compareToConstant', 'inputs', 1, 'outputs', 1, ...
    'params', struct('relop', 'ge', 'const', 0.5)), ...
  struct('id', 'sub', 'type', 'subsystem', 'inputs', 1, 'outputs', 1, ...
    'params', struct('subsystem', inner2, ...
    'controlPort', struct('kind', 'trigger', 'triggerType', 'rising'))), ...
  struct('id', 'tw', 'type', 'toWorkspace', 'inputs', 1, 'outputs', 0, ...
    'params', struct('VariableName', 'triggered_y', 'SaveFormat', 'Array', ...
    'Decimation', 1, 'MaxDataPoints', 'inf'))};
d2.connections = {...
  struct('from', 'clk', 'to', 'cmp', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'cmp', 'to', 'sub', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'sub', 'to', 'tw', 'fromIndex', 0, 'toIndex', 0)};
d2.sampleTime = 0.1; d2.duration = 1.0; d2.variables = struct();
jsondecode(__nflow_simulate__(jsonencode(d2)));
disp('Triggered subsystem (counter += 1 once at the rising edge t = 0.5, then holds):');
disp(evalin('base', 'triggered_y')');

% --- Enable + trigger: the same counter, but the rising edge at t=0.5 is only
%     honored while the enable is on. Here the enable turns on at t=0.3, so the
%     edge fires; if the enable turned on only after t=0.5 the edge would be
%     missed (counter stays 0). enableTrigger has two control ports: enable
%     first, trigger second.
inner3 = inner2;
inner3.controlPort = struct('kind', 'enableTrigger', 'triggerType', 'rising');
d3 = struct();
d3.blocks = {...
  struct('id', 'clk', 'type', 'clock', 'inputs', 0, 'outputs', 1, 'params', struct()), ...
  struct('id', 'en', 'type', 'compareToConstant', 'inputs', 1, 'outputs', 1, ...
    'params', struct('relop', 'ge', 'const', 0.3)), ...
  struct('id', 'tr', 'type', 'compareToConstant', 'inputs', 1, 'outputs', 1, ...
    'params', struct('relop', 'ge', 'const', 0.5)), ...
  struct('id', 'sub', 'type', 'subsystem', 'inputs', 2, 'outputs', 1, ...
    'params', struct('subsystem', inner3, ...
    'controlPort', struct('kind', 'enableTrigger', 'triggerType', 'rising'))), ...
  struct('id', 'tw', 'type', 'toWorkspace', 'inputs', 1, 'outputs', 0, ...
    'params', struct('VariableName', 'enabletrig_y', 'SaveFormat', 'Array', ...
    'Decimation', 1, 'MaxDataPoints', 'inf'))};
d3.connections = {...
  struct('from', 'clk', 'to', 'en', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'clk', 'to', 'tr', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'en', 'to', 'sub', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'tr', 'to', 'sub', 'fromIndex', 0, 'toIndex', 1), ...
  struct('from', 'sub', 'to', 'tw', 'fromIndex', 0, 'toIndex', 0)};
d3.sampleTime = 0.1; d3.duration = 1.0; d3.variables = struct();
jsondecode(__nflow_simulate__(jsonencode(d3)));
disp('Enable+trigger subsystem (edge honored only while enabled -> counter 1):');
disp(evalin('base', 'enabletrig_y')');

% --- Resettable: the counter runs every step, but a reset edge at t=0.5 returns
