% --- Action selector: an `if` block drives two mutually-exclusive `action`
%     subsystems, recombined by a `merge`. The if evaluates u1 < 0.5 over its
%     input (the clock): while true the "if" port is on and action A runs
%     (emits 10); otherwise the "else" port is on and action B runs (emits 20).
%     An action subsystem is level-gated by its selector line (kind "action"),
%     like an enabled subsystem, but wired from an if/switchCase output. The
%     merge follows whichever branch ran this step. This is the full
%     if/switchCase -> action -> merge conditional-execution pattern.
function s = action_branch(value)
  s = struct();
  s.blocks = {...
    struct('id', 'k', 'type', 'constant', 'inputs', 0, 'outputs', 1, ...
      'params', struct('Value', value)), ...
    struct('id', 'yout', 'type', 'labelSink', 'inputs', 1, 'outputs', 1, ...
      'params', struct('gotoTag', 'y'))};
  s.connections = {struct('from', 'k', 'to', 'yout', 'fromIndex', 0, 'toIndex', 0)};
  s.externalOutputs = {struct('id', 'yout', 'name', 'y')};
  s.controlPort = struct('kind', 'action');
end

ac = struct('kind', 'action');
d5 = struct();
d5.blocks = {...
  struct('id', 'clk', 'type', 'clock', 'inputs', 0, 'outputs', 1, 'params', struct()), ...
  struct('id', 'sel', 'type', 'if', 'inputs', 1, 'outputs', 2, ...
    'params', struct('IfExpression', 'u1 < 0.5', 'ElseIfExpressions', '', 'ShowElse', 'on')), ...
  struct('id', 'subA', 'type', 'subsystem', 'inputs', 1, 'outputs', 1, ...
    'params', struct('subsystem', action_branch(10), 'controlPort', ac)), ...
  struct('id', 'subB', 'type', 'subsystem', 'inputs', 1, 'outputs', 1, ...
    'params', struct('subsystem', action_branch(20), 'controlPort', ac)), ...
  struct('id', 'mrg', 'type', 'merge', 'inputs', 2, 'outputs', 1, ...
    'params', struct('InitialOutput', 0)), ...
  struct('id', 'tw', 'type', 'toWorkspace', 'inputs', 1, 'outputs', 0, ...
    'params', struct('VariableName', 'action_y', 'SaveFormat', 'Array', ...
    'Decimation', 1, 'MaxDataPoints', 'inf'))};
d5.connections = {...
  struct('from', 'clk', 'to', 'sel', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'sel', 'to', 'subA', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'sel', 'to', 'subB', 'fromIndex', 1, 'toIndex', 0), ...
  struct('from', 'subA', 'to', 'mrg', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'subB', 'to', 'mrg', 'fromIndex', 0, 'toIndex', 1), ...
  struct('from', 'mrg', 'to', 'tw', 'fromIndex', 0, 'toIndex', 0)};
d5.sampleTime = 0.1; d5.duration = 1.0; d5.variables = struct();
jsondecode(__nflow_simulate__(jsonencode(d5)));
disp('Action selector (if -> action A/B -> merge; 10 while t < 0.5, then 20):');
disp(evalin('base', 'action_y')');

% --- Function-call: a generator drives a function-call subsystem N times per
%     step (caller-driven execution, outside the topological schedule). The
%     callee holds a unit-delay counter incremented once per invocation, so with
%     NumberOfIterations = 3 its output climbs by 3 every step: 3, 6, 9, ... A
%     function-call subsystem is a subsystem whose control port kind is
%     "functionCall"; its control input is wired from the generator's event port.
inner6 = inner2; % reuse the unit-delay counter subsystem
inner6.controlPort = struct('kind', 'functionCall');
d6 = struct();
d6.blocks = {...
  struct('id', 'gen', 'type', 'functionCallGenerator', 'inputs', 0, 'outputs', 1, ...
    'params', struct('NumberOfIterations', 3)), ...
  struct('id', 'sub', 'type', 'subsystem', 'inputs', 1, 'outputs', 1, ...
    'params', struct('subsystem', inner6, 'controlPort', struct('kind', 'functionCall'))), ...
  struct('id', 'tw', 'type', 'toWorkspace', 'inputs', 1, 'outputs', 0, ...
    'params', struct('VariableName', 'fcall_y', 'SaveFormat', 'Array', ...
    'Decimation', 1, 'MaxDataPoints', 'inf'))};
d6.connections = {...
  struct('from', 'gen', 'to', 'sub', 'fromIndex', 0, 'toIndex', 0), ...
  struct('from', 'sub', 'to', 'tw', 'fromIndex', 0, 'toIndex', 0)};
d6.sampleTime = 0.1; d6.duration = 1.0; d6.variables = struct();
jsondecode(__nflow_simulate__(jsonencode(d6)));
disp('Function-call subsystem (generator fires the callee 3x/step -> 3, 6, 9, ...):');
disp(evalin('base', 'fcall_y')');
