i = [1, 1, 1, 2, 2, 3, 3, 3, 3];
j = [1, 2, 5, 2, 3, 1, 3, 4, 5];
s = [11, 12, 15, 22, 23, 31, 33, 34, 35];
m = 3;
n = 5;
nz_max = 9;
a = sparse(i, j, s, m, n, nz_max);
asserts.isequal(nzmax(a), nz_max);
%=============================================================================
A = sparse(eye(3, 3));
asserts.isequal(nzmax(A), 3);
%=============================================================================
I = [1 2 3];
J = [3 1 2];
V = [32 42 53];
sp = sparse(I, J, V);
asserts.isequal(nzmax(sp), 3);
%=============================================================================
A = eye(3, 3);
asserts.isequal(nzmax(A), 9);
%=============================================================================
A = [0 1 2 3;
  1 0 0 0;
  5 0 1 0];
S = sparse(A);
asserts.isequal(nzmax(S), 6);
%=============================================================================
S = sparse(single([1 0; 0 2]));
asserts.isequal(nzmax(S), 2);
%=============================================================================
S = sparse([1 2 1 2], [1 1 2 2], single([0 -0 complex(0, 0) complex(0, 2)]), 2, 2, 4);
asserts.isequal(nnz(S), 1);
asserts.isequal(nzmax(S), 4);
%=============================================================================
A = single([1 + 2i 0; 0 0]);
asserts.isequal(nzmax(A), 4);
