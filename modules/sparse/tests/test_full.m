asserts.isequal(nargin('full'), 1);
asserts.isequal(nargout('full'), 1);
%=============================================================================
A = sparse([1 0; 0 2]);
R = full(A);
asserts.isequal(R, [1 0; 0 2]);
asserts.isfalse(issparse(R));
%=============================================================================
asserts.isequal(full(42), 42);
%=============================================================================
S = sparse([1 0; 0 2]);
asserts.isequal(full(S), [1 0; 0 2]);
emptySparse = sparse(zeros(0, 3));
asserts.isequal(full(emptySparse), zeros(0, 3));
