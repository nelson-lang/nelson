% Generate an interactive HTML dashboard from Nelson data and open it.
if ~exist('webDashboardSampleCount', 'var')
  webDashboardSampleCount = 160;
end

% Compute a data series in Nelson, then hand it to the browser to animate.
webDashboardTime = linspace(0, 4 * pi, webDashboardSampleCount);
webDashboardSeries = sin(webDashboardTime) + 0.4 * sin(3 * webDashboardTime);
webDashboardData = sprintf('%.4f,', webDashboardSeries);
webDashboardData = webDashboardData(1:end - 1);

% Build a self-contained page: an animated canvas drawing the Nelson series.
webDashboardHtml = [ ...
  '<!doctype html><html><head><meta charset="utf-8">', ...
  '<title>Nelson web dashboard</title><style>', ...
  'html,body{margin:0;height:100%;background:#0b0e14;', ...
  'font-family:Segoe UI,Arial,sans-serif;color:#dce3f0;overflow:hidden}', ...
  '#t{position:absolute;top:14px;left:20px;font-size:18px;font-weight:600}', ...
  'canvas{display:block}</style></head><body>', ...
  '<div id="t">Live signal computed in Nelson, animated in the WebView</div>', ...
  '<canvas id="c"></canvas><script>', ...
  'const data=[', webDashboardData, '];', ...
  'const cv=document.getElementById("c"),g=cv.getContext("2d");', ...
  'function fit(){cv.width=innerWidth;cv.height=innerHeight;}fit();', ...
  'onresize=fit;let p=0;', ...
  'function draw(){g.fillStyle="#0b0e14";g.fillRect(0,0,cv.width,cv.height);', ...
  'const n=data.length,w=cv.width,h=cv.height,mid=h/2;', ...
  'g.lineWidth=2.5;g.beginPath();', ...
  'for(let i=0;i<n;i++){const x=i/(n-1)*w;', ...
  'const y=mid-data[(i+Math.floor(p))%n]*mid*0.6;', ...
  'i?g.lineTo(x,y):g.moveTo(x,y);}', ...
  'const hue=(p*2)%360;g.strokeStyle="hsl("+hue+",80%,65%)";g.stroke();', ...
  'for(let i=0;i<n;i+=6){const x=i/(n-1)*w;', ...
  'const y=mid-data[(i+Math.floor(p))%n]*mid*0.6;', ...
  'g.fillStyle="hsl("+hue+",80%,75%)";g.beginPath();', ...
  'g.arc(x,y,3,0,7);g.fill();}', ...
  'p+=0.6;requestAnimationFrame(draw);}draw();', ...
  '</script></body></html>'];

webDashboardFile = [tempname(), '.html'];
webDashboardId = fopen(webDashboardFile, 'wt');
fwrite(webDashboardId, webDashboardHtml);
fclose(webDashboardId);

% Open the generated page in the native WebView.
web(webDashboardFile);
disp(['Opened the Nelson web dashboard: ', webDashboardFile]);
