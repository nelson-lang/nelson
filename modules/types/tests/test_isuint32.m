asserts.isequal(nargin('isuint32'), 1);
asserts.isequal(nargout('isuint32'), 1);
%=============================================================================
A = 3;
res = isuint32(A);
asserts.isfalse(res);
%=============================================================================
A = uint32(3);
res = isuint32(A);
asserts.istrue(res);
