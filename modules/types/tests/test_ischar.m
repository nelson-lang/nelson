asserts.isequal(nargin('ischar'), 1);
asserts.isequal(nargout('ischar'), 1);
%=============================================================================
A = 3;
res = ischar(A);
asserts.isfalse(res);
%=============================================================================
B = 'NelSon';
res = ischar(B);
asserts.istrue(res);
%=============================================================================
C = [1; 3];
res = ischar(C);
asserts.isfalse(res);
