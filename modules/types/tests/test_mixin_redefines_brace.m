% <--WEIGHT 2-->
% A nelson.mixin.indexing.RedefinesBrace subclass customizes brace indexing.
% The protected braceReference / braceAssign hooks receive a
% nelson.indexing.IndexingOperation (indexOp.Indices{...}).
%=============================================================================
d = [tempname(), '/'];
mkdir(d);
%=============================================================================
filewrite([d, 'BraceBag.m'], [...
  "classdef BraceBag < nelson.mixin.indexing.RedefinesBrace"; ...
  "  properties"; ...
  "    Data"; ...
  "  end"; ...
  "  methods"; ...
  "    function obj = BraceBag(x)"; ...
  "      if nargin > 0"; ...
  "        obj.Data = x;"; ...
  "      else"; ...
  "        obj.Data = {};"; ...
  "      end"; ...
  "    end"; ...
  "    function d = raw(obj)"; ...
  "      d = obj.Data;"; ...
  "    end"; ...
  "  end"; ...
  "  methods (Access = protected)"; ...
  "    function varargout = braceReference(obj, indexOp)"; ...
  "      varargout{1} = obj.Data{indexOp.Indices{1}};"; ...
  "    end"; ...
  "    function obj = braceAssign(obj, indexOp, val)"; ...
  "      obj.Data{indexOp.Indices{1}} = val;"; ...
  "    end"; ...
  "    function n = braceListLength(obj, indexOp, ctx)"; ...
  "      n = 1;"; ...
  "    end"; ...
  "  end"; ...
  "end"]);
addpath(d);
%=============================================================================
b = BraceBag({10, 'hi', [1, 2, 3]});
assert_istrue(isa(b, 'nelson.mixin.indexing.RedefinesBrace'));
%=============================================================================
assert_isequal(b{1}, 10);
assert_isequal(b{2}, 'hi');
assert_isequal(b{3}, [1, 2, 3]);
%=============================================================================
b{1} = 99;
c = b.raw();
assert_isequal(c{1}, 99);
%=============================================================================
rmpath(d);
%=============================================================================
