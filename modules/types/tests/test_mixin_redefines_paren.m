% <--WEIGHT 2-->
% A nelson.mixin.indexing.RedefinesParen subclass customizes parentheses
% indexing. The protected parenReference / parenAssign hooks receive a
% nelson.indexing.IndexingOperation (indexOp.Indices{...}), matching the
% expected behavior. Verified value-for-value against the reference.
%=============================================================================
d = [tempname(), '/'];
mkdir(d);
%=============================================================================
filewrite([d, 'ParenBag.m'], [...
  "classdef ParenBag < nelson.mixin.indexing.RedefinesParen"; ...
  "  properties"; ...
  "    Data"; ...
  "  end"; ...
  "  methods"; ...
  "    function obj = ParenBag(x)"; ...
  "      if nargin > 0"; ...
  "        obj.Data = x;"; ...
  "      else"; ...
  "        obj.Data = [];"; ...
  "      end"; ...
  "    end"; ...
  "    function varargout = size(obj, varargin)"; ...
  "      varargout{1} = size(obj.Data, varargin{:});"; ...
  "    end"; ...
  "    function obj = cat(dim, varargin)"; ...
  "      acc = [];"; ...
  "      for k = 1:numel(varargin)"; ...
  "        acc = cat(dim, acc, varargin{k}.Data);"; ...
  "      end"; ...
  "      obj = ParenBag(acc);"; ...
  "    end"; ...
  "    function d = raw(obj)"; ...
  "      d = obj.Data;"; ...
  "    end"; ...
  "  end"; ...
  "  methods (Static)"; ...
  "    function e = empty(varargin)"; ...
  "      e = ParenBag([]);"; ...
  "    end"; ...
  "  end"; ...
  "  methods (Access = protected)"; ...
  "    function varargout = parenReference(obj, indexOp)"; ...
  "      varargout{1} = ParenBag(obj.Data(indexOp.Indices{1}));"; ...
  "    end"; ...
  "    function obj = parenAssign(obj, indexOp, val)"; ...
  "      obj.Data(indexOp.Indices{1}) = val.Data;"; ...
  "    end"; ...
  "    function obj = parenDelete(obj, indexOp)"; ...
  "      obj.Data(indexOp.Indices{1}) = [];"; ...
  "    end"; ...
  "    function n = parenListLength(obj, indexOp, ctx)"; ...
  "      n = 1;"; ...
  "    end"; ...
  "  end"; ...
  "end"]);
addpath(d);
%=============================================================================
b = ParenBag([10, 20, 30, 40]);
assert_istrue(isa(b, 'nelson.mixin.indexing.RedefinesParen'));
%=============================================================================
% parenReference receives an IndexingOperation
x = b(2);
assert_isequal(x.raw(), 20);
%=============================================================================
% end resolves through the inherited size-derived method
y = b(end);
assert_isequal(y.raw(), 40);
%=============================================================================
% range index
z = b(2:3);
assert_isequal(z.raw(), [20, 30]);
%=============================================================================
% parenAssign updates in place (not whole-object replacement)
b(1) = ParenBag(99);
assert_isequal(b.raw(), [99, 20, 30, 40]);
%=============================================================================
rmpath(d);
