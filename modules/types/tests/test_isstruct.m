asserts.isequal(nargin('isstruct'), 1);
asserts.isequal(nargout('isstruct'), 1);
%=============================================================================
A = 1;
res = isstruct(A);
asserts.isfalse(res);
%=============================================================================
B = struct();
res = isstruct(B);
asserts.istrue(res);
%=============================================================================
C.a = 1;
C.B = 'hello';
res = isstruct(C);
asserts.istrue(res);
%=============================================================================
B = struct([]);
res = isstruct(B);
asserts.istrue(res);
