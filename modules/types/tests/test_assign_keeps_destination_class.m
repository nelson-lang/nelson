%=============================================================================
% indexed assignment into an existing numeric, char or logical array keeps
% the class of the destination: the value is converted to it.
%=============================================================================
% double destination
c = [1 2];
c(1) = true;
assert_isequal(c, [1 2]);
%=============================================================================
c = [1 2];
c(:) = true;
assert_isequal(c, [1 1]);
%=============================================================================
c = [1 2];
c(2:3) = int8([3 4]);
assert_isequal(c, [1 3 4]);
%=============================================================================
c = [1 2];
c(:) = 'xy';
assert_isequal(c, [120 121]);
%=============================================================================
c = [1 2];
c(3) = uint8(200);
assert_isequal(c, [1 2 200]);
%=============================================================================
c = [1 2];
c(:) = single([2.5 3.5]);
assert_isequal(c, [2.5 3.5]);
%=============================================================================
c = [1 2; 3 4];
c(:, :) = int16(7);
assert_isequal(c, [7 7; 7 7]);
%=============================================================================
c = [1 2; 3 4];
c(1, 2:3) = int8([5 6]);
assert_isequal(c, [1 5 6; 3 4 0]);
%=============================================================================
c = [1 2];
c(1) = int8(5);
c(2) = uint8(3);
assert_isequal(c, [5 3]);
%=============================================================================
% text is parsed as a number
c = [1 2];
c(1) = "zz";
assert_isequal(c, [NaN 2]);
%=============================================================================
c = [1 2];
c(2:3) = ["5" "6"];
assert_isequal(c, [1 5 6]);
%=============================================================================
c = [1 2];
c(1, 1) = "5";
assert_isequal(c, [5 2]);
%=============================================================================
c = [1 2 3];
c(2:3) = [string(missing) "4"];
assert_isequal(c, [1 NaN 4]);
%=============================================================================
% a complex value makes the destination complex
c = [1 2];
c(1) = 3i;
assert_isequal(c, [3i 2]);
%=============================================================================
c = single([1 2]);
c(1) = 3i;
assert_isequal(c, single([3i 2]));
%=============================================================================
c = single([1 2]);
c(1:2) = [2.5 3];
assert_isequal(c, single([2.5 3]));
%=============================================================================
% nothing changes when the subscripts select no element
c = [1 2];
c([], []) = 3i;
assert_isequal(c, [1 2]);
c(false(1, 2)) = 3i;
assert_isequal(c, [1 2]);
c = true(1, 2);
c(false(1, 2)) = NaN;
assert_isequal(c, [true true]);
%=============================================================================
% integer destination: values round and saturate
c = int8([1 2]);
c(1) = int16(300);
assert_isequal(c, int8([127 2]));
%=============================================================================
c = uint16([1 2]);
c(:) = [-1.5 2.7];
assert_isequal(c, uint16([0 3]));
%=============================================================================
c = int8([1 2]);
c(:) = [NaN 2.5];
assert_isequal(c, int8([0 3]));
%=============================================================================
c = int8([1 2]);
c(3) = true;
assert_isequal(c, int8([1 2 1]));
%=============================================================================
c = int8([1 2]);
c(1:2) = 'xy';
assert_isequal(c, int8([120 121]));
%=============================================================================
c = int8([1 2]);
assert_checkerror('c(1) = 3i;', _('Invalid conversion from complex matrix to ''int8'' matrix.'));
%=============================================================================
c = int8([1 2]);
msg = sprintf(_('Unable to perform assignment because value of type ''%s'' is not convertible to ''%s''.'), 'string', 'int8');
assert_checkerror('c(1) = "5";', msg);
%=============================================================================
% logical destination
c = true(1, 2);
c(:) = 'xy';
assert_isequal(c, [true true]);
%=============================================================================
c = false(1, 2);
c(1:2) = [0 -1.5];
assert_isequal(c, [false true]);
%=============================================================================
c = true(1, 2);
c(3) = int8(0);
assert_isequal(c, [true true false]);
%=============================================================================
c = true(1, 2);
assert_checkerror('c(1) = NaN;', _('Conversion to logical with NaN is not possible.'));
assert_checkerror('c(1, 1:2) = [1 NaN];', _('Conversion to logical with NaN is not possible.'));
assert_checkerror('c(1) = 3i;', _('Conversion to logical from complex is not possible.'));
assert_isequal(c, [true true]);
%=============================================================================
% char destination
c = 'ab';
c(1) = 65;
assert_isequal(c, 'Ab');
%=============================================================================
c = 'ab';
c(:) = [66 67];
assert_isequal(c, 'BC');
%=============================================================================
c = 'ab';
c(3) = "5";
assert_isequal(c, 'ab5');
%=============================================================================
c = 'ab';
c(:) = "zz";
assert_isequal(c, 'zz');
%=============================================================================
c = 'ab';
assert_checkerror('c(1) = true;', _('Conversion to char from logical is not possible.'));
assert_checkerror('c(:) = [true false];', _('Conversion to char from logical is not possible.'));
assert_checkerror('c(1) = 3i;', _('Conversion to char from complex is not possible.'));
%=============================================================================
% typed empty destination keeps its class
c = int8([]);
c(2) = 2.7;
assert_isequal(c, int8([0 3]));
%=============================================================================
c = single([]);
c(1, 2) = int8(3);
assert_isequal(c, single([0 3]));
%=============================================================================
c = false(1, 0);
c(1:2) = [2 0];
assert_isequal(c, [true false]);
%=============================================================================
% empty double destination adopts the class of the value
c = [];
c(2) = int8(3);
assert_isequal(c, int8([0 3]));
%=============================================================================
c = [];
c(1) = 'a';
assert_isequal(c, 'a');
%=============================================================================
c = [];
c(1) = single(2);
assert_isequal(c, 2);
%=============================================================================
