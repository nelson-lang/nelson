asserts.isequal(nargin('ishandle'), 1);
asserts.isequal(nargout('ishandle'), 1);
%=============================================================================
A = 3;
res = ishandle(A);
asserts.isfalse(res);
%=============================================================================
A = [1 2; 3 4];
res = ishandle(A);
asserts.isequal(res, logical([0 0; 0 0]));
