% <--WEIGHT 2-->
A = [1:5]';
R = A(1:end);
REF = [1:5]';
asserts.isequal(R, REF);
%=============================================================================
A = [1:5];
R = A(1:end);
REF = [1:5];
asserts.isequal(R, REF);
%=============================================================================
A = 1:10;
B = A;
asserts.isequal(A(7), 7);
asserts.isequal(B, 1:10);
%=============================================================================
A = single(1:5);
R = A(4);
asserts.isequal(class(R), 'single');
asserts.isequal(R, single(4));
%=============================================================================
A = int32(1:5);
R = A(3);
asserts.isequal(class(R), 'int32');
asserts.isequal(R, int32(3));
%=============================================================================
A = [1 + 2i, 3 + 4i];
asserts.isequal(A(2), 3 + 4i);
%=============================================================================
A = 1:20;
R = A(5:12);
asserts.isequal(R, 5:12);
asserts.isequal(size(R), [1 8]);
%=============================================================================
A = (1:20)';
R = A(5:12);
asserts.isequal(R, (5:12)');
asserts.isequal(size(R), [8 1]);
%=============================================================================
A = single(1:20);
R = A(4:9);
asserts.isequal(class(R), 'single');
asserts.isequal(R, single(4:9));
%=============================================================================
idx = double(5:12);
A = int16(1:20);
R = A(idx);
asserts.isequal(class(R), 'int16');
asserts.isequal(R, int16(5:12));
%=============================================================================
idx = double(4:9);
A = (1:20)';
R = A(idx);
asserts.isequal(R, (4:9)');
asserts.isequal(size(R), [6 1]);
%=============================================================================
idx = double(3:6);
A = 1:8;
A(idx) = [30 40 50 60];
asserts.isequal(A, [1 2 30 40 50 60 7 8]);
%=============================================================================
A = [1 + 2i, 3 + 4i, 5 + 6i, 7 + 8i];
R = A(2:4);
asserts.isequal(R, [3 + 4i, 5 + 6i, 7 + 8i]);
%=============================================================================
A = 1:5;
A([2 4]) = [20 40];
asserts.isequal(A, [1 20 3 40 5]);
%=============================================================================
A = 1:8;
A(3:6) = [30 40 50 60];
asserts.isequal(A, [1 2 30 40 50 60 7 8]);
%=============================================================================
A = 1:5;
A([2 2 3]) = [10 20 30];
asserts.isequal(A, [1 20 30 4 5]);
%=============================================================================
A = [1 2 3 4 5];
A(A < 4) = A(A < 4) + 10;
asserts.isequal(A, [11 12 13 4 5]);
%=============================================================================
A = [10 20 30 40];
mask = logical([1 0 1 0]);
A(mask) = [11 31];
asserts.isequal(A, [11 20 31 40]);
%=============================================================================
A = [10 20 30 40]';
mask = logical([1 0 1 0]');
A(mask) = [11; 31];
asserts.isequal(A, [11 20 31 40]');
%=============================================================================
A = [10 20 30];
mask = logical([0 1 0 0 0]);
A(mask) = 22;
asserts.isequal(A, [10 22 30]);
%=============================================================================
A = 10:15;
mask = logical([0 1 0 1 0 0]);
R = A(mask);
asserts.isequal(R, [11 13]);
asserts.isequal(size(R), [1 2]);
%=============================================================================
A = (10:15)';
mask = logical([0 1 0 1 0 0]);
R = A(mask);
asserts.isequal(R, [11; 13]);
asserts.isequal(size(R), [2 1]);
%=============================================================================
A = 10:12;
mask = logical([0 1 0 0 0]);
R = A(mask);
asserts.isequal(R, 11);
%=============================================================================
asserts.isequal(bytecode_local_parens_fastpath([10 20 30], 2), 20);
asserts.isequal(bytecode_local_parens_fastpath([true false true], 2), false);
asserts.isequal(bytecode_local_parens_assign_fastpath([10 20 30], 3), 30);
asserts.isequal(bytecode_local_parens_handle_fastpath(@(x) x + 3, 4), 7);
asserts.isequal(bytecode_local_parens_assign_handle_fastpath(@(x) x + 4, 5), 9);
