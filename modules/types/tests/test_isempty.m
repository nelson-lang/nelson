asserts.isequal(nargin('isempty'), 1);
asserts.isequal(nargout('isempty'), 1);
%=============================================================================
A = rand(3, 3, 3);
res = isempty(A);
asserts.isfalse(res);
%=============================================================================
A(:, :, :) = [];
res = isempty(A);
asserts.istrue(res);
%=============================================================================
B = {};
res = isempty(B);
asserts.istrue(res);
%=============================================================================
C = struct();
res = isempty(C);
asserts.isfalse(res);
%=============================================================================
C = struct([]);
res = isempty(C);
asserts.istrue(res);
