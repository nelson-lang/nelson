% <--WEIGHT 2-->
d = [tempname(), '/'];
mkdir(d);
%=============================================================================
filewrite([d, 'TCDDefault.m'], [...
  "classdef TCDDefault < nelson.mixin.CustomDisplay"; ...
  "  properties"; ...
  "    Alpha = 3"; ...
  "    Beta = 'hello'"; ...
  "  end"; ...
  "end"]);
filewrite([d, 'TCDHeader.m'], [...
  "classdef TCDHeader < nelson.mixin.CustomDisplay"; ...
  "  properties"; ...
  "    Alpha = 3"; ...
  "  end"; ...
  "  methods (Access = protected)"; ...
  "    function h = getHeader(obj)"; ...
  "      h = ""== custom header =="";"; ...
  "    end"; ...
  "    function f = getFooter(obj)"; ...
  "      f = 'custom footer';"; ...
  "    end"; ...
  "  end"; ...
  "end"]);
filewrite([d, 'TCDGroups.m'], [...
  "classdef TCDGroups < nelson.mixin.CustomDisplay"; ...
  "  properties"; ...
  "    X = 1"; ...
  "    Y = 2"; ...
  "  end"; ...
  "  methods (Access = protected)"; ...
  "    function groups = getPropertyGroups(obj)"; ...
  "      groups = [nelson.mixin.util.PropertyGroup({'X'}, 'First'), nelson.mixin.util.PropertyGroup({'Y'}, 'Second')];"; ...
  "    end"; ...
  "  end"; ...
  "end"]);
addpath(d);
%=============================================================================
% default composition: class-name header + right-aligned properties
o = TCDDefault();
s = evalc('disp(o)');
assert_istrue(contains(s, 'TCDDefault with properties:'));
assert_istrue(contains(s, 'Alpha: 3'));
assert_istrue(contains(s, 'Beta: ''hello'''));
%=============================================================================
% getHeader may return a string scalar (honored) and getFooter a char vector
o2 = TCDHeader();
s2 = evalc('disp(o2)');
assert_istrue(contains(s2, '== custom header =='));
assert_istrue(contains(s2, 'custom footer'));
assert_isfalse(contains(s2, 'with properties:'));
%=============================================================================
% getPropertyGroups drives grouped display with titles
o3 = TCDGroups();
s3 = evalc('disp(o3)');
assert_istrue(contains(s3, 'First:'));
assert_istrue(contains(s3, 'Second:'));
assert_istrue(contains(s3, 'X: 1'));
assert_istrue(contains(s3, 'Y: 2'));
%=============================================================================
% non-scalar (array) display lists property names, not values
arr = [TCDDefault(), TCDDefault()];
sarr = evalc('disp(arr)');
assert_istrue(contains(sarr, '1x2 TCDDefault array with properties:'));
assert_istrue(contains(sarr, 'Alpha'));
assert_isfalse(contains(sarr, 'Alpha: 3'));
%=============================================================================
% empty object display
em = TCDDefault.empty(0, 0);
sem = evalc('disp(em)');
assert_istrue(contains(sem, '0x0 TCDDefault array with properties:'));
%=============================================================================
% PropertyGroup value object
pg = nelson.mixin.util.PropertyGroup({'a', 'b', 'c'}, 'T');
assert_isequal(pg.NumProperties, 3);
assert_isequal(pg.Title, 'T');
assert_isequal(pg.PropertyList, {'a', 'b', 'c'});
%=============================================================================
rmpath(d);
