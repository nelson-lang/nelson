asserts.isequal(nargin('isint64'), 1);
asserts.isequal(nargout('isint64'), 1);
%=============================================================================
A = 3;
res = isint64(A);
asserts.isfalse(res);
%=============================================================================
A = int64(3);
res = isint64(A);
asserts.istrue(res);
