% <--WEIGHT 2-->
% A chained index on a RedefinesParen object dispatches the whole chain once:
% the parenReference hook receives the full IndexingOperation list (numel > 1),
% matching expected behavior, and obj.Data.(indexOp) applies it.
%=============================================================================
d = [tempname(), '/'];
mkdir(d);
%=============================================================================
filewrite([d, 'ChainProbe.m'], [...
  "classdef ChainProbe < nelson.mixin.indexing.RedefinesParen"; ...
  "  properties"; ...
  "    Data"; ...
  "    Seen = 0"; ...
  "  end"; ...
  "  methods"; ...
  "    function obj = ChainProbe(x)"; ...
  "      if nargin > 0; obj.Data = x; else; obj.Data = []; end"; ...
  "    end"; ...
  "    function varargout = size(obj, varargin)"; ...
  "      [varargout{1:nargout}] = size(obj.Data, varargin{:});"; ...
  "    end"; ...
  "    function n = lastSeen(obj)"; ...
  "      n = obj.Seen;"; ...
  "    end"; ...
  "  end"; ...
  "  methods (Access = protected)"; ...
  "    function varargout = parenReference(obj, indexOp)"; ...
  "      assignin('base', 'probeNumel', numel(indexOp));"; ...
  "      [varargout{1:nargout}] = obj.Data.(indexOp);"; ...
  "    end"; ...
  "    function obj = parenAssign(obj, indexOp, varargin)"; ...
  "      obj.Data.(indexOp) = varargin{1};"; ...
  "    end"; ...
  "    function obj = parenDelete(obj, indexOp)"; ...
  "      obj.Data.(indexOp) = [];"; ...
  "    end"; ...
  "    function n = parenListLength(obj, indexOp, ctx)"; ...
  "      n = 1;"; ...
  "    end"; ...
  "  end"; ...
  "  methods (Static)"; ...
  "    function e = empty(varargin)"; ...
  "      e = ChainProbe([]);"; ...
  "    end"; ...
  "  end"; ...
  "end"]);
%=============================================================================
addpath(d);
%=============================================================================
% single paren: hook sees one operation
b = ChainProbe(struct('f', {[1 2 3], [4 5 6 7]}));
r1 = b(2);
assert_isequal(evalin('base', 'probeNumel'), 1);
assert_isequal(class(r1), 'struct');
%=============================================================================
% chained paren + dot: the whole chain reaches the hook (numel == 2)
r2 = b(2).f;
assert_isequal(evalin('base', 'probeNumel'), 2);
assert_isequal(r2, [4 5 6 7]);
%=============================================================================
rmpath(d);
rmdir(d, 's');
