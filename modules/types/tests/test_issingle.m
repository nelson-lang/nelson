asserts.isequal(nargin('issingle'), 1);
asserts.isequal(nargout('issingle'), 1);
%=============================================================================
A = 3.6;
res = issingle(A);
asserts.isfalse(res);
%=============================================================================
B = single([1; 3]);
res = issingle(B);
asserts.istrue(res);
%=============================================================================
B = sparse([1; 3]);
res = issingle(B);
asserts.isfalse(res);
