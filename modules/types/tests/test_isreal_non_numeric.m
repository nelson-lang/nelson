% <--WEIGHT 2-->
R = isreal(['s']);
asserts.istrue(R);
%=============================================================================
R = isreal(['str1']);
asserts.istrue(R);
%=============================================================================
R = isreal(['str1', 'str2', 'str3']);
asserts.istrue(R);
%=============================================================================
R = isreal(['str1'; 'str2'; 'str3']);
asserts.istrue(R);
%=============================================================================
R = isreal(['str1', 'str2', 'str3'; 'str4', 'str5', 'str6']);
asserts.istrue(R);
%=============================================================================
R = isreal([[1] == [1]]);
asserts.istrue(R);
%=============================================================================
R = isreal([[1, 2, 3] == [1, 0, 3]]);
asserts.istrue(R);
%=============================================================================
R = isreal([[1; 2; 3] == [1; 0; 3]]);
asserts.istrue(R);
%=============================================================================
R = isreal([[1, 2, 3; 4, 5, 6] == [1, 0, 3; 4, 5, 0]]);
asserts.istrue(R);
%=============================================================================
R = isreal(rand(3, 3, 3));
asserts.istrue(R);
%=============================================================================
R = isreal(sparse(4 + 3i));
asserts.isfalse(R);
%=============================================================================
R = isreal(sparse(true));
asserts.istrue(R);
%=============================================================================
R = isreal({});
asserts.isfalse(R);
%=============================================================================
R = isreal(struct());
asserts.isfalse(R);
%=============================================================================
R = single([3, i]);
asserts.isfalse(isreal(R));
%=============================================================================
R = [3, i];
asserts.isfalse(isreal(R));
%=============================================================================
R = [3, 0i];
asserts.istrue(isreal(R));
