% nelson.mixin.indexing.Redefines{Paren,Brace,Dot} base classes: a subclass
% resolves the superclass and inherits the size/cat-derived methods
% (numel/length/isempty/ndims/end/horzcat/vertcat).
%=============================================================================
d = [tempname(), '/'];
mkdir(d);
%=============================================================================
filewrite([d, 'IdxBag.m'], [...
  "classdef IdxBag < nelson.mixin.indexing.RedefinesParen"; ...
  "  properties"; ...
  "    Data"; ...
  "  end"; ...
  "  methods"; ...
  "    function obj = IdxBag(x)"; ...
  "      if nargin > 0"; ...
  "        obj.Data = x;"; ...
  "      else"; ...
  "        obj.Data = [];"; ...
  "      end"; ...
  "    end"; ...
  "    function varargout = size(obj, varargin)"; ...
  "      varargout{1} = size(obj.Data, varargin{:});"; ...
  "    end"; ...
  "  end"; ...
  "  methods (Access = protected)"; ...
  "    function obj = cat(dim, varargin)"; ...
  "      acc = [];"; ...
  "      for k = 1:numel(varargin)"; ...
  "        acc = cat(dim, acc, varargin{k}.Data);"; ...
  "      end"; ...
  "      obj = IdxBag(acc);"; ...
  "    end"; ...
  "  end"; ...
  "end"]);
filewrite([d, 'BraceBag.m'], [...
  "classdef BraceBag < nelson.mixin.indexing.RedefinesBrace"; ...
  "end"]);
filewrite([d, 'DotBag.m'], [...
  "classdef DotBag < nelson.mixin.indexing.RedefinesDot"; ...
  "end"]);
addpath(d);
%=============================================================================
% base classes resolve (previously errored "Superclass not found")
b = IdxBag([10 20 30 40]);
assert_istrue(isa(b, 'nelson.mixin.indexing.RedefinesParen'));
assert_istrue(isa(BraceBag(), 'nelson.mixin.indexing.RedefinesBrace'));
assert_istrue(isa(DotBag(), 'nelson.mixin.indexing.RedefinesDot'));
%=============================================================================
% derived methods implemented via the abstract size / cat
assert_isequal(size(b), [1, 4]);
assert_isequal(numel(b), 4);
assert_isequal(length(b), 4);
assert_isequal(ndims(b), 2);
assert_isfalse(isempty(b));
assert_istrue(isempty(IdxBag([])));
%=============================================================================
% horzcat / vertcat via cat
h = [IdxBag([1, 2]), IdxBag([3, 4])];
assert_isequal(h.Data, [1, 2, 3, 4]);
v = [IdxBag([1, 2]); IdxBag([3, 4])];
assert_isequal(v.Data, [1, 2; 3, 4]);
%=============================================================================
rmpath(d);
