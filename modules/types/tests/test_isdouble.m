asserts.isequal(nargin('isdouble'), 1);
asserts.isequal(nargout('isdouble'), 1);
%=============================================================================
A = 3;
res = isdouble(A);
asserts.istrue(res);
%=============================================================================
A = single(3);
res = isdouble(A);
asserts.isfalse(res);
%=============================================================================
A = single([3, i]);
res = isdouble(A);
asserts.isfalse(res);
%=============================================================================
A = [3, i];
res = isdouble(A);
asserts.istrue(res);
