% A nelson.mixin.indexing.RedefinesDot subclass customizes dot indexing for
% names that are not real properties/methods. The protected dotReference /
% dotAssign hooks receive a nelson.indexing.IndexingOperation (indexOp.Name).
%=============================================================================
d = [tempname(), '/'];
mkdir(d);
%=============================================================================
filewrite([d, 'DotBag.m'], [...
  "classdef DotBag < nelson.mixin.indexing.RedefinesDot"; ...
  "  properties (Access = private)"; ...
  "    Store"; ...
  "  end"; ...
  "  methods"; ...
  "    function obj = DotBag()"; ...
  "      obj.Store = struct();"; ...
  "    end"; ...
  "  end"; ...
  "  methods (Access = protected)"; ...
  "    function varargout = dotReference(obj, indexOp)"; ...
  "      varargout{1} = obj.Store.(indexOp.Name);"; ...
  "    end"; ...
  "    function obj = dotAssign(obj, indexOp, val)"; ...
  "      obj.Store.(indexOp.Name) = val;"; ...
  "    end"; ...
  "    function n = dotListLength(obj, indexOp, ctx)"; ...
  "      n = 1;"; ...
  "    end"; ...
  "  end"; ...
  "end"]);
addpath(d);
%=============================================================================
b = DotBag();
assert_istrue(isa(b, 'nelson.mixin.indexing.RedefinesDot'));
%=============================================================================
b.alpha = 42;
b.beta = 'hello';
assert_isequal(b.alpha, 42);
assert_isequal(b.beta, 'hello');
%=============================================================================
% reassignment
b.alpha = [1, 2, 3];
assert_isequal(b.alpha, [1, 2, 3]);
%=============================================================================
rmpath(d);
%=============================================================================
