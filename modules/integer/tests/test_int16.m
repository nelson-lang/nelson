asserts.isequal(nargin('int16'), 1);
asserts.isequal(nargout('int16'), 1);
%=============================================================================
R = int16([-1 0 1]);
asserts.isequal(class(R), 'int16');
asserts.isequal(R, int16([-1 0 1]));
asserts.isequal(int16(40000), intmax('int16'));
asserts.isequal(int16(-40000), intmin('int16'));
%=============================================================================
asserts.isequal(class(int16(-2)), 'int16');
