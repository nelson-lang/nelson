matver = {'-v7', '-v7.3'};
%=============================================================================
h = warndlg();
%=============================================================================
for v = matver
  test_file_mat = [tempname(), '.mat'];
  test_file_mat_literal = ['''', strrep(test_file_mat, '''', ''''''), ''''];
  version_literal = ['''', v{1}, ''''];
  asserts.checkerror(['savemat(', test_file_mat_literal, ', ''h'', ', version_literal, ');'], ...
    sprintf(_('Cannot save variable: %s'), 'h'));
end
%=============================================================================
close(h);
