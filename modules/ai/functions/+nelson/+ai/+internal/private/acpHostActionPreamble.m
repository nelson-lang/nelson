% Instruction prepended to the claude-agent-acp prompt so the agent can pilot the
% LIVE Nelson GUI. The agent's own file tools run in a sandbox and cannot reach
% the running session, so widget actions are requested through a marker that the
% in-session poll (acpRunHostActions) parses and executes. This bridge does not
% use the MCP subprocess, so it works whether or not NELSON_AI_ACP_MCP is set.
function s = acpHostActionPreamble()
  lines = {};
  lines{end + 1} = 'You can drive the live Nelson GUI (open files, launch tools).';
  lines{end + 1} = 'Your own file tools cannot reach the running session, so to act on it';
  lines{end + 1} = 'emit a marker on its own line, exactly:';
  lines{end + 1} = '<<nelson-action>>{"tool": "<name>", "arguments": {<arguments>}}<<end>>';
  lines{end + 1} = 'Available actions:';
  lines{end + 1} = ['- open_nelson_file {"filename": "...", "line": N}: open an existing file in ', ...
    'the editor; "line" is optional and scrolls to that line (use it to point at an error).'];
  lines{end + 1} = '- launch_nflow {"model": "..."}: open the NFlow editor (model is optional).';
  lines{end + 1} = '- open_nelson_notebook {"filename": "..."}: open a notebook document.';
  lines{end + 1} = ['- insert_into_nelson_file {"filename": "...", "code": "..."}: open a file and ', ...
    'drop code into the editor for the user to review and save. Use this to add/insert code ', ...
    'into a file instead of saying you cannot edit it.'];
  lines{end + 1} = ['- open_nelson_doc {"topic": "..."}: open the documentation browser on a ', ...
    'function name or keyword.'];
  lines{end + 1} = ['- run_current_file {"filename": "..."}: run a SAVED Nelson file in the ', ...
    'console. "filename" is optional: with it, that saved file runs even when no editor is ', ...
    'open; without it, the file currently open in the editor runs. Only a saved file on disk ', ...
    'runs (never an unsaved draft), so insert or propose the code, have the user save it, then ', ...
    'run it by filename.'];
  lines{end + 1} = ['- profile_current_file {"filename": "..."}: profile a SAVED file (run it ', ...
    'under the profiler). Its slowest functions are sent back to you so you ANALYZE them for ', ...
    'the user (name the hot spots and what to optimize), and the full report also opens in the ', ...
    'live Profiler panel. Use it when the user asks why code is slow or where time goes. ', ...
    '"filename" is optional (defaults to the editor file), same saved-file rule as run.'];
  lines{end + 1} = ['- debug_nelson_file {"filename": "...", "line": N}: set a breakpoint at ', ...
    'line N in a SAVED file and open it there, so the debugger (Call Stack, variables) ', ...
    'engages when the user runs. Omit "line" to just open it and report its breakpoints. ', ...
    'Use it when the user wants to debug or step through code.'];
  lines{end + 1} = ['- clear_breakpoints {"filename": "..."}: clear the breakpoints of a file, ', ...
    'or all of them when "filename" is omitted.'];
  lines{end + 1} = ['Running, profiling and debugging all need a file SAVED on disk. When you ', ...
    'write code for the user to run, give the draft a BARE filename (for example ', ...
    '"analysis.m"), which saves in the current working directory that always exists; ', ...
    'never invent an absolute path like D:\tmp or /tmp, which fails to save. Insert it, ', ...
    'ask the user to save, then run/profile/debug it by that same filename.'];
  lines{end + 1} = ['- propose_nelson_edit {"filename": "...", "code": "..."}: propose a full-file ', ...
    'edit. "code" is the complete new content; the editor shows it (with a diff) for the user ', ...
    'to review and save. Prefer this over insert_into_nelson_file when you rewrite an existing ', ...
    'file rather than append to it.'];
  lines{end + 1} = ['The marker must be valid JSON on a single line: inside it escape every ', ...
    'backslash as \\ (so a path d:\\demo.m), every double quote as \", and every line ', ...
    'break in a code value as \n. Do not wrap the marker in a code fence.'];
  lines{end + 1} = 'Emit the marker when the user asks to open/edit a file or launch a tool, then confirm in words.';
  lines{end + 1} = 'Always add a short sentence after the marker; never reply with only a marker.';
  lines{end + 1} = ['insert_into_nelson_file only drops a draft into the editor: it is NOT saved. ', ...
    'Never say a file was saved, created, or written; say the code is in the editor to review ', ...
    'and save, and do not claim a file exists until the user has saved it.'];
  s = strjoin(lines, char(10));
end
