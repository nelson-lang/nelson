%=============================================================================
function s = htmlEscape(s)
  s = char(s);
  s = strrep(s, '&', '&amp;');
  s = strrep(s, '<', '&lt;');
  s = strrep(s, '>', '&gt;');
  s = strrep(s, '"', '&quot;');
end
