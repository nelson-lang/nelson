% Build a self-contained HTML page from a normalized feed structure.
%=============================================================================
function html = newsfeedHtml(feed)
  n = numel(feed.items);
  cards = '';
  for k = 1:n
    it = feed.items(k);
    title = htmlEscape(it.title);
    titleHtml = title;
    if ~isempty(it.link)
      titleHtml = ['<a href="', htmlEscape(it.link), '" target="_blank" rel="noopener">', title, '</a>'];
    end
    dateHtml = '';
    if ~isempty(it.date); dateHtml = ['<div class="date">', htmlEscape(it.date), '</div>']; end
    thumbHtml = '';
    if ~isempty(it.image)
      thumbHtml = ['<img class="thumb" src="', htmlEscape(it.image), '" alt="" loading="lazy">'];
    end
    cards = [cards, ...
      '<article class="item">', ...
        thumbHtml, ...
        '<div class="body">', ...
          '<h2>', titleHtml, '</h2>', ...
          dateHtml, ...
          '<div class="summary">', it.summary, '</div>', ...
        '</div>', ...
      '</article>', newline];
  end

  head = feed.title;
  if isempty(head); head = 'Newsfeed'; end
  head = htmlEscape(head);

  html = [...
    '<!DOCTYPE html><html lang="en"><head><meta charset="utf-8">', ...
    '<meta name="viewport" content="width=device-width, initial-scale=1">', ...
    '<title>', head, '</title><style>', styleSheet(), '</style></head><body>', ...
    '<header><h1>', head, '</h1>', ...
    '<div class="meta">', num2str(n), ' items', feedSource(feed), '</div></header>', ...
    '<main>', cards, '</main>', ...
    '<footer>Rendered by Nelson newsfeed</footer>', ...
    '</body></html>'];
end
%=============================================================================
function s = feedSource(feed)
  s = '';
  if ~isempty(feed.link)
    s = [' &middot; <a href="', htmlEscape(feed.link), '" target="_blank" rel="noopener">source</a>'];
  end
end
